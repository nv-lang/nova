fi
case "$NOVA_CAL_FACTOR" in ''|*[!0-9]*) NOVA_CAL_FACTOR=1 ;; esac
export NOVA_CAL_FACTOR

step loop "arch-ratchet"
guard "$ROOT/scripts/guards/arch-ratchet.sh" || fail "arch-ratchet (emit_c growth)"

