#!/bin/sh
# scripts/gate.sh — ЕДИНЫЙ авторитетный гейт (план 231 трек Д п.1).
# Запуск из корня целевого дерева (main-репа или worktree):  bash scripts/gate.sh
# Ассерты делает СКРИПТ, не интегратор: любой провал = exit 1 с внятной строкой.
#
# Состав (CLAUDE.md/dev-workflow):
#   1) cargo build --release (nova-cli)
#   2) мега-CU spec_tests/conformance ОДНИМ CU: exit=0 И строка "PASS: N  FAIL: 0" присутствует
#   3) nova check std/src (БЕЗ NOVA_STD_PATH): канон "PASS: 147  FAIL: 26  WARN: 1078"
#      (ассертится ТОЛЬКО FAIL — см. ~:212; PASS/WARN растут от новых файлов законно)
#   4) nova lint --deny std/src: канон 0 находок
#   5) nova lint --deny spec_tests: канон 0 находок (221.1 №416 хвост)
#   6) флагман examples/flagship/aggregator --strict-effects: строка "built:"
set -u
ROOT="$(pwd)"
# Boehm GC для мега-CU (test_runner::detect_boehm читает NOVA_GC_LIB_DIR).
# `vcpkg_installed` под .gitignore — у worktree его нет, он есть только в
# ГЛАВНОМ дереве, общем для всех worktree через .git. Поэтому берём его не по
# захардкоженному пути (с 2026-07-26 здесь стояло `D:\Sources\nv-lang\nova\...`
# — путь к машине владельца в публичном скрипте, а worktree 274 через него
# линковал чужой GC и не знал об этом; владелец увидел это в
# nova-p274/scripts/gate.sh 2026-08-16), а ВЫВОДИМ от расположения: главное
# дерево = родитель `git rev-parse --git-common-dir`. Из main это `.git` →
# само дерево; из worktree — абсолютный путь к main. Явный NOVA_GC_LIB_DIR из
# окружения побеждает (CI/другая раскладка). Если каталога нет — переменную
# не ставим, раннер честно скажет «GC не найден», а не слинкует наугад.
if [ -z "${NOVA_GC_LIB_DIR:-}" ]; then
    _common="$(git -C "$ROOT" rev-parse --git-common-dir 2>/dev/null)"
    case "$_common" in
        .git) _main="$ROOT" ;;
        *)    _main="$(dirname "$_common")" ;;
    esac
    _gc="$_main/compiler-codegen/vcpkg_installed/x64-windows-static/lib"
    if [ -d "$_gc" ]; then
        export NOVA_GC_LIB_DIR="$_gc"
    fi
    unset _common _main _gc
fi
unset NOVA_STD_PATH 2>/dev/null || true

# ── ЯРУСЫ ГЕЙТА (конвенция docs/dev/gate-guard-conventions.md, Г4) ───────────
#
# ЗАЧЕМ. Полный прогон стоит 23.4 минуты (профиль по шагам —
# docs/plans/275-gate-cost.md, раздел 0), и запускал его только тот, кто о нём
# помнил: CI зовёт `scripts/gate-novac.sh` и НЕ зовёт этот файл. Замер
# 2026-08-21: стражей 81, под внешним судьёй 25, без внешнего вызывающего 56.
# Механизм, который запускает только помнящий о нём, — не механизм (Г8), и
# цена уже уплачена: гейт не гоняли неделю, и в нём накопились четыре красных,
# из которых три не принадлежали тому, кто их нашёл.
#
# Лечится это НЕ ускорением. Лечится тем, что дешёвая часть гейта отделена от
# дорогой и потому может зваться машиной на каждый пуш.
#
#   loop — ТОЛЬКО чтение текста. Ни сборки, ни запуска компилятора, ни
#          `nova test`. Шаг, который поднимает `nova` или `cargo`, сюда не
#          попадает НИКОГДА — это прямая формулировка Г4, а не пожелание.
#   push — поведение: мега-CU, `conformance --full`, `nova test std/src`,
#          флагманы, смоук, crate-tests.
#   full — всё: самотесты стражей, сборка флагмана на ЧИСТОМ дереве, пакетные
#          репы, вердикт внешнего CI.
#
# ЯРУСЫ НАКОПИТЕЛЬНЫЕ: loop ⊂ push ⊂ full. Иначе `push` был бы утверждением
# не сильнее, а ДРУГИМ, — а Г4 говорит прямо: зелёный `loop` не есть основание
# для пуша. Тот, кто зовёт ярус перед отправкой, обязан получить надмножество.
#
# УМОЛЧАНИЕ — `full`, и это условие, а не настройка: всякий, кто звал гейт как
# `bash scripts/gate.sh`, обязан получить ровно тот же набор шагов в том же
# порядке, что и до появления ярусов.
# У ГЕЙТА НЕТ АРГУМЕНТОВ — ЯРУС ЕДЕТ ПЕРЕМЕННОЙ (реестр 221.1 №778).
# Ловушка стоила двадцати минут 2026-08-27: `bash scripts/gate.sh loop`
# выглядит очевидно, читается как ярус — и МОЛЧА исполняет `full`, потому что
# аргумент не читает никто, а умолчание яруса — самый тяжёлый. Дважды подряд,
# по десять минут, и оба раза это выглядело зависанием, а не ошибкой вызова.
# Асимметрия и была дефектом: неверное ЗНАЧЕНИЕ переменной гейт отвергал
# фатально, а не тот КАНАЛ глотал без единого слова — строгость стояла ровно
# там, где ошибиться труднее. Второй формы записи намеренно НЕ заводим: две
# формы одного и того же расходятся на первой же правке (этим правилом живёт
# весь репозиторий). Только громкий отказ — и правильная строка в нём.
if [ "$#" -ne 0 ]; then
    case "$1" in
        loop|push|full)
            echo "GATE FATAL: ярус задаётся переменной окружения, а не аргументом." >&2
            echo "  надо:  NOVA_GATE_TIER=$1 bash scripts/gate.sh" >&2
            echo "  было:  bash scripts/gate.sh $1  — аргумент не читается никем," >&2
            echo "         и молча пошёл бы ярус '${NOVA_GATE_TIER:-full}'." >&2
            ;;
        *)
            echo "GATE FATAL: гейт не принимает аргументов, получен '$1'." >&2
            echo "  ярус:      NOVA_GATE_TIER=loop|push|full bash scripts/gate.sh" >&2
            echo "  сухой ход: NOVA_GATE_DRYRUN=1 bash scripts/gate.sh" >&2
            ;;
    esac
    exit 1
fi

NOVA_GATE_TIER="${NOVA_GATE_TIER:-full}"
case "$NOVA_GATE_TIER" in
    loop|push|full) ;;
    *) echo "GATE FATAL: неизвестный ярус NOVA_GATE_TIER='$NOVA_GATE_TIER' (можно loop|push|full)" >&2
       exit 1 ;;
esac
case "$NOVA_GATE_TIER" in
    loop) GATE_TIER_N=1 ;;
    push) GATE_TIER_N=2 ;;
    full) GATE_TIER_N=3 ;;
esac

# СУХОЙ ПРОГОН — печатаются заголовки шагов, не исполняется ничего.
# Заведён как ДОКАЗАТЕЛЬСТВО того, что умолчание не поехало: список шагов до
# правки и после сверяется дословно (`diff`), а не на глаз. Тот же довод, что
# у Г6: «выглядит так же» — не сверка.
NOVA_GATE_DRYRUN="${NOVA_GATE_DRYRUN:-0}"

# Путь к собранному компилятору. Пуст до шага сборки — и обязан существовать
# ДО НЕГО, потому что `set -u` разворачивает аргументы шага раньше, чем шаг
# решит, его ли это ярус: в `loop` сборки нет, а строка вызова стража с
# `"$NOVA"` в аргументах читается всё равно.
NOVA=""

STEP_ACTIVE=1
# tier_at_least <ярус> — исполняется ли на ВЫБРАННОМ ярусе шаг такого класса.
tier_at_least() {
    case "$1" in
        loop) [ "$GATE_TIER_N" -ge 1 ] ;;
        push) [ "$GATE_TIER_N" -ge 2 ] ;;
        full) [ "$GATE_TIER_N" -ge 3 ] ;;
        *) return 1 ;;
    esac
}
# body_runs — исполнять ли ТЕЛО текущего шага. Заголовок и тело разделены
# намеренно: сухой прогон обязан напечатать состав яруса, ничего не сделав.
body_runs() {
    [ "$STEP_ACTIVE" -eq 1 ] || return 1
    [ "$NOVA_GATE_DRYRUN" = "1" ] && return 1
    return 0
}

# КОПИМ отказы вместо выхода на первом (2026-08-09, требование владельца
# «почти каждый шаг можно делать в фоне» + наблюдение: гейт падал на ПЕРВОМ же
# страже и не доходил до остальных, из-за чего интегратор четырежды подряд
# чинил по одной находке, тратя по 40-минутному прогону на каждую).
#
# Теперь стражи-проверки копят ошибки и гейт сообщает ВСЕ разом; выход
# происходит один раз, перед дорогими шагами (мега-CU) — незачем тратить
# 37 минут, если дерево уже не проходит дешёвые проверки.
GATE_FAILS=""
GATE_FAIL_N=0

# ОТМЕТКИ ВРЕМЕНИ — свойство ГЕЙТА, а не способа запуска (2026-08-09).
#
# Раньше время в лог ставила обёртка gate-bg.sh, и прогон, запущенный напрямую,
# оказывался непрофилируемым: владелец просил профиль, а данных не было вовсе.
# Профиль не должен зависеть от того, кто как позвал скрипт, поэтому отметку
# ставит сам шаг. Формат читает scripts/tools/gate-profile.sh.
# ESC не литералом (2026-08-12, страж check-no-control-chars): невидимый
# управляющий байт внутри регулярки — форма, которую съедает любой копипаст,
# и тогда снятие цветовых кодов молча перестаёт работать, а `PASS:` перестаёт
# находиться. Байт задаётся явно и один раз.
ESC=$(printf '\033')
GATE_T0=$(date +%s)
# ШАГ ОБЪЯВЛЯЕТ СВОЙ ЯРУС ПЕРВЫМ АРГУМЕНТОМ: `step loop "arch-ratchet"`.
# Ярус обязателен и не имеет умолчания — шаг, забывший его назвать, роняет
# гейт сразу. Молчаливое умолчание означало бы, что новый шаг, написанный по
# образцу соседней строки, тихо попадает не в тот ярус, и заметить это можно
# было бы только по секундам (тот же класс, что №519: молчаливо несудимое).
step() {
    _step_tier="$1"; shift
    case "$_step_tier" in
        loop|push|full) ;;
        *) echo "GATE FATAL: шаг гейта без яруса (loop|push|full): $_step_tier $*" >&2
           exit 1 ;;
    esac
    if tier_at_least "$_step_tier"; then
        STEP_ACTIVE=1
        printf '[%5ds] == gate: %s ==\n' "$(( $(date +%s) - GATE_T0 ))" "$1"
    else
        STEP_ACTIVE=0
    fi
}
fail() {
    echo "GATE FAIL: $1" >&2
    GATE_FAILS="$GATE_FAILS
  * $1"
    GATE_FAIL_N=$((GATE_FAIL_N + 1))
}
# ШАГ ОБЯЗАН ПРЕДЪЯВИТЬ СВОЮ СТРОКУ (правило П1 №4, реестр 221.1 №645, №647).
#
# Код возврата 0 значит «страж не упал», а не «страж проверил». 2026-08-14
# выяснилось, что шаг про секреты в дереве месяцами проходил вхолостую: из-за
# литерального `\n` страж получал не тот корень, честно печатал «ok: git не
# отдал списка файлов» — и гейт принимал это за проверку, потому что смотрел
# только на код возврата. Строка была; читать её было некому.
#
# Отсюда обёртка: страж зовётся через неё, и шаг засчитывается ТОЛЬКО если в
# выводе появилась строка со словом `ok:`. Нет строки — «шаг ничего не
# доказал», и это отказ, а не тишина. Ровно то же правило владелец давно
# сформулировал для тестового фильтра: не рапортовать счёт, которого не видел.
#
# Форму «страж зовётся через guard, а не голым bash» держит
# scripts/guards/check-gate-steps-assert.sh — иначе правило живёт до первого
# нового шага, написанного по образцу соседней строки.
# `--deadline N` — предел времени на шаг. Заворачивать вызов обёртки снаружи
# (`with-deadline.sh N guard …`) НЕЛЬЗЯ: `guard` — функция оболочки, а не
# программа, и внешняя команда её не найдёт. Именно так 2026-08-14 я сломал
# четыре шага разом при механическом переводе на обёртку; форму теперь держит
# свойство 4 в check-gate-steps-assert.sh.
guard() {
    # Шаг чужого яруса не исполняется — и НЕ засчитывается отказом: он просто
    # не этого прогона. Сухой прогон не исполняет ничего вовсе.
    body_runs || return 0
    local deadline=""
    if [ "$1" = "--deadline" ]; then deadline="$2"; shift 2; fi
    local g="$1"; shift
    local runner=bash out rc
    case "$g" in *.py) runner=python ;; esac
    if [ -n "$deadline" ]; then
        out="$(bash "$ROOT/scripts/tools/with-deadline.sh" "$deadline" "$runner" "$g" "$@" 2>&1)"; rc=$?
    else
        out="$("$runner" "$g" "$@" 2>&1)"; rc=$?
    fi
    printf '%s\n' "$out"
    [ "$rc" -eq 0 ] || return "$rc"
    printf '%s\n' "$out" | grep -q 'ok:' && return 0
    echo "ШАГ НИЧЕГО НЕ ДОКАЗАЛ: $(basename "$g") вышел с нулём, но не напечатал строку ok:" >&2
    echo "  Ноль без строки — это «не упал», а не «проверил» (реестр №645)." >&2
    return 1
}

# Барьер: вызывается там, где продолжать бессмысленно либо дорого.
gate_barrier() {
    if [ "$GATE_FAIL_N" -gt 0 ]; then
        echo "" >&2
        echo "GATE: отказов на этом рубеже — $GATE_FAIL_N:$GATE_FAILS" >&2
        exit 1
    fi
}
# `fatal` — для случаев, где продолжать НЕЛЬЗЯ (нет бинаря, сломано окружение).
fatal() { echo "GATE FATAL: $1" >&2; exit 1; }

# --- gate: dev-override visibility (221.1 №283, владелец 2026-08-04) -------
# `nova.override.toml`/`nova.local.toml` ([replace], D420) — gitignored,
# законный инструмент владельца для локальной разработки: путь-оверрайд
# поверх запиненной git-зависимости, без re-tag/push на каждой итерации.
# Опасность — не в самом файле, а в том, что он МОЛЧА подменяет резолв
# для перекрытых пакетов: гейт может показать `built:` на дереве с
# override, хотя тот же граф по `nova.lock.toml` (то, что реально видит
# любой чистый checkout — worktree/clone/CI) не соберётся вовсе. Ровно
# так был замаскирован №283 (tls запинен на коммите ДО переименования
# read_to_vec -> read_bytes, флагман уже звал новое имя — main собирался
# только потому, что override тихо подставлял живую соседнюю nova-tls).
#
# Выбор — ПРЕДУПРЕЖДЕНИЕ, не отказ. Override — рабочий инструмент
# владельца для повседневной разработки; гейт гоняется с главного репо
# постоянно (сегодня — пять раз), и жёсткий отказ означал бы либо вечно
# красный гейт на обычном рабочем дереве владельца, либо (реалистичнее)
# что первый же отказ научит держать override временно переименованным
# на время гейта — то есть ту же слепоту, только руками, а не автоматикой.
# Дыра была не в СУЩЕСТВОВАНИИ override, а в его МОЛЧАНИИ: «built:» и
# «GATE OK» выглядели одинаково что с override, что без него. Здесь чиним
# именно это — предупреждение печатается дважды (в начале прогона И рядом
# с финальным вердиктом, чтобы не потерялось при `tail`), перечисляет
# перекрытые пакеты и НЕ трогает exit code гейта.
OVERRIDE_FILES=$(find "$ROOT" \
    \( -path "*/target" -o -path "*/.git" -o -path "*/vcpkg_installed" \
       -o -path "*/node_modules" -o -path "*/.claude" \) -prune \
    -o \( -iname "nova.override.toml" -o -iname "nova.local.toml" \) -print \
    2>/dev/null)
print_override_warning() {
    echo "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
    echo "!!! GATE WARNING: dev-override (nova.override.toml/nova.local.toml) активен."
    echo "!!! Этот прогон НЕ доказывает, что дерево собирается на чистом checkout'е"
    echo "!!! (worktree/clone/CI) — перекрытые пакеты резолвятся МИМО nova.lock.toml."
    echo "$OVERRIDE_FILES" | while IFS= read -r f; do
        [ -n "$f" ] || continue
        echo "!!!   файл: $f"
        grep -v '^[[:space:]]*#' "$f" | grep -v '^[[:space:]]*$' | sed 's/^/!!!     /'
    done
    echo "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
}
if [ -n "$OVERRIDE_FILES" ]; then
    print_override_warning
fi

# КАЛИБРОВКА СРОКОВ (реестр 221.1 №558/№475, замер 2026-08-17) — ОДИН раз на
