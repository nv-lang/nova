# их судить, и оба раза оговорка честно сказала об этом в строке вердикта.
# Правило, которое читают и не исполняют, стоит меньше, чем кажется.
#
# СУТЬ ЯРУСА НЕ МЕНЯЕТСЯ: компилятор здесь НЕ СОБИРАЕТСЯ. Но если он УЖЕ
# собран — а у окна, которое только что гоняло фикстуру, он собран всегда — линт
# ИЗМЕНЁННЫХ файлов стоит около секунды. Нет бинаря — шаг говорит об этом ВСЛУХ
# и пропускает: молчаливый пропуск — тот же класс №770, ради которого всё это и затеяно.
#
# Судятся только СУЩЕСТВУЮЩИЕ файлы: удалённый путь в списке дал бы отказ линта
# о ненайденном файле — ложная краснота на здоровом дереве.
step loop "линт изменённых .nv, если компилятор уже собран (№770, вторая ступень)"
if body_runs; then
    _LNV=""
    for _f in $( {
            git -C "$ROOT" status --porcelain 2>/dev/null | sed -e 's/^...//' -e 's/.* -> //'
            _ups=$(git -C "$ROOT" rev-parse --abbrev-ref --symbolic-full-name '@{upstream}' 2>/dev/null)
            [ -n "$_ups" ] && git -C "$ROOT" diff --name-only "$_ups..HEAD" 2>/dev/null
        } | grep -E '^(spec_tests|std)/.*\.nv$' | sort -u ); do
        [ -f "$ROOT/$_f" ] && _LNV="$_LNV $ROOT/$_f"
    done
    if [ -z "$_LNV" ]; then
        echo "линт изменённых :: изменённых .nv в корпусе нет — судить нечего"
    else
        _LN="$ROOT/nova-cli/target/release/nova.exe"
        [ -x "$_LN" ] || _LN="$ROOT/nova-cli/target/release/nova"
        if [ ! -x "$_LN" ]; then
            echo "линт изменённых :: компилятор не собран — шаг пропущен, корпус судит ярус push"
        else
            _LNLOG="${TMPDIR:-/tmp}/gate_lint_changed_$$.log"
            "$_LN" lint --deny $_LNV >"$_LNLOG" 2>&1
            _LNRC=$?
            _LNLINE=$(sed -e "s/\[[0-9;]*m//g" "$_LNLOG" | grep -E "^lint: .* finding\(s\)" | tail -1)
            echo "линт изменённых :: $_LNLINE"
            echo "$_LNLINE" | grep -qE "finding\(s\)" \
                || fail "линт изменённых .nv: строки 'N finding(s)' нет вовсе (краш? см. $_LNLOG)"
            echo "$_LNLINE" | grep -qE ", 0 finding\(s\)" \
                || fail "линт изменённых .nv: находки > 0 (см. $_LNLOG). Канон корпуса — ноль; тот же шаг на ярусе push покраснеет на CI"
            [ "$_LNRC" -eq 0 ] || fail "линт изменённых .nv: exit=$_LNRC (см. $_LNLOG)"
        fi
    fi
    unset _LNV _LN _LNLOG _LNRC _LNLINE _ups _f
fi

