# `## D<N> (NEW) — …`, а слово в СКОБКАХ говорит ровно ПРОТИВОПОЛОЖНОЕ тому, ради чего
# введено исключение: это НОВОЕ решение. Цена промаха измерена тем же днём: за слепым
# пятном пряталась живая коллизия D228 (№772, закрыта перенумерацией I/O-драйвера в D466).
# Теперь принимаются: два или три диеза, необязательное `NEW`, необязательная скобка.
#
# Номер теперь берётся `sed`-ом из НАЧАЛА заголовка, а не `grep -oE "[0-9]+"` по всему
# совпадению, и это не косметика: в скобке бывают цифры — `## D375 (ex-D277,
# renumber 2026-07-03) — …` отдал бы 375, 277, 2026, 07, 03, и год с месяцем считались
# бы номерами решений — то есть расширение без этой правки завело бы ложные отказы.
if body_runs; then
    DUPES=$(grep -rhoE "^#{2,3} *D[0-9]+ *(NEW)? *(\([^)]*\))? *(\.|—)" spec/decisions/*.md \
            | sed -E "s/^#+ *D([0-9]+).*/\1/" | sort -n | uniq -d)
    [ -n "$DUPES" ] && fail "дублирующиеся номера D-блоков: $(echo "$DUPES" | tr '\n' ' ')"
fi
# №651: вердикт внешнего гейта — у итога, где его прочтут. Красный CI не
# роняет локальный гейт (совещательный шаг, см. его вызов), но GATE OK не
# имеет права ВЫГЛЯДЕТЬ полной правдой, когда авторитетный гейт красен.
CI_TAIL=""
if [ -n "${CI_VERDICT_LINE:-}" ]; then
    echo "внешний гейт (повтор вердикта, №651): $CI_VERDICT_LINE"
    case "$CI_VERDICT_LINE" in
        *RED*|*STALE*|*ОШИБКА*) CI_TAIL=" [ВНЕШНИЙ CI НЕ ЗЕЛЁНЫЙ — см. строку выше; пуш остановит pre-push]" ;;
    esac
fi

# №70: ЯРУС, КОТОРЫЙ ЧЕГО-ТО НЕ СУДИЛ, НЕ ИМЕЕТ ПРАВА ВЫГЛЯДЕТЬ ПОЛНОЙ ПРАВДОЙ.
# Тот же класс, что №651 выше (красный CI под «GATE OK») и №690 («GATE OK» над
# списком отказов): итоговая строка утверждает больше, чем проверено. Замерено
# 2026-08-26 на себе: три пуша подряд (ee4ce2ee, 372a8276, d2ca61628) ушли в main
# после локального «GATE OK» яруса loop, а авторитетный гейт краснел на
# `nova lint --deny spec_tests` — шаге яруса push.
#
# Почему не «перенести линт в loop», хотя он идёт 1с: ярус loop состоит ИЗ
# ОДНИХ стражей и не собирает компилятор вовсе (`NOVA=""` до шага сборки) —
# это его суть, а не недосмотр: он стоит секунды и потому гоняется каждый
# шаг. Линту нужен собранный `nova`, то есть cargo build — цена яруса push.
# Значит чинится не состав яруса, а его ВЕРДИКТ: loop вправе быть зелёным на
# изменённом корпусе, но не вправе молчать о том, что корпус он не судил.
#
# Считаем ИЗМЕНЁННОЕ, а не всё дерево: незакоммиченное плюс непушенное.
# Расширено в тот же день: сначала считались только `.nv`/`.rs`, и первый же прогон на
# правке рантайма назвал два файла из четырёх — `nova_rt/*.c` и `*.h` компилируются в рантайм
# и судятся тем же ярусом push. Оговорка, называющая МЕНЬШЕ, чем изменено, больна тем
# же, чем её отсутствие.
# Чистое дерево на ярусе loop — законно зелёное без оговорок, и оговорка,
# печатаемая всегда, через неделю перестаёт читаться вовсе.
TIER_TAIL=""
if [ "$GATE_TIER_N" -lt 2 ]; then
    _dirty_nv=$( {
        git -C "$ROOT" status --porcelain 2>/dev/null | sed -e 's/^...//' -e 's/.* -> //'
        _ups=$(git -C "$ROOT" rev-parse --abbrev-ref --symbolic-full-name '@{upstream}' 2>/dev/null)
        [ -n "$_ups" ] && git -C "$ROOT" diff --name-only "$_ups..HEAD" 2>/dev/null
    } | grep -E '\.(nv|rs|c|h)$' | sort -u | wc -l | tr -d ' ')
    if [ "${_dirty_nv:-0}" -gt 0 ]; then
        TIER_TAIL=" [ЯРУС loop НЕ СУДИЛ КОРПУС: изменено $_dirty_nv .nv/.rs/.c/.h — линт, мега-CU и прогон живут в push; №770]"
    fi
    unset _dirty_nv _ups
fi
# ── БЮДЖЕТ ЯРУСА (конвенция гейтов, Г1..Г7; механизм — окно 274) ────────────
# Гейт МЕРЯЕТ СЕБЯ и краснеет при превышении. Число — не рекорд, а потолок с
# запасом; живёт в scripts/guards/gate-budget.baseline и снимается замером.
# Предел масштабируется калибровкой машины (CAL): без неё на медленной машине
# он краснеет на здоровом дереве, а на быстрой не ловит ничего.
#
# Ярус, для которого строки нет, назван ВСЛУХ, а не молчит: молчаливо несудимый
# ярус — вечнозелёная дыра (класс №519).
GATE_ELAPSED=$(( $(date +%s) - GATE_T0 ))
if [ "$NOVA_GATE_DRYRUN" != "1" ]; then
    BUDGET=$(grep -E "^$NOVA_GATE_TIER[[:space:]]+[0-9]+" "$ROOT/scripts/guards/gate-budget.baseline" 2>/dev/null \
             | head -1 | awk '{print $2}')
    case "$BUDGET" in
        ''|*[!0-9]*)
            echo "бюджет :: ярус $NOVA_GATE_TIER идёт ${GATE_ELAPSED}с; строки бюджета для него нет (не судится)" ;;
        *)
            CAL="$NOVA_CAL_FACTOR"
            BUDGET_LIMIT=$(( BUDGET * CAL ))
            echo "бюджет :: ярус $NOVA_GATE_TIER — ${GATE_ELAPSED}с при пределе ${BUDGET_LIMIT}с (${BUDGET}с × калибровка ${CAL}x)"
            [ "$GATE_ELAPSED" -le "$BUDGET_LIMIT" ] \
                || fail "ярус $NOVA_GATE_TIER вышел за бюджет: ${GATE_ELAPSED}с > ${BUDGET_LIMIT}с (scripts/guards/gate-budget.baseline). Ярус, который перестал быть дешёвым, перестаёт зваться — это Г1..Г7 целиком. Чини цену шага, а не число в базе. НО СНАЧАЛА ПЕРЕЗАПУСТИ НА НЕЗАНЯТОЙ МАШИНЕ: это валл-клок, и соседняя сборка его удваивает. Замер 2026-08-26 на ОДНОМ дереве за один день: 147-294с, и первый же перезапуск после окончания сборок вернул 164с. Регресс шага повторяется, разброс — нет." ;;
    esac
fi

