"""scripts/guards/novac_subset_debt.py — ОДИН ДОМ правила «что есть отказ подмножества
и когда он датирован». Импортируется стражами, сам стражем не является.

ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Правило нужно ДВУМ проверкам с разными предметами:
`check-novac-subset-debt-dated.py` судит ДЕРЕВО (сколько бессрочных отказов лежит), а
`check-novac-commit-no-simplification.py` судит КОММИТ (не добавляет ли он новый). Две копии
одного образца разошлись бы на первой правке — и это не гипотеза: ровно так 2026-09-13 правило
выбора яруса гейта жило двумя копиями, было вынесено в один дом, и вынос обошёл двух зовущих
из трёх (реестр №988).

ЗАМЕР, РАДИ КОТОРОГО ДОМ И ЗАВЁЛСЯ (2026-09-13, окно 274). Прежний образец ловил ОДНО
написание — `"... not compiled yet ..."`. Вторая формулировка того же предмета,
`"outside the subset: ..."`, им не видна вовсе, а ею записано большинство отказов дерева.
То есть обещание стража «новый бессрочный отказ красит гейт сразу» не работало для написания,
которым записана большая часть отказов: окно, пишущее `"outside the subset: ..."` без этапа,
проходило зелёным. Шапка самого стража при этом заявляла, что судит «not compiled yet» И ЕГО
ФОРМЫ, — проза обещала область, которой у кода не было. **Чисел здесь намеренно нет**: они
печатаются самим стражем при каждом прогоне, а копия числа в прозе устаревает молча (этот
урок стоил проекту двух протухших счётчиков в `AGENTS.md`).

ПОЧЕМУ ЭТО ВАЖНО ДЛЯ ПЛАНА 274 (слово владельца 2026-09-13): каждый пункт делается БЕЗ
УПРОЩЕНИЙ, ровно по спеке, как для прода. Отказ подмножества — это и есть упрощение;
законно оно ровно тогда, когда НАЗВАНО и несёт этап, к которому исчезнет. Проверка, видящая
часть упрощений, разрешает остальные молча.
"""
import re

# ОБА написания, потому что предмет один. Список закрыт намеренно: новая формулировка отказа
# добавляется СЮДА, и это видно в диффе — в отличие от нового написания, которое иначе просто
# уехало бы мимо обеих проверок.
SPELLINGS = (
    "not compiled yet",
    "outside the subset",
)
RE_DEBT = re.compile(
    r'"[^"]*(?:%s)[^"]*"' % "|".join(re.escape(s) for s in SPELLINGS))

# СРОК — этап, к которому отказа не станет: `(E2-b3)`, `(E4)`, либо волна подмножества
# `(274.7 B1b)`, которая называет момент точнее этапа. Голая ссылка на план без буквы и
# номера волны сроком НЕ считается — иначе любая ссылка сошла бы за срок.
#
# СРОК ЧИТАЕТСЯ ВНУТРИ СКОБОК, А НЕ ВМЕСТО НИХ (правка 2026-09-13, окно 274). Прежний
# образец требовал, чтобы скобка содержала ТОЛЬКО этап, и не видел `(E2-b2 multi-file)`,
# `(E2-b, with the numeric family)`, `(no arm coercion before E2-b3)` — шесть отказов,
# у которых срок назван, считались бессрочными. Заставлять автора вычёркивать пояснение
# ради регулярки значит делать сообщение ХУЖЕ: `(E2-b2 multi-file)` говорит читателю не
# только КОГДА, но и ЧТО снимет отказ.
#
# СКОБКА ОСТАЁТСЯ ОБЯЗАТЕЛЬНОЙ, и это не формальность: она отличает ОТВЕТ на вопрос
# «когда» от упоминания этапа по пути. `«... arrives with E2-b3 -- the parameter itself
# is compiled»` в проходной фразе сроком не считается и сегодня (единственный из семи,
# оставшийся бессрочным). Признак — авторский жест, а не наличие букв в строке.
RE_STAGE = re.compile(r"\([^()]*\bE[0-9][0-9a-zA-Z-]*\b[^()]*\)"
                      r"|\([^()]*\b274\.7 [A-Z][0-9]+[a-z]?\b[^()]*\)")


# --- СЧЁТ ПО ДВЕРИ (В11-б, 2026-09-14) -------------------------------------
#
# Дверь, а не написание, есть машинный признак предмета: код диагностики выбирается
# из вида отказа в `@refuse_span_kind`, и вид приходит от того, какую дверь позвал
# автор правила. Написание же — требование к ЧЕЛОВЕКУ, читающему отказ, и мерить им
# предмет значит мерить окрестность.
#
# ДВЕРИ ДОЛГА и ДВЕРИ ПОСТОЯННОЙ ОШИБКИ перечислены поимённо. Список закрыт и
# закрыт намеренно: новая дверь добавляется СЮДА и видна в диффе — в отличие от
# новой двери, заведённой молча, которая увела бы отказы мимо обеих проверок.
SUBSET_DOORS = ("@report_first_leaf_of", "@refuse", "@refuse_span")
LANG_DOORS = ("@reject_first_leaf_of",)

RE_MSG_CONST = re.compile(r'^const\s+([A-Z][A-Z0-9_]*)\s*=\s*(".*)$')
# ВНИМАНИЕ НА ФОРМУ ОБРАЗЦА: он ищет ТОЛЬКО имя двери, не пытаясь вычленить список
# аргументов. Первая редакция брала `([^)]*)` — и резала аргумент по первой `)`, а СРОК
# стоит В СКОБКАХ: всякий датированный отказ, чей текст содержит `(`, обрезался до срока
# и считался бессрочным. Замер мерил свою регулярку, а не дерево, и выглядел
# правдоподобно — вскрыло его только СОПОСТАВЛЕНИЕ со счётом по написанию, где среди
# «невидимых» оказались строки с написанием на месте.
RE_DOOR_CALL = re.compile(r"(@[a-z_]+)\(")
# Аргумент ищется на строке вызова напрямую: либо имя константы, либо целый литерал.
# Разбирать сбалансированные скобки внутри текста сообщения незачем.
# ЛЮБОЕ заглавное имя, а не только `*_MSG`: засчитывается оно по ОБЪЯВЛЕНИЮ (есть ли
# такая константа в папке), а не по суффиксу. Первая редакция требовала `_MSG`, и это
# слепота к конвенции именования -- первый же автор, назвавший текст иначе, увёл бы
# отказ мимо счёта, и молча. Поймано собственным самотестом, написанным ради другого.
RE_MSG_NAME = re.compile(r"\b([A-Z][A-Z0-9_]*)\b")
RE_STR_LIT = re.compile(r'"(?:[^"\\]|\\.)*"')


def msg_constants(text):
    """Объявления `const X_MSG = "..."` -> {имя: (строка, литерал)}.

    Литерал читается вместе с продолжениями: сообщения длинные и переносятся, а
    образец, читающий только первую строку, увидел бы половину текста и не нашёл в
    ней срока — то есть посчитал бы датированный отказ бессрочным.
    """
    lines = text.replace("\r\n", "\n").split("\n")
    out = {}
    for i, line in enumerate(lines):
        m = RE_MSG_CONST.match(line)
        if not m:
            continue
        name, body = m.group(1), m.group(2)
        j = i
        while body.count('"') < 2 and j + 1 < len(lines):
            j += 1
            body += " " + lines[j].strip()
        out[name] = (i + 1, body)
    return out


def door_uses(text):
    """Вызовы дверей -> список (строка, дверь, аргумент-как-написан).

    Комментарии пропускаются по тому же правилу, что и в счёте по написанию: текст
    отказа в комментарии есть ПРОЗА о долге, а не сам долг.
    """
    out = []
    for i, line in enumerate(text.replace("\r\n", "\n").split("\n"), 1):
        if is_comment(line):
            continue
        for m in RE_DOOR_CALL.finditer(line):
            door = m.group(1)
            if door not in SUBSET_DOORS and door not in LANG_DOORS:
                continue
            rest = line[m.end():]
            lit = RE_STR_LIT.search(rest)
            names = [n for n in RE_MSG_NAME.findall(rest)]
            out.append((i, door, names, lit.group(0) if lit else ""))
    return out


def by_door(files):
    """Отказы, СЧИТАННЫЕ ПО ДВЕРИ. `files` — {путь: текст} всей папки `check/`.

    Возвращает (subset, lang), где каждый элемент — (путь, строка, текст, есть_срок).
    Текст берётся у константы, если аргумент — её имя, иначе из инлайнового литерала.
    """
    consts = {}
    for path, text in files.items():
        for name, (line, body) in msg_constants(text).items():
            consts[name] = (path, line, body)

    subset, lang = [], []
    for path, text in files.items():
        for line, door, names, lit in door_uses(text):
            body = None
            for n in names:
                if n in consts:
                    body = consts[n][2]
                    break
            if body is None and lit:
                body = lit
            if body is None:
                continue
            rec = (path, line, body, bool(RE_STAGE.search(body)))
            (lang if door in LANG_DOORS else subset).append(rec)
    return subset, lang


def is_comment(line):
    """Строка-комментарий: отказ в ней — ПРОЗА о долге, а не сам долг.

    Правило унаследовано от первой редакции стража и проверено на нём же: процитированный в
    комментарии текст отказа однажды стал «долгом», как и цитата в `_test.nv`.
    """
    return line.lstrip(" \t\v\f").startswith("//")


def refusals(text):
    """Отказы подмножества в тексте: список (номер строки, сам литерал, несёт ли срок).

    СРОК ИЩЕТСЯ ВНУТРИ ЛИТЕРАЛА, а не в строке: этап обязан стоять в сообщении, которое
    ЧИТАЕТ пользователь. Срок, стоящий рядом в коде, отвечает на вопрос автора, а не на
    вопрос того, кому отказали.
    """
    out = []
    for i, line in enumerate(text.replace("\r\n", "\n").split("\n"), 1):
        if is_comment(line):
            continue
        m = RE_DEBT.search(line)
        if not m:
            continue
        out.append((i, m.group(0), bool(RE_STAGE.search(m.group(0)))))
    return out


def undated(text):
    """Только бессрочные — те, что и есть невыплаченный долг."""
    return [(i, lit) for i, lit, staged in refusals(text) if not staged]
