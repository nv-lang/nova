#!/usr/bin/env bash
# Страж: в рабочем дереве нет файлов со СМЕШАННЫМИ окончаниями строк.
#
# ЗАЧЕМ. Смешанные окончания строк ломают всё построчное: diff показывает
# правку там, где её нет; `grep -c` и `wc -l` расходятся между машинами;
# инструмент, считающий позицию по строкам, и инструмент, считающий по
# байтам, дают разные ответы для одного и того же места. Файл при этом
# выглядит нормально в любом редакторе — расхождение видно только машине.
#
# ЧЕСТНО ПРО ПОВОД, потому что первая версия этой шапки утверждала лишнее.
# 2026-08-18 владелец показал `novac/src/lex/lex.nv`, где inlay-подсказки LSP
# встают ВНУТРЬ слов, и файл оказался смешанным (469 CRLF + 6 одиночных LF),
# а съезд был ровно на шесть символов. Корреляция выглядела доказательством,
# и я записал её сюда как причину. Синтетическая проверка её ОПРОВЕРГЛА: один
# и тот же исходник, записанный тремя способами (весь LF / весь CRLF /
# смешанно), даёт ОДИНАКОВЫЕ подсказки и ноль плохих во всех трёх. Значит
# причина поездки подсказок (реестр №709) НЕ НАЙДЕНА, и этот страж её НЕ
# закрывает. Он закрывает свой собственный класс — негигиену, которая
# однажды даст расхождение в другом месте.
#
# ПОЧЕМУ GIT ЭТОГО НЕ ВИДИТ. `core.autocrlf=true`, `.gitattributes` нет: в
# объекте файл однороден, а смешанным становится ПОСЛЕ выкладки, когда
# инструмент дописывает строки в LF; `git diff` при этом ПУСТ — git
# нормализует окончания при сравнении. Дефект живёт там, где никто не
# смотрит: в рабочем дереве, которое и читают инструменты.
#
# ЛЕЧЕНИЕ — НЕ КОММИТ. В git чинить нечего; чинится ПЕРЕВЫКЛАДКА:
#     rm <файл> && git -C <дерево> checkout -- <файл>
# Профилактика: записывая файл, сохраняй ЕГО окончания строк, а не свои
# (питон-скрипты по умолчанию пишут `\n` — именно так класс и заводится,
# в том числе у интегратора).
#
# НОЛЬ, БЕЗ ХРАПОВИКА: замер 2026-08-18 — в `nova` был ОДИН такой файл на
# 5632, вылечен перевыкладкой. База ради одного случая дороже нуля.
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u

NAME="check-mixed-eol"
ROOT="${1:-.}"
CORE="$ROOT/scripts/guards/mixed-eol-scan.py"

if [ ! -f "$CORE" ]; then
    echo "$NAME: FAIL — нет ядра $CORE" >&2
    exit 1
fi

OUT=$(python "$CORE" "$ROOT" 2>&1)
if [ $? -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    echo "$OUT" >&2
    exit 1
fi

TOTAL=$(printf '%s\n' "$OUT" | sed -n 's/^total=\([0-9][0-9]*\)$/\1/p' | tail -1)
case "$TOTAL" in
    ''|*[!0-9]*) echo "$NAME: FAIL — ядро не вернуло число" >&2; exit 1;;
esac

if [ "$TOTAL" -ne 0 ]; then
    echo "$NAME: FAIL — файлов со смешанными окончаниями строк: $TOTAL" >&2
    printf '%s\n' "$OUT" | grep -v '^total=' | head -10 >&2
    echo "    Один одиночный LF в CRLF-файле разводит построчные и побайтные" >&2
    echo "    счётчики: diff показывает правку там, где её нет, а два инструмента" >&2
    echo "    дают разные позиции для одного места. В редакторе всё выглядит цело." >&2
    echo "    Лечится НЕ коммитом — в git файл уже однороден, а перевыкладкой:" >&2
    echo "      rm <файл> && git -C \"$ROOT\" checkout -- <файл>" >&2
    exit 1
fi

echo "$NAME ok: смешанных окончаний строк в рабочем дереве нет"
exit 0
