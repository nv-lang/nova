#!/bin/sh
# scripts/guards/check-novac-fuzz-zero-panic.sh — приёмка Э1 ранга CORE
# (план 274 §9): novac НЕ ПАДАЕТ ни на одном входе. Мутационный фаззер
# (scripts/tools/novac-fuzz-mutations.sh) — свидетель; этот страж — дверь,
# через которую его вердикт попадает в гейт.
#
# ПОЧЕМУ ОБЁРТКА, А НЕ ВЫЗОВ ИНСТРУМЕНТА ПРЯМО В ГЕЙТЕ. Так и было — и так
# приёмка ПРОПАЛА. Аудит 274.3 2026-08-17 (находка F2, помеченная в доке
# закрытой): шаг фаззера, вписанный в gate.sh коммитом be09fd794, исчез при
# переезде novac-шагов в gate-novac.sh, и месяц ранг CORE не проверялся
# ничем. Инструмент, вызываемый из гейта напрямую, не виден мета-стражу
# реестра — он сверяет план ↔ файлы стражей ↔ вызовы гейта ↔ самотесты.
# Обёртка ставит приёмку под этот мета-страж: теперь её пропажа краснеет
# сама. Это фикс КЛАССА («механизм есть, но его исчезновение никем не
# замечается»), а не фикс экземпляра.
#
# $1 — корень; $2 — override пути инструмента (шов самотеста); $3 — шаг.
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
TOOL="${2:-$ROOT/scripts/tools/novac-fuzz-mutations.sh}"
# ШАГ МУТАЦИЙ ЗАВИСИТ ОТ ЯРУСА (правка 2026-09-16, слово владельца «фаззер надо
# уменьшить, не надо столько много и так долго»).
#
# ЗАМЕР, КОТОРЫЙ ЭТО РЕШИЛ: на шаге 40 страж идёт БОЛЬШЕ ПЯТНАДЦАТИ МИНУТ
# локально (сосед по шагу — 83с), а на CI он внутри `novac-heavy`, который
# съел 37 минут из 45-минутного предела job'а и довёл его до ОТМЕНЫ (№1138).
#
# ЧТО ИМЕННО ТЕРЯЕТ ЯРУС push, названо числом, а не словом «немного»: шаг —
# это байтовый ШАГ мутаций, число проб обратно пропорционально ему. Шаг 160
# вместо 40 — это ЧЕТВЕРТЬ позиций мутаций, то есть выборка, а не полнота.
# Полная плотность не отменена, она ПЕРЕЕХАЛА в ночной ярус `full`.
#
# ПОЧЕМУ ЭТО НЕ «СНЯТИЕ ПРОВЕРКИ»: приёмка ранга CORE («novac не падает ни на
# одном входе») остаётся под судом каждую ночь и под выборкой — на каждом
# пуше. Ослаблением было бы молчание о выборке; поэтому страж ПЕЧАТАЕТ, каким
# шагом он шёл, и «зелено» на выборке нельзя прочесть как «зелено на всём».
NOVAC_TIER="${NOVAC_TIER:-push}"
case "$NOVAC_TIER" in
    full) _step_default=40 ;;
    *)    _step_default=160 ;;
esac
STEP="${3:-$_step_default}"
NAME=check-novac-fuzz-zero-panic

if [ ! -f "$TOOL" ]; then
    echo "$NAME: FAIL — нет инструмента $TOOL: приёмка ранга CORE осталась без свидетеля (274.3/F2)" >&2
    exit 1
fi

OUT="$(sh "$TOOL" "$STEP" 2>&1)"
rc=$?
if [ "$rc" -ne 0 ]; then
    echo "$NAME: FAIL — фаззер нашёл падение novac (приёмка Э1, ранг CORE):" >&2
    printf '%s\n' "$OUT" | tail -n 6 | sed 's/^/  /' >&2
    exit 1
fi
# Вердикт НАЗЫВАЕТ ШАГ: «зелено на выборке» и «зелено» — разные утверждения,
# и путать их нельзя (тот же довод, по которому ноль без строки `ok:` не
# считается проверкой).
printf '%s\n' "$OUT" | tail -n 1 | sed "s/^/$NAME ok (ярус $NOVAC_TIER, шаг мутаций $STEP): /"
exit 0
