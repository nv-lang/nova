#!/bin/sh
# scripts/guards/check-novac-ice-messages.sh — сообщение `ice()` заменяет
# собой место падения (конвенция П12 §дополнение; вопрос владельца
# 2026-08-16 «панику не возвращаем на место появления, чтобы место было
# точным?»).
#
# ФАКТ, ИЗ КОТОРОГО РАСТЁТ ПРАВИЛО (проверено пробой 2026-08-16). `ice()` —
# функция-обёртка над `panic`, поэтому рантайм записывает site ТЕЛА ОБЁРТКИ,
# а не места вызова: проба дала `site: {file: icesite.nv, line: 5}` — строку
# самого `ice()`, при том что сломалось в вызывающей функции. Трасса при
# этом пуста (`trace: []`). Аналога `#[track_caller]` в языке нет:
# `__FILE__`/`__LINE__` есть только внутри кодогена для контрактов и
# пользовательскому коду не отдаются. Значит ЕДИНСТВЕННЫЙ носитель места —
# текст сообщения, и он обязан быть носителем надёжным.
#
# ПРОВЕРЯЕТ по novac/src/**/*.nv (тесты исключены):
#   * каждое сообщение `ice("…")` УНИКАЛЬНО в пределах novac — два одинаковых
#     текста при схлопнутом site неразличимы (живой случай: `sem: expected a
#     leaf` стоял в leaf_text и в leaf_kind сразу);
#   * каждое начинается с `<модуль>: ` — модуль первым словом, потому что
#     это первое, что нужно знать читающему отказ.
# НЕ ПРОВЕРЯЕТ: содержательность текста (приёмка); сообщения `panic(` вне
#   двери (это ведомство check-novac-no-naked-panic.sh); многострочные и
#   интерполированные сообщения — они здесь не встречаются, а появятся —
#   правило уточняется вместе с ними.
#
# $1 — корень репозитория; $2 — override сканируемой директории (самотест).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-ice-messages

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

T="${TMPDIR:-/tmp}/novac-ice-msgs.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | sort | while IFS= read -r f; do
    rel=${f#"$SRC"/}
    tr -d '\r' < "$f" | grep -noP 'ice\("\K[^"]+' | sed "s|^|$rel:|"
done > "$T/all"

TOTAL=$(wc -l < "$T/all" | tr -d '[:space:]')
if [ "$TOTAL" -eq 0 ]; then
    echo "$NAME ok: судить нечего (вызовов ice() в $SRC: 0)"
    exit 0
fi

# --- дубли: один и тот же текст в двух местах ------------------------------
cut -d: -f3- "$T/all" | sort | uniq -d > "$T/dups"
if [ -s "$T/dups" ]; then
    echo "$NAME: FAIL — одинаковый текст ice() в разных местах (П12: текст заменяет site):" >&2
    while IFS= read -r m; do
        echo "  «$m» — здесь:" >&2
        grep -F ":$m" "$T/all" | sed 's|^|    |' >&2
    done < "$T/dups"
    echo "  Site паники указывает на тело ice(), а не на место вызова (аналога track_caller нет)," >&2
    echo "  поэтому одинаковый текст делает два разных отказа неразличимыми. Назови в тексте" >&2
    echo "  функцию или условие: «sem: leaf_text on a branch node»." >&2
    exit 1
fi

# --- префикс модуля --------------------------------------------------------
cut -d: -f3- "$T/all" | grep -vP '^[a-z_]+: ' > "$T/noprefix" || true
if [ -s "$T/noprefix" ]; then
    echo "$NAME: FAIL — сообщение ice() без префикса модуля (П12):" >&2
    while IFS= read -r m; do
        grep -F ":$m" "$T/all" | sed 's|^|  |' >&2
    done < "$T/noprefix"
    echo "  Форма: «<модуль>: что сломалось». Модуль первым словом — это первое," >&2
    echo "  что нужно знать читающему отказ, когда site указывает на дверь." >&2
    exit 1
fi

echo "$NAME ok: вызовов ice(): $TOTAL, все тексты уникальны и с префиксом модуля"
exit 0
