#!/bin/sh
# scripts/guards/check-guard-honesty.sh — страж не имеет права ВРАТЬ или МОЛЧАТЬ
# вместо того, чтобы судить.
#
# ОДИН предмет, три формы. Все три пойманы живьём 2026-08-18 разбором красного
# CI, и каждая делала одно и то же: вердикт был, а проверки не было.
#
#  (1) CRLF в .sh. check-novac-cli-surface.sh и check-novac-row-fields.sh лежали
#      в индексе с CRLF; под sh на Linux они падали с "syntax error near
#      unexpected token do\r" — а гейт показывал их ПАДЕНИЕ как нарушение
#      правила: «команда novac, которой нет у nova-cli», «поле строки реестра
#      без записи». Соврал дважды: и про правило, и про то, что вообще
#      проверялось. Из 275 скриптов в CRLF лежали ровно эти два.
#
#  (2) Слепота на Linux. Стражи искали nova.exe; на Linux бинарь зовётся nova, и
#      дифф-страж — главное доказательство корректности проекта — печатал
#      «судить нечего (оракул не собран)» при СОБРАННОМ оракуле. Зелёное
#      молчание, неотличимое от «проверено» (класс K-A, 274.3/F1).
#
#  (3) Апостроф в сообщении. В двойных кавычках он выполняется оболочкой:
#      символ пропадает из текста, а в вывод падает "x: command not found".
#      Видно только на КРАСНОЙ ветке — то есть ровно тогда, когда сообщение
#      читают. 15 таких мест в 8 файлах; одно я добавил сам через десять минут
#      после того, как измерил класс, — значит правило нужно машине, а не
#      памяти.
#
# ПРОВЕРЯЕТ scripts/**/*.sh:
#   * ни одного CRLF в ИНДЕКСЕ (рабочее дерево на Windows законно иное);
#   * файл, называющий nova.exe, знает и второе имя — через дверь
#     novac_find_oracle или прямым запасным путём;
#   * апостроф в двойных кавычках у echo/printf.
# ПРОВЕРЯЕТ scripts/**/*.py — стражи переезжают на python (П14: один старт
#   интерпретатора вместо сорока), и судья, который смотрит только .sh, слепнет
#   РОВНО ПО МЕРЕ ПЕРЕЕЗДА. Это класс №519, и он здесь закрыт:
#   * та же слепота к имени бинаря (nova.exe без второго имени);
#   * check-*.py, который печатает вердикт, не переведя поток на LF: python на
#     Windows пишет CRLF там, где shell писал LF, и вывод расходится с
#     shell-редакцией молча — сверка порта перестаёт что-либо значить
#     (поймано на первых же портах 2026-08-19).
# НЕ ПРОВЕРЯЕТ: строки, содержащие одинарную кавычку — там живут awk-программы
#   и фикстуры самотестов, где апостроф безобиден; это сознательная слепая
#   зона, названная здесь, а не молчаливая. Смысл сообщений; прочие башизмы
#   (их судит сам CI, и это честнее, чем угадывать их список).
#
# $1 — корень репозитория (default: вычислить от себя).

set -u

NAME="check-guard-honesty"
ROOT="${1:-$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)}"
DIR="$ROOT/scripts"
DOOR="lib/novac.sh"

if [ ! -d "$DIR" ]; then
    echo "$NAME ok: судить нечего (нет $DIR)"
    exit 0
fi

FILES=$(find "$DIR" -type f -name '*.sh' | sort)
N=$(printf '%s\n' "$FILES" | grep -c . || true)
if [ "$N" -eq 0 ]; then
    echo "$NAME: FAIL — в $DIR нет ни одного .sh: судить нечего там, где судить обязано" >&2
    exit 1
fi

BAD=""

# (1) CRLF — в ИНДЕКСЕ, а не в рабочем дереве: на Windows checkout законно
# кладёт CRLF почти во всё, и судить диск значит краснеть на здоровом дереве
# (поймано этим же стражем в первый запуск). Значение имеет то, что выкачивает
# Linux, то есть содержимое блоба; про него отвечает --eol.
CR=$(git -C "$ROOT" ls-files --eol -- 'scripts/*.sh' 'scripts/**/*.sh' 2>/dev/null \
    | awk '$1 ~ /i\/crlf/ { print "  " $NF ": CRLF в индексе — под sh на Linux не запустится" }')
[ -n "$CR" ] && BAD="$BAD$CR
"

# (2) и (3) — ОДИН проход awk по всем скриптам разом (2026-08-19). Прежняя
# редакция поднимала до десяти процессов на файл: 84 секунды на 277 файлах,
# больше любого другого шага гейта. Страж о цене формы сам платил её.
SCAN=$(printf '%s\n' "$FILES" | xargs awk -v ROOT="$ROOT/" -v DOOR="$DOOR" '
    function verdict() {
        if (rel == "") return
        if (!skip && saw_exe && !saw_door && !saw_fallback)
            printf "  %s: знает только nova.exe — на Linux не найдёт оракула и промолчит\n", rel
    }
    FNR == 1 {
        verdict()
        rel = FILENAME; sub("^" ROOT, "", rel)
        skip = (index(rel, DOOR) > 0 || index(rel, "/selftest/") > 0)
        saw_exe = 0; saw_door = 0; saw_fallback = 0
    }
    {
        line = $0; sub(/\r$/, "", line)
        if (!skip) {
            if (line !~ /^[[:space:]]*#/ && line ~ /release\/nova\.exe/) saw_exe = 1
            if (line ~ /novac_find_oracle/) saw_door = 1
            if (line ~ /release\/nova"/ || line ~ /release\/nova /) saw_fallback = 1
        }
        # Строки с одинарной кавычкой пропускаются целиком: там awk-программы
        # и фикстуры самотестов, где апостроф безобиден (слепая зона названа
        # в шапке).
        if (line ~ /^[[:space:]]*(echo|printf|ok|bad)[[:space:]]/ &&
            index(line, "\047") == 0 && index(line, "\\`") == 0 && index(line, "`") > 0)
            printf "  %s:%d: апостроф в двойных кавычках — оболочка выполнит его как команду\n", rel, FNR
    }
    END { verdict() }
')
[ -n "$SCAN" ] && BAD="$BAD$SCAN
"

# (4) ДВОЙНОЙ возврат каретки (`\r\r`) в файлах дерева. 2026-08-19: патч-
# скрипт записал novac/src/parse/decls.nv с `\r\r\n` — 81 строка. Компилятор
# это стерпел, а всякий читатель с универсальными переводами строк увидел
# ВДВОЕ больше строк: номера в диагностиках уехали на девять, и поймано это
# было случайно. Ошибка инструмента, которая портит ДАННЫЕ, обязана краснеть.
CRCR=$(git -C "$ROOT" ls-files -z -- 'novac/**' 'scripts/**' 'docs/**' 2>/dev/null \
    | xargs -0 grep -lIU "$(printf '\r\r')" 2>/dev/null \
    | sed 's|^|  |; s|$|: двойной возврат каретки (\\r\\r) — файл записан сломанным инструментом|')
[ -n "$CRCR" ] && BAD="$BAD$CRCR
"

# (5) Питоновские стражи — под тем же судом. Считаются ОТДЕЛЬНО и печатаются
# в итоге: если завтра переезд доедет до конца, а число питоновских останется
# нулём, это будет видно в строке вердикта, а не выяснится через месяц.
PY=$(find "$DIR" -type f -name '*.py' | sort)
NPY=$(printf '%s\n' "$PY" | grep -c . || true)
if [ "$NPY" -gt 0 ]; then
    PSCAN=$(printf '%s\n' "$PY" | xargs awk -v ROOT="$ROOT/" '
        function verdict() {
            if (rel == "") return
            if (!skip && saw_exe && !saw_fallback)
                printf "  %s: знает только nova.exe — на Linux не найдёт оракула и промолчит\n", rel
            if (is_check && saw_print && !saw_lf)
                printf "  %s: печатает вердикт, не переведя поток на LF — на Windows это CRLF\n", rel
        }
        FNR == 1 {
            verdict()
            rel = FILENAME; sub("^" ROOT, "", rel)
            skip = (index(rel, "/selftest/") > 0)
            is_check = (rel ~ /check-[^\/]*\.py$/)
            saw_exe = 0; saw_fallback = 0; saw_print = 0; saw_lf = 0
        }
        {
            line = $0; sub(/\r$/, "", line)
            if (line !~ /^[[:space:]]*#/ && line ~ /release\/nova\.exe/) saw_exe = 1
            if (line ~ /release\/nova[^.]/ || line ~ /release\/nova$/) saw_fallback = 1
            if (line ~ /novac_find_oracle/) saw_fallback = 1
            if (line ~ /(^|[^A-Za-z_.])print\(/) saw_print = 1
            if (line ~ /reconfigure\(/ && line ~ /newline=/) saw_lf = 1
        }
        END { verdict() }
    ')
    [ -n "$PSCAN" ] && BAD="$BAD$PSCAN
"
fi

if [ -n "$(printf '%s' "$BAD" | tr -d '[:space:]')" ]; then
    echo "$NAME: FAIL — страж может соврать или промолчать вместо проверки" >&2
    printf '%s' "$BAD" >&2
    echo "  Вердикт без проверки хуже отсутствия стража: по нему принимают решения." >&2
    exit 1
fi

echo "$NAME ok: скриптов проверено $N (.sh) и ${NPY:-0} (.py), CRLF 0, слепых к имени бинаря 0, съедаемых оболочкой сообщений 0"
exit 0
