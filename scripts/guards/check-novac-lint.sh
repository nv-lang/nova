#!/bin/sh
# scripts/guards/check-novac-lint.sh — свод nv-coding-style по novac/src чист.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, а не inline-строкой в гейте. Раннер guard() гейта
# исполняет ПЕРВЫЙ аргумент как файл через `bash <файл>`; inline-форма
# `guard sh -c '...'` подсовывала ему бинарь /usr/bin/sh и падала с
# «cannot execute binary file» — гейт краснел про линт, которого не было
# (живой случай 2026-08-16, два прогона подряд). Файл-страж — единственная
# форма, которую контракт раннера исполняет честно.
#
# ПРОВЕРЯЕТ: `nova lint novac/src` даёт 0 замечаний. Бинарь — оракул дерева
#   ($ROOT/nova-cli/target/release/nova); нет бинаря — красный, молчать
#   нельзя (класс №519: пустой вход не «зелёный», а сломанный разбор).
# НЕ ПРОВЕРЯЕТ: стиль самих правил линта (их держит оракул).
#
# $1 — корень репозитория; $2 — override бинаря nova (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
NOVA="${2:-$ROOT/nova-cli/target/release/nova}"
NAME=check-novac-lint

if [ ! -x "$NOVA" ] && [ ! -f "$NOVA" ]; then
    echo "$NAME: FAIL — бинарь nova не найден: $NOVA (нет бинаря — нет проверки, молчать нельзя)" >&2
    exit 1
fi
OUT=$("$NOVA" lint "$ROOT/novac/src" 2>&1)
LAST=$(printf '%s\n' "$OUT" | tail -n 1)
case "$LAST" in
    *" 0 finding"*)
        echo "$NAME ok: nova lint по novac/src — 0 замечаний ($LAST)"
        exit 0 ;;
    *finding*)
        echo "$NAME: FAIL — nova lint нашёл замечания в novac/src:" >&2
        printf '%s\n' "$OUT" | tail -n 20 >&2
        exit 1 ;;
    *)
        echo "$NAME: FAIL — вывод nova lint не распознан (сломан разбор, класс №519): «$LAST»" >&2
        exit 1 ;;
esac
