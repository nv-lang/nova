#!/bin/sh
# scripts/guards/check-novac-lint.sh — свод nv-coding-style по novac/src чист.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, а не inline-строкой в гейте. Раннер guard() гейта
# исполняет ПЕРВЫЙ аргумент как файл через `bash <файл>`; inline-форма
# `guard sh -c '...'` подсовывала ему бинарь /usr/bin/sh и падала с
# «cannot execute binary file» — гейт краснел про линт, которого не было
# (живой случай 2026-08-16, два прогона подряд). Файл-страж — единственная
# форма, которую контракт раннера исполняет честно.
#
# ПРОВЕРЯЕТ: `nova lint novac/src` даёт 0 замечаний. Бинарь — оракул дерева
#   ($ROOT/nova-cli/target/release/nova); нет бинаря — красный, молчать
#   нельзя (класс №519: пустой вход не «зелёный», а сломанный разбор).
#   ПЛЮС: ноль не куплен маркером — см. ниже.
# НЕ ПРОВЕРЯЕТ: стиль самих правил линта (их держит оракул).
#
# ПОЧЕМУ ЗДЕСЬ ЖЕ ПРОВЕРЯЕТСЯ ЧИСЛО МАРКЕРОВ, а не отдельным стражем: маркер
# `[M-...]` В СТРОКЕ ГАСИТ находку линта на этой строке. Замерено 2026-08-31 на
# этом дереве: проба с `Foo.from` и `Foo.parse` даёт 2 находки, она же с
# дописанным `// [M-lint-probe-274]` — 1, и маркер взят произвольный, то есть
# гасит любой. Класс найден соседним окном в std (реестр №858, трек оракула:
# `W_STATIC_CONVERSION` видел нарушение публичного API с 2026-07-09 и всё это
# время отчитывался зелёным).
#
# Корень в оракуле и чинится там. Здесь — защита от того, чтобы класс проявился
# в novac НЕЗАМЕТНО: страж, который докладывает «0 замечаний», обязан отвечать
# за то, что ноль настоящий. Проверено обратной пробой на живом дереве:
# единственный маркер novac стоит в ДОКОВОЙ строке и не гасит ничего (0 находок
# и с ним, и с нейтрализованным), поэтому база — не ноль, а «сколько есть».
#
# УСЛОВИЕ КОНЦА, чтобы защита не пережила болезнь: когда №858 закрыт и маркер
# перестал гасить, эта половина стража снимается вместе с базой.
#
# $1 — корень репозитория; $2 — override бинаря nova (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
NOVA="${2:-$ROOT/nova-cli/target/release/nova}"
NAME=check-novac-lint

if [ ! -x "$NOVA" ] && [ ! -f "$NOVA" ]; then
    echo "$NAME: FAIL — бинарь nova не найден: $NOVA (нет бинаря — нет проверки, молчать нельзя)" >&2
    exit 1
fi
# База маркеров: ЧИСЛО строк, а не ноль — существующий маркер живёт в доке и
# ничего не гасит (обратная проба выше). Рост числа — красный: новая строка с
# маркером может унести с собой находку, и никто этого не увидит.
MARK_BASE=1
MARKS=$(grep -rn '\[M-' "$ROOT/novac/src" --include='*.nv' 2>/dev/null | wc -l | tr -d ' ')
if [ "$MARKS" -gt "$MARK_BASE" ]; then
    echo "$NAME: FAIL — строк с маркером [M-...] в novac/src: $MARKS при базе $MARK_BASE" >&2
    echo "  Маркер в строке ГАСИТ находку линта на ней (замер 2026-08-31, реестр №858)," >&2
    echo "  поэтому каждая новая такая строка может унести находку молча." >&2
    echo "  Либо снимите маркер, либо поднимите базу СТРОКОЙ С ПРИЧИНОЙ и покажите" >&2
    echo "  обратной пробой, что она ничего не гасит: нейтрализуйте маркер и" >&2
    echo "  сравните число находок." >&2
    grep -rn '\[M-' "$ROOT/novac/src" --include='*.nv' 2>/dev/null | head -10 >&2
    exit 1
fi
OUT=$("$NOVA" lint "$ROOT/novac/src" 2>&1)
LAST=$(printf '%s\n' "$OUT" | tail -n 1)
case "$LAST" in
    *" 0 finding"*)
        echo "$NAME ok: nova lint по novac/src — 0 замечаний ($LAST); строк с маркером [M-]: $MARKS при базе $MARK_BASE — ноль не куплен маркером"
        exit 0 ;;
    *finding*)
        echo "$NAME: FAIL — nova lint нашёл замечания в novac/src:" >&2
        printf '%s\n' "$OUT" | tail -n 20 >&2
        exit 1 ;;
    *)
        echo "$NAME: FAIL — вывод nova lint не распознан (сломан разбор, класс №519): «$LAST»" >&2
        exit 1 ;;
esac
