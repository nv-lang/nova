#!/usr/bin/env bash
# scripts/guards/check-no-mojibake.sh
# Текст, испорченный «UTF-8 прочитан как CP1251», не попадает в дерево.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №637 (обратные апострофы и кириллица через
# оболочку), №643; ремонтный инструмент `scripts/tools/demojibake.py`
# (GitHub issue #1), план 231 трек Д.
#
# ЗАЧЕМ. Класс известен давно — под него написан ремонтный инструмент, — но
# СТРАЖА не было, и 2026-08-13 порча прошла в `main` трижды за смену: запись
# реестра №635 лишилась всех трёх обязательных полей (их «съело» на пути через
# heredoc), а правило «Отправляй то, что проверял» на странице правил уехало
# на три зеркала нечитаемым. Ни один существующий механизм этого не увидел:
# `check-no-control-chars` смотрит управляющие БАЙТЫ, а мохибейк состоит из
# вполне законных символов; `doc-conventions` проверяет язык и парность, а не
# читаемость.
#
# ПРИЗНАК — и почему именно такой. Первая редакция искала «кириллица, за
# которой идёт символ Latin-1» и дала 2468 ложных срабатываний: русские
# кавычки «» — это U+00AB/U+00BB, ровно Latin-1 Supplement. Признак обязан
# быть таким, какого в правильном русском тексте НЕ БЫВАЕТ ВОВСЕ: буквы
# сербско-македонского ряда (Ђ Ѓ ђ ѓ ћ ќ љ њ ї ѕ), в которые превращаются
# вторые байты UTF-8 при чтении как CP1251. Их наличие — не эвристика, а
# подпись поломки.
#
# ВТОРАЯ ПОДПИСЬ — СИМВОЛ-ЗАМЕНА U+FFFD (добавлена 2026-09-05, реестр №972).
# Порча бывает двух родов, и до этой правки страж знал один. «UTF-8 как CP1251»
# текст СОХРАНЯЕТ — его можно вернуть обратным преобразованием. Символ-замена
# означает, что байты УТЕРЯНЫ: обратного преобразования нет, восстановить можно
# только из истории git. Второй род жил в дереве молча: 6552 символа в восьми
# файлах, из них 6204 в `docs/history/simplifications-closed.md` — файле, на
# который AGENTS.md ссылается как на дом закрытых упрощений, — и 342 в
# `docs/plans/45-nova-doc.md`.
#
# Почему это не заметили: ремонтный проход `e504932dd` («восстановление
# cp1251-порчи», 2026-07-19) прошёл по дереву и НЕ изменил их числа. Инструмент
# и страж делили ОДНУ слепую зону, поэтому починка выглядела полной, а гейт с
# тех пор был зелёным по обеим меркам. Найдено 2026-09-05 не поиском порчи, а
# случайно: одна такая пара («НУЛ<замена>ём») попалась в записи №585 реестра.
#
# ДВЕ МЕТРИКИ, А НЕ ОДНА СУММА, и это осознанно: слив их в один счёт, я сделал
# бы прежнее число несравнимым с его собственной летописью — храповик, у
# которого молча сменился предмет счёта, мерит уже не то, что обещал.
#
# ЧЕГО НЕ ЛОВИТ (сказано честно):
#   * порчу, не дающую этих букв (короткие слова, где второй байт лёг иначе);
#   * английский текст — он такой порчи не переживает заметно;
#   * `scripts/tools/demojibake.py` исключён НАМЕРЕННО: он ХРАНИТ образцы
#     порчи как данные, и краснеть на ремонтном инструменте значит учить
#     обходить стража;
#   * потерю СМЫСЛА без символа-замены: если байты выпали так, что получилась
#     другая законная буква, обе подписи молчат. Такой порчи в дереве не
#     искали — способа искать её механически я не знаю.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-no-mojibake.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-no-mojibake.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
BASELINE="${NOVA_MOJIBAKE_BASELINE:-$ROOT/scripts/guards/mojibake.baseline}"
CORE="$(dirname "${BASH_SOURCE[0]}")/mojibake-scan.py"

[ -f "$CORE" ] || { echo "check-no-mojibake: нет ядра $CORE" >&2; exit 1; }

read_base() {   # $1 — ключ в базе; нет базы или ключа — 0
    local v=0
    [ -f "$BASELINE" ] && v=$(sed -n "s/^$1=\([0-9][0-9]*\).*/\1/p" "$BASELINE" | head -1)
    echo "${v:-0}"
}

# ОДИН обход на обе подписи (`--both`), а не два вызова ядра. Замер 2026-09-05:
# два вызова стоили 4538мс + 3949мс, из них `git ls-files` — 150мс; вся цена в
# обходе и чтении 27 расширений, поэтому один проход снимает почти половину.
BOTH=$(python "$CORE" "$ROOT" --both 2>/dev/null)

OUT=$(printf '%s\n' "$BOTH" | sed -n 's/^sig://p')
TOTAL=$(printf '%s\n' "$OUT" | grep -c . || true)
TOTAL=${TOTAL:-0}
BASE=$(read_base mojibake_lines)

OUT_F=$(printf '%s\n' "$BOTH" | sed -n 's/^fffd://p')
TOTAL_F=$(printf '%s\n' "$OUT_F" | grep -c . || true)
TOTAL_F=${TOTAL_F:-0}
BASE_F=$(read_base fffd_lines)

echo "check-no-mojibake: строк с подписью порчи $TOTAL (база $BASE), с символом-заменой $TOTAL_F (база $BASE_F)"

FAIL=0

if [ "$TOTAL" -gt "$BASE" ]; then
    echo "check-no-mojibake: ВЫРОСЛО — $TOTAL > базы $BASE" >&2
    printf '%s\n' "$OUT" | head -20 | sed 's/^/    /' >&2
    echo "" >&2
    echo "    Это «UTF-8 прочитан как CP1251»: текст записан через оболочку." >&2
    echo "    Пиши файл инструментом записи и запускай его; сообщения коммитов" >&2
    echo "    передавай через -F <файл>. Починить уже испорченное:" >&2
    echo "      python scripts/tools/demojibake.py <файл>" >&2
    echo "    Реестр 221.1 №637." >&2
    FAIL=1
fi

if [ "$TOTAL_F" -gt "$BASE_F" ]; then
    echo "check-no-mojibake: ВЫРОСЛО (символ-замена) — $TOTAL_F > базы $BASE_F" >&2
    printf '%s\n' "$OUT_F" | head -20 | sed 's/^/    /' >&2
    echo "" >&2
    echo "    Это НЕ cp1251-порча: байты УТЕРЯНЫ, обратного преобразования нет," >&2
    echo "    и demojibake.py здесь не поможет. Верни текст из истории git —" >&2
    echo "    найди последнюю ревизию файла без символа-замены и возьми кусок" >&2
    echo "    оттуда. Реестр 221.1 №972." >&2
    FAIL=1
fi

# ─────────────────────────────────────────────────────────────────────────
# ИМЕНА НОСИТЕЛЕЙ И ЗНАМЕНАТЕЛЬ ОСМОТРА (2026-09-20).
#
# ЗАЧЕМ, если числа уже держатся. Счёт прячет ЗАМЕНУ: одну порчу вычистили,
# другая приехала слиянием — итог прежний, храповик молчит. У символа-замены
# это особенно наглядно: все 418 строк живут в ОДНОМ файле, и порча, заведённая
# в другом при уборке в этом, была бы невидима вовсе.
#
# И СУЖЕНИЕ ОБХОДА: счёт берётся обходом со списком расширений, списком
# пропусков и фильтром по индексу git. Сузь любой из трёх — число упадёт, и
# падение прочтётся как уборка. Отсюда ЗНАМЕНАТЕЛЬ: сколько файлов ядро реально
# прочитало. Он может только расти.
#
# КАК РАЗБИРАЕТСЯ ИСЧЕЗНОВЕНИЕ НОСИТЕЛЯ. Предмет — ЧИСЛО СТРОК, поэтому «файл
# ушёл из набора» тождественно «строк стало ноль», то есть неотличимо от уборки
# по построению (как у machine-paths и в отличие от стража проводки, где
# помогало существование файла). Различает их знаменатель, и только он.
#
# Ярус имён идёт, только когда база ПРИНАДЛЕЖИТ судимому дереву: поддельные
# деревья самотеста сверяются базой настоящей репы, и «осмотрено 3 из 6000»
# было бы свойством фикстуры, а не находкой.
# КОРЕНЬ ПРИВОДИТСЯ К АБСОЛЮТНОМУ ПУТИ ПЕРЕД СРАВНЕНИЕМ. Первая редакция
# сравнивала абсолютный путь базы с корнем КАК ПЕРЕДАН, и при вызове
# `check-no-mojibake.sh .` — то есть тем самым способом, каким его зовут руками
# и в гейте — ярус имён молча пропускался, а страж печатал зелёный. Проверка,
# не измерившая своего предмета, выглядит точно так же, как измерившая.
MJ_TIER_NAMES=1
MJ_ROOT_ABS="$(cd "$ROOT" 2>/dev/null && pwd)"
MJ_BASE_ABS="$(cd "$(dirname "$BASELINE")" 2>/dev/null && pwd)/$(basename "$BASELINE")"
case "$MJ_BASE_ABS" in
    "${MJ_ROOT_ABS:-$ROOT}"/*) ;;
    *) MJ_TIER_NAMES=0 ;;
esac

if [ "$MJ_TIER_NAMES" = "1" ]; then
    MJ_SCANNED=$(printf '%s\n' "$BOTH" | sed -n 's/^scanned://p' | tail -1)
    case "${MJ_SCANNED:-}" in ''|*[!0-9]*)
        echo "check-no-mojibake: FAIL — ядро не вернуло знаменатель scanned:" >&2
        exit 1;;
    esac
    MJ_WANT_SCANNED=$(sed -n 's/^scanned_files=\([0-9][0-9]*\)$/\1/p' "$BASELINE" | head -1)
    MJ_BASE_FILES=$(sed -n 's/^mojibake_file=//p' "$BASELINE")
    MJ_BASE_FFFD=$(sed -n 's/^fffd_file=//p' "$BASELINE")
    MJ_NAMED=$(printf '%s\n%s\n' "$MJ_BASE_FILES" "$MJ_BASE_FFFD" | grep -c . )

    # База, признающая НОЛЬ долга, законно не имеет ни имён, ни знаменателя:
    # пустой набор и есть ноль, а знаменатель охраняет счёт, которого нет.
    # Требование адресовано базе, которая долг ПРИЗНАЁТ числом.
    if [ $((BASE + BASE_F)) -gt 0 ] && { [ -z "$MJ_WANT_SCANNED" ] || [ "$MJ_NAMED" -eq 0 ]; }; then
        echo "check-no-mojibake: FAIL — база держит только счёт: нет строк scanned_files=, mojibake_file=, fffd_file=." >&2
        echo "    Счёт прячет замену носителя и сужение обхода (реестр 221.1 №637/№972)." >&2
        exit 1
    fi
    if [ "$MJ_SCANNED" -lt "$MJ_WANT_SCANNED" ]; then
        echo "check-no-mojibake: FAIL — ОСМОТРЕНО МЕНЬШЕ ФАЙЛОВ, ЧЕМ В БАЗЕ: $MJ_SCANNED < $MJ_WANT_SCANNED — обход сузился." >&2
        echo "    Долг, переставший считаться, читается как убранный. Это не он." >&2
        exit 1
    fi

    # Сравнение — один проход awk на обе подписи (цена яруса, план 275-Ф.1).
    mj_pairs() { printf '%s\n' "$1" | awk -F: 'NF>=2 { c[$1]++ } END { for (k in c) print k, c[k] }' | sort; }
    # Две подписи сравниваются ДВУМЯ вызовами одной функции, а не одним awk с
    # тремя режимами: первая редакция слепила оба потока в один и разделяла их
    # признаком «видел ли я этот ключ», что ломается на файле, несущем ОБЕ
    # подписи. Два процесса на ярус — цена, которую он платит охотно.
    mj_cmp() {  # $1 — строки базы «путь число», $2 — текущие пары, $3 — метка
        printf '%s\n%s\n%s\n' "$1" "@@@" "$2" | awk -v tag="$3" '
            $0 == "@@@" { cur = 1; next }
            !cur { if (NF == 2) { base[$1] = $2; seen[$1] = 1 } ; next }
            NF != 2 { next }
            {
                if (!($1 in seen)) print "NEW(" tag ") " $1 " " $2
                else if ($2 + 0 > base[$1] + 0) print "GROWN(" tag ") " $1 " " base[$1] " -> " $2
            }'
    }
    MJ_DIFF=$(printf '%s\n%s\n' \
        "$(mj_cmp "$MJ_BASE_FILES" "$(mj_pairs "$OUT")" sig)" \
        "$(mj_cmp "$MJ_BASE_FFFD" "$(mj_pairs "$OUT_F")" fffd)" | grep -v '^$' || true)
    if [ -n "$MJ_DIFF" ]; then
        echo "check-no-mojibake: FAIL — порча в НОВЫХ носителях или её стало больше в прежних:" >&2
        printf '%s\n' "$MJ_DIFF" | head -20 | sed 's/^/    /' >&2
        echo "    Общее число могло НЕ вырасти: убрали в одном файле, приехало в другом." >&2
        FAIL=1
    fi
fi

[ "$FAIL" -eq 0 ] || { echo "check-no-mojibake: FAIL" >&2; exit 1; }

if [ "$TOTAL" -lt "$BASE" ]; then
    echo "check-no-mojibake: долг СНИЗИЛСЯ ($TOTAL < базы $BASE) — опусти базу в $BASELINE"
fi
if [ "$TOTAL_F" -lt "$BASE_F" ]; then
    echo "check-no-mojibake: долг символа-замены СНИЗИЛСЯ ($TOTAL_F < базы $BASE_F) — опусти базу в $BASELINE"
fi
if [ "$MJ_TIER_NAMES" = "1" ]; then
    # Знаменатели печатаются ВСЕГДА: по ним видно, что ярус имён шёл, а не был
    # тихо пропущен. Вердикт без знаменателя не отличить от вердикта без работы.
    echo "check-no-mojibake ok: новой порчи текста нет ($TOTAL <= $BASE, замен $TOTAL_F <= $BASE_F); носителей в базе $MJ_NAMED, осмотрено файлов $MJ_SCANNED >= $MJ_WANT_SCANNED"
else
    echo "check-no-mojibake ok: новой порчи текста нет ($TOTAL <= $BASE, замен $TOTAL_F <= $BASE_F) (база не принадлежит судимому дереву: ярус имён не проверяется)"
fi
exit 0
