#!/usr/bin/env bash
# Страж: число кодов диагностик БЕЗ neg-фикстуры может только убывать.
#
# ЗАЧЕМ. Правило 5 (`check-test-fixture-coverage`) требует фикстуру на НОВЫЙ
# код и работает по диффу. Про НАКОПЛЕННОЕ оно не знает ничего — а накопилось
# много, пока его собственный образец был слеп ко второй форме записи кода
# (реестр №639: до 2026-08-13 искалось только `"E_FOO"`, тогда как канон —
# `"[E_FOO] сообщение"`).
#
# ЗАМЕР 2026-08-19, приёмка №639 пункт (1). Кодов, которые компилятор умеет
# выпускать, — 421: в форме литерала 79, в канонной 364, ТОЛЬКО в канонной
# 342. Названы хотя бы одной neg-фикстурой 211. БЕЗ ФИКСТУРЫ — 210, то есть
# ровно половина диагностик не проверяется ничем.
#
# ЧТО ЭТОТ СТРАЖ ЕСТЬ И ЧЕГО В НЁМ НЕТ. Он не требует написать 210 фикстур
# разом — это была бы работа ради числа. Он требует, чтобы число не РОСЛО:
# новая диагностика приезжает с фикстурой, старые разбираются волнами. База
# опускается вручную, каждое движение — со строкой летописи.
#
# Убывание — не отказ, а ЗАМЕТКА с просьбой опустить базу: закрытие дыры
# правильное действие, наказывать за него красным нельзя (довод №703).
#
# $1 — корень. Самотест — selftest/test-check-diag-fixture-coverage.sh
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u
export LC_ALL=C

NAME="check-diag-fixture-coverage"
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CORE="$(dirname "$0")/diag-fixture-coverage-scan.py"
# База ищется от КОРНЯ ПРОВЕРЯЕМОГО ДЕРЕВА, а не рядом со стражем: иначе на
# подставном дереве самотеста читалась бы НАСТОЯЩАЯ база, и самотест
# доказывал бы не то. Поймано собственным самотестом при первом же прогоне.
BASE_FILE="$ROOT/scripts/guards/diag-fixture-coverage.baseline"

[ -f "$CORE" ] || { echo "$NAME: FAIL — нет ядра $CORE" >&2; exit 1; }

OUT=$(python "$CORE" "$ROOT" 2>&1)
if [ $? -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    printf '%s\n' "$OUT" | tail -5 >&2
    exit 1
fi

MISS=$(printf '%s\n' "$OUT" | sed -n 's/^missing=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
DECL=$(printf '%s\n' "$OUT" | sed -n 's/^declared=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
case "$MISS" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число" >&2; exit 1;; esac
if [ "$MISS" -lt 0 ]; then
    echo "$NAME: FAIL — ядро не нашло исходники компилятора (переехали?)" >&2
    exit 1
fi

BASE=$(grep -E '^missing=' "$BASE_FILE" 2>/dev/null | head -1 | cut -d= -f2)
case "$BASE" in ''|*[!0-9]*)
    echo "$NAME: FAIL — база не задана или некорректна ($BASE_FILE)" >&2
    exit 1;;
esac

if [ "$MISS" -gt "$BASE" ]; then
    echo "$NAME: FAIL — кодов диагностик без neg-фикстуры стало больше: $MISS > $BASE" >&2
    printf '%s\n' "$OUT" | grep -v '^declared=\|^covered=\|^missing=' | head -15 >&2
    echo "    Новая диагностика обязана приезжать со своей neg-фикстурой:" >&2
    echo "    файл в spec_tests/** или std/** с маркером EXPECT_COMPILE_ERROR" >&2
    echo "    (или EXPECT_COMPILE_WARNING), называющим ЭТОТ ТОЧНЫЙ код." >&2
    echo "    Обе формы записи кода считаются одинаково: \"E_FOO\" и" >&2
    echo "    \"[E_FOO] текст\" — вторая канон, и до №639 её не видел никто." >&2
    exit 1
fi

if [ "$MISS" -lt "$BASE" ]; then
    echo "$NAME ok: без фикстуры $MISS из $DECL (база $BASE) — ЗАМЕТКА: база выше факта, опусти её с летописью в $BASE_FILE"
    exit 0
fi

echo "$NAME ok: кодов без neg-фикстуры не прибавилось ($MISS из $DECL, база $BASE)"
exit 0
