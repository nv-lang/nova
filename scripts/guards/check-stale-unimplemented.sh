#!/usr/bin/env bash
# scripts/guards/check-stale-unimplemented.sh
# Пометка «пока не реализован» в спеке обязана согласовываться со статусом
# плана, на который она ссылается.
#
# ДОМ И ОСНОВАНИЕ: план 231 «Выход из цикла точечных фиксов», трек Д (машинное
# принуждение норм); запись реестра 221.1 №557.
#
# ЗАЧЕМ. Расхождение спеки и реализации ловилось весь день 2026-08-10 в ОДНУ
# сторону — дока обещала то, чего нет (№553: `Random` без криптостойкого
# источника; №455: дока врёт именем EXPECT_*). Обратная сторона того же класса
# оказалась ничем не покрыта: `spec/syntax.md:33` и `syntax.en.md:42` больше
# месяца несли «⚠ пока не реализован» про блоб-литерал `x"…"`, хотя план 186,
# на который они же и ссылаются, стоит «✅ РЕАЛИЗОВАН 2026-07-09», и проба
# `x"0d0a0d0a"` честно даёт четыре байта. Читатель спеки в этом случае не
# получает сломанную программу — он просто НЕ ПОЛЬЗУЕТСЯ рабочей возможностью,
# и потому промах живёт годами: никто не жалуется.
#
# ЧТО ПРОВЕРЯЕТСЯ. Строка в `spec/**` вида «не реализован» / «not yet
# implemented», содержащая ссылку на `docs/plans/NNN-*.md`, краснеет, если у
# ЭТОГО плана статус говорит РЕАЛИЗОВАН / СДЕЛАНО / ЗАВЕРШЁН / ЗАКРЫТ.
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): пометку БЕЗ ссылки на план — судить о ней
# машине не по чему; и обратный случай (реализовано, но в спеке не описано
# вовсе) — отсутствие текста грепом не ловится в принципе. Здесь закрывается
# ровно то, что закрывается механически: пометка, которую опровергает наш же
# план.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-stale-unimplemented.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-stale-unimplemented.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
cd "$ROOT" || { echo "check-stale-unimplemented: нет каталога $ROOT" >&2; exit 1; }

[ -d spec ] || { echo "check-stale-unimplemented ok: каталога spec нет"; exit 0; }

VIOL=0
DONE_RE='РЕАЛИЗОВАН|СДЕЛАНО|ЗАВЕРШ|ЗАКРЫТ|✅'

# Ищем строку с пометкой; ссылка на план может стоять на ней ЛИБО на следующей
# (в спеке абзацы переносятся), поэтому берём окно из двух строк.
while IFS= read -r hit; do
    file="${hit%%:*}"
    rest="${hit#*:}"
    line="${rest%%:*}"
    win=$(sed -n "${line},$((line + 1))p" "$file" 2>/dev/null)
    plan=$(printf '%s' "$win" | grep -oE 'docs/plans/[0-9][0-9A-Za-z.]*-[a-z0-9-]*\.md' | head -1)
    [ -n "$plan" ] || continue
    [ -f "$plan" ] || { echo "check-stale-unimplemented: НАРУШЕНИЕ — $file:$line ссылается на несуществующий план $plan" >&2; VIOL=$((VIOL + 1)); continue; }
    st=$(grep -m1 '\*\*Статус' "$plan" || true)
    if printf '%s' "$st" | grep -qE "$DONE_RE"; then
        echo "check-stale-unimplemented: НАРУШЕНИЕ — $file:$line говорит «не реализован», а $plan говорит:" >&2
        printf '    %s\n' "$(printf '%s' "$st" | cut -c1-100)" >&2
        VIOL=$((VIOL + 1))
    fi
done < <(grep -rnE 'не реализован|not yet implemented|not implemented yet' spec --include='*.md' 2>/dev/null)

if [ "$VIOL" -gt 0 ]; then
    echo "" >&2
    echo "    Спека, объявляющая нереализованным то, что работает, — не мелочь:" >&2
    echo "    читатель просто НЕ ПОЛЬЗУЕТСЯ готовой возможностью и не жалуется," >&2
    echo "    поэтому промах живёт годами. Убери пометку либо поправь статус" >&2
    echo "    плана — расходиться им нельзя (реестр 221.1 №557)." >&2
    echo "check-stale-unimplemented: FAIL — нарушени(й) $VIOL" >&2
    exit 1
fi

echo "check-stale-unimplemented ok: пометки «не реализован» не противоречат статусам планов"
exit 0
