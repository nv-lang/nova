#!/bin/sh
# scripts/guards/check-novac-deps.sh — таблица рёбер novac: единственный источник.
# План: docs/plans/274-novac-self-hosted-compiler.md §10.2; вход — docs/plans/274.1-novac-architecture.md §2а.
#
# ПРАВИЛО (274 §10.2, архитектура §3): граница между модулями существует, только
# если она — строка таблицы рёбер. Импорт вне таблицы — красный. Источник ОДИН:
# сама таблица §3 в docs/dev/novac-architecture.md (markdown), второй копии в
# машинном файле НЕТ намеренно — иначе они разойдутся (класс К4).
#
# Что проверяет: каждый import в novac/src/<mod>/*.nv (и main.nv) разрешён
# строкой «| `<mod>` | ... |» таблицы §3 (колонка «в» перечисляет разрешённые
# цели). Модуль вне карты — красный. Импорты std.* — вне юрисдикции (язык).
# Что НЕ проверяет: направление данных «что течёт» (семантика — ревью) и
# внутримодульные двери.
#
# $1 — корень репо; $2 — override дерева novac (самотест); $3 — override
# файла архитектуры (самотест).
# Проверялся: Windows (Git Bash), 2026-08-14.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
ARCH="${3:-$ROOT/docs/dev/novac-architecture.md}"

if [ ! -f "$ARCH" ]; then
    echo "check-novac-deps: FAIL — нет $ARCH" >&2; exit 1
fi
if [ ! -d "$SRC" ]; then
    echo "check-novac-deps ok: судить нечего (novac/src ещё нет)"; exit 0
fi

# Разрешённые рёбра из таблицы §3: строки «| `из` | `в1`, `в2` | ...»
EDGES=$(awk -F'|' '
    /^## 3\./ { t=1; next } t && /^## / { t=0 }
    t && $2 ~ /`/ {
        from=$2; gsub(/[` ]/, "", from)
        to=$3; gsub(/`/, "", to)
        if (from == "из" || from == "---") next
        n=split(to, a, ",")
        for (i=1; i<=n; i++) { gsub(/ /, "", a[i]); if (a[i] != "" ) print from ":" a[i] }
    }' "$ARCH")

if [ -z "$EDGES" ]; then
    echo "check-novac-deps: FAIL — таблица §3 не распарсилась из $ARCH" >&2; exit 1
fi

# ОДИН проход awk по всем файлам разом (2026-08-19). Прежняя редакция звала
# `sed` на каждый файл и `grep` на каждый импорт: двести процессов и 21
# секунда стены на 32 файлах. Правила те же, слово в слово; форм ввоза
# четыре (import/use, с `export` и без), отступ любой -- и то и другое
# найдено адверсарными пробами и потому проверяется явно.
SCAN=$(find "$SRC" -name '*.nv' 2>/dev/null | sort | xargs awk -v SRC="$SRC" -v EDGES="$EDGES" '
    BEGIN {
        n = split(EDGES, e, /\n/)
        for (i = 1; i <= n; i++) if (e[i] != "") { edge[e[i]] = 1
            split(e[i], p, ":"); known[p[1]] = 1; known[p[2]] = 1 }
    }
    FNR == 1 {
        rel = FILENAME; sub("^" SRC "/", "", rel)
        mod = rel
        if (index(rel, "/") > 0) sub(/\/.*$/, "", mod); else mod = "main"
        if (!(mod in known) && mod != "main") {
            printf "  %s: модуль \047%s\047 отсутствует в карте §3\n", rel, mod
            skip[FILENAME] = 1
        }
    }
    skip[FILENAME] { next }
    {
        line = $0; sub(/\r$/, "", line)
        if (line !~ /^[[:space:]]*(export[[:space:]]+)?(import|use)[[:space:]]/) next
        imp = line
        sub(/^[[:space:]]*(export[[:space:]]+)?(import|use)[[:space:]]+/, "", imp)
        sub(/[[:space:]].*$/, "", imp)
        # ТОЛЬКО относительные пути -- ввоз из `std` не модуль novac и ребром
        # §3 не является; прежний sed печатал именно и только `./`/`../`.
        if (imp !~ /^[.][.]?[/]/) next
        sub(/^[.][.]?[/]/, "", imp)
        # Резать по первому из пробела, точки или `{` -- как второй sed.
        sub(/[ .{].*$/, "", imp)
        if (imp == "") next
        total++
        if (!((mod ":" imp) in edge))
            printf "  %s: импорт \047%s\047 — ребра \047%s -> %s\047 нет в таблице §3\n", rel, imp, mod, imp
    }
    END { printf "@@%d\n", total }
')
N=$(printf '%s\n' "$SCAN" | sed -n 's/^@@//p' | tail -n 1)
BAD=$(printf '%s\n' "$SCAN" | grep -v '^@@' || true)

if [ -n "$BAD" ]; then
    echo "check-novac-deps: FAIL — импорты вне таблицы рёбер (архитектура §3):" >&2
    printf '%b\n' "$BAD" >&2
    echo "  Ребро добавляется ТОЛЬКО строкой таблицы §3 с контрактом «что течёт»." >&2
    exit 1
fi
# --- Ацикличность: правило было, механизма не было ---------------------------
# План §10.3 запрещает циклы, а §3/К4 утверждал, что ацикличность «следует из
# таблицы». Проба 2026-08-17 это опровергла: цикл добавляется строкой таблицы
# ровно так же, как честное ребро, и всё остаётся зелёным. Следствие из
# документа — не механизм. Здесь алгоритм Кана: если после снятия всех
# истоков остаются рёбра, в графе цикл, и он назван поимённо.
CYC=$(printf '%s\n' "$EDGES" | awk -F: '
    { from[NR]=$1; to[NR]=$2; n=NR }
    END {
        # Обрезаем с ОБЕИХ сторон: ребро, чей конец никуда дальше не ведёт,
        # в цикле не участвует; ребро, в чьё начало ничто не входит, — тоже.
        # Иначе в отчёт попадает весь путь, ведущий к циклу (main -> pipeline
        # вместо diag -> emit_c), и сообщение указывает не туда.
        changed=1
        while (changed) {
            changed=0
            for (i=1; i<=n; i++) {
                if (dead[i]) continue
                out=0; inn=0
                for (j=1; j<=n; j++) {
                    if (dead[j]) continue
                    if (from[j]==to[i]) out=1
                    if (to[j]==from[i]) inn=1
                }
                if (!out || !inn) { dead[i]=1; changed=1 }
            }
        }
        for (i=1; i<=n; i++) if (!dead[i]) printf "%s -> %s\n", from[i], to[i]
    }')
if [ -n "$CYC" ]; then
    echo "check-novac-deps: FAIL — в графе модулей ЦИКЛ (план §10.3):" >&2
    printf '%s\n' "$CYC" | sed 's/^/  /' >&2
    echo "  Направление зависимостей — единственное архитектурное правило" >&2
    echo "  окна: слой не смотрит вверх. Цикл снимается разрывом ребра, а не" >&2
    echo "  строкой в таблице." >&2
    exit 1
fi


E=$(printf '%s\n' "$EDGES" | wc -l)
echo "check-novac-deps ok: рёбер в карте $E, импортов проверено $N, вне таблицы 0"
exit 0
