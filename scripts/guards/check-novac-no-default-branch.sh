#!/bin/sh
# scripts/guards/check-novac-no-default-branch.sh — на закрытом множестве
# ветки «всё остальное» нет (конвенция П21; требование владельца 2026-08-16).
#
# КЛАСС. Живой случай в `emit_type_decls`: `if kind == TkRecord { … } else {
# emit_sum_decl(…) }`. `else` здесь значит «всё, что не запись, — сумма»:
# появится четвёртый вид типа — он молча уедет в эмиссию суммы, и это тот же
# №652 («тихий дефолт»), только на диспетчере. Исчерпывающий `match` вместо
# цепочки даёт на этом месте ошибку компиляции, то есть заставляет решить.
#
# ПРОВЕРЯЕТ по novac/src/**/*.nv (тесты исключены):
#   * арм-заглушка `_ =>` в `match` по ЗАКРЫТОМУ множеству — запрещена: она
#     проглатывает будущие варианты. ОТКРЫТОЕ множество — исключение, и оно
#     машинное: если сосед-арм разбирает ЛИТЕРАЛ (символьный, строковый,
#     числовой), домен не перечислим и `_` обязателен, а не ленив (живой
#     случай 2026-08-16: `json_escape` разбирает `char`, и std пишет ту же
#     форму в encoding/json.nv). Закрытость домена судит соседний страж
#     `check-novac-match-exhaustive`, которому литеральные армы не ложатся
#     ни в одну сумму. (Подстановочник ВНУТРИ образца — `Leaf(_)`,
#     `Branch { .. }` — законен: это payload, а не ветка «всё остальное».)
#   * `else`, закрывающий разбор ПО ВИДУ (условие `<...kind...> == Тип.Вариант`;
#     заглядывание `peek()` — вопрос да/нет, не диспетчер, и не судится),
#     обязан быть честным отказом: `ice(`, `@refuse(`, `report` в первых
#     теле (первые 12 значащих строк); для парсера отказ — это `NodeKind.Err` (он даёт
#     диагностику той же ветвью). Иначе — красный: такой `else` делает правдоподобную
#     работу за неизвестный вариант.
# НЕ ПРОВЕРЯЕТ: `else` при обычном булевом условии (их большинство и они
#   законны); полноту самого `match` (это работа компилятора); цепочки, где
#   вариант проверяется через хелпер, а не сравнением (появятся — правило
#   уточняется вместе с ними).
#
# $1 — корень репозитория; $2 — override сканируемой директории (самотест).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-no-default-branch

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

NF=$(find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | wc -l | tr -d '[:space:]')
if [ "$NF" -eq 0 ]; then
    echo "$NAME ok: судить нечего (в $SRC файлов .nv: 0)"
    exit 0
fi

BAD=$(find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | sort | while IFS= read -r f; do
    rel=${f#"$SRC"/}
    tr -d '\r' < "$f" | awk -v rel="$rel" '
        {
            raw = $0
            line = raw
            sub(/\/\/.*$/, "", line)
            # 1) арм-заглушка `_ =>` — только на ЗАКРЫТОМ множестве. Домен
            # ОТКРЫТ, если сосед-арм разбирает литерал (символьный, строковый,
            # числовой): перечислить его нельзя, и `_` там обязателен.
            if (line ~ /=>/ && line ~ /^[[:space:]]*[\047\"0-9-]/) lit_seen = 1
            if (line ~ /^[[:space:]]*match /) lit_seen = 0
            # `_ => None` — НЕ проглатывание: тип функции (Option) уже объявил
            # отображение ЧАСТИЧНЫМ, и «этого варианта тут нет» — законный ответ,
            # а не догадка. Диспетчер, обязанный РЕШИТЬ за каждый вариант, — другое,
            # и он остаётся исчерпывающим (владелец 2026-08-17).
            # Законны ровно две формы остатка (П21 п.3-4): `None` — частичность,
            # объявленная типом; отказ (`ice`/`@refuse`) — честная смерть или
            # диагностика. Всё прочее в `_ =>` это догадка за неизвестный вариант.
            if (line ~ /^[[:space:]]*_[[:space:]]*=>[[:space:]]*None[[:space:]]*$/) ok_default = 1
            else if (line ~ /^[[:space:]]*_[[:space:]]*=>/ && (line ~ /ice\(/ || line ~ /@refuse\(/)) ok_default = 1
            else ok_default = 0
            if (ok_default) lit_seen = lit_seen
            else if (line ~ /^[[:space:]]*_[[:space:]]*=>/ && !lit_seen) {
                printf "  %s:%d: арм-заглушка `_ =>` проглотит будущий вариант\n", rel, NR
            }
            # 1а) Пустое значение ХВОСТОМ функции — тот же тихий дефолт: если
            # ветка всё-таки достижима, наружу уйдёт пустой идентификатор и
            # сломанный C, без единого слова. Законно только как успокоитель
            # известного бага оракула — тогда рядом стоит [LEGACY-#NNN].
            # Живой случай (владелец, 2026-08-16): `c_method` возвращал "" за
            # исчерпывающим match — мёртвый код без маркера и без причины.
            if (line ~ /^[[:space:]]*(return[[:space:]]+)?""[[:space:]]*$/ && prev_bare_close) {
                if (!marked) {
                    printf "  %s:%d: пустое значение хвостом без маркера [LEGACY-#NNN]\n", rel, NR
                }
            }
            if (raw ~ /\[LEGACY-#/) marked = 1
            else if (raw !~ /^[[:space:]]*\/\// && raw !~ /^[[:space:]]*$/ && line !~ /^[[:space:]]*(return[[:space:]]+)?""[[:space:]]*$/) marked = 0
            if (raw !~ /^[[:space:]]*\/\// && raw !~ /^[[:space:]]*$/) prev_bare_close = (line ~ /^[[:space:]]*\}[[:space:]]*$/) ? 1 : 0
            # 2) запомнить ПОСЛЕДНЕЕ условие на КАЖДОМ отступе: `else`
            # принадлежит той цепочке, на чьём отступе он стоит. Без этого
            # `else` обычного булева условия приписывался далёкому варианту
            # (поймано на живом дереве 2026-08-16).
            if (line ~ /^[[:space:]]*(\} else )?if[[:space:]]/) {
                ind = line
                sub(/[^[:space:]].*$/, "", ind)
                L = length(ind)
                c = line
                sub(/^[[:space:]]+/, "", c)
                cond_at[L] = c
                line_at[L] = NR
                # Судим ДИСПЕТЧЕР ПО ВИДУ («какой это вариант»): слева `kind`.
                # Заглядывание вперёд (`peek()` — «что дальше?») это вопрос
                # да/нет, у него `else` значит «не эта форма», и разбор идёт
                # другим путём — не ветка «всё остальное» (разбор 2026-08-16).
                #
                # ИЗВЕСТНАЯ ДЫРА (2026-08-16, честно): диспетчер по ID ТИПА
                # (`at == prims.str_id`) этим стражем НЕ судится. На нём жил
                # живой дефект — println с неизвестным типом молча печатался
                # как int; сам дефект починен (emit_c: теперь ice), но попытка
                # расширить страж не доказала ловлю на подложке, а страж без
                # доказательства запрещён (П16). Дыра записана в 274.3/F66.
                isvar_at[L] = (line ~ /==[[:space:]]*[A-Z][A-Za-z0-9_]*\.[A-Z]/ && line ~ /kind/ && line !~ /peek\(/) ? 1 : 0
            }
            # 3) else, закрывающий цепочку СВОЕГО отступа
            if (line ~ /}[[:space:]]*else[[:space:]]*\{/) {
                eind = line
                sub(/[^[:space:]].*$/, "", eind)
                L = length(eind)
                if (isvar_at[L] == 1 && NR - line_at[L] <= 60) {
                    pending = NR; look = 12; cond = cond_at[L]
                }
                next
            }
            if (pending > 0 && look > 0) {
                if (line ~ /ice\(|@refuse\(|report|NodeKind\.Err/) { pending = 0 }
                # комментарии не тратят окно: у отказа бывает длинное объяснение
                if (raw !~ /^[[:space:]]*\/\//) look--
                if (look == 0 && pending > 0) {
                    printf "  %s:%d: `else` за проверкой варианта (`%s`) делает работу, а не отказ\n", rel, pending, substr(cond, 1, 44)
                    pending = 0
                }
            }
        }
        END {
            if (pending > 0) {
                printf "  %s:%d: `else` за разбором по виду (`%s`) делает работу, а не отказ\n", rel, pending, substr(cond, 1, 44)
            }
        }
    '
done)

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — ветка «всё остальное» на закрытом множестве (конвенция П21):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Диспетчер по сумме — исчерпывающий 'match' с именованной веткой на вариант." >&2
    echo "  Тогда новый вариант даёт ошибку компиляции ровно здесь, а не тихо уезжает" >&2
    echo "  в чужую ветку. Если ветка «остальное» нужна — она обязана быть отказом:" >&2
    echo "  'ice(…)' для сломанного инварианта, '@refuse(…)' для формы вне подмножества." >&2
    exit 1
fi

MATCHES=$(grep -rc "match " "$SRC" --include='*.nv' 2>/dev/null | awk -F: '{s+=$2} END {print s+0}')
echo "$NAME ok: файлов .nv: $NF, match-выражений: $MATCHES, веток «всё остальное»: 0"
exit 0
