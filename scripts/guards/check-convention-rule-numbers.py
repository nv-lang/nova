# -*- coding: utf-8 -*-
"""scripts/guards/check-convention-rule-numbers.py — номер правила конвенции
принадлежит ОДНОМУ правилу (заведён 2026-09-07).

Дом правила: `docs/dev/gate-guard-conventions.md` — там нумерованные Г-правила,
на которые ссылаются планы, стражи, фикстуры и окна между собой.
Дом работы: `docs/plans/275-gate-cost.md` (план 275 — применение конвенции
к `scripts/gate.sh` и стражам дерева); адрес назначен интегратором 2026-09-07.

ЗАМЕР, РАДИ КОТОРОГО ЗАВЕДЁН. 2026-09-07 в этом файле оказалось СЕМНАДЦАТЬ
заголовков на шестнадцать номеров: `## Г14` стоял дважды — строка 160 («прогон,
который мог взять кэш, замером не считается») и строка 311 («замер действителен
только в той среде, где механизм будет жить»). Прожили так две недели. За один
вечер три сессии сослались на номера правил, и ссылка «Г14» означала РАЗНОЕ в
зависимости от того, кто читал: снаружи под ней понимали правило про кэш
(`docs/dev/prompts/integrator-handoff.md`, фикстура `a4_value_sum_pos.nv`), а
`scripts/guards/gate-budget.baseline` — правило про среду.

ПОЧЕМУ ЭТО КЛАСС, А НЕ ОПЕЧАТКА. Дубль номера не виден ни одному читателю:
каждый видит СВОЁ правило и считает ссылку разрешённой. Автор второго Г14 знал,
что номер занят, и написал об этом прямо в тексте — то есть даже честно
названный дубль не был замечен две недели, потому что номера правил не сверял
никто. Ровно тот класс, что «вердикт не с того дерева»: расхождение выглядит
нормой, потому что обе стороны по отдельности правдоподобны.

ЧТО СУДИТСЯ. Внутри одного документа номер правила встречается ровно один раз.
Правило = заголовок markdown вида `## <ПРЕФИКС><ЧИСЛО>. <название>`, где
ПРЕФИКС — одна заглавная кириллическая буква (сегодня это `Г`; форма пригодна и
для будущих семей, если такие заведут).

ЧЕГО СТРАЖ НЕ ЛОВИТ, И ЭТО НАЗВАНО НАРОЧНО:
  * ссылку на НЕСУЩЕСТВУЮЩЕЕ правило (сегодня нашлись три: `ГТ1`, `ГТ10`,
    `ГТ14` — семьи `ГТ` в дереве нет вовсе). Машинно это требует способа
    отличить живую ссылку от ИСТОРИЧЕСКОЙ цитаты («до 2026-09-07 здесь стояло
    ГТ14»), а такого способа у нас пока нет — молчаливый запрет цитировать
    историю хуже незакрытой половины класса;
  * диапазоны в прозе («правила Г1–Г14»), которые устаревают молча. Они сняты
    правкой того же дня и заменены формой «Г-правила», но страж на них дал бы
    ложные срабатывания на тех же исторических цитатах.
Обе половины закрываются одним механизмом — способом пометить цитату, — и это
отдельная работа, а не хвост этой.

НЕПУСТОТА ПРОВЕРЯЕТСЯ ЯВНО. Если шаблон заголовка перестанет совпадать (файл
переименован, форма заголовка изменилась), страж найдёт НОЛЬ правил и вернёт
ОТКАЗ, а не зелень: проверка, которой нечего судить, обязана краснеть — иначе
она годами сообщает «всё хорошо» о том, чего не читала.

ИСПОЛЬЗОВАНИЕ:
    python scripts/guards/check-convention-rule-numbers.py [КОРЕНЬ]
"""
import io
import os
import re
import sys

# Вердикт уходит с LF даже на Windows: гейт разбирает эти строки, а
# `check-guard-honesty` отвергает стража, чей вердикт приезжает CRLF.
sys.stdout.reconfigure(encoding="utf-8", errors="replace", newline="\n")
sys.stderr.reconfigure(encoding="utf-8", errors="replace", newline="\n")

NAME = "check-convention-rule-numbers"

# `## Г14. Название` — заголовок правила. Префикс: одна заглавная кириллическая
# буква, дальше число и ТОЧКА (точка отсекает «Г15-амендмент» и прочую прозу).
RULE = re.compile(u"^#{2,4}[ \t]+([А-Я])(\\d+)\\.[ \t]")

# Документ считается конвенцией с нумерованными правилами, если таких
# заголовков в нём хотя бы столько. Три — чтобы случайная пара заголовков в
# обычной странице не превращала её в «конвенцию».
MIN_RULES = 3


def scan(path):
    """Заголовки правил файла: [(префикс, номер, строка)]."""
    try:
        text = io.open(path, encoding="utf-8", errors="replace", newline="").read()
    except OSError:
        return []
    out = []
    for lineno, line in enumerate(text.replace("\r\n", "\n").split("\n"), 1):
        m = RULE.match(line)
        if m:
            out.append((m.group(1), int(m.group(2)), lineno))
    return out


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    docs = os.path.join(root, "docs", "dev")

    files_checked = 0
    rules_seen = 0
    violations = []

    for base, dirs, files in os.walk(docs):
        for fname in sorted(files):
            if not fname.endswith(".md"):
                continue
            path = os.path.join(base, fname)
            found = scan(path)
            if len(found) < MIN_RULES:
                continue
            files_checked += 1
            rules_seen += len(found)
            seen = {}
            for prefix, num, lineno in found:
                seen.setdefault((prefix, num), []).append(lineno)
            rel = os.path.relpath(path, root).replace("\\", "/")
            for (prefix, num), lines in sorted(seen.items(), key=lambda kv: kv[0][1]):
                if len(lines) > 1:
                    violations.append(
                        u"%s: номер %s%d занят %d раз — строки %s"
                        % (rel, prefix, num, len(lines),
                           u", ".join(str(n) for n in lines)))

    if files_checked == 0:
        sys.stderr.write(
            u"%s: FAIL — не найдено НИ ОДНОГО документа с нумерованными правилами "
            u"под %s.\n" % (NAME, os.path.relpath(docs, root).replace("\\", "/")))
        sys.stderr.write(
            u"  Это отказ, а не зелень: проверка, которой нечего судить, молчит "
            u"так же, как исправная. Изменилась форма заголовка правила или "
            u"переехал каталог — почини шаблон, а не выводы.\n")
        return 1

    if violations:
        sys.stderr.write(u"%s: FAIL — один номер на два правила:\n" % NAME)
        for v in violations:
            sys.stderr.write(u"    %s\n" % v)
        sys.stderr.write(
            u"  Ссылка на такой номер означает РАЗНОЕ в зависимости от того, кто "
            u"читал, и ни один читатель этого не видит: каждому виден свой "
            u"заголовок.\n"
            u"  Чинится так: номер остаётся у того правила, на которое БОЛЬШЕ "
            u"ссылок в дереве (греп по номеру), второе получает свободный, и "
            u"ссылки на него переезжают ТОЙ ЖЕ правкой.\n")
        return 1

    print(u"%s ok: документов с нумерованными правилами %d, правил %d, "
          u"дублей номеров 0" % (NAME, files_checked, rules_seen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
