#!/bin/sh
# scripts/guards/check-novac-pch.sh — предкомпилированная прелюдия (PCH) в
# горячем пути novac НЕ ИСЧЕЗАЕТ молча (план 274.2 §2, «заголовки рантайма
# 0.43 с на файл → 0.22 с»; указание владельца 2026-08-17: «добавь это в
# целевую схему сборки + страж»).
#
# ЗАЧЕМ. `nova_rt.h` тянет gc.h и libuv — 82 тыс. строк после препроцессора,
# и БЕЗ PCH это половина времени компиляции каждого файла. Смоук строит PCH
# один раз на ревизию оракула и переиспользует; так тёплый прогон стал 1.7 с
# вместо 40. Механизм держался НИ НА ЧЁМ: убери `-include-pch` — и увидит это
# только `check-novac-iteration-cost` по бюджету времени, а у него
# восьмикратный запас, то есть скорее всего не увидит вовсе (владелец указал
# на дыру 2026-08-17). Цена, добытая заменой, обязана быть под замком.
#
# ПРОВЕРЯЕТ в scripts/tools/novac-e1-smoke.sh (горячий путь novac):
#   * есть построение PCH: `-x c-header` с выходом в `*.pch`;
#   * есть ИСПОЛЬЗОВАНИЕ: `-include-pch`;
#   * PCH КЭШИРУЕТСЯ по ревизии оракула (в имени файла — штамп), а не
#     строится каждый прогон: строка сборки стоит под проверкой «файла нет».
# НЕ ПРОВЕРЯЕТ: что PCH реально ускоряет (это замер, а не грамматика);
#   `nova build` оракула — там PCH НЕТ (замер 2026-08-17: один вызов clang,
#   `-O0 -g`, ноль упоминаний pch), и это не наша земля: записано в 274.2
#   как эскалация интегратору.
#
# $1 — корень репозитория; $2 — override пути к смоуку (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SMOKE="${2:-$ROOT/scripts/tools/novac-e1-smoke.sh}"
NAME=check-novac-pch

if [ ! -f "$SMOKE" ]; then
    echo "$NAME: FAIL — нет $SMOKE: горячий путь novac потерян, судить нечего, а молчать нельзя (класс №519)" >&2
    exit 1
fi

BAD=""
grep -q -- '-x c-header' "$SMOKE" || BAD="$BAD
  нет построения PCH (-x c-header ... -o *.pch)"
grep -q -- '-include-pch' "$SMOKE" || BAD="$BAD
  PCH не ИСПОЛЬЗУЕТСЯ (-include-pch пропал): каждый прогон снова разбирает 82 тыс. строк заголовков"
grep -qE '\.pch"?$|\.pch"' "$SMOKE" || BAD="$BAD
  нет файла *.pch — кэшировать нечего"
grep -qE 'PCH=.*\$[A-Z_]*STAMP|prelude-\$' "$SMOKE" || BAD="$BAD
  имя PCH не несёт штамп ревизии оракула: кэш протухнет молча и даст мусорный объектник"
grep -qE 'if \[ ! -f "\$PCH" \]|\[ -f "\$PCH" \] \|\|' "$SMOKE" || BAD="$BAD
  PCH строится безусловно (нет проверки «файла нет»): цена возвращается на каждый прогон"

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — предкомпилированная прелюдия исчезла из горячего пути (274.2 §2):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Верни PCH: собрать один раз на ревизию оракула (-x c-header -> *.pch с штампом)," >&2
    echo "  дальше -include-pch. Без него компиляция каждого файла снова платит 82 тыс. строк" >&2
    echo "  заголовков рантайма, и цена цикла (П14) уезжает в разы." >&2
    exit 1
fi

echo "$NAME ok: PCH в горячем пути — строится по штампу оракула, кэшируется, применяется через -include-pch"
exit 0
