#!/bin/sh
# scripts/guards/check-novac-pch.sh -- предкомпилированная прелюдия (PCH)
# обязательна ВО ВСЕХ режимах компиляции (конвенция П28; указание владельца
# 2026-08-17: «PCH обязателен во всех режимах, в конвенцию + страж»).
#
# ЗАЧЕМ. `nova_rt.h` тянет gc.h и libuv -- 82 тыс. строк после препроцессора.
# Без PCH их разбирает КАЖДЫЙ вызов компилятора C: 0.43 с на файл против
# 0.22 с (план 274.2 §2). Смоук это уже платил один раз на ревизию оракула и
# стал 1.7 с вместо 40 с. Но правило держалось на одном файле и на памяти
# автора: убери `-include-pch` -- и увидит это только страж цены цикла по
# бюджету времени, у которого восьмикратный запас. Цена, добытая заменой,
# обязана быть под замком, и не в одном месте, а в ПРАВИЛЕ.
#
# ПРОВЕРЯЕТ по scripts/tools/novac-*.sh и scripts/guards/check-novac-*.sh:
#   * КАЖДЫЙ вызов компилятора C, который КОМПИЛИРУЕТ (несёт `-c`),
#     несёт `-include-pch`;
#   * хотя бы один вызов СТРОИТ PCH (`-x c-header` -> `*.pch`), и его имя
#     несёт штамп ревизии оракула (иначе кэш протухнет молча и даст мусорный
#     объектник), и он не пересобирается при наличии файла.
#   Исключены: сборка самого PCH и ЛИНКОВКА (она ничего не разбирает).
# НЕ ПРОВЕРЯЕТ: `nova build` оракула -- там PCH НЕТ (замер 2026-08-17: один
#   вызов clang, `-O0 -g`, ноль упоминаний pch). Это не наша земля: требование
#   записано в 274.2 §1а как целевая схема и передано интегратору; страж
#   держит нашу половину, чтобы правило было живым, а не декларацией.
#
# $1 -- корень репозитория; $2 -- override сканируемой директории (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SMOKE="${2:-$ROOT/scripts/tools/novac-e1-smoke.sh}"
NAME=check-novac-pch

SRC="${2:-$ROOT/scripts}"

FILES=$(find "$SRC" -type f -name 'novac-*.sh' -o -type f -name 'check-novac-*.sh' 2>/dev/null | sort)
if [ -z "$FILES" ]; then
    echo "$NAME: FAIL — в $SRC нет ни одного инструмента novac: страж потерял мишень (класс №519)" >&2
    exit 1
fi

T="${TMPDIR:-/tmp}/novac-pch.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

BAD=""
NCOMP=0
NPCH=0
for f in $FILES; do
    rel=$(basename "$f")
    # строки, где зовут компилятор C
    while IFS= read -r line; do
        [ -n "$line" ] || continue
        n=${line%%:*}
        body=${line#*:}
        case "$body" in
            *"-x c-header"*) NPCH=$((NPCH+1)); continue ;;   # это СБОРКА pch
        esac
        # КОМПИЛЯЦИЯ — это `-c`. Линковка тоже упоминает .o, но ничего не
        # разбирает, поэтому PCH ей не нужен (страж принял её за компиляцию
        # с первого захода — признак уточнён).
        case "$body" in
            *" -c "*) ;;
            *) continue ;;
        esac
        NCOMP=$((NCOMP+1))
        case "$body" in
            *-include-pch*) ;;
            *) BAD="$BAD
  $rel:$n — компиляция C без -include-pch: каждый вызов снова разбирает 82 тыс. строк заголовков" ;;
        esac
    done <<EOF
$(grep -n 'REAL_CLANG\|\$CL "\|clang\.exe' "$f" 2>/dev/null | grep -v '^[0-9]*: *#')
EOF
done

if [ "$NCOMP" -eq 0 ]; then
    echo "$NAME: FAIL — не найдено ни одной компиляции C: разбор сломался, а молчать нельзя (класс №519)" >&2
    exit 1
fi
if [ "$NPCH" -eq 0 ]; then
    BAD="$BAD
  ни один инструмент не СТРОИТ PCH (-x c-header -> *.pch): кэшировать нечего"
fi

SMOKE="$ROOT/scripts/tools/novac-e1-smoke.sh"
if [ -f "$SMOKE" ]; then
    grep -qE 'PCH=.*\$[A-Z_]*STAMP|prelude-\$' "$SMOKE" || BAD="$BAD
  имя PCH не несёт штамп ревизии оракула: протухший кэш даст мусорный объектник"
    grep -qE 'if \[ ! -f "\$PCH" \]|\[ -f "\$PCH" \] \|\|' "$SMOKE" || BAD="$BAD
  PCH строится безусловно (нет проверки «файла нет»): цена возвращается на каждый прогон"
fi

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — компиляция C без предкомпилированной прелюдии (П28):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Правило: PCH во ВСЕХ режимах. Собрать один раз на ревизию оракула" >&2
    echo "  (-x c-header -> *.pch со штампом), дальше каждая компиляция несёт" >&2
    echo "  -include-pch. Линковка и сборка самого PCH исключены." >&2
    exit 1
fi

echo "$NAME ok: компиляций C: $NCOMP, все с -include-pch; сборок PCH: $NPCH (по штампу оракула, кэшируется)"
exit 0
