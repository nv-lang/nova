#!/usr/bin/env bash
# scripts/guards/check-expect-cc-error-ratchet.sh — реестр 221.1 №966.
#
# ЗАЧЕМ. Фикстура с маркером `EXPECT_CC_ERROR` объявляет: «эту ошибку поймает
# СИШНЫЙ компилятор». Амендмент D405 от 2026-09-04, п. 4, говорит об этом
# дословно: «одна дверь сверки операндов для всех числовых операторов; чекер,
# не Си (`EXPECT_CC_ERROR` для этих случаев — НЕ ПРИЁМКА)». Такая фикстура
# зелена, но приёмкой не является по трём причинам, и все три измерены:
#
#   1. пользователь получает координату в СГЕНЕРИРОВАННОМ `main.c`, а не в
#      своём файле (замер №959: три формы из шести ловил Си);
#   2. привязка держится на подстроке ЧУЖОГО диагностического сообщения и
#      рвётся при смене версии компилятора Си;
#   3. маркер БЕЗ подстроки принимает ЛЮБОЙ отказ Си — в том числе по
#      совершенно другой причине. Такая фикстура зеленеет и когда дефект
#      вернулся, и когда сломалось соседнее; она не слабая, она не
#      утверждает НИЧЕГО. На день заведения таких две из восьми.
#
# ПОЧЕМУ ХРАПОВИК, А НЕ НОЛЬ. Перевод каждой фикстуры на диагностику чекера —
# это фикс компилятора, а не правка маркера: пока чекер не ловит форму, менять
# маркер значит красить корпус. Обнулить одним движением нельзя. Храповик
# запрещает РОСТ: новая фикстура, отдающая приёмку сишному компилятору, красит
# гейт немедленно; старые уходят по одной, вместе с волнами, которые эти формы
# и так трогают (274.7 берёт перечень как критерии приёмки своих волн).
#
# ЧЕГО ЭТОТ СТРАЖ НЕ ЛОВИТ, сказано честно: он считает ФОРМУ, а не смысл. Он
# не знает, ДОЛЖЕН ли чекер ловить конкретную форму, и не отличает фикстуру,
# ждущую отказа линковщика, от ждущей отказа типизации Си. Это суждение, и оно
# принадлежит тому, кто чинит.
#
# ПОЧЕМУ ЭТО НЕ ДУБЛЬ СОСЕДА (правило одного дома). Рядом живёт
# `check-novac-legacy-workarounds.py`, и его ось B тоже смотрит на
# `EXPECT_CC_ERROR`. Предметы РАЗНЫЕ и деревья не пересекаются: сосед сканирует
# ТОЛЬКО `novac/**` и требует, чтобы файл-носитель обхода бага оракула нёс
# маркер `[LEGACY-#N-…]` с живой строкой реестра. Здесь — `spec_tests/**`, и
# утверждение другое: приёмка САМОГО ОРАКУЛА не отдаётся Си и их число не
# растёт. Ни один из двух не покрывает дерево другого — проверено чтением
# области соседа (`src = root / "novac"`, строка 87).
#
# ПРАВИЛО СЧЁТА, И ОНО ЗДЕСЬ НЕ ФОРМАЛЬНОСТЬ. Считаются файлы, у которых
# СТРОКА НАЧИНАЕТСЯ маркером (`^// EXPECT_CC_ERROR`), а не файлы, где эта
# подстрока встречается. Наивный греп по имени даёт на два больше: у двух
# фикстур, давно переведённых на диагностику чекера, старое имя маркера живёт
# в ПРОЗЕ комментария как запись об истории. Это тот же класс, что
# `reference-guards-read-prose-as-data`: процитированный маркер — не маркер.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-expect-cc-error-ratchet.sh [КОРЕНЬ]
# ПЕРЕМЕННЫЕ:
#   NOVA_CCERROR_BASELINE — путь к базе, по умолчанию
#                           scripts/guards/expect-cc-error.baseline
# Самотест: scripts/guards/selftest/test-check-expect-cc-error-ratchet.sh

set -u
export LC_ALL=C

NAME=check-expect-cc-error-ratchet
ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
BASELINE="${NOVA_CCERROR_BASELINE:-$ROOT/scripts/guards/expect-cc-error.baseline}"
SCAN="$ROOT/spec_tests"

if [ ! -d "$SCAN" ]; then
    echo "$NAME ok: судить нечего (нет $SCAN)"
    exit 0
fi

# Файл считается носителем, если ХОТЬ ОДНА его строка НАЧИНАЕТСЯ с маркера.
LIST=$(grep -rlE '^// EXPECT_CC_ERROR' "$SCAN" --include='*.nv' 2>/dev/null | sed "s@^$ROOT/@@" | sort)
N=$(printf '%s' "$LIST" | grep -c . || true)

BASE=0
if [ -f "$BASELINE" ]; then
    BASE=$(sed -n 's/^cc_error_fixtures=\([0-9][0-9]*\).*/\1/p' "$BASELINE" | head -1)
    BASE=${BASE:-0}
else
    echo "$NAME: базы нет ($BASELINE) — считаю базой 0" >&2
fi

echo "$NAME: фикстур, отдающих приёмку сишному компилятору, $N (база $BASE)"

if [ "${N:-0}" -gt "$BASE" ]; then
    echo "$NAME: FAIL — ВЫРОСЛО: $N > базы $BASE" >&2
    printf '%s\n' "$LIST" | sed 's/^/    /' >&2
    echo "    D405 (амендмент 2026-09-04, п. 4): «чекер, не Си»." >&2
    echo "    Новая фикстура не должна просить сишный компилятор быть нашим" >&2
    echo "    чекером: если форму ловит Nova — маркер EXPECT_COMPILE_ERROR с" >&2
    echo "    её кодом; если не ловит — это дефект, и ему нужна строка реестра," >&2
    echo "    а не зелёная фикстура. Реестр 221.1 №966." >&2
    exit 1
fi

if [ "${N:-0}" -lt "$BASE" ]; then
    echo "$NAME: долг СНИЗИЛСЯ ($N < базы $BASE) — опусти базу в $BASELINE строкой-летописью"
fi

echo "$NAME ok: роста нет ($N <= $BASE)"
exit 0
