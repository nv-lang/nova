#!/bin/sh
# scripts/guards/check-novac-one-door-export.sh — одна дверь на класс задачи:
# одна и та же операция не экспортируется из ДВУХ модулей novac.
#
# ПРАВИЛО. План 274.1 §2в п.2 (docs/plans/274.1-novac-architecture.md,
# «Как это проверяет страж», пункт 2): «операция одного класса задачи,
# экспортированная из двух модулей, — красный (две двери)». Сводный аудит
# правил — план 274 §10.3а (docs/plans/274-novac-self-hosted-compiler.md):
# строка «одна дверь класса задачи ВНУТРИ модуля» прямо называет этот скрипт
# «экспорт-страж §2в» и закрепляет за ним МЕЖмодульные вторые двери
# (внутримодульные оставлены NO-HIT-ревью приёмки). Сам принцип — 274 §4 п.18
# и 274.1 §2б: «один класс задачи — одна дверь».
#
# ЗАЧЕМ. Принцип «одни двери одного класса задач» — центральный в архитектуре
# novac, и до этого файла он держался только прозой: check-novac-deps.sh в
# своей шапке прямо отказывается его судить («что НЕ проверяет: направление
# данных "что течёт" ... и внутримодульные двери»). А вторая дверь никогда не
# заводится решением вслух — она заводится тем, что автор второго модуля не
# нашёл первую и написал своё collect(). Именно так нынешний компилятор получил
# infer_call_ret_c мимо чекера: весь план 196 — снятие одной второй двери, и
# это стоило месяцев. Машина умеет ровно ту половину, которая формализуема:
# одно ИМЯ — из одного модуля. Совпадение имён не доказывает дублирование само
# по себе, но это дешёвый и точный сигнал: два модуля назвали операцию
# одинаково, значит считают её одной и той же.
#
# ПРОВЕРЯЕТ: все экспортируемые имена в $SRC/**/*.nv. Модуль — папка, которая
#   файл СОДЕРЖИТ (правило проекта: папка = один модуль из co-equal файлов,
#   значит вложенная папка — свой модуль); файлы прямо в корне дерева — общий
#   псевдомодуль main. Каждое имя приписано к своему пространству:
#     export fn имя(                            — свободная функция -> имя
#     export fn Тип @имя( / Тип mut @имя( / Тип имя(  — метод       -> Тип@имя
#     export fn []Тип @имя(                     — метод среза       -> []Тип@имя
#     export fn Тип.имя(                        — статический метод -> Тип.имя
#     export type Имя                           — тип               -> Имя
#   `export unsafe fn` — та же дверь под модификатором и судится наравне
#   (в std такая форма живая: `export unsafe fn []u8 @to_str_unchecked`).
#   Один ключ, экспортированный из ДВУХ РАЗНЫХ модулей, — красный, с обоими
#   местами (файл:строка). Дженерик-параметры (Deque[T], в т.ч. с ограничениями
#   вида [T Compare + Hash]) и модификаторы получателя (mut, consume) в ключ не
#   входят: они не различают дверь. А вот `[]` входит: []u8 — СВОЙ тип, не u8,
#   и `[]u8 @to_str` рядом с `u8 @to_str` — две разные двери, не одна.
#   Отдельно ассертит, что разобран хоть один экспорт — тихо опустевший разбор
#   сделал бы стража вечнозелёным (класс №519).
# НЕ ПРОВЕРЯЕТ: вторые двери ВНУТРИ одного модуля (файлы одной папки co-equal
#   и составляют один модуль; это NO-HIT-ревью приёмки, 274 §10.3а);
#   одинаковые по смыслу двери под РАЗНЫМИ именами (collect vs gather —
#   семантика, машине не видна); export const (константа — не операция);
#   тесты *_test.nv (они не двери, а потребители); что именно течёт по рёбрам
#   и разрешено ли ребро (это check-novac-deps.sh). ЯВНО ВНЕ СУДА, чтобы дыра
#   была названной, а не молчаливой: `export extern "abi" fn ...` (объявление
#   ЧУЖОЙ двери, у него своя грамматика с ABI-строкой; в novac/src таких нет) и
#   `export import ...` (реэкспорт — это та же дверь, показанная из другого
#   места, а не вторая). Появятся в novac — расширять здесь, а не молчать.
#
# $1 — корень репозитория (по умолчанию вычисляется от расположения файла).
# $2 — override сканируемой директории (шов самотеста; по умолчанию novac/src).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SRC="${2:-$ROOT/novac/src}"
SRC="${SRC%/}"
NAME=check-novac-one-door-export

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

T="${TMPDIR:-/tmp}/novac-one-door.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0
TAB=$(printf '\t')

# --- источники: тесты дверьми не являются ----------------------------------
# NUL-разделитель, а не перевод строки: путь дерева приходит аргументом $2 и
# вполне может содержать пробел (TMPDIR самотеста на Windows — запросто).
find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' -print0 > "$T/files0"
if [ ! -s "$T/files0" ]; then
    echo "$NAME ok: судить нечего (нет .nv в $SRC)"
    exit 0
fi

# --- разбор экспортов: вид<TAB>ключ<TAB>модуль<TAB>файл:строка --------------
# Ключ квалифицирован пространством: у методов разных типов пространства
# разные, поэтому A @len и B @len НЕ сталкиваются, а A @len из двух модулей —
# сталкиваются (это и есть две двери одной операции).
xargs -0 awk -v SRC="$SRC" '
    function strip_generics(s,   prev) {
        prev = ""
        while (s != prev) { prev = s; sub(/\[[^][]*\]/, "", s) }
        return s
    }
    function first_ident(s) {
        if (match(s, /[A-Za-z_][A-Za-z0-9_]*/)) return substr(s, RSTART, RLENGTH)
        return ""
    }
    FNR == 1 {
        rel = substr(FILENAME, length(SRC) + 2)
        if (index(rel, "/") == 0) { mod = "main" }
        else { mod = rel; sub(/\/[^\/]*$/, "", mod) }
    }
    # `unsafe` — модификатор двери, а не другая дверь: приводим к общей форме,
    # иначе `export unsafe fn raw_copy(` из двух модулей проходит МОЛЧА.
    { sub(/\r$/, ""); sub(/^export unsafe fn /, "export fn ") }

    /^export type / {
        nm = first_ident(strip_generics(substr($0, 13)))
        if (nm != "") print "тип\t" nm "\t" mod "\t" rel ":" FNR
        next
    }

    /^export fn / {
        h = substr($0, 11)
        p = index(h, "(")
        if (p == 0) next
        head = substr(h, 1, p - 1)
        gsub(/^[ \t]+/, "", head)
        # Приёмник-срез: []u8 — СВОЙ тип, а не u8, и его метод — своя дверь.
        # Маркер снимается ДО вычистки дженериков, потому что она видит в `[]`
        # пустую группу и съедает её: без этих двух строк `[]u8 @to_str` и
        # `u8 @to_str` из разных модулей дают один ключ и ложный красный.
        sl = ""
        while (sub(/^\[\][ \t]*/, "", head)) sl = sl "[]"
        head = strip_generics(head)
        gsub(/^[ \t]+/, "", head); gsub(/[ \t]+$/, "", head)
        if (head == "") next
        if (head ~ /[ \t]/) {
            # Тип @имя, Тип mut @имя, Тип имя — метод; модификаторы получателя
            # отбрасываются, дверь различает пара Тип+имя.
            n = split(head, tk, /[ \t]+/)
            ty = first_ident(tk[1])
            mn = tk[n]; sub(/^@/, "", mn); mn = first_ident(mn)
            if (ty == "" || mn == "") next
            print "метод\t" sl ty "@" mn "\t" mod "\t" rel ":" FNR
        } else if (index(head, ".") > 0) {
            # Тип.имя — статический метод/конструктор, тоже под своим типом.
            split(head, dt, ".")
            ty = first_ident(dt[1]); mn = first_ident(dt[2])
            if (ty == "" || mn == "") next
            print "статический метод\t" sl ty "." mn "\t" mod "\t" rel ":" FNR
        } else {
            nm = first_ident(head)
            if (nm != "") print "свободная функция\t" sl nm "\t" mod "\t" rel ":" FNR
        }
        next
    }
' < "$T/files0" > "$T/raw"

if [ ! -s "$T/raw" ]; then
    echo "$NAME: FAIL — в $SRC есть .nv, но ни одного экспорта не разобрано: страж потерял мишень (класс №519)" >&2
    echo "  Либо форма экспорта в языке изменилась, либо путь не тот. Молчать нельзя: вечнозелёный страж хуже отсутствующего." >&2
    exit 1
fi

# Повтор одного ключа ВНУТРИ модуля второй дверью не является (файлы одной
# папки co-equal), поэтому на модуль оставляем одну запись — первую по файлу.
sort "$T/raw" | awk -F'\t' '!seen[$1 FS $2 FS $3]++' > "$T/doors"

# Ключи, встреченные более чем в одном модуле.
cut -f1,2 "$T/doors" | uniq -d > "$T/dups"

NKEYS=$(cut -f1,2 "$T/doors" | sort -u | wc -l | tr -d '[:space:]')
NMODS=$(cut -f3 "$T/doors" | sort -u | wc -l | tr -d '[:space:]')
NDUP=$(wc -l < "$T/dups" | tr -d '[:space:]')

if [ "$NDUP" -ne 0 ]; then
    {
        echo "$NAME: FAIL — две двери в один класс задачи (план 274.1 §2в п.2): одно имя экспортировано из разных модулей"
        while IFS="$TAB" read -r kind key; do
            [ -n "$key" ] || continue
            echo "  $kind $key — экспортировано из разных модулей:"
            awk -F'\t' -v k1="$kind" -v k2="$key" '$1 == k1 && $2 == k2 { print "      модуль " $3 " -> " $4 }' "$T/doors"
        done < "$T/dups"
        echo "  Как чинить: оставь ОДНУ дверь — модуль-производитель, — а второй модуль пусть"
        echo "  ИМПОРТИРУЕТ её и ЧИТАЕТ результат, а не перевычисляет (274.1 §2в: каждый класс"
        echo "  информации имеет одну дверь-производителя, потребители ЧИТАЮТ, а не перевычисляют)."
        echo "  Если операции РАЗНЫЕ — разведи имена так, чтобы разница читалась в имени, а не в"
        echo "  комментарии: одинаковое имя в двух модулях зовущий читает как одну операцию."
        echo "  Ребро, по которому пойдёт импорт, обязано быть строкой таблицы §3 архитектуры"
        echo "  (check-novac-deps.sh): двери сводятся вместе с картой, а не вместо неё."
    } >&2
    exit 1
fi

echo "$NAME ok: экспортированных дверей: $NKEYS в $NMODS модулях, вторых дверей: 0"
exit 0
