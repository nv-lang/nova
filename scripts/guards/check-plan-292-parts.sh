#!/usr/bin/env bash
# Страж: таблица частей плана 292 сверяется С ДЕРЕВОМ.
#
# ЗАЧЕМ. План 292 обязан читаться как самодостаточный рецепт — просьба владельца
# 2026-09-19: «сделай его самодостаточным, чтобы можно было применить на др
# проекте». Перечень частей и есть суть такого рецепта, и он же первым протухает:
# в тот же день, когда перечень писался, в нём уже стояли числа строк, неверные
# через сутки, а трёх частей не было вовсе.
#
# ЧТО ОН СУДИТ, И ЧЕГО НЕ СУДИТ — граница названа нарочно, чтобы зелёный вердикт
# не читался шире, чем он есть:
#   * судит: каждый путь, названный в таблице, СУЩЕСТВУЕТ в дереве. Это ловит
#     переименование и удаление — тот класс, из-за которого таблица врёт молча;
#   * НЕ судит: полноту с другой стороны («всякая часть механизма названа»).
#     Для этого нужен второй список того, что считается частью, — то есть второй
#     дом правды, который разойдётся с первым. Полнота остаётся глазной и здесь
#     НАЗВАНА глазной, а не выдана за машинную.
#
# Запуск: bash scripts/guards/check-plan-292-parts.sh <корень>
set -u
ROOT="${1:-.}"
PLAN="$ROOT/docs/plans/292-stop-requires-proof.md"
NAME="check-plan-292-parts"

if [ ! -f "$PLAN" ]; then
  echo "$NAME FAIL: нет файла плана: $PLAN"
  exit 1
fi

# Пути берутся из СТРОК ТАБЛИЦЫ (начинаются с `| \``), а не отовсюду: в прозе
# плана пути упоминаются как примеры и как СНЯТЫЕ файлы (`guard-stop.py`), и
# требовать их существования значило бы краснеть на верно описанной истории.
# Слэш-команды (`/stop`, `/status`) тоже стоят в таблицах и тоже содержат косую
# черту — они НЕ пути в дереве, и требовать от них файла значит краснеть на
# верной записи. Отсекаются по ведущей косой: путь в репозитории относительный.
PATHS=$(grep -o '^| `[^`]*`' "$PLAN" | sed 's/^| `//; s/`$//' \
        | grep '/' | grep -v '^/' | sort -u)

if [ -z "$PATHS" ]; then
  # Пустая мишень — не «нарушений ноль». Таблицу могли переписать другой формой,
  # и страж зеленел бы, ничего не проверяя.
  echo "$NAME FAIL: в плане не найдено ни одной строки таблицы с путём —"
  echo "  либо таблица переписана другой формой, либо раздел частей исчез."
  exit 1
fi

missing=0
total=0
while IFS= read -r p; do
  [ -z "$p" ] && continue
  total=$((total + 1))
  # Часть может быть парой «файл + файл» — такие строки таблица пишет через ` + `,
  # и sed выше берёт первый; второй проверяется своей строкой, если он есть.
  if [ ! -e "$ROOT/$p" ]; then
    echo "$NAME: НЕТ В ДЕРЕВЕ: $p"
    missing=$((missing + 1))
  fi
done <<EOF
$PATHS
EOF

echo "$NAME: путей в таблице $total, отсутствует $missing"
if [ "$missing" -gt 0 ]; then
  echo "$NAME FAIL: план называет части, которых нет. Либо файл переименован —"
  echo "  поправь таблицу ТОЙ ЖЕ правкой, — либо часть снята, и тогда скажи в"
  echo "  плане, ЧЕМ она заменена: перенос без этой строки повторит нашу дыру."
  exit 1
fi
echo "$NAME ok: каждая названная часть есть в дереве (полнота перечня — глазная)"
exit 0
