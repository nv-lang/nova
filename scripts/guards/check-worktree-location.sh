#!/usr/bin/env bash
# scripts/guards/check-worktree-location.sh
# Рабочие деревья (`git worktree`) живут ТОЛЬКО В ПАПКЕ `worktrees/` РЯДОМ С
# РЕПОЗИТОРИЕМ — `<родитель главной рабочей копии>/worktrees/<имя>`, — и
# никогда внутри репозитория. В родителе остаются только основные репозитории.
#
# ПАПКА ВЫВОДИТСЯ, А НЕ ПИШЕТСЯ (2026-08-23, по слову владельца: путь к его
# машине не место светить в публичном репозитории). Дозволенная папка — это
# `worktrees` в родительском каталоге ГЛАВНОЙ рабочей копии (первая запись
# `git worktree list`), то есть на любой машине она своя и правильная сама
# собой. Явный override — `NOVA_WORKTREE_DIR` (полный путь к папке). Это ровно
# принцип соседнего стража `check-no-machine-paths`: расположение выводится от
# репозитория.
#
# ОДНА ПАПКА ВМЕСТО РОДИТЕЛЯ (задача владельца 2026-10-05): прежде дозволялся
# весь родитель главной копии, и деревья лежали вперемешку с основными
# репозиториями nv-lang (`nova-carina`, `nova-ci-red2` рядом с `nova-http`).
# Теперь у них своя папка — её же называет настройка `worktrees` плагина
# crew-harness (`.opencode/crew-harness.json`), и плагин кладёт туда
# деревья задач. Прежний override `NOVA_WORKTREE_ROOT` страж БОЛЬШЕ НЕ ЧИТАЕТ:
# ярлык владельца выставляет его в каталог выше nv-lang, и при старом смысле
# («корень, под которым всё дозволено») страж пропускал любое дерево на диске.
#
# ГЛАВНАЯ РАБОЧАЯ КОПИЯ правилу не подлежит: она и есть репозиторий в
# родителе. Судятся только ДОПОЛНИТЕЛЬНЫЕ деревья.
#
# ДОМ И ОСНОВАНИЕ: план 231 «Выход из цикла точечных фиксов», трек Д (машинное
# принуждение норм); запись реестра 221.1 №561; правило владельца 2026-08-10.
#
# ЗАЧЕМ — две измеренные причины, не порядок ради порядка:
#
#   1. ДИСК. Рабочее дерево Nova весит десятки мегабайт, а сборка — гигабайты.
#      Диск `C:` у нас регулярно уходит под ноль: 2026-08-10 он был занят на
#      100 % (82 МБ свободно), clang падал с `no space on device`, и это
#      выглядело как ТРИДЦАТЬ провалов тестов — полчаса ушло на поиск
#      несуществующего дефекта компилятора.
#   2. СТРАЖИ. Worktree, лежащий ВНУТРИ репозитория, попадает под все грепы:
#      2026-08-10 `check-checker-entrypoints` покраснел на шести файлах из
#      `.claude/worktrees/**` — чужих снимков на коммитах, где нужной функции
#      ещё не существовало. Страж судил наш код по чужому прошлому.
#
# ЧТО ПРОВЕРЯЕТСЯ: каждый путь из `git worktree list`, кроме главной копии,
# лежит в дозволенной папке (сравнение регистронезависимое и по обеим формам
# разделителя — Windows отдаёт `D:/…`, MSYS видит `/d/…`).
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): worktree, заведённый и удалённый между
# прогонами гейта. Страж смотрит текущее состояние, а не историю.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-worktree-location.sh [КОРЕНЬ]
# ПЕРЕМЕННЫЕ:
#   NOVA_WORKTREE_DIR — папка, в которой дозволены деревья
#                       (по умолчанию — `worktrees` в родителе главной копии)
# Самотест — scripts/guards/selftest/test-check-worktree-location.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

cd "$ROOT" || { echo "check-worktree-location: нет каталога $ROOT" >&2; exit 1; }
git rev-parse --git-dir >/dev/null 2>&1 || { echo "check-worktree-location ok: не git-репозиторий"; exit 0; }

# Главная копия — всегда первая запись `git worktree list --porcelain`, и путь
# она печатает в той же форме, в какой печатает остальные, — значит
# сравнивать будем одинаковое.
MAIN=$(git worktree list --porcelain 2>/dev/null | sed -n 's|^worktree ||p' | head -1)
. "$(dirname "${BASH_SOURCE[0]}")/lib/family.sh"
ALLOWED=$(nova_worktree_dir "$ROOT")

# Приводим к одному виду: нижний регистр, прямые слэши, форма `/d/...` -> `d:/...`
norm() {
    printf '%s' "$1" \
        | tr 'A-Z' 'a-z' \
        | sed 's|\\|/|g' \
        | sed -E 's|^/([a-z])/|\1:/|'
}

ALLOWED_N=$(norm "$ALLOWED")
MAIN_N=$(norm "$MAIN")

# У РАННЕРА CI СУДИТЬ НЕЧЕГО — и это выходит само, без особого случая.
#
# Обе причины выше — про машину автора: `C:` уходящий под ноль и worktree
# внутри репозитория, попадающий под грепы стражей. У раннера CI один чекаут и
# ноль дополнительных деревьев. Найдено 2026-08-23, когда CI впервые запустил
# `scripts/gate.sh`: единственным красным яруса `loop` на Linux был этот страж,
# доложивший о чекауте раннера как о дереве «вне дозволенного корня».
#
# До 2026-10-05 это лечилось проверкой «дозволенного корня на машине нет —
# правило не про неё». Теперь главная копия из правила исключена, и у раннера
# судить попросту нечего; а проверка существования папки была бы дырой: снёс
# пустую `worktrees/` — и деревья в родителе снова проходят молча.

BAD=""
N=0

while IFS= read -r line; do
    case "$line" in
        worktree\ *) ;;
        *) continue ;;
    esac
    p="${line#worktree }"
    [ -n "$p" ] || continue
    N=$((N + 1))
    pn=$(norm "$p")
    [ "$pn" = "$MAIN_N" ] && continue
    case "$pn" in
        "$ALLOWED_N"/*) ;;
        *) BAD="$BAD
    $p" ;;
    esac
done < <(git worktree list --porcelain 2>/dev/null)

echo "check-worktree-location: рабочих деревьев $N (с главной копией), дозволенная папка $ALLOWED"

if [ -n "$BAD" ]; then
    echo "check-worktree-location: НАРУШЕНИЕ — деревья вне дозволенной папки:$BAD" >&2
    echo "" >&2
    echo "    Перенеси: git worktree move <путь> $ALLOWED/<имя>" >&2
    echo "    (дерево с поднятыми сабмодулями move не берёт: mv + git worktree repair)" >&2
    echo "    либо сними: git worktree remove <путь>." >&2
    echo "    Причина не в порядке: диск C: уходит под ноль и ломает сборку" >&2
    echo "    чужой ошибкой, а дерево ВНУТРИ репозитория попадает под грепы" >&2
    echo "    стражей и краснит их на чужих снимках (реестр 221.1 №561)." >&2
    echo "check-worktree-location: FAIL" >&2
    exit 1
fi

# ЧИСЛО ДЕРЕВЬЕВ — ПОД ХРАПОВИК (2026-08-11, реестр 221.1 №595).
#
# Владелец: «где держишь? память не работает». Держал в голове — то есть нигде.
# Шестьдесят с лишним деревьев на один `.git` это не порядок ради порядка:
# каждое стоит места на диске (диск C: у нас регулярно уходит под ноль), они
# делят один индекс и один stash, а брошенное дерево держит ветку, из-за чего
# та вечно числится несведённой (поймано в тот же день: слитые ветки групп L и
# M выглядели несведёнными, пока их деревья стояли).
#
# База опускается ровно так же, как у прочих храповиков: снял деревья — впиши
# новое число. Расти нельзя.
WT_BASE_FILE="${NOVA_WORKTREE_BASELINE:-$(dirname "$0")/worktree-count.baseline}"
if [ -f "$WT_BASE_FILE" ]; then
    WT_BASE=$(sed -n 's/^worktrees=\([0-9][0-9]*\).*/\1/p' "$WT_BASE_FILE" | head -1)
    WT_BASE=${WT_BASE:-0}
    if [ "$N" -gt "$WT_BASE" ]; then
        echo "check-worktree-location: деревьев $N > базы $WT_BASE — храповик только вниз" >&2
        echo "    Сними отработавшие: git worktree remove <путь>, затем" >&2
        echo "    git branch -D <ветка> — иначе ветка вечно числится несведённой." >&2
        echo "check-worktree-location: FAIL" >&2
        exit 1
    fi
    [ "$N" -lt "$WT_BASE" ] && echo "check-worktree-location: деревьев стало меньше ($N < $WT_BASE) — опусти базу в $WT_BASE_FILE"
fi

echo "check-worktree-location ok: все рабочие деревья в $ALLOWED"
exit 0
