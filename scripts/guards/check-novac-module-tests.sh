#!/bin/sh
# scripts/guards/check-novac-module-tests.sh — модульные тесты novac идут в
# ГЕЙТЕ, а не только в CI.
#
# ПОЧЕМУ ЭТОТ СТРАЖ ПОЯВИЛСЯ (2026-08-18, живой случай). Тесты
# `novac/src/*/*_test.nv` гонял только workflow nova-gate.yml. Гейт их не звал —
# и волна, менявшая контракт лексера и правило экранирования, оставила ДВА
# красных теста, которых локальный прогон не показал ни разу: их нашли руками,
# случайно, уже после зелёного гейта. Это ровно тот класс, против которого весь
# план: проверка существует, но ничего не держит. Зелёный гейт обязан значить
# «можно пушить», иначе он учит себе не верить.
#
# ПРАВИЛО: каждый `novac/src/*/*_test.nv` проходит. Ноль провалов — зелёный;
# хоть один — красный с именами упавших тестов.
#
# ПРОВЕРЯЕТ: ОДИН пачечный вызов `nova test` на все файлы разом (конвенция
# П26: инструмент на много файлов зовёт компилятор один раз — 9 секунд на все
# восемь против минуты по одному). Ассертится СТРОКА ИТОГА `PASS: n  FAIL: m`,
# а не код возврата: ноль без строки — это «не упал», а не «проверил»
# (реестр №645), и именно так гейт-фильтры уже врали раньше.
#
# НЕ ПРОВЕРЯЕТ: что тесты ПОКРЫВАЮТ модуль (это дело ревью и
# check-novac-selftest-proves-red.sh для самих стражей); что тестов достаточно;
# поведение novac на корпусе (check-novac-differential.sh).
#
# $1 — корень репозитория (default: вычислить от себя);
# $2 — override пути к бинарю оракула (шов самотеста).

set -u

NAME="check-novac-module-tests"
ROOT="${1:-$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)}"
. "$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/lib/novac.sh"
ORACLE="${2:-$(novac_find_oracle "$ROOT" || true)}"
SRC="$ROOT/novac/src"

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

# shellcheck disable=SC2086
set -- $(find "$SRC" -type f -name '*_test.nv' | sort)
if [ "$#" -eq 0 ]; then
    echo "$NAME: FAIL — ни одного *_test.nv в novac/src" >&2
    echo "  Тесты живут РЯДОМ с модулем (конвенция проекта); их отсутствие" >&2
    echo "  означает, что модули novac не проверяются вовсе." >&2
    exit 1
fi
N="$#"

if [ ! -f "$ORACLE" ]; then
    echo "$NAME: FAIL — оракула нет ($ORACLE), а тесты есть: судить нечем" >&2
    echo "  Собрать: cargo build --release -p nova-cli" >&2
    exit 1
fi

# `--timeout 300`: ЭТОТ страж судит КОНТРАКТ модуля, а не часы.
#
# ЗАМЕР 2026-09-08. Ярус отказал `PASS: 15  FAIL: 11`; та же команда на
# свободной машине четырьмя минутами позже — `PASS: 26  FAIL: 0`. Разница —
# соседний гейт, запущенный параллельно. Без явного предела тест умирает по
# умолчанию и попадает в FAIL НЕОТЛИЧИМО от упавшего ассерта: слова TIMEOUT в
# логе яруса не было ни разу, и одиннадцать «сломанных модулей» выглядели
# регрессом контракта.
#
# Время судит БЮДЖЕТ ЯРУСА — отдельный механизм с калибровкой (реестр №997).
# Смешивать два суда в одном числе значит получать ложные отказы там, где
# сломалась не работа, а расписание.
#
# ЧЕГО ЭТО НЕ ЧИНИТ (окно 274, тем же днём): предел даёт РАЗЛИЧИМОСТЬ, но не
# полную — тест, убитый чужой стеной, и тест, честно вставший, дадут одно
# слово. Полное лекарство — ОТДЕЛЬНЫЙ СЧЁТЧИК раннера: «PASS 15 FAIL 0
# TIMEOUT 11» читается верно, «FAIL 11» врёт молча. Это правка раннера, не
# стража, и она заведена строкой в план 275.
# ПРЕДЕЛ 600, А НЕ 300: ЭТОТ ШАГ ИДЁТ В ОДНОЙ ПАРАЛЛЕЛЬНОЙ ПАЧКЕ С ФАЗЗЕРОМ.
#
# ЗАМЕР 2026-09-08 на СВОБОДНОЙ машине (сосед отдал, прогон чистый):
#   `handed_sum_test` в ярусе — TIMEOUT, killed after 327444ms при пределе 300с;
#   тот же тест ОДИН, `nova test --timeout 500` — PASS за 70 секунд.
#
# Причина не в тесте и не в соседе: `gate-novac.sh:481-486` кладёт этот страж в
# ту же пачку `par_add`, что фаззер (4566 мутаций) и мэнглинг. Ярус нагружает
# САМ СЕБЯ, и любой per-test предел внутри такой пачки мерит ПАЧКУ, а не тест —
# тот же класс, что №997: вердикт зависит от того, что рядом, а не от предмета.
#
# 600 остаётся ловушкой для ЗАВИСАНИЯ (бесконечный цикл упрётся и в него), но
# перестаёт убивать работу, которая просто делит машину с фаззером. Настоящее
# лекарство — вынести шаг из пачки либо считать предел от калибровки; и то и
# другое дороже одной цифры и живёт строкой №1038.
OUT="$("$ORACLE" test --timeout 600 "$@" 2>&1)"
SUMMARY=$(printf '%s\n' "$OUT" | sed 's/\x1b\[[0-9;]*m//g' | grep -E '^PASS: [0-9]+  FAIL: [0-9]+' | tail -n 1)

if [ -z "$SUMMARY" ]; then
    echo "$NAME: FAIL — прогон не напечатал строку итога" >&2
    printf '%s\n' "$OUT" | tail -n 15 >&2
    echo "  Ноль без строки — это «не упал», а не «проверил» (реестр №645)." >&2
    exit 1
fi

FAILED=$(printf '%s\n' "$SUMMARY" | sed -E 's/.*FAIL: ([0-9]+).*/\1/')
PASSED=$(printf '%s\n' "$SUMMARY" | sed -E 's/^PASS: ([0-9]+).*/\1/')

if [ "$FAILED" != "0" ]; then
    echo "$NAME: FAIL — модульных тестов упало: $FAILED (из $N файлов)" >&2
    # ТАЙМАУТ ВИДЕН ОТДЕЛЬНО ОТ АССЕРТА (правка 2026-09-08): в логе яруса
    # совпала ТОЛЬКО строка итога, и отличить контракт от часов было нечем.
    printf '%s\n' "$OUT" | sed 's/\x1b\[[0-9;]*m//g' \
        | grep -E 'RUN-FAIL|TIMEOUT|timed out|FAIL:' | head -n 12 >&2
    if printf '%s\n' "$OUT" | grep -qiE 'timeout|timed out'; then
        echo '  СРЕДИ ПРОВАЛОВ ЕСТЬ ТАЙМАУТЫ — это ЧАСЫ, а не контракт.' >&2
        echo '  Перезапусти на НЕЗАНЯТОЙ машине прежде, чем искать регресс:' >&2
        echo '  соседняя сборка удваивает время и делает провал неотличимым.' >&2
    fi
    echo "  Тест держит КОНТРАКТ модуля. Если контракт сменился сознательно —" >&2
    echo "  тест едет за ним в том же слиянии, с причиной в комментарии; если" >&2
    echo "  нет — сломан модуль, а не тест." >&2
    exit 1
fi

echo "$NAME ok: модульных тестов novac: файлов $N, PASS $PASSED, FAIL 0 (один пачечный вызов)"
exit 0
