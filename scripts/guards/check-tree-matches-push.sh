#!/usr/bin/env bash
# scripts/guards/check-tree-matches-push.sh
# Отправляешь НЕ ТО, что проверял: незакоммиченная работа в рабочем дереве.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №635, план 231 трек Д (машинное принуждение
# норм). Родня — №565 (`check-clean-checkout-build.sh`): та же трещина между
# «что я проверил» и «что увидит посторонний», только с другой стороны.
#
# ЗАЧЕМ — случай 2026-08-13, дословно. Гейт 17 был ЗЕЛЁНЫМ целиком: мега-CU
# 781/0, `nova test std/src` 75/0, линт 0/0. Я отправил 92 коммита и доложил
# зелёный вердикт. А в рабочем дереве осталось НЕЗАКОММИЧЕННЫМ: правка чекера
# №631 (возврат точного `E7301`), весь страж №629 (`check-branch-absorption-
# method.sh`, его самотест и `scripts/tools/branch-absorbed.sh`), фикс линта в
# `n602`. При этом `gate.sh` уже был закоммичен СО ШАГОМ, зовущим тот страж, —
# то есть `main` звал файл, которого в репозитории нет.
#
# Гейт судит РАБОЧЕЕ ДЕРЕВО, CI судит КОММИТ. Пока они совпадают, разницы не
# видно; как только расходятся, зелёный вердикт становится ложью — и ловит его
# уже посторонний. Поймал именно CI: `nova-gate` и `nova-lint` покраснели ровно
# на этом.
#
# ПОЧЕМУ НЕ В САМОМ ГЕЙТЕ. Гейт гоняют и посреди работы, когда дерево грязное
# по построению — там это норма, а не нарушение. Ложь начинается в момент
# ОТПРАВКИ: с этой секунды «я проверил» относится к тому, чего в отправляемом
# нет. Поэтому проверка живёт в pre-push.
#
# ЧТО ПРОВЕРЯЕТСЯ. Изменения ОТСЛЕЖИВАЕМЫХ файлов (изменён/удалён/в индексе, но
# не закоммичен). Неотслеживаемый мусор НЕ считается: черновики и логи в дереве
# — обычное дело, и запрещать их значит учить обходить стража. Но файл, который
# уже под версией и изменён, — это ровно тот случай, когда проверенное и
# отправляемое разошлись.
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): НОВЫЙ файл, который нужен коммиту, но никогда
# не добавлялся, — он неотслеживаемый и сюда не попадает. Ровно так пропал
# `branch-absorbed.sh`. Против этого работает другой страж — `check-guard-
# wiring.sh` на CI, где рабочего дерева нет вовсе: он увидит, что гейт зовёт
# несуществующий файл. Один страж всего не закрывает, и делать вид, что
# закрывает, хуже, чем назвать границу.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-tree-matches-push.sh [КОРЕНЬ]
# Обход — осознанный: NOVA_ALLOW_DIRTY_PUSH=1 git push …
# Самотест — scripts/guards/selftest/test-check-tree-matches-push.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 \
    || { echo "check-tree-matches-push ok: не git-репозиторий"; exit 0; }

if [ "${NOVA_ALLOW_DIRTY_PUSH:-0}" = "1" ]; then
    echo "check-tree-matches-push: пропущено (NOVA_ALLOW_DIRTY_PUSH=1)"
    exit 0
fi

# Только ОТСЛЕЖИВАЕМЫЕ: `--porcelain` без `-uall`, затем отсев строк `??`.
DIRTY=$(git -C "$ROOT" status --porcelain --untracked-files=no 2>/dev/null | grep -v '^??' || true)

if [ -n "$DIRTY" ]; then
    echo "check-tree-matches-push: ОТПРАВЛЯЕТСЯ НЕ ТО, ЧТО ПРОВЕРЕНО." >&2
    echo "" >&2
    echo "    Незакоммиченные изменения отслеживаемых файлов:" >&2
    printf '%s\n' "$DIRTY" | sed 's/^/      /' >&2
    echo "" >&2
    echo "    Гейт судит РАБОЧЕЕ ДЕРЕВО, а отправляется КОММИТ. Пока они" >&2
    echo "    расходятся, зелёный вердикт относится к тому, чего в" >&2
    echo "    отправляемом нет (реестр 221.1 №635: так уехали правка чекера" >&2
    echo "    №631, весь страж №629 и фикс линта — при том что gate.sh уже" >&2
    echo "    звал этот страж из main)." >&2
    echo "" >&2
    echo "    Закоммить их либо, если расхождение осознанное:" >&2
    echo "      NOVA_ALLOW_DIRTY_PUSH=1 git push …" >&2
    echo "check-tree-matches-push: FAIL" >&2
    exit 1
fi

echo "check-tree-matches-push ok: отслеживаемых изменений вне коммитов нет"
exit 0
