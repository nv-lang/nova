#!/usr/bin/env bash
# scripts/guards/check-effect-boundary-shape.sh
# Граница эффекта — API на Nova, а не таблица системных вызовов (D456).
#
# ДОМ И ОСНОВАНИЕ: `spec/decisions/04-effects.md` D456 (владелец 2026-08-11),
# план 268, реестр 221.1 №568, №579.
#
# ЗАЧЕМ. D456 записан прозой и перечисляет восемь форм, которых на границе быть
# не должно. Механизма не было ни одного — и цена этого измерена: обход в
# `Net.lookup` (адрес массива, переодетый в `int`, плюс счётчик) прожил недели,
# защищённый комментарием, который УЧИЛ несуществующему ограничению («a Vec
# payload does not survive the effect vtable's GC tracing»). Две пробы 2026-08-11
# и 2026-08-12 утверждение опровергли, а форма всё это время расходилась по
# `std` как образец. Правило без машины — симптом, а не фикс.
#
# ГДЕ ПРОХОДИТ ГРАНИЦА, дословно по D456 («Где живут C-формы»): C-формы живут в
# `extern "C"`-объявлениях `ffi.nv` и ВНУТРИ `real_*`-обработчика. Обработчик —
# ПЕРЕВОДЧИК, а не сквозной канал. Поэтому страж смотрит ТОЛЬКО на объявления
# операций внутри `type X effect { … }` и не трогает ни `ffi.nv`, ни тела
# обработчиков: сырой указатель ПОД границей законен, ЧЕРЕЗ неё — нет.
#
# ЧТО ПРОВЕРЯЕТСЯ — только механически различимое. Пункты D456 про пустые
# sentinel-значения и про `str` с не-UTF-8 байтами машинно неотличимы от верного
# кода и здесь НЕ проверяются; это сказано прямо, чтобы зелёный вердикт не
# читался как «граница соответствует D456 целиком».
#   R1  сырой указатель в подписи операции (`*()`, `*mut`, `*const`) — D456 §5
#   R2  обход по индексу: в одном эффекте есть и `X_count`/`X_len`, и `X_at`
#       (либо `X_key_at`/`X_val_at`) — D456 §3
#   R3  счётчик рядом с данными: параметр-коллекция, за которым идёт `int`
#       с именем `*c`/`*_count`/`*_len` — D456 §6
#   R4  позиционная простыня: больше шести параметров — D456 §8
#   R5  out-параметр: `mut out…` в списке параметров — D456 §4
#
# ПОЧЕМУ ХРАПОВИК, А НЕ НОЛЬ. `Fs` и `Os` сегодня — ровно та таблица системных
# вызовов, которую D456 запрещает, и переписывать их решено в v0.2 (D460: они не
# несут `#stable` и тегом не замораживаются). Обнулить одним движением нельзя,
# не сделав реформу; храповик запрещает РОСТ и требует, чтобы число падало.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-effect-boundary-shape.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-effect-boundary-shape.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
BASELINE="${NOVA_EFFECT_SHAPE_BASELINE:-$ROOT/scripts/guards/effect-boundary-shape.baseline}"

TMP="${TMPDIR:-/tmp}/effshape_$$"
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

# Весь разбор — ОДИН проход awk по всем файлам сразу. Первая редакция гоняла
# цикл оболочки с `grep` на каждую операцию (шесть правил на ~120 операций =
# ~700 процессов) и не уложилась в две минуты; после переписи — две секунды.
# Страж, тормозящий гейт, будет отключён (реестр №475).
AWK_CORE="$(dirname "${BASH_SOURCE[0]}")/effect-boundary-shape.awk"
[ -f "$AWK_CORE" ] || { echo "check-effect-boundary-shape: нет ядра $AWK_CORE" >&2; exit 1; }

find "$ROOT/std/src" "$ROOT/examples" -name '*.nv' -type f -print0 2>/dev/null \
    | xargs -0 -r awk -f "$AWK_CORE" > "$TMP/hits.txt" 2>/dev/null

# `grep -c` при НУЛЕ совпадений печатает `0` И выходит с кодом 1, поэтому
# привычное `|| echo 0` дописывало ВТОРОЙ ноль, и `TOTAL` становился «0\n0» —
# дальше `[ "$TOTAL" -gt ... ]` падал с `integer expected`. На живом дереве это
# невидимо (там находки есть), поймал самотест на чистой фикстуре.
TOTAL=$(grep -c . "$TMP/hits.txt" 2>/dev/null || true)
TOTAL=${TOTAL:-0}

BASE=0
[ -f "$BASELINE" ] && BASE=$(sed -n 's/^violations=\([0-9][0-9]*\).*/\1/p' "$BASELINE" | head -1)
BASE=${BASE:-0}

echo "check-effect-boundary-shape: нарушений формы границы $TOTAL (база $BASE)"
if [ "$TOTAL" -gt "$BASE" ]; then
    echo "check-effect-boundary-shape: ВЫРОСЛО — $TOTAL > базы $BASE" >&2
    cat "$TMP/hits.txt" >&2
    echo "" >&2
    echo "    Граница эффекта — публичный API на Nova (D456). C-формы живут в" >&2
    echo "    ffi.nv и ВНУТРИ real_*-обработчика: обработчик — переводчик, а не" >&2
    echo "    сквозной канал. Если C-форма видна в декларации эффекта, перевод" >&2
    echo "    просто не написан — и его придётся писать каждому, кто пишет мок." >&2
    echo "check-effect-boundary-shape: FAIL" >&2
    exit 1
fi
if [ "$TOTAL" -lt "$BASE" ]; then
    echo "check-effect-boundary-shape: долг СНИЗИЛСЯ ($TOTAL < базы $BASE) — опусти базу в $BASELINE"
fi
echo "check-effect-boundary-shape ok: роста нарушений формы границы нет ($TOTAL <= $BASE)"
exit 0
