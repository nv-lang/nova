# -*- coding: utf-8 -*-
"""scripts/guards/check-plan-wave-boundaries.py — волна плана, у которой есть
критерии приёмки, обязана нести ГРАНИЦЫ и ОТКРЫТЫЕ ВОПРОСЫ.

Адрес: план 276 шаг 4; реестр 221.1 №774 (зонтик приёмов работы с агентом).

ЗАЧЕМ. Критерии говорят, что будет сделано. Молчание о том, чего делать НЕ
будем, читается как забывчивость — и следующее окно доделывает «очевидное»,
которого никто не заказывал. А открытый вопрос без разумного умолчания
останавливает работу молчанием адресата: спросили и ждут.

Поэтому в волне, у которой есть `**Критерии`, обязаны быть:
  * «Не делаем» — границы: отсутствие чего-то названо РЕШЕНИЕМ;
  * «Открытые вопросы» — с адресатом, умолчанием и сроком. Вопрос без
    разумного умолчания блокирующий, и такой допустим один на волну (это
    правило судит человек — машина не отличит разумное умолчание от отписки).

СУДИТ ТОЛЬКО НОВОЕ, И ЭТО ГЛАВНОЕ В УСТРОЙСТВЕ. Страж, покрасневший на всей
истории планов, будет отключён первым же окном, которому он помешает, — и
правило исчезнет вместе с ним. Поэтому раздел попадает под суд, лишь если
САМАЯ ПОЗДНЯЯ дата в нём не раньше `CUTOVER` (день заведения стража). Старые
волны не трогаются вовсе: их писали до правила, и переписывать историю ради
зелёного гейта мы не станем.

ГДЕ ИСКАТЬ ГРАНИЦЫ — В РАЗДЕЛЕ ИЛИ ВО ВСЁМ ПЛАНЕ. План может объявить границы
ОДИН раз на весь документ (так сделан план 276), и повторять их в каждой волне
значило бы плодить копии — ровно то, против чего построен репозиторий. Поэтому
условие считается выполненным, если оба заголовка есть в разделе ЛИБО где-то в
файле плана.

ЧЕГО НЕ ПРОВЕРЯЕТ (сказано честно): что границы ОСМЫСЛЕННЫ, что у вопроса есть
адресат и умолчание, что блокирующий вопрос один. Это суждения; машина видит
наличие, человек — качество.

ЗАМЕР В ЧАС ЗАВЕДЕНИЯ (2026-08-29): под судом 3 раздела, нарушений 0.

$1 — корень; $2 — override даты отсечки (шов самотеста).
"""
import glob
import os
import io
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace", newline="\n")
sys.stderr.reconfigure(encoding="utf-8", errors="replace", newline="\n")

NAME = "check-plan-wave-boundaries"

# День заведения стража. Раньше этой даты не судим НИЧЕГО.
CUTOVER = "2026-08-29"

DATE = re.compile(r"20\d\d-\d\d-\d\d")
CRITERIA = u"**Критерии"
NEED = [u"Не делаем", u"Открытые вопросы"]


def main():
    a = sys.argv
    root = os.path.abspath(a[1] if len(a) > 1 else ".")
    cutover = a[2] if len(a) > 2 else CUTOVER

    plans = sorted(glob.glob(os.path.join(root, "docs", "plans", "*.md")))
    if not plans:
        print(f"{NAME} ok: судить нечего — планов в {root}/docs/plans нет")
        return 0

    judged = 0
    bad = []
    for path in plans:
        try:
            t = io.open(path, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        file_has = {n: (n in t) for n in NEED}
        for sec in re.split(r"(?m)^## ", t)[1:]:
            if CRITERIA not in sec:
                continue
            dates = DATE.findall(sec)
            if not dates or max(dates) < cutover:
                continue
            judged += 1
            missing = [n for n in NEED if not (n in sec or file_has[n])]
            if missing:
                head = sec.split("\n")[0].strip()[:70]
                bad.append((os.path.basename(path), head, missing))

    print(f"{NAME}: волн под судом {judged} (с {cutover}), без границ {len(bad)}")

    if bad:
        print(f"{NAME}: НАРУШЕНИЕ — волна с критериями, но без границ:", file=sys.stderr)
        for f, head, missing in bad:
            print(f"    {f} · «{head}» → нет: {', '.join(missing)}", file=sys.stderr)
        print("", file=sys.stderr)
        print("    «Не делаем» объясняет читателю, что отсутствие чего-то — РЕШЕНИЕ,",
              file=sys.stderr)
        print("    а не забывчивость: без него следующее окно доделывает «очевидное»,",
              file=sys.stderr)
        print("    которого никто не заказывал. «Открытые вопросы» с адресатом,",
              file=sys.stderr)
        print("    умолчанием и сроком не дают работе встать из-за молчания адресата.",
              file=sys.stderr)
        print("    Оба можно объявить ОДИН раз на весь план — тогда волна их наследует.",
              file=sys.stderr)
        print(f"{NAME}: FAIL", file=sys.stderr)
        return 1

    print(f"{NAME} ok: у каждой новой волны с критериями есть границы и открытые вопросы")
    return 0


if __name__ == "__main__":
    sys.exit(main())
