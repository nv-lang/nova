#!/usr/bin/env bash
# scripts/guards/check-novac-oracle-fresh.sh — бинарь ОРАКУЛА новее своих
# исходников (класс «локально зелено, в CI красно»; замер 2026-08-23).
#
# ЗАЧЕМ. Весь гейт novac судит ОРАКУЛОМ: им строится novac, его эмиссией
# считается оболочка, с ним сверяются мэнгл и дифф-корпус. Бинарь оракула лежит
# в дереве и НИКЕМ не проверялся на свежесть — гейт брал тот, что был.
#
# Замер 2026-08-23. Локальный `nova.exe` собран 08-21 21:16; main влит в ветку
# 08-22 23:57 и оракул после этого не пересобирался — трое суток гейт зеленел
# ВЧЕРАШНИМ компилятором, а CI, который строит оракула сам, краснел четырьмя
# отказами подряд с 08-21. Стоило пересобрать — те же отказы воспроизвелись
# локально с первого прогона. То есть красноту CI нельзя было ни объяснить, ни
# отладить: локальный гейт отвечал на ДРУГОЙ вопрос и об этом молчал.
#
# ПРОВЕРЯЕТ: ни один `.rs` компилятора не новее бинаря оракула. Иначе — красный
# с числом отставших файлов и командой пересборки.
# НЕ ПРОВЕРЯЕТ: что бинарь собран ИМЕННО из этого дерева (mtime — не хеш;
# названная слепая зона, и её закрывает CI, который строит с нуля); свежесть
# самого novac — это делает шаг novac-build.
#
# $1 — корень; $2 — override бинаря (шов самотеста).
set -u
export LC_ALL=C

NAME="check-novac-oracle-fresh"
ROOT="${1:-.}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"

BIN="${2:-}"
if [ -z "$BIN" ]; then
    BIN="$ROOT/nova-cli/target/release/nova.exe"
    [ -f "$BIN" ] || BIN="$ROOT/nova-cli/target/release/nova"
fi

if [ ! -f "$BIN" ]; then
    echo "$NAME ok: судить нечего (бинаря оракула нет — об этом говорит novac-build)"
    exit 0
fi

# Каталоги исходников оракула. Ищем только там, где живёт компилятор: узкий
# список дешевле и не краснеет от чужих кратов.
SRC_DIRS=""
for d in nova-cli compiler-codegen compiler-front compiler-mid compiler-driver; do
    [ -d "$ROOT/$d" ] && SRC_DIRS="$SRC_DIRS $ROOT/$d"
done
if [ -z "$SRC_DIRS" ]; then
    echo "$NAME: FAIL — не найдено ни одного каталога исходников оракула: страж потерял мишень (класс №519)" >&2
    exit 1
fi

# shellcheck disable=SC2086
NEWER=$(find $SRC_DIRS -name '*.rs' -newer "$BIN" 2>/dev/null | grep -v '/target/' | sed "s|^$ROOT/||")
CNT=$(printf '%s' "$NEWER" | grep -c . || true)

if [ "$CNT" -gt 0 ]; then
    echo "$NAME: FAIL — исходников новее бинаря оракула: $CNT" >&2
    printf '%s\n' "$NEWER" | head -5 | sed 's|^|  |' >&2
    echo "  Гейт судит ОРАКУЛОМ: им строится novac, его эмиссией считается" >&2
    echo "  оболочка, с ним сверяются мэнгл и корпус. Старый бинарь отвечает" >&2
    echo "  на другой вопрос и зеленеет там, где CI краснеет (замер 2026-08-23:" >&2
    echo "  трое суток и четыре отказа CI подряд)." >&2
    echo "  Пересобрать: cargo build --release --manifest-path nova-cli/Cargo.toml" >&2
    exit 1
fi

echo "$NAME ok: бинарь оракула новее всех .rs компилятора (искали в:$(printf '%s' "$SRC_DIRS" | sed "s|$ROOT/||g"))"
exit 0
