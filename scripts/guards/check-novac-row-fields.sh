#!/bin/sh
# scripts/guards/check-novac-row-fields.sh — состав ПОЛЕЙ строк реестра
# объявлен в плане и сверяется (конвенция П22, план 274 §10.3в).
#
# ЗАЧЕМ. Находка владельца 2026-08-16: план 273 объявляет каноническую форму
# «метод — функция, у которой первый параметр помечен получателем», таблицу
# свели в одну — и остановились: строка держала поле `recv_id`, а прочие
# параметры сборщик проверял и ВЫБРАСЫВАЛ. Снаружи выглядело выполненным,
# внутри получатель остался единственным запомненным параметром. Тот же
# корень был у `dup bool` (флаг вместо сохранённого кандидата) и у
# `fn_rets []int` (вектор рядом с таблицей): строка держит привилегированную
# или производную копию того, что должно читаться из общей структуры.
# «Производность» машине не формализуема — СОСТАВ полей формализуем.
#
# ПРОВЕРЯЕТ:
#   (A) множество полей каждой СТРОКИ реестра (`value`-записи; контейнеры
#       Ctx/*Table/Scope судит §10.3б) в novac/src/sem/sem.nv против
#       первой и второй колонок таблицы §10.3в плана 274 — В ОБЕ СТОРОНЫ.
#       Поле без строки плана — красный («поле заведено без ответа на вопрос
#       "почему поле, а не функция"»); строка плана без поля — красный
#       (протухшая запись, класс №519). Ассертит непустоту таблицы: пустой
#       или переименованный раздел иначе сделал бы стража вечнозелёным.
#   (C) булево поле на строке-элементе списка без пометки «[на элемент]»
#       в §10.3в — П23: свойство одного элемента, положенное на каждый.
#   (B) узкий признак класса: строка, хранящая общий список (пара `*_off` +
#       `*_cnt`), не имеет права нести поле, именующее ОДИН выделенный его
#       элемент — `recv*`, `self*`, `first*`, `head*`. Это ровно та форма,
#       с которой всё началось.
# НЕ ПРОВЕРЯЕТ: содержательность колонки «зачем» (приёмка); записи вне
#   sem.nv (там не реестры); типы полей и их порядок.
#
# $1 — корень репозитория; $2 — override пути к sem.nv; $3 — override плана.
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SEM="${2:-$ROOT/novac/src/sem/sem.nv}"
PLAN="${3:-$ROOT/docs/plans/274-novac-self-hosted-compiler.md}"
NAME=check-novac-row-fields

if [ ! -f "$SEM" ]; then
    echo "$NAME ok: судить нечего (нет $SEM)"
    exit 0
fi
[ -f "$PLAN" ] || { echo "$NAME: FAIL — нет плана $PLAN, состав полей не с чем сверить" >&2; exit 1; }

T="${TMPDIR:-/tmp}/novac-row-fields.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

# --- поля записей из исходника: строки вида "Запись поле" -------------------
tr -d '\r' < "$SEM" | awk '
    # СТРОКИ реестра — это `value`-записи (так документировано у TypeDef);
    # контейнеры (Ctx, *Table, Scope) — обычные записи, их состав судит
    # §10.3б, а не эта таблица.
    /^export type [A-Z][A-Za-z0-9_]* value \{/ { rec = $3; next }
    /^export type [A-Z][A-Za-z0-9_]* \{/ { rec = ""; next }
    rec != "" && /^\}/ { rec = "" }
    rec != "" && /^[[:space:]]+[a-z_][A-Za-z0-9_]*[[:space:]]/ {
        line = $0
        gsub(/^[[:space:]]+/, "", line)
        split(line, p, /[[:space:]]/)
        print rec " " p[1]
    }
' | sort -u > "$T/src"

# --- пары из таблицы §10.3в: | `Запись` | `поле` | ... ----------------------
tr -d '\r' < "$PLAN" | awk '
    /^#+ .*10\.3в/ { inb = 1; next }
    inb && /^#+ / { inb = 0 }
    inb && /^\|[[:space:]]*`[A-Z][A-Za-z0-9_]*`[[:space:]]*\|/ {
        line = $0
        sub(/^\|[[:space:]]*`/, "", line)
        rec = line
        sub(/`.*$/, "", rec)
        rest = line
        sub(/^[^|]*\|/, "", rest)
        # во второй ячейке может стоять несколько полей через пробел
        n = split(rest, cells, "|")
        f = cells[1]
        while (match(f, /`[a-z_][A-Za-z0-9_]*`/)) {
            fld = substr(f, RSTART + 1, RLENGTH - 2)
            print rec " " fld
            f = substr(f, RSTART + RLENGTH)
        }
    }
' | sort -u > "$T/plan"

NSRC=$(wc -l < "$T/src" | tr -d '[:space:]')
NPLAN=$(wc -l < "$T/plan" | tr -d '[:space:]')
if [ "$NSRC" -eq 0 ]; then
    echo "$NAME: FAIL — в $SEM не нашлось ни одной записи-строки: страж потерял мишень (класс №519)" >&2
    exit 1
fi
if [ "$NPLAN" -eq 0 ]; then
    echo "$NAME: FAIL — таблица §10.3в пуста или переименована: сверять не с чем, а молчать нельзя (класс №519)" >&2
    exit 1
fi

MISSING=$(comm -23 "$T/src" "$T/plan")
STALE=$(comm -13 "$T/src" "$T/plan")
if [ -n "$MISSING" ]; then
    echo "$NAME: FAIL — поле строки заведено без записи в §10.3в (П22):" >&2
    printf '%s\n' "$MISSING" | sed 's/^/  /' >&2
    echo "  Впиши поле в §10.3в и ответь там на вопрос «почему это ПОЛЕ, а не функция" >&2
    echo "  от уже хранимого». Производное значение выражается функцией: получатель —" >&2
    echo "  не поле, а params[param_off], и читает его одна FnTable.recv_of." >&2
    exit 1
fi
if [ -n "$STALE" ]; then
    echo "$NAME: FAIL — строка §10.3в без поля в коде (протухшая запись, класс №519):" >&2
    printf '%s\n' "$STALE" | sed 's/^/  /' >&2
    exit 1
fi

# --- (B) выделенный элемент общего списка ----------------------------------
SMELL=$(awk '{ rec[$1] = rec[$1] " " $2 } END {
    for (r in rec) {
        has_range = (rec[r] ~ /_off/ && rec[r] ~ /_cnt/)
        if (!has_range) continue
        n = split(rec[r], f, " ")
        for (i = 1; i <= n; i++) {
            if (f[i] ~ /^(recv|self|first|head)/) {
                printf "  %s.%s — выделенный элемент общего списка рядом с парой *_off/*_cnt\n", r, f[i]
            }
        }
    }
}' "$T/src")
if [ -n "$SMELL" ]; then
    echo "$NAME: FAIL — строка хранит общий список И отдельное поле на один его элемент (П22):" >&2
    printf '%s\n' "$SMELL" >&2
    echo "  Это производная: элемент читается из списка функцией (образец: FnTable.recv_of" >&2
    echo "  возвращает params[param_off] у метода). Поле рядом со списком расходится с ним." >&2
    exit 1
fi

# --- (C) булево поле на строке-ЭЛЕМЕНТЕ списка (П23) -----------------------
# Класс: свойство, которое по инварианту может держать лишь ОДИН элемент,
# положено на КАЖДЫЙ элемент — и представление начинает допускать состояния,
# запрещённые языком («третий параметр — получатель», «получателей два»).
# Живой случай 2026-08-16: `ParamDef.is_recv`. Формализуемая половина: если
# строка хранится СПИСКОМ, её булево поле обязано нести в §10.3в пометку
# «[на элемент]» — то есть автор ответил вслух, почему бит может различаться
# у разных элементов, а не является свойством всего списка.
ELEMENT_ROWS=$(tr -d '' < "$SEM" | grep -oE '\[\][A-Z][A-Za-z0-9_]*' | sed 's/^\[\]//' | sort -u)
BOOLS=$(tr -d '' < "$SEM" | awk '
    /^export type [A-Z][A-Za-z0-9_]* value \{/ { rec = $3; next }
    rec != "" && /^\}/ { rec = "" }
    rec != "" && /^[[:space:]]+[a-z_][A-Za-z0-9_]*[[:space:]]+bool([[:space:]]|$)/ {
        line = $0; gsub(/^[[:space:]]+/, "", line); split(line, p, /[[:space:]]/)
        print rec " " p[1]
    }')
UNTAGGED=""
for pair in $(printf '%s
' "$BOOLS" | tr ' ' '@'); do
    [ -n "$pair" ] || continue
    rec=${pair%@*}; fld=${pair#*@}
    echo "$ELEMENT_ROWS" | grep -qx "$rec" || continue
    row=$(tr -d '' < "$PLAN" | grep -F "\`$rec\`" | grep -F "\`$fld\`" | head -1)
    case "$row" in
        *"[на элемент]"*) ;;
        *) UNTAGGED="$UNTAGGED $rec.$fld" ;;
    esac
done
if [ -n "$UNTAGGED" ]; then
    echo "$NAME: FAIL — булево поле на строке-элементе списка без пометки «[на элемент]» (П23):" >&2
    for f in $UNTAGGED; do echo "  $f" >&2; done
    echo "  Если свойство по инварианту может держать лишь ОДИН элемент — бит принадлежит" >&2
    echo "  владельцу списка, а не элементу: иначе представление допускает запрещённые" >&2
    echo "  состояния (образец: has_recv на FnDef, а не is_recv на каждом параметре)." >&2
    echo "  Если бит правда различается по элементам — впиши «[на элемент]» в §10.3в." >&2
    exit 1
fi

echo "$NAME ok: полей строк реестра: $NSRC, все объявлены в §10.3в, протухших записей: 0, выделенных элементов списка: 0"
exit 0
