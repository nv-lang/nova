#!/usr/bin/env bash
# Страж: собственный набор тестов `nova-lsp` проходит целиком.
#
# ЗАЧЕМ. 2026-08-18 обнаружилось, что 433 теста расширения НЕ ГОНЯЕТ НИКТО —
# ни `scripts/gate.sh`, ни один workflow в `.github/workflows/`. Пять из них
# были красными, и сказать, как давно, нельзя: гнилой тест не оставляет следа,
# пока его не запустят. Расширение VS Code входит в поставку v0.1, то есть
# непроверенным поставлялся кусок продукта.
#
# ЧТО ИМЕННО ПРОГНИЛО, для понимания цены молчания: два теста утверждали, что
# `std.io` и `std.math` не существуют (оба написаны с тех пор); два — что
# модуль зовётся `hashmap` (переименован в `hash_map`, 36 импортов новой формы);
# один строил значение снятой формой `Foo {}` вместо `Foo.new(..)` и оттого
# проверял не тот путь, который называл. Ни одного дефекта продукта — ровно
# поэтому их и не заметили: красный тест, который никто не запускает, неотличим
# от отсутствующего.
#
# ПОЧЕМУ АССЕРТ НА СТРОКУ, А НЕ КОД ВОЗВРАТА. Код возврата отличает «упал» от
# «не упал», а нужно «проверил». Ноль без строки `test result: ok. N passed;
# 0 failed` — это молчание, и оно обязано быть красным (класс F1, реестр №645:
# страж, зелёный ни о чём). Отдельно требуется N > 0: пустой набор тоже даёт
# «ok».
#
# ПОЧЕМУ `--lib`, А НЕ ВЕСЬ `cargo test`. Двоичные цели линкуются в тот же
# `nova-lsp.exe`, который держит открытым работающий редактор; линковка тогда
# падает с `os error 5` и страж краснеет о среде, а не о коде. Библиотечный
# набор — это и есть 433 теста; интеграционные гоняются отдельно.
#
# $1 — корень репозитория.
# NOVA_LSP_TESTS_CMD — команда вместо cargo (самотест подставляет свою).
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u
export LC_ALL=C

NAME="check-lsp-tests"
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CRATE="$ROOT/nova-lsp"

if [ ! -f "$CRATE/Cargo.toml" ]; then
    echo "$NAME: FAIL — нет $CRATE/Cargo.toml" >&2
    exit 1
fi

if [ -n "${NOVA_LSP_TESTS_CMD:-}" ]; then
    OUT=$(eval "$NOVA_LSP_TESTS_CMD" 2>&1)
elif command -v cargo >/dev/null 2>&1; then
    OUT=$(cd "$CRATE" && cargo test --release --lib 2>&1)
else
    echo "$NAME ok: cargo недоступен — судить нечем"
    exit 0
fi

# Строка вердикта обязана БЫТЬ. Её отсутствие — не «прошло», а «неизвестно».
LINE=$(printf '%s\n' "$OUT" | grep -E '^test result: (ok|FAILED)\.' | tail -1)
if [ -z "$LINE" ]; then
    echo "$NAME: FAIL — набор не отчитался строкой 'test result:'" >&2
    printf '%s\n' "$OUT" | tail -20 >&2
    echo "    Ноль без строки вердикта — это 'не упал', а не 'проверил'." >&2
    exit 1
fi

PASSED=$(printf '%s\n' "$LINE" | sed -n 's/.* \([0-9][0-9]*\) passed.*/\1/p')
FAILED=$(printf '%s\n' "$LINE" | sed -n 's/.* \([0-9][0-9]*\) failed.*/\1/p')
case "${PASSED:-}${FAILED:-}" in
    ''|*[!0-9]*) echo "$NAME: FAIL — не разобрал строку вердикта: $LINE" >&2; exit 1;;
esac

if [ "$FAILED" -ne 0 ]; then
    echo "$NAME: FAIL — тестов nova-lsp упало: $FAILED (прошло $PASSED)" >&2
    printf '%s\n' "$OUT" | grep -E "^(thread|test .* FAILED|    [a-z_]+::)" | head -20 >&2
    echo "    Прогнать вручную: cd nova-lsp && cargo test --release --lib" >&2
    exit 1
fi

# Пустой набор тоже отчитывается «ok» — это не проверка, это тишина.
if [ "$PASSED" -lt 100 ]; then
    echo "$NAME: FAIL — прошло всего $PASSED тестов, набор был вдвое больше" >&2
    echo "    Похоже, отфильтровался или не собрался; 'ok' на пустом наборе" >&2
    echo "    ничего не значит." >&2
    exit 1
fi

echo "$NAME ok: набор nova-lsp зелёный целиком ($PASSED тестов)"
exit 0
