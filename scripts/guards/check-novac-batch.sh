#!/bin/sh
# scripts/guards/check-novac-batch.sh — инструмент, обрабатывающий много
# файлов, зовёт novac ОДИН раз (план 274.2 §1б.1; владелец 2026-08-17:
# «пусть делают пачкой конечно» и следом «где записано, когда сделаем, страж
# есть?» — стража не было).
#
# ЗАЧЕМ. Замер: чистый старт novac 149 мс против ~50 мс работы на маленьком
# файле — три четверти пофайлового прохода это ЗАПУСК. Корпус в 61 файл
# платил его 61 раз; пачкой novac стал 1.7 с вместо 12.8 с. Экономия ничем не
# держалась: вернуть цикл по файлам — правка в две строки, и её никто не
# заметит, кроме бюджета времени с восьмикратным запасом.
#
# ПРОВЕРЯЕТ scripts/tools/novac-diff-corpus.sh:
#   * есть ПАЧЕЧНЫЙ вызов (один `check` со списком, а не с одним файлом);
#   * список переводится в ОТНОСИТЕЛЬНЫЕ пути (MSYS переписывает `/d/...` в
#     `D:\...` на границе exec, novac печатает полученное, и вердикты
#     перестают сходиться — живая ошибка 2026-08-17: «принято 55» вместо 5);
#   * есть ОТКАТ на пофайловый проход, если пачка умерла (иначе вердикты
#     берутся из мусора).
# НЕ ПРОВЕРЯЕТ: что пачка быстрее (это храповик цены цикла); фаззер — он
#   пачечный с самого начала, и его форма судится тем же храповиком.
#
# $1 — корень; $2 — override пути к раннеру (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
RUNNER="${2:-$ROOT/scripts/tools/novac-diff-corpus.sh}"
NAME=check-novac-batch

if [ ! -f "$RUNNER" ]; then
    echo "$NAME: FAIL — нет $RUNNER: судить нечего, а молчать нельзя (класс №519)" >&2
    exit 1
fi

BAD=""
grep -q 'list.rel' "$RUNNER" || BAD="$BAD
  нет перевода списка в ОТНОСИТЕЛЬНЫЕ пути (list.rel): вердикты пачки не сойдутся с файлами"
grep -qE 'check \$\(sed|check \$\(cat|check \$\{' "$RUNNER" || BAD="$BAD
  нет пачечного вызова novac (один check со списком файлов)"
grep -q 'NOVAC_BATCH' "$RUNNER" || BAD="$BAD
  нет переключателя отката: если пачка умрёт, вердикты будут взяты из мусора"
grep -q 'NOVAC_BATCH=0' "$RUNNER" || BAD="$BAD
  откат на пофайловый проход не выставляется ни в одной ветке"

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — пачечный проход раннера разобран (274.2 §1б.1):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Верни: один вызов novac со списком ОТНОСИТЕЛЬНЫХ путей, вердикт по" >&2
    echo "  полю file диагностик, откат на пофайловый проход при смерти пачки." >&2
    exit 1
fi

echo "$NAME ok: раннер зовёт novac пачкой (относительные пути, откат при смерти пачки на месте)"
exit 0
