#!/usr/bin/env bash
# scripts/guards/check-no-control-chars.sh
# Невидимый управляющий байт в исходнике — это код, который читается правильно
# и работает неправильно.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №TBD-control-chars; перенесено 2026-08-12 из
# другого проекта владельца по его указанию
# «посмотри, возможно есть что к нам перетащить».
#
# ЗАЧЕМ. Там повод был такой: дважды за день в регулярку стража попадал
# настоящий символ забоя (0x08) вместо последовательности `\b` — код выглядел
# верным, читался верным, а выражение не совпадало НИКОГДА, и страж молча
# переставал ловить. У нас это тот же класс, что №596 и №603: текст, идущий
# через оболочку, приходит не тем, чем был, и порча молчаливая.
#
# И он оправдался на первой же минуте: в `scripts/gate.sh` нашлись ДВА
# литеральных ESC (0x1b) внутри `sed -e "s/<ESC>\[[0-9;]*m//g"` — снятие
# цветовых кодов. Использование законное, форма опасная: байт невидим, любой
# копипаст его съедает, и гейт молча перестаёт находить строку `PASS:`.
# Оба переписаны на `ESC=$(printf '\033')` тем же слиянием — поэтому страж
# строгий и БЕЗ базы: ни одного законного случая в дереве не осталось.
#
# ЧТО ЛОВИТСЯ: любой управляющий байт, кроме табуляции (0x09), перевода
# строки (0x0a) и возврата каретки (0x0d).
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): невидимые символы ВНЕ диапазона управляющих
# — неразрывный пробел, zero-width space, мягкий перенос. Это другой класс
# (юникодные пробелы), у него другой периметр, и валить его сюда значило бы
# получить стража, который ловит два разных зверя и красит на обоих.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-no-control-chars.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-no-control-chars.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

# Периметр: то, что пишем мы. Бинарное, чужое и сгенерированное — мимо.
#
# ОДИН вызов grep на весь список, а не по вызову на файл: первая версия делала
# два процесса на каждый из тысяч файлов и не укладывалась в две минуты. Страж,
# который не успевает, — не страж; тот же урок, что у `check-doc-examples.sh`
# (22 с → 4 с) и `check-invariant-discipline.sh`.
FOUND=$(cd "$ROOT" 2>/dev/null && git ls-files -z 2>/dev/null \
    | tr '\0' '\n' \
    | grep -E '\.(sh|rs|nv|md|py|toml|yml|yaml|json|c|h)$' \
    | grep -vE '^(compiler-codegen/nova_rt/(libuv|gc|libatomic_ops)|compiler-codegen/vcpkg_installed)/' \
    | tr '\n' '\0' \
    | xargs -0 -r grep -clP '[\x00-\x08\x0b\x0c\x0e-\x1f]' 2>/dev/null)

if [ -n "$FOUND" ]; then
    echo "check-no-control-chars: невидимые управляющие байты в исходниках:" >&2
    printf '%s\n' "$FOUND" | sed 's/^/    /' >&2
    echo "" >&2
    echo "    Смотреть так:  grep -nP '[\\x00-\\x08\\x0b\\x0c\\x0e-\\x1f]' <файл> | cat -v" >&2
    echo "    Чинить так: байт задаётся ЯВНО и один раз —" >&2
    echo "      ESC=\$(printf '\\033')   и дальше \${ESC} в выражении," >&2
    echo "    а не литералом внутри строки, где его не видно (реестр №596, №603)." >&2
    echo "check-no-control-chars: FAIL" >&2
    exit 1
fi

echo "check-no-control-chars ok: невидимых управляющих байтов нет"
exit 0
