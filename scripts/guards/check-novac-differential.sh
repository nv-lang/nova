#!/bin/sh
#
# ПОРЯДОК ВЕРДИКТОВ ПОПРАВЛЕН 2026-09-20 (реестр 221.1 №1199, нашло окно Карины). У стража
# ТРИ этапа, и каждый печатал своё «ok». Читающий — ЧЕЛОВЕК, а не сканер, и он
# останавливается на первом: под «ok: исходы совпали» всю ночь
# прожила тихая мискомпиляция (№1191): четыре фикстуры
# собирались одинаково и ОТВЕЧАЛИ по-разному.
#
# ТЕПЕРЬ: слово «ok» принадлежит ТОЛЬКО последнему этапу и
# говорит, что он ИТОГОВЫЙ; промежуточные докладывают ЗАМЕР с номером
# этапа (1/3, 2/3) и прямо пишут «НЕ ВЕРДИКТ». Отказы как были в stderr.
#
# ЗАМЕР ПО ЛОГАМ ПРОГОНОВ (51 лог): такой страж в дереве РОВНО ОДИН.
# Первая попытка считала порядок строк в ИСХОДНИКЕ и дала 58 —
# число шума: «ok» и «FAIL» почти всегда стоят в разных ветвях.
# scripts/guards/check-novac-differential.sh — дифференциальный прогон novac
# против оракула.
#
# ПРАВИЛО (план 274 §10.3, §10.3а: «контракт = оракулу; расхождения только из
# реестра»): novac обязан принимать/отвергать те же программы, что нынешний
# компилятор (оракул nova-cli/target/release/nova.exe check). Страж прогоняет
# оба бинаря по novac/fixtures/**/pos_*.nv и сравнивает ИСХОД (принял/отверг,
# а с 2026-08-16 у принятых обеими сторонами — ещё и ОТВЕТ: stdout и код
# возврата через смоук, потому что одинаковый вердикт при разном значении
# зелёным быть не должен (274.3/F18: `1 + 2 * 3` считалось как 9),
# по коду возврата). Расхождение, не записанное в novac/divergences.allow
# (строка = путь фикстуры от корня, с прямыми слэшами), — красное.
#
# НЕ проверяет: совпадение текстов/кодов диагностик (только исход),
# поведение на neg_* (их судят diag-schema и no-cascade), обоснованность
# записей allow — её судит приёмка и docs/plans/274.12-novac-divergences.md.
# Контракт вызова: '<bin> check <file>'; если CLI novac окажется иным —
# страж правится тем же коммитом, что вводит бинарь.
#
# С Э2 (274 §10.4) страж — ещё и судья храповика НА ПРОГРЕСС: зовёт
# scripts/tools/novac-diff-corpus.sh (корпус examples/), парсит его машинную
# строку baseline-numbers и сверяет с novac-corpus.baseline В ОБЕ СТОРОНЫ:
# меньше базы — откат (красный), больше базы — рост без поднятия базы тем же
# коммитом (тоже красный). Корзины «вне точки»/«заблокировано оракулом»/
# «расстояние до самосборки» печатаются раннером рядом с базой (§10.4).
# БЮДЖЕТ — НЕ ЧИСЛОМ ЗДЕСЬ, А ФАЙЛОМ: `diff-corpus-ms` в
# `scripts/guards/novac-iteration-cost.baseline` (на 2026-09-18 — 560000мс, то
# есть ~9.3 мин), плюс поправка на загрузку (`novac_load_scale`, см. ниже).
# Здесь стояло «~2–6 мин (замер 2026-08-14: 334с)», и к 2026-09-18 это
# расходилось с собственным бюджетом стража вдвое даже БЕЗ поправки.
# Замер того дня: стена 1282993мс (21.4 мин) при поправленном бюджете
# 1937600мс — ЗЕЛЁНЫЙ, хотя шапка заставляла ждать отказа вчетверо раньше:
# окно четырежды собиралось снимать прогон как «зависший». Число в прозе,
# которому не с чем сверяться, гниёт молча — то же правило, что `AGENTS.md`
# применил к себе, сняв счёт стражей из своего текста.
# Для быстрых локальных итераций:
# NOVAC_CORPUS=0 отключает КОРПУСНЫЙ храповик (examples/ через novac-diff-corpus);
# NOVAC_SMOKE=0 отключает ПОВЕДЕНЧЕСКИЙ смоук фикстур (компиляцию C и запуск,
# сверка stdout с оракулом). Каждый шов гасит ОДНУ стадию и печатает её имя
# (реестр №992: пока смоук висел на NOVAC_CORPUS, эта строка говорила «фикстуры
# остаются», а компиляция C снималась молча — намеренно сломанный эмиттер прошёл
# зелёным, 2026-09-06). Сверка «принял/отверг» не отключается ничем. Отключение
# в ГЕЙТЕ — только сознательным решением интегратора, не тихим дефолтом.
#
# Страж «ожидает бинарь»: пока novac/target/novac.exe не существует — зелёный
# честной строкой: страж до кода легален, молчание нелегально (№645).
#
# $1 — корень репозитория (default: вычислить от себя);
# $2 — override бинаря novac (для самотеста).
#
# Проверялся: Windows (Git Bash), 2026-08-14.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
NAME=check-novac-differential
. "$(dirname "$0")/lib/novac.sh"
BIN="${2:-$(novac_bin "$ROOT")}"   # #1607: the door, not a file name

novac_require_bin "$NAME" "$ROOT" "$BIN"

ORACLE="$(novac_find_oracle "$ROOT" || true)"
if [ -z "$ORACLE" ]; then
    # Worktree без своего target: оракул главного дерева (приём №650 —
    # главная репа выводится из git, не из памяти).
    :
fi
if [ -z "$ORACLE" ]; then
    echo "$NAME ok: судить нечего (оракул nova-cli/target/release/nova.exe не собран)"
    exit 0
fi

FIXDIR="$ROOT/novac/fixtures"
ALLOW="$ROOT/novac/divergences.allow"
T="${TMPDIR:-/tmp}/novac-differential.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0

if [ -d "$FIXDIR" ]; then
    find "$FIXDIR" -type f -name 'pos_*.nv' | sort > "$T/list"
else
    : > "$T/list"
fi
N=$(wc -l < "$T/list" | tr -d ' ')
if [ "$N" -eq 0 ]; then
    echo "$NAME ok: судить нечего (0 фикстур pos_*.nv в novac/fixtures)"
    exit 0
fi

# ---- ПУЛ: фикстуры судятся параллельно, вердикт остаётся поштучным (№1717) ---
# ВРЕМЯ ЛИНЕЙНО ПО КОРПУСУ, а предел — нет. Корпус рос 109 -> 141 -> 186 -> 190
# фикстур за неделю, страж шёл одним потоком и 2026-10-05 на CI (a16c01868, run
# 37342004286) был снят пределом 1200с на этапе 2: вердикта не было вовсе.
# ЗАМЕР НА ФИКСТУРУ (Windows, 8 фикстур, через одну на 24, холодный кэш), мс:
#   novac check 1922 · оракул check 822 · сборка оракулом 10736 ·
#   novac emit + clang -c (PCH) + линковка + два запуска 1523.
# Этап 2 ЗАНОВО звал оба `check` (ещё 2744мс: дубль этапа 1), и сборка оракулом —
# больше половины цены — повторялась в каждом прогоне CI. Итого ~18с на фикстуру,
# 57–75 мин на корпус одним потоком. Три правки класса, а не числа предела:
#   1) этап 1 пишет исход каждой фикстуры в файл, этап 2 читает его, а не зовёт
#      `check` снова — минус две трети процессов этапа 1 в этапе 2;
#   2) фикстуры делятся между NOVAC_POOL_JOBS потоками (по умолчанию — ядра;
#      общая дверь novac_pool в lib/novac.sh, ею же ходит check-novac-no-panic),
#      а сводка СВЕРЯЕТ, что исход есть у КАЖДОЙ строки списка: фикстура без
#      файла исхода — красный «пул потерял», а не тихий пропуск;
#   3) бинарь оракула кэшируется по СОДЕРЖИМОМУ (novac_oracle_key в lib/novac.sh,
#      ключ печатает `novac-e1-smoke.sh --prepare`), и каталог бинарей переносится
#      между прогонами CI (NOVAC_SMOKE_EXE_CACHE, .github/workflows/nova-gate.yml).
# Каждая строка этапа 2 печатает стену и число потоков: следующий рост корпуса виден
# числом в логе, а не обрывом.
J=$(novac_pool_jobs)
mkdir -p "$T/r"
# Исход фикстуры: $T/r/<номер>.v = «<novac> <оракул>», слова «принял»/«отверг».
one_verdict() {
    if "$BIN" check "$2" >/dev/null 2>&1 </dev/null; then _b="принял"; else _b="отверг"; fi
    if "$ORACLE" check "$2" >/dev/null 2>&1 </dev/null; then _o="принял"; else _o="отверг"; fi
    printf '%s %s\n' "$_b" "$_o" > "$T/r/$1.v"
}

t_stage=$(date +%s)
novac_pool one_verdict "$T/list" "$J"
bad=0
allowed=0
lost=0
i=0
while IFS= read -r f; do
    i=$((i+1))
    rel=${f#"$ROOT"/}
    if [ ! -f "$T/r/$i.v" ]; then
        printf '  %s: исхода нет — поток пула его не записал\n' "$rel" >> "$T/lost"
        lost=$((lost+1))
        continue
    fi
    read -r b o < "$T/r/$i.v"
    if [ "$b" != "$o" ]; then
        if [ -f "$ALLOW" ] && grep -Fxq "$rel" "$ALLOW"; then
            allowed=$((allowed+1))
        else
            printf '  %s: novac %s, оракул %s\n' "$rel" "$b" "$o" >> "$T/bad"
            bad=$((bad+1))
        fi
    fi
done < "$T/list"

if [ "$lost" -gt 0 ]; then
    echo "$NAME: FAIL — фикстур без исхода: $lost из $N — пул потерял их, о них не узнали ничего (№1717):" >&2
    cat "$T/lost" >&2
    exit 1
fi
if [ "$bad" -gt 0 ]; then
    echo "$NAME: FAIL — расхождений с оракулом вне novac/divergences.allow: $bad" >&2
    cat "$T/bad" >&2
    echo "  Чинить: либо баг novac (чинится той же волной, обходы запрещены)," >&2
    echo "  либо осознанное расхождение — тогда строка-путь в" >&2
    echo "  novac/divergences.allow + запись в docs/plans/274.12-novac-divergences.md" >&2
    echo "  (план 274 §10.3а)." >&2
    exit 1
fi
echo "$NAME этап 1/3 ИСХОДЫ: фикстур $N, совпали с оракулом (в allow: $allowed); стена $(( $(date +%s) - t_stage ))с, потоков $J — НЕ ВЕРДИКТ, поведение и храповик ниже"

# ---- ОТВЕТ, а не только вердикт (274.3/F18, урок 2026-08-16) -------------
# Вердикт «оба приняли» ничего не говорит о ЗНАЧЕНИИ. Живой случай: фикстура
# int_arith/pos_1.nv содержит `1 + 2 * 3 - 4`, novac парсил плоской цепью и
# считал 9 вместо 7 — и страж был зелёным, потому что сравнивал только
# «принял/отверг». Поэтому каждая принятая обеими сторонами фикстура ещё и
# ЗАПУСКАЕТСЯ через смоук: stdout и код возврата novac сверяются с оракулом
# байт в байт. Это дорого (сборка двух бинарей на фикстуру), поэтому у шага
# СВОЙ шов NOVAC_SMOKE=0 — не корпусный: две стадии под одним именем и
# гасились вместе, а докстрока обещала обратное (№992).
if [ "${NOVAC_SMOKE:-1}" = "0" ]; then
    echo "$NAME: стадия ПОВЕДЕНИЯ фикстур пропущена (NOVAC_SMOKE=0) — компиляция C и запуск НЕ проверялись, сверены только исходы принял/отверг"
else
    SMOKE="$ROOT/scripts/tools/novac-e1-smoke.sh"
    if [ -x "$SMOKE" ] || [ -f "$SMOKE" ]; then
        # БЛИЗНЕЦ (2026-10-03, трек D133): строка `// NOVAC_TWIN <файл>` в фикстуре
        # называет её явный разворот, лежащий рядом, — норму, которую оракул не
        # реализует (D476, реестр 221.1 №1107). Тогда оракул собирает БЛИЗНЕЦА, novac —
        # фикстуру, и ответ сверяется так же байт в байт. Это не пропуск: allow здесь
        # ничего не снимает, а близнец без файла — красный.
        #
        # Итог фикстуры: $T/r/<номер>.b — первое слово `совпало`, `близнец` (совпало
        # против близнеца), `разошлось` или `не-судилась`, дальше причина. Каждая
        # фикстура получает РОВНО ОДНО из них, и сводка это сверяет (№1717).
        one_behaviour() {
            _r="$T/r/$1"
            read -r _b _o < "$_r.v"
            if [ "$_b" != "принял" ]; then echo "не-судилась novac отверг" > "$_r.b"; return 0; fi
            _twin=$(sed -n 's|^// NOVAC_TWIN \([^ ]*\)$|\1|p' "$2" | head -n 1)
            _src="$2"
            if [ -n "$_twin" ]; then
                _src="$(dirname "$2")/$_twin"
                if [ ! -f "$_src" ]; then
                    echo "разошлось близнец NOVAC_TWIN $_twin не найден" > "$_r.b"
                    return 0
                fi
                # Оракул судит ТО, что собирает: близнеца. Фикстура, которую оракул
                # отвергает (исход — в allow), сверяется так же, если близнец есть.
                if "$ORACLE" check "$_src" >/dev/null 2>&1 </dev/null; then _o="принял"; else _o="отверг"; fi
            fi
            if [ "$_o" != "принял" ]; then echo "не-судилась оракул отверг" > "$_r.b"; return 0; fi
            if bash "$SMOKE" "$_src" "$2" > "$_r.out" 2>&1; then
                if [ "$_src" = "$2" ]; then echo "совпало" > "$_r.b"; else echo "близнец" > "$_r.b"; fi
            else
                echo "разошлось поведение разошлось с оракулом" > "$_r.b"
            fi
        }
        t_stage=$(date +%s)
        # Общее на прогон готовится ОДИН раз до пула; не вышло — пул в один поток,
        # и каждый смоук готовит сам и сам называет отказ, как было до пула.
        jb=$J
        if bash "$SMOKE" --prepare > "$T/prepare.out" 2>&1; then
            okey=$(sed -n 's/.*ключ оракула \([0-9a-zA-Z]*\).*/\1/p' "$T/prepare.out" | head -n 1)
            [ -n "$okey" ] && export NOVAC_SMOKE_ORACLE_KEY="$okey"
        else
            jb=1
        fi
        novac_pool one_behaviour "$T/list" "$jb"
        beh=0; behbad=0; twins=0; skipped=0; fromcache=0
        i=0
        while IFS= read -r f; do
            i=$((i+1))
            rel=${f#"$ROOT"/}
            if [ ! -f "$T/r/$i.b" ]; then
                behbad=$((behbad+1))
                printf '  %s: итога нет — поток пула его не записал (№1717)\n' "$rel" >> "$T/behbad"
                continue
            fi
            read -r verdict why < "$T/r/$i.b"
            [ -f "$T/r/$i.out" ] && grep -q 'оракул из кэша' "$T/r/$i.out" && fromcache=$((fromcache+1))
            case "$verdict" in
                совпало) beh=$((beh+1)) ;;
                близнец) beh=$((beh+1)); twins=$((twins+1)) ;;
                не-судилась)
                    skipped=$((skipped+1))
                    printf '  %s: не судилась — %s\n' "$rel" "$why" >> "$T/skipped" ;;
                *)
                    behbad=$((behbad+1))
                    printf '  %s: %s\n' "$rel" "$why" >> "$T/behbad"
                    [ -f "$T/r/$i.out" ] && sed 's/^/      /' "$T/r/$i.out" | head -n 4 >> "$T/behbad" ;;
            esac
        done < "$T/list"
        if [ "$behbad" -gt 0 ]; then
            echo "$NAME: FAIL — фикстура принята обоими, но ОТВЕТ разный: $behbad" >&2
            cat "$T/behbad" >&2
            echo "  Одинаковый вердикт при разном ответе — худший вид зелёного:" >&2
            echo "  подмножество имеет право ОТКАЗАТЬ, но не имеет права посчитать иначе." >&2
            exit 1
        fi
        echo "$NAME этап 2/3 ПОВЕДЕНИЕ: $beh из $N байт-в-байт (из них против близнеца NOVAC_TWIN: $twins), не судились $skipped — каждая названа ниже; стена $(( $(date +%s) - t_stage ))с, потоков $jb, бинарь оракула из кэша $fromcache из $beh — НЕ ВЕРДИКТ, храповик ниже"
        [ "$skipped" -gt 0 ] && cat "$T/skipped"
    fi
fi

# ---- ЯРУС push СУДИТ ЭТАПЫ 1–2, ЭТАП 3 — ЯРУС full (реестр 221.1 №1442) ----
# ЗАМЕР НА LINUX, В СРЕДЕ CI (2026-09-30). В гейте этот страж идёт в
# параллельном блоке `novac-behaviour` под пределом 600с x калибровка (на CI
# калибровка 1): c775a97 — ~600с всего, из них корпус 177с стены; affa00973 —
# этапы 1–2 доложены, страж снят пределом на этапе 3 («ОБРЫВ, вердикта нет»);
# dc634c42c — 590с. В одиночку на тихой 4-ядерной Linux-машине: этап 1 — 47с,
# этап 2 — 162с, этап 3 — 168с. Предел не растёт с корпусом, а этап 3 растёт.
# Весь job `novac-gate` на пуше в 45 минут с запасом 20% не входит (разбор —
# REPORT-p1442.md), значит корпус ПЕРЕЕЗЖАЕТ, а не отключается: Г4 сам относит
# «полный корпус» к ярусу full, и ночной прогон по расписанию его исполняет и
# краснеет по храповику. Ярус push получает ПОЛНЫЙ вердикт по этапам 1–2.
#
# ПОЧЕМУ НЕ ШОВ: `NOVAC_CORPUS=0` — шов выборки, прогон с ним не даёт слова
# `final` (№992). Здесь не выборка, а распределение по ярусам, поэтому
# переменная своя, без формы `:-1`, и ставит её ТОЛЬКО гейт — из своего яруса.
# Вручную (переменной нет) страж, как прежде, идёт всеми тремя этапами.
if [ "${NOVAC_DIFF_TIER:-full}" = "push" ]; then
    echo "$NAME ok: ИТОГ ЯРУСА push — этапы 1–2 (исходы и поведение фикстур $N); этап 3/3 (корпус, храповик, самосборка) судит ярус full — ночной прогон (№1442)"
    exit 0
fi

# ---- Храповик корпуса (274 §10.4; с Э2) ----------------------------------
if [ "${NOVAC_CORPUS:-1}" = "0" ]; then
    echo "$NAME: стадия КОРПУСА пропущена (NOVAC_CORPUS=0) — храповик contract/behavior по examples/ НЕ сверялся"
    exit 0
fi
BASE="$ROOT/scripts/guards/novac-corpus.baseline"
if [ ! -f "$BASE" ]; then
    echo "$NAME ok: храповика ещё нет (novac-corpus.baseline отсутствует — Э1)"
    exit 0
fi
RUN="$ROOT/scripts/tools/novac-diff-corpus.sh"
if ! sh "$RUN" > "$T/corpus.out" 2>&1; then
    echo "$NAME: FAIL — корпусный прогон красный:" >&2
    tail -10 "$T/corpus.out" >&2
    exit 1
fi
NUMS=$(grep '^novac-diff-corpus baseline-numbers:' "$T/corpus.out")
cm=$(echo "$NUMS" | sed -n 's/.*contract-match=\([0-9]*\).*/\1/p')
bm=$(echo "$NUMS" | sed -n 's/.*behavior-match=\([0-9]*\).*/\1/p')
base_cm=$(tr -d '\r' < "$BASE" | sed -n 's/^contract-match \([0-9]*\)$/\1/p')
base_bm=$(tr -d '\r' < "$BASE" | sed -n 's/^behavior-match \([0-9]*\)$/\1/p')
if [ -z "$cm" ] || [ -z "$bm" ] || [ -z "$base_cm" ] || [ -z "$base_bm" ]; then
    echo "$NAME: FAIL — не распарсил числа храповика (прогон: '$NUMS'; база: cm='$base_cm' bm='$base_bm')" >&2
    exit 1
fi
grep -E '^novac-diff-corpus: (файлов|поведенчески|цена)' "$T/corpus.out" | sed "s/^/$NAME: /"
# САМОСБОРКА ОБЯЗАНА ИДТИ ПАЧКОЙ (реестр 221.1 №1310). Раннер три недели не
# запускал пачку (`timeout 60 VAR=val` -> rc=127), уходил в пофайловый откат и
# печатал «ICE убил пачку» без ICE — а число `self-distance`, мера ступени 0.2,
# снималось не тем способом под батчевым именем. Откат законен только при
# настоящей смерти пачки, и тогда это не норма, а находка: краснота снимается
# ЧЕЛОВЕКОМ, причиной в NOVAC_SELFBUILD_FALLBACK_OK, и причина печатается здесь.
# Поля нет вовсе — формат раннера разошёлся со стражем: тоже красный, а не пропуск.
# С 2026-09-23 пачка идёт МОДУЛЯМИ (`batch-unit`, NOVAC_UNIT=1 — консенсус окна
# Карины и интегратора о мере 0.2): прежняя пофайловая пачка `batch` тоже не
# та мера, и молчаливый возврат к ней краснит так же, как откат.
smode=$(echo "$NUMS" | sed -n 's/.*self-mode=\([a-z-]*\).*/\1/p')
if [ "$smode" != "batch-unit" ]; then
    if [ -n "$smode" ] && [ -n "${NOVAC_SELFBUILD_FALLBACK_OK:-}" ]; then
        echo "$NAME: самосборка НЕ пачкой (self-mode=$smode) — принято по причине: $NOVAC_SELFBUILD_FALLBACK_OK"
    else
        echo "$NAME: FAIL — самосборка шла НЕ пачкой: self-mode=${smode:-<поля нет в строке раннера>} (реестр 221.1 №1310)." >&2
        echo "  Пачка умерла или не запустилась, и self-distance снят пофайлово — это другой вопрос под тем же именем." >&2
        echo "  Разбери причину по строке «самосборка (...)» выше; снять красноту — только причиной:" >&2
        echo "    NOVAC_SELFBUILD_FALLBACK_OK='<почему откат законен сейчас>'" >&2
        exit 1
    fi
fi
# ПРИНИМАЕТСЯ ЕДИНИЦА, А НЕ ФАЙЛ (реестр 221.1 №1350, 2026-09-25). Единица пачки —
# один модуль, один текст, а `novac/src/check/run.nv` типизирует текст только при
# чистом вердикте обхода. Один отказ обхода в ЛЮБОМ файле единицы выключает
# типизацию всей единицы, и её молчащие файлы не судил никто; мера, считавшая их
# принятыми, давала 79/108 при 0/16 чистых единиц. Раннер печатает по строке на
# единицу, и страж ПЕРЕСЧИТЫВАЕТ заголовок по ним: засчитать принятым файл
# единицы с диагностиками — красный, а не цифра. Полей нет — формат разошёлся,
# тоже красный.
if [ "$smode" = "batch-unit" ]; then
    su=$(echo "$NUMS" | sed -n 's/.*self-units=\([0-9]*\)\/\([0-9]*\).*/\1 \2/p')
    suf=$(echo "$NUMS" | sed -n 's/.*self-unit-files=\([0-9]*\)\/\([0-9]*\).*/\1 \2/p')
    if [ -z "$su" ] || [ -z "$suf" ]; then
        echo "$NAME: FAIL — в строке раннера нет self-units / self-unit-files (реестр 221.1 №1350):" >&2
        echo "  без счёта по единицам мера 0.2 снова считает принятыми файлы, которых никто не типизировал." >&2
        exit 1
    fi
    re_units=$(grep -c '^novac-diff-corpus self-unit: ' "$T/corpus.out" | tr -d '[:space:]')
    re_clean=$(grep '^novac-diff-corpus self-unit: ' "$T/corpus.out" | awk '$NF == 0' | wc -l | tr -d '[:space:]')
    re_files=$(grep '^novac-diff-corpus self-unit: ' "$T/corpus.out" | awk '$NF == 0 { s += $(NF-2) } END { print s + 0 }')
    # Not `set --`: that would overwrite the guard's own $1/$2 (root, binary).
    su_clean=${su%% *}; su_total=${su##* }
    suf_files=${suf%% *}
    if [ "$re_units" != "$su_total" ] || [ "$re_clean" != "$su_clean" ] || [ "$re_files" != "$suf_files" ]; then
        echo "$NAME: FAIL — счёт единиц не сходится со строками единиц (реестр 221.1 №1350):" >&2
        echo "  заголовок: единиц чисто $su_clean из $su_total, файлов в чистых $suf_files; по строкам: $re_clean из $re_units, файлов $re_files." >&2
        echo "  Файл единицы, в которой есть диагностики, засчитан принятым — его никто не типизировал." >&2
        exit 1
    fi
    echo "$NAME: самосборка по единицам: чисто $su_clean из $su_total, файлов в чистых $suf_files — пересчитано по строкам единиц"
fi
# Cost ratchet (P14): the corpus run's wall must stay within its budget.
wall_ms=$(sed -n 's/^novac-diff-corpus: цена прогона.*стена \([0-9]*\)ms.*/\1/p' "$T/corpus.out")
bud_ms=$(tr -d '\r' < "$ROOT/scripts/guards/novac-iteration-cost.baseline" 2>/dev/null | sed -n 's/^diff-corpus-ms \([0-9]*\)$/\1/p')
# Бюджет масштабируется загрузкой машины (274.3/F10, общая дверь
# lib/novac.sh): абсолютная стена под полным прогоном гейта даёт 146с
# против 50с на тихой машине — без поправки это ложный красный.
if [ -n "$wall_ms" ] && [ -n "$bud_ms" ]; then
    scale=$(novac_load_scale "$ROOT")
    ebud_ms=$(( bud_ms * scale / 100 ))
    if [ "$wall_ms" -gt "$ebud_ms" ]; then
        echo "$NAME: FAIL — ПРОСАДКА цены дифф-раннера: ${wall_ms}мс > бюджет ${bud_ms}мс (с поправкой на загрузку ${ebud_ms}мс, калибровка x${scale}/100; П14)" >&2
        exit 1
    fi
    echo "$NAME: цена дифф-раннера ${wall_ms}мс при бюджете ${ebud_ms}мс (калибровка x${scale}/100)"
fi
# --- Монотонность САМОГО файла базы (адверсарная проверка 2026-08-17) ------
# Храповик сверял ПРОГОН с файлом и ни разу — файл с его историей. Значит
# откат делался в одну строку: опусти число в базе, и прогон снова "== база",
# зелено. Ратчет, который можно отпустить рукой, — не ратчет. Сравниваем с
# версией файла в HEAD; допускается только рост.
BFILE="$ROOT/scripts/guards/novac-corpus.baseline"
HEAD_B=$(git -C "$ROOT" show "HEAD:scripts/guards/novac-corpus.baseline" 2>/dev/null || true)
if [ -n "$HEAD_B" ]; then
    for key in contract-match behavior-match; do
        was=$(printf '%s\n' "$HEAD_B" | sed -n "s/^$key[[:space:]][[:space:]]*\([0-9][0-9]*\).*/\1/p" | head -1)
        now=$(sed -n "s/^$key[[:space:]][[:space:]]*\([0-9][0-9]*\).*/\1/p" "$BFILE" 2>/dev/null | head -1)
        [ -n "$was" ] && [ -n "$now" ] || continue
        if [ "$now" -lt "$was" ]; then
            # Законный откат ОБЪЯВЛЯЕТСЯ строкой, называющей ИМЕННО этот переход
            # (2026-08-20). До этого дня страж требовал объяснения и не читал
            # ни одного: значит законного отката не существовало, а текст обещал
            # путь, которого не открывал. Маркер с числами нельзя оставить
            # работать наперёд — он покрывает один переход, и следующее
            # уменьшение без своей строки снова красное.
            if grep -qE "^#[[:space:]]*RATCHET-DOWN[[:space:]]+$key[[:space:]]+$was[[:space:]]*->[[:space:]]*$now([^0-9]|\$)" "$BFILE"; then
                echo "$NAME: откат объявлен: $key $was -> $now (строка RATCHET-DOWN в базе)"
            else
                echo "$NAME: FAIL — база ОПУЩЕНА рукой: $key было $was, стало $now (§10.4: числа могут только расти)" >&2
                echo "  Законный откат объявляется строкой в самом файле базы:" >&2
                echo "    # RATCHET-DOWN $key $was -> $now (<дата>, <причина>)" >&2
                echo "  Числа в строке обязаны совпасть с переходом — разрешение и есть запись." >&2
                exit 1
            fi
        fi
    done
fi


if [ "$cm" -lt "$base_cm" ] || [ "$bm" -lt "$base_bm" ]; then
    echo "$NAME: FAIL — ОТКАТ храповика: contract $cm (база $base_cm), behavior $bm (база $base_bm)" >&2
    exit 1
fi
if [ "$cm" -gt "$base_cm" ] || [ "$bm" -gt "$base_bm" ]; then
    echo "$NAME: FAIL — прогресс без поднятия базы: contract $cm (база $base_cm), behavior $bm (база $base_bm)." >&2
    echo "  Подними числа в scripts/guards/novac-corpus.baseline ТЕМ ЖЕ коммитом (§10.4)." >&2
    exit 1
fi
echo "$NAME ok: ИТОГ ВСЕХ ТРЁХ ЭТАПОВ — храповик корпуса: contract $cm, behavior $bm (== база)"
exit 0
