#!/bin/sh
# scripts/guards/check-novac-effects-at-door.sh — способности (эффекты)
# живут только у двери novac.
#
# ПРАВИЛО (конвенция П15 «Контекст компиляции — данные на ресивере; эффект —
# только способность», docs/dev/novac-compiler-conventions.md; та же линия —
# план 274 §2 и архитектура novac §1 «компилятор сам ничего не читает»):
# дверь novac ровно одна — novac/src/main.nv, и в ней стоит
# `with Fs = real_fs(), Os = real_os() { ... }`. Всё, что ниже двери (sem,
# check, parse, lex, emit_c, diag, tree, source, names, builtins, pipeline),
# обязано быть чистыми функциями над переданными данными: не объявляет
# эффектов, не ставит обработчиков, не носит эффектов в сигнатурах.
#
# ЗАЧЕМ СТРАЖ. Эффект, просочившийся ниже двери, ничего не ломает в момент
# появления: сборка зелёная, тесты зелёные — просто «чистый» проход стал
# способен лезть в мир, и через полгода он туда лезет. Аудит механизмов
# 2026-08-16: П15 была единственной строкой конвенции без стража и без
# честной пометки «немашинное». Этот страж закрывает её машинную половину.
#
# ПРОВЕРЯЕТ по $SRC/**/*.nv (тесты *_test.nv включительно — они тоже ниже
#   двери; сам $SRC/main.nv не судится вовсе, там дверь и стоять эффектам
#   положено):
#   1) установку обработчика — `with <Имя> = ...`;
#   2) объявление эффекта — `type <Имя> effect {`;
#   3) эффект в сигнатуре — имя эффекта в СТРОКЕ ЭФФЕКТОВ, то есть между
#      `)` списка параметров и `->` / `{` / `=>` / концом строки:
#      `fn read_decls(dir str) Fs -> []str`, `fn @close() Net {`.
#      Ряд разделён пробелами и может быть длиннее одного имени
#      (`fn main() Fs Os -> ()`), а имя — нести аргументы типа
#      (`Fs Fail[IoError] -> ()`). Судится любая строка, а не только та,
#      где есть слово `fn`: у сигнатуры, разбитой на строки, закрывающая
#      скобка сидит либо отдельно, либо в хвосте последнего параметра, а у
#      метода протокола или эффекта слова `fn` нет вовсе.
#   Имена эффектов не выдуманы и не зашиты: берутся грепом
#   `export type <Имя> effect` из $PRELUDE/*.nv, плюс Fs и Os (эти двое
#   живут в std/src/fs и std/src/os, но дверь novac держит именно их).
#   Прелюдии нет или в ней ноль эффектов — честная строка в stderr, и суд
#   идёт только по Fs/Os.
# НЕ ПРОВЕРЯЕТ (сказано честно):
#   * комментарии и строковые литералы — не судятся вовсе. Фикстура теста
#     novac ЕСТЬ текст на Nova: `fn f() Fs -> int` внутри кавычек — это
#     входные данные компилятора, а не способность модуля. Цена решения:
#     эффект, склеенный в строке и выполненный через eval, страж не увидит —
#     eval'а в Nova нет, цена нулевая.
#   * эффекты, объявленные вне прелюдии (например `Net` из std/src/net): в
#     словаре имён их нет, значит форма 3 их пропустит. Формы 1 и 2 их
#     увидят — объявление и обработчик судятся по форме, а не по имени.
#   * семантику: вызов функции, которая сама объявлена с эффектом в другом
#     модуле, страж не раскрутит — это работа компилятора, не грепа.
#   * саму дверь: что именно main.nv делает со своими Fs/Os — приёмка.
#
# $1 — корень репозитория (по умолчанию вычисляется от себя);
# $2 — override сканируемой директории (шов самотеста; default $ROOT/novac/src);
# $3 — override каталога прелюдии (шов самотеста; default $ROOT/std/src/prelude).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
PRELUDE="${3:-$ROOT/std/src/prelude}"
NAME=check-novac-effects-at-door
DOOR=main.nv

# Страж до кода легален: novac ещё может не существовать.
if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi
SRC=$(cd "$SRC" && pwd) || exit 1

T="${TMPDIR:-/tmp}/novac-effects-at-door.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

# --- словарь имён эффектов -------------------------------------------------
# Fs и Os — дверь novac; остальные имена вычитываются из прелюдии, чтобы
# список не был памятью автора стража: зашитый список отстаёт молча (№519).
{ echo Fs; echo Os; } > "$T/eff"
: > "$T/pre"
if [ -d "$PRELUDE" ]; then
    cat "$PRELUDE"/*.nv 2>/dev/null | tr -d '\r' \
        | sed -n 's/^[[:space:]]*export type \([A-Z][A-Za-z0-9_]*\)[[:space:]][[:space:]]*effect.*$/\1/p' \
        > "$T/pre"
fi
NPRE=$(grep -c . < "$T/pre")
if [ "$NPRE" -eq 0 ]; then
    echo "$NAME: прелюдия не прочитана ($PRELUDE): ни одного 'export type <Имя> effect' — сужу только по Fs/Os" >&2
fi
cat "$T/pre" >> "$T/eff"
sort -u "$T/eff" > "$T/eff.sorted"
NEFF=$(grep -c . < "$T/eff.sorted")
EFFECTS=$(tr '\n' ' ' < "$T/eff.sorted")

# --- что судим -------------------------------------------------------------
find "$SRC" -type f -name '*.nv' | sort > "$T/files"
NFILES=$(grep -c . < "$T/files")
if [ "$NFILES" -eq 0 ]; then
    echo "$NAME ok: судить нечего (нет *.nv под $SRC)"
    exit 0
fi
if [ ! -f "$SRC/$DOOR" ]; then
    echo "$NAME: FAIL — дверь $SRC/$DOOR не найдена, а всё правило П15 держится на ней" >&2
    echo "  Либо дверь переехала — тогда почини DOOR в этом страже той же волной," >&2
    echo "  либо её снесли — тогда эффекты стоят где попало, и чинить надо код." >&2
    echo "  Молча судить novac без двери страж не станет: он бы вечнозеленел (№519)." >&2
    exit 1
fi
NJUDGED=$((NFILES - 1))

# --- разбор ----------------------------------------------------------------
# Комментарии, строковые и символьные литералы вырезаются ДО суда. Строка
# бывает многострочной (фикстуры тестов novac такие и есть), поэтому
# состояние instr живёт между строками одного файла; а символьный литерал с
# кавычкой внутри (лексер сравнивает байт открывающей кавычки) иначе увёл бы
# разбор в вечную строку — и страж ослеп бы молча.
# Один запуск awk на всё дерево, а не по процессу на файл: на Windows запуск
# процесса дороже самого разбора, и страж в гейте должен стоить секунды.
: > "$T/bad"
set --
while IFS= read -r f; do
    [ -n "$f" ] || continue
    [ "$f" = "$SRC/$DOOR" ] && continue
    set -- "$@" "$f"
done < "$T/files"
if [ "$#" -gt 0 ]; then
    awk -v EFFECTS="$EFFECTS" '
    function clean(s,   out, i, c, k, found, L) {
        out = ""; i = 1; L = length(s)
        while (i <= L) {
            c = substr(s, i, 1)
            if (instr) {                                   # внутри строкового литерала
                if (c == "\\") { i += 2; continue }
                if (c == "\"") { instr = 0 }
                i++
                continue
            }
            if (c == "/" && substr(s, i + 1, 1) == "/") break   # комментарий до конца строки
            if (c == "\"") { instr = 1; i++; continue }
            if (c == Q) {                                  # символьный литерал вида (x as u8)
                found = 0
                for (k = i + 1; k <= i + 4 && k <= L; k++) {
                    if (substr(s, k, 1) == "\\") { k++; continue }
                    if (substr(s, k, 1) == Q) { found = k; break }
                }
                if (found) { out = out " "; i = found + 1; continue }
            }
            out = out c
            i++
        }
        return out
    }
    BEGIN {
        n = split(EFFECTS, e, " ")
        for (i = 1; i <= n; i++) if (e[i] != "") eff[e[i]] = 1
        Q = sprintf("%c", 39)
    }
    FNR == 1 { instr = 0 }   # новый файл — новое состояние: строка не течёт через границу
    {
        line = $0
        sub(/\r$/, "", line)
        cl = clean(line)
        # Имя вырезается из НАЙДЕННОГО куска, а не отрезанием от строки:
        # gawk на `^.*[^A-Za-z0-9_]type` молча не находит там, где находит
        # `[^A-Za-z0-9_]type` — и нарушитель тогда зовётся «export».
        # 1. установка обработчика
        if (match(cl, /(^|[^A-Za-z0-9_])with[[:space:]]+[A-Z][A-Za-z0-9_]*[[:space:]]*=/)) {
            h = substr(cl, RSTART, RLENGTH)
            sub(/^[^A-Za-z0-9_]*with[[:space:]]+/, "", h)
            sub(/[[:space:]]*=$/, "", h)
            printf "%s:%d: обработчик \`with %s = ...\` ниже двери\n", FILENAME, FNR, h
        }
        # 2. объявление эффекта
        if (match(cl, /(^|[^A-Za-z0-9_])type[[:space:]]+[A-Z][A-Za-z0-9_]*[[:space:]]+effect([[:space:]]*\{|[[:space:]]*$)/)) {
            h = substr(cl, RSTART, RLENGTH)
            sub(/^[^A-Za-z0-9_]*type[[:space:]]+/, "", h)
            sub(/[[:space:]]+effect[[:space:]]*\{?[[:space:]]*$/, "", h)
            printf "%s:%d: объявление эффекта \`type %s effect\` ниже двери\n", FILENAME, FNR, h
        }
        # 3. строка эффектов: имена между `)` списка параметров и
        # `->` / `=>` / `{` / концом строки.
        # Ряд разделён ПРОБЕЛАМИ, а не запятыми: `fn main() Fs Os -> ()`
        # (examples/effects/serde_fs_build.nv:21). Запятая в этой позиции —
        # выдумка: рядов из двух и более эффектов в дереве 51, все через
        # пробел, запятых ноль. Имя вдобавок носит аргументы типа —
        # `Fail[IoError]`, `Cache[str, int]`, 162 такие сигнатуры, — и одна
        # квадратная скобка рвала ряд целиком: в `) Fs Fail[IoError] ->`
        # терялся и Fail, и стоящий перед ним Fs (std/src/fs/fs.nv:326).
        # Судится ЛЮБАЯ строка, а не только с `fn` или начатая с `)`:
        # у многострочной сигнатуры закрывающая скобка сидит в хвосте
        # последнего параметра (`cfg PropertyConfig) Random Fail[E] -> ()`,
        # std/src/testing/property.nv:363), а у метода протокола или эффекта
        # слова `fn` нет вовсе (`@generate() Random -> T`, там же:87).
        # Ложных тревог ширина не даёт: прогон по всем 3728 .nv дерева БЕЗ
        # словаря вернул в этой позиции 28 имён, и все 28 — эффекты.
        rest = cl
        while (match(rest, /\)[[:space:]]+[A-Z]/)) {
            row = substr(rest, RSTART + RLENGTH - 1)   # с первой заглавной
            rest = substr(rest, RSTART + RLENGTH)
            nn = 0
            closed = 0
            while (1) {
                # ряд обязан кончиться стрелкой, телом или концом строки:
                # иначе это не сигнатура, а выражение, и судить его нечем
                if (row ~ /^[[:space:]]*(->|=>|\{)/ || row ~ /^[[:space:]]*$/) { closed = 1; break }
                if (!match(row, /^[[:space:]]*,?[[:space:]]*[A-Z][A-Za-z0-9_]*/)) break
                L2 = RLENGTH
                tok = substr(row, 1, L2)
                row = substr(row, L2 + 1)
                sub(/^[[:space:]]*,?[[:space:]]*/, "", tok)
                # аргументы типа: одного уровня вложенности хватает на всё,
                # что есть в дереве (`Repo[Vec[int]]` — предел)
                if (match(row, /^\[[^][]*(\[[^][]*\][^][]*)*\]/)) row = substr(row, RLENGTH + 1)
                nn++
                enames[nn] = tok
            }
            if (closed)
                for (j = 1; j <= nn; j++)
                    if (enames[j] in eff)
                        printf "%s:%d: эффект \`%s\` в сигнатуре функции ниже двери\n", FILENAME, FNR, enames[j]
        }
    }
    ' "$@" > "$T/bad"
fi

if [ -s "$T/bad" ]; then
    echo "$NAME: FAIL — способности ниже двери (конвенция П15, дверь — $SRC/$DOOR):" >&2
    sed 's/^/  /' "$T/bad" >&2
    echo "  Чинить так: обработчик и объявление остаются в $DOOR — и только там" >&2
    echo "  стоит 'with Fs = real_fs(), Os = real_os()', а модуль ниже получает УЖЕ" >&2
    echo "  прочитанные данные параметром и возвращает результат значением." >&2
    echo "  Плуминг снимается РЕСИВЕРОМ ('type Checker { src, ctx, out }' и методы @walk)," >&2
    echo "  а не амбиентностью: подменяемое на границе — способность, вычисленное нами" >&2
    echo "  же и только читаемое — данные (П15.3)." >&2
    exit 1
fi

echo "$NAME ok: файлов ниже двери $NJUDGED, способностей вне двери 0 (имён эффектов в словаре: $NEFF)"
exit 0
