#!/usr/bin/env bash
# check-expect-marker-colon.sh — реестр 221.1 №942(в).
#
# ПРАВИЛО, которое этот страж наконец делает механическим. `AGENTS.md` говорит
# дословно: «No colon after the marker name — the colon would become part of the
# matched substring; the corpus never uses that form». Правило было верным, было
# записано, и его никто не проверял.
#
# ЧТО ЭТО СТОИЛО, замер 2026-09-05. Пять пиров `spec_tests/conformance/` писали
# `// EXPECT_STDOUT: ok`, то есть просили подстроку `: ok`. Своя их строка вывода —
# «ok» без двоеточия — под неё не подходила. Подходила ЧУЖАЯ: тест в другом файле
# называется «ok-path НЕ триггерит Fail handler…», харнесс печатает
# `  PASS: ok-path …`, и вот в этой строке двоеточие есть. Вердикт пяти файлов
# держался на ИМЕНИ постороннего теста; переименуй тот тест — и пять фикстур
# краснеют без единой причины в себе.
#
# Вместе с №942(а) (маркер пира подменял вердикт всего CU) это глушило 6207
# `assert` в 1168 файлах. Опечатка в один символ и была тем, что делало дыру
# рабочей.
#
# ХРАПОВИКА ЗДЕСЬ НЕТ НАМЕРЕННО: у этой формы нет ни одного законного применения,
# и на момент заведения в дереве ноль носителей (все шесть исправлены тем же
# слиянием). База, разрешающая «исторические», разрешала бы ровно то, что стоило
# нам вечера.
set -u
export LC_ALL=C
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
ROOT="${1:-$(cd "$SCRIPT_DIR/../.." && pwd)}"

# Только корпусы, где маркеры что-то значат. `docs/` исключён: там форма
# цитируется В ПРОЗЕ — этим самым файлом в том числе, — и страж, читающий прозу
# как данные, краснел бы на собственном объяснении (класс уже знаком: страж
# считает процитированный в тексте маркер настоящим).
DIRS=""
for d in spec_tests std examples nova_tests; do
    [ -d "$ROOT/$d" ] && DIRS="$DIRS $ROOT/$d"
done
[ -n "$DIRS" ] || { echo "expect-marker-colon ok: корпусов нет, судить нечего"; exit 0; }

# `EXPECT_<ИМЯ>:` — двоеточие сразу за именем маркера. Ищем в комментариях `.nv`.
hits="$(grep -rnE '^[[:space:]]*//[[:space:]]*EXPECT_[A-Z_]+:' --include='*.nv' $DIRS 2>/dev/null || true)"

if [ -n "$hits" ]; then
    echo "EXPECT-MARKER-COLON FAIL: маркер с двоеточием — форма, запрещённая AGENTS.md (реестр №942в):" >&2
    echo "$hits" | while IFS= read -r line; do echo "  $line" >&2; done
    echo "" >&2
    echo "ПОЧЕМУ это не придирка: двоеточие уходит В ИСКОМУЮ ПОДСТРОКУ." >&2
    echo "  \`// EXPECT_STDOUT: ok\` просит не «ok», а «: ok» — и совпадает с ЧУЖОЙ" >&2
    echo "  строкой харнесса вида \`PASS: ok-…\`, то есть с именем другого теста." >&2
    echo "КАК НАДО: убрать двоеточие — \`// EXPECT_STDOUT ok\`." >&2
    echo "  А если файл — пир folder-module с \`test\`-блоками и без \`fn main\`," >&2
    echo "  маркер там вообще лишний: вердикт даёт харнесс, а маркер пира" >&2
    echo "  становится требованием ко ВСЕМУ compile unit (№942)." >&2
    exit 1
fi
echo "expect-marker-colon ok: маркеров с двоеточием нет"
