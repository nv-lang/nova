# -*- coding: utf-8 -*-
"""scripts/guards/check-script-eol-pinned.py — файл, который ИСПОЛНЯЮТ или
РАЗБИРАЮТ ПОСТРОЧНО, обязан иметь закреплённые окончания строк (заведён 2026-09-07).

Дом правила: `.gitattributes` (правило заведено 2026-08-18 после падения двух
стражей на CI с `syntax error near unexpected token $'do\\r'`).
Дом работы: `docs/plans/275-gate-cost.md` (план 275 — применение конвенции к
`scripts/gate.sh` и стражам дерева); форма стража задана интегратором 2026-09-07.

ЗАМЕР, РАДИ КОТОРОГО ЗАВЕДЁН. 2026-09-07: `core.autocrlf = true`, а `.gitattributes`
крепил `*.sh` и не крепил `*.py` — python-стражей в дереве 99. Первый же чистый
чекаут отдал бы их CRLF, и `check-guard-honesty` покраснел бы на всех разом, ПО
ОКРУЖЕНИЮ, а не по существу. Дыра не срабатывает у того, кто её заложил: файлы уже
лежат на диске как LF, checkout их не трогает, и локально зелено сколь угодно долго.

ПОЧЕМУ СТРАЖ, А НЕ ПРАВКА `.gitattributes`. Правка закрыла носителя. Замер КЛАССА
после неё нашёл ещё 48 незакреплённых файлов, и среди них `scripts/githooks/*` —
шелл-скрипты БЕЗ РАСШИРЕНИЯ, исполняемые git'ом на каждом коммите: правило
ключевалось по `.sh` и их не видело. Их поломка выглядела бы как «git сломался».
Следующий страж на новом языке открыл бы дыру снова.

ПОЧЕМУ СВОЙСТВО, А НЕ ЧИСЛО (форма — требование интегратора, довод его же).
«Незакреплённых не больше 36» — снимок дерева: он устареет на законном тридцать
седьмом `*.md` и потребует правки константы вместо разбора, а главное — пропустит
ПОДМЕНУ: сняли крепление с `githooks`, добавили исключённый `.md`, число сошлось,
мина вернулась. Поэтому судится свойство: закреплено ВСЁ, кроме перечисленных ниже
КЛАССОВ исключений, у каждого — причина.

ИСКЛЮЧЕНИЯ — КЛАССАМИ И С ПРИЧИНОЙ, а не списком путей: список из 36 имён устаревал
бы так же, как число, и прятал бы подмену внутри себя.

РОДСТВО С `check-mixed-eol`, чтобы ни одного из двух не сняли как лишний.
Тот судит СОДЕРЖИМОЕ файлов в рабочем дереве (смешанные окончания внутри
одного файла, №442) — то есть СЛЕДСТВИЕ, уже лежащее на диске. Этот судит
АТРИБУТ, то есть ПРИЧИНУ: файл, приехавший чекаутом ОДНОРОДНО CRLF,
для соседа не «смешанный» и проходит его проверку, а shell и awk на нём ломаются.

ИСПОЛЬЗОВАНИЕ:
    python scripts/guards/check-script-eol-pinned.py [КОРЕНЬ]
"""
import os
import subprocess
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace", newline="\n")
sys.stderr.reconfigure(encoding="utf-8", errors="replace", newline="\n")

NAME = "check-script-eol-pinned"

# Каталоги, где живут исполняемые и построчно разбираемые файлы гейта.
ROOTS = ["scripts", ".claude"]

# КЛАССЫ ИСКЛЮЧЕНИЙ. Ключ — расширение (или имя файла), значение — ПРИЧИНА.
# Добавление сюда — сознательный акт: без причины запись не принимается ревью,
# а причина «пока не дошли руки» означает, что файл надо крепить, а не исключать.
EXEMPT = {
    ".md": u"проза: CRLF ей безразличен, а крепление тронуло бы чекаут всей документации",
    ".ps1": u"PowerShell — виндовый инструмент, CRLF для него родной",
    ".json": u"JSON допускает оба окончания; файл читает не наш гейт",
    ".gdb": u"скрипты отладчика, запускаются руками при разборе падения",
    ".c": u"эксперименты для компилятора C, который принимает оба окончания",
}


def collect(root):
    files = []
    for d in ROOTS:
        base_dir = os.path.join(root, d)
        if not os.path.isdir(base_dir):
            continue
        for base, dirs, names in os.walk(base_dir):
            if os.sep + ".git" + os.sep in base + os.sep:
                continue
            for n in sorted(names):
                rel = os.path.relpath(os.path.join(base, n), root)
                files.append(rel.replace("\\", "/"))
    return drop_ignored(root, sorted(files))


def drop_ignored(root, files):
    """(продолжение доки ниже; сперва — ловушка, найденная у СОСЕДА.)

    ВНИМАНИЕ ТОМУ, КТО РАСШИРИТ `ROOTS`. Этот приём применён и в
    `mixed-eol-scan.py`, и там 2026-09-08 он оказался МЁРТВЫМ: путь внутри
    ПОДМОДУЛЯ заставляет `git check-ignore --stdin` вернуть 128
    (`fatal: Pathspec '...' is in submodule`), ОДИН такой путь убивает весь
    вызов, и запасная ветка «при ошибке не выбрасывать ничего» честно не
    отсекала НИЧЕГО — замер: кандидатов 7339, оставлено 7339.

    Здесь этого не случается только потому, что `ROOTS` — `scripts/` и
    `.claude/`, а подмодуль лежит в `compiler-codegen/nova_rt/libuv`. Добавишь
    корень, достающий до подмодуля, — сперва перенеси сюда отсев подмодулей из
    `mixed-eol-scan.py`, иначе правка станет мёртвой МОЛЧА, а страж будет
    выглядеть починенным.
    """
    """Выбросить то, что git ИГНОРИРУЕТ — СГЕНЕРИРОВАННОЕ, а не исходное.

    ЗАЧЕМ (правка интегратора 2026-09-07, в день заведения стража). На дереве
    интегратора страж нашёл 213 «нарушений», и ВСЕ они — внутри
    `.claude/cargo-target/` (156 МБ вывода cargo, `.gitignore:75` — `.claude/*`).
    У того, у кого этот каталог пуст, страж зелён; у того, кто собирал, —
    красен. То есть вердикт зависел от СРЕДЫ, а не от предмета — нарушение Г7
    конвенции гейтов тем самым стражем, который заводился ради соседнего класса.

    Спрашиваем ОДНИМ процессом (Г2), вход БАЙТАМИ — по той же причине, что
    в `attrs` ниже: текстовый режим допишет `\r` и замер испортится сам собой.
    Код возврата `check-ignore`: 0 — есть игнорируемые, 1 — нет ни одного,
    128 — ошибка; при ошибке НЕ выбрасываем ничего (лучше ложный отказ,
    чем тихая зелень на пустом списке).
    """
    if not files:
        return files
    proc = subprocess.run(
        ["git", "-C", root, "check-ignore", "--stdin"],
        input=("\n".join(files) + "\n").encode("utf-8"), capture_output=True)
    if proc.returncode not in (0, 1):
        return files
    ignored = set(proc.stdout.decode("utf-8", "replace").split("\n"))
    return [f for f in files if f not in ignored]


def attrs(root, files):
    """`eol` для каждого пути одним процессом.

    ВХОД ПЕРЕДАЁТСЯ БАЙТАМИ НАМЕРЕННО: в текстовом режиме Python на Windows
    дописывает `\\r` к каждой строке, git ищет путь `gate.sh\\r`, не находит и
    отвечает `unspecified` — замер закреплений окончаний строк оказывается испорчен
    окончаниями строк. Поймано на себе 2026-09-07: первый прогон дал «591 из 591
    незакреплён», и заметно это стало лишь потому, что прямой `check-attr` говорил
    про `.sh` обратное. Разошлись два замера — расхождение и есть ответ.
    """
    proc = subprocess.run(
        ["git", "-C", root, "check-attr", "--stdin", "eol"],
        input=("\n".join(files) + "\n").encode("utf-8"), capture_output=True)
    out = proc.stdout.decode("utf-8", "replace")
    got = {}
    for line in out.splitlines():
        parts = line.rsplit(": ", 2)
        if len(parts) == 3:
            got[parts[0]] = parts[2]
    return got, proc.returncode


def main():
    root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
    files = collect(root)

    if not files:
        sys.stderr.write(
            u"%s: FAIL — под %s не найдено НИ ОДНОГО файла.\n"
            % (NAME, u" и ".join(ROOTS)))
        sys.stderr.write(
            u"  Это отказ, а не зелень: проверка, которой нечего судить, молчит так "
            u"же, как исправная. Переехали каталоги — почини перечень, а не выводы.\n")
        return 1

    got, rc = attrs(root, files)

    # АССЕРТ ПОЛНОТЫ ОТВЕТА: git обязан ответить про столько же путей, сколько
    # спросили. Без него порча входа (см. `attrs`) читается как «всё незакреплено»
    # или, хуже, как «всё в порядке» — в зависимости от того, что именно потерялось.
    if rc != 0 or len(got) != len(files):
        sys.stderr.write(
            u"%s: FAIL — git ответил про %d путей из %d (код %d).\n"
            % (NAME, len(got), len(files), rc))
        sys.stderr.write(
            u"  Неполный ответ означает, что судить нечем: скорее всего испорчен вход "
            u"(перевод строк в текстовом режиме) или путь вне репозитория.\n")
        return 1

    bad = []
    exempt_n = 0
    for f in files:
        ext = os.path.splitext(f)[1].lower()
        name = os.path.basename(f)
        if ext in EXEMPT or name in EXEMPT:
            exempt_n += 1
            continue
        if got.get(f) != "lf":
            bad.append((f, ext or u"(без расширения)"))

    if bad:
        sys.stderr.write(
            u"%s: FAIL — исполняемые или построчно разбираемые файлы без "
            u"закреплённых окончаний строк: %d\n" % (NAME, len(bad)))
        for f, ext in bad[:20]:
            sys.stderr.write(u"    %s   [%s]\n" % (f, ext))
        if len(bad) > 20:
            sys.stderr.write(u"    ... и ещё %d\n" % (len(bad) - 20))
        sys.stderr.write(
            u"  При `core.autocrlf=true` следующий чекаут отдаст их CRLF, и стражи "
            u"покраснеют ПО ОКРУЖЕНИЮ, а не по существу — причём не у того, кто это "
            u"допустил: файлы уже лежат на диске как LF.\n"
            u"  Чинится ОДНИМ из двух: крепи в `.gitattributes` (`<шаблон> text "
            u"eol=lf`) либо, если файл машинами не разбирается, заведи КЛАСС "
            u"исключения в EXEMPT этого стража — с причиной, а не с молчанием.\n")
        return 1

    print(u"%s ok: файлов под %s — %d, исключено классами %d, "
          u"незакреплённых 0" % (NAME, u"/".join(ROOTS), len(files), exempt_n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
