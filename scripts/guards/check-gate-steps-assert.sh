#!/usr/bin/env bash
# scripts/guards/check-gate-steps-assert.sh
# Шаг гейта обязан предъявить свою строку, а не только код возврата.
#
# ДОМ И ОСНОВАНИЕ: правило П1 №4 «гейт-фильтр обязан ассертить строку
# PASS/FAIL; не рапортовать счёт, которого не видел» (разрешение владельца
# завести стража — 2026-08-14); реестр 221.1 №645, №647.
#
# ЗАЧЕМ. Носитель измерен, а не предположен: шаг «секреты в дереве» проходил
# вхолостую из-за двух литеральных символов вместо переноса строки — страж
# получал не тот корень, честно печатал «git не отдал списка файлов», и гейт
# засчитывал ноль. Починка одной строки классом не является: при заведении
# этого стража в гейте нашлись ЕЩЁ ДВА места той же формы (шаги про мохибейк и
# про повторы в планах). Они шли не вхолостую по случайности — оба стража
# лишний аргумент игнорируют, — но форма была та же, и первый же страж с
# другим порядком аргументов сделал бы их слепыми.
#
# ТРИ СВОЙСТВА:
#   1. в командных строках скриптов нет литеральной пары «слэш+n» («слэш+t»)
#      вместо настоящего переноса — кавычки при разборе снимаются, поэтому
#      `printf '%s\n'` законен, а `bash страж.sh "$ROOT" \n || fail` — нет;
#   2. каждый страж зовётся из гейта через обёртку `guard`, а не голым
#      `bash`/`python`: обёртка требует в выводе строку `ok:`;
#   3. каждый страж, вызываемый гейтом, в принципе способен эту строку
#      напечатать (в исходнике есть `ok:`) — иначе шаг красен навсегда.
#
# ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ — `check-ci-status.sh`: он законно может ничего не
# проверить (прогонов CI на коммите ещё нет), и честный ответ «нечего
# смотреть» не должен маскироваться под `ok:`. Исключение живёт ЗДЕСЬ списком,
# а не молчаливым согласием, и требует причины в комментарии рядом с вызовом.
#
# ЧЕГО НЕ ЛОВИТ (честно): шага, который печатает `ok:` не по делу. От вранья
# внутри стража механизм не спасает — он закрывает только вранье МОЛЧАНИЕМ,
# когда доказательства нет вовсе.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-gate-steps-assert.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-gate-steps-assert.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
GATE="$ROOT/scripts/gate.sh"
EXEMPT="check-ci-status.sh"

[ -f "$GATE" ] || { echo "check-gate-steps-assert: нет $GATE" >&2; exit 1; }

BAD=0

# --- 1. литеральная пара «слэш+n» вне кавычек --------------------------------
# Кавычки снимаются awk'ом, комментарии пропускаются целиком: в комментарии
# такая пара — рассказ о поломке, а не поломка (наступил при заведении, №647).
LIT=$(for f in "$ROOT"/scripts/*.sh "$ROOT"/scripts/guards/*.sh "$ROOT"/scripts/githooks/*; do
        [ -f "$f" ] || continue
        awk -v F="$f" '
            /^[[:space:]]*#/ { next }
            {
                line = $0
                gsub(/"[^"]*"/, "", line)
                gsub(/'"'"'[^'"'"']*'"'"'/, "", line)
                # За парой обязан идти ПРОБЕЛ или конец строки: именно так
                # выглядит подмена переноса (`… "$ROOT" \n    || fail`).
                # Иначе в находки лезут регулярки `[ \t]` внутри многострочных
                # awk-программ — кавычки там открыты на предыдущей строке, и
                # снять их построчно нельзя. Пять таких ложных срабатываний
                # были получены при заведении стража, до сужения признака.
                if (line ~ /\\[nt]([[:space:]]|$)/) printf "%s:%d\n", F, NR
            }' "$f"
      done)
LIT_N=$(printf '%s\n' "$LIT" | grep -c . || true); LIT_N=${LIT_N:-0}
if [ "$LIT_N" -gt 0 ]; then
    echo "check-gate-steps-assert: литеральная пара «слэш+n/t» вместо переноса строки — $LIT_N" >&2
    printf '%s\n' "$LIT" | head -10 | sed 's/^/    /' >&2
    echo "    Оболочка отдаст её команде как аргумент 'n', и шаг проверит не то." >&2
    BAD=1
fi

# --- 2. вызов стража мимо обёртки guard --------------------------------------
RAW=$(grep -nE '^[[:space:]]*([A-Z_][A-Z0-9_]*=[^[:space:]]+[[:space:]]+)*(bash|python)[[:space:]]+"\$ROOT/scripts/guards/' "$GATE" \
      | grep -v "$EXEMPT" || true)
RAW_N=$(printf '%s\n' "$RAW" | grep -c . || true); RAW_N=${RAW_N:-0}
if [ "$RAW_N" -gt 0 ]; then
    echo "check-gate-steps-assert: стражи зовутся мимо обёртки guard — $RAW_N" >&2
    printf '%s\n' "$RAW" | head -10 | sed 's/^/    /' >&2
    echo "    Замени 'bash \"\$ROOT/scripts/guards/X\"' на 'guard \"\$ROOT/scripts/guards/X\"':" >&2
    echo "    голый вызов засчитывает ноль без доказательства (реестр №645)." >&2
    BAD=1
fi

# --- 4. обёртка стоит в позиции аргумента чужой команды ----------------------
# `guard` — ФУНКЦИЯ оболочки. Внешняя программа (`with-deadline.sh`, `timeout`,
# `xargs`) её не найдёт и упадёт с «No such file or directory» — а шаг при этом
# отрапортует отказ по СВОЕЙ причине из `|| fail`, то есть соврёт о том, что
# именно сломалось. Так 2026-08-14 три шага гейта разом сообщили о дефектах
# дерева, которых не было: инвариант на честном слове, кириллица в коммитах и
# несобираемый флагман. Ни одного из них не существовало.
#
# Признак точный: строка НАЧИНАЕТСЯ с `guard`, а предыдущая заканчивается
# обратным слэшем — значит обёртка стоит аргументом продолженной команды.
# Предел времени задаётся флагом `guard --deadline N`, а не обёрткой снаружи.
ARG=$(awk '
    prev ~ /\\$/ && $0 ~ /^[[:space:]]*guard[[:space:]]/ { printf "gate.sh:%d\n", NR }
    { prev = $0 }' "$GATE")
ARG_N=$(printf '%s\n' "$ARG" | grep -c . || true); ARG_N=${ARG_N:-0}
if [ "$ARG_N" -gt 0 ]; then
    echo "check-gate-steps-assert: обёртка guard стоит аргументом чужой команды — $ARG_N" >&2
    printf '%s\n' "$ARG" | head -10 | sed 's/^/    /' >&2
    echo "    guard — функция оболочки; внешняя команда её не найдёт." >&2
    echo "    Предел времени задаётся так: guard --deadline 300 \"\$ROOT/…\"" >&2
    BAD=1
fi

# --- 3. страж не способен напечатать свою строку -----------------------------
# ПЕРИМЕТР — ВЕСЬ НАБОР, а не только вызываемое гейтом (указание владельца
# 2026-08-14). Первая редакция проверяла лишь стражей из `gate.sh`, и это
# оставляло дыру ровно того же вида, что чинится: страж, вызываемый хуком или
# CI, мог молча возвращать ноль, и никто бы не заметил. Замер при расширении:
# из 46 стражей строку не печатали три — два починены тут же, третий (см.
# EXEMPT) законно ничего не проверяет.
MUTE=""
# Расширение НЕ часть личности стража: с 2026-08-19 они переезжают на
# python (П14), и глоб по .sh молча перестал бы судить переехавших.
for g in "$ROOT"/scripts/guards/check-*.sh "$ROOT"/scripts/guards/check-*.py "$ROOT"/scripts/guards/*ratchet*.sh; do
    [ -f "$g" ] || continue
    b="$(basename "$g")"
    [ "$b" = "$EXEMPT" ] && continue
    grep -q 'ok:' "$g" || MUTE="$MUTE $b"
done
if [ -n "$MUTE" ]; then
    echo "check-gate-steps-assert: страж не печатает строку 'ok:' и потому не сможет доказать шаг —$MUTE" >&2
    echo "    Добавь в успешный выход строку вида '<имя> ok: <что именно проверено>'." >&2
    BAD=1
fi

if [ "$BAD" -ne 0 ]; then
    echo "    Правило: П1 №4 (не рапортовать того, чего не видел); реестр 221.1 №645, №647." >&2
    echo "check-gate-steps-assert: FAIL" >&2
    exit 1
fi

echo "check-gate-steps-assert ok: каждый шаг гейта требует от стража его собственную строку"
exit 0
