#!/bin/sh
# scripts/guards/check-novac-emission-size.sh — храповик на объём C, который
# выдаёт novac (план 274.2 §1б.2; владелец 2026-08-17: «согласен, где это
# записано, когда сделаем, страж есть?» — стража не было).
#
# ЗАЧЕМ. Раздувание эмиссии — главный резерв скорости сборки: замер того же
# дня даёт у оракула 47 192 строки C на 5 381 строку .nv (×7.6), и лишь 7 %
# из них — собственный код, остальное — библиотека, вкомпилированная в каждую
# единицу трансляции. novac обязан быть лучше, но «обязан быть лучше» без
# числа не проверяется никак. Число здесь.
#
# ПРОВЕРЯЕТ: для каждого файла базы `novac-emission.baseline` эмиссия novac
#   даёт РОВНО столько строк, сколько записано. Больше — рост, требующий
#   объяснения в коммите; меньше — база протухла и её надо опустить той же
#   волной, иначе следующий рост до прежней цифры пройдёт молча (храповик в
#   обе стороны, как у поверхности и у корпуса).
# НЕ ПРОВЕРЯЕТ: эмиссию оракула (не наша земля); долю собственного кода —
#   она станет числом на Э2-б2, когда появится mono и будет что делить.
#
# $1 — корень; $2 — override базы (шов самотеста); $3 — override novac.
# env NOVAC_EMISSION=0 — пропустить (дешёвая выборка; гейт гоняет всегда).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
BASE="${2:-$ROOT/scripts/guards/novac-emission.baseline}"
NOVAC="${3:-$ROOT/novac/target/novac.exe}"
NAME=check-novac-emission-size

if [ "${NOVAC_EMISSION:-1}" = "0" ]; then
    echo "$NAME ok: пропущено по NOVAC_EMISSION=0"
    exit 0
fi
[ -f "$BASE" ] || { echo "$NAME: FAIL — нет базы $BASE: сверять не с чем (класс №519)" >&2; exit 1; }
if [ ! -f "$NOVAC" ]; then
    echo "$NAME: FAIL — нет бинаря $NOVAC: эмиссию нечем померить, а молчать нельзя (класс №519)" >&2
    exit 1
fi

BAD=""
N=0
while IFS=' ' read -r name want; do
    case "$name" in ''|'#'*) continue ;; esac
    src="$ROOT/examples/basics/$name.nv"
    [ -f "$src" ] || { BAD="$BAD
  $name — файла $src нет: база протухла"; continue; }
    got=$(NOVA_STD_PATH="$ROOT/std/src" "$NOVAC" emit "$src" 2>/dev/null | wc -l | tr -d '[:space:]')
    N=$((N+1))
    if [ "$got" != "$want" ]; then
        BAD="$BAD
  $name — $got строк C, в базе $want"
    fi
done < "$BASE"

if [ "$N" -eq 0 ]; then
    echo "$NAME: FAIL — база пуста: сверять нечего (класс №519)" >&2
    exit 1
fi
if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — объём эмиссии novac разошёлся с базой (274.2 §1б.2):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Рост — сознательное решение: подними базу ТЕМ ЖЕ коммитом и назови" >&2
    echo "  в сообщении, откуда лишние строки. Падение — опусти базу, иначе" >&2
    echo "  следующий рост до прежней цифры пройдёт молча." >&2
    exit 1
fi

echo "$NAME ok: файлов $N, объём эмиссии совпадает с базой"
exit 0
