#!/usr/bin/env bash
# check-no-manual-status-table.sh — машинный страж против реинтродукции ручной
# сводной индекс-таблицы статусов планов в docs/plans/README.md.
#
# Почему: индекс-таблица статусов в README дублирует пофайловый `**Статус:**`
# и неизбежно дрейфует (прецедент: застряла на редакции 2026-07-03, занижая
# статусы 180/202/203/204/205/206 — снято 2026-07-13). Правило зафиксировано
# в docs/dev/conventions-governance.md («Статус плана — только пофайлово»).
#
# Единственный источник статуса — строка `**Статус:**` в docs/plans/NNN-*.md;
# сводка — сгенерированный docs/plans/STATUS.md (bash scripts/tools/gen-plan-status.sh).
#
# Часть семейства машинных стражей плана 231 «Выход из цикла точечных
# фиксов» (docs/plans/231-bug-cycle-exit.md, трек Д «машинное принуждение
# норм» — конвенция без гейта дрейфует; docs/plans/231.2-enforcement-infra.md
# — исполнительный дом трека Д); сама норма (не сама проверка) объявлена
# в docs/dev/conventions-governance.md, а не в плане 231 — план 231 её не
# формулирует, только требует, чтобы у КАЖДОЙ конвенции такого рода был
# машинный страж.
#
# Сигнатура ручного статус-реестра: строка markdown-таблицы вида
#   | 123 | [foo.md](foo.md) | ... | ✅ ЗАКРЫТ ... |
# т.е. первая колонка — число (план), где-то в строке — ссылка на .md-файл
# плана, и в строке встречается один из статус-эмодзи (✅/📋/🟡/🔴/⏸/⛔/🟣).
# ИСПОЛЬЗОВАНИЕ: scripts/guards/check-no-manual-status-table.sh [корень-репы]
# Без аргумента — своя репа; аргумент нужен самотесту (фикстуры).
# Коды: 0 — чисто, 1 — найдена ручная статус-таблица.
# План: docs/plans/231-bug-cycle-exit.md §4в (трек Ж); правило —
# docs/dev/conventions-governance.md, «Статус плана — только пофайлово».
#
# Порог N=3 — одна-две случайные строки с похожим видом (напр. цитата/пример
# в тексте) не считаются реестром; ≥3 подряд-похожих строки = таблица.

set -euo pipefail

# LC_ALL=C — байтовый grep: в ru_RU.UTF-8 Git Bash grep НЕ матчит астральные
# (4-байтовые) символы — 🟡/🔴/📋 давали 0 хитов при корректных байтах в файле
# (✅ 3-байтовый матчился — потому порог «3 строки» тихо не добирался).
# Поймано селфтестом в gate.sh 2026-08-01; тот же класс, что check-doc-hygiene.
export LC_ALL=C
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
# Скрипт живёт в scripts/guards/ — корень репы на два уровня выше.
REPO_ROOT="${1:-$(cd "$SCRIPT_DIR/../.." && pwd)}"  # аргумент — для самотеста на фикстурах
README="$REPO_ROOT/docs/plans/README.md"
THRESHOLD=3

if [ ! -f "$README" ]; then
  # Нет файла — нечего проверять (не наша забота здесь).
  exit 0
fi

# Строка похожа на ряд ручного статус-реестра:
#   начинается с "| <число...>", содержит markdown-ссылку "[...](....md)"
#   и один из статус-эмодзи где-то в строке.
STATUS_EMOJI='✅|📋|🟡|🔴|⏸|⛔|🟣'

hits="$(grep -cE "^\|[[:space:]]*[0-9]+[0-9.]*[[:space:]]*\|.*\]\([^)]*\.md\).*\|.*(${STATUS_EMOJI})" "$README" || true)"
hits="${hits:-0}"

if [ "$hits" -ge "$THRESHOLD" ]; then
  echo "check-no-manual-status-table.sh: ОШИБКА — найдено $hits строк(и), похожих на ручную" >&2
  echo "сводную индекс-таблицу статусов планов в $README." >&2
  echo "Рукописная статус-таблица ЗАПРЕЩЕНА (см. docs/dev/conventions-governance.md," >&2
  echo "раздел «Статус плана — только пофайлово, ручная сводная таблица запрещена»)." >&2
  echo "Статус ведётся ТОЛЬКО пофайлово (**Статус:** в docs/plans/NNN-*.md);" >&2
  echo "сводка — сгенерированный docs/plans/STATUS.md (bash scripts/tools/gen-plan-status.sh)." >&2
  exit 1
fi

echo "check-no-manual-status-table.sh: OK ($hits подозрительных строк, порог $THRESHOLD)"
