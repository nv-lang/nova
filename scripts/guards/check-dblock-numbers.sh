#!/usr/bin/env bash
# Номер D-блока занят ДВАЖДЫ — и увидеть это надо ДО слияния, а не на нём.
#
# ЗАЧЕМ. За сутки 2026-09-20 номер D478 оказался занят ТРЕМЯ окнами. Шаг
# `D-number uniqueness` в `gate.sh` берёт заголовки СВОЕГО дерева и к чужим
# веткам слеп ПО ПОСТРОЕНИЮ: блок, живущий в неслитой ветке соседа, в выборку
# не попадает вовсе. Поэтому столкновение находилось в момент слияния — когда
# правка стоит дороже всего: у влитого блока десяток файлов, строка реестра и
# каталог проб с номером В ИМЕНИ.
#
# ПОЧЕМУ НЕ ХУК НА СЛИЯНИИ. Приходящая сторона видна РАНЬШЕ слияния: окна делят
# один `.git`, значит чужие ветки лежат в нём уже сейчас и читаются
# `for-each-ref` + `git show <ветка>:<файл>`. Проверка на слиянии была бы вторым
# рубежом, и слабым: `merge --no-commit` плюс отдельный коммит обходит
# `pre-merge-commit` молча (замер по соседнему хуку). Здесь первый рубеж —
# обход веток, доступный любому окну в любой прогон.
#
# ЧТО СУДИТСЯ, три проверки:
#   1. один номер в ДВУХ местах с разными заголовками — отказ, названы оба;
#   2. номер выдан в `spec/decisions/ISSUED-NUMBERS.md` одной ветке, а стоит в
#      другой — отказ: выдача разошлась с исполнением;
#   3. номер выдан, а блока с ним нет нигде — ПРЕДУПРЕЖДЕНИЕ, не отказ: его
#      могли выдать час назад и ещё не написать.
#
# ЧТО ЭТОТ СТРАЖ НЕ ДЕЛАЕТ НАМЕРЕННО: не чинит и не предлагает замен. Скрипт
# перенумерации у окна 283 съел собственный след — заменил `(ex-D478,` на
# `(ex-D482,`, то есть уничтожил ровно ту запись, ради которой перенумерация
# делалась, и проверка «старого номера не осталось» показала ЗЕЛЁНОЕ, потому
# что порча выглядит как успех. Страж, который только НАЗЫВАЕТ места, этого
# класса лишён по построению.
#
# И он ищет ЗАГОЛОВКИ, а не вхождения текста: хеш коммита `d478e72a` под форму
# `^## D<N>` не подходит, так что слепая ловля хешей исключена тем же.
#
# ЗНАМЕНАТЕЛЬ ПЕЧАТАЕТСЯ: сколько веток осмотрено, сколько блоков и строк
# таблицы прочитано. Ноль нарушений при нуле осмотренного — это не «чисто».
#
# usage: check-dblock-numbers.sh [КОРЕНЬ] [ДОП-ССЫЛКА ...]
#   ДОП-ССЫЛКА — например `MERGE_HEAD` или имя чужой ветки: добавляется к
#   обходу. Без аргументов берутся все локальные ветки общего `.git`.
set -u
export LC_ALL=C

NAME="check-dblock-numbers"
ROOT="${1:-.}"
[ $# -gt 0 ] && shift
EXTRA_REFS="$*"
cd "$ROOT" 2>/dev/null || { echo "$NAME: нет каталога $ROOT" >&2; exit 2; }

git rev-parse --git-dir >/dev/null 2>&1 || {
    echo "$NAME ok: судить нечего (не git-дерево)"; exit 0; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
PAIRS="$TMP/pairs"    # <номер> <место> <заголовок>
: > "$PAIRS"

# ЕДИНСТВЕННЫЙ ДОМ РАЗБОРА ЗАГОЛОВКА. Форма выстрадана дважды в `gate.sh`
# (реестр №123: точка ИЛИ тире; №771: `(NEW)` и скобка), и вторая копия
# разошлась бы на первой же правке. Поэтому разбор живёт ЗДЕСЬ, а шаг гейта
# зовёт этот страж.
# Метка места подставляется AWK-переменной, а не в текст выражения: имя ветки
# содержит `/` (`repro/699-…`), и `sed "s/…/…$1/"` на таком имени разваливается —
# поймано первым же прогоном, сорок строк «unknown option to `s'».
extract() {   # stdin: текст файла; $1 — метка места
    awk -v lbl="$1" '
        /^#{2,3} *D[0-9]+/ {
            if (match($0, /^#+ *D[0-9]+ *(NEW)? *(\([^)]*\))? *(\.|—)/)) {
                head = substr($0, RSTART, RLENGTH)
                num = head
                sub(/^#+ *D/, "", num)
                sub(/[^0-9].*$/, "", num)
                rest = substr($0, RSTART + RLENGTH)
                gsub(/^[ \t]+|[ \t]+$/, "", rest)
                print num " " lbl " " rest
            }
        }'
}

BLOCKS=0
# `ISSUED-NUMBERS.md` ИЗ ВЫБОРКИ ЗАГОЛОВКОВ ИСКЛЮЧЁН НАМЕРЕННО: это реестр брони,
# он ГОВОРИТ о номерах, а не объявляет их. Страж, считающий текст про свой
# предмет частью предмета, ловит сам себя — интегратор наступил на это сегодня
# трижды (цитата имени поля создала второе поле), и здесь тот же капкан стоял бы
# ровно на файле, ради которого страж и пишется.
SKIP_BASENAME="ISSUED-NUMBERS.md"

add_from_worktree() {
    for f in spec/decisions/*.md; do
        [ -f "$f" ] || continue
        [ "$(basename "$f")" = "$SKIP_BASENAME" ] && continue
        extract "дерево:$(basename "$f")" < "$f" >> "$PAIRS"
    done
}

# --- ПРОВЕРКА 0: номер занят ДВАЖДЫ В ОДНОМ ДЕРЕВЕ ---------------------------
# Это ровно то, что делал шаг `D-number uniqueness` в `gate.sh`. Переезд обязан
# сохранить вердикт: страж, который тихо ослабил проверку, хуже дубля.
own_tree_dupes() {
    local out=""
    for f in spec/decisions/*.md; do
        [ -f "$f" ] || continue
        [ "$(basename "$f")" = "$SKIP_BASENAME" ] && continue
        extract "own" < "$f"
    done | awk '{print $1}' | sort -n | uniq -d
}

add_from_ref() {   # $1 — ссылка
    local ref="$1" files f
    files=$(git ls-tree -r --name-only "$ref" -- spec/decisions 2>/dev/null \
            | grep '\.md$' || true)
    [ -n "$files" ] || return 0
    for f in $files; do
        git show "$ref:$f" 2>/dev/null | extract "$ref:$(basename "$f")" >> "$PAIRS"
    done
}

# СУДИТСЯ НЕ «НОМЕР ЕСТЬ В ДВУХ ВЕТКАХ», А «ВЕТКА ЕГО ДОБАВИЛА».
#
# Первая редакция сравнивала заголовки под одним номером по всем веткам и
# кричала на КАЖДЫЙ влитый блок: один и тот же D228 лежит в восьми ветках, и это
# норма, а не столкновение. Хуже: у `D430` в старой ветке заголовок отличался
# одним словом (`try_to_<T>` против `to_<T>`) — то есть правка ТЕКСТА читалась
# как занятый дважды номер. Признак был не тот.
#
# Верный признак берётся у истории: ветка ДОБАВИЛА заголовок, которого нет в
# точке расхождения с `main`. Три окна, каждое ЗАВЕДШЕЕ `## D478`, различаются
# этим, а влитый блок — нет, он у всех общий.
BASE_REF="${NOVA_DBLOCK_BASE:-main}"
git rev-parse --verify -q "$BASE_REF" >/dev/null 2>&1 || BASE_REF="HEAD"
add_from_ref "$BASE_REF"          # то, что уже занято общей историей
sed -i "s/^\([0-9]*\) $BASE_REF:/\1 БАЗА($BASE_REF):/" "$PAIRS" 2>/dev/null || true

REFS=$(git for-each-ref --format='%(refname:short)' refs/heads 2>/dev/null)
NREFS=0
for r in $REFS $EXTRA_REFS; do
    git rev-parse --verify -q "$r" >/dev/null 2>&1 || continue
    [ "$r" = "$BASE_REF" ] && continue
    NREFS=$((NREFS + 1))
    # Заголовки, ДОБАВЛЕННЫЕ этой веткой относительно точки расхождения.
    git diff "$BASE_REF...$r" -- spec/decisions 2>/dev/null \
        | grep -E "^\+#{2,3} *D[0-9]+" \
        | sed -E "s/^\+//" \
        | extract "$r" >> "$PAIRS"
done
# Добавленное САМИМ рабочим деревом (ещё не закоммиченное) — тоже сторона.
git diff "$BASE_REF" -- spec/decisions 2>/dev/null \
    | grep -E "^\+#{2,3} *D[0-9]+" | sed -E "s/^\+//" \
    | extract "дерево(незакоммиченное)" >> "$PAIRS"
BLOCKS=$(grep -c . "$PAIRS" || true)

# --- таблица выданных номеров ------------------------------------------------
TABLE="spec/decisions/ISSUED-NUMBERS.md"
ISSUED="$TMP/issued"   # <номер> <ветка-из-таблицы>
: > "$ISSUED"
NTABLE=0
if [ -f "$TABLE" ]; then
    # Строки таблицы вида `| D480 | предмет | окно / ветка | … |`.
    grep -E "^\| *D[0-9]+ *\|" "$TABLE" \
        | sed -E "s/^\| *D([0-9]+) *\|[^|]*\|([^|]*)\|.*/\1 \2/" \
        | sed -E "s/[[:space:]]+$//" >> "$ISSUED"
    NTABLE=$(grep -c . "$ISSUED" || true)
fi

# ЗНАМЕНАТЕЛЬ ПЕЧАТАЕТСЯ ЦЕЛИКОМ, и отдельной величиной — сколько заголовков
# ДОБАВЛЕНО ветками. Именно они и судятся; ноль добавленных означает «судить
# было нечего», а не «столкновений нет», и читатель обязан это различать.
NADDED=$(awk '$2 !~ /^БАЗА\(/ {c++} END{print c+0}' "$PAIRS")
echo "$NAME: осмотрено веток $NREFS, заголовков D-блоков $BLOCKS (из них ДОБАВЛЕНО ветками $NADDED), строк таблицы $NTABLE"
if [ "$NADDED" -eq 0 ]; then
    echo "$NAME: добавленных ветками заголовков НЕТ — судить нечего (это не «чисто»)"
fi

FAILED=0

OWN_DUPES=$(own_tree_dupes)
if [ -n "$OWN_DUPES" ]; then
    FAILED=1
    echo "$NAME: дублирующиеся номера D-блоков В ЭТОМ ДЕРЕВЕ: $(echo "$OWN_DUPES" | tr '\n' ' ')" >&2
fi

# --- 1. один номер в двух местах с РАЗНЫМИ заголовками -----------------------
# Столкновение = номер, ДОБАВЛЕННЫЙ кем-то, и при этом либо уже занятый базой,
# либо добавленный ещё кем-то. Оба случая — отказ, и в отказе названы все места.
ADDED_NUMS=$(awk '$2 !~ /^БАЗА\(/ {print $1}' "$PAIRS" | sort -n -u)
for n in $ADDED_NUMS; do
    PLACES=$(awk -v n="$n" '$1==n {print $2}' "$PAIRS" | sort -u)
    NPLACES=$(printf '%s\n' "$PLACES" | grep -c . || true)
    [ "${NPLACES:-0}" -le 1 ] && continue
    FAILED=1
    echo "$NAME: НОМЕР D$n ЗАНЯТ ДВАЖДЫ:" >&2
    awk -v n="$n" '$1==n {printf "    %s\n", $0}' "$PAIRS" | sort -u | head -8 >&2
done

# --- 2. таблица против дерева ------------------------------------------------
while read -r num branch; do
    [ -n "${num:-}" ] || continue
    WHERE=$(awk -v n="$num" '$1==n {print $2}' "$PAIRS" | sort -u | tr '\n' ' ')
    [ -n "$WHERE" ] || continue
    case "$WHERE" in
        *"$branch"*) : ;;
        *)
            # Ветка из таблицы записана как «окно / ветка»; сверяем вхождением
            # ПОСЛЕДНЕГО слова, чтобы `nova-78 / d480-ref-type-spelling` сошлось
            # с `d480-ref-type-spelling:03-syntax.md`.
            B=$(printf '%s' "$branch" | awk '{print $NF}' | tr -d '`')
            case "$WHERE" in
                *"$B"*) : ;;
                *)
                    FAILED=1
                    echo "$NAME: D$num ВЫДАН «$branch», а блок стоит в: $WHERE" >&2
                    ;;
            esac
            ;;
    esac
done < "$ISSUED"

# --- 3. выдан, но нигде не написан — предупреждение --------------------------
while read -r num branch; do
    [ -n "${num:-}" ] || continue
    if ! awk -v n="$num" '$1==n {found=1} END{exit !found}' "$PAIRS"; then
        echo "$NAME: D$num выдан («$branch»), но блока с ним нет ни в одной ветке — не отказ, но проверь"
    fi
done < "$ISSUED"

if [ "$FAILED" -ne 0 ]; then
    echo "$NAME: FAIL" >&2
    exit 1
fi
echo "$NAME ok: столкновений номеров нет, таблица сходится с ветками"
exit 0
