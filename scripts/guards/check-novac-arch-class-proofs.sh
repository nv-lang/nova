#!/bin/sh
# scripts/guards/check-novac-arch-class-proofs.sh — три доказательства у каждого
# решения класса в архитектуре novac.
#
# ПРАВИЛО (план 274.1, приёмка; требование владельца 2026-08-14): раздел
# «Классы проблем» в docs/dev/novac-architecture.md обязан существовать, и
# КАЖДЫЙ класс в нём несёт три доказательства — **Верность:**, **Место:**,
# **Минимальность:**. Решение без любого из трёх приёмку не проходит.
#
# Страж проверяет СТРУКТУРУ (маркеры на месте), не содержательность — тот же
# честный уровень, что у аудита по классу дефекта: вопрос нельзя пропустить
# молча, а качество ответа остаётся на приёмке (норма 254).
#
# Класс = заголовок '### К<N>.' внутри раздела. Блок класса — до следующего
# '###' или '## '. Ноль классов при существующем разделе — зелено (раздел
# заполняется; пустота видна приёмке 274.1, а не стражу).
#
# Аргумент $1 — корень репозитория (по умолчанию — вычислить от себя);
# $2 — override пути файла (для самотеста).
#
# Проверялся: Windows (Git Bash), 2026-08-14.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
DOC="${2:-$ROOT/docs/dev/novac-architecture.md}"

if [ ! -f "$DOC" ]; then
    echo "check-novac-arch-class-proofs: FAIL — нет $DOC" >&2
    exit 1
fi

if ! grep -q '^## .*Классы проблем' "$DOC"; then
    echo "check-novac-arch-class-proofs: FAIL — в архитектуре нет раздела «Классы проблем»" >&2
    echo "  Требование приёмки 274.1: раздел обязан существовать (владелец 2026-08-14)." >&2
    exit 1
fi

BAD=$(awk '
    /^## .*Классы проблем/ { in_sec=1; next }
    in_sec && /^## /       { in_sec=0 }
    in_sec && /^### К[0-9]/ {
        if (cls != "") check()
        cls=$0; v=0; m=0; mi=0; next
    }
    in_sec && cls != "" {
        if ($0 ~ /\*\*Верность:\*\*/)      v=1
        if ($0 ~ /\*\*Место:\*\*/)         m=1
        if ($0 ~ /\*\*Минимальность:\*\*/) mi=1
    }
    function check() {
        if (!v || !m || !mi) {
            printf "  %s — не хватает:%s%s%s\n", cls, (v?"":" Верность"), (m?"":" Место"), (mi?"":" Минимальность")
            bad++
        }
    }
    END { if (cls != "") check(); exit bad > 0 ? 0 : 0 }
' "$DOC")

if [ -n "$BAD" ]; then
    echo "check-novac-arch-class-proofs: FAIL — классы без полного набора доказательств:" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Каждому классу: **Верность:** (почему решение убивает класс)," >&2
    echo "  **Место:** (модуль/слои карты), **Минимальность:** (что ломается" >&2
    echo "  при снятии каждого инварианта). План 274.1 §4." >&2
    exit 1
fi

N=$(awk '/^## .*Классы проблем/{s=1;next} s&&/^## /{s=0} s&&/^### К[0-9]/{n++} END{print n+0}' "$DOC")
echo "check-novac-arch-class-proofs ok: классов $N, у каждого все три доказательства"
exit 0
