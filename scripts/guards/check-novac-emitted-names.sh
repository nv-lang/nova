#!/bin/sh
# scripts/guards/check-novac-emitted-names.sh — у каждого C-имени, которое
# novac ПЕЧАТАЕТ, есть объявленный префикс, и префикс говорит, ЧЬЁ это имя
# (конвенция П24, вторая половина; владелец 2026-08-17: «есть какая-то
# система?» — система была, но нигде не записана).
#
# ГРАНИЦА, КОТОРУЮ ДЕРЖИТ ПРЕФИКС, — это ABI:
#   * `Nova_...` и `nova_...` — имена ОРАКУЛА и его рантайма: точки входа
#     методов std (`Nova_<Тип>_method_<имя>`), вход программы
#     (`nova_fn_main_impl`), аллокатор и печать (`nova_alloc`,
#     `nova_print_*`), проверяемая арифметика (`nova_int_checked_*`), `fmod`.
#     Мы их НЕ придумываем: совпадение с ними и есть ABI, и его отдельно
#     стережёт `check-novac-mangle-fixed-point`.
#   * `novac_...`, `NOVAC_...`, `_novac_...` — НАШИ имена, и приставка `c`
#     ровно затем, чтобы ничто выдуманное нами не столкнулось с рантаймом:
#     `novac_user_<имя>` (функции пользователя), `novac_make_<Сумма>_<Вариант>`
#     (конструкторы вариантов), `NOVAC_TAG_<Сумма>_<Вариант>` (константы
#     перечисления — заглавные по конвенции C), `_novac_tmp/scr/match/strlit`
#     (временные; ведущее подчёркивание значит «не имя пользователя»).
# Регистр не произволен: он говорит, ЧТО это в C — тип оракула сохраняет его
# регистр, константа перечисления заглавная, функция и локаль строчные.
#
# ПРОВЕРЯЕТ строковые литералы-идентификаторы в novac/src/sem/mangle.nv и
#   novac/src/emit_c/emit_c.nv: каждый начинается с одного из объявленных
#   префиксов ЛИБО стоит в списке известных исключений (ключевые слова C и
#   имена, которые не являются идентификаторами: `void`, `_`, слоты шаблона).
# НЕ ПРОВЕРЯЕТ: что имя оракула существует (это mangle-fixed-point);
#   содержимое оболочки (она снимается генератором).
#
# $1 — корень; $2 — override списка файлов (шов самотеста, через пробел).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
FILES="${2:-$ROOT/novac/src/sem/mangle.nv $ROOT/novac/src/emit_c/emit_c.nv}"
NAME=check-novac-emitted-names

T="${TMPDIR:-/tmp}/novac-names.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

: > "$T/names"
for f in $FILES; do
    [ -f "$f" ] || { echo "$NAME: FAIL — нет $f: судить нечего (класс №519)" >&2; exit 1; }
    grep -ohE '"[A-Za-z_][A-Za-z0-9_]*(\$\{[^}]*\})?[A-Za-z0-9_]*"' "$f" >> "$T/names"
done
sort -u "$T/names" > "$T/uniq"
N=$(wc -l < "$T/uniq" | tr -d '[:space:]')
if [ "$N" -eq 0 ]; then
    echo "$NAME: FAIL — не нашлось ни одного имени: разбор сломался (класс №519)" >&2
    exit 1
fi

BAD=""
while IFS= read -r q; do
    n=$(printf '%s' "$q" | sed 's/^"//;s/"$//')
    case "$n" in
        Nova_*|nova_*|novac_*|NOVAC_*|_novac_*) continue ;;         # объявленные пространства
        void|_|equal|fmod) continue ;;                              # C-ключевое, подстановочник, метод протокола, libm
        __NOVAC_BODY__|__NOVAC_STRLITS__) continue ;;                # слоты шаблона оболочки
        NOVA_UNIT) continue ;;                                       # константа рантайма
    esac
    BAD="$BAD
  $n — имя без объявленного пространства (Nova_/nova_ — оракул, novac_/NOVAC_/_novac_ — наше)"
done < "$T/uniq"

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — печатаемое C-имя вне объявленных пространств (П24):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Наше имя начинается с novac_/NOVAC_/_novac_ — приставка `c` затем, чтобы" >&2
    echo "  выдуманное нами не столкнулось с рантаймом. Имя оракула (Nova_/nova_) не" >&2
    echo "  выдумывают: его существование стережёт check-novac-mangle-fixed-point." >&2
    exit 1
fi

echo "$NAME ok: печатаемых имён: $N, все в объявленных пространствах"
exit 0
