#!/usr/bin/env bash
# scripts/guards/check-expect-markers.sh — неизвестный `EXPECT_*` в тесте.
# Реестр 221.1 №453 (часть 3) / №473 (вторая половина), план 221
# (docs/plans/221-release-v0-1.md).
#
# №453 (часть 3): `parse_expect`+соседи (`test_runner.rs`) знают РОВНО
# фиксированный набор имён, всё прочее молча падает в `None`/не распознаётся.
# Следствие: файл с опечаткой в маркере ЗЕЛЁН и не проверяет НИЧЕГО. Найдено
# аудитом 2026-08-08: в корпусе жили `EXPECT_OUTPUT` (5) и `EXPECT_RUN_OK` (3)
# — восемь фикстур-пустышек. Тем же классом (реестр 221.1 №463, окно p463):
# `EXPECT_LINT_WARNING` изобретён БЕЗ реализации в раннере — добавлен в
# белый список ОДНОВРЕМЕННО с реализацией в `test_runner.rs`
# (`ExpectMarker::LintWarning` + проверка в `run_one` через
# `lints::run_conv_rules`), не раньше.
#
# №473 (вторая половина, найдено при исправлении первой): раньше `KNOWN` был
# СТРОКОЙ РУКАМИ — третьей копией списка (раннер знает его сам, дока
# AGENTS.md/test-conventions.md называет его текстом, и страж держал СВОЮ
# копию) — то есть страж, поставленный ловить расхождение раннера и фикстур,
# сам был обречён разойтись с раннером тем же способом. Требование приёмки:
# «страж обязан ВЫВОДИТЬ список из исходника раннера, а не хранить копию».
# Полный вывод семантики (что именно `TestType` получает файл) через bash
# требует переисполнять Rust — недостижимо без сборки компилятора. Вместо
# этого список ИМЁН выводится синтаксически: каждое `EXPECT_*`, которое
# раннер распознаёт (через `strip_prefix`/`line.contains`), написано в
# `test_runner.rs` как ИЗОЛИРОВАННЫЙ строковый литерал — сама строка МЕЖДУ
# кавычками равна имени маркера (с необязательным `// ` перед ним, как у
# `EXPECT_TIMEOUT_MS` в `parse_timeout_ms`). Живая проба (2026-08-11):
# grep этого шаблона по `test_runner.rs` даёт РОВНО те же 11 имён, что были
# в ручной копии — вывод синтаксисом, а не совпадение вручную подобранных
# чисел. Тестовые фикстуры Rust (`fs::write(..., "// EXPECT_TIMEOUT\nfn ...")`)
# в выборку не попадают: в них ПОСЛЕ имени маркера внутри той же кавычки
# ещё текст, а не закрывающая кавычка сразу — шаблон требует имя БЫТЬ ВСЕМ
# содержимым литерала.
#
# Раннер молчит по построению, поэтому проверяем снаружи: любой `// EXPECT_*`,
# которого нет в выведенном списке, — красный гейт.
set -u
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
cd "$ROOT" || exit 1

# Источник истины — САМ раннер, найденный относительно расположения СТРАЖА
# (не $ROOT): страж кросс-репно не используется (не входит в GUARDS=
# scripts/tools/sync-guards-to-packages.sh), а $ROOT здесь — проверяемое
# дерево фикстур, которое в самотесте бывает синтетическим temp-каталогом
# без своего компилятора.
GUARD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_SRC="$GUARD_DIR/../../compiler-codegen/src/test_runner.rs"
if [ ! -f "$RUNNER_SRC" ]; then
    echo "check-expect-markers: не найден исходник раннера ($RUNNER_SRC) — список известных маркеров вывести неоткуда, страж не может проверять" >&2
    exit 1
fi
KNOWN="$(grep -ohE '"(// ?)?EXPECT_[A-Z_]+"' "$RUNNER_SRC" \
         | sed -E 's/^"(\/\/ ?)?//; s/"$//' | sort -u | paste -sd'|' -)"
if [ -z "$KNOWN" ]; then
    echo "check-expect-markers: из $RUNNER_SRC не вывелось НИ ОДНОГО имени EXPECT_* — страж сломан (регэксп разошёлся с исходником?), это ОТКАЗ, а не «маркеров нет»" >&2
    exit 1
fi

BAD=$(grep -rhoE '^[[:space:]]*//[[:space:]]*EXPECT_[A-Z_]+' \
        spec_tests std examples 2>/dev/null \
      | sed 's|.*//[[:space:]]*||' | sort -u | grep -vE "^($KNOWN)$")

if [ -n "$BAD" ]; then
    echo "check-expect-markers: НЕИЗВЕСТНЫЕ маркеры (раннер их МОЛЧА игнорирует):" >&2
    echo "$BAD" | sed 's/^/    /' >&2
    echo "    известные: $(echo "$KNOWN" | tr '|' ' ')" >&2
    echo "check-expect-markers: FAIL" >&2
    exit 1
fi
echo "check-expect-markers ok: неизвестных EXPECT_* нет"
exit 0
