# -*- coding: utf-8 -*-
"""scripts/guards/check-novac-no-undeclared-simplification.py — в Карине нет
НЕЗАЯВЛЕННЫХ упрощений.

ТРЕБОВАНИЕ ВЛАДЕЛЬЦА 2026-09-13, дословно: «каждый пункт плана 274 должен
делаться без упрощений ровно по спеке, как для прода».

План: docs/plans/274-novac-self-hosted-compiler.md (зонтик самохостинга) и
его подпланы; реестр 221.1 — дом строк, которыми заявляется законный долг.

ЧТО ЭТОТ СТРАЖ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ — это разные вещи, и вторая важнее.

  ДЕЛАЕТ: ловит маркер срезанного угла (TODO/FIXME/HACK/XXX, `todo()`,
  `unimplemented`, «not implemented», «упрощ», «для простоты», «пока что»,
  «заглушк»), НЕ СОПРОВОЖДЁННЫЙ ЗАЯВКОЙ — номером строки реестра, маркером
  `[M-…]`/`[INV-…]`, ссылкой на план или на D-блок.

  НЕ ДЕЛАЕТ: не судит, СООТВЕТСТВУЕТ ЛИ реализация спеке. Машина этого не
  может, и обещать это стражем — обман дороже отсутствующей проверки.
  Соответствие держат другие механизмы, и они названы здесь, чтобы никто не
  принял зелёный вердикт этого стража за «сделано по спеке»: корпусный
  дифференциал (`novac-diff-corpus.sh`), фикстуры с `nova:expect`, проба в обе
  стороны и приёмка волны, записанная в плане.

ПОЧЕМУ НЕ «САМОАТТЕСТАЦИЯ». Напрашивалась строка в сообщении коммита вида
«подтверждаю: без упрощений». Такая проверка судит НАМЕРЕНИЕ автора, а не
дерево, и превращается в ритуал с первого же дня: подпись ставится не думая,
потому что её требует механизм, а не предмет. Здесь судится СЛЕД: если угол
срезан и это честно помечено — маркер есть, и он обязан нести заявку.

ПОЧЕМУ ЭТО НЕ НОВОЕ ПРАВИЛО, А ЕГО МЕХАНИЗАЦИЯ. `AGENTS.md` (Defects and
tests) уже говорит: «Found a defect → file it … A marker in code with no entry
is invisible debt». Правило было, механизма не было. Второго дома не заводится:
дом правила — `AGENTS.md`, здесь только исполнение.

НУЛЕВАЯ ТЕРПИМОСТЬ, И ЭТО ИЗМЕРЕНО, А НЕ ЗАЯВЛЕНО. Замер 2026-09-13 по
`novac/**`: маркеров всего ЧЕТЫРЕ, и все четыре заявлены. Дерево уже на нуле,
поэтому храповик не нужен — страж кусает только НОВОЕ. Если бы долг был, нужна
была бы база: страж, краснеющий на всей истории, отключается первым же окном.

СУДИТ `novac/**` — дерево Карины. Оракул не судится: у него своя история и свои
строки реестра, и распространять требование на него — отдельное решение
владельца, а не следствие этого.

$1 — корень; $2 — override каталога (шов самотеста).
"""
import os
import pathlib
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace", newline="\n")
sys.stderr.reconfigure(encoding="utf-8", errors="replace", newline="\n")

NAME = "check-novac-no-undeclared-simplification"

# Признаки срезанного угла. ОДНОЗНАЧНЫЕ: первая редакция ловила ещё
# `temporary`/`stub`, и замер показал 139 «нарушений», из которых сто с лишним
# были «временная переменная C» — термин предмета, а не упрощение. Страж,
# краснеющий на словаре предметной области, будет отключён, и правильно.
MARKERS = re.compile(
    r"\b(TODO|FIXME|HACK|XXX)\b"
    r"|\btodo\(\)"
    r"|\bunimplemented\b"
    r"|not\s+implemented"
    r"|упрощ|для\s+простоты|пока\s+что|заглушк",
    re.IGNORECASE | re.UNICODE)

# Заявка: строка реестра, плавающий маркер, маркер инварианта, план, D-блок.
# Пробел вместо точки в номере подплана (`274 9.1g.3`) — законная форма: так
# написан единственный живой маркер дерева, и ловить его было бы ложным отказом.
DECLARED = re.compile(
    r"№\s*\d{2,4}"
    r"|\[(?:M|INV)-[^\]]+\]"
    r"|\b\d{2,3}[ .]\d+(?:\.\d+)*[a-zа-я]*\b"
    r"|\bD\d{2,3}\b"
    r"|\bplan\s+\d{2,3}\b",
    re.IGNORECASE | re.UNICODE)

SUFFIXES = (".nv", ".toml")


def main():
    a = sys.argv
    root = pathlib.Path(a[1] if len(a) > 1 else ".").resolve()
    src = pathlib.Path(a[2]) if len(a) > 2 else root / "novac"

    if not src.is_dir():
        print("%s ok: судить нечего (нет %s)" % (NAME, src))
        return 0

    bad = []
    seen = 0
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for fn in sorted(filenames):
            if not fn.endswith(SUFFIXES):
                continue
            p = pathlib.Path(dirpath) / fn
            seen += 1
            try:
                text = p.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            for i, line in enumerate(text.split("\n"), 1):
                if MARKERS.search(line) and not DECLARED.search(line):
                    rel = p.relative_to(root) if str(p).startswith(str(root)) else p
                    bad.append((str(rel).replace("\\", "/"), i, " ".join(line.split())[:120]))

    if not bad:
        print("%s ok: файлов %d, незаявленных упрощений 0" % (NAME, seen))
        return 0

    sys.stderr.write("%s: FAIL — незаявленных упрощений: %d\n" % (NAME, len(bad)))
    for rel, i, line in bad[:20]:
        sys.stderr.write("    %s:%d\n        %s\n" % (rel, i, line))
    if len(bad) > 20:
        sys.stderr.write("    ... и ещё %d\n" % (len(bad) - 20))
    sys.stderr.write(
        "\n    Требование владельца 2026-09-13: пункты плана 274 делаются БЕЗ\n"
        "    упрощений, ровно по спеке, как для прода. Срезанный угол законен\n"
        "    только ЗАЯВЛЕННЫМ: в той же строке — номер строки реестра 221.1,\n"
        "    маркер `[M-…]`/`[INV-…]`, номер плана или D-блок.\n"
        "    Незаявленный маркер — невидимый долг (`AGENTS.md`, Defects and tests):\n"
        "    следующее окно его не найдёт, и он переживёт релиз.\n"
        "\n"
        "    ЧТО ЭТОТ СТРАЖ НЕ ПРОВЕРЯЕТ: соответствие реализации спеке. Его\n"
        "    зелёный вердикт НЕ означает «сделано по спеке» — это держат\n"
        "    корпусный дифференциал, фикстуры с `nova:expect` и приёмка волны.\n")
    return 1


if __name__ == "__main__":
    sys.exit(main())
