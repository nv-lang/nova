#!/bin/sh
# scripts/guards/check-novac-edge-payload.sh — колонка «что течёт» у КАЖДОГО
# ребра карты novac: ребро без объявленного контракта — красный.
#
# ПРАВИЛО И ОТКУДА. План docs/plans/274.1-novac-architecture.md §2в п.3:
# «ребро без объявленного "что течёт" — красный (дыра в карте, а не право по
# умолчанию)»; там же §2в: «таблица рёбер получает колонку "что течёт": ребро
# разрешает не просто "модуль A видит модуль B", а конкретный контракт данных
# по этому ребру». Сама карта docs/dev/novac-architecture.md §3 повторяет это
# инвариантом раздела: «рёбра только из таблицы, и каждое несёт контракт "что
# течёт"». Зонтик — план 274 §10.3/§10.3а (каждому правилу — свой страж).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СТРАЖ (аудит механизмов 2026-08-16). check-novac-deps.sh
# разбирает у строки таблицы §3 ровно две колонки — «из» и «в» — и честно
# пишет в своей шапке: «Что НЕ проверяет: направление данных "что течёт"».
# Значит вторая половина правила §3 держалась прозой: колонку можно было
# оставить пустой или прочеркнуть, и ВСЕ механизмы оставались зелёными.
# Ребро с пустым контрактом — это разрешение «A видит B» без ответа на вопрос
# ЧТО он оттуда берёт; ровно из такой дыры в 196 кодоген перевыводил типы мимо
# чекера. Здесь эта половина правила становится машинной.
#
# ПРОВЕРЯЕТ: в docs/dev/novac-architecture.md находит раздел «## 3.» и в нём —
#   таблицу markdown, в шапке которой есть колонка «что течёт» (номер колонки
#   берётся ИЗ ШАПКИ, а не зашит числом). Для каждой строки-ребра этой таблицы
#   ячейка «что течёт» обязана быть непустой и не быть заглушкой: пусто,
#   отсутствующая колонка, «-»/«--»/«—»/«–», «TBD», «TODO», «n/a», «?» —
#   красный с именем ребра и НОМЕРОМ СТРОКИ файла. «Пусто» считается ПОСЛЕ
#   снятия оформления, вертикальных черт, неразрывных пробелов и HTML-
#   комментариев: ячейка из одних `|`, из одного U+00A0 или из «<!-- позже -->»
#   рендерится ПУСТОЙ, значит пуста и для машины (иначе лишняя черта в строке
#   или комментарий вместо контракта прячут дыру — ложная зелень).
#   Строки внутри фенсед-блоков (``` / ~~~) рёбрами НЕ считаются: в §3
#   естественно показать пример «так нельзя», и судить иллюстрацию как
#   настоящее ребро — ложная краснота. Отдельно ассертит, что
#   шапка с колонкой найдена И что строк-рёбер под ней больше нуля:
#   переименованный раздел, переназванная колонка или опустевшая таблица
#   иначе сделали бы стража вечнозелёным (класс №519).
# НЕ ПРОВЕРЯЕТ: ПРАВДУ написанного в колонке (правда ли по ребру течёт именно
#   это — приёмка и ревью; машина умеет судить только наличие); соответствие
#   контракта импортам в коде и наличие самого ребра — это check-novac-deps.sh
#   (колонки «из»/«в»); таблицы вне раздела §3 и вне таблицы рёбер (строка
#   соседней таблицы или соседнего раздела ребром не считается); язык и
#   орфографию ячейки.
#
# $1 — корень репозитория (по умолчанию вычисляется от самого стража).
# $2 — override пути к файлу архитектуры (шов самотеста).
#
# Ветки «судить нечего» здесь НЕТ намеренно: сканируемой директории у стража
# нет, его мишень — один документ, и пропажа документа есть пропажа мишени, а
# не отсутствие работы (класс №519). Соседи по этому же файлу судят так же:
# check-novac-deps.sh и check-novac-arch-invariants.sh на отсутствующем
# docs/dev/novac-architecture.md красные.
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
ARCH="${2:-$ROOT/docs/dev/novac-architecture.md}"
NAME=check-novac-edge-payload

if [ ! -f "$ARCH" ]; then
    echo "$NAME: FAIL — нет $ARCH: карта рёбер пропала, судить «что течёт» не по чему (класс №519)" >&2
    exit 1
fi

T="${TMPDIR:-/tmp}/novac-edge-payload.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0
TAB=$(printf '\t')
# U+00A0: [:space:] под LC_ALL=C его не знает, а ячейка из одного неразрывного
# пробела (частый гость копипасты из отрендеренной таблицы) пуста для читателя.
NBSP=$(printf '\302\240')

# --- разбор таблицы рёбер --------------------------------------------------
# Вход нормализуется: CRLF снимается, табуляции внутри строк заменяются на
# пробел — табуляция служит разделителем полей МЕЖДУ awk и оболочкой, и в
# ячейке её быть не должно.
# Выход: строка «H<таб>колонка<таб>строка_шапки» (шапка найдена) и по строке
#        «R<таб>строка<таб>нет_колонки(0|1)<таб>имя_ребра<таб>что_течёт».
tr -d '\r' < "$ARCH" | tr '\t' ' ' | awk -v SEP="$TAB" '
    function trim(s) { gsub(/^[[:space:]]+/, "", s); gsub(/[[:space:]]+$/, "", s); return s }
    BEGIN { FS = "|"; flowcol = 0 }
    # фенсед-блок — ИЛЛЮСТРАЦИЯ, а не карта. В §3 законно показать «так
    # нельзя» примером таблицы (в т.ч. со своей шапкой «что течёт»); судить
    # такую строку как настоящее ребро — ложная краснота. Открытие фенса
    # закрывает и таблицу: код-блок таблицу разрывает.
    /^[[:space:]]*(```|~~~)/ { fence = !fence; intbl = 0; next }
    fence { next }
    # раздел §3 карты: от своего заголовка до следующего заголовка того же уровня
    /^##[[:space:]]+3\./ { insec = 1; next }
    insec && /^##[[:space:]]/ { insec = 0 }
    !insec { next }
    {
        # не строка таблицы — таблица кончилась
        if ($0 !~ /^[[:space:]]*\|/) { intbl = 0; next }
        if (!intbl) {
            # шапка ищется ПО ИМЕНИ колонки, номер колонки не зашит числом
            if (index($0, "что течёт") == 0) next
            for (i = 1; i <= NF; i++) if (index($i, "что течёт")) flowcol = i
            if (flowcol == 0) next
            headlast = NF
            if (trim($NF) == "") headlast = NF - 1
            intbl = 1; needsep = 1
            print "H" SEP flowcol SEP NR
            next
        }
        # ровно одна строка сразу под шапкой законно состоит из чёрточек
        if (needsep) { needsep = 0; if ($0 ~ /^[[:space:]]*\|[-:|[:space:]]*$/) next }
        # пустая строка таблицы (одни вертикальные черты и пробелы) — не ребро
        bare = $0; gsub(/[|[:space:]]/, "", bare)
        if (bare == "") next
        # последняя колонка: хвостовая вертикальная черта даёт пустое поле
        lastcol = NF
        if (trim($NF) == "") lastcol = NF - 1
        # имя ребра — все колонки ДО «что течёт» (обычно «из» и «в»)
        label = ""
        for (i = 2; i < flowcol; i++) {
            c = trim($i)
            if (c != "") label = (label == "" ? c : label " -> " c)
        }
        if (label == "") label = "(ребро без имён в колонках слева)"
        # ячейка «что течёт». Если по шапке это ПОСЛЕДНЯЯ колонка — берём всё
        # от неё до конца строки: вертикальная черта внутри ячейки иначе
        # обрезала бы контракт молча. Если за ней по шапке есть ещё колонки
        # (примечание и т.п.) — берём РОВНО свою: иначе пустая ячейка «что
        # течёт» пряталась бы за текстом соседней справа — ложная зелень.
        flow = ""; miss = 1
        if (lastcol >= flowcol) {
            miss = 0
            if (flowcol >= headlast) {
                for (i = flowcol; i <= lastcol; i++) flow = (i == flowcol ? $i : flow "|" $i)
            } else {
                flow = $flowcol
            }
        }
        print "R" SEP NR SEP miss SEP label SEP trim(flow)
    }
' > "$T/rows"

if ! grep -q "^H" "$T/rows"; then
    echo "$NAME: FAIL — в $ARCH не нашлось таблицы рёбер с колонкой «что течёт»:" >&2
    echo "  ждали раздел «## 3.» и в нём строку-шапку markdown с ячейкой «что течёт»." >&2
    echo "  Раздел переименовали/перенумеровали или колонку переназвали — страж потерял" >&2
    echo "  мишень, а молчать нельзя: это ровно класс №519 (вечнозелёный механизм)." >&2
    exit 1
fi
NROWS=$(grep -c "^R" "$T/rows")
if [ "$NROWS" -eq 0 ]; then
    echo "$NAME: FAIL — таблица рёбер §3 в $ARCH найдена, но строк-рёбер под шапкой ноль:" >&2
    echo "  карта без рёбер не бывает; пустая таблица сделала бы стража вечнозелёным (класс №519)." >&2
    exit 1
fi

# --- вердикт по каждой строке ----------------------------------------------
N=0
HOLES=0
: > "$T/bad"
while IFS="$TAB" read -r tag ln miss label flow; do
    [ "$tag" = "R" ] || continue
    N=$((N + 1))
    # нормализация: снимаем оформление, прочерки, вертикальные черты и
    # неразрывные пробелы. Тире и U+00A0 снимаются ТОЧНОЙ многобайтовой
    # последовательностью через sed, а не побайтным tr: tr порвал бы кириллицу
    # (0xD0 0x94 — «Д», байт 0x94 общий с «—»). Черта снимается потому, что
    # лишняя колонка в строке («| a | b |  |  |» при шапке в три колонки)
    # оставляла в ячейке один разделитель — и пустая «что течёт» проходила
    # зелёной. Ни один настоящий контракт не состоит из одних черт.
    # HTML-комментарий снимается по той же причине: «<!-- заполню позже -->»
    # рендерится ПУСТОЙ ячейкой, значит контракта в ней нет. Снимается
    # нежадно ([^>]*), чтобы «<!-- a --> `Token[]` <!-- b -->» остался зелёным.
    norm=$(printf '%s' "$flow" \
        | sed -e 's/<!--[^>]*-->//g' \
              -e 's/—//g; s/–//g; s/−//g' -e "s/$NBSP//g" \
              -e 's/[-.,:;*_`~"|[:space:]]//g' \
        | tr 'A-Z' 'a-z')
    hole=""
    case "$norm" in
        "")
            hole="колонка «что течёт» пуста (или в ней один прочерк)" ;;
        tbd|todo|na|n/a|"?"|"??"|"???"|xxx)
            hole="в колонке «что течёт» заглушка «$flow», а не контракт" ;;
    esac
    [ "$miss" = "1" ] && hole="в строке нет колонки «что течёт» вовсе (колонок меньше, чем в шапке)"
    if [ -n "$hole" ]; then
        HOLES=$((HOLES + 1))
        echo "  $ARCH:$ln: $label — $hole" >> "$T/bad"
    fi
done < "$T/rows"

if [ "$HOLES" -ne 0 ]; then
    echo "$NAME: FAIL — рёбра без объявленного «что течёт» (274.1 §2в п.3, карта §3):" >&2
    cat "$T/bad" >&2
    echo "  Ребро без контракта — дыра в карте, а не привилегия: оно разрешает «A видит B»," >&2
    echo "  не отвечая, ЧТО именно A оттуда берёт. Впиши в колонку «что течёт» конкретные" >&2
    echo "  данные ребра («Token[]», «строит GreenNode», «читает инстанцирования»), либо" >&2
    echo "  убери строку: ребра, которое не объяснить, не существует." >&2
    exit 1
fi

echo "$NAME ok: рёбер в таблице §3: $N, все несут «что течёт», дыр: 0"
exit 0
