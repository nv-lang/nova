#!/usr/bin/env bash
# scripts/guards/check-ratchet-moves.sh — сдвинул храповик, напиши почему
# ТЕМ ЖЕ слиянием (274 §10.4; замер 2026-08-22).
#
# ОБЛАСТЬ РАСШИРЕНА 2026-08-30 интегратором с `novac-*.baseline` на ВСЕ
# `scripts/guards/*.baseline` (и файл переименован из `check-novac-…`, чтобы имя
# не врало про область). Ровно этот шаг предусмотрен абзацем «зачем именно в
# новаковой семье» ниже: «интегратор заберёт, если понадобится». Понадобилось —
# адверсариальная панель нашла запуском, что «число ВЛАДЕЛЬЦА» в новой
# `hunter-debt.baseline` не судилось ничем: бюджет раскручивался дописанной в
# конец второй строкой, а прежняя оставалась в файле на виду. Сами стражи
# охотника теперь требуют ключ ровно один раз, а хронику при сдвиге требует
# этот страж — один дом на одно правило.
#
# ФОРМА ЧИСЛА понимается двумя способами, потому что базы в проекте пишутся
# двумя: `имя 123` (семья novac) и `имя=123` (базы стражей охотника).
#
# ЗАЧЕМ. Перепроверка по указанию владельца задала вопрос, который я сам себе не
# задавал: «а не двигал ли я храповики, чтобы красное стало зелёным?». Ответ был
# хороший — за сутки менялась одна база (`novac-surface`), шесть раз, и каждый
# раз я писал причину рядом. Но НИЧТО этого не требовало: причина появлялась
# потому, что я про неё помнил, а храповик — единственное место в проекте, где
# «сделать зелёным» физически проще, чем «сделать правильным». Правило, которое
# держится памятью, — не правило (это же и есть довод README хуков: машиной
# вместо памяти).
#
# ПРОВЕРЯЕТ: в диффе (сначала индекс, если пуст — рабочее дерево) для каждой
#   novac-базы `scripts/guards/novac-*.baseline`: если добавлена строка вида
#   `<имя> <число>`, в том же диффе того же файла обязана быть добавлена хотя бы
#   одна строка-комментарий (`#`). Одна причина на один сдвиг — минимум, который
#   отличает «решил» от «подогнал».
#
# НЕ ПРОВЕРЯЕТ: КАЧЕСТВО причины (её судит приёмка и ревью — названная слепая
#   зона); сдвиги в базах вне novac (у семьи main свой реестр); удаление строки
#   без добавления (это уже ловит сам страж поверхности: «база протухла»).
#
# ЗАЧЕМ ИМЕННО В НОВАКОВОЙ СЕМЬЕ. Правило общее для любого храповика, но заводить
# его на весь проект значит править стражей, которые судят чужие деревья.
# Предложение владельца 2026-08-23: сделать под novac, а интегратор заберёт, если
# понадобится. Отсюда префикс `check-novac-` и область `novac-*.baseline`.
#
# $1 — корень; $2 — override дерева git (шов самотеста).
set -u
export LC_ALL=C

NAME="check-ratchet-moves"
ROOT="${1:-.}"
GITDIR="${2:-$ROOT}"

if [ ! -d "$GITDIR/.git" ] && ! git -C "$GITDIR" rev-parse --git-dir >/dev/null 2>&1; then
    echo "$NAME ok: судить нечего (нет git-дерева в $GITDIR)"
    exit 0
fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

# Индекс — основной вход: страж стоит перед коммитом. Если индекс пуст, судим
# рабочее дерево: волна в работе — тот же предмет, только раньше.
git -C "$GITDIR" diff --cached -- 'scripts/guards/*.baseline' > "$TMP/d" 2>/dev/null
if [ ! -s "$TMP/d" ]; then
    git -C "$GITDIR" diff -- 'scripts/guards/*.baseline' > "$TMP/d" 2>/dev/null
fi

if [ ! -s "$TMP/d" ]; then
    echo "$NAME ok: сдвигов храповиков в диффе нет"
    exit 0
fi

BAD=0
MOVED=0
FILE=""
NUMS=0
CMTS=0

flush() {
    [ -n "$FILE" ] || return 0
    if [ "$NUMS" -gt 0 ]; then
        MOVED=$((MOVED+1))
        if [ "$CMTS" -eq 0 ]; then
            echo "  $FILE: сдвинуто чисел $NUMS, добавленных строк-причин 0" >&2
            BAD=$((BAD+1))
        fi
    fi
}

while IFS= read -r line; do
    case "$line" in
        '+++ b/'*)
            flush
            FILE="${line#+++ b/}"
            NUMS=0
            CMTS=0
            ;;
        '+#'*)   CMTS=$((CMTS+1)) ;;
        '+'*)
            body="${line#+}"
            # ровно «имя число» или «имя=число» и ничего больше
            if printf '%s' "$body" | grep -qE '^[a-z_]+([ =])[0-9]+$'; then
                NUMS=$((NUMS+1))
            fi
            ;;
    esac
done < "$TMP/d"
flush

if [ "$BAD" -gt 0 ]; then
    echo "$NAME: FAIL — храповик сдвинут без причины В ТОМ ЖЕ диффе (файлов $BAD):" >&2
    echo "  Храповик — единственное место, где «сделать зелёным» проще, чем" >&2
    echo "  «сделать правильным»: новое число само себя оправдывает. Поэтому" >&2
    echo "  причина обязана приехать тем же слиянием — строкой комментария рядом" >&2
    echo "  с числом: что выросло, зачем и почему это решение, а не подгонка." >&2
    exit 1
fi

echo "$NAME ok: файлов с сдвигом храповика: $MOVED, сдвигов без причины: 0"
exit 0
