#!/bin/sh
# scripts/guards/check-no-machine-paths.sh — в отслеживаемых скриптах нет
# абсолютных путей к машине владельца.
#
# Реестр: docs/plans/221.1-bug-sweep.md №698. Владелец открыл
# nova-p274/scripts/gate.sh и спросил «что за пути?»: в гейте с первого дня
# (2026-07-26) стояло `NOVA_GC_LIB_DIR="D:\Sources\nv-lang\nova\..."` — путь к
# ЕГО машине в публичном скрипте; dev-env.sh «сверял значения с gate.sh» — то
# есть копировал их; cdb_session.sh — то же. Три копии одного костыля.
# Через него worktree 274 линковал GC из чужого дерева и не знал об этом.
#
# ПРАВИЛО: расположение ВЫВОДИТСЯ (от $ROOT, от `git rev-parse
# --git-common-dir`, от `dirname "$0"`), а не пишется. Путь к машине —
# только в комментарии-примере или в строке «Проверялся: ...».
#
# ЧТО СЧИТАЕТСЯ ПУТЁМ К МАШИНЕ: `d:/Sources`, `D:\Sources`, `/d/Sources`,
# `/mnt/d/Sources`, `C:\Users\<имя>` — в строке, которая НЕ комментарий.
#
# ИСКЛЮЧЕНИЯ (осознанные, названные):
#   * этот страж и его самотест — они обязаны НЕСТИ образцы форм, которые ловят;
#   * docs/plans/repro/** — улики, там пути — часть улики.
#
# СНЯТО 2026-08-23: исключение для check-worktree-location.sh и repo-hygiene.sh.
# Оно держалось на том, что политика worktree «уже под NOVA_WORKTREE_ROOT», но
# литерал в них при этом стоял — и в публичном репозитории это был путь к машине
# владельца. Теперь корень в обоих ВЫВОДИТСЯ (родитель главной рабочей копии /
# каталог скрипта), литерала нет, и исключение стало ненужным: оба файла судятся
# наравне со всеми.
#
# $1 — корень. Самотест — selftest/test-check-no-machine-paths.sh
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
NAME=check-no-machine-paths
FILES=$(git -C "$ROOT" ls-files -- 'scripts/*.sh' 'scripts/**/*.sh' 'scripts/*.py' 'scripts/**/*.py' '.github/workflows/*.yml' 2>/dev/null \
    | grep -vE '^scripts/guards/check-no-machine-paths\.sh$|^scripts/guards/selftest/test-check-no-machine-paths\.sh$' \
    )
# ИСКЛЮЧЕНИЕ `scripts/claude-hooks/selftest/` СНЯТО (№765, 2026-08-26).
# Оно прикрывало РОВНО ОДИН файл — `test-guard-git-commit-backtick.py`
# с абсолютным windows-путём к перехватчику, из-за которого тот
# самотест на CI не проверял ничего вообще. Страж, которому велели
# не смотреть туда, где дефект, — не страж. Файл починен тем же слиянием.
# scripts/claude-hooks/selftest/** — самотесты хуков ДЕРЖАТ такие пути как
# ТЕСТОВЫЕ ДАННЫЕ (строки, которые хук обязан распознать) — исключены каталогом.
# `Prichina:` — текст подсказки хука с примером команды; `step "` — текст шага
# гейта (политика №561 названа словами). Оба — сообщения, не пути исполнения.
if [ -z "$FILES" ]; then
    echo "$NAME: FAIL — git не отдал списка скриптов под $ROOT" >&2
    exit 1
fi
# ОДИН grep НА ВСЕ ФАЙЛЫ вместо форка grep+grep+printf+sed НА КАЖДЫЙ файл в
# цикле (план 275-Ф.1, гейт-стоимость — профиль показал ~29с на этом месте
# при сотнях отслеживаемых скриптов). `-H` держит имя файла в выводе даже
# когда xargs-пачка ужалась до одного файла (без -H grep одиночного файла
# молчит об имени — тогда группировка ниже развалилась бы).
RAW=$(printf '%s\n' "$FILES" | sed "s#^#$ROOT/#" \
    | xargs -d '\n' -r grep -nHE '([Dd]:[/\\]+Sources|/d/Sources|/mnt/d/Sources|[Cc]:[/\\]+Users[/\\])' 2>/dev/null \
    | sed "s#^$ROOT/##" \
    | grep -vE '^[^:]*:[0-9]+:[[:space:]]*#' \
    | grep -vE 'Проверялся|проверялся|# |Prichina:|machine-path-fixture|^[^:]*:[0-9]+:step ')
# `machine-path-fixture` — ИМЕНОВАННОЕ исключение НА СТРОКЕ (№765, 2026-08-26):
# путь лежит ВНУТРИ строки-аргумента, которую хук получает как данные, и в этом
# весь смысл случая. Пришло на смену исключению целой папки
# `scripts/claude-hooks/selftest/`, которое прикрывало и настоящий дефект —
# самотест, зашитый на абсолютный windows-путь, три ночи «проходивший» на CI по
# совпадению кодов возврата.
# Группировка по файлу — тем же порядком, каким grep выдаёт совпадения
# (файлы обходятся в порядке $FILES, строки внутри файла — по возрастанию
# номера), поэтому один проход awk без сортировки воспроизводит ровно то
# же дерево вывода, что раньше строил цикл на bash.
BAD=$(printf '%s\n' "$RAW" | awk -F: '
    NF < 2 { next }
    {
        path = $1
        rest = substr($0, length(path) + 2)
        if (!started) { print ""; started = 1 }
        if (path != cur) { print "  " path ":"; cur = path }
        line = "    " rest
        if (length(line) > 140) line = substr(line, 1, 140)
        print line
    }')
if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — абсолютный путь к машине в отслеживаемом скрипте (№698):$BAD" >&2
    echo "    Расположение выводится от \$ROOT / git-common-dir / dirname \$0, а не пишется." >&2
    exit 1
fi
N=$(printf '%s\n' "$FILES" | wc -l)

# ─────────────────────────────────────────────────────────────────────────
# ЯРУС 2 и ЯРУС 3 (расширение области, решение владельца 2026-09-12).
#
# ПОЧЕМУ ОБЛАСТЬ РАСШИРЕНА. Ярус 1 выше судит СКРИПТЫ и только строки вне
# комментариев — это верно для его предмета: «скрипт не должен зависеть от
# чужой машины». Но у владельца предмет оказался ДРУГОЙ: «раскладка машины не
# должна публиковаться». Замер 2026-09-12: 326 отслеживаемых файлов несли
# машинные пути, и ярус 1 пропускал их ЗАКОННО, потому что почти все — в
# `docs/**` и в комментариях. Область проверки не совпадала с предметом
# тревоги; это и исправлено.
#
# ПОЧЕМУ ДВА ЯРУСА, А НЕ ОДИН. Ноль на всё дерево завести нельзя: он покраснел
# бы на тысяче исторических упоминаний, и первое же окно снесло бы стража
# (правило /plan-recheck п.5). Поэтому чувствительное получает НОЛЬ, а объёмное
# — храповик от сегодняшнего числа.

# Исключения общие для обоих ярусов: этот страж и его самотест НЕСУТ образцы;
# `docs/plans/repro/**` — улики (путь там часть улики); самотесты хуков держат
# пути как тестовые данные; вендоренный libuv и замороженный архив — не наши.
EXC=":(exclude)compiler-codegen/nova_rt/libuv :(exclude)nova_tests.old"
EXC="$EXC :(exclude)docs/plans/repro :(exclude)scripts/claude-hooks/selftest"
EXC="$EXC :(exclude)scripts/guards/check-no-machine-paths.sh"
EXC="$EXC :(exclude)scripts/guards/selftest/test-check-no-machine-paths.sh"

# ЯРУС 2 — НОЛЬ, без базы: ИМЯ ПОЛЬЗОВАТЕЛЯ и КАТАЛОГ СЕССИИ в любом файле.
# Имя владельца и так стоит в поле автора каждого коммита — намеренно; здесь
# закрывается другое: домашний путь и каталог сессии с UUID, по которым видна
# раскладка инструмента. Оба сегодня равны нулю (вычищено 2026-09-12), поэтому
# ноль здесь — не пожелание, а достигнутое состояние.
# `Users/…` с многоточием — ПРОЗА (в правилах, в строке реестра 698, в
# комментарии самотеста), и она не путь: отсеивается пост-фильтром.
SENS=$(git -C "$ROOT" grep -nIE '[A-Za-z]:[/\\]+Users[/\\]+[^ -~]|AppData[/\\]+Local[/\\]+Temp[/\\]+claude' -- $EXC 2>/dev/null \
    | grep -vE 'Users[/\\]+…')
if [ -n "$SENS" ]; then
    echo "$NAME: FAIL — имя пользователя или каталог сессии в отслеживаемом файле:" >&2
    printf '%s\n' "$SENS" | head -20 >&2
    echo "    Домашний путь пишется как %USERPROFILE%, каталог сессии — заполнителем." >&2
    exit 1
fi

# ЯРУС 3 — ХРАПОВИК: все машинные пути во всех отслеживаемых файлах.
# Число считается ЭТОЙ ЖЕ командой, поэтому база пересчитывается стражем, а не
# переписывается рукой из чужого замера (урок AGENTS.md 2026-09-11: копия числа,
# которую нечем сверить, протухает молча).
PB="$(dirname "$0")/machine-paths.baseline"
CUR=$(git -C "$ROOT" grep -oIE '([Dd]:[/\\]+Sources|/d/Sources|/mnt/d/Sources|[Cc]:[/\\]+Users[/\\])' -- $EXC 2>/dev/null | wc -l)
CUR=$(printf '%s' "$CUR" | tr -d ' ')
if [ ! -f "$PB" ]; then
    echo "$NAME: FAIL — нет базы $PB: храповик без базы ничего не держит" >&2
    exit 1
fi
WANT=$(grep -E '^paths=[0-9]+$' "$PB" | head -1 | cut -d= -f2)
if [ -z "$WANT" ]; then
    echo "$NAME: FAIL — в базе $PB нет строки paths=N" >&2
    exit 1
fi
if [ "$CUR" -gt "$WANT" ]; then
    echo "$NAME: FAIL — машинных путей стало БОЛЬШЕ: $CUR > базы $WANT (№698)" >&2
    echo "    Новый путь пишется выводом (от \$ROOT / git-common-dir / dirname \$0)," >&2
    echo "    а не литералом. Если рост осознан — опусти строку в $PB с хроникой." >&2
    exit 1
fi

echo "$NAME ok: скриптов $N (путей вне комментариев 0); имён и каталогов сессий 0; всего путей $CUR <= базы $WANT (№698)"
exit 0
