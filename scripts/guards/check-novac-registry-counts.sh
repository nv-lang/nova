#!/usr/bin/env bash
# scripts/guards/check-novac-registry-counts.sh — число в реестре стражей равно
# факту (класс doc-truth; замер 2026-08-22).
#
# ЗАЧЕМ. Перепроверка по указанию владельца нашла в документах, написанных мной
# же часами раньше, ДВА протухших числа: «560 имён проверяется» там, где страж
# отвечает 471, и «12 случаев» там, где в самотесте 16. Оба стояли в строках
# реестра §10.3 — в тексте, по которому читают, что механизм умеет. А когда я
# поправил число, поправил не до конца: в строке остались ОБА, и это нашёл уже
# сам страж на первом прогоне.
#
# Протухшее число хуже отсутствующего: отсутствующее гонит смотреть, протухшее
# выглядит замером. Класс тот же, что у даты живой строки и у долей леджера
# (check-novac-plan-liveline, check-novac-time-ledger) — здесь он на счётчиках.
#
# ПРОВЕРЯЕТ: если строка реестра называет `selftest/test-<имя>.sh` и рядом число
#   «N случаев» — самотест печатает ровно N строк `ok`.
# НЕ ПРОВЕРЯЕТ: строки без числа (число необязательно — обязательна правдивость);
#   числа, не относящиеся к случаям самотеста («471 имя», «204 экспорта») — это
#   вывод самого стража, и за него отвечает он. Названная слепая зона: числа в
#   прозе плана вне таблицы реестра.
#
# ПОЧЕМУ SHELL, А НЕ PYTHON: самотесты — bash, и питоновский `subprocess` на этой
# машине резолвит `bash` в WSL, который падает на проксях (замер: rc=1, вывод
# «WSL ... не поддерживает прокси-серверы localhost»). Страж на bash запускает их
# тем же интерпретатором, под которым идёт гейт, — иначе «печатает 0» у всех и
# страж рапортует о поломке, которой нет.
#
# $1 — корень; $2 — override плана (шов самотеста).
set -u
export LC_ALL=C

NAME="check-novac-registry-counts"
ROOT="${1:-.}"
PLAN="${2:-$ROOT/docs/plans/274-novac-self-hosted-compiler.md}"
GUARDS="$ROOT/scripts/guards"

if [ ! -f "$PLAN" ]; then
    echo "$NAME ok: судить нечего (нет $PLAN)"
    exit 0
fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

# Пары «файл самотеста<TAB>обещанное число». ВСЕ числа строки, а не одно: на
# первом прогоне страж взял ПОСЛЕДНЕЕ и позеленел на строке, где стояли и `12`,
# и `16` — то есть пропустил ровно тот носитель, ради которого заводился (ERE не
# знает ленивых кванторов, и `[^|]*?` работал как жадный). Два числа на один
# самотест — сами по себе дефект: непонятно, какое из них обещание.
python - "$PLAN" > "$TMP/claims" <<'PYEOF'
import io, re, sys
for line in io.open(sys.argv[1], encoding='utf-8').read().split('\n'):
    if not line.startswith('|'):
        continue
    for m in re.finditer(r'selftest/(test-[a-z0-9-]+\.sh)`', line):
        tail = line[m.end():].split('|')[0]
        nums = re.findall(r'(\d+)\s+случа', tail)
        for n in nums:
            print('%s\t%s' % ('selftest/' + m.group(1), n))
PYEOF
# `tr -d` НЕ украшение: питон на Windows печатает `\r\n`, и без снятия CR число
# приходит как `13\r`, а сравнение с `13` даёт расхождение, которого нет —
# поймано на первом же прогоне после починки регулярки.
tr -d '\r' < "$TMP/claims" | sort -u > "$TMP/claims.clean"
mv "$TMP/claims.clean" "$TMP/claims"

CLAIMS=$(grep -c "" < "$TMP/claims")
if [ "$CLAIMS" -eq 0 ]; then
    echo "$NAME: FAIL — в реестре нет ни одной пары «самотест + число случаев»: страж потерял мишень (класс №519)" >&2
    exit 1
fi

BAD=0
while IFS="$(printf '\t')" read -r rel claimed; do
    [ -n "$rel" ] || continue
    if [ ! -f "$GUARDS/$rel" ]; then
        echo "  $rel: назван в реестре, а файла нет" >&2
        BAD=$((BAD+1))
        continue
    fi
    seen=$(grep -c "^$rel	" "$TMP/claims")
    if [ "$seen" -gt 1 ]; then
        echo "  $rel: строка реестра обещает $seen РАЗНЫХ числа случаев — неясно, какое из них обещание" >&2
        BAD=$((BAD+1))
        continue
    fi
    actual=$(bash "$GUARDS/$rel" 2>&1 | grep -cE '^[[:space:]]+ok[[:space:]]')
    if [ "$actual" != "$claimed" ]; then
        echo "  $rel: реестр обещает $claimed случаев, самотест печатает $actual" >&2
        BAD=$((BAD+1))
    fi
done < "$TMP/claims"

if [ "$BAD" -gt 0 ]; then
    echo "$NAME: FAIL — число в реестре не равно факту (расхождений $BAD):" >&2
    echo "  Протухшее число хуже отсутствующего: отсутствующее гонит смотреть," >&2
    echo "  протухшее выглядит замером. Либо число обновляется той же волной," >&2
    echo "  что и самотест, либо его в строке нет." >&2
    exit 1
fi

echo "$NAME ok: пар «самотест + число случаев» в реестре: $CLAIMS, расхождений: 0"
exit 0
