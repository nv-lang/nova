#!/usr/bin/env bash
# scripts/guards/check-registry-entry-shape.sh
# Реестр 221.1. Требование владельца, повторённое ТРИЖДЫ за одну сессию
# 2026-08-08: «проверь найденные дефекты, все добавлены в план? определи класс
# бага, приоритет и добавь в описание, чтобы не было попыток фиксить конкретный
# баг, т.к. фиксить надо класс дефекта через одно окно в рамках 196».
#
# Затем — вопрос, породивший этот файл: «у нас есть автомат для этого действия?»
# Не было. Правило существовало только в голове интегратора, и потому владельцу
# приходилось повторять его каждые несколько часов. Правило без механизма есть
# симптом, а не фикс.
#
# ЧТО ПРОВЕРЯЕТСЯ у каждой записи реестра:
#   1. ПРИОРИТЕТ — `К1`, `К2` или `К3`. Без него запись не встаёт в очередь.
#      К3 добавлен 2026-08-10: страж его не знал, а реестр им пользовался —
#      двенадцать записей с честным приоритетом числились «без приоритета» и
#      сидели в базе долга. Страж, считающий верное оформление нарушением, учит
#      обходить себя.
#   2. КЛАСС — слово «КЛАСС» в описании. Без него следующее окно починит
#      НОСИТЕЛЯ: один упавший тест, одну строку — и дефект вернётся соседней
#      дверью. Ровно это происходило с №370 (закрыт наполовину, три носителя
#      остались), №381/№383/№384/№345/№386 (пять дверей бáундов, найденных по
#      одной), №466 (пять веток конструирования, хук на одной).
#   3. ОГОВОРКА О НОСИТЕЛЕ — «фикс носителя приёмкой не считается» или равное по
#      смыслу. Это не украшение: она адресована окну, которое будет читать
#      запись без всего остального контекста.
#
# ПОЧЕМУ ХРАПОВИК, А НЕ НОЛЬ. Записей в реестре сотни, и заполнены они по-разному
# — старые заводились до того, как норма сложилась. Обнулить одним движением
# нельзя, не переписав историю разбора. Храповик запрещает РОСТ: новая запись без
# класса краснит гейт немедленно, старые разбираются своим порядком и опускают
# базу.
#
# ЧЕГО ЭТОТ СТРАЖ НЕ ЛОВИТ (сказано честно): он проверяет ФОРМУ, а не смысл.
# Слово «КЛАСС» рядом с описанием одного носителя пройдёт. Отличить настоящее
# обобщение от переписанного носителя машина не может — это суждение. Страж
# закрывает лишь то, что закрывается механически: забывчивость.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-registry-entry-shape.sh [КОРЕНЬ]
# ПЕРЕМЕННЫЕ:
#   NOVA_REGSHAPE_BASELINE — путь к базе, по умолчанию
#                            scripts/guards/registry-entry-shape.baseline

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
REG="$ROOT/docs/plans/221.1-bug-sweep.md"
BASELINE="${NOVA_REGSHAPE_BASELINE:-$ROOT/scripts/guards/registry-entry-shape.baseline}"

[ -f "$REG" ] || { echo "check-registry-entry-shape: нет реестра $REG" >&2; exit 1; }

# Один проход awk. Построчный цикл с гроздью grep на строку уже однажды не
# уложился в таймаут на страже инвариантов — повторять урок незачем.
OUT=$(awk '
    /^\| [0-9]+ \|/ {
        # Номер записи.
        num = $0; sub(/^\| /, "", num); sub(/ \|.*/, "", num)
        bad = ""
        if ($0 !~ /К[123]/)                                  bad = bad " приоритет"
        if ($0 !~ /КЛАСС/)                                   bad = bad " класс"
        # РЕГИСТР НЕ СУДИТСЯ — ни у одного слова оговорки. До 2026-09-15
        # «НЕ» принималось в обоих регистрах, а «приёмкой» требовалось
        # строчными, и запись, выделившая оговорку ЗАГЛАВНЫМИ целиком
        # («ОГОВОРКА: ФИКС НОСИТЕЛЯ ПРИЁМКОЙ НЕ СЧИТАЕТСЯ»), считалась
        # неоформленной. То есть страж судил ТИПОГРАФИКУ вместо предмета:
        # оговорка была на месте и адресована ровно тому читателю, ради
        # которого она требуется. Замер в день правки: таких записей РОВНО
        # одна из 1058 (№1116) — класс мелкий, но ложная краснота дороже
        # своего размера, потому что по ней идут искать поломку, которой нет.
        # ФОРМЫ ПЕРЕЧИСЛЕНЫ ЦЕЛИКОМ, И ЭТО НЕ МНОГОСЛОВИЕ: под LC_ALL=C awk
        # сравнивает БАЙТЫ, поэтому ни tolower(), ни символьный класс вида
        # [ёе] на кириллице не работают — класс становится набором байтов и
        # ложно срабатывает на соседних буквах. Попытка свернуть эти четыре
        # ветки в две классом провалила селфтест в тот же день (2026-09-15).
        if ($0 !~ /приёмкой (НЕ|не) считается/ &&
            $0 !~ /приемкой (НЕ|не) считается/ &&
            $0 !~ /ПРИЁМКОЙ (НЕ|не) СЧИТАЕТСЯ/ &&
            $0 !~ /ПРИЕМКОЙ (НЕ|не) СЧИТАЕТСЯ/)              bad = bad " оговорка-о-носителе"
        if (bad != "") { printf "%s:%s\n", num, bad; cnt++ }
        rows++
    }
    # ЗНАМЕНАТЕЛЬ РАЗБОРА (2026-09-20): сколько строк реестра awk вообще узнал.
    # Без него падение счёта неотличимо от того, что разбор перестал видеть
    # строки (разметка, переезд файла, съехавший образец), — а это падение
    # читается как погашенный долг.
    END { printf "TOTAL %d\n", cnt + 0; printf "ROWS %d\n", rows + 0 }
' "$REG")

# Запись, ждущая номера, НЕВИДИМА для проверки выше: регулярка строки реестра —
# `| ЧИСЛО |`, а окно пишет `| TBD |` (номера присваивает интегратор, не окна).
# 2026-08-10: так в реестре три часа жили три записи, которых не видел ни один
# страж. Номер обязан быть присвоен ДО гейта — иначе «оформлено» считается по
# неполному множеству.
TBD=$(grep -cE '^\| *(№)?TBD *\|' "$REG" || true)
if [ "${TBD:-0}" -gt 0 ]; then
    echo "check-registry-entry-shape: записей без номера (TBD) — $TBD" >&2
    grep -nE '^\| *(№)?TBD *\|' "$REG" | cut -c1-120 | sed 's/^/    /' >&2
    echo "    Номер присваивает интегратор перед гейтом: запись с TBD не видна" >&2
    echo "    проверке формы, и её отсутствие оформления не считается." >&2
    echo "check-registry-entry-shape: FAIL" >&2
    exit 1
fi

# ДВА РАЗА ОДИН НОМЕР — ЖЁСТКИЙ ОТКАЗ, БЕЗ ХРАПОВИКА. Дубль рождается не
# опечаткой, а СЛИЯНИЕМ: конфликт «обе стороны добавили строки», разрешённый
# сохранением обеих, тихо удваивает записи. Замер 2026-08-24/26: №753 существовал
# ДВУМЯ строками разной длины два дня, ни один страж этого не видел, нашлось
# случайно при простановке соседних номеров. Две строки под одним номером — два
# ответа на вопрос «что это за дефект», и который прочтёт следующее окно, решает
# порядок в файле. Храповик не нужен: на день введения дублей ноль.
DUPES=$(awk '
    /^\| [0-9]+ \|/ {
        num = $0; sub(/^\| /, "", num); sub(/ \|.*/, "", num)
        seen[num]++
    }
    END { for (n in seen) if (seen[n] > 1) printf "%s x%d\n", n, seen[n] }
' "$REG")
if [ -n "$DUPES" ]; then
    echo "check-registry-entry-shape: один номер несколькими строками:" >&2
    printf '%s\n' "$DUPES" | sed 's/^/    №/' >&2
    echo "    Дубль обычно рождается слиянием «сохранить обе стороны»: сверь две" >&2
    echo "    строки — как правило, одна есть надмножество другой (№753 совпадал" >&2
    echo "    на 2570 символах и дальше продолжался) — и оставь полную." >&2
    echo "check-registry-entry-shape: FAIL" >&2
    exit 1
fi

# ОТКРЫТАЯ К1 БЕЗ ВЕРДИКТА «БЛОКИРУЕТ ТЕГ» — ЖЁСТКИЙ ОТКАЗ, БЕЗ ХРАПОВИКА.
#
# Вопрос владельца 2026-08-11: «К1 сильно прибавляется и не уменьшается, что
# делать?» Ответ оказался не в темпе починки, а в том, что «К1» смешивал три
# разные вещи: то, что ЗАМОРАЖИВАЕТ публичную поверхность тегом; то, что МОЛЧА
# врёт или портит память; и то, что просто громко не поддержано. Первые две
# держат релиз, третья — нет, и без поля различить их было нельзя: «58 открытых
# К1» читалось как приговор, хотя таковым не являлось.
#
# Поле введено разбором того же дня по ВСЕМ открытым К1 (63 записи: 36 держат
# тег, 27 нет). Раз множество полное, храповик не нужен — новая К1 обязана
# нести вердикт сразу. Пустого «НЕТ» не бывает: причина, почему с этим безопасно
# выпускаться, пишется в той же строке, иначе поле станет способом убрать
# неудобное с глаз.
# Матч по КОЛОНКЕ приоритета, а не по всей строке: слово «К1» встречается и в
# прозе соседних записей («тот же класс, что у К1-записи №…»), и страж, судящий
# по всей строке, требовал бы вердикта от записей К2.
NOVERDICT=$(awk '
    /^\| [0-9]+ \|[^|]*К1[^|]*\|/ && !/ЗАКРЫТ/ && !/БЛОКИРУЕТ ТЕГ/ {
        num = $0; sub(/^\| /, "", num); sub(/ \|.*/, "", num); print num
    }
' "$REG")
if [ -n "$NOVERDICT" ]; then
    echo "check-registry-entry-shape: открытые К1 без вердикта «БЛОКИРУЕТ ТЕГ»:" >&2
    printf '%s\n' "$NOVERDICT" | sed 's/^/    №/' >&2
    echo "    Допиши в запись: **БЛОКИРУЕТ ТЕГ: ДА|НЕТ — почему**." >&2
    echo "    ДА — если замораживает публичную поверхность, молча врёт или портит" >&2
    echo "    память, либо ломает то, что мы поставляем. НЕТ — только с причиной," >&2
    echo "    почему выпускаться с этим безопасно." >&2
    echo "check-registry-entry-shape: FAIL" >&2
    exit 1
fi

N=$(printf '%s\n' "$OUT" | sed -n 's/^TOTAL //p')
ROWS=$(printf '%s\n' "$OUT" | sed -n 's/^ROWS //p')
LIST=$(printf '%s\n' "$OUT" | grep -v '^TOTAL \|^ROWS ' || true)
NOW_NUMS=$(printf '%s\n' "$LIST" | sed -n 's/^\([0-9][0-9]*\):.*/\1/p' | sort -n)

# ШОВ ЗАСЕВА: печать ПОЛНОГО набора номеров. Нужен ровно затем, чтобы база
# заполнялась ИЗ САМОГО СТРАЖА, а не вторым предикатом рядом: две копии одного
# правила расходятся на первой же правке, и база начинает держать не тот набор,
# который страж считает. Отказ при этом не выносится — это выдача, не суд.
if [ -n "${NOVA_REGSHAPE_LIST:-}" ]; then
    printf '%s\n' "$NOW_NUMS"
    printf 'ROWS %s\n' "${ROWS:-0}"
    exit 0
fi

BASE=0
if [ -f "$BASELINE" ]; then
    BASE=$(sed -n 's/^incomplete_entries=\([0-9][0-9]*\).*/\1/p' "$BASELINE" | head -1)
    BASE=${BASE:-0}
else
    echo "check-registry-entry-shape: базы нет ($BASELINE) — считаю базой 0" >&2
fi

echo "check-registry-entry-shape: записей без полного оформления $N (база $BASE)"

if [ "${N:-0}" -gt "$BASE" ]; then
    echo "check-registry-entry-shape: ВЫРОСЛО — $N > базы $BASE" >&2
    printf '%s\n' "$LIST" | head -20 | sed 's/^/    №/' >&2
    echo "    Запись без КЛАССА заставит следующее окно чинить НОСИТЕЛЯ, и дефект" >&2
    echo "    вернётся соседней дверью (прецеденты: №370, №466, пять дверей бáундов)." >&2
    echo "    Допиши в запись: приоритет К1/К2/К3, поле КЛАСС, и оговорку" >&2
    echo "    «фикс носителя приёмкой не считается»." >&2
    echo "check-registry-entry-shape: FAIL" >&2
    exit 1
fi

if [ "${N:-0}" -lt "$BASE" ]; then
    echo "check-registry-entry-shape: долг СНИЗИЛСЯ ($N < базы $BASE) — опусти базу в $BASELINE"
fi

# ─────────────────────────────────────────────────────────────────────────
# ЯРУС ИМЁН (2026-09-20). Счёт в 343 записи прячет ЗАМЕНУ: одну запись
# дооформили, другая приехала слиянием неоформленной — итог тот же, храповик
# молчит. И прячет СУЖЕНИЕ РАЗБОРА: образец строки реестра съехал — счёт упал —
# падение прочлось как уборка. Против первого — набор номеров, против второго —
# знаменатель разобранных строк, который может только расти.
#
# Ярус идёт, только когда база ПРИНАДЛЕЖИТ судимому дереву: у самотеста своя
# подставная репа, и сверять её с набором настоящего реестра бессмысленно.
RS_TIER=1
RS_ROOT_ABS="$(cd "$ROOT" 2>/dev/null && pwd)"
RS_BASE_ABS="$(cd "$(dirname "$BASELINE")" 2>/dev/null && pwd)/$(basename "$BASELINE")"
case "$RS_BASE_ABS" in
    "${RS_ROOT_ABS:-$ROOT}"/*) ;;
    *) RS_TIER=0 ;;
esac

if [ "$RS_TIER" = "1" ]; then
    RS_WANT_ROWS=$(sed -n 's/^scanned_rows=\([0-9][0-9]*\)$/\1/p' "$BASELINE" | head -1)
    RS_NAMES=$(sed -n 's/^incomplete_row=\([0-9][0-9]*\)$/\1/p' "$BASELINE" | sort -n)
    RS_NAMED=$(printf '%s\n' "$RS_NAMES" | grep -c . )

    if [ -z "$RS_WANT_ROWS" ] || { [ "${BASE:-0}" -gt 0 ] && [ "$RS_NAMED" -eq 0 ]; }; then
        echo "check-registry-entry-shape: FAIL — база держит только счёт: нет строк scanned_rows= / incomplete_row=." >&2
        echo "    Счёт прячет замену записи и сужение разбора." >&2
        exit 1
    fi
    if [ "${RS_NAMED:-0}" -ne "${BASE:-0}" ]; then
        echo "check-registry-entry-shape: FAIL — база противоречит себе: incomplete_entries=$BASE, номеров $RS_NAMED" >&2
        exit 1
    fi
    if [ "${ROWS:-0}" -lt "${RS_WANT_ROWS:-0}" ]; then
        echo "check-registry-entry-shape: FAIL — РАЗОБРАНО МЕНЬШЕ СТРОК, ЧЕМ В БАЗЕ: $ROWS < $RS_WANT_ROWS — разбор сузился." >&2
        echo "    Долг, переставший считаться, читается как погашенный. Это не он." >&2
        exit 1
    fi

    # comm вместо построчного `while read` + `grep` на каждый элемент: тот же
    # O(n*m) с подпроцессом на итерацию однажды уже не уложился в таймаут
    # (комментарий выше, строка 55) — здесь тот же класс, просто набор чисел,
    # а не строк реестра, и раньше он не был замечен, потому что оба списка
    # были короче. `comm` требует ЛЕКСИКОГРАФИЧЕСКОЙ сортировки (под LC_ALL=C,
    # заданным в шапке файла), а не числовой (`sort -n`, которым оба набора
    # уже отсортированы для остального скрипта) — 9 идёт ПОСЛЕ 10 лексикографи-
    # чески, значит сортировка для `comm` берётся заново, отдельной переменной,
    # не переиспользует $NOW_NUMS/$RS_NAMES напрямую.
    RS_NOW_LEX=$(printf '%s\n' "$NOW_NUMS" | grep -v '^$' | sort)
    RS_NAMES_LEX=$(printf '%s\n' "$RS_NAMES" | grep -v '^$' | sort)
    # `grep -v '^$'` INSIDE the substitution too: `printf '%s\n' ""` on an
    # empty variable still emits one blank line, which `comm` would then read
    # as a phantom entry on whichever side is actually empty (found by the
    # selftest: an all-paid case reported a spurious "new" entry that was
    # really just this blank line).
    RS_NEW=$(comm -23 <(printf '%s\n' "$RS_NOW_LEX" | grep -v '^$') <(printf '%s\n' "$RS_NAMES_LEX" | grep -v '^$') | tr '\n' ' ')
    if [ -n "$RS_NEW" ]; then
        echo "check-registry-entry-shape: FAIL — НОВЫЕ неоформленные записи: $RS_NEW" >&2
        echo "    Общее число могло НЕ вырасти: одну дооформили, другая пришла." >&2
        exit 1
    fi
    RS_PAID=$(comm -13 <(printf '%s\n' "$RS_NOW_LEX" | grep -v '^$') <(printf '%s\n' "$RS_NAMES_LEX" | grep -v '^$') | tr '\n' ' ')
    if [ -n "$RS_PAID" ]; then
        echo "check-registry-entry-shape ok: дооформлены — $RS_PAID: убери эти incomplete_row= из $BASELINE и поправь счёт ТОЙ ЖЕ правкой"
        exit 0
    fi
    echo "check-registry-entry-shape ok: роста неоформленных записей нет ($N <= $BASE, номера сверены поимённо), разобрано строк $ROWS >= $RS_WANT_ROWS"
    exit 0
fi

echo "check-registry-entry-shape ok: роста неоформленных записей нет ($N <= $BASE) (база не принадлежит судимому дереву: ярус имён не проверяется)"
exit 0
