#!/usr/bin/env bash
# scripts/guards/check-accepted-branch-merged.sh
# Работа окна принята в реестре — значит его ветка влита либо удалена.
#
# ДОМ И ОСНОВАНИЕ: план 231, трек Д (машинное принуждение норм); реестр 221.1
# №594.
#
# ЗАЧЕМ — случай 2026-08-11, дословно. Окно плана 270 сдало отчёт, интегратор
# принял его, переписал по нему КЛАСС записи №576 и очередь работ в 221.1 — и
# про саму ветку забыл. В ней осталось двадцать два файла проб и поправка плана
# на сто с лишним строк. Обнаружилось случайно, при уборке worktree, через
# несколько часов.
#
# Опасность не в потере файлов (они в git), а в РАСХОЖДЕНИИ: реестр говорит
# «закрыто», дерево этого не содержит. Следующий, кто прочтёт запись, будет
# искать в `main` то, чего там нет, — и либо решит, что запись врёт, либо
# сделает работу заново.
#
# ЧТО ПРОВЕРЯЕТСЯ. Из реестра берутся строки, где стоит признак приёмки
# (ЗАКРЫТО / ПРИНЯТО / «окно p-…»), и из них — упоминания ВЕТОК вида `p…`.
# Для каждой такой ветки, если она СУЩЕСТВУЕТ локально, требуется, чтобы она
# была влита в `main`. Ветки нет — хорошо (удалена после слияния); влита —
# хорошо; существует и не влита — ОТКАЗ.
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): работу, принятую БЕЗ упоминания ветки в
# записи. Страж не умеет угадывать, что с чем связано, — он проверяет ровно ту
# связь, которую автор записи назвал сам. Отсюда практическое следствие: имя
# ветки в записи о приёмке — не украшение, а то, что делает приёмку
# проверяемой.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-accepted-branch-merged.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-accepted-branch-merged.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
REG="$ROOT/docs/plans/221.1-bug-sweep.md"

[ -f "$REG" ] || { echo "check-accepted-branch-merged: нет реестра $REG" >&2; exit 1; }
git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 \
    || { echo "check-accepted-branch-merged ok: не git-репозиторий"; exit 0; }

# Ветки, названные в строках с признаком приёмки.
NAMED=$(grep -aE 'ЗАКРЫТО|ПРИНЯТО|окно p' "$REG" 2>/dev/null \
        | grep -aoE '\bp[-a-zA-Z0-9]*[0-9][-a-zA-Z0-9]*\b' \
        | sort -u)

[ -n "$NAMED" ] || { echo "check-accepted-branch-merged ok: веток в записях о приёмке не названо"; exit 0; }

MERGED_LIST="$(git -C "$ROOT" branch --merged main --format='%(refname:short)' 2>/dev/null)"
ALL_LIST="$(git -C "$ROOT" branch --format='%(refname:short)' 2>/dev/null)"

BAD=""
N=0
for b in $NAMED; do
    printf '%s\n' "$ALL_LIST" | grep -qx "$b" || continue     # ветки нет — она удалена, это норма
    printf '%s\n' "$MERGED_LIST" | grep -qx "$b" && continue  # влита — норма
    BAD="$BAD $b"
    N=$((N + 1))
done

if [ "$N" -gt 0 ]; then
    echo "check-accepted-branch-merged: принято в реестре, но НЕ влито — $N:" >&2
    for b in $BAD; do echo "    $b" >&2; done
    echo "    Реестр говорит «закрыто», а дерево этого не содержит. Следующий," >&2
    echo "    кто прочтёт запись, будет искать в main то, чего там нет." >&2
    echo "    Влей ветку либо удали её, если работа вошла другим путём." >&2
    echo "check-accepted-branch-merged: FAIL" >&2
    exit 1
fi

echo "check-accepted-branch-merged ok: все названные в приёмке ветки влиты или удалены"
exit 0
