#!/usr/bin/env bash
# scripts/guards/check-accepted-branch-merged.sh
# Работа окна принята в реестре — значит его ветка влита либо удалена.
#
# ДОМ И ОСНОВАНИЕ: план 231, трек Д (машинное принуждение норм); реестр 221.1
# №594.
#
# ЗАЧЕМ — случай 2026-08-11, дословно. Окно плана 270 сдало отчёт, интегратор
# принял его, переписал по нему КЛАСС записи №576 и очередь работ в 221.1 — и
# про саму ветку забыл. В ней осталось двадцать два файла проб и поправка плана
# на сто с лишним строк. Обнаружилось случайно, при уборке worktree, через
# несколько часов.
#
# Опасность не в потере файлов (они в git), а в РАСХОЖДЕНИИ: реестр говорит
# «закрыто», дерево этого не содержит. Следующий, кто прочтёт запись, будет
# искать в `main` то, чего там нет, — и либо решит, что запись врёт, либо
# сделает работу заново.
#
# ЧТО ПРОВЕРЯЕТСЯ. Из реестра берутся строки, где стоит признак приёмки
# (ЗАКРЫТО / ПРИНЯТО / «окно p-…»), и из них — упоминания ВЕТОК вида `p…`.
# Для каждой такой ветки, если она СУЩЕСТВУЕТ локально, требуется, чтобы она
# была влита в `main`. Ветки нет — хорошо (удалена после слияния); влита —
# хорошо; существует и не влита — ОТКАЗ.
#
# ОСОЗНАННОЕ УПОМИНАНИЕ ВЕТКИ В ДИАГНОЗЕ — метка в ТОЙ ЖЕ СТРОКЕ:
#   [BRANCH-MENTION-OK: <ветка> — причина]
# Зачем она нужна. Страж — построчный греп, а строка реестра занимает ОДНУ
# строку файла. Поэтому ветка, названная в ДИАГНОЗЕ («влит был отставший
# `origin/p274-novac`»), неотличима от ветки, названной как НОСИТЕЛЬ принятой
# работы. Поймано 2026-09-06 на №994: строка ЗАКРЫТА стражем, лежащим в `main`,
# а ветка в ней — ПРЕДМЕТ ОШИБКИ, а не место приёмки; страж покраснел на
# строке, ОПИСЫВАЮЩЕЙ проблему, а не на тех, у кого она есть.
# Метка, а не список исключений — по идиоме дерева (`[3DOT-OK: причина]`
# у check-branch-absorption-method, `[INV-TODO: №NNN]` у check-invariant-discipline):
# осознанная форма разрешается, но обязана назвать себя и причину РЯДОМ с
# местом, а не в отдельном файле, который разойдётся.
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): работу, принятую БЕЗ упоминания ветки в
# записи. Страж не умеет угадывать, что с чем связано, — он проверяет ровно ту
# связь, которую автор записи назвал сам. Отсюда практическое следствие: имя
# ветки в записи о приёмке — не украшение, а то, что делает приёмку
# проверяемой.

# ХЭШ СИЛЬНЕЕ ВЕТКИ: метка [MERGED-AS: <хэш>] (правка 2026-09-17, реестр №1143).
#
# ДЕФЕКТ МЕРЫ, ради которого правка. Страж требовал, чтобы ВЕТКА ЦЕЛИКОМ была
# влита, — а строка реестра утверждает совсем другое: что вошла ЭТА РАБОТА.
# Разница видна на живом окне: ветка `p274-novac` несёт принятую работу И
# продолжает жить новыми коммитами, поэтому `branch --merged` не назовёт её
# никогда. Мера краснела на самом факте того, что окно работает, — то есть
# судила ИМЯ ВЕТКИ вместо СУДЬБЫ РАБОТЫ. Это тот же класс, что №1140: замысел
# верен, неполна мерка.
#
# НОВАЯ ФОРМА. Если строка приёмки несёт [MERGED-AS: <хэш>], страж проверяет
# ровно то, что утверждает запись: является ли этот коммит предком `main`.
# Предок — работа в main, и живая ветка долгом не считается. Не предок — ОТКАЗ,
# причём более сильный, чем прежний: назван коммит, а не догадка по имени.
#
# ПОЧЕМУ СТАРОЕ ПРАВИЛО ОСТАЁТСЯ. Хэша нет у сотен исторических строк, и
# требовать его задним числом значило бы покраснеть на всей истории. Поэтому
# правило двухступенчатое: есть хэш — судим по хэшу; нет — по ветке, как было.
# Случай 2026-08-11 (забытая ветка без хэша) остаётся красным, и это проверено
# самотестом отдельным случаем, а не рассуждением.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-accepted-branch-merged.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-accepted-branch-merged.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
REG="$ROOT/docs/plans/221.1-bug-sweep.md"

[ -f "$REG" ] || { echo "check-accepted-branch-merged: нет реестра $REG" >&2; exit 1; }
git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 \
    || { echo "check-accepted-branch-merged ok: не git-репозиторий"; exit 0; }

# Ветки, названные в строках с признаком приёмки.
# Строки с признаком приёмки — кандидаты. Из каждой берём имена веток, НО
# выбрасываем те, что помечены в ТОЙ ЖЕ строке как упомянутые осознанно.
# Построчно, а не по файлу целиком: метка в ОДНОЙ строке не должна
# прощать ту же ветку в ДРУГОЙ — иначе одна метка глушит весь реестр.
# Строка с меткой [MERGED-AS: <хэш>] судится ПО ХЭШУ, а не по ветке: запись
# утверждает судьбу РАБОТЫ, и хэш — прямое её доказательство.
HASHES=$(grep -aoE '\[MERGED-AS: [0-9a-f]{7,40}\]' "$REG" 2>/dev/null \
         | grep -aoE '[0-9a-f]{7,40}' | sort -u)

NAMED=$(grep -aE 'ЗАКРЫТО|ПРИНЯТО|окно p' "$REG" 2>/dev/null \
        | while IFS= read -r _line; do
              case "$_line" in
                  *'[MERGED-AS: '*) continue ;;  # судится хэшем, ветка не при чём
              esac
              for _b in $(printf '%s\n' "$_line" \
                          | grep -aoE '\bp[-a-zA-Z0-9]*[0-9][-a-zA-Z0-9]*\b'); do
                  case "$_line" in
                      *"[BRANCH-MENTION-OK: $_b "*) : ;;   # осознанно и с причиной
                      *) printf '%s\n' "$_b" ;;
                  esac
              done
          done \
        | sort -u)



MERGED_LIST="$(git -C "$ROOT" branch --merged main --format='%(refname:short)' 2>/dev/null)"
ALL_LIST="$(git -C "$ROOT" branch --format='%(refname:short)' 2>/dev/null)"

BAD=""
N=0

# (1) Хэши. Предок main — работа вошла; не предок — отказ, с именем коммита.
# Неизвестный объект НЕ прощается: запись ссылается на то, чего в дереве нет.
for h in $HASHES; do
    if git -C "$ROOT" cat-file -e "$h^{commit}" 2>/dev/null; then
        git -C "$ROOT" merge-base --is-ancestor "$h" main 2>/dev/null && continue
        BAD="$BAD хэш:$h(не-предок-main)"
    else
        BAD="$BAD хэш:$h(нет-такого-коммита)"
    fi
    N=$((N + 1))
done

# (2) Ветки — прежнее правило, для строк без хэша.
for b in $NAMED; do
    printf '%s\n' "$ALL_LIST" | grep -qx "$b" || continue     # ветки нет — она удалена, это норма
    printf '%s\n' "$MERGED_LIST" | grep -qx "$b" && continue  # влита — норма
    BAD="$BAD $b"
    N=$((N + 1))
done

if [ "$N" -gt 0 ]; then
    echo "check-accepted-branch-merged: принято в реестре, но НЕ влито — $N:" >&2
    for b in $BAD; do echo "    $b" >&2; done
    echo "    Реестр говорит «закрыто», а дерево этого не содержит. Следующий," >&2
    echo "    кто прочтёт запись, будет искать в main то, чего там нет." >&2
    echo "    Влей ветку либо удали её, если работа вошла другим путём." >&2
    echo "check-accepted-branch-merged: FAIL" >&2
    exit 1
fi

set -- $HASHES; _nh=$#
set -- $NAMED;  _nb=$#
echo "check-accepted-branch-merged ok: работа принятых записей в main (хэшей $_nh, веток $_nb)"
exit 0
