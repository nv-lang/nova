#!/usr/bin/env bash
# Страж: одна строка реестра — ОДИН действующий вердикт и ОДИН статус.
#
# ЗАЧЕМ. Строки дописываются в хвост: расследование продолжилось, вердикт
# изменился, приписка легла в конец. Человек читает ПОСЛЕДНЕЕ и видит правду;
# сканеры читают ПЕРВОЕ и видят вердикт месячной давности. Строка при этом
# выглядит безупречно — расхождение не видно никому, кроме машины.
#
# ЧТО ЭТО СТОИЛО (замер 2026-08-18, ревизия по вопросу владельца «всё ли
# найденное добавлено в план»): СЕМЬ строк несли по два-три «БЛОКИРУЕТ ТЕГ»,
# пять из них ПРОТИВОРЕЧИВЫЕ, и ТРИДЦАТЬ СЕМЬ — по два `Статус:`. Заглавные
# числа релиза врали в ОБЕ стороны сразу:
#   * блокеров насчитывалось 67 при настоящих 62 — три строки со СНЯТЫМ
#     вердиктом продолжали числиться блокерами;
#   * #611/#660/#662 числились «K1 без маршрута», хотя давно ЗАКРЫТЫ;
#   * четыре ПЕРЕОТКРЫТЫЕ строки (446, 447, 452, 465) машина считала
#     закрытыми и не показывала вовсе.
#
# ПОЧЕМУ ЭТО К1-ПО ПОСЛЕДСТВИЯМ, а не опрятность: по этим числам судят о
# готовности тега. Реестр — источник истины релиза, и он тихо расходился сам с
# собой.
#
# КАК ПИСАТЬ ПРАВИЛЬНО. Менять вердикт НА МЕСТЕ; прежний оставлять летописью
# без маркера — `ТЕГ БЛОКИРОВАЛ (историческая запись): …`, `Статус был: …`.
# История сохраняется дословно, притязание на действующий ответ — у одного.
#
# НОЛЬ, БЕЗ ХРАПОВИКА: после уборки 2026-08-18 дублей ноль. Храповик здесь был
# бы неуместен — один дубль уже означает, что какое-то из чисел неверно.
#
# $1 — корень. Самотест — selftest/test-check-registry-single-verdict.sh
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u
export LC_ALL=C

NAME="check-registry-single-verdict"
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CORE="$(dirname "$0")/registry-verdict-scan.py"

[ -f "$CORE" ] || { echo "$NAME: FAIL — нет ядра $CORE" >&2; exit 1; }

OUT=$(python "$CORE" "$ROOT" 2>&1)
if [ $? -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    printf '%s\n' "$OUT" | tail -5 >&2
    exit 1
fi

DV=$(printf '%s\n' "$OUT" | sed -n 's/^dup_verdict=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
DS=$(printf '%s\n' "$OUT" | sed -n 's/^dup_status=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
DR=$(printf '%s\n' "$OUT" | sed -n 's/^dup_route=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
NS=$(printf '%s\n' "$OUT" | sed -n 's/^verdict_no_status=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
case "$NS" in ''|*[!0-9-]*) NS=0;; esac
case "$DV" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число вердиктов" >&2; exit 1;; esac
case "$DS" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число статусов" >&2; exit 1;; esac
case "$DR" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число маршрутов" >&2; exit 1;; esac
if [ "$DV" -lt 0 ] || [ "$DS" -lt 0 ] || [ "$DR" -lt 0 ]; then
    echo "$NAME: FAIL — ядро не нашло реестр (переехал?)" >&2
    exit 1
fi

if [ "$DV" -ne 0 ] || [ "$DS" -ne 0 ] || [ "$DR" -ne 0 ]; then
    echo "$NAME: FAIL — строк с двойным вердиктом: $DV, статусом: $DS, маршрутом: $DR" >&2
    printf '%s\n' "$OUT" | grep -v '^dup_' | head -12 >&2
    echo "    Сканеры читают ПЕРВОЕ вхождение, дописки идут в хвост — значит" >&2
    echo "    машина судит по устаревшему ответу, а человек по свежему, и" >&2
    echo "    заглавные числа релиза расходятся с содержимым строк." >&2
    echo "    Меняй вердикт НА МЕСТЕ; прежний оставляй летописью без маркера:" >&2
    echo "      ТЕГ БЛОКИРОВАЛ (историческая запись): …   /   Статус был: …" >&2
    echo "    У МАРШРУТА последний НЕ побеждает автоматически — решай по смыслу" >&2
    echo "    и снимай маркер с недействующего: ЗАМЕТКА О ХОДЕ (не маршрут): …" >&2
    exit 1
fi

# ВЕРДИКТ БЕЗ СТАТУСА — строка, про которую машина не знает НИЧЕГО, и это
# не мелочь: страж релиза считает такую ОТКРЫТОЙ, то есть заглавное число
# блокеров включает строки, где статус просто не написан. Нашлось тем, что
# ДВА СКАНЕРА РАЗОШЛИСЬ: 55 блокеров против 35 при честном подсчёте.
# Десять таких строк среди блокеров заполнены 2026-08-19; остальные —
# храповик, который может только убывать.
NS_BASE_FILE="$ROOT/scripts/guards/verdict-no-status.baseline"
NS_BASE=$(grep -E '^rows=' "$NS_BASE_FILE" 2>/dev/null | head -1 | cut -d= -f2)
case "$NS_BASE" in ''|*[!0-9]*)
    echo "$NAME: FAIL — база verdict-no-status не задана ($NS_BASE_FILE)" >&2
    exit 1;;
esac
if [ "$NS" -gt "$NS_BASE" ]; then
    echo "$NAME: FAIL — строк с вердиктом, но БЕЗ статуса стало больше: $NS > $NS_BASE" >&2
    printf '%s\n' "$OUT" | grep 'verdict without a status' | head -12 >&2
    echo "    Строка, объявившая вердикт, обязана объявить и статус: иначе" >&2
    echo "    страж релиза считает её открытой по умолчанию, а написано" >&2
    echo "    ничего — и заглавное число врёт молча." >&2
    exit 1
fi
if [ "$NS" -lt "$NS_BASE" ]; then
    echo "$NAME ok: вердиктов без статуса $NS (база $NS_BASE) — ЗАМЕТКА: опусти базу с летописью"
    exit 0
fi

echo "$NAME ok: у каждой строки реестра ровно один действующий вердикт, статус и маршрут"
exit 0
