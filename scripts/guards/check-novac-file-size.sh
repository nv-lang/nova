#!/bin/sh
# scripts/guards/check-novac-file-size.sh — потолок длины файла в novac/src.
#
# ПРАВИЛО (план 274, решение 12, §10.4): файл в novac/src/**/*.nv не длиннее
# 1000 строк. Жёстко, БЕЗ базлайна: novac пишется заново, ни одного законного
# исключения в дереве быть не должно — файл, переросший потолок, режется тем
# же слиянием, а не вносится в список прощённых.
#
# ЧТО ПРОВЕРЯЕТ: только длину *.nv-файлов под novac/src (wc -l).
# ЧЕГО НЕ ПРОВЕРЯЕТ (сказано честно): содержательную связность файла — файл
# на 999 строк из трёх несвязных тем страж пропустит, это дело приёмки;
# не-.nv файлы и остальное дерево вне novac/src — другой периметр.
#
# Аргумент $1 — корень репозитория (по умолчанию — вычислить от себя);
# $2 — override сканируемой директории (для самотеста; default $ROOT/novac/src).
#
# Проверялся: Windows (Git Bash), 2026-08-14.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
LIMIT=1000

# Страж до кода легален: novac ещё может не существовать.
if [ ! -d "$SRC" ]; then
    echo "check-novac-file-size ok: судить нечего (нет $SRC)"
    exit 0
fi

N=0
BAD=""
while IFS= read -r f; do
    [ -n "$f" ] || continue
    N=$((N+1))
    lines=$(wc -l < "$f")
    if [ "$lines" -gt "$LIMIT" ]; then
        BAD="$BAD  $f — $lines строк
"
    fi
done <<EOF
$(find "$SRC" -type f -name '*.nv')
EOF

if [ -n "$BAD" ]; then
    echo "check-novac-file-size: FAIL — файлы длиннее $LIMIT строк (274 реш. 12, §10.4):" >&2
    printf '%s' "$BAD" >&2
    echo "  Чинить так: резать файл по смыслу на со-равные файлы того же модуля" >&2
    echo "  (папка = один модуль), не заводить базлайн и не просить исключение." >&2
    exit 1
fi

if [ "$N" -eq 0 ]; then
    echo "check-novac-file-size ok: судить нечего (0 .nv-файлов в $SRC)"
    exit 0
fi

echo "check-novac-file-size ok: файлов $N, все не длиннее $LIMIT строк"
exit 0
