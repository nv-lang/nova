#!/bin/sh
# scripts/guards/lib/novac.sh — общие функции стражей novac (274.3, класс К-A).
# Подключение: . "$ROOT/scripts/guards/lib/novac.sh"
#
# novac_require_bin NAME ROOT BIN — F1: «судить нечего» законно ТОЛЬКО пока
#   novac/src/main.nv не существует. Как только исходник есть, отсутствие
#   бинаря = гейт его не собрал (или сборка упала) — красный, не «ok».
#
# novac_is_panic_rc RC — F3: ЕДИНОЕ определение паники вместо трёх разных
#   порогов (>=124 в фаззере, >=128 в страже, >=124 в дифф-раннере).
#   Уточнение контракта (274.3/F3, проверено живым фаззером 2026-08-15):
#   план §7 говорит «на любом входе novac завершается кодом 0 или 1» — это
#   про ВЕРДИКТ компилятора (принял / отверг с диагностикой). Кроме вердикта
#   у CLI есть ДВЕРЬ: файл не читается / не UTF-8 / неверный вызов — это
#   exit 2 с честным сообщением (документировано в novac/src/main.nv, носитель
#   контракта — маркер EXPECT_EXIT_CODE 2). Мутационный фаззер порождает
#   не-UTF-8 входы штатно: 15 таких кейсов из 192 честно отвечают «not UTF-8»
#   и выходят 2 — паникой это не является.
#   Итог: паника = код НЕ 0, НЕ 1 и НЕ 2 (сюда попадают 3 — abort рантайма на
#   Windows, 101 — паника Nova, 124 — таймаут, >=128 — сигнал), либо слово
#   'panic' в stderr (это проверяет вызывающий), либо МОЛЧАЛИВАЯ дверь — см.
#   novac_is_silent_door: exit 2 без единого байта вывода означает отказ без
#   причины, а это тот же класс «тихо», что и паника.
#
# novac_is_silent_door RC OUTFILE ERRFILE — exit 2 без вывода = красный.
novac_require_bin() {
    _name="$1"; _root="$2"; _bin="$3"
    if [ -f "$_bin" ]; then return 0; fi
    if [ -f "$_root/novac/src/main.nv" ]; then
        echo "$_name: FAIL — novac/src существует, а бинаря $_bin нет: гейт обязан собрать novac шагом novac-build (274.3/F1); «судить нечего» больше не законно" >&2
        exit 1
    fi
    echo "$_name ok: судить нечего (novac/src ещё нет)"
    exit 0
}

novac_is_panic_rc() {
    [ "$1" -ne 0 ] && [ "$1" -ne 1 ] && [ "$1" -ne 2 ]
}

novac_is_silent_door() {
    [ "$1" -eq 2 ] || return 1
    [ -s "$2" ] && return 1
    [ -s "$3" ] && return 1
    return 0
}

# novac_load_scale ROOT — F10: поправка на ЗАГРУЗКУ машины, общая для всех
# бюджетов времени. Печатает множитель в сотых (100 = машина как при записи
# базы, 300 = втрое медленнее). Считается по эталонному fork оболочки — под
# MSYS это главный источник шума — против записанного в базе `cal-ms`.
# Абсолютный wall-clock судить нельзя: один и тот же `novac check` даёт 150мс
# на тихой машине и 3300мс под полным прогоном гейта, а дифф-раннер — 50с и
# 146с (оба случая пойманы ложными красными 2026-08-15).
novac_load_scale() {
    _base="$1/scripts/guards/novac-iteration-cost.baseline"
    _cal_base=$(tr -d '\r' < "$_base" 2>/dev/null | sed -n 's/^cal-ms \([0-9][0-9]*\)$/\1/p' | head -n 1)
    [ -n "$_cal_base" ] && [ "$_cal_base" -gt 0 ] 2>/dev/null || { echo 100; return 0; }
    # МЕДИАНА ИЗ ДЕВЯТИ, А НЕ МИНИМУМ ИЗ ТРЁХ (правка 2026-09-09, найдено
    # окном 274, подтверждено мною чтением и замером).
    #
    # ЧТО БЫЛО НЕ ТАК. Здесь брался МИНИМУМ из трёх замеров форка. Минимум из
    # серии — это классический способ измерить ЛУЧШИЙ МОМЕНТ машины, то есть
    # ОТФИЛЬТРОВАТЬ загрузку. А функция называется мерой загрузки, и её
    # результат делает бюджет БОЛЬШЕ, когда машина занята. То есть она
    # отфильтровывала ровно тот сигнал, ради которого заведена.
    #
    # ЗАМЕР, КОТОРЫЙ ЭТО ПОКАЗАЛ (2026-09-09, машина под идущим ярусом):
    #   * окно 274: поправка ВНУТРИ яруса 346, при отдельном прогоне на тихой
    #     машине 413 — то есть при ВЫРОСШЕЙ загрузке поправка УМЕНЬШИЛАСЬ;
    #   * мой замер: пять вызовов подряд при неизменной загрузке дали
    #     256, 298, 260, 236, 235 — разброс 27%, а сырые замеры форка
    #     135..200мс, разброс 148%.
    # Вердикт «уложился / не уложился» решался тем, какой образец достался
    # стражу. Это не шум измерения предмета, это неверная мера.
    #
    # ПОЧЕМУ МЕДИАНА. Нужна ТИПИЧНАЯ скорость форка сейчас: минимум даёт
    # незагруженный момент (занижает), максимум ловит любой единичный всплеск
    # (завышает и прыгает). Медиана устойчива к обоим хвостам. Девять замеров
    # вместо трёх стоят девяти пустых оболочек — на фоне яруса это ничто.
    _samples=""
    for _i in 1 2 3 4 5 6 7 8 9; do
        _s=$(date +%s%N | cut -c1-13)
        sh -c : >/dev/null 2>&1
        _e=$(( $(date +%s%N | cut -c1-13) - _s ))
        _samples="$_samples$_e\n"
    done
    _b=$(printf "$_samples" | sort -n | sed -n '5p')
    [ -n "$_b" ] || _b=999999
    _sc=$(( _b * 100 / _cal_base ))
    [ "$_sc" -lt 100 ] && _sc=100
    [ "$_sc" -gt 2000 ] && _sc=2000
    echo "$_sc"
}

# novac_find_oracle ROOT — путь к бинарю ОРАКУЛА или пусто (rc=1).
#
# ОДНО место, знающее имя файла. 2026-08-18, разбор красного CI: дифф-страж и
# страж свежести оболочки печатали на Linux «судить нечего (оракул не собран)»,
# хотя job собирает его командой cargo. Причина — одна буква: искали
# `nova.exe`, а на Linux бинарь зовётся `nova`. Главное доказательство
# корректности проекта — дифф против оракула — не выполнялось на CI и
# держалось только на машине автора, причём ЗЕЛЁНЫМ молчанием, неотличимым
# от «проверено» (класс K-A, 274.3/F1).
novac_find_oracle() {
    _fo_root="$1"
    for _fo_c in \
        "$_fo_root/nova-cli/target/release/nova.exe" \
        "$_fo_root/nova-cli/target/release/nova"; do
        [ -f "$_fo_c" ] && { printf '%s\n' "$_fo_c"; return 0; }
    done
    # Worktree без своего target: сборка одна на все деревья (реестр #650).
    _fo_main=$(git -C "$_fo_root" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)
    if [ -n "$_fo_main" ]; then
        for _fo_c in \
            "$_fo_main/../nova-cli/target/release/nova.exe" \
            "$_fo_main/../nova-cli/target/release/nova"; do
            [ -f "$_fo_c" ] && { printf '%s\n' "$_fo_c"; return 0; }
        done
    fi
    return 1
}

# novac_bin ROOT — путь к бинарю КАРИНЫ, который ЗАПУСКАТЬ (реестр 221.1 №1607).
#
# ОДНО место, решающее, какой из двух файлов — Карина. Переменная NOVAC вызывающего
# первой; иначе более СВЕЖИЙ из novac/target/novac.exe и novac/target/novac; если нет
# ни одного — путь сборки этой платформы (вызывающий судит отсутствие сам, обычно
# novac_require_bin). Почему не по имени: сборка на Linux пишет `novac`, а `novac.exe`,
# оставшийся от прежней сборки, побеждал именем — облачная сессия p274-carina-k1
# 2026-10-02 мерила Карину, которой уже не было (замеры 140/161 и 124/144, 15 ложных
# красных в no-cascade и diag-schema). До двери выбор стоял в двадцати местах, и каждое
# знало своё имя файла; страж check-novac-bin-door держит, чтобы так не стало снова.
novac_bin() {
    if [ -n "${NOVAC:-}" ]; then printf '%s\n' "$NOVAC"; return 0; fi
    _nb_a="$1/novac/target/novac.exe"; _nb_b="$1/novac/target/novac"
    if [ -f "$_nb_a" ] && [ -f "$_nb_b" ]; then
        if [ "$_nb_b" -nt "$_nb_a" ]; then printf '%s\n' "$_nb_b"; else printf '%s\n' "$_nb_a"; fi
    elif [ -f "$_nb_a" ]; then printf '%s\n' "$_nb_a"
    elif [ -f "$_nb_b" ]; then printf '%s\n' "$_nb_b"
    else novac_bin_out "$1"; fi
}

# novac_oracle_key ROOT ORACLE CLANG — ключ ПО СОДЕРЖИМОМУ для бинаря, который оракул
# собрал из фикстуры (реестр 221.1 №1717). Бинарь фикстуры — функция четырёх вещей:
# самого оракула, рантайма и std, которые оракул читает С ДИСКА при сборке
# (compiler-codegen/nova_rt, вендоренные libuv/bdwgc, std/src), clang, которым он
# собирает, и текста фикстуры (его добавляет вызывающий). Ключ знает первые три.
#
# Прежний ключ смоука — штамп ВРЕМЕНИ оракула плюс самый свежий заголовок рантайма —
# знал меньше, чем то, от чего бинарь зависит (правка std или runtime-.c без
# пересборки оракула отдавала старый бинарь), и при этом менялся на КАЖДОЙ сборке
# оракула: на CI оракул собирается заново в каждом прогоне, и кэш между прогонами был
# невозможен в принципе. Содержимое снимается git-ом: дерево HEAD по путям (одна
# строка хеша на каталог, подмодули — их коммитом), плюс грязная разница рабочего
# дерева и неотслеживаемые файлы — правка без коммита тоже меняет ключ. Вне git ключа
# нет (rc=1): вызывающий остаётся при штампе времени, как было.
# Кроме деревьев оракул слушает ОКРУЖЕНИЕ и КОРНЕВОЙ nova.toml: NOVA_STD_PATH и ключ
# `std = "..."` (compiler-codegen/src/manifest.rs) уводят std в другой каталог,
# NOVA_RT_DIR / NOVA_CG_INCLUDE (nova-cli/src/main.rs, RepoPaths) — рантайм; ключ
# знает их значения и текст nova.toml (охота guards 2026-10-05, находка 8). Clang —
# его путь и версия; нет clang — так и пишется, а не пустая строка.
# Не знает: файлы, игнорируемые git, в compiler-codegen/ и std/ — сборочный мусор
# меняет ключ каждый прогон, а оракул его, по чтению, не читает.
novac_oracle_key() {
    _ok_root="$1"; _ok_oracle="$2"; _ok_cc="$3"
    _ok_paths="compiler-codegen std"
    _ok_tree=$(git -C "$_ok_root" rev-parse HEAD:compiler-codegen HEAD:std 2>/dev/null) || return 1
    {
        printf '%s\n' "$_ok_tree"
        sha256sum < "$_ok_oracle"
        # shellcheck disable=SC2086
        git -C "$_ok_root" diff HEAD --binary -- $_ok_paths 2>/dev/null
        # shellcheck disable=SC2086
        git -C "$_ok_root" ls-files -o --exclude-standard -z -- $_ok_paths 2>/dev/null \
            | (cd "$_ok_root" && xargs -0 -r sha256sum)
        cat "$_ok_root/nova.toml" 2>/dev/null
        printf 'env NOVA_STD_PATH=%s NOVA_RT_DIR=%s NOVA_CG_INCLUDE=%s\n' \
            "${NOVA_STD_PATH:-}" "${NOVA_RT_DIR:-}" "${NOVA_CG_INCLUDE:-}"
        printf 'clang %s: ' "$_ok_cc"
        "$_ok_cc" --version 2>/dev/null | head -n 1 || echo "нет"
    } | sha256sum | cut -c1-16
}

# novac_pool FN LIST [J] — FN <номер строки> <строка> для каждой строки файла LIST,
# в J потоков (по умолчанию novac_pool_jobs). Реестр 221.1 №1717: стражи над корпусом
# фикстур шли одним потоком, корпус растёт мержами, а предел постоянен — каждые ~30
# новых фикстур снимали стража без вердикта. Поток s берёт строки с номером
# i ≡ s (mod J): делёж детерминирован, и вызывающий ОБЯЗАН сверить, что итог есть у
# каждой строки (FN пишет файл по номеру) — строка без итога красная, а не пропуск.
# FN зовётся с ЗАКРЫТЫМ stdin: стандартный ввод потока — сам список, и программа,
# читающая ввод (бинарь фикстуры в смоуке), съедала строки своего потока (охота
# guards 2026-10-05, находка 4). Каталог итогов вызывающий берёт из mktemp: в
# переиспользованном каталоге чужой итог прошёл бы за свой (находки 2–3).
novac_pool() {
    _np_fn="$1"; _np_list="$2"; _np_j="${3:-$(novac_pool_jobs)}"
    _np_s=0
    while [ "$_np_s" -lt "$_np_j" ]; do
        ( _np_i=0
          while IFS= read -r _np_f; do
              _np_i=$((_np_i + 1))
              [ $(( (_np_i - 1) % _np_j )) -eq "$_np_s" ] || continue
              "$_np_fn" "$_np_i" "$_np_f" </dev/null
          done < "$_np_list" ) &
        _np_s=$((_np_s + 1))
    done
    wait
}

# novac_pool_jobs — число потоков пула: NOVAC_POOL_JOBS, иначе число ядер (nproc;
# нет его — 2). Ведущие нули снимаются: `08` в арифметике оболочки — неверное
# восьмеричное, и пул умирал целиком (охота guards 2026-10-05, находка 1).
novac_pool_jobs() {
    _pj_n=$(nproc 2>/dev/null || echo 2)
    _pj=$(printf '%s' "${NOVAC_POOL_JOBS:-$_pj_n}" | sed 's/^0*//')
    case "$_pj" in ''|*[!0-9]*) _pj=$_pj_n ;; esac
    case "$_pj" in ''|*[!0-9]*|0) _pj=2 ;; esac
    printf '%s\n' "$_pj"
}

# novac_check BIN FILE OUT ERR — `BIN check FILE`: stdout в OUT, stderr в ERR, код
# возврата — свой. Реестр 221.1 №1717, замер CI 2026-10-05 (run 37353522969): пять
# стражей корпуса (no-panic, diag-schema, no-cascade, fixture-expect, этап 1
# дифференциала) звали `novac check` по ОДНИМ И ТЕМ ЖЕ фикстурам — ~1200 запусков
# там, где нужно ~390, — и на четырёх ядрах трое из них снимались пределом 600с.
# Гейт теперь прогоняет корпус ОДИН раз (scripts/tools/novac-check-cache.sh) в
# каталог NOVAC_CHECK_CACHE, и дверь отдаёт записанный итог, если он снят ТЕМ ЖЕ
# бинарём (файл `bin` каталога) для ТОГО ЖЕ пути (файл `.path` записи: ключ —
# cksum пути, и совпадение ключа без совпадения пути — промах, а не чужой итог).
# Нет каталога, другой бинарь, нет записи — дверь зовёт novac сама, как раньше.
novac_check() {
    _nc_bin="$1"; _nc_f="$2"; _nc_out="$3"; _nc_err="$4"
    if [ -n "${NOVAC_CHECK_CACHE:-}" ] && [ -f "$NOVAC_CHECK_CACHE/bin" ]; then
        read -r _nc_cb < "$NOVAC_CHECK_CACHE/bin"
        if [ "$_nc_cb" = "$_nc_bin" ]; then
            _nc_e="$NOVAC_CHECK_CACHE/$(novac_check_key "$_nc_f")"
            _nc_rc=""; _nc_p=""
            [ -f "$_nc_e.rc" ] && read -r _nc_rc < "$_nc_e.rc"
            [ -f "$_nc_e.path" ] && read -r _nc_p < "$_nc_e.path"
            case "$_nc_rc" in
                ''|*[!0-9]*) ;;
                *)  if [ "$_nc_p" = "$_nc_f" ]; then
                        cp "$_nc_e.out" "$_nc_out" && cp "$_nc_e.err" "$_nc_err" && return "$_nc_rc"
                    fi ;;
            esac
        fi
    fi
    "$_nc_bin" check "$_nc_f" > "$_nc_out" 2> "$_nc_err" </dev/null
}

# novac_check_key FILE — имя записи кэша для пути (cksum пути и его длина).
novac_check_key() {
    printf '%s' "$1" | cksum | tr ' ' '-'
}

# novac_bin_out ROOT — куда СОБИРАТЬ Карину: `novac.exe` на Windows, `novac` иначе
# (так её собирает CI, .github/workflows/nova-gate.yml). Пара к novac_bin.
novac_bin_out() {
    case "$(uname -s 2>/dev/null)" in
        MINGW*|MSYS*|CYGWIN*) printf '%s\n' "$1/novac/target/novac.exe" ;;
        *) printf '%s\n' "$1/novac/target/novac" ;;
    esac
}
