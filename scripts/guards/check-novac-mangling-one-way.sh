#!/bin/sh
# scripts/guards/check-novac-mangling-one-way.sh — дверь мэнглинга
# ОДНОСТОРОННЯЯ: C-имя вычисляется из сущности и НИКОГДА не разбирается
# обратно (конвенция П24; владелец 2026-08-16).
#
# ОТКУДА ПРАВИЛО. Нормативный D285 §3 описывает резолв метода так: «извлечь
# base-type из obj_ty — strip `Nova_`/`NovaValue_` prefix, `*`, часть до
# первого `____`». То есть идентичность типа восстанавливается РАЗБОРОМ
# МАНГЛ-ИМЕНИ: структурная информация выбрасывается в строку, а потом строка
# парсится обратно. Владелец назвал это бредом, и он прав — ни один
# серьёзный компилятор так не делает: rustc резолвит по `Ty`/`DefId`, а
# `rustc_symbol_mangling` — односторонняя функция от инстанса; символьные
# имена не парсятся ради семантики. Тот же D315 это прямо запрещает
# («мангл-имя — решение лоуэринга, не свойство типа»), то есть спека сама
# себе противоречит, а описанный алгоритм — это описание реализации оракула,
# а не язык. novac обязан не унаследовать его; сегодня он чист.
#
# ПРОВЕРЯЕТ по novac/src/**/*.nv (комментарии не судятся — они законно
# ОПИСЫВАЮТ форму чужих имён):
#   * строковый разбор ABI-имени: `starts_with("Nova`, `contains("____")`,
#     `find("____")`, `strip`/`trim_start` с ABI-приставкой, сравнение с
#     литералом, начинающимся на `Nova_`/`NovaValue_`;
#   * применение строковой проверки НЕПОСРЕДСТВЕННО к результату двери:
#     `c_type(...).starts_with(`, `c_struct(...).contains(` и т.п.
# НЕ ПРОВЕРЯЕТ: построение имён (это работа двери); имена C-хелперов
#   рантайма в шаблоне оболочки (там C, а не Nova); косвенный разбор через
#   промежуточную переменную (появится — правило уточняется вместе с ним).
#
# $1 — корень репозитория; $2 — override сканируемой директории (самотест).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-mangling-one-way

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi
NF=$(find "$SRC" -type f -name '*.nv' | wc -l | tr -d '[:space:]')
if [ "$NF" -eq 0 ]; then
    echo "$NAME ok: судить нечего (в $SRC файлов .nv: 0)"
    exit 0
fi

BAD=$(find "$SRC" -type f -name '*.nv' | sort | while IFS= read -r f; do
    rel=${f#"$SRC"/}
    tr -d '\r' < "$f" | awk -v rel="$rel" '
        {
            line = $0
            sub(/\/\/.*$/, "", line)          # комментарии не судятся
            if (line ~ /^[[:space:]]*$/) next
            why = ""
            if (line ~ /(starts_with|contains|find|index_of)\([[:space:]]*"(Nova_|NovaValue_)/) why = "строковая проверка ABI-приставки"
            else if (line ~ /"____"/) why = "разбор по разделителю мономорфизации ____"
            else if (line ~ /(strip|trim_start|trim_prefix)[a-z_]*\([[:space:]]*"(Nova_|NovaValue_)/) why = "срезание ABI-приставки"
            else if (line ~ /==[[:space:]]*"(Nova_|NovaValue_)/) why = "сравнение с ABI-именем как со значением"
            else if (line ~ /c_(type|struct|method|fn|tag|maker)\([^)]*\)\.[a-z_]+\(/) why = "строковая операция прямо на результате двери мэнглинга"
            if (why != "") {
                t = line; gsub(/^[[:space:]]+/, "", t)
                printf "  %s:%d: %s: %s\n", rel, NR, why, substr(t, 1, 60)
            }
        }
    '
done)

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — C-имя разбирается обратно (конвенция П24):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Идентичность живёт в РЕЕСТРЕ, а не в строке: спрашивай реестр (id типа," >&2
    echo "  голову конструктора, строку вызываемого), а не имя. Дверь мэнглинга —" >&2
    echo "  функция ИЗ сущности В строку, и обратного хода у неё нет по построению." >&2
    echo "  Образец: rustc резолвит по Ty/DefId, rustc_symbol_mangling односторонний." >&2
    exit 1
fi

echo "$NAME ok: файлов .nv: $NF, разборов C-имени: 0 (дверь односторонняя)"
exit 0
