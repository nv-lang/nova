#!/usr/bin/env bash
# scripts/guards/check-doc-language-pairs.sh
# Публичная страница живёт на ДВУХ языках, в ДВУХ файлах, и каждая сторона
# написана на том языке, который обещает её имя.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №608, №609; указание владельца 2026-08-12
# («нужны два языка публичных док + страж, что есть два языка в разных файлах
# … и что они реально анг + русс; анг называется без постфикса, рус — с .ru.»).
#
# КОНВЕНЦИЯ ИМЁН — ОДНА НА ВЕСЬ ПРОЕКТ:
#     `X.md`     — английская сторона (без постфикса)
#     `X.ru.md`  — русская сторона
# `docs/guide/` жил так всегда; `spec/` до 2026-08-12 жил наоборот (`X.md`
# русский, `X.en.md` английский) — переименован. Две конвенции в одном
# репозитории означали, что читатель обязан помнить, в какой он папке.
#
# ЗАЧЕМ ИМЕННО ЭТОТ СТРАЖ. `spec/GLOSSARY.en.md` назывался английской
# стороной, а внутри был русский текст, и русской стороны у него не было вовсе.
# Не поймал никто: соседний `check-doc-conventions.sh` вынужден был ТРИЖДЫ
# выписать этому файлу исключение вместо того, чтобы назвать несоответствие.
# Исключение в трёх местах — верный признак, что лжёт имя, а не проверка.
#
# ЧТО ПРОВЕРЯЕТСЯ — три вещи, каждая своим сообщением:
#   1. ПАРА. У английской `X.md` есть русская `X.ru.md`, и наоборот. Известные
#      пробелы — в `doc-pair-missing.baseline`, и КАЖДАЯ строка там несёт номер
#      записи реестра: имя без номера — отложенный долг без следа (урок №559).
#   2. ЯЗЫК СТОРОНЫ. Английская сторона написана по-английски (кириллицы в
#      прозе почти нет), русская — по-русски (кириллица есть). Проверяется
#      ЛИЧНОСТЬ файла целиком, а не отдельные затесавшиеся строки: их считает
#      храповик `mixed_language` в `check-doc-conventions.sh`, и дублировать
#      его тут нечего.
#   3. СТАРАЯ ФОРМА НЕ ВОЗВРАЩАЕТСЯ. Файла `*.en.md` в перимeтре быть не
#      должно: конвенция одна, и второй двери у неё нет.
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): качества перевода. Страж отвечает на вопрос
# «на том ли языке это написано», а не «хорошо ли». Расхождение сторон по
# смыслу считает `translation_drift` в соседнем страже.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-doc-language-pairs.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-doc-language-pairs.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
BASE_FILE="${NOVA_DOC_PAIR_BASELINE:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/doc-pair-missing.baseline}"

# Периметр: публичные страницы. `spec/decisions/` сюда НЕ входит — это
# нормативные D-блоки без английской стороны, и их миграция названа отдельной
# записью реестра, а не спрятана в молчании этого стража (№610).
DIRS="spec docs/guide"

FAILED=0
say_fail() { echo "check-doc-language-pairs: $1" >&2; FAILED=1; }

# Доля строк прозы (вне ```-блоков) с кириллицей, в процентах; -1 = нет прозы.
cyr_pct() {
    awk '
        /^[[:space:]]*```/ { infence = !infence; next }
        infence { next }
        /^[[:space:]]*$/ { next }
        { total++; if ($0 ~ /[\xd0\xd1]/) cyr++ }
        END { if (total == 0) print -1; else printf "%d\n", (cyr * 100) / total }
    ' "$1"
}

# Известные пробелы пары. Каждая строка ОБЯЗАНА нести номер записи.
BASELINE=""
if [ -f "$BASE_FILE" ]; then
    while IFS= read -r line; do
        case "$line" in ''|'#'*) continue ;; esac
        name=$(printf '%s' "$line" | awk '{print $1}')
        case "$line" in
            *№[0-9]*) : ;;
            *) say_fail "строка базы без номера записи: $line — имя без номера это долг без следа" ;;
        esac
        BASELINE="$BASELINE $name"
    done < "$BASE_FILE"
fi
in_baseline() { case " $BASELINE " in *" $1 "*) return 0 ;; esac; return 1; }

for d in $DIRS; do
    [ -d "$ROOT/$d" ] || continue

    # --- 1. Пара ----------------------------------------------------------
    for f in "$ROOT/$d"/*.md; do
        [ -f "$f" ] || continue
        case "$f" in *.ru.md) continue ;; esac
        b=$(basename "$f" .md)
        if [ ! -f "$ROOT/$d/$b.ru.md" ] && ! in_baseline "$d/$b.md"; then
            say_fail "у английской $d/$b.md нет русской стороны $d/$b.ru.md"
        fi
    done
    for f in "$ROOT/$d"/*.ru.md; do
        [ -f "$f" ] || continue
        b=$(basename "$f" .ru.md)
        if [ ! -f "$ROOT/$d/$b.md" ] && ! in_baseline "$d/$b.ru.md"; then
            say_fail "у русской $d/$b.ru.md нет английской стороны $d/$b.md"
        fi
    done

    # --- 2. Язык стороны --------------------------------------------------
    for f in "$ROOT/$d"/*.md; do
        [ -f "$f" ] || continue
        p=$(cyr_pct "$f")
        [ "$p" -lt 0 ] && continue
        case "$f" in
            *.ru.md)
                [ "$p" -lt 20 ] && say_fail "$(basename "$f") стоит на русской стороне, но кириллицы в прозе всего ${p}% — это непереведённая заглушка под русским именем"
                ;;
            *)
                [ "$p" -ge 25 ] && say_fail "$(basename "$f") назван английской стороной, но кириллицы в прозе ${p}% — имя обещает не то, что внутри"
                ;;
        esac
    done

    # --- 3. Старая форма не возвращается ----------------------------------
    for f in "$ROOT/$d"/*.en.md; do
        [ -f "$f" ] || continue
        say_fail "$d/$(basename "$f") — форма .en.md снята 2026-08-12: английская сторона называется без постфикса"
    done
done

if [ "$FAILED" -ne 0 ]; then
    echo "" >&2
    echo "    Публичная страница живёт на двух языках в двух файлах:" >&2
    echo "    X.md — английская сторона, X.ru.md — русская. Имя стороны" >&2
    echo "    обязано совпадать с языком внутри (реестр 221.1 №608, №609)." >&2
    echo "check-doc-language-pairs: FAIL" >&2
    exit 1
fi

echo "check-doc-language-pairs ok: пары на месте, стороны на своих языках"
exit 0
