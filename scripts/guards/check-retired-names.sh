#!/usr/bin/env bash
# Страж: СНЯТОЕ ИМЯ не встречается в живых зонах.
#
# ЗАЧЕМ. Переименование считается сделанным не когда исправлен носитель, а
# когда греп по старой форме даёт ноль. 2026-08-17 это доказано дважды за один
# день, и оба раза находил человек:
#   * спека фиксировала переименование `NOVA_NO_AUTOARM` -> `NOVA_AUTOARM` в
#     ОДНОЙ строке («renamed из legacy», план 83.4.5.9), пока три соседние
#     пользовались снятым именем как действующим (аудит спеки, пункт 38);
#   * через час интегратор переименовал `SignedInt` -> `SignedInts` в одном
#     файле и остановился — форма жила ещё в семи, 28 вхождений, включая три
#     файла `std`. Заметил владелец вопросом «UnsignedInts — ещё такое вроде
#     есть».
# Полумеры этого класса опаснее пропуска: читатель видит и старое имя, и
# новое, и считает, что оба действующие.
#
# ЧТО ПРОВЕРЯЕТ. По списку `retired-names.list` (пары `старое -> новое`) — ни
# одного вхождения снятого имени в живых зонах. НУЛЬ, без храповика:
# переименование либо сделано, либо нет. `docs/plans/**` не проверяется —
# исторические записи; строки, которые сами помечают имя снятым, вычитаются
# ядром (иначе страж съел бы объяснение, ради которого пишется амендмент).
#
# ПОЧЕМУ ЯДРО НА ПИТОНЕ. Нужен отрицательный просмотр вперёд: `SignedInt`
# ловится, `SignedInts` — нет, разница в одном символе ПОСЛЕ совпадения.
# Тот же довод, что у registry-routes-scan.py и retracted-try-scan.py.
#
# Реестр 221.1 №442 (класс: правило без машины), план
# docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).
set -u

NAME="check-retired-names"
ROOT="${1:-.}"
CORE="$ROOT/scripts/guards/retired-names-scan.py"
LIST="$ROOT/scripts/guards/retired-names.list"

if [ ! -f "$CORE" ]; then
    echo "$NAME: FAIL — нет ядра $CORE" >&2
    exit 1
fi
if [ ! -f "$LIST" ]; then
    echo "$NAME: FAIL — нет списка пар $LIST" >&2
    exit 1
fi

OUT=$(python "$CORE" "$ROOT" 2>&1)
RC=$?
if [ "$RC" -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    echo "$OUT" >&2
    exit 1
fi

TOTAL=$(printf '%s\n' "$OUT" | sed -n 's/^total=\([0-9][0-9]*\)$/\1/p' | tail -1)
case "$TOTAL" in
    ''|*[!0-9]*) echo "$NAME: FAIL — ядро не вернуло число" >&2; exit 1;;
esac

PAIRS=$(grep -c -- '->' "$LIST" 2>/dev/null || echo 0)

if [ "$TOTAL" -ne 0 ]; then
    echo "$NAME: FAIL — снятое имя живёт в рабочей зоне: $TOTAL вхождений" >&2
    printf '%s\n' "$OUT" | grep -v '^total=' | head -10 >&2
    echo "    Переименование считается сделанным не когда исправлен носитель," >&2
    echo "    а когда греп по старой форме даёт НОЛЬ. Либо доправь оставшееся," >&2
    echo "    либо, если строка ОБЪЯСНЯЕТ снятие, напиши это в ней словами" >&2
    echo "    (амендмент / «здесь стояло» / renamed) — такие строки не считаются." >&2
    exit 1
fi

echo "$NAME ok: снятых имён в рабочих зонах нет (пар в списке: $PAIRS)"
exit 0
