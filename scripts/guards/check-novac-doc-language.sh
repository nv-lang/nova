#!/bin/sh
# scripts/guards/check-novac-doc-language.sh — документация, комментарии и
# строковые литералы novac — ПО-АНГЛИЙСКИ (конвенция П13; владелец
# 2026-08-15: «дока и комментарии в .nv — по-английски», русский текст в
# комментариях novac запрещён).
#
# Правило было и раньше, механизма не было — русский текст расползся на 265
# строк и попался только глазами. Этот страж и есть недостающий механизм.
#
# ПРОВЕРЯЕТ awk-ом по novac/src/**/*.nv (ВКЛЮЧАЯ *_test.nv — дока тестов
# тоже дока):
#   * ни одна строка не содержит кириллицы. Кириллица считается ПО БАЙТАМ
#     UTF-8: любая пара \xd0/\xd1 + \x80-\xbf. Это ровно блок
#     U+0400..U+047F, и он весь кириллический — а больше байты \xd0/\xd1 в
#     корректном UTF-8 нигде и не встречаются (байты продолжения лежат в
#     \x80-\xbf, ведущие для 3- и 4-байтовых — в \xe0-\xef и \xf0-\xf4).
#     Значит диапазон одновременно и без ложняков, и без дыр: Ё/ё, і, ј, ѐ,
#     Ѣ попадают сами, без списка исключений — эмодзи, греческий, CJK и
#     диакритика не попадают в принципе. Именно по байтам, а НЕ классом
#     [А-Яа-я] и не `grep -i`: в
#     этом окружении под LC_ALL=C такой класс ложно матчит § и тире (176
#     ложных срабатываний, проверено 2026-08-15);
#   * судится СТРОКА ЦЕЛИКОМ, а не только комментарий: строковые литералы
#     novac — это тексты диагностик, они обязаны быть английскими наравне с
#     докой.
#   * ЕДИНСТВЕННОЕ исключение — идентификаторы конвенций, реестра и разделов:
#     знак «П», «№» или «§», сразу за которым ЦИФРЫ (можно через точку), и
#     необязательная ОДНА строчная кириллическая буква-суффикс. Суффикс — не
#     послабление, а норма этого проекта: номера разделов здесь буквенные
#     (§4а, §10.3а, §2б, №114б — 240 употреблений в docs/**), и без него
#     страж заставляет транслитерировать ссылку, разрывая её с адресатом
#     (так в novac/src/names/names.nv уже появилось «§4a» латиницей вместо
#     «§4а» из novac-architecture.md). Ссылка снимается со строки ПЕРЕД
#     проверкой ЦЕЛИКОМ; всё, что осталось кириллического, — красное.
#     Исключение УЗКОЕ: цифра обязана стоять вплотную к знаку («Проверка» —
#     красная), суффикс — ровно одна буква вплотную к цифрам («П5 и ещё» и
#     «П13.5аб» — красные).
# НЕ ПРОВЕРЯЕТ: качество английского (грамматику, орфографию, осмысленность
# — это приёмка); наличие самой документации (за это отвечает
# check-novac-type-field-docs.sh); другие языки на не-латинице (греческий,
# иврит) — судится ровно кириллица, как записано в правиле; файлы вне
# novac/src (std, тесты языка, скрипты — там русский законен).
#
# Реестр правил: план 274 §10.3/§10.3а (каждое правило — против своего
# стража).
# $1 — корень репозитория; $2 — override сканируемой директории (шов для
# самотеста).
# Проверялся: Windows (Git Bash), 2026-08-15.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-doc-language

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

# Байты собираются printf-ом, а не пишутся в файл буквами: так страж читается
# и правится в любом редакторе и не зависит от того, в какой кодировке его
# сохранили.
CYR=$(printf '\320[\200-\277]|\321[\200-\277]')  # весь U+0400..U+047F
SUF=$(printf '(\320[\260-\277]|\321[\200-\217]|\321\221)?')  # необязательная а-я/ё
PE=$(printf '\320\237')                          # П
NO=$(printf '\342\204\226')                      # №
PAR=$(printf '\302\247')                         # §
# Ссылка = знак + цифры (можно через точку) + необязательный буквенный
# суффикс: П5, П13.5, П13.5а, №652, №114б, §7, §4а, §10.3а, § 2б.
# Точка пишется классом [.], а не \., чтобы в значении не было ни одного
# обратного слэша: awk -v сам обрабатывает escape-последовательности.
REF="($PE|$NO|$PAR ?)[0-9]+([.][0-9]+)*$SUF"

scan() {
    find "$SRC" -type f -name '*.nv' | sort | while IFS= read -r f; do
        rel=${f#"$SRC"/}
        awk -v rel="$rel" -v REF="$REF" -v CYR="$CYR" '
            {
                line = $0; sub(/\r$/, "", line)
                # снимаем разрешённые ссылки: П13.5, №114б, §10.3а
                probe = line
                gsub(REF, "", probe)
                if (probe ~ CYR) {
                    printf "  %s:%d: %s\n", rel, NR, line
                }
            }
        ' "$f"
    done
}

BAD=$(scan)

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — русский текст в novac (конвенция П13: дока, комментарии и строковые литералы .nv — по-английски):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Как чинить: перевести эти строки на английский — и ///-док, и обычные" >&2
    echo "  // комментарии, и строковые литералы (это тексты диагностик компилятора)." >&2
    echo "  Единственное, что тут законно кириллицей, — ссылки вида П13.5, №652 и §10.3а." >&2
    exit 1
fi

N=$(find "$SRC" -type f -name '*.nv' | wc -l | tr -d '[:space:]')
REFS=$(find "$SRC" -type f -name '*.nv' | sort | while IFS= read -r f; do
    awk -v REF="$REF" '{ t += gsub(REF, "") } END { print t+0 }' "$f"
done | awk '{ t += $1 } END { print t+0 }')
echo "$NAME ok: файлов .nv: $N, строк с кириллицей: 0 (законных ссылок П/№/§ + цифра: $REFS)"
exit 0
