#!/usr/bin/env bash
# scripts/guards/check-no-handwritten-plan-index.sh
# Второго индекса планов не бывает: рукописная сводка статусов запрещена.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №612; правило владельца, зафиксированное в
# `docs/plans/README.md` («в этом README статусов, снапшотов и „текущих
# приоритетов“ НЕТ намеренно»), вычистка 2026-07-21.
#
# ЗАЧЕМ. Рукописная сводка расходится с планами молча: она не врёт в момент
# написания, она врёт через неделю. Источник правды статуса — ТОЛЬКО строка
# `**Статус:**` в самом файле плана; единственная допустимая сводка —
# автогенерируемый `docs/plans/STATUS.md`, и он честно пишет в шапке, что
# протухает между перегенерациями.
#
# ПОЧЕМУ ПРАВИЛА ОКАЗАЛОСЬ МАЛО. Запрет записан прозой в 2026-07-21, а промпт
# `docs/dev/prompts/update-plans-readme.md`, который ПРЕДПИСЫВАЛ вести ровно
# эту таблицу («README — единый source of truth о статусе всех планов»), дожил
# до 2026-08-12 и всё это время звал любого агента её восстановить. Правило
# запрещало, механизм приглашал — побеждает механизм.
#
# ЧТО ПРОВЕРЯЕТСЯ:
#   1. `docs/plans/README.md` не содержит строк-планов вида `| 123 | …` и не
#      содержит статус-значков ✅/🟡/🔴 — то есть в нём нет таблицы статусов.
#   2. `docs/plans/STATUS.md`, если существует, несёт шапку AUTO-GENERATED —
#      единственная сводка обязана честно называть себя сгенерированной.
#   3. Ни один файл в `docs/dev/prompts/` не предписывает вести сводную
#      таблицу планов (ищется по назначению, а не по имени файла).
#
# ЧЕГО НЕ ЛОВИТ (сказано честно): рукописную сводку, заведённую в файле с
# другим именем и в другой папке. Страж держит известное место и известный
# способ его воскресить.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-no-handwritten-plan-index.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-no-handwritten-plan-index.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
FAILED=0
say_fail() { echo "check-no-handwritten-plan-index: $1" >&2; FAILED=1; }

README="$ROOT/docs/plans/README.md"
if [ -f "$README" ]; then
    n=$(grep -cE '^\| *[0-9]+(\.[0-9]+)? *\|' "$README" || true)
    [ "${n:-0}" -gt 0 ] && say_fail "docs/plans/README.md снова несёт строки-планы ($n) — это второй индекс"
    # Литеральные значки, не \xNN: grep -E escape-последовательностей не знает
    # (это Perl-синтаксис), и с ними проверка молча пропускала всё подряд.
    m=$(grep -cF -e '✅' -e '🟡' -e '🔴' "$README" || true)
    [ "${m:-0}" -gt 0 ] && say_fail "docs/plans/README.md несёт статус-значки ($m) — сводка статусов здесь запрещена"
fi

STATUS="$ROOT/docs/plans/STATUS.md"
if [ -f "$STATUS" ]; then
    head -3 "$STATUS" | grep -q 'AUTO-GENERATED' \
        || say_fail "docs/plans/STATUS.md без шапки AUTO-GENERATED — сводка обязана называть себя сгенерированной"
fi

PROMPTS="$ROOT/docs/dev/prompts"
if [ -d "$PROMPTS" ]; then
    # Ищем предписание вести сводную таблицу планов — по СМЫСЛУ, а не по имени
    # файла: имя можно сменить, назначение — нет.
    # Кириллические КЛАССЫ вида [а-я] под LC_ALL=C не работают — это байтовый
    # диапазон, а не буквы: ровно на этом страж и промолчал при первом
    # запуске. Поэтому здесь только ЛИТЕРАЛЫ.
    bad=$(grep -rlE 'сводную таблицу|сводной таблицы|сводная таблица|source of truth о статусе' "$PROMPTS" 2>/dev/null || true)
    if [ -n "$bad" ]; then
        for f in $bad; do
            say_fail "$(basename "$f") предписывает вести сводную таблицу планов — правило запрещает, а этот файл приглашает"
        done
    fi
fi

if [ "$FAILED" -ne 0 ]; then
    echo "" >&2
    echo "    Источник правды статуса — строка **Статус:** в самом плане." >&2
    echo "    Единственная сводка — автогенерируемый docs/plans/STATUS.md" >&2
    echo "    (bash scripts/tools/gen-plan-status.sh). Реестр 221.1 №612." >&2
    echo "check-no-handwritten-plan-index: FAIL" >&2
    exit 1
fi

echo "check-no-handwritten-plan-index ok: второго индекса планов нет"
exit 0
