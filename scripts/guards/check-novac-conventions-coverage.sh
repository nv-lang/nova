#!/bin/sh
# scripts/guards/check-novac-conventions-coverage.sh — МЕТА-страж обратного
# направления: у каждого правила конвенции назван механизм.
#
# ЗАЧЕМ. Аудит механизмов 2026-08-16 нашёл мета-дыру: направление
# СТРАЖ → план → гейт → самотест сверяется (`check-novac-guard-registry.sh`),
# а обратного направления ПРАВИЛО → механизм нет ни у кого. Правило без стража
# невидимо механизму ЦЕЛИКОМ — оно не попадает ни в одно из четырёх множеств
# реестра. Именно так П15 просидел без механизма при зелёном реестре стражей.
# Отсюда прямое следствие, которое стоит помнить: зелёный реестр стражей НЕ
# является свидетельством покрытия правил, пока нет этого стража.
#
# ПРОВЕРЯЕТ: каждый раздел `## ПNN.` в docs/dev/novac-compiler-conventions.md
#   обязан НАЗВАТЬ свой механизм — одно из двух:
#     * имя файла стража вида `check-novac-*.sh` (или `check-*.sh` общего свода)
#       где-нибудь в теле раздела;
#     * честную пометку немашинности: знак ⚖, либо слова «немашинн»,
#       «не формализуем», «судится приёмкой», «ревью» — то есть правило
#       ОБЪЯВЛЕНО непроверяемым, а не притворяется проверенным.
#   Ассертит, что разделов найдено больше нуля: переименование заголовков
#   иначе сделало бы стража вечнозелёным (класс №519).
# НЕ ПРОВЕРЯЕТ: что названный страж существует и вызывается — это ведомство
#   `check-novac-guard-registry.sh`, вместе они замыкают круг; содержательность
#   пометки немашинности (приёмка); правила вне файла конвенций.
#
# $1 — корень репозитория; $2 — override пути к файлу конвенций (самотест).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CONV="${2:-$ROOT/docs/dev/novac-compiler-conventions.md}"
NAME=check-novac-conventions-coverage

if [ ! -f "$CONV" ]; then
    echo "$NAME ok: судить нечего (нет $CONV)"
    exit 0
fi

T="${TMPDIR:-/tmp}/novac-conv-coverage.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

tr -d '\r' < "$CONV" | awk '
    /^## П[0-9]+\./ {
        if (rule != "") { printf "%s\t%d\t%d\n", rule, line, covered }
        rule = $0
        sub(/^## /, "", rule)
        sub(/\..*$/, "", rule)
        line = NR
        covered = 0
        next
    }
    rule != "" {
        if ($0 ~ /check-[a-z0-9-]+\.sh/) covered = 1
        else if ($0 ~ /⚖|немашинн|не формализуем|формализовать .* нельзя|судится приёмкой|на ревью|красные на ревью/) covered = 1
    }
    END { if (rule != "") printf "%s\t%d\t%d\n", rule, line, covered }
' > "$T/rules"

N=$(wc -l < "$T/rules" | tr -d '[:space:]')
if [ "$N" -eq 0 ]; then
    echo "$NAME: FAIL — в $CONV не нашлось ни одного раздела вида '## ПNN.': страж потерял мишень (класс №519)" >&2
    exit 1
fi

BAD=$(awk -F'\t' '$3 == 0 { printf "  %s (строка %s) — механизм не назван\n", $1, $2 }' "$T/rules")
if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — правило конвенции без названного механизма:" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Каждое правило обязано назвать ЛИБО своего стража (имя файла check-*.sh)," >&2
    echo "  ЛИБО честно объявить себя немашинным (знак ⚖ или словами «судится приёмкой»)." >&2
    echo "  Правило, которое не сделало ни того ни другого, невидимо реестру стражей" >&2
    echo "  целиком — оно не попадает ни в одно из его четырёх множеств." >&2
    exit 1
fi

GUARDED=$(awk -F'\t' '$3 == 1' "$T/rules" | wc -l | tr -d '[:space:]')
echo "$NAME ok: правил конвенции: $N, у всех назван механизм ($GUARDED), без механизма: 0"
exit 0
