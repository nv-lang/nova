#!/usr/bin/env bash
# check-guard-wiring.sh — МЕТА-СТРАЖ: проверяет, что каждый страж-скрипт реально
# подключён и проверен, а не просто лежит в каталоге.
#
# ПОЧЕМУ (правило владельца 2026-07-27, дословно): «в скрипте нет толку, если не
# подключён к автопроверке или сам содержит ошибки». Скрипт-страж, который
# никто не запускает, — хуже отсутствия стража: он создаёт ложное ощущение
# защиты и тихо гниёт (пути меняются, рефакторы ломают матчинг), а узнаём мы об
# этом в момент, когда он ДОЛЖЕН был поймать беду и не поймал.
#
# Три обязательных свойства каждого постоянного механизма (план 231 §4в):
#   1. ДОКУМЕНТИРОВАН — содержательная шапка (зачем, что проверяет, как
#      запускать) и ссылка на план/реестр;
#   2. ПОДКЛЮЧЁН — вызывается из `scripts/gate.sh` (прямо или через цикл
#      самотестов);
#   3. ПРОВЕРЕН — имеет самотест `scripts/selftest/test-<имя>.sh`, который
#      доказывает ОБА свойства: ловит нарушение / не даёт ложняка.
#
# ЧТО ПРОВЕРЯЕТ. Для каждого файла `scripts/guards/check-*.sh` (соглашение
# имён для стражей) — все три пункта выше. Разовые инструменты волн (миграции,
# конвертеры, `scripts/tools/`) стражами не считаются и не проверяются.
# (см. `scripts/README.md` — карта guards/ vs tools/).
#
# ИСПОЛЬЗОВАНИЕ:
#   scripts/guards/check-guard-wiring.sh [корень-репы]
# Без аргумента — проверяется репа, в которой лежит сам скрипт. Аргумент нужен
# самотесту: он собирает игрушечные репы-фикстуры и натравливает стража на них
# (без параметра страж всегда смотрел бы на настоящую репу, и фикстуры ничего
# не проверяли бы — эта ошибка была допущена в первой редакции и поймана
# собственным самотестом).
# Выход: 0 — все стражи документированы, подключены и покрыты; 1 — есть
# неподключённый/непроверенный/недокументированный страж (печатает какой и чего
# именно ему не хватает).
#
# План: docs/plans/231-bug-cycle-exit.md §4в (трек Ж — самотесты механизмов
# принуждения). Повод-прецедент: реестр 221.1 №138.

set -uo pipefail
# LC_ALL=C — байтовый grep (msys2 grep в UTF-8-локали не матчит астральные
# символы; класс пойман селфтестами 2026-08-01 — doc-hygiene, status-table)
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
# Скрипт живёт в scripts/guards/ — корень репы на два уровня выше.
REPO_ROOT="${1:-$(cd "$SCRIPT_DIR/../.." && pwd)}"
GATE="$REPO_ROOT/scripts/gate.sh"
SELFTEST_DIR="$REPO_ROOT/scripts/guards/selftest"

# Минимум содержательной шапки: столько строк комментария в первых 20.
MIN_HEADER_LINES=8

problems=0
report() { echo "  ✗ $1" >&2; problems=$((problems + 1)); }

# ССЫЛКА НА ПЛАН — ХРАПОВИК, А НЕ ЖЁСТКИЙ ОТКАЗ (реестр 221.1 №785,
# 2026-08-27). Остальные два свойства — подключён и покрыт самотестом — остаются
# жёсткими. Почему именно это свойство смягчено: у него ОДНОГО набралось 52
# нарушителя, все в одной области, а вердикт «всё или ничего» не даёт гасить
# долг по одному. Страж, который либо зелен, либо валит ярус целиком, стоит
# выключенного: его красноту начинают обходить. Рост по-прежнему красный.
noref=0
NOREF_NAMES=""
WIRING_BASELINE="${NOVA_WIRING_BASELINE:-$(dirname "${BASH_SOURCE[0]}")/guard-wiring.baseline}"

echo "check-guard-wiring: проверяю стражи scripts/guards/check-*.sh и check-*.py"

shopt -s nullglob
# Расширение НЕ часть личности стража (переезд на python, П14).
guards=("$REPO_ROOT"/scripts/guards/check-*.sh "$REPO_ROOT"/scripts/guards/check-*.py)
if [ "${#guards[@]}" -eq 0 ]; then
    echo "  стражей не найдено — нечего проверять"
    exit 0
fi

# ПРЕДВАРИТЕЛЬНЫЙ ПРОХОД (план 275-Ф.1, гейт-стоимость): раньше НА КАЖДЫЙ
# файл-страж форкались head+grep (шапка), grep (ссылка на план), grep (имя
# в gate.sh), grep (форма обхода самотестов) — 4-5 процессов на файл, ~90
# файлов, профиль показал ~22с. Три из четырёх проверок НЕ зависят от
# конкретного файла (loop_covers — константа для всего прогона) или сводятся
# к чтению уже загруженного в память текста (wired_directly — просто
# подстрока в содержимом gate.sh, без нужды перечитывать файл через grep).
# Единственное, что реально должно смотреть В КАЖДЫЙ файл (шапка + ссылка на
# план), сведено к ОДНОМУ проходу awk по всем файлам разом.
GATE_CONTENT=""
[ -f "$GATE" ] && GATE_CONTENT="$(<"$GATE")"
loop_covers=0
grep -qE "selftest/test-\*\.sh|selftest[^\"']*-name '?test-\*\.sh|guards/selftest" \
    "$GATE" 2>/dev/null && loop_covers=1

declare -A HEADER_LINES HAS_PLAN_REF
while IFS=$'\t' read -r fpath hc ref; do
    [ -n "$fpath" ] || continue
    HEADER_LINES["$fpath"]="$hc"
    HAS_PLAN_REF["$fpath"]="$ref"
# ОДИН проход awk по всем стражам (оптимизация main: 90 файлов, каждый форк
# заметен) И докстринг питоновского стража (правка ветки p274: шапка .py живёт в
# тройных кавычках, а не в решётках, поэтому счёт только по '^#' объявлял бы
# каждый порт недокументированным). Слияние 2026-08-22 сохранило ОБА умысла:
# структуру main и правило ветки. Открывающая строка бывает и с префиксом `u`.
done < <(awk '
    FNR == 1 {
        if (NR > 1) print prevfile "\t" hc "\t" ref
        prevfile = FILENAME; hc = 0; ref = 0; d = 0
    }
    FNR <= 20 {
        if ($0 ~ /^#/) { hc++ }
        else if ($0 ~ /^u?"""/) { d = !d; hc++ }
        else if (d) { hc++ }
    }
    # Написаний адреса ТРИ, и это замер, а не вкус: проект пишет и
    # «docs/plans/...», и «план 274», и «реестр 221.1 №785», и просто
    # «реестр №813». Пока читатель знал два первых, ДВА стража, назвавшие
    # адрес честно (`check-gate-build-order` -> №813,
    # `check-spec-retired-names` -> №845), считались безадресными: страж
    # судил НАПИСАНИЕ, а не наличие адреса, — тот же класс, из-за которого
    # выше уже перестали искать буквальный текст цикла `for`.
    /docs\/plans\/|план [0-9]|реестр 221\.1|реестр №[0-9]/ { ref = 1 }
    END { if (prevfile != "") print prevfile "\t" hc "\t" ref }
' "${guards[@]}")

for g in "${guards[@]}"; do
    # basename как bash-подстановка, а не форк внешней команды (оптимизация
    # main: 90 файлов, каждый форк заметен). Расширение снимается ОБА: страж
    # бывает и `.sh`, и `.py`, а имя без расширения — то, чем его называют гейт
    # и реестр.
    name="${g##*/}"
    name="${name%.sh}"
    name="${name%.py}"
    ok=1

    # 1. Документирован: содержательная шапка + ссылка на план. Считает
    #    предвычисление выше — оно знает и решётки, и докстринг.
    header_lines="${HEADER_LINES[$g]:-0}"
    if [ "$header_lines" -lt "$MIN_HEADER_LINES" ]; then
        report "$name: шапка тонкая ($header_lines строк < $MIN_HEADER_LINES) — нужно «зачем / что проверяет / как запускать»"
        ok=0
    fi
    if [ "${HAS_PLAN_REF[$g]:-0}" -ne 1 ]; then
        noref=$((noref + 1))
        NOREF_NAMES="$NOREF_NAMES $name"
        ok=0
    fi

    # 2. Подключён: вызывается из gate.sh — либо напрямую, либо своим самотестом
    #    через обход каталога самотестов.
    #
    # ФОРМА ОБХОДА НЕ ФИКСИРОВАНА, и это важно. Раньше здесь стоял поиск
    # буквального `selftest/test-*.sh` — текста цикла `for`. 2026-08-12 гейт
    # перевели на параллельный запуск (`find … -name 'test-*.sh' | xargs -P`),
    # и шесть стражей мгновенно объявились «не подключёнными», хотя запускались
    # как раньше: страж проверял НАПИСАНИЕ цикла, а не факт обхода каталога.
    # Теперь принимается любая форма, называющая каталог самотестов, — это то
    # свойство, которое на самом деле требуется.
    wired_directly=0
    case "$GATE_CONTENT" in *"$name"*) wired_directly=1 ;; esac

    # 3. Проверен: есть самотест.
    selftest="$SELFTEST_DIR/test-$name.sh"
    has_selftest=0
    [ -f "$selftest" ] && has_selftest=1

    if [ "$has_selftest" -eq 0 ]; then
        report "$name: НЕТ самотеста ($selftest) — страж без теста = доверие на слово"
        ok=0
    fi
    if [ "$wired_directly" -eq 0 ] && { [ "$loop_covers" -eq 0 ] || [ "$has_selftest" -eq 0 ]; }; then
        report "$name: НЕ подключён к gate.sh (ни явным шагом, ни через самотест в цикле)"
        ok=0
    fi

    [ "$ok" -eq 1 ] && echo "  ok: $name — документирован, подключён, покрыт самотестом"
done

WIRING_BASE=0
if [ -f "$WIRING_BASELINE" ]; then
    WIRING_BASE=$(sed -n 's/^no_plan_ref=\([0-9][0-9]*\).*/\1/p' "$WIRING_BASELINE" | head -1)
    WIRING_BASE=${WIRING_BASE:-0}
else
    echo "check-guard-wiring: базы нет ($WIRING_BASELINE) — считаю базой 0" >&2
fi
echo "check-guard-wiring: без ссылки на план $noref (база $WIRING_BASE)"
if [ "$noref" -gt "$WIRING_BASE" ]; then
    echo "check-guard-wiring: ВЫРОСЛО — $noref > базы $WIRING_BASE" >&2
    for n in $NOREF_NAMES; do echo "    ✗ $n: нет ссылки на план/реестр в шапке" >&2; done
    problems=$((problems + 1))
elif [ "$noref" -lt "$WIRING_BASE" ]; then
    echo "check-guard-wiring: долг СНИЗИЛСЯ ($noref < базы $WIRING_BASE) — опусти базу в $WIRING_BASELINE с летописью"
fi

if [ "$problems" -ne 0 ]; then
    cat >&2 <<'HINT'

Правило (владелец 2026-07-27): «в скрипте нет толку, если не подключён к
автопроверке или сам содержит ошибки». Новый страж обязан иметь ВСЕ ТРИ:
  1) содержательную шапку со ссылкой на план (образец — check-no-runtime-copy.sh);
  2) шаг в scripts/gate.sh (или покрытие через цикл самотестов);
  3) самотест scripts/guards/selftest/test-<имя>.sh, доказывающий, что страж
     ловит нарушение и не даёт ложных срабатываний (образец —
     selftest/test-check-no-runtime-copy.sh).
См. docs/plans/231-bug-cycle-exit.md §4в.
HINT
    exit 1
fi

echo "check-guard-wiring ok: все стражи подключены и покрыты самотестами; без ссылки на план $noref при базе $WIRING_BASE (не выросло)"
