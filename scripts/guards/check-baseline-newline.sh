#!/bin/sh
# scripts/guards/check-baseline-newline.sh — каждый файл-база оканчивается
# переводом строки.
#
# КЛАСС (реестр №891, найден окном 274 2026-09-03 на своей же правке). Страж-
# храповик читает базу построчно: `while read ... done < "$BASE"`. Оболочечный
# `read` возвращает ЛОЖЬ на последней строке, если у неё нет завершающего `\n`,
# — тело цикла для неё не выполняется. Значит последняя строка базы молча
# уходит из проверки, а храповик рапортует «совпадает». Ратчет, считающий
# меньше, чем перечисляет, не держит ничего.
#
# ПОЧЕМУ ОБЩИЙ СТРАЖ, А НЕ ПРАВКА ЧИТАТЕЛЕЙ. Уязвимых читателей сегодня двое
# (`arch-ratchet.sh`, `check-doc-language-pairs.sh` — оба `done < "$BASE_FILE"`),
# и их можно было бы починить поимённо. Но испорченный вход общий для ВСЕХ баз:
# любая правка регуляркой с `\s*$` съедает завершающий `\n` (так и случилось),
# а завтрашний страж прочтёт базу как угодно. Дешевле запретить сам испорченный
# файл, чем чинить каждого читателя и надеяться на дисциплину следующего.
#
# ЗАМЕР НА ДЕНЬ ЗАВЕДЕНИЯ: баз 54, без перевода строки — 1
# (`doc-hygiene.baseline`). Его читатель безопасен (читает грепом, а не
# `read`), поэтому это НЕ живой дефект — но это заряженное ружьё: смени
# читателя на `while read`, и строка `cyrillic_lint=54` исчезнет из проверки.
#
# $1 — корень репозитория; $2 — override сканируемой директории (шов самотеста).
set -u
LC_ALL=C; export LC_ALL
NAME="check-baseline-newline"
ROOT="${1:-.}"
DIR="${2:-$ROOT}"

BAD=""
N=0
for f in $(cd "$DIR" 2>/dev/null && git ls-files 2>/dev/null | grep -E '\.baseline$'); do
    p="$DIR/$f"
    [ -f "$p" ] || continue
    N=$((N + 1))
    # Пустой файл — тоже отказ: сверять не с чем (класс №519).
    if [ ! -s "$p" ]; then
        BAD="$BAD
  $f — база ПУСТА"
        continue
    fi
    last=$(tail -c 1 "$p" | od -An -c | tr -d ' ')
    [ "$last" = "\\n" ] || BAD="$BAD
  $f — нет завершающего перевода строки"
done

if [ "$N" -eq 0 ]; then
    echo "$NAME ok: судить нечего — баз не найдено"
    exit 0
fi

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — база без завершающего перевода строки (класс №891):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Оболочечный 'read' не отдаёт последнюю строку без '\\n', и она" >&2
    echo "  молча уходит из проверки: храповик считает меньше, чем перечисляет." >&2
    echo "  Чинить: дописать перевод строки в конец файла. Частая причина —" >&2
    echo "  правка регуляркой, где '\\s*\$' съедает последний '\\n'." >&2
    exit 1
fi

echo "$NAME ok: баз $N, все оканчиваются переводом строки"
exit 0
