#!/bin/sh
# scripts/guards/check-novac-no-silent-skip.sh — в проходе, который ПИШЕТ
# канал чекера, нет молчаливого выхода: ветка либо записывает, либо
# отказывает, либо падает ice — но не уходит молча.
#
# КЛАСС (вопрос владельца 2026-08-16 по строке `if kids.len() < 2 { return }`
# в `@type_expr`: «что значит этот return?»). Он не значил ничего хорошего:
#   * если форма гарантирована парсером — ветка МЁРТВАЯ, и молчаливый выход
#     прячет инвариант вместо того, чтобы его утверждать;
#   * если форма достижима — узел остаётся БЕЗ ЗАПИСИ в канале, а читатели
#     канала тотальны: дыра всплывает как «no type recorded» из другого
#     модуля и на проход позже. Ошибка пользователя превращается в ICE не
#     про то и не там.
# Проба того же дня: `1 +` в конце строки утягивает СЛЕДУЮЩИЙ оператор в
# операнды, `println(...)` оказывается в позиции значения, и `novac check`
# паниковал. Три молчаливых `return` были ровно этой формы.
#
# ПОЧЕМУ ПРЕЖНИЕ СТРАЖИ НЕ ЛОВИЛИ. `check-novac-no-default-branch` судит
# арм-заглушки `_ =>` и диспетчерский `else` — и прямо пишет, что цепочки с
# ранним выходом не судит. `check-novac-channel-one-writer` держит ЕДИНСТВЕН-
# НОСТЬ писателя, а не полноту записи. Тотальность читателей — второй этаж:
# она ловит дыру, но в чужом модуле и позже. Машинного правила на «ветка
# ничего не решила» не было ни у кого.
#
# ПРОВЕРЯЕТ в novac/src/check/**.nv, внутри функций прохода канала
#   (`fn Checker mut @type_*`): каждый `return` обязан иметь в ТРЁХ
#   предшествующих значащих строках одно из:
#     * `@refuse(` / `@report_` — отказ выдан;
#     * `ice(` — инвариант объявлен сломанным;
#     * `@out.len() > 0` — выход потому, что отказ уже выдан ниже по стеку;
#   либо нести в том же окне пометку `// SILENT-OK: <причина>`
#   (не меньше четырёх слов). Пометка — не лазейка, а требование СКАЗАТЬ,
#   почему молчание здесь правильно.
# НЕ ПРОВЕРЯЕТ: функции вне прохода канала (у предикатов `return true/false`
#   законен); правдивость причины в пометке (это приёмка); полноту канала как
#   таковую (её держат тотальные читатели).
#
# $1 — корень репозитория; $2 — override сканируемой директории (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src/check}"
NAME=check-novac-no-silent-skip

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

T="${TMPDIR:-/tmp}/novac-silent-skip.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

find "$SRC" -type f -name '*.nv' | sort > "$T/files"
if [ ! -s "$T/files" ]; then
    echo "$NAME: FAIL — в $SRC нет ни одного .nv: страж потерял мишень (класс №519)" >&2
    exit 1
fi

: > "$T/bad"
NFN=0
NRET=0
cat "$T/files" | xargs awk -v SRC="$SRC" -v STAT="$T/stat" '
        FNR == 1 { REL = FILENAME; sub("^" SRC "/", "", REL) }
        { sub(/\r$/, "", $0) }
        # вход в функцию прохода канала
        /^fn Checker mut @type_[a-z_]*\(/ { inwalk = 1; nfn++; delete hist; nh = 0; next }
        /^fn / || /^export fn / { inwalk = 0 }
        inwalk {
            line = $0
            body = line; sub(/^[[:space:]]+/, "", body)
            if (body == "") next
            # комментарий — не ветка: слово "return" в прозе не решение
            if (body ~ /^\/\//) { hist[++nh] = body; next }
            if (body ~ /(^|[^a-zA-Z_])return([^a-zA-Z_]|$)/) {
                nret++
                okay = 0
                # пометка на своей строке или на предыдущей
                if (line ~ /SILENT-OK:/) okay = 1
                # пометка может быть многострочной прозой — смотрим то же окно
                for (i = 0; i < 3 && nh - i >= 1; i++) if (hist[nh - i] ~ /SILENT-OK:/) okay = 1
                # решение в трёх предыдущих значащих строках ИЛИ на своей
                cand = line
                for (i = 0; i < 3 && nh - i >= 1; i++) cand = cand " " hist[nh - i]
                if (cand ~ /@refuse\(/ || cand ~ /@report_/ || cand ~ /ice\(/ || cand ~ /@out\.len\(\) > 0/) okay = 1
                if (!okay) printf "  %s:%d — молчаливый выход в проходе канала: %s\n", REL, FNR, body
            }
            hist[++nh] = body
        }
        END { printf "%d %d\n", nfn, nret > STAT }
    ' >> "$T/bad"
    if [ -f "$T/stat" ]; then
        NFN=$((NFN + $(cut -d' ' -f1 "$T/stat")))
        NRET=$((NRET + $(cut -d' ' -f2 "$T/stat")))
        rm -f "$T/stat"
    fi

if [ "$NFN" -eq 0 ]; then
    echo "$NAME: FAIL — не найдено ни одной функции прохода канала (fn Checker mut @type_*): страж потерял мишень (класс №519)" >&2
    exit 1
fi

if [ -s "$T/bad" ]; then
    echo "$NAME: FAIL — ветка прохода канала не решила ничего (ни записи, ни отказа, ни ice):" >&2
    cat "$T/bad" >&2
    echo "  Читатели канала ТОТАЛЬНЫ: пропущенный узел всплывёт как «no type recorded»" >&2
    echo "  из другого модуля и проходом позже. Реши здесь: @refuse(...) если это" >&2
    echo "  ошибка пользователя, ice(...) если инвариант, либо пометь строкой" >&2
    echo "  '// SILENT-OK: <почему молчание верно>' (минимум четыре слова)." >&2
    exit 1
fi

echo "$NAME ok: функций прохода канала $NFN, выходов $NRET — у каждого решение (запись, отказ, ice или названная причина)"
exit 0
