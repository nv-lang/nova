#!/bin/sh
# scripts/guards/check-novac-precondition.sh — предусловие двери живёт в
# СИГНАТУРЕ (конвенция П20 п.5; владелец 2026-08-17: «почему не два
# requires?» и следом «ещё нужен страж»).
#
# ЗАЧЕМ. Условие на аргумент читает ВЫЗЫВАЮЩИЙ, а тело видит только
# реализующий: `requires` — часть объявленной формы двери, `assert` первой
# строкой тела — та же проверка, спрятанная от читателя. Язык допускает
# СПИСОК клауз (проба 2026-08-17), поэтому «первое условие в requires, второе
# assert'ом» — это не форма, а недоделанный перевод: ровно так и осталось в
# двух дверях канала, пока владелец не спросил.
#
# ПРОВЕРЯЕТ по novac/src/**/*.nv (тесты исключены): `assert(` не стоит ПЕРВОЙ
#   значащей строкой тела функции. Первая строка тела — это то место, куда
#   попадает проверка входа; если она там, её место в сигнатуре.
# НЕ ПРОВЕРЯЕТ: assert'ы ГЛУБЖЕ в теле — они об инвариантах над уже
#   вычисленным, а не над входом, и остаются законными; правдивость условия
#   (это приёмка); контракты `ensures` (их черёд придёт с возвратными
#   инвариантами).
#
# $1 — корень; $2 — override сканируемой директории (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-precondition

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

T="${TMPDIR:-/tmp}/novac-precond.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | sort > "$T/files"
if [ ! -s "$T/files" ]; then
    echo "$NAME: FAIL — в $SRC нет ни одного .nv: страж потерял мишень (класс №519)" >&2
    exit 1
fi

: > "$T/bad"
: > "$T/cnt"
while IFS= read -r f; do
    rel=${f#"$SRC"/}
    tr -d '\r' < "$f" | awk -v REL="$rel" -v OUT="$T/bad" -v CNT="$T/cnt" '
        # Тело начинается либо на той же строке (`fn f() {`), либо ниже
        # (когда между сигнатурой и телом стоят клаузы requires).
        /^(export )?fn / {
            infn = 1
            body = ($0 ~ /\{[[:space:]]*$/) ? 1 : 0
            next
        }
        infn && !body && /\{[[:space:]]*$/ { body = 1; next }
        body {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            if (line == "") next
            if (line ~ /^\/\//) next
            nfn++
            if (line ~ /^assert\(/) {
                printf "  %s:%d — assert первой строкой тела: это предусловие, его место в сигнатуре (requires)\n", REL, FNR >> OUT
            }
            body = 0; infn = 0
        }
        END { print nfn+0 >> CNT }
    '
done < "$T/files"
N=$(awk '{s+=$1} END {print s+0}' "$T/cnt")

if [ "$N" -eq 0 ]; then
    echo "$NAME: FAIL — не нашлось ни одного тела функции: разбор сломался (класс №519)" >&2
    exit 1
fi
if [ -s "$T/bad" ]; then
    echo "$NAME: FAIL — предусловие спрятано в теле (П20 п.5):" >&2
    cat "$T/bad" >&2
    echo "  Перенеси в сигнатуру: requires <условие>, \"текст\" — клауз может быть" >&2
    echo "  НЕСКОЛЬКО, у каждой своё сообщение. assert глубже в теле законен: он" >&2
    echo "  об инварианте над уже вычисленным, а не над входом." >&2
    exit 1
fi

echo "$NAME ok: тел функций проверено: $N, предусловий в теле: 0"
exit 0
