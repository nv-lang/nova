#!/bin/sh
# scripts/guards/check-novac-line-length.sh — строка кода novac не длиннее
# разумного предела (конвенция П29; указание владельца 2026-08-17 по живой
# строке в 258 символов: «определить максимальную разумную длину строки и
# соблюдать её»).
#
# ПРЕДЕЛ 120. Он не выдуман: замер 2026-08-17 по novac/src — при 120 нарушают
# 66 строк из ~6000, при 100 — 141, при 140 — 36. Сто двадцать это норма
# отрасли (rustfmt ставит 100, ядро Linux ушло со 80 на 100) и та граница, за
# которой строку перестают читать целиком: диффы, обзоры бок о бок и терминал
# на половину экрана рвут её молча.
#
# ЧЕТЫРЕ ИСКЛЮЧЕНИЯ, И КАЖДОЕ — ПРЕДЕЛ ЯЗЫКА, А НЕ ЛЕНЬ. Проверено пробой в
# тот же день: Nova НЕ ПОЗВОЛЯЕТ перенести ни список импорта
# (`expected identifier, got newline`), ни образец арма (`expected =>, got
# newline`). Поэтому:
#   1. строка `import ...` — переносить нечем;
#   2. образец арма (до `=>` только имена вариантов, `|` и пробелы) — тоже;
#   3. строка с ОДНОЙ длинной строковой литерой (60+ символов) — резать
#      сообщение пополам хуже, чем длинная строка: диагностику потом ищут
#      грепом по тексту;
#   4. хвостовой `///`-док у поля: код короткий, длинный только комментарий, и
#      форма `field int /// текст` — установленная в проекте (D104 rev-2).
# Всё остальное — проза комментариев и обычный код — переносится, и предел на
# них распространяется.
#
# ПРОВЕРЯЕТ novac/src/**/*.nv (включая тесты: длинная строка в тесте читается
#   так же плохо). НЕ ПРОВЕРЯЕТ: std и оракул (там своя норма: замер даёт 643
#   строки длиннее 120 и максимум в 641 тыс. символов — это не наша земля).
#
# $1 — корень репозитория; $2 — override сканируемой директории (шов самотеста);
# $3 — override предела (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-17.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
LIMIT="${3:-120}"
NAME=check-novac-line-length

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

T="${TMPDIR:-/tmp}/novac-line-length.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

find "$SRC" -type f -name '*.nv' | sort > "$T/files"
if [ ! -s "$T/files" ]; then
    echo "$NAME: FAIL — в $SRC нет ни одного .nv: страж потерял мишень (класс №519)" >&2
    exit 1
fi

: > "$T/bad"
NL=0
while IFS= read -r f; do
    rel=${f#"$SRC"/}
    tr -d '\r' < "$f" | awk -v REL="$rel" -v LIM="$LIMIT" -v OUT="$T/bad" -v CNT="$T/cnt" '
        { total++ }
        length($0) <= LIM { next }
        # 1. импорт — язык не переносит
        /^import / { next }
        # 2. образец арма: до "=>" только имена, "|" и пробелы
        {
            if (index($0, "=>") > 0) {
                head = substr($0, 1, index($0, "=>") - 1)
                if (head ~ /^[[:space:]]*[A-Za-z_][A-Za-z0-9_]*([[:space:]]*\|[[:space:]]*[A-Za-z_][A-Za-z0-9_]*)+[[:space:]]*$/) next
            }
        }
        # 3. одна длинная строковая литера
        /"[^"]{60,}"/ { next }
        # 4. хвостовой ///-док: код до него укладывается
        {
            p = index($0, "///")
            if (p > 1) {
                code = substr($0, 1, p - 1)
                sub(/[[:space:]]+$/, "", code)
                if (length(code) <= LIM) next
            }
        }
        { printf "  %s:%d — %d символов (предел %d)\n", REL, FNR, length($0), LIM >> OUT }
        END { print total >> CNT }
    '
done < "$T/files"
NL=$(awk '{s+=$1} END {print s+0}' "$T/cnt" 2>/dev/null)

if [ -s "$T/bad" ]; then
    echo "$NAME: FAIL — строки длиннее $LIMIT символов (П29):" >&2
    head -n 20 "$T/bad" >&2
    n=$(wc -l < "$T/bad" | tr -d '[:space:]')
    [ "$n" -gt 20 ] && echo "  ... и ещё $((n - 20))" >&2
    echo "  Перенеси: прозу комментария по словам, длинное выражение — во" >&2
    echo "  вспомогательное имя или в if-цепочку. Исключения (импорт, образец" >&2
    echo "  арма, одна длинная литера, хвостовой ///-док) страж пропускает сам." >&2
    exit 1
fi

echo "$NAME ok: строк .nv: $NL, длиннее $LIMIT символов вне четырёх исключений: 0"
exit 0
