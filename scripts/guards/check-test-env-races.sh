#!/usr/bin/env bash
# Страж: одну переменную среды правит не больше ОДНОГО теста.
#
# ЗАЧЕМ. Тесты Rust идут параллельно в ОДНОМ процессе, а среда у процесса
# одна. Две тестовые функции, правящие одну переменную, гоняются друг с
# другом — и «зелено» становится вопросом планировщика, а не кода.
#
# ПРЕЦЕДЕНТ (реестр №733, 2026-08-19). `march_flag_default` и
# `march_flag_native_env` правили `NOVA_MARCH_NATIVE`. Локально гонка
# выигрывалась, на CI (ubuntu-latest) проиграла и остановила отправку. Это был
# ПЕРВЫЙ раз, когда её было видно вообще: собственный набор крейта до №723 не
# гонял ни гейт, ни CI. Дефект пролежал столько, сколько существовали оба
# теста.
#
# КАК ПИСАТЬ ПРАВИЛЬНО. Решение — в чистую функцию, она проверяется без среды;
# ЧТЕНИЕ среды проверяет РОВНО ОДИН тест, последовательно и в известном
# порядке. Гонки тогда нет по построению, а не по везению.
#
# НОЛЬ, БЕЗ ХРАПОВИКА. Одна такая пара уже означает тест, зелёный по удаче.
# Послаблять здесь нечего: правка стоит десяти строк.
#
# $1 — корень. Самотест — selftest/test-check-test-env-races.sh
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u
export LC_ALL=C

NAME="check-test-env-races"
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CORE="$(dirname "$0")/test-env-race-scan.py"

[ -f "$CORE" ] || { echo "$NAME: FAIL — нет ядра $CORE" >&2; exit 1; }

OUT=$(python "$CORE" "$ROOT" 2>&1)
if [ $? -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    printf '%s\n' "$OUT" | tail -5 >&2
    exit 1
fi

N=$(printf '%s\n' "$OUT" | sed -n 's/^racy=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
case "$N" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число" >&2; exit 1;; esac
if [ "$N" -lt 0 ]; then
    echo "$NAME: FAIL — ядро не нашло исходников крейтов (переехали?)" >&2
    exit 1
fi

if [ "$N" -ne 0 ]; then
    echo "$NAME: FAIL — переменных среды, которые правит больше одного теста: $N" >&2
    printf '%s\n' "$OUT" | grep -v '^racy=' | head -20 >&2
    echo "    Тесты Rust идут ПАРАЛЛЕЛЬНО в одном процессе: эти тесты гоняются" >&2
    echo "    друг с другом, и зелёное здесь — вопрос планировщика." >&2
    echo "    Разведи так (как №733): решение вынеси в чистую функцию и проверь" >&2
    echo "    её без среды; ЧТЕНИЕ среды оставь РОВНО ОДНОМУ тесту, который" >&2
    echo "    проверяет обе стороны последовательно." >&2
    exit 1
fi

echo "$NAME ok: ни одной переменной среды, которую правит больше одного теста"
exit 0
