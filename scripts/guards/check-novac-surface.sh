#!/bin/sh
# scripts/guards/check-novac-surface.sh — публичная поверхность каждого модуля
# под храповиком (план 274 §10.4 «novac-surface.baseline»: «рост требует
# обоснования в коммите»; аудит механизмов 2026-08-16 — базы не было ни файлом,
# ни маркером часов, при том что план её обещал).
#
# ЗАЧЕМ. Экспорт — это обещание: всё, что модуль экспортирует, кто-то может
# начать читать, и снять это потом стоит дороже, чем не давать. Поверхность
# растёт тихо, по одному `export` за правку, и никто не спрашивает «а зачем это
# наружу». Замер при заведении: `sem` экспортирует 46 имён, все прочие модули —
# от 1 до 6. Ровно там, где живёт до-дженериковый реестр, и есть самая широкая
# дверь наружу.
#
# ПРОВЕРЯЕТ: число строк `export ` (тип, функция, метод, константа) в каждом
#   модуле novac/src (папка = модуль; файлы в корне = модуль `main`), тесты
#   *_test.nv исключены, против строк `<модуль> <число>` в
#   scripts/guards/novac-surface.baseline. Храповик В ОБЕ СТОРОНЫ:
#   * поверхность выросла без поднятия базы — красный («рост без обоснования»);
#   * поверхность сузилась, а база не опущена — красный (протухшая база:
#     иначе следующий рост до старой цифры пройдёт молча, класс №519);
#   * модуль есть в коде, но нет в базе, и наоборот — красный.
#   Поднятие базы идёт ТЕМ ЖЕ коммитом, что и рост, с причиной в сообщении.
# НЕ ПРОВЕРЯЕТ: нужность каждого экспорта (приёмка); экспорты в тестах;
#   поверхность по типам против функций (одно число на модуль — сознательная
#   грубость: страж должен задать вопрос, а не заменить ревью).
#
# $1 — корень репозитория; $2 — override сканируемой директории; $3 — override
# файла базы (швы самотеста).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
BASE="${3:-$ROOT/scripts/guards/novac-surface.baseline}"
NAME=check-novac-surface

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi
[ -f "$BASE" ] || { echo "$NAME: FAIL — нет базы $BASE: храповик поверхности обещан планом (§10.4), а файла нет" >&2; exit 1; }

T="${TMPDIR:-/tmp}/novac-surface.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

# --- факт: модуль -> число экспортов -----------------------------------------
find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | sort | while IFS= read -r f; do
    rel=${f#"$SRC"/}
    case "$rel" in
        */*) mod=${rel%%/*} ;;
        *)   mod=main ;;
    esac
    n=$(tr -d '\r' < "$f" | grep -c '^export ')
    echo "$mod $n"
done | awk '{ s[$1] += $2 } END { for (m in s) printf "%s %d\n", m, s[m] }' | sort > "$T/fact"

# --- база --------------------------------------------------------------------
tr -d '\r' < "$BASE" | sed 's/#.*//' | awk 'NF == 2 && $2 ~ /^[0-9]+$/ { print $1, $2 }' | sort > "$T/base"

NB=$(wc -l < "$T/base" | tr -d '[:space:]')
if [ "$NB" -eq 0 ]; then
    echo "$NAME: FAIL — база $BASE пуста или не разобралась: сверять не с чем, а молчать нельзя (класс №519)" >&2
    exit 1
fi

# --- сверка ------------------------------------------------------------------
join -a1 -a2 -e '?' -o 0,1.2,2.2 "$T/fact" "$T/base" > "$T/joined"
GREW=$(awk '$2 != "?" && $3 != "?" && $2 + 0 > $3 + 0 { printf "  %s: экспортов %s, база %s — рост без поднятия базы\n", $1, $2, $3 }' "$T/joined")
SHRANK=$(awk '$2 != "?" && $3 != "?" && $2 + 0 < $3 + 0 { printf "  %s: экспортов %s, база %s — база протухла, опусти её\n", $1, $2, $3 }' "$T/joined")
NOBASE=$(awk '$3 == "?" { printf "  %s: модуль есть в коде (%s экспортов), строки в базе нет\n", $1, $2 }' "$T/joined")
NOMOD=$(awk '$2 == "?" { printf "  %s: строка в базе (%s), а модуля в коде нет\n", $1, $3 }' "$T/joined")

if [ -n "$GREW$SHRANK$NOBASE$NOMOD" ]; then
    echo "$NAME: FAIL — публичная поверхность разошлась с базой (274 §10.4):" >&2
    [ -n "$GREW" ]   && printf '%s\n' "$GREW" >&2
    [ -n "$SHRANK" ] && printf '%s\n' "$SHRANK" >&2
    [ -n "$NOBASE" ] && printf '%s\n' "$NOBASE" >&2
    [ -n "$NOMOD" ]  && printf '%s\n' "$NOMOD" >&2
    echo "  Рост поверхности — сознательное решение: подними базу ТЕМ ЖЕ коммитом и" >&2
    echo "  назови в сообщении, зачем новое имя нужно наружу. Сужение — опусти базу," >&2
    echo "  иначе следующий рост до прежней цифры пройдёт молча." >&2
    exit 1
fi

TOTAL=$(awk '{ s += $2 } END { print s + 0 }' "$T/fact")
NM=$(wc -l < "$T/fact" | tr -d '[:space:]')
echo "$NAME ok: модулей $NM, экспортов всего $TOTAL, все на базе"
exit 0
