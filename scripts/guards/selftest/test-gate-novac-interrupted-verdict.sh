#!/usr/bin/env bash
# Самотест: УБИТЫЙ ГЕЙТ NOVAC НЕ ПИШЕТ ЗЕЛЁНОГО ВЕРДИКТА (реестр 221.1 №1307).
#
# КЛАСС: вердикт, который пишет ловушка EXIT по `$?` ПОСЛЕДНЕЙ завершённой
# команды, делает прерванный прогон зелёным. Прогон, убитый сигналом посреди
# работы, выходит через ту же ловушку и наследует 0 от последнего успешного
# шага. Замер 2026-09-23: интегратор снял гейт на 49-й секунде (он судил ветку
# без свежего `main`, и вердикт всё равно был бы непригоден), и в файл лёг
# `RC=0 SEC=49 TIER=novac HASH=16b501ea7…`. Страж слияния читает ровно RC, ярус
# и хэш — он открыл бы этим файлом слияние, которого никто не судил.
#
# ПОЧЕМУ ЖИВОЙ ПРОГОН, А НЕ ТОЛЬКО ВЫНУТАЯ ФУНКЦИЯ: дыра жила не в теле
# функции, а в том, ЧЕМ кончился процесс. Самотест, построенный на форме,
# которой в реальном пути нет, уже бывал зелёным над сломанным механизмом
# (реестр №989). Поэтому случай 1 запускает НАСТОЯЩИЙ `gate-novac.sh` и убивает
# его сигналом сразу после первого шага — до первого шага гейт не зовёт
# компилятор, и прогон стоит секунды.
#
# ЧЕТЫРЕ СЛУЧАЯ, и каждый контролирует соседний:
#   1. живой гейт, убитый TERM после первого шага -> вердикт ЕСТЬ, RC не 0,
#      в строке INTERRUPTED=1 (молчание файла тоже было бы честным, но тогда
#      проба не отличила бы «убит» от «не стартовал»);
#   2. функция ловушки, вынутая из файла: $?=0 без флага -> RC=125;
#   3. ОБРАТНАЯ ПРОБА: $?=0 С флагом -> RC=0. Без неё правка могла бы просто
#      писать 125 всегда, и случаи 1–2 были бы зелены на сломанном гейте;
#   4. красный код не трогается: $?=1 без флага -> RC=1, а не 125 (различение
#      не должно прятать настоящий отказ под «прерван»).
# Плюс структура: флаг ставится ровно в одном месте и НИЖЕ последнего красного
# рубежа. Флаг, поднятый выше, снова сделал бы зелёным прогон, убитый между
# флагом и концом, — а случай 1 этого не увидел бы, он убивает гейт в начале.
#
# Запуск: bash scripts/guards/selftest/test-gate-novac-interrupted-verdict.sh
# Выход: 0 — механизм цел, 1 — сломан.

set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
GATE="$ROOT/scripts/gate-novac.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

CASES=0
FAILS=0
ok()   { CASES=$((CASES+1)); echo "  ok: $1"; }
bad()  { CASES=$((CASES+1)); FAILS=$((FAILS+1)); echo "  FAIL: $1"; }

[ -f "$GATE" ] || { echo "test-gate-novac-interrupted-verdict: нет $GATE"; exit 1; }

# --- 1: живой гейт, убитый сигналом ---------------------------------------
V="$TMP/verdict"
LOG="$TMP/gate.log"
NOVA_NOVAC_VERDICT="$V" NOVAC_TIER=loop bash "$GATE" "$ROOT" > "$LOG" 2>&1 &
PID=$!
_seen=0
for _i in $(seq 1 180); do
    if grep -aq '== novac-gate:' "$LOG" 2>/dev/null; then _seen=1; break; fi
    kill -0 "$PID" 2>/dev/null || break
    sleep 0.5
done
if [ "$_seen" != "1" ]; then
    kill -TERM "$PID" 2>/dev/null; wait "$PID" 2>/dev/null
    bad "1: гейт не дошёл до первого шага за 90с — судить обрыв нечем (лог: $(tail -c 300 "$LOG" | tr '\n' ' '))"
else
    kill -TERM "$PID" 2>/dev/null
    wait "$PID" 2>/dev/null
    if [ ! -f "$V" ]; then
        bad "1: убитый гейт не оставил вердикта вовсе — нельзя отличить «убит» от «не стартовал»"
    else
        _line=$(cat "$V")
        _rc=$(sed -n 's/^RC=\([0-9][0-9]*\).*/\1/p' "$V" | head -1)
        case "${_rc:-}" in
            ''|0) bad "1: УБИТЫЙ гейт записал ЗЕЛЁНЫЙ вердикт: $_line" ;;
            *) case "$_line" in
                   *INTERRUPTED=1*) ok "1: убитый гейт красный и назван прерванным ($_line)" ;;
                   *) bad "1: убитый гейт красный, но не назван прерванным: $_line" ;;
               esac ;;
        esac
    fi
fi

# --- 2..4: функция ловушки, вынутая из файла -------------------------------
FN="$TMP/fn.sh"
sed -n '/^_novac_write_verdict() {/,/^}/p' "$GATE" > "$FN"
if ! grep -q '_novac_write_verdict' "$FN"; then
    bad "2-4: функция _novac_write_verdict не найдена в гейте"
else
    run_trap() {  # $1 = код последней команды, $2 = флаг
        (
            NOVAC_DONE="$TMP/v2"; GATE_T0=$(date +%s); SEAMS=""
            NOVAC_VERDICT_HASH=deadbeef; NOVAC_VERDICT_BRANCH=selftest
            NOVAC_REACHED_VERDICT="$2"
            . "$FN"
            (exit "$1"); _novac_write_verdict
        ) >/dev/null 2>&1
        sed -n 's/^RC=\([0-9][0-9]*\).*/\1/p' "$TMP/v2" | head -1
    }
    r=$(run_trap 0 0); [ "$r" = "125" ] && ok "2: \$?=0 без флага -> RC=125" || bad "2: \$?=0 без флага дал RC=$r, ждался 125"
    r=$(run_trap 0 1); [ "$r" = "0" ]   && ok "3: \$?=0 с флагом -> RC=0 (различение по флагу, не «всегда 125»)" || bad "3: \$?=0 с флагом дал RC=$r, ждался 0"
    r=$(run_trap 1 0); [ "$r" = "1" ]   && ok "4: \$?=1 без флага -> RC=1 (красный не прячется под «прерван»)" || bad "4: \$?=1 без флага дал RC=$r, ждался 1"
fi

# --- структура: флаг один, и он ниже последнего красного рубежа ------------
_set_lines=$(grep -n '^NOVAC_REACHED_VERDICT=1' "$GATE" | cut -d: -f1)
_n=$(printf '%s\n' "$_set_lines" | grep -c .)
_last_red=$(grep -nE '^[[:space:]]+exit [12]$' "$GATE" | tail -1 | cut -d: -f1)
if [ "$_n" != "1" ]; then
    bad "структура: флаг NOVAC_REACHED_VERDICT=1 ставится в $_n местах, ждалось ровно одно"
elif [ -z "${_last_red:-}" ] || [ "$_set_lines" -le "$_last_red" ]; then
    bad "структура: флаг (строка $_set_lines) стоит НЕ ниже последнего красного рубежа (строка ${_last_red:-?})"
else
    ok "структура: флаг один (строка $_set_lines), ниже последнего красного рубежа (строка $_last_red)"
fi

if [ "$FAILS" -gt 0 ]; then
    echo "test-gate-novac-interrupted-verdict: FAIL ($FAILS из $CASES)"
    exit 1
fi
echo "test-gate-novac-interrupted-verdict ok: $CASES случаев — убитый гейт novac не пишет зелёного вердикта"
exit 0
