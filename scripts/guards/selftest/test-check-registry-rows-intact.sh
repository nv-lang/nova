#!/usr/bin/env bash
# scripts/guards/selftest/test-check-registry-rows-intact.sh — самотест стража
# «реестр 221.1 не теряет строк при слиянии» (реестр №642; процедура слияния —
# в шапке docs/plans/221.1-bug-sweep.md).
#
# СЕМЬ СЛУЧАЕВ, каждый отвечает на свой вопрос:
#   1. фикстурный реестр ровно на базе — ЗЕЛЁНЫЙ;
#   2. одна строка потеряна (как при слиянии выбором стороны) — КРАСНЫЙ, и
#      названы файл и номер пропавшей записи;
#   3. дубль номера — КРАСНЫЙ, и названы ОБЕ строки адресом файл:строка;
#   4. новая дыра в нумерации, которой нет в gaps= — КРАСНЫЙ с номером;
#   5. пустой реестр (ноль подсудных строк) — КРАСНЫЙ как потеря мишени, а не
#      зелёный ноль;
#   6. файла реестра нет вовсе — тоже потеря мишени, КРАСНЫЙ;
#   7. реестр вырос, база не поднята — КРАСНЫЙ с готовыми числами: отстающий
#      храповик молча разрешил бы потерять столько же строк.
# Дополнительно: законная дыра из gaps= зелёная (случай 1 несёт её внутри).
#
# Настоящего дерева самотест НЕ трогает: только свои фикстуры.
set -u
export LC_ALL=C

ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/../../.." && pwd)"
G="$ROOT/scripts/guards/check-registry-rows-intact.py"
T="${TMPDIR:-/tmp}/registry-rows-selftest.$$"
FAILED=0
ok()  { echo "  ok: $1"; }
bad() { echo "  FAIL: $1"; FAILED=$((FAILED+1)); }
mkdir -p "$T"
trap 'rm -rf "$T"' EXIT

# Фикстурный реестр: номера 1,2,3,5,6 — номер 4 законная дыра, она в базе.
# Строки нарочно длинные и однострочные, как в настоящем реестре.
mk_reg() {  # $1 = путь файла, $2... = номера строк
    {
        echo "# фикстурный реестр"
        echo ""
        echo "| # | что | статус |"
        echo "|---|---|---|"
        for num in $2; do
            echo "| $num | K1 | zapis nomer $num, dlinnaya odnostrochnaya, kak v nastoyashchem reestre |"
        done
    } > "$1"
}

printf 'rows=5\nmax=6\ngaps=4\n' > "$T/base"
run() {  # $1 = путь реестра
    NOVA_REGISTRY_ROWS_BASELINE="$T/base" python "$G" "$ROOT" "$1" >"$T/out" 2>"$T/err"
}

# --- 1. ровно на базе, законная дыра №4 внутри ----------------------------------
mk_reg "$T/clean.md" "1 2 3 5 6"
if run "$T/clean.md"; then ok "пять записей при базе 5, дыра 4 законна — зелёный"
else bad "чистый реестр покраснел: $(cat "$T/err")"; fi

# --- 2. потеряна строка (слияние унесло №3) -------------------------------------
mk_reg "$T/lost.md" "1 2 5 6"
if run "$T/lost.md"; then bad "потеря строки прошла зелёным"
else
    if grep -q "lost.md" "$T/err" && grep -q "ПОТЕРЯНО 1" "$T/err" && grep -q "№3" "$T/err"; then
        ok "потеря строки красная, названы файл и номер"
    else bad "красный, но без адреса: $(cat "$T/err")"; fi
fi

# --- 3. дубль номера -------------------------------------------------------------
mk_reg "$T/dup.md" "1 2 3 3 5 6"
if run "$T/dup.md"; then bad "дубль номера прошёл зелёным"
else
    if grep -q "dup.md:7" "$T/err" && grep -q "dup.md:8" "$T/err"; then
        ok "дубль красный, обе строки названы адресом файл:строка"
    else bad "красный, но обе строки не названы: $(cat "$T/err")"; fi
fi

# --- 4. новая дыра, которой нет в gaps= ------------------------------------------
# Номеров пять (база сходится), максимум 7, но №5 пропал, а №7 добавлен.
mk_reg "$T/hole.md" "1 2 3 6 7"
if run "$T/hole.md"; then bad "новая дыра в нумерации прошла зелёной"
else
    if grep -q "hole.md" "$T/err" && grep -q "ДЫРА" "$T/err" && grep -q "№5" "$T/err"; then
        ok "новая дыра красная, номер назван"
    else bad "красный, но номер дыры не назван: $(cat "$T/err")"; fi
fi

# --- 5. ноль строк — потеря мишени -----------------------------------------------
printf '# tut byl reestr\n\ntekst bez tablicy\n' > "$T/empty.md"
if run "$T/empty.md"; then bad "ноль подсудных строк — а страж зелёный"
else
    if grep -q "empty.md" "$T/err" && grep -q "мишень потеряна" "$T/err"; then
        ok "пустой реестр красный, названа потеря мишени"
    else bad "красный, но не про мишень: $(cat "$T/err")"; fi
fi

# --- 6. файла реестра нет --------------------------------------------------------
if run "$T/net-takogo-fajla.md"; then bad "отсутствующий реестр — а страж зелёный"
else
    if grep -q "net-takogo-fajla.md" "$T/err" && grep -q "мишень потеряна" "$T/err"; then
        ok "отсутствующий реестр красный, путь назван"
    else bad "красный, но путь не назван: $(cat "$T/err")"; fi
fi

# --- 7. реестр вырос, база не поднята --------------------------------------------
mk_reg "$T/grown.md" "1 2 3 5 6 7"
if run "$T/grown.md"; then bad "рост при неподнятой базе прошёл зелёным"
else
    if grep -q "rows=6" "$T/err" && grep -q "max=7" "$T/err"; then
        ok "рост красный, готовые числа базы напечатаны"
    else bad "красный, но без готовых чисел: $(cat "$T/err")"; fi
fi

echo "итог: FAIL $FAILED"
if [ "$FAILED" -eq 0 ]; then
    echo "test-check-registry-rows-intact ok: потеря строки, дубль номера, новая дыра, пустой и отсутствующий реестр и отставшая база краснеют с адресом; реестр на базе с законной дырой зелёный"
    exit 0
fi
exit 1
