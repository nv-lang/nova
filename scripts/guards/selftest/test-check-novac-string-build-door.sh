#!/bin/sh
# Самотест check-novac-string-build-door.py (П16). Шов $2 — сканируемая директория.
# Форма строки НЕ украшение: check-novac-registry-counts.sh считает случаи по
# шаблону "^[[:space:]]+ok[[:space:]]", то есть двоеточие после ok делает случай
# невидимым для счёта, а число в строке реестра — ложью.
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$GD/../.." && pwd)"
G="$GD/check-novac-string-build-door.py"
T="${TMPDIR:-/tmp}/novac-strbuild-selftest.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok   $1"; }
bad() { echo "  FAIL: $1" >&2; fails=$((fails+1)); }
run() { python "$G" "$ROOT" "$1" > "$T/out" 2> "$T/err"; }
mk()  { d="$T/$1"; mkdir -p "$d/m"; f="$d/m/$2"; shift 2; printf "%s\n" "$@" > "$f"; echo "$d"; }

# --- ГЛАВНЫЙ случай: строка склеивается сама с собой -----------------------
D=$(mk loop m.nv "module a" "fn render() -> str {" "    mut out = \"\"" \
    "    for i in 0..n {" "        out = \"\${out}(\"" "    }" "    out" "}")
if run "$D"; then
    bad "склейка строки самой с собой прошла - главный случай не ловится"
else
    grep -q "m.nv:5" "$T/err" && ok "склейка в цикле поймана с номером строки" \
        || bad "покраснел без точного места"
fi

# --- та же форма с текстом ПЕРЕД интерполяцией -----------------------------
D=$(mk prefix m.nv "module a" "fn f() -> () {" "    s = \", \${s}\"" "}")
run "$D" && bad "склейка с текстом слева прошла" || ok "склейка с текстом слева поймана"

# --- та же форма с полем: \${out.x} ----------------------------------------
D=$(mk field m.nv "module a" "fn f() -> () {" "    out = \"\${out.buf}!\"" "}")
run "$D" && bad "склейка через поле той же переменной прошла" \
    || ok "склейка через поле той же переменной поймана"

# --- ЗАКОННОЕ: билдер --------------------------------------------------------
D=$(mk builder m.nv "module a" "fn render() -> str {" "    consume sb = StringBuilder.new()" \
    "    for i in 0..n {" "        sb.append(\"(\")" "    }" "    sb.into_str()" "}")
run "$D" && ok "сборка через StringBuilder проходит" \
    || bad "страж съел билдер - он запрещает то, что сам предлагает"

# --- ЗАКОННОЕ: интерполируется ДРУГАЯ переменная ---------------------------
D=$(mk other m.nv "module a" "fn f() -> str {" "    msg = \"expected \${want}, found \${got}\"" "    msg" "}")
run "$D" && ok "интерполяция другой переменной проходит" \
    || bad "страж съел обычную интерполяцию - правило шире класса"

# --- ЗАКОННОЕ: комментарий, ЦИТИРУЮЩИЙ запрещённую форму -------------------
D=$(mk comment m.nv "module a" \
    "// A BUILDER, not repeated interpolation: out = \"\${out}...\" in a loop" \
    "// copies everything gathered so far on every step." "fn f() -> () { }")
run "$D" && ok "комментарий с причиной проходит" \
    || bad "комментарий покраснел - страж стирает причину вместе с симптомом"

# --- ЗАКОННОЕ и НАЗВАННОЕ: та же форма в тесте -----------------------------
# Тест собирает текст фикстуры ОДИН раз, длина видна в самом тесте. Исключение
# названо в шапке стража; случай ниже держит его от тихого расширения.
D="$T/intest"; mkdir -p "$D/m"
printf "%s\n" "module a" "fn f() -> () { }" > "$D/m/m.nv"
printf "%s\n" "module a" "fn t() -> () {" "    deep = \"\${deep}(\"" "}" > "$D/m/m_test.nv"
run "$D" && ok "сборка фикстуры в _test.nv проходит" \
    || bad "страж вышел за свой класс - тест собирает текст один раз"

# --- ПОТЕРЯННАЯ МИШЕНЬ: вне тестов не осталось ни одного .nv ---------------
D2="$T/blind"; mkdir -p "$D2/m"
printf "%s\n" "module a" "fn t() -> () { }" > "$D2/m/m_test.nv"
if run "$D2"; then
    bad "ноль судимых файлов прошёл - страж слеп и печатает ноль как замер"
else
    grep -q "потерял мишень" "$T/err" && ok "потерянная мишень поймана" \
        || bad "покраснел не тем текстом на потерянной мишени"
fi

# --- НЕТ ДИРЕКТОРИИ ВОВСЕ: судить нечего, и это сказано вслух --------------
if run "$T/no-such-dir"; then
    grep -q "судить нечего" "$T/out" && ok "отсутствие каталога названо вслух" \
        || bad "прошёл молча - зелёный без замера неотличим от проверки"
else
    bad "отсутствие каталога покраснело - страж требует того, чего может не быть"
fi

[ "$fails" -eq 0 ] && echo "test-check-novac-string-build-door: ok" || exit 1
