#!/bin/sh
# Самотест check-novac-conventions-coverage.sh (П16: обязан доказать, что ловит).
# Шов $2 — путь к файлу конвенций; каждый случай это свой крошечный файл.
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$GD/../.." && pwd)"
G="$GD/check-novac-conventions-coverage.sh"
T="${TMPDIR:-/tmp}/novac-conv-cov-selftest.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok: $1"; }
bad() { echo "  FAIL: $1" >&2; fails=$((fails+1)); }
run() { sh "$G" "$ROOT" "$1" > "$T/out" 2> "$T/err"; }

# --- 1. у обоих правил назван страж — зелёный ----------------------------
cat > "$T/c1.md" <<'EOF'
# Конвенции

## П1. Первое правило

Текст правила.

**Механизм:** `check-novac-deps.py`.

## П2. Второе правило

Текст.

Держит `check-novac-no-panic.sh`.
EOF
if run "$T/c1.md"; then
    grep -q "правил конвенции: 2" "$T/out" && ok "оба со стражем — зелёный, счёт верный" || bad "зелёный, но счёт не тот [$(cat "$T/out")]"
else
    bad "чистый файл покраснел: $(cat "$T/err")"
fi

# --- 2. ГЛАВНЫЙ случай: правило без механизма — красный ------------------
cat > "$T/c2.md" <<'EOF'
# Конвенции

## П1. Со стражем

`check-novac-deps.py` держит это.

## П2. Без всего

Просто текст правила, и ничего больше.
EOF
if run "$T/c2.md"; then
    bad "правило без механизма прошло — страж не ловит свой главный случай"
else
    grep -q "П2" "$T/err" && ok "правило без механизма поймано и названо" || bad "красный, но П2 не назван [$(cat "$T/err")]"
fi

# --- 3. честная пометка немашинности — зелёная --------------------------
cat > "$T/c3.md" <<'EOF'
# Конвенции

## П1. Немашинное правило

⚖ Машине не формализуемо: судится приёмкой.
EOF
run "$T/c3.md" && ok "честная пометка немашинности принимается" || bad "пометка не сработала: $(cat "$T/err")"

# --- 4. словесная форма той же пометки ----------------------------------
cat > "$T/c4.md" <<'EOF'
# Конвенции

## П1. Тоже немашинное

Это суждение, скриптом не формализуемо, красные на ревью.
EOF
run "$T/c4.md" && ok "словесная пометка немашинности принимается" || bad "словесная пометка не сработала"

# --- 5. страж, названный в СОСЕДНЕМ правиле, не покрывает наше ----------
cat > "$T/c5.md" <<'EOF'
# Конвенции

## П1. Со стражем

`check-novac-deps.py`.

## П2. Без механизма

Ничего.

## П3. Снова со стражем

`check-novac-no-panic.sh`.
EOF
if run "$T/c5.md"; then
    bad "правило без механизма между двумя покрытыми прошло"
else
    grep -q "П2" "$T/err" && ok "покрытие не протекает от соседа" || bad "красный, но не про П2"
fi

# --- 6. заголовки переименованы / разделов нет — КРАСНЫЙ, не зелёный ----
cat > "$T/c6.md" <<'EOF'
# Конвенции

## Правило первое

Текст без нумерации.
EOF
if run "$T/c6.md"; then
    bad "файл без разделов ПNN дал зелёный — вечнозелёный страж (класс №519)"
else
    grep -q "потерял мишень" "$T/err" && ok "потеря мишени — красный, названо почему" || bad "красный, но без объяснения"
fi

# --- 7. нет файла конвенций — судить нечего -----------------------------
run "$T/absent.md"
grep -q "судить нечего" "$T/out" && ok "нет файла — судить нечего" || bad "ждали «судить нечего»"

# --- 8. настоящий файл конвенций ----------------------------------------
sh "$G" "$ROOT" >/dev/null 2>&1 && ok "настоящие конвенции — зелёные" || bad "настоящий файл покраснел: $(sh "$G" "$ROOT" 2>&1 | head -3)"

echo "итог: FAIL $fails"
if [ "$fails" -eq 0 ]; then
    echo "test-check-novac-conventions-coverage ok: все случаи, включая правило без механизма и потерю мишени"
    exit 0
fi
exit 1
