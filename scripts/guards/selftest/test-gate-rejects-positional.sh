#!/bin/sh
# Самотест: гейт обязан ОТКАЗАТЬ на позиционный аргумент, а не глотать его
# (реестр 221.1 №778; П16 — страж без доказательства красноты запрещён).
#
# Почему это вообще самотест, а не «ну не пиши так». `bash scripts/gate.sh loop`
# — самая естественная форма записи из всех возможных: так зовут почти любой
# скрипт с режимами. Гейт же читает ярус ТОЛЬКО из `NOVA_GATE_TIER`, а
# умолчание у него `full`. То есть очевидная опечатка запускала самый тяжёлый
# ярус вместо самого лёгкого — молча, и выглядела зависанием: 2026-08-27 это
# случилось дважды подряд по десять минут.
#
# Краснота доказывается МУТАЦИЕЙ ПОДСУДНОГО: подложному гейту отнимаем блок
# отказа и ждём, что аргумент снова проглочен. Без этой части самотест доказывал
# бы лишь то, что настоящий гейт сегодня зелёный, — а не то, что судит он именно
# блок отказа.
export LC_ALL=C
SD="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SD/../../.." && pwd)"
GATE="$ROOT/scripts/gate.sh"
T="${TMPDIR:-/tmp}/nova-gate-positional-selftest.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok   $1"; }
bad() { echo "  FAIL $1" >&2; fails=$((fails+1)); }

[ -f "$GATE" ] || { echo "  FAIL нет судимого файла: $GATE" >&2; exit 1; }

# ── краснеет: настоящий гейт на имени яруса в аргументе ───────────────────
out="$(bash "$GATE" loop 2>&1)"; rc=$?
[ "$rc" -ne 0 ] && ok "имя яруса аргументом — отказ (rc=$rc)" \
                || bad "имя яруса аргументом проглочено (rc=0) — ярус ушёл бы в full"
case "$out" in
    *"NOVA_GATE_TIER=loop bash scripts/gate.sh"*)
        ok "в отказе названа правильная строка вызова" ;;
    *)  bad "отказ не назвал правильную строку вызова" ;;
esac
case "$out" in
    *full*) ok "сказано, какой ярус пошёл бы молча" ;;
    *)      bad "не сказано, какой ярус пошёл бы молча" ;;
esac

# Отказ обязан быть ДЕШЁВЫМ: он стоит до первого тяжёлого шага, иначе цена
# опечатки остаётся прежней. Шагов гейта в выводе быть не должно.
case "$out" in
    *"== gate:"*) bad "отказ пришёл ПОСЛЕ шагов гейта — цена опечатки не снята" ;;
    *)            ok "отказ пришёл до первого шага" ;;
esac

# ── краснеет: посторонний аргумент ────────────────────────────────────────
out2="$(bash "$GATE" --tier=loop 2>&1)"; rc2=$?
[ "$rc2" -ne 0 ] && ok "посторонний аргумент — отказ (rc=$rc2)" \
                 || bad "посторонний аргумент проглочен (rc=0)"
case "$out2" in
    *"NOVA_GATE_DRYRUN=1"*) ok "в отказе назван и сухой ход" ;;
    *) bad "отказ не назвал сухой ход" ;;
esac

# ── проходит: без аргументов блок молчит (сухой ход, ничего не исполняя) ──
out3="$(NOVA_GATE_DRYRUN=1 bash "$GATE" 2>&1)"; rc3=$?
case "$out3" in
    *"не принимает аргументов"*|*"а не аргументом"*)
        bad "блок сработал БЕЗ аргументов — ложное срабатывание" ;;
    *)  ok "без аргументов блок молчит" ;;
esac
[ "$rc3" -eq 0 ] && ok "сухой ход без аргументов зелёный" \
                 || bad "сухой ход без аргументов покраснел (rc=$rc3)"

# ── мутация подсудного: без блока отказа аргумент снова проглочен ─────────
cat > "$T/gate-with.sh" <<'SH'
if [ "$#" -ne 0 ]; then
    case "$1" in
        loop|push|full) echo "GATE FATAL: ярус задаётся переменной окружения" >&2 ;;
        *) echo "GATE FATAL: гейт не принимает аргументов" >&2 ;;
    esac
    exit 1
fi
NOVA_GATE_TIER="${NOVA_GATE_TIER:-full}"
echo "tier=$NOVA_GATE_TIER"
SH
cat > "$T/gate-without.sh" <<'SH'
NOVA_GATE_TIER="${NOVA_GATE_TIER:-full}"
echo "tier=$NOVA_GATE_TIER"
SH

bash "$T/gate-with.sh" loop >/dev/null 2>&1 \
    && bad "подложный гейт С блоком проглотил аргумент" \
    || ok "подложный гейт С блоком отказал"

mout="$(bash "$T/gate-without.sh" loop 2>&1)"
[ "$mout" = "tier=full" ] \
    && ok "мутант БЕЗ блока воспроизводит дефект дословно (tier=full на 'loop')" \
    || bad "мутант БЕЗ блока дал '$mout', ожидалось tier=full"

echo "самотест gate-rejects-positional: PASS $((10-fails)) FAIL $fails"
[ "$fails" -eq 0 ]
