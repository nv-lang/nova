#!/bin/sh
# Самотест check-runtime-cxx-clean.sh (реестр 221.1 №1061). Доказывает ТРИ
# стороны, и ни одна не смотрит на живое дерево: шов — аргумент корня, поэтому
# подложка своя, и вердикт самотеста не смешивается с состоянием настоящих
# заголовков. Стояла бы проба на живом дереве — красный самотест означал бы
# сразу «проверка сломана» и «рантайм сломан», два события под одним цветом.
#
# 1. заголовок, который C++ принимает   -> зелено;
# 2. составной литерал `(T){...}` в нём -> красно, и в тексте назван №1061;
# 3. C++-драйвера нет                   -> ПРОПУЩЕНО вслух, а не тихое зелёное.
#
# Третий случай главный: тихий пропуск дал бы зелёную строку со смыслом
# «проверено» при непроверенном — ровно тот класс, ради которого страж заведён.
# Драйвера в нём нет не потому, что выпотрошен PATH (тогда пропали бы и mktemp
# с grep, и страж падал бы по другой причине, а проба доказывала бы не то), а
# через собственный шов стража NOVA_CXX — имя, которого нет ни в одном каталоге.
#
# ОПРЕДЕЛЕНИЕ ДРАЙВЕРА ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ: самотест спрашивает об этом сам
# страж, читая его вывод. Второй список каталогов разошёлся бы с первым на
# первой же машине с другим расположением LLVM.
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
G="$GD/check-runtime-cxx-clean.sh"
T="${TMPDIR:-/tmp}/runtime-cxx-clean-selftest.$$"
trap 'rm -rf "$T"' 0
fails=0
cases=0
ok()   { echo "  ok: $1"; }
bad()  { echo "  FAIL: $1" >&2; fails=$((fails+1)); }
skip() { echo "  ПРОПУСК: $1"; }

mk() {
    d="$T/$1"; mkdir -p "$d/compiler-codegen/nova_rt"
    echo "$d"
}

# --- случай 1: заголовок, законный в обоих языках ----------------------------
cases=$((cases+1))
D=$(mk clean)
cat > "$D/compiler-codegen/nova_rt/nova_rt.h" <<'EOF'
#include <stdint.h>
typedef struct { const uint8_t* ptr; int64_t len; } nova_str;
static inline nova_str nova_str_of(const void* p, int64_t n) {
    nova_str s; s.ptr = (const uint8_t*)p; s.len = n; return s;
}
EOF
sh "$G" "$D" > "$T/out1" 2> "$T/err1"; rc1=$?
if grep -q "НЕ СУДИЛ" "$T/out1"; then
    skip "случай 1: C++-драйвера на машине нет — судить нечем (это проверяет случай 3)"
elif [ "$rc1" -eq 0 ]; then
    grep -q " ok" "$T/out1" && ok "чистый заголовок — зелено, вердикт назван" \
        || bad "вышел с нулём, но вердикт не назван словом ok"
else
    bad "чистый заголовок покраснел: $(cat "$T/err1")"
fi

# --- случай 2: ГЛАВНЫЙ — составной литерал, которого в C++ нет ----------------
cases=$((cases+1))
D=$(mk broken)
cat > "$D/compiler-codegen/nova_rt/nova_rt.h" <<'EOF'
#include <stdint.h>
typedef struct { const uint8_t* ptr; int64_t len; } nova_str;
static nova_str nova_bad(const char* p) { return (nova_str){ p, 3 }; }
EOF
sh "$G" "$D" > "$T/out2" 2> "$T/err2"; rc2=$?
if grep -q "НЕ СУДИЛ" "$T/out2"; then
    skip "случай 2: C++-драйвера на машине нет"
elif [ "$rc2" -eq 0 ]; then
    bad "составной литерал прошёл зелёным — страж не судит того, ради чего заведён"
else
    grep -q "1061" "$T/err2" && ok "составной литерал — красно, запись реестра названа" \
        || bad "красно, но в тексте нет №1061: чинящий не найдёт, куда идти"
fi

# --- случай 3: драйвера нет — пропуск обязан быть ГРОМКИМ ---------------------
cases=$((cases+1))
D=$(mk noc)
cat > "$D/compiler-codegen/nova_rt/nova_rt.h" <<'EOF'
#include <stdint.h>
typedef struct { const uint8_t* ptr; int64_t len; } nova_str;
EOF
if NOVA_CXX="no-such-cxx-driver-4f2a" sh "$G" "$D" > "$T/out3" 2> "$T/err3"; then
    # ДВА требования разом: `ok:` — чтобы обёртка гейта сочла шаг доказанным
    # (без неё авторитетный CI краснеет, замер 2026-09-09), и слова «НЕ СУДИЛ» —
    # чтобы человек не прочёл зелёную строку как «проверено».
    if grep -q "ok:" "$T/out3" && grep -q "НЕ СУДИЛ" "$T/out3"; then
        ok "без драйвера — пропуск назван вслух, а не тихое зелёное"
    else
        bad "вышел с нулём, но пропуск не объявлен: строка читается как «проверено»"
    fi
else
    bad "без драйвера страж покраснел — ложный отказ, судить было нечем"
fi

echo "test-check-runtime-cxx-clean: случаев $cases, отказов $fails"
[ "$fails" -eq 0 ] || exit 1
