#!/bin/sh
# Самотест check-plans-tag-bound (П16: страж без доказательства красноты
# запрещён). Обе стороны каждого свойства — на подложном дереве планов.
#
# Отдельно доказывается СИММЕТРИЯ базы: рост краснеет, и падение краснеет тоже.
# База, оставленная высокой, молча разрешает откатиться ровно на столько, на
# сколько продвинулся, — поэтому «упало ниже базы» здесь такой же обязательный
# красный случай, как «выросло».
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
G="$GD/check-plans-tag-bound.py"
T="${TMPDIR:-/tmp}/nova-plans-tag-bound-selftest.$$"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok   $1"; }
bad() { echo "  FAIL $1" >&2; fails=$((fails+1)); }

P="$T/tree/docs/plans"
B="$T/tree/scripts/guards/plans-tag-bound.baseline"
mk() { rm -rf "$T/tree"; mkdir -p "$P" "$T/tree/scripts/guards"; }
base() { printf '# chronicle\nno_verdict=%s\n' "$1" > "$B"; }
run() { python "$G" "$T/tree" >"$T/out" 2>"$T/err"; echo $?; }
said() { grep -q "$1" "$T/out" "$T/err" 2>/dev/null; }

# ── 1. кандидат С вердиктом при базе 0 — зелено ─────────────────────────────
mk; base 0
cat > "$P/900-x.md" <<'EOF'
# План 900
**Статус:** ЖДЁТ 1.0 — работа была привязана к тегу, теперь к релизу Карины.
Фаза 2 делалась после тега.
EOF
[ "$(run)" = "0" ] && ok "кандидат с вердиктом — зелено" \
    || bad "план с вердиктом не должен краснеть"

# ── 2. кандидат БЕЗ вердикта при базе 0 — красно, и файл назван ─────────────
mk; base 0
cat > "$P/900-x.md" <<'EOF'
# План 900
**Статус:** в работе. Волна 2 — после тега.
EOF
[ "$(run)" = "1" ] && said "900-x.md" \
    && ok "кандидат без вердикта — красно, и файл назван" \
    || bad "план без вердикта обязан краснеть с именем файла"

# ── 3. тот же файл при базе 1 — зелено (база держит историю) ────────────────
mk; base 1
cat > "$P/900-x.md" <<'EOF'
# План 900
**Статус:** в работе. Волна 2 — после тега.
EOF
[ "$(run)" = "0" ] && ok "база 1 держит один незакрытый — зелено" \
    || bad "страж не должен краснеть на том, что уже в базе"

# ── 4. вердикт проставлен, база не опущена — КРАСНО ─────────────────────────
mk; base 1
cat > "$P/900-x.md" <<'EOF'
# План 900
**Статус:** ИСКЛЮЧЕНИЕ 0.3 — без него не собираются примеры. Фаза 2 — после тега.
EOF
[ "$(run)" = "1" ] && ok "падение ниже базы — красно (базу опускают той же правкой)" \
    || bad "база, оставленная высокой, обязана краснеть"

# ── 5. файл-ПРЕДМЕТ (реестр оракула) кандидатом не считается ────────────────
mk; base 0
cat > "$P/221.1-bug-sweep.md" <<'EOF'
# Реестр
Строка блокирует тег; чинится до тега.
EOF
[ "$(run)" = "0" ] && said "kandidatov 0" \
    && ok "221.1 — предмет, а не кандидат" \
    || bad "файлы-предметы не должны попадать в счёт"

# ── 6. план БЕЗ фразы о теге — не кандидат ─────────────────────────────────
mk; base 0
cat > "$P/901-y.md" <<'EOF'
# План 901
**Статус:** в работе, срок не привязан ни к чему.
EOF
[ "$(run)" = "0" ] && said "kandidatov 0" \
    && ok "план без фразы о теге — не кандидат" \
    || bad "страж считает лишнее"

# ── 7. база без строки no_verdict= — FAIL, а не тихий ноль ─────────────────
mk
printf '# tol_ko letopis_ i ni odnoj stroki znacheniya\n' > "$B"
cat > "$P/900-x.md" <<'EOF'
# План 900
**Статус:** волна 2 — после тега.
EOF
[ "$(run)" = "1" ] && said "no_verdict" \
    && ok "база без значения — FAIL с названной причиной" \
    || bad "потерянная строка базы обязана краснеть, а не читаться нулём"

if [ "$fails" -ne 0 ]; then
    echo "test-check-plans-tag-bound: FAIL ($fails)" >&2
    exit 1
fi
echo "test-check-plans-tag-bound: ok"
