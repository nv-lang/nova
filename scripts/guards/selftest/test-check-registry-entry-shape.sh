#!/usr/bin/env bash
# Селфтест scripts/guards/check-registry-entry-shape.sh.
#
# Проверяем ОБА направления. Второе важнее первого: страж, краснеющий на
# правильно оформленной записи, будет отключён в первый же день, и правило умрёт
# вместе с ним — как уже случилось бы с check-no-accumulation, если бы он считал
# накоплением всякую рабочую ветку окна.
set -u
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
G="$ROOT/scripts/guards/check-registry-entry-shape.sh"
FAILED=0
ok()  { echo "  ok: $1"; }
bad() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/docs/plans" "$TMP/scripts/guards"
REG="$TMP/docs/plans/221.1-bug-sweep.md"
BASE="$TMP/base"

# Полностью оформленная запись — образец.
GOOD='| 900 | 🔴 К1 | **Заголовок дефекта.** Описание. **КЛАСС: одна операция размазана по трём местам.** Фикс носителя приёмкой НЕ считается. **БЛОКИРУЕТ ТЕГ: ДА — молча неверный результат.** |'

mk() { printf '%s\n' "$@" > "$REG"; }

# 1. Полная запись — зелено при базе 0.
mk "$GOOD"; echo 'incomplete_entries=0' > "$BASE"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ]; then ok "полная запись проходит"; else bad "ложный отказ на полной записи: $out"; fi

# 2. Нет приоритета.
mk '| 901 | **Заголовок.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q 'приоритет'; then ok "ловит запись без приоритета"; else bad "не поймал отсутствие приоритета (код $rc): $out"; fi

# 3. Нет класса — самый опасный случай: окно починит носителя.
mk '| 902 | 🔴 К1 | **Заголовок.** Описание. Фикс носителя приёмкой НЕ считается. **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q 'класс'; then ok "ловит запись без КЛАССА"; else bad "не поймал отсутствие класса (код $rc): $out"; fi

# 4. Нет оговорки о носителе.
mk '| 903 | 🟡 К2 | **Заголовок.** **КЛАСС: что-то.** Описание. |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q 'оговорка-о-носителе'; then ok "ловит запись без оговорки о носителе"; else bad "не поймал отсутствие оговорки (код $rc): $out"; fi

# 5. Храповик держит существующий долг: две неполные записи при базе 2 — зелено.
mk '| 904 | 🔴 К1 | **A.** Описание. **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |' '| 905 | 🔴 К1 | **B.** Описание. **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |'
echo 'incomplete_entries=2' > "$BASE"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ]; then ok "храповик держит долг в пределах базы"; else bad "ложный отказ на долге в базе (код $rc): $out"; fi

# 6. Рост сверх базы — красно.
mk '| 904 | 🔴 К1 | **A.** **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |' '| 905 | 🔴 К1 | **B.** **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |' '| 906 | 🔴 К1 | **C.** **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q 'ВЫРОСЛО'; then ok "ловит рост сверх базы"; else bad "не поймал рост (код $rc): $out"; fi

# 7. Снижение долга — зелено, но сообщает, что базу надо опустить.
mk "$GOOD"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ] && echo "$out" | grep -q 'СНИЗИЛСЯ'; then ok "сообщает о снижении долга"; else bad "не сообщил о снижении (код $rc): $out"; fi

# 8. К3 — тоже приоритет. Проверка появилась после того, как страж считал
#    двенадцать записей с К3 неоформленными и держал их в базе долга.
mk '| 907 | 🟢 К3 | **Заголовок.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. |'
echo 'incomplete_entries=0' > "$BASE"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ]; then ok "К3 считается приоритетом"; else bad "ложный отказ на записи с К3 (код $rc): $out"; fi

# 9. Запись без номера (TBD) — красно. Она невидима проверке формы, значит
#    «оформлено» считалось бы по неполному множеству.
mk "$GOOD" '| TBD | 🔴 К1 | **Заголовок.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. **БЛОКИРУЕТ ТЕГ: НЕТ — фикстура селфтеста.** |'
echo 'incomplete_entries=0' > "$BASE"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q 'без номера'; then ok "ловит запись с TBD вместо номера"; else bad "не поймал TBD (код $rc): $out"; fi

# 10. И обратно: полностью оформленные записи БЕЗ TBD — зелено (не ложняк).
mk "$GOOD"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ]; then ok "без TBD ложняка нет"; else bad "ложный отказ после проверки TBD (код $rc): $out"; fi

# 11. Открытая К1 без вердикта «БЛОКИРУЕТ ТЕГ» — красно, и БЕЗ храповика.
#     Поле введено разбором 2026-08-11 по всем открытым К1 сразу, поэтому
#     множество полное и послабления не нужно: новая К1 обязана нести вердикт.
mk '| 908 | 🔴 К1 | **Заголовок.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. Статус: ОТКРЫТ |'
echo 'incomplete_entries=0' > "$BASE"
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q 'БЛОКИРУЕТ ТЕГ'; then ok "ловит К1 без вердикта о теге"; else bad "не поймал К1 без вердикта (rc=$rc): $out"; fi

# 12. ЗАКРЫТАЯ К1 вердикта не требует — вопрос «держит ли тег» к ней не стоит.
#     И К2 не требует тоже: слово «К1» в прозе соседней записи не делает её К1.
mk '| 909 | 🔴 К1 | **Заголовок.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. Статус: ЗАКРЫТ |' \
   '| 910 | 🟡 К2 | **Заголовок.** **КЛАСС: тот же, что у К1-записи №908.** Фикс носителя приёмкой НЕ считается. |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ]; then ok "закрытая К1 и К2 вердикта не требуют"; else bad "ложный отказ на закрытой К1 / К2: $out"; fi

# 13. Один номер двумя строками — красно, номер назван. Дубль рождается
#     слиянием «сохранить обе стороны» (№753, 2026-08-24: две строки разной
#     длины, два дня, нашлось случайно).
mk '| 911 | 🟡 К2 | **A.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. |' \
   '| 911 | 🟡 К2 | **A, длиннее.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. Ещё хвост. |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 1 ] && echo "$out" | grep -q '911 x2'; then ok "ловит дубль номера и называет его"; else bad "дубль номера не пойман"; fi

# 14. Разные номера — ложняка нет.
mk '| 912 | 🟡 К2 | **A.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. |' \
   '| 913 | 🟡 К2 | **B.** **КЛАСС: что-то.** Фикс носителя приёмкой НЕ считается. |'
out=$(NOVA_REGSHAPE_BASELINE="$BASE" bash "$G" "$TMP" 2>&1); rc=$?
if [ "$rc" -eq 0 ]; then ok "разные номера проходят"; else bad "ложный отказ на разных номерах"; fi

if [ "$FAILED" -eq 0 ]; then echo "селфтест check-registry-entry-shape: 14/14 ok"; exit 0; fi
echo "селфтест check-registry-entry-shape: ЕСТЬ ПРОВАЛЫ" >&2
exit 1
