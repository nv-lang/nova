#!/usr/bin/env bash
# Самотест check-novac-acceptance-donor.py — обе стороны, на фикстурном плане.
#
# ЦЕНТРАЛЬНЫЙ СЛУЧАЙ — ГРАНИЦА БЛОКА. Приёмка кончается следующим заголовком
# раздела, а не пустой строкой: блоки в плане 274 многоабзацные, и страж с
# окном «до пустой строки» объявил бы недоназванным донора, стоящего третьим
# абзацем. Второй — честное «донор: нет» принимается: отсутствие эталона это
# ответ, если он назван.
set -u
export LC_ALL=C
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
G="$ROOT/scripts/guards/check-novac-acceptance-donor.py"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); echo "  ok   $1"; }
bad() { FAIL=$((FAIL+1)); echo "  FAIL $1" >&2; }
check(){ if [ "$2" = "$3" ]; then ok "$1"; else bad "$1 (ждал '$3', получил '$2')"; fi; }
has(){ if printf '%s' "$2" | grep -q "$3"; then ok "$1"; else bad "$1 (в выводе нет '$3': '$2')"; fi; }

P="$TMP/plan.md"

echo "== проходит =="
python "$G" "$TMP" "$TMP/nowhere.md" >/dev/null 2>&1
check "нет плана — зелёный (судить нечего)" "$?" "0"

printf '**ПРИЁМКА В1.** Гейт зелёный.\n\n**Донор:** rustc newtype_index.\n\n#### Следующий раздел\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "донор ВТОРЫМ абзацем — зелёный (граница по заголовку)" "$RC" "0"
has "назвал число блоков" "$OUT" "1"

printf '**ПРИЁМКА В2.** Гейт зелёный.\n\nМного текста.\n\nЕщё абзац.\n\n**Донор: нет** — это наше решение, эталон молчит.\n\n### Раздел\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "честное «донор: нет» — зелёный" "$RC" "0"

printf '**ПРИЁМКА В3.** Донор: Go, unused import это ошибка.\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "донор в той же строке, план кончился — зелёный" "$RC" "0"

printf '**ПРИЁМКА A.** Донор: rustc.\n\n#### Р\n\n**ПРИЁМКА B.** Донор: Go.\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "ДВА блока, у обоих донор — зелёный" "$RC" "0"
has "посчитал оба" "$OUT" "2"

echo "== краснеет =="
printf '**ПРИЁМКА В4.** Гейт зелёный, модульные 8/8.\n\nЧисло поймано: ноль.\n\n#### Раздел\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "приёмка без донора — красный" "$RC" "1"
has "назвал строку" "$OUT" "строка 1"

printf '**ПРИЁМКА A.** Донор: rustc.\n\n#### Р\n\n**ПРИЁМКА B.** Без эталона.\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "один из двух без донора — красный" "$RC" "1"
has "указал именно ВТОРОЙ блок" "$OUT" "ПРИЁМКА B"

printf '#### Раздел без приёмок\n\nТекст.\n' > "$P"
OUT=$(python "$G" "$TMP" "$P" 2>&1); RC=$?
check "план без приёмок — красный (страж потерял мишень)" "$RC" "1"
has "назвал класс потерянной мишени" "$OUT" "519"

echo "самотест check-novac-acceptance-donor: PASS $PASS FAIL $FAIL"
[ "$FAIL" -eq 0 ]
