#!/bin/sh
# Самотест check-novac-no-copy-loop.sh (П16). Шов $2 — сканируемая директория.
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$GD/../.." && pwd)"
G="$GD/check-novac-no-copy-loop.sh"
T="${TMPDIR:-/tmp}/novac-copyloop-selftest.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok: $1"; }
bad() { echo "  FAIL: $1" >&2; fails=$((fails+1)); }
run() { sh "$G" "$ROOT" "$1" > "$T/out" 2> "$T/err"; }
mk()  { d="$T/$1"; mkdir -p "$d/m"; shift; printf "%s\n" "$@" > "$d/m/m.nv"; echo "$d"; }

# --- ГЛАВНЫЙ случай: однострочное перекладывание --------------------------
D=$(mk oneline "module a" "fn f() -> () {" "    for n in src() { out.push(n) }" "}")
if run "$D"; then
    bad "однострочное перекладывание прошло — главный случай не ловится"
else
    grep -q "перекладывание поэлементно" "$T/err" && ok "однострочный цикл пойман" \
        || bad "покраснел не тем текстом"
fi

# --- ГЛАВНЫЙ случай: многострочное ---------------------------------------
D=$(mk block "module a" "fn f() -> () {" "    for n in src() {" "        out.push(n)" "    }" "}")
if run "$D"; then
    bad "многострочное перекладывание прошло"
else
    grep -q "перекладывание поэлементно" "$T/err" && ok "многострочный цикл пойман" \
        || bad "покраснел не тем текстом"
fi

# --- цикл НЕСЁТ работу: преобразование ------------------------------------
D=$(mk mapped "module a" "fn f() -> () {" "    for n in src() { out.push(wrap(n)) }" "}")
run "$D" && ok "push преобразования не считается перекладыванием" \
    || bad "цикл с преобразованием покраснел — страж шире правила"

# --- цикл кладёт ДРУГУЮ переменную ----------------------------------------
D=$(mk other "module a" "fn f() -> () {" "    for n in src() { out.push(prev) }" "}")
run "$D" && ok "push чужой переменной не считается перекладыванием" \
    || bad "push чужого имени покраснел"

# --- в теле есть ещё что-то -----------------------------------------------
D=$(mk more "module a" "fn f() -> () {" "    for n in src() {" "        seen += 1" \
    "        out.push(n)" "    }" "}")
run "$D" && ok "тело с работой рядом не считается перекладыванием" \
    || bad "цикл с работой покраснел"

# --- чистое дерево ---------------------------------------------------------
D=$(mk clean "module a" "fn f() -> () {" "    out.append(src())" "}")
run "$D" && ok "append проходит" || bad "чистое дерево покраснело"

# --- потерянная мишень -----------------------------------------------------
mkdir -p "$T/empty"
run "$T/empty" && bad "пустая директория прошла — страж не заметил потери мишени" \
    || ok "пустая директория красная (мишень потеряна)"

[ "$fails" -eq 0 ] && echo "test-check-novac-no-copy-loop: ok" || exit 1
