#!/bin/sh
# Самотест check-novac-plan-liveline.py.
#
# Доказывает мутацией, что страж краснеет там, где обязан. Отдельно проверяется
# ловушка, на которую он сам попался в первой редакции: дата из СОСЕДНЕГО
# раздела не должна зеленить устаревшую живую строку. Страж, который молчит, —
# просто отсутствует; страж, который говорит «свежо» о протухшем, — хуже, чем
# отсутствует.
export LC_ALL=C

GD="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$GD/../.." && pwd)"
G="$GD/check-novac-plan-liveline.py"
T="${TMPDIR:-/tmp}/novac-liveline-selftest.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0

fails=0
ok()  { echo "  ok: $1"; }
bad() { echo "  FAIL: $1" >&2; fails=$((fails+1)); }

mkplan() {  # $1 — каталог дерева, $2 — содержимое плана
    mkdir -p "$1/docs/plans"
    printf '%s\n' "$2" > "$1/docs/plans/274-novac-self-hosted-compiler.md"
}

# ── 1. живое дерево — зелёный со строкой ok: ──────────────────────────────
if python "$G" "$ROOT" > "$T/out" 2> "$T/err"; then
    if grep -q "^check-novac-plan-liveline ok:" "$T/out"; then
        ok "живое дерево — зелёный со строкой ok:"
    else
        bad "зелёный без строки ok: [$(head -n 1 "$T/out")]"
    fi
else
    bad "живое дерево красное: [$(head -n 1 "$T/err")]"
fi

# ── 2. отставшая живая строка — красный ──────────────────────────────────
mkplan "$T/stale" "**СДЕЛАНО (живая строка; обновляется тем же слиянием, что и код — на 2026-01-01):** нечто"
if python "$G" "$T/stale" 2026-06-01 > "$T/o2" 2> "$T/e2"; then
    bad "отставшая на месяцы строка зелёная: [$(head -n 1 "$T/o2")]"
else
    grep -q "отстала от кода" "$T/e2" \
        && ok "отставшая строка — красный, с числом дней" \
        || bad "красный, но не про отставание: [$(head -n 1 "$T/e2")]"
fi

# ── 3. ЛОВУШКА первой редакции: свежая дата в соседнем разделе ───────────
mkplan "$T/trap" "**Состояние на 2026-06-01** — свежая дата, но НЕ у живой строки.

**СДЕЛАНО (живая строка; обновляется тем же слиянием, что и код — на 2026-01-01):** нечто"
if python "$G" "$T/trap" 2026-06-01 > "$T/o3" 2> "$T/e3"; then
    bad "чужая свежая дата зазеленила протухшую живую строку: [$(head -n 1 "$T/o3")]"
else
    ok "дата соседнего раздела не спасает протухшую живую строку"
fi

# ── 4. в пределах отставания — зелёный (правило не нулевое) ──────────────
mkplan "$T/fresh" "**СДЕЛАНО (живая строка; обновляется тем же слиянием, что и код — на 2026-06-01):** нечто"
if python "$G" "$T/fresh" 2026-06-02 > "$T/o4" 2>&1; then
    ok "отставание в пределах предела — зелёный"
else
    bad "день отставания сделан красным: [$(head -n 1 "$T/o4")]"
fi

# ── 5. живая строка БЕЗ даты — красный ───────────────────────────────────
mkplan "$T/nodate" "**СДЕЛАНО (живая строка; обновляется тем же слиянием, что и код):** нечто"
if python "$G" "$T/nodate" 2026-06-01 > "$T/o5" 2> "$T/e5"; then
    bad "живая строка без даты зелёная: [$(head -n 1 "$T/o5")]"
else
    grep -q "нет маркера даты" "$T/e5" \
        && ok "живая строка без даты — красный" \
        || bad "красный, но не про отсутствие даты: [$(head -n 1 "$T/e5")]"
fi

# ── 6. живых строк нет вовсе — красный (правило исчезло) ─────────────────
mkplan "$T/none" "просто текст плана без живых строк"
if python "$G" "$T/none" 2026-06-01 > "$T/o6" 2> "$T/e6"; then
    bad "план без живых строк зелёный: [$(head -n 1 "$T/o6")]"
else
    ok "исчезновение живых строк — красный"
fi

# ── 7. нет плана вовсе — честное «судить нечего» ─────────────────────────
mkdir -p "$T/bare"
if python "$G" "$T/bare" 2026-06-01 > "$T/o7" 2>&1; then
    grep -q "судить нечего" "$T/o7" \
        && ok "нет плана — судить нечего" \
        || bad "зелёный без честной формулировки: [$(head -n 1 "$T/o7")]"
else
    bad "отсутствие плана сделано красным: [$(head -n 1 "$T/o7")]"
fi

# ── 8. ЖИВАЯ СТРОКА С ЗАГЛАВНОЙ БУКВЫ ВИДНА ───────────────────
# До 2026-09-08 страж искал СТРОГО строчное «живая строка», и абзац, начатый
# с заглавной, для него НЕ СУЩЕСТВОВАЛ. В плане 274 такая строка стояла ШАПКОЙ —
# читатель видел её ПЕРВОЙ, а судилась другая, закопанная. Нашло окно 274.
mkplan "$T/upper" "**Живая строка — на 2026-01-01 (окно 274).** нечто"
if python "$G" "$T/upper" 2026-06-01 > "$T/o8" 2> "$T/e8"; then
    bad "строка с заглавной не замечена — зелёный на протухшем: [$(head -n 1 "$T/o8")]"
else
    grep -q "151" "$T/e8" \
        && ok "живая строка с заглавной буквы судится наравне со строчной" \
        || bad "красный, но не про отставание: [$(head -n 1 "$T/e8")]"
fi

# ── 9. ХРАПОВИК НЕДАТИРОВАННЫХ КРАСНЕЕТ НА РОСТ ─────────────
# Живая строка без СВОЕГО маркера даты не судится ничем: даты
# собираются СКОПОМ, и ОДНА датированная «прикрывает» остальные.
# Здесь две строки: свежая датированная и недатированная — без храповика
# это было бы ЗЕЛЁНО, и вторая строка врала бы без единого стража.
mkdir -p "$T/undated/docs/plans"
printf '%s\n%s\n' \
  "**СДЕЛАНО (живая строка; на 2026-06-01):** свежая" \
  "**Живая строка шапки без даты.** нечто" \
  > "$T/undated/docs/plans/274-novac-self-hosted-compiler.md"
if python "$G" "$T/undated" 2026-06-01 > "$T/o9" 2> "$T/e9"; then
    bad "недатированная живая строка прошла молчком: [$(head -n 1 "$T/o9")]"
else
    grep -q "без маркера даты" "$T/e9" \
        && ok "храповик ловит недатированную строку рядом со свежей" \
        || bad "красный, но не про недатированную: [$(head -n 1 "$T/e9")]"
fi

if [ "$fails" -ne 0 ]; then
    echo "итог: FAIL $fails" >&2
    exit 1
fi
echo "итог: PASS"
exit 0
