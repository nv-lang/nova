#!/bin/sh
# Самотест check-plan-wave-boundaries (П16: страж без доказательства красноты
# запрещён). Обе стороны каждого свойства — на подложном дереве планов.
#
# Отдельно доказывается ГЛАВНОЕ свойство: старые волны НЕ судятся. Страж,
# краснеющий на истории, будет отключён первым же окном, и правило исчезнет
# вместе с ним — поэтому «не тронул старое» здесь такой же обязательный
# случай, как «поймал новое».
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
G="$GD/check-plan-wave-boundaries.py"
T="${TMPDIR:-/tmp}/nova-wave-boundaries-selftest.$$"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok   $1"; }
bad() { echo "  FAIL $1" >&2; fails=$((fails+1)); }

P="$T/tree/docs/plans"
mk() { rm -rf "$T/tree"; mkdir -p "$P"; }
run() { python "$G" "$T/tree" 2026-08-29 >"$T/out" 2>"$T/err"; echo $?; }
said() { grep -q "$1" "$T/out" "$T/err" 2>/dev/null; }

# ── 1. новая волна с критериями и обоими разделами — зелено ─────────────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Волна 1 (2026-08-30)

**Критерии.** (а) страж зелёный.

**Не делаем (границы).** Второй язык не трогаем.

**Открытые вопросы.** Нет.
EOF
[ "$(run)" = "0" ] && ok "новая волна с границами — зелено" \
    || bad "полная волна не должна краснеть"

# ── 2. новая волна БЕЗ «Не делаем» — красно, и сказано чего нет ─────────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Волна 1 (2026-08-30)

**Критерии.** (а) страж зелёный.

**Открытые вопросы.** Нет.
EOF
[ "$(run)" = "1" ] && said "900-x.md" \
    && ok "нет границ — красно, и файл назван" \
    || bad "волна без границ обязана краснеть с именем файла"

# ── 3. новая волна БЕЗ «Открытые вопросы» — красно ──────────────────────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Волна 1 (2026-08-30)

**Критерии.** (а) страж зелёный.

**Не делаем (границы).** Ничего.
EOF
[ "$(run)" = "1" ] && ok "нет открытых вопросов — красно" \
    || bad "волна без открытых вопросов обязана краснеть"

# ── 4. СТАРАЯ волна без обоих — ЗЕЛЕНО (историю не судим) ──────────────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Волна 1 (2026-07-01)

**Критерии.** (а) что-то старое.
EOF
[ "$(run)" = "0" ] && ok "старая волна не судится — зелено (историю не переписываем)" \
    || bad "страж не имеет права краснеть на волнах старше отсечки"

# ── 5. волна БЕЗ критериев не судится вовсе ────────────────────────────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Заметка (2026-08-30)

Просто текст без критериев приёмки.
EOF
[ "$(run)" = "0" ] && ok "раздел без критериев не судится" \
    || bad "судить надо волны с критериями, а не всякий текст"

# ── 6. границы объявлены ОДИН раз на весь план — волна их наследует ────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

**Не делаем (границы).** Объявлено на весь план.

**Открытые вопросы.** Тоже на весь план.

## Волна 1 (2026-08-30)

**Критерии.** (а) страж зелёный.

## Волна 2 (2026-08-31)

**Критерии.** (б) и второй тоже.
EOF
[ "$(run)" = "0" ] && said "2" \
    && ok "план-уровневые границы наследуются обеими волнами" \
    || bad "объявленные один раз границы обязаны покрывать волны плана"

# ── 7. дата ровно в день отсечки — судится (граница включающая) ────────────
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Волна 1 (2026-08-29)

**Критерии.** (а) ровно в день отсечки.
EOF
[ "$(run)" = "1" ] && ok "дата РОВНО в отсечку судится, а не проскакивает" \
    || bad "граница отсечки обязана быть включающей"

# ── 8. планов нет вовсе — зелено, судить нечего ────────────────────────────
mk
[ "$(run)" = "0" ] && ok "планов нет — зелено, судить нечего" \
    || bad "пустая папка планов краснеть не должна"

# ── 9. самая ПОЗДНЯЯ дата решает: старый заголовок, свежая правка внутри ───
mk
cat > "$P/900-x.md" <<'EOF'
# План 900

## Волна 1 (2026-07-01)

**Критерии.** (а) старое.

Дополнено 2026-08-30 новым пунктом приёмки.
EOF
[ "$(run)" = "1" ] && ok "свежая правка внутри старой волны возвращает её под суд" \
    || bad "решать обязана САМАЯ ПОЗДНЯЯ дата раздела, иначе правило обходится датой заголовка"

echo "самотест check-plan-wave-boundaries: PASS $((9 - fails)) FAIL $fails"
[ "$fails" -eq 0 ] || exit 1
