#!/bin/sh
# Самотест check-novac-edge-payload.py (П16: страж обязан ДОКАЗАТЬ, что ловит).
#
# ПОДЛОЖКА. У стража один шов — $2 (путь к файлу архитектуры), поэтому
# настоящее дерево нужно ровно один раз (последний случай): каждый случай —
# свой крошечный markdown во временном каталоге. Дёшево, без оракула, красных
# случаев больше, чем зелёных.
#
# ЧТО ДОКАЗЫВАЕТ: заполненная колонка — зелёная; пустая ячейка — красная И с
# номером строки; прочерк «—» и заглушка TBD — красные; строка, у которой
# колонки нет вовсе, — красная; переименованный/перенумерованный раздел,
# переназванная колонка и таблица без строк — КРАСНЫЕ, а не зелёные (класс
# №519); строки соседнего раздела и соседней таблицы ребром не считаются;
# пустая ячейка не прячется ни за соседкой справа, ни за лишней колонкой, ни за
# неразрывным пробелом; ложняки (черта внутри ячейки, тире внутри прозы,
# отсутствие хвостовой черты, CRLF, выравнивание двоеточиями, отступ, пример
# «так нельзя» в фенсед-блоке) НЕ краснеют.
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$GD/../.." && pwd)"
G="$GD/check-novac-edge-payload.py"
T="${TMPDIR:-/tmp}/novac-edge-payload-selftest.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok: $1"; }
bad() { echo "  FAIL: $1" >&2; fails=$((fails+1)); }
run() { python "$G" "$ROOT" "$1" > "$T/out" 2> "$T/err"; }

# --- конструктор подложки --------------------------------------------------
# doc_open: всё до строк таблицы рёбер §3 (включая соседний раздел §2 с его
# собственной таблицей — она в юрисдикцию не входит).
doc_open() {
    { echo '# Карта novac (подложка самотеста)'
      echo ''
      echo '## 2. Карта модулей'
      echo ''
      echo '| модуль | что делает |'
      echo '|---|---|'
      echo '| `lex` | режет текст |'
      echo ''
      echo '## 3. Рёбра — с колонкой «что течёт»'
      echo ''
      echo 'Проза раздела: ребро вне таблицы — красный.'
      echo ''
      echo '| из | в | что течёт |'
      echo '|---|---|---|'
    } > "$1"
}
# doc_close: хвост после таблицы рёбер — вторая таблица ВНУТРИ §3 без колонки
# «что течёт» и соседний раздел §4, где такая колонка есть, но пустая. Ни то,
# ни другое ребром не считается.
doc_close() {
    { echo ''
      echo 'Ещё проза, таблица рёбер кончилась.'
      echo ''
      echo '| понятие | дом |'
      echo '|---|---|'
      echo '| `Ctx` | `sem` |'
      echo ''
      echo '## 4. Карта информации'
      echo ''
      echo '| из | в | что течёт |'
      echo '|---|---|---|'
      echo '| `сосед` | `раздел` |  |'
    } >> "$1"
}

# --- 1. все ячейки заполнены — зелёный ------------------------------------
doc_open "$T/green.md"
{ echo '| `lex` | `source` | читает `SourceText`; отдаёт `Token[]` |'
  echo '| `parse` | `lex` | `Token[]` |'
  echo '| `mono` | `sem` | читает инстанцирования |'
} >> "$T/green.md"
doc_close "$T/green.md"
if run "$T/green.md"; then
    grep -q "рёбер в таблице §3: 3" "$T/out" \
        && ok "заполненная колонка — зелёный, итог числом: $(cat "$T/out")" \
        || bad "зелёный, но итог не тот [$(cat "$T/out")]"
else
    bad "заполненная колонка покраснела: $(cat "$T/err")"
fi

# --- 1а. то же дерево доказывает, что чужие строки не считаются -----------
# В §4 лежит строка с ПУСТОЙ колонкой, в §3 после таблицы — таблица без такой
# колонки вовсе. Случай 1 зелёный ⇒ обе мимо. Проверяем ещё и число: 3, а не 4.
if grep -q "рёбер в таблице §3: 3" "$T/out"; then
    ok "строка соседнего раздела и соседней таблицы ребром не считается (3, не 4)"
else
    bad "чужие строки подмешались в счёт рёбер [$(cat "$T/out")]"
fi

# --- 2. пустая ячейка — красный, с номером строки -------------------------
doc_open "$T/empty.md"
{ echo '| `lex` | `source` | `Token[]` |'
  echo '| `pusto` | `source` |  |'
  echo '| `mono` | `sem` | читает инстанцирования |'
} >> "$T/empty.md"
doc_close "$T/empty.md"
LN=$(grep -n 'pusto' "$T/empty.md" | head -1 | cut -d: -f1)
if run "$T/empty.md"; then
    bad "ребро с ПУСТОЙ колонкой «что течёт» прошло — страж не ловит свой главный случай"
else
    if grep -q "pusto" "$T/err" && grep -q ":$LN:" "$T/err"; then
        ok "пустая колонка поймана, ребро и строка названы: $(grep pusto "$T/err")"
    else
        bad "красный, но без имени ребра или без номера строки $LN [$(cat "$T/err")]"
    fi
fi

# --- 3. прочерк «—» — красный ---------------------------------------------
doc_open "$T/dash.md"
{ echo '| `lex` | `source` | `Token[]` |'
  echo '| `procherk` | `sem` | — |'
} >> "$T/dash.md"
LN=$(grep -n 'procherk' "$T/dash.md" | head -1 | cut -d: -f1)
if run "$T/dash.md"; then
    bad "прочерк «—» в колонке «что течёт» прошёл как контракт"
else
    grep -q "procherk" "$T/err" && grep -q ":$LN:" "$T/err" \
        && ok "прочерк — красный, ребро и строка названы" \
        || bad "красный, но ребро/строка не названы [$(cat "$T/err")]"
fi

# --- 4. заглушка TBD — красный --------------------------------------------
doc_open "$T/tbd.md"
{ echo '| `lex` | `source` | `Token[]` |'
  echo '| `zaglushka` | `sem` | TBD |'
} >> "$T/tbd.md"
if run "$T/tbd.md"; then
    bad "заглушка TBD прошла как объявленный контракт"
else
    grep -q "zaglushka" "$T/err" && ok "TBD — красный, ребро названо" \
        || bad "красный, но zaglushka не назван [$(cat "$T/err")]"
fi

# --- 5. колонки в строке нет вовсе — красный ------------------------------
doc_open "$T/short.md"
{ echo '| `lex` | `source` | `Token[]` |'
  echo '| `korotkaya` | `sem` |'
} >> "$T/short.md"
if run "$T/short.md"; then
    bad "строка без третьей колонки прошла — «что течёт» можно просто не писать"
else
    grep -q "korotkaya" "$T/err" && ok "строка без колонки — красный" \
        || bad "красный, но korotkaya не названа [$(cat "$T/err")]"
fi

# --- 6. раздел перенумерован — КРАСНЫЙ, не зелёный ------------------------
{ echo '# Карта novac'
  echo ''
  echo '## 4. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт |'
  echo '|---|---|---|'
  echo '| `lex` | `source` | `Token[]` |'
} > "$T/moved.md"
if run "$T/moved.md"; then
    bad "таблица уехала из §3, а страж ЗЕЛЁНЫЙ — вечнозелёный механизм (класс №519)"
else
    grep -q "не нашлось таблицы рёбер" "$T/err" \
        && ok "перенумерованный раздел — красный, названо почему" \
        || bad "красный, но без объяснения [$(cat "$T/err")]"
fi

# --- 7. колонку переназвали — КРАСНЫЙ --------------------------------------
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра'
  echo ''
  echo '| из | в | контракт |'
  echo '|---|---|---|'
  echo '| `lex` | `source` | `Token[]` |'
} > "$T/renamed.md"
if run "$T/renamed.md"; then
    bad "колонку переназвали, а страж ЗЕЛЁНЫЙ — судить перестал молча (класс №519)"
else
    grep -q "не нашлось таблицы рёбер" "$T/err" \
        && ok "переназванная колонка — красный" \
        || bad "красный, но без объяснения [$(cat "$T/err")]"
fi

# --- 8. таблица есть, строк нет — КРАСНЫЙ ---------------------------------
doc_open "$T/norows.md"
doc_close "$T/norows.md"
if run "$T/norows.md"; then
    bad "таблица рёбер без единой строки дала ЗЕЛЁНЫЙ (класс №519)"
else
    grep -q "строк-рёбер под шапкой ноль" "$T/err" \
        && ok "пустая таблица — красный" \
        || bad "красный, но без объяснения [$(cat "$T/err")]"
fi

# --- 9. файла нет — красный (мишень пропала, а не «судить нечего») --------
if run "$T/net-takogo-fajla.md"; then
    bad "отсутствующий файл архитектуры дал зелёный — страж потерял мишень молча"
else
    grep -q "карта рёбер пропала" "$T/err" && ok "нет файла — красный" \
        || bad "красный, но без объяснения [$(cat "$T/err")]"
fi

# --- 10. ложняки: страж НЕ обязан краснеть --------------------------------
# Черта внутри ячейки, тире ВНУТРИ прозы, строка без хвостовой черты, отступ,
# выравнивание двоеточиями. Всё это законный markdown.
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт |'
  echo '|:---|:---:|---:|'
  echo '| `pipe` | `cell` | таблица `a | b` внутри ячейки |'
  echo '| `dash` | `inside` | листья — `Token` ДАННЫМИ (тире внутри прозы) |'
  echo '| `notail` | `pipe` | строка без хвостовой черты'
  echo '  | `indent` | `pipe` | строка с отступом |'
} > "$T/tricky.md"
if run "$T/tricky.md"; then
    grep -q "рёбер в таблице §3: 4" "$T/out" \
        && ok "ложняки не краснеют: черта в ячейке, тире в прозе, нет хвоста, отступ, двоеточия" \
        || bad "зелёный, но посчитано не 4 ребра [$(cat "$T/out")]"
else
    bad "ЛОЖНЯК: законный markdown покраснел: $(cat "$T/err")"
fi

# --- 11. CRLF — не повод краснеть -----------------------------------------
sed 's/$/\r/' "$T/green.md" > "$T/crlf.md"
if run "$T/crlf.md"; then
    grep -q "рёбер в таблице §3: 3" "$T/out" && ok "CRLF-файл судится так же" \
        || bad "CRLF: зелёный, но счёт поехал [$(cat "$T/out")]"
else
    bad "ЛОЖНЯК: CRLF покраснел: $(cat "$T/err")"
fi

# --- 12. колонка «что течёт» НЕ последняя — пустота не прячется за соседкой -
# Если справа появится колонка примечаний, пустая ячейка «что течёт» не должна
# «дочитаться» текстом соседки: это была бы ложная ЗЕЛЕНЬ, а она хуже ложной
# красноты.
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт | примечание |'
  echo '|---|---|---|---|'
  echo '| `lex` | `source` | `Token[]` | Э1 |'
  echo '| `spryatalos` | `sem` |  | зато примечание длинное |'
} > "$T/notlast.md"
if run "$T/notlast.md"; then
    bad "пустая колонка спряталась за соседкой справа — ложная зелень"
else
    grep -q "spryatalos" "$T/err" \
        && ok "колонка не последняя: пустая ячейка всё равно поймана" \
        || bad "красный, но spryatalos не назван [$(cat "$T/err")]"
fi
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт | примечание |'
  echo '|---|---|---|---|'
  echo '| `lex` | `source` | `Token[]` | Э1 |'
  echo '| `parse` | `lex` | `Token[]` | — |'
} > "$T/notlast-ok.md"
if run "$T/notlast-ok.md"; then
    grep -q "рёбер в таблице §3: 2" "$T/out" \
        && ok "прочерк в СОСЕДНЕЙ колонке (примечание) не краснеет — судится только «что течёт»" \
        || bad "зелёный, но счёт поехал [$(cat "$T/out")]"
else
    bad "ЛОЖНЯК: прочерк в колонке примечаний покраснел: $(cat "$T/err")"
fi

# --- 13. лишняя колонка/черта/NBSP не выдают пустую ячейку за контракт ------
# Шапка в три колонки, а в строке четыре: рендерер лишнюю ячейку отбрасывает,
# для читателя «что течёт» ПУСТА. Наивная склейка «до конца строки» оставляла
# в ячейке один разделитель `|` — непусто, ложная ЗЕЛЕНЬ. То же с ячейкой из
# одних черт и с ячейкой из неразрывного пробела (U+00A0: [:space:] под
# LC_ALL=C его не снимает).
NBSP=$(printf '\302\240')
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт |'
  echo '|---|---|---|'
  echo '| `lex` | `source` | `Token[]` |'
  echo '| `lishnyaya` | `sem` |  |  |'
} > "$T/extracol.md"
if run "$T/extracol.md"; then
    bad "пустая «что течёт» с лишней колонкой справа прошла зелёной — дыру спрятал разделитель"
else
    grep -q "lishnyaya" "$T/err" && ok "лишняя колонка не прячет пустую «что течёт»" \
        || bad "красный, но lishnyaya не названа [$(cat "$T/err")]"
fi
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт |'
  echo '|---|---|---|'
  echo '| `lex` | `source` | `Token[]` |'
  echo '| `cherty` | `sem` | | |'
  echo "| \`nerazryvnyj\` | \`sem\` | $NBSP |"
  echo '| `kommentarij` | `sem` | <!-- заполню позже --> |'
} > "$T/blank-ish.md"
if run "$T/blank-ish.md"; then
    bad "ячейка из одних черт / из NBSP / из HTML-комментария прошла как контракт"
else
    grep -q "cherty" "$T/err" && grep -q "nerazryvnyj" "$T/err" \
        && grep -q "kommentarij" "$T/err" \
        && ok "одни черты, одиночный U+00A0 и HTML-комментарий — пусто: все три красные" \
        || bad "красный, но названы не все три строки [$(cat "$T/err")]"
fi
# обратная сторона: комментарий РЯДОМ с настоящим контрактом не краснеет
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт |'
  echo '|---|---|---|'
  echo '| `lex` | `source` | <!-- к Э2 --> `Token[]` <!-- уточнить --> |'
} > "$T/comment-ok.md"
if run "$T/comment-ok.md"; then
    grep -q "рёбер в таблице §3: 1" "$T/out" \
        && ok "комментарий рядом с контрактом не съедает контракт" \
        || bad "зелёный, но счёт поехал [$(cat "$T/out")]"
else
    bad "ЛОЖНЯК: контракт с HTML-комментариями по бокам покраснел: $(cat "$T/err")"
fi

# --- 14. фенсед-пример «так нельзя» ребром не считается --------------------
# §3 — ровно то место, где уместно показать дырявую строку примером. Судить
# иллюстрацию как настоящее ребро — ложная краснота (и счёт рёбер поехал бы).
{ echo '# Карта novac'
  echo ''
  echo '## 3. Рёбра — с колонкой «что течёт»'
  echo ''
  echo '| из | в | что течёт |'
  echo '|---|---|---|'
  echo '| `lex` | `source` | `Token[]` |'
  echo '| `parse` | `lex` | `Token[]` |'
  echo ''
  echo 'Так нельзя (пример, а не ребро):'
  echo ''
  echo '```markdown'
  echo '| из | в | что течёт |'
  echo '|---|---|---|'
  echo '| `primer` | `sem` |  |'
  echo '```'
  echo ''
  echo 'И вот так тоже нельзя:'
  echo ''
  echo '~~~'
  echo '| `vtoroj-primer` | `sem` | — |'
  echo '~~~'
} > "$T/fenced.md"
if run "$T/fenced.md"; then
    grep -q "рёбер в таблице §3: 2" "$T/out" \
        && ok "фенсед-пример не ребро: посчитано 2, иллюстрации мимо" \
        || bad "зелёный, но счёт поехал — иллюстрация попала в рёбра [$(cat "$T/out")]"
else
    bad "ЛОЖНЯК: пример «так нельзя» в фенсед-блоке покраснел: $(cat "$T/err")"
fi

# --- 15. настоящее дерево --------------------------------------------------
if python "$G" "$ROOT" > "$T/real.out" 2> "$T/real.err"; then
    ok "настоящая карта — зелёная: $(cat "$T/real.out")"
else
    bad "настоящая карта КРАСНАЯ (это находка по факту): $(head -4 "$T/real.err")"
fi

echo "итог: FAIL $fails"
if [ "$fails" -eq 0 ]; then
    echo "test-check-novac-edge-payload ok: все случаи, включая пустую ячейку с номером строки, прочерк, TBD и потерянную таблицу"
    exit 0
fi
exit 1
