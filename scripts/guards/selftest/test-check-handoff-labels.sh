#!/usr/bin/env bash
# Самотест check-handoff-labels.py.
#
# Случаи по ОСЯМ: (схема метки: полная дата / прежняя) × (есть ли метка в базе),
# плюс края — часть суток, отсутствие записок и устаревшая строка базы.

set -u
export LC_ALL=C

G="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/check-handoff-labels.py"
TMP="${TMPDIR:-/tmp}/selftest_hl_$$"
FAILED=0
CASES=0
ok()  { CASES=$((CASES+1)); echo "  ok: $1"; }
bad() { CASES=$((CASES+1)); echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

setup() {   # $1 — метка(и) в записке интегратора, $2 — содержимое базы
    rm -rf "$TMP"
    mkdir -p "$TMP/docs/dev/prompts" "$TMP/scripts/guards"
    printf '%s\n' "$1" > "$TMP/docs/dev/prompts/integrator-handoff.md"
    printf '%s\n' "${2:-}" > "$TMP/scripts/guards/handoff-labels.baseline"
}

run() { python "$G" "$TMP" > "$TMP/.out" 2> "$TMP/.err"; }

# 1. Полная дата — норма.
setup '## 0-2026-09-17. Состояние на 2026-09-17' ''
run
if [ $? -eq 0 ]; then ok "полная дата проходит"; else bad "1: ложняк на полной дате: $(cat "$TMP/.err")"; fi

# 2. Полная дата С ЧАСТЬЮ СУТОК — тоже норма: второй раздел за день законен.
setup '## 0-2026-09-17-вечер. Состояние на 2026-09-17' ''
run
if [ $? -eq 0 ]; then ok "часть суток после даты проходит"; else bad "2: ложняк на части суток: $(cat "$TMP/.err")"; fi

# 3. Четыре цифры — ОТКАЗ. Это случай 2026-09-17: та же форма значила в двух
#    записках разное (`0-1609` = 16 сентября, `0-0917` = 17 сентября).
setup '## 0-1809. Состояние' ''
run
if [ $? -eq 1 ] && grep -q "0-1809" "$TMP/.err"; then
    ok "четыре цифры ловятся и метка НАЗЫВАЕТСЯ"
else
    bad "3: не поймал четырёхзначную метку: $(cat "$TMP/.err")"
fi

# 4. Латинское слово без даты — тот же отказ (`0-bis` = «дважды»).
setup '## 0-quater. Состояние' ''
run
if [ $? -eq 1 ]; then ok "метка без даты ловится"; else bad "4: не поймал метку без даты"; fi

# 5. Та же прежняя метка, внесённая в базу, — норма: история не переименовывается.
setup '## 0-1809. Состояние' '0-1809  # прежняя схема, запись от такого-то дня'
run
if [ $? -eq 0 ]; then ok "прежняя метка из базы не краснит"; else bad "5: база не сработала: $(cat "$TMP/.err")"; fi

# 6. КРАЙ: записок нет вовсе — вакуумно-зелено, а не отказ. Страж ездит и в
#    пакетные репозитории, где ролевых записок не бывает.
rm -rf "$TMP"; mkdir -p "$TMP/scripts/guards"
run
if [ $? -eq 0 ] && grep -q "судить нечего" "$TMP/.out"; then
    ok "нет записок — вакуумно-зелено"
else
    bad "6: при отсутствии записок страж не промолчал: $(cat "$TMP/.out") $(cat "$TMP/.err")"
fi

# 7. Строка базы, которой в записках больше нет, — НАЗВАНА, но не краснит:
#    метки живут в двух ветках, и пропажа в одной не есть ошибка.
setup '## 0-2026-09-17. Состояние' '0-1609  # лежит в ветке окна Карины'
run
if [ $? -eq 0 ] && grep -q "0-1609" "$TMP/.out"; then
    ok "неиспользуемая строка базы названа, но не краснит"
else
    bad "7: не сообщил о неиспользуемой строке базы: $(cat "$TMP/.out")"
fi

# --- ЗНАМЕНАТЕЛЬ: страж идёт по ЗАПИСКАМ, а не по меткам (правка 2026-09-20) --
#
# Прежде перечислялись МЕТКИ, и записка без единой метки в проверку НЕ ВХОДИЛА:
# ноль нарушений при нуле осмотренного читался как «чисто». Клетки ниже ловят
# именно это, и парами: безметочная краснеет — она же в базе зеленеет.

# 8. Записка БЕЗ единой метки — КРАСНЫЙ, и файл НАЗВАН.
setup '# Записка без единого раздела с меткой'
run
if [ $? -eq 1 ] && grep -q "integrator-handoff.md" "$TMP/.err"; then
    ok "записка без метки — красный, и файл назван"
else
    bad "8: безметочная записка не покраснела: $(cat "$TMP/.out") $(cat "$TMP/.err")"
fi

# 9. Она же, но названная в базе строкой `nolabel:` — ЗЕЛЁНЫЙ. Без этой половины
#    клетка 8 доказывала бы лишь умение краснеть всегда.
setup '# Записка без единого раздела с меткой' 'nolabel:integrator-handoff.md'
run
if [ $? -eq 0 ]; then
    ok "безметочная записка из базы не краснит (храповик, а не запрет)"
else
    bad "9: база nolabel не сработала: $(cat "$TMP/.err")"
fi

# 10. ВОСЬМАЯ записка, которой нет ни в одном списке, — страж обязан её УВИДЕТЬ:
#     список снимается с дерева, а не зашит. Без этого новая записка не судилась
#     бы, пока кто-нибудь не вспомнит вписать её руками.
setup '## 0-2026-09-20. Состояние'
printf '%s\n' '# Восьмая записка, меток нет' > "$TMP/docs/dev/prompts/window-999-handoff.md"
run
if [ $? -eq 1 ] && grep -q "window-999-handoff.md" "$TMP/.err"; then
    ok "новая записка судится сразу, без внесения в список"
else
    bad "10: восьмая записка осталась невидимой: $(cat "$TMP/.out") $(cat "$TMP/.err")"
fi

# 11. Обратная сторона к 10: убрали восьмую — снова зелено, и в выводе стоит
#     ЧИСЛО ОСМОТРЕННЫХ. Знаменатель обязан быть виден, иначе пустая мишень
#     читается как чистая.
rm -f "$TMP/docs/dev/prompts/window-999-handoff.md"
run
if [ $? -eq 0 ] && grep -q "ОСМОТРЕНО ЗАПИСОК 1" "$TMP/.out"; then
    ok "убрали восьмую — зелено, и число осмотренных напечатано"
else
    bad "11: нет числа осмотренных записок в зелёном выводе: $(cat "$TMP/.out")"
fi

rm -rf "$TMP"
if [ "$FAILED" -eq 0 ]; then
    echo "селфтест check-handoff-labels: $CASES/$CASES ok"
    exit 0
fi
echo "селфтест check-handoff-labels: ЕСТЬ ПРОВАЛЫ" >&2
exit 1
