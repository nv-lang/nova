#!/usr/bin/env bash
# Самотест check-dead-anchors.py — клетки ПАРАМИ, и одна пара важнее прочих.
#
# Страж, считающий ЛЮБЫЕ ссылки, выглядит точно так же, как страж, считающий
# мёртвые: на растущем дереве оба краснеют. Поэтому здесь есть клетка «ссылка на
# СУЩЕСТВУЮЩИЙ якорь — зелено», без которой всё остальное ничего не доказывает.
set -u
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
G="$ROOT/scripts/guards/check-dead-anchors.py"
FAILED=0
OKN=0
ok()  { OKN=$((OKN + 1)); echo "  ok   $1"; }
bad() { echo "  ПРОВАЛ $1" >&2; FAILED=1; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
B="$TMP/base"

setup() {   # $1 — содержимое единственного .md; $2 — база
    rm -rf "$TMP/tree"; mkdir -p "$TMP/tree/docs"
    printf '%s\n' "$1" > "$TMP/tree/docs/a.md"
    printf '%s\n' "${2:-dead=0}" > "$B"
}
run() { python "$G" "$TMP/tree" "$B" > "$TMP/.out" 2> "$TMP/.err"; }

# --- пара 1: мёртвая ссылка ловится, живая — нет ----------------------------
setup 'смотри (#d999) здесь' 'dead=0'
run
if [ $? -ne 0 ] && grep -q "d999" "$TMP/.err"; then
    ok "новый мёртвый якорь — красный, адрес назван"
else
    bad "1: мёртвая ссылка не поймана: $(cat "$TMP/.out") $(cat "$TMP/.err")"
fi

setup '## Заголовок {#d999}

смотри (#d999) здесь' 'dead=0'
run
if [ $? -eq 0 ]; then
    ok "ссылка на СУЩЕСТВУЮЩИЙ якорь — зелёный (считаются мёртвые, а не все)"
else
    bad "2: живая ссылка сочтена мёртвой: $(cat "$TMP/.err")"
fi

# --- пара 2: база держит прошлое, но не рост --------------------------------
setup 'старая (#d100) ссылка' 'dead=1
d100'
run
if [ $? -eq 0 ]; then
    ok "мёртвый якорь ИЗ БАЗЫ не краснит (засев, а не ноль)"
else
    bad "3: засеянный адрес покрасил стража: $(cat "$TMP/.err")"
fi

setup 'старая (#d100) и ещё раз (#d100)' 'dead=1
d100'
run
if [ $? -ne 0 ] && grep -q "БОЛЬШЕ" "$TMP/.err"; then
    ok "ещё одна ссылка на СТАРЫЙ мёртвый адрес — красный (счёт вырос)"
else
    bad "4: рост числа при тех же адресах не пойман: $(cat "$TMP/.err")"
fi

# --- пара 3: храповик вниз называется вслух ---------------------------------
setup 'ничего нет' 'dead=1
d100'
run
if [ $? -eq 0 ] && grep -q "опусти базу" "$TMP/.out"; then
    ok "долг снизился — сказано опустить базу той же правкой"
else
    bad "5: снижение долга не названо: $(cat "$TMP/.out")"
fi

# --- 6: ЯВНЫЙ target приоритетнее сгенерированного --------------------------
# Ловушка интегратора: у D481 заголовок несёт `(ex-D478, renumber …)`, и
# автоматический slug с номером не совпадает. Судится ЯВНЫЙ `{#dNNN}`.
setup '## D481. Char-литерал (ex-D478, renumber 2026-09-20) {#d481}

ссылка (#d481) обязана считаться живой' 'dead=0'
run
if [ $? -eq 0 ]; then
    ok "явный target у длинного заголовка — ссылка живая"
else
    bad "6: явный target не учтён: $(cat "$TMP/.err")"
fi

# --- 7: ЗНАМЕНАТЕЛЬ виден ---------------------------------------------------
setup 'смотри (#d100)' 'dead=1
d100'
run
if grep -q "осмотрено .md файлов" "$TMP/.out"; then
    ok "знаменатель напечатан (файлы, ссылки, targetы, мёртвые)"
else
    bad "7: знаменателя в выводе нет: $(cat "$TMP/.out")"
fi

# --- 8: НЕТ БАЗЫ — отказ, а не молчаливое зелено ----------------------------
setup 'смотри (#d100)' ''
rm -f "$B"
run
if [ $? -ne 0 ] && grep -q "нет базы" "$TMP/.err"; then
    ok "базы нет — громкий отказ, а не тихое зелено"
else
    bad "8: без базы страж не отказал: $(cat "$TMP/.out") $(cat "$TMP/.err")"
fi

echo "селфтест check-dead-anchors: $OKN/$OKN ok"
[ "$FAILED" -eq 0 ] || { echo "селфтест check-dead-anchors: ЕСТЬ ПРОВАЛЫ" >&2; exit 1; }
