#!/usr/bin/env bash
# Самотест: ОБРЫВ СТРАЖА В ПАРАЛЛЕЛЬНОМ БЛОКЕ `gate-novac` НАЗЫВАЕТСЯ ОБРЫВОМ,
# А НЕ ПРИЧИНОЙ СТРАЖА (Г16 и Г9, реестр 221.1 №1113).
#
# КЛАСС: остановка, надевшая одежду результата. До правки 2026-09-15 разбор
# блока брал `_rc=1` по умолчанию, когда файла кода возврата не было, — то есть
# ОБРЫВ («о предмете не узнали ничего») уезжал в сводку ЗАГОТОВЛЕННОЙ причиной
# стража. Измеренный носитель: ярус интегратора умер на шаге `novac-behaviour`,
# и доложить он должен был «дифф-гейт красный: расхождение поведения вне
# реестра» — вердикт о расхождении двух компиляторов, ни одного из которых не
# судили. По такому докладу идут чинить код, которого никто не мерил.
#
# ПОЧЕМУ САМОТЕСТ, А НЕ ТОЛЬКО ПРАВКА: различение живёт в трёх строках разбора,
# и оно ровно того рода, который снимают при первой же уборке «лишнего» — как
# сняли бы хвост идентичности вердикта (см. test-gate-verdict-identity.sh).
#
# ЧЕТЫРЕ СЛУЧАЯ, и каждый куплен ошибкой или контролирует соседний:
#   1. подоболочка умерла, файла .rc нет      -> сводка говорит ОБРЫВ;
#   2. и в этом случае причина стража НЕ звучит (Г9: механизм не называет
#      причину, которой не устанавливал);
#   3. страж вышел кодом убитого (137)        -> тоже ОБРЫВ, а не вердикт;
#   4. ОБРАТНАЯ ПРОБА: живой страж с кодом 1  -> причина стража печатается
#      КАК ПРЕЖДЕ. Без неё правка могла бы просто перестать называть причины
#      вообще, и тест был бы зелен на сломанном механизме.
#
# Компилятор и гейт НЕ запускаются: функция `par_run` извлекается из файла и
# гоняется с заглушками вместо стражей — приём и форма те же, что у
# test-gate-verdict-identity.sh (извлечённая функция рубежа).
#
# Запуск: bash scripts/guards/selftest/test-gate-novac-par-abort.sh
# Выход: 0 — различение цело, 1 — сломано.

set -uo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
GATE="$ROOT/scripts/gate-novac.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); echo "  ok   $1"; }
bad() { FAIL=$((FAIL+1)); echo "  FAIL $1" >&2; }
has()    { case "$2" in *"$1"*) ok "$3" ;; *) bad "$3 (не нашёл '$1')" ;; esac; }
has_no() { case "$2" in *"$1"*) bad "$3 (нашёл лишнее '$1')" ;; *) ok "$3" ;; esac; }

[ -f "$GATE" ] || { echo "нет $GATE" >&2; exit 1; }

# ── Извлекаем разбор блока вместе с его окружением ───────────────────────────
awk '/^par_run\(\) \{/,/^\}/' "$GATE" > "$TMP/par_run.sh"
[ -s "$TMP/par_run.sh" ] || { echo "не извлёк par_run из гейта" >&2; exit 1; }
awk '/^is_desync\(\) \{/,/^\}/' "$GATE" > "$TMP/is_desync.sh"
[ -s "$TMP/is_desync.sh" ] || { echo "не извлёк is_desync из гейта" >&2; exit 1; }

# ── Заглушки вместо стражей ──────────────────────────────────────────────────
# ОБРЫВ моделируется честно: заглушка убивает СВОЮ подоболочку, поэтому
# `echo $? > .rc` в ней не выполняется и файла кода возврата не остаётся —
# ровно то, что случается с убитым или снятым по памяти процессом.
cat > "$TMP/g_abort.sh" <<'EOF'
echo "начал работу и не дожил"
kill -9 $PPID
sleep 30
EOF
cat > "$TMP/g_killed.sh" <<'EOF'
echo "меня сняли"
exit 137
EOF
cat > "$TMP/g_red.sh" <<'EOF'
echo "нашёл расхождение"
exit 1
EOF

MSG_ABORT="дифф-гейт красный: расхождение поведения вне реестра"
MSG_RED="пачечный проход раннера разобран"

run_case() { # <файл-заглушки> <сообщение-стража> -> печатает сводку
    (
        set +e
        ROOT="$ROOT"
        NOVAC_JOBS=2
        PAR_DIR="$TMP/par.$$"
        PAR_N=0
        GATE_FAILS=""; GATE_FAIL_N=0; DESYNC_MSGS=""; DESYNC_N=0
        fail()   { echo "СВОДКА-FAIL: $1"; }
        desync() { echo "СВОДКА-DESYNC: $1"; }
        # shellcheck disable=SC1090
        . "$TMP/is_desync.sh"
        . "$TMP/par_run.sh"
        mkdir -p "$PAR_DIR"
        PAR_N=1
        printf '%s\n' "$1" > "$PAR_DIR/1.cmd"
        printf '%s\n' "$2" > "$PAR_DIR/1.msg"
        par_run
    ) 2>&1
}

echo "== 1-2. подоболочка умерла: файла .rc нет =="
OUT_ABORT="$(run_case "$TMP/g_abort.sh" "$MSG_ABORT")"
has    "ОБРЫВ"   "$OUT_ABORT" "сводка называет ОБРЫВ"
has_no "$MSG_ABORT" "$OUT_ABORT" "причина стража НЕ названа (Г9)"

echo "== 3. код убитого процесса (137) — тоже не вердикт =="
OUT_KILLED="$(run_case "$TMP/g_killed.sh" "$MSG_ABORT")"
has    "ОБРЫВ"   "$OUT_KILLED" "снятый по коду 137 назван обрывом"
has_no "$MSG_ABORT" "$OUT_KILLED" "причина стража НЕ названа и здесь"

echo "== 4. обратная проба: живой красный страж называет свою причину =="
OUT_RED="$(run_case "$TMP/g_red.sh" "$MSG_RED")"
has    "$MSG_RED" "$OUT_RED" "красный вердикт печатает причину стража КАК ПРЕЖДЕ"
has_no "ОБРЫВ"    "$OUT_RED" "живой красный обрывом не зовётся"

echo ""
echo "итог: $PASS ok, $FAIL FAIL"
[ "$FAIL" -eq 0 ] || exit 1
