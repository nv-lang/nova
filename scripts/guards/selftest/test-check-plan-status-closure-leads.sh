#!/usr/bin/env bash
# test-check-plan-status-closure-leads.sh — САМОТЕСТ стража
# `check-plan-status-closure-leads.py` (закрытие плана обязано стоять в ПЕРВОЙ
# строке абзаца статуса, потому что сводку генератор собирает по `grep -m1`).
#
# Проверяются оба обязательных свойства — ЛОВИТ нарушение и НЕ даёт ложняка, —
# и вдобавок три границы, на которых страж легко стал бы вредным:
#   * план БЕЗ слова закрытия (обычная работа в полёте) — не нарушение;
#   * закрытие В ПЕРВОЙ строке, а обоснование ниже — не нарушение (это как раз
#     та форма, к которой правило и ведёт);
#   * абзац статуса кончается пустой строкой: слово «ЗАКРЫТА», стоящее в теле
#     плана НИЖЕ абзаца, к статусу отношения не имеет и ловиться не должно.
# Без последней границы страж краснел бы на каждом плане, где в «Ходе» написано
# «фаза закрыта» — то есть почти на всех, и его сняли бы первым же окном.
#
# Запуск: bash scripts/guards/selftest/test-check-plan-status-closure-leads.sh
# Выход: 0 — страж исправен; 1 — сломан.
#
# Маркер: [M-plan-status-closure-must-lead-the-line] в
# docs/plans/backlog-followups.md. Замер заведения — реестр 221.1, план 283.1.

set -uo pipefail
export LC_ALL=C.UTF-8 2>/dev/null || true

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
GUARD="$REPO_ROOT/scripts/guards/check-plan-status-closure-leads.py"

[ -f "$GUARD" ] || { echo "САМОТЕСТ: нет стража $GUARD" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

fails=0
check() { # имя, ожидаемый_код, фактический_код
    if [ "$2" -eq "$3" ]; then
        echo "  ok: $1"
    else
        echo "  ПРОВАЛ: $1 — ожидался код $2, получен $3" >&2
        fails=$((fails + 1))
    fi
}

mk_plan() { # каталог, имя-файла ; тело с stdin
    mkdir -p "$1/docs/plans"
    cat > "$1/docs/plans/$2"
}

# --- 1. НАРУШЕНИЕ: закрытие спрятано ниже первой строки -------------------
c1="$tmp/c1"
mk_plan "$c1" "900-x.md" <<'EOF'
# План 900

**Статус:** ЗАПЛАНИРОВАН 2026-09-07 — решение владельца того же дня.
Исполняется после слияния соседней волны, потому что перенос обнуляет
вердикты приёмки.
**ВОЛНА ЗАКРЫТА 2026-09-07** — вердикты в «Ходе».

## Ход
EOF
python "$GUARD" "$c1" >/dev/null 2>&1
check "ловит закрытие, дописанное в конец абзаца" 1 $?

# --- 2. НОРМА: закрытие первым, обоснование следом ------------------------
c2="$tmp/c2"
mk_plan "$c2" "900-x.md" <<'EOF'
# План 900

**Статус:** ВОЛНА ЗАКРЫТА 2026-09-07 (слот 15:49–15:57) — вердикты в «Ходе».
Заведена тем же днём по решению владельца; исполнялась после слияния
соседней волны.

## Ход
EOF
python "$GUARD" "$c2" >/dev/null 2>&1
check "не ложнит, когда закрытие стоит первым" 0 $?

# --- 3. НОРМА: работа в полёте, слова закрытия нет вовсе ------------------
c3="$tmp/c3"
mk_plan "$c3" "900-x.md" <<'EOF'
# План 900

**Статус:** 🔨 В РАБОТЕ (заведён 2026-09-07). Ф.1 идёт, Ф.2 не начата;
приёмка машинная, критерии в разделе ниже.

## Ход
EOF
python "$GUARD" "$c3" >/dev/null 2>&1
check "не ложнит на плане без слова закрытия" 0 $?

# --- 4. ГРАНИЦА: «закрыта» ниже абзаца статуса — не статус ----------------
c4="$tmp/c4"
mk_plan "$c4" "900-x.md" <<'EOF'
# План 900

**Статус:** 🔨 В РАБОТЕ (заведён 2026-09-07). Идёт Ф.2.

## Ход

Ф.1 ЗАКРЫТА 2026-09-06: восемь вердиктов, корпус сошёлся.
EOF
python "$GUARD" "$c4" >/dev/null 2>&1
check "не ловит слово закрытия ВНЕ абзаца статуса" 0 $?

# --- 5. ГРАНИЦА: файл без строки статуса вообще ---------------------------
c5="$tmp/c5"
mk_plan "$c5" "README.md" <<'EOF'
# Индекс планов

Здесь нет строки статуса, и это законно.
EOF
python "$GUARD" "$c5" >/dev/null 2>&1
check "не падает на файле без строки статуса" 0 $?

# --- 6. НАСТОЯЩЕЕ ДЕРЕВО: на дне заведения нарушений ноль -----------------
python "$GUARD" "$REPO_ROOT" >/dev/null 2>&1
check "настоящее дерево проходит" 0 $?

if [ "$fails" -ne 0 ]; then
    echo "САМОТЕСТ ПРОВАЛЕН: $fails" >&2
    exit 1
fi
echo "test-check-plan-status-closure-leads: 6 ok, 0 FAIL"
exit 0
