#!/bin/sh
# Самотест check-commands-no-state (П16: страж без доказательства красноты
# запрещён). Краснота доказывается ТОЙ ЖЕ формой, из-за которой страж заведён:
# «Открытые сегодня: …» в `/carina` 2026-09-16.
#
# Отдельно доказано ДВА свойства, без которых страж был бы вреден:
#   * он НЕ краснеет на тексте ПРО запрет (иначе покраснел бы на конвенции,
#     которая эти формы цитирует, — и был бы отключён первым же окном);
#   * он судит ТОЛЬКО .claude/commands (планы и доки живут другим правилом).
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
G="$GD/check-commands-no-state.py"
T="${TMPDIR:-/tmp}/nova-cmdstate-selftest.$$"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok   $1"; }
bad() { echo "  FAIL $1" >&2; fails=$((fails+1)); }

C="$T/tree/.claude/commands"
mk() { rm -rf "$T/tree"; mkdir -p "$C"; }
run() { python "$G" "$T/tree" >"$T/out" 2>"$T/err"; echo $?; }
said() { grep -q "$1" "$T/out" "$T/err" 2>/dev/null; }

# ── 1. команда без состояния — зелено ───────────────────────────────────────
mk
cat > "$C/a.md" <<'EOF'
Роль: окно правит свой подплан. Что открыто — смотри командой:
grep -n "Status:" docs/plans/274.*.md
EOF
[ "$(run)" = "0" ] && ok "команда из правил и команд — зелено" \
    || bad "здоровая команда покраснела"

# ── 2. та самая форма — красно, и строка названа ───────────────────────────
mk
cat > "$C/a.md" <<'EOF'
Роль окна.
Открытые сегодня: 274.5, 274.6, 274.7.
EOF
[ "$(run)" = "1" ] && said "a.md:2" \
    && ok "«Открытые сегодня» — красно, и строка названа" \
    || bad "форма состояния обязана краснеть с номером строки"

# ── 3. счёт коммитов как факт — красно ─────────────────────────────────────
mk
cat > "$C/a.md" <<'EOF'
Замер при заведении: **61 коммит позади**, всё прежнее влито.
EOF
[ "$(run)" = "1" ] && ok "счёт коммитов — красно" \
    || bad "число, меняющееся каждым пушем, обязано краснеть"

# ── 4. текст ПРО запрет — зелено (иначе страж съест конвенцию) ────────────
mk
cat > "$C/a.md" <<'EOF'
ЗАПРЕЩЕНО писать «Открытые сегодня: …» — такая строка протухнет.
EOF
[ "$(run)" = "0" ] && ok "текст про запрет — зелено, страж не ест конвенцию" \
    || bad "страж покраснел на описании собственного правила"

# ── 5. то же состояние В ПЛАНЕ — не судится (другое правило) ──────────────
mk
mkdir -p "$T/tree/docs/plans"
cat > "$C/a.md" <<'EOF'
Роль окна, без состояния.
EOF
cat > "$T/tree/docs/plans/900-x.md" <<'EOF'
Открытые сегодня: 274.5 и 274.8.
EOF
[ "$(run)" = "0" ] && ok "план с состоянием — не предмет этого стража" \
    || bad "страж вышел за свой предмет"

# ── 6. каталога команд нет — FAIL, а не тихий ноль ────────────────────────
rm -rf "$T/tree"; mkdir -p "$T/tree"
[ "$(run)" = "1" ] && said "net kataloga" \
    && ok "нет каталога — FAIL с названной причиной" \
    || bad "пустая мишень обязана краснеть, а не читаться как «нарушений 0»"

if [ "$fails" -ne 0 ]; then
    echo "test-check-commands-no-state: FAIL ($fails)" >&2
    exit 1
fi
echo "test-check-commands-no-state: ok"
