#!/usr/bin/env bash
# test-check-no-manual-status-table.sh — САМОТЕСТ стража
# `check-no-manual-status-table.sh` (запрет рукописной сводной таблицы статусов
# планов в docs/plans/README.md).
#
# ПОЧЕМУ этот самотест появился: мета-страж `check-guard-wiring.sh` (правило
# владельца 2026-07-27 «в скрипте нет толку, если не подключён к автопроверке
# или сам содержит ошибки») при первом же прогоне указал, что у этого стража
# самотеста НЕТ — то есть много месяцев он охранял правило, а сам никем не был
# проверен. Ровно тот случай, ради которого мета-страж и заводился.
#
# Проверяются оба обязательных свойства: ЛОВИТ нарушение / НЕ даёт ложняка.
# Отдельно закреплён порог: одна-две похожие строки (цитата, пример в тексте)
# таблицей НЕ считаются — иначе страж превратился бы в источник ложных
# срабатываний, и его начали бы обходить.
#
# Запуск: scripts/selftest/test-check-no-manual-status-table.sh
# Выход: 0 — страж исправен; 1 — сломан.
#
# План: docs/plans/231-bug-cycle-exit.md §4в. Правило —
# docs/dev/conventions-governance.md, «Статус плана — только пофайлово».

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# Скрипт живёт в scripts/guards/selftest/ — корень репы на три уровня выше.
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
GUARD="$REPO_ROOT/scripts/guards/check-no-manual-status-table.sh"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

fails=0
check() { # имя, ожидаемый_код, фактический_код
    if [ "$2" -eq "$3" ]; then
        echo "  ok: $1"
    else
        echo "  ПРОВАЛ: $1 — ожидался код $2, получен $3" >&2
        fails=$((fails + 1))
    fi
}

mk_readme() { # каталог, содержимое-через-stdin
    mkdir -p "$1/docs/plans"
    cat > "$1/docs/plans/README.md"
}

echo "самотест check-no-manual-status-table:"

# (1) ЛОВИТ: полноценная рукописная статус-таблица (3 строки = порог).
r1="$tmp/r1"
mk_readme "$r1" <<'EOF'
# Планы

| № | План | Статус |
|---|---|---|
| 221 | [221-release.md](221-release.md) | ✅ ЗАКРЫТ |
| 222 | [222-http.md](222-http.md) | 🟡 В РАБОТЕ |
| 231 | [231-bug-cycle.md](231-bug-cycle.md) | 🔴 НЕ НАЧАТ |
EOF
bash "$GUARD" "$r1" >/dev/null 2>&1
check "ловит рукописную статус-таблицу (3 строки)" 1 $?

# (2) НЕ ловит: чистый README без таблицы.
r2="$tmp/r2"
mk_readme "$r2" <<'EOF'
# Планы

Статус каждого плана — пофайлово, строка `**Статус:**` в docs/plans/NNN-*.md.
Сводка генерируется: bash scripts/gen-plan-status.sh → docs/plans/STATUS.md.
EOF
bash "$GUARD" "$r2" >/dev/null 2>&1
check "НЕ ловит чистый README" 0 $?

# (3) НЕ ловит: ОДНА похожая строка — это цитата/пример, не реестр (порог 3).
#     Ложняк здесь дороже пропуска: страж, кричащий на пример в тексте, будет обойдён.
r3="$tmp/r3"
mk_readme "$r3" <<'EOF'
# Планы

Пример того, как делать НЕЛЬЗЯ (одна строка — иллюстрация, не таблица):

| 221 | [221-release.md](221-release.md) | ✅ ЗАКРЫТ |
EOF
bash "$GUARD" "$r3" >/dev/null 2>&1
check "НЕ ловит одиночную строку-иллюстрацию (порог 3)" 0 $?

# (4) НЕ ловит: README отсутствует вовсе — нечего проверять.
r4="$tmp/r4"; mkdir -p "$r4/docs/plans"
bash "$GUARD" "$r4" >/dev/null 2>&1
check "НЕ ловит отсутствие README" 0 $?

# (5) РЕАЛЬНАЯ РЕПА: сейчас таблицы быть не должно.
bash "$GUARD" >/dev/null 2>&1
check "реальная репа nova: рукописной таблицы нет" 0 $?

if [ "$fails" -ne 0 ]; then
    echo "самотест ПРОВАЛЕН: $fails свойств(а) не выполняются" >&2
    exit 1
fi
echo "самотест ok: страж ловит таблицу, не даёт ложняка на иллюстрациях"
