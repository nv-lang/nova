#!/bin/sh
# Самотест check-context-layer-budget (П16: страж без доказательства красноты
# запрещён). Красноту доказываем МУТАЦИЕЙ ПОДСУДНОГО: у подложного дерева
# отнимаем по одной части механизма и ждём красного с названной причиной.
#
# Судимое здесь — не текст правил, а ДВЕ ТРУБЫ, по которым текст приезжает в
# окно: (1) список после сжатия + читающий его хук + потолок; (2) цепочка
# `@`-импортов корневого CLAUDE.md + потолок. Поэтому подложное дерево содержит
# обе трубы, и каждая проба ломает ровно одну.
#
# КЛЮЧЕВОЕ В УСТРОЙСТВЕ ДЕРЕВА: файл `b.md` ТОЛЬКО импортируется и в список НЕ
# входит. Без него нельзя доказать половины по отдельности — рост общего файла
# краснит обе сразу, и страж, считающий только одну половину, прошёл бы такой
# самотест. Ровно так и было до 2026-08-29: половина `session-start` не мерилась
# вовсе, а самотест был зелёным.
export LC_ALL=C
GD="$(cd "$(dirname "$0")/.." && pwd)"
G="$GD/check-context-layer-budget.py"
T="${TMPDIR:-/tmp}/nova-context-layer-selftest.$$"
trap 'rm -rf "$T"' 0
fails=0
ok()  { echo "  ok   $1"; }
bad() { echo "  FAIL $1" >&2; fails=$((fails+1)); }

CAPS="$T/tree/scripts/guards/context-layer-budget.baseline"

# ── подложное дерево со ВСЕМИ частями обеих труб ─────────────────────────────
mk_tree() {
    rm -rf "$T/tree"
    mkdir -p "$T/tree/.claude/commands" "$T/tree/scripts/guards" "$T/tree/scripts/claude-hooks"
    printf 'x%.0s' $(seq 1 100) > "$T/tree/.claude/commands/a.md"
    printf 'y%.0s' $(seq 1 100) > "$T/tree/.claude/commands/b.md"
    printf '# list\n\n.claude/commands/a.md\n' > "$T/tree/.claude/after-compact.list"
    printf 'root: @.claude/commands/a.md and @.claude/commands/b.md\n' > "$T/tree/CLAUDE.md"
    printf '# caps\nafter-compact = 1000\nsession-start = 1000\n' > "$CAPS"
    printf 'read the .claude/after-compact.list here\n' \
        > "$T/tree/scripts/claude-hooks/inject-after-compact.py"
}

run() { python "$G" "$T/tree" >"$T/out" 2>"$T/err"; echo $?; }
said() { grep -q "$1" "$T/out" "$T/err" 2>/dev/null; }
set_caps() { printf '# caps\nafter-compact = %s\nsession-start = %s\n' "$1" "$2" > "$CAPS"; }

# ── 1. живое дерево — зелёное, и говорит ОБА числа и ОБА потолка ─────────────
mk_tree
[ "$(run)" = "0" ] && said "100/1000" && said "1000" \
    && ok "здоровое дерево: зелёный, назвал обе половины и оба потолка" \
    || bad "здоровое дерево должно быть зелёным и печатать обе половины"

# ── 2. нет файла потолков — красный ─────────────────────────────────────────
mk_tree; rm -f "$CAPS"
[ "$(run)" = "1" ] && ok "потолки убраны — красный" || bad "без потолков обязан краснеть"

# ── 3. потолки не разобраны — красный ───────────────────────────────────────
mk_tree; printf '# caps\nafter-compact = много\nsession-start = 1000\n' > "$CAPS"
[ "$(run)" = "1" ] && ok "потолок не число — красный" || bad "неразобранный потолок обязан краснеть"

# ── 4. потерян ОДИН из двух ключей — красный (полуслепая база хуже никакой) ──
mk_tree; printf '# caps\nafter-compact = 1000\n' > "$CAPS"
[ "$(run)" = "1" ] && said "session-start" \
    && ok "пропал ключ session-start — красный, и ключ назван" \
    || bad "база без одного ключа обязана краснеть с именем ключа"

# ── 5. инжектора нет — красный ──────────────────────────────────────────────
mk_tree; rm -f "$T/tree/scripts/claude-hooks/inject-after-compact.py"
[ "$(run)" = "1" ] && ok "инжектор убран — красный" || bad "список без читателя обязан краснеть"

# ── 6. инжектор перестал читать список — красный (выхолащивание) ────────────
mk_tree; printf 'inject something, but not from any list\n' \
    > "$T/tree/scripts/claude-hooks/inject-after-compact.py"
[ "$(run)" = "1" ] && ok "инжектор не читает список — красный" \
    || bad "выхолощенный механизм обязан краснеть"

# ── 7. файл из списка пропал — красный (это и есть молчание хука) ───────────
mk_tree; rm -f "$T/tree/.claude/commands/a.md"
[ "$(run)" = "1" ] && said "a.md" \
    && ok "файл списка пропал — красный, и назван поимённо" \
    || bad "пропавший файл обязан краснеть с именем"

# ── 8. ПОЛОВИНА 1 отдельно: список выше своего потолка ──────────────────────
#     Потолок session-start заведомо просторный — краснеть обязана ровно одна.
mk_tree; set_caps 50 100000
[ "$(run)" = "1" ] && said "after-compact" \
    && ok "половина after-compact выше потолка — красный, половина названа" \
    || bad "превышение первой половины обязано краснеть с её именем"

# ── 9. потолок ровно по объёму — зелёный (граница не ложнит) ────────────────
mk_tree; set_caps 100 100000
[ "$(run)" = "0" ] && ok "объём РОВНО в потолок — зелёный" || bad "равенство не должно краснить"

# ── 10. списка нет вовсе — зелёный, судить нечего ───────────────────────────
mk_tree; rm -f "$T/tree/.claude/after-compact.list"
[ "$(run)" = "0" ] && ok "списка нет — зелёный, судить нечего" \
    || bad "без списка судить нечего, краснеть не за что"

# ── 11. шапка YAML не считается в after-compact — как её не считает инжектор ─
mk_tree
{ printf -- '---\ndescription: "x"\n---\n'; printf 'z%.0s' $(seq 1 50); } \
    > "$T/tree/.claude/commands/a.md"
set_caps 50 100000
[ "$(run)" = "0" ] && ok "YAML-шапка в объём после сжатия не входит" \
    || bad "шапка обязана сниматься, как её снимает инжектор"

# ── 12. ПОЛОВИНА 2 отдельно: рост ТОЛЬКО импортируемого файла ───────────────
#     b.md в списке НЕТ, значит краснеть может лишь session-start. Это и есть
#     проба, которой у прежнего стража не было и быть не могло.
mk_tree; printf 'y%.0s' $(seq 1 5000) > "$T/tree/.claude/commands/b.md"
set_caps 100000 1000
[ "$(run)" = "1" ] && said "session-start" \
    && ok "половина session-start выше потолка — красный, половина названа" \
    || bad "рост импортируемого файла обязан краснить вторую половину"

# ── 13. и она же зеленеет от поднятия СВОЕГО потолка ────────────────────────
#     Доказывает, что судит именно потолок, а не случайность формы дерева.
set_caps 100000 100000
[ "$(run)" = "0" ] && ok "потолок session-start поднят — зелёный" \
    || bad "поднятие своего потолка обязано зеленить вторую половину"

# ── 14. битая цель `@`-импорта — красный, и названа поимённо ────────────────
mk_tree; rm -f "$T/tree/.claude/commands/b.md"
[ "$(run)" = "1" ] && said "b.md" \
    && ok "цель импорта пропала — красный, и названа поимённо" \
    || bad "битый импорт обязан краснеть с именем: это молча непривезённое правило"

# ── 15. импорты ТРАНЗИТИВНЫ: b.md тянет c.md, и он попадает в счёт ──────────
mk_tree
printf 'b imports @.claude/commands/c.md\n' > "$T/tree/.claude/commands/b.md"
printf 'w%.0s' $(seq 1 900) > "$T/tree/.claude/commands/c.md"
set_caps 100000 900
[ "$(run)" = "1" ] \
    && ok "транзитивный импорт посчитан — красный на потолке 900" \
    || bad "цепочка обязана разворачиваться транзитивно, иначе слой мерится не весь"

# ── 16. в session-start файл считается ЦЕЛИКОМ, вместе с YAML-шапкой ────────
#     Ровно то, чем половины и различаются: при импорте шапка видна как текст.
mk_tree
{ printf -- '---\nd: "x"\n---\n'; printf 'q%.0s' $(seq 1 50); } \
    > "$T/tree/.claude/commands/b.md"
BLEN=$(wc -c < "$T/tree/.claude/commands/b.md")
CLEN=$(wc -c < "$T/tree/CLAUDE.md")
EXACT=$((BLEN + CLEN + 100))
set_caps 100000 $((EXACT - 1))
[ "$(run)" = "1" ] \
    && ok "шапка ВХОДИТ в session-start: потолок на байт ниже точного — красный" \
    || bad "в session-start шапка обязана считаться: при импорте она приезжает текстом"
set_caps 100000 "$EXACT"
[ "$(run)" = "0" ] \
    && ok "и точный потолок — зелёный (счёт сходится побайтно)" \
    || bad "точный побайтный потолок обязан быть зелёным"

echo "самотест check-context-layer-budget: PASS $((17 - fails)) FAIL $fails"
[ "$fails" -eq 0 ] || exit 1
