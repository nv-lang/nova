#!/usr/bin/env bash
# Страж: строка реестра не остаётся ОТКРЫТОЙ, когда её правка уже слита.
#
# ЗАЧЕМ. Правка приземляется, фикстура кладётся, коммит называет номер в
# заголовке — а строка реестра остаётся `OPEN`, потому что автор правил
# ДРУГИЕ строки того же файла и свою не тронул. Наружу это выглядит как
# нескончаемый поток дефектов: реестр показывает работу, которая давно
# сделана.
#
# ЧТО ЭТО СТОИЛО (замер 2026-08-19). ЧЕТЫРЕ БЛОКИРУЮЩИЕ строки — №711, №714,
# №719, №720 — стояли `OPEN` при слитой правке И приколотой фикстуре. Плюс
# №677, у которого приёмка была выполнена чужой фикстурой. То есть пятая
# часть открытых блокеров тега была фикцией учёта, а не работой. Именно этим
# объясняется вопрос владельца «как флагман собирался месяц назад, если багов
# нескончаемо»: он собирался потому, что дефекты узкие и чинились сразу, а
# реестр их не списывал.
#
# ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Коммит `fix(#N)` доказывает ПОПЫТКУ, не закрытие: у
# №599 в истории «causa 2» и «causa 3» — правка частями; у №520 фикс снял
# ВРЕД, но не причину; у №705 закрыта одна ветвь из многих. Поэтому страж не
# закрывает строки и не советует их закрывать — он лишь требует, чтобы
# расхождение было ОСОЗНАННЫМ: либо строка закрывается, либо её номер стоит в
# базе с причиной, почему она остаётся открытой при слитой правке.
#
# ХРАПОВИК. База — `fixed-but-open.baseline`, по номеру в строке плюс причина.
# Новый номер вне базы = отказ. Записи, переставшие быть нужными, страж
# показывает ЗАМЕТКОЙ и не краснеет: закрытие строки — правильное действие, и
# наказывать за него ложным красным нельзя (довод №703).
#
# $1 — корень. Самотест — selftest/test-check-fixed-but-open.sh
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u
export LC_ALL=C

NAME="check-fixed-but-open"
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CORE="$(dirname "$0")/fixed-but-open-scan.py"

[ -f "$CORE" ] || { echo "$NAME: FAIL — нет ядра $CORE" >&2; exit 1; }

OUT=$(python "$CORE" "$ROOT" ${2:+"$2"} 2>&1)
if [ $? -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    printf '%s\n' "$OUT" | tail -5 >&2
    exit 1
fi

UX=$(printf '%s\n' "$OUT" | sed -n 's/^unexpected=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
ST=$(printf '%s\n' "$OUT" | sed -n 's/^stale=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
case "$UX" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число" >&2; exit 1;; esac
if [ "$UX" -lt 0 ]; then
    echo "$NAME: FAIL — ядро не нашло реестр (переехал?)" >&2
    exit 1
fi

if [ "$UX" -ne 0 ]; then
    echo "$NAME: FAIL — строк с приземлённой правкой, но статусом OPEN: $UX" >&2
    printf '%s\n' "$OUT" | grep -v '^unexpected=\|^stale=\|^open_with_fix=' | head -12 >&2
    echo "    Правка слита, а строка числится открытой — значит план" >&2
    echo "    показывает работу, которой нет, и блокеры тега завышены." >&2
    echo "    Сделай ОДНО из двух, оба честны:" >&2
    echo "      1) закрой строку — но СНАЧАЛА докажи, что фикстура умеет" >&2
    echo "         падать: обратно примени коммит-правку к исходникам," >&2
    echo "         пересобери тот же бинарь и убедись, что тест краснеет;" >&2
    echo "      2) впиши номер в scripts/guards/fixed-but-open.baseline с" >&2
    echo "         причиной, почему строка остаётся открытой при слитой" >&2
    echo "         правке (починен носитель, класс открыт; фикс частичный;" >&2
    echo "         закрыта одна ветвь) — как у №520, №633, №705, №716." >&2
    exit 1
fi

if [ "$ST" -gt 0 ]; then
    printf '%s\n' "$OUT" | grep '^  note:' >&2
    echo "$NAME ok: расхождений нет; в базе $ST устаревших записей — можно убрать"
    exit 0
fi

echo "$NAME ok: ни одной строки с приземлённой правкой и статусом OPEN вне базы"
exit 0
