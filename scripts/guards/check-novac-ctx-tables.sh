#!/bin/sh
# scripts/guards/check-novac-ctx-tables.sh — состав таблиц строк `Ctx`
# объявлен в плане и сверяется (конвенция П17, план 274 §10.3б; корень —
# план 273 §2).
#
# ЗАЧЕМ. Правило «одно понятие — одна таблица» не формализуется машиной:
# машина не знает, что `MethodTable` и `fn_rets` — одно понятие. Зато
# формализуется состав: набор полей `Ctx` обязан совпадать со строками
# таблицы §10.3б. Тогда вторая таблица не заводится молча — её приходится
# вписать, а вписывание есть решение вслух, и вопрос «зачем вторая?»
# задаётся в ту же минуту, а не через полгода отладки.
#
# ПРОВЕРЯЕТ: множество имён полей `export type Ctx { ... }` в novac/src/sem/sem.nv
#   против множества имён из первой колонки таблицы §10.3б плана 274 —
#   В ОБЕ СТОРОНЫ. Поле без строки плана — красный («реестр заведён без
#   решения»); строка плана без поля — красный (протухшая запись, она же
#   класс №519: переименовали — таблица тихо перестала судить).
#   Отдельно ассертит, что таблица §10.3б НЕПУСТА: пустой раздел иначе
#   сделал бы стража вечнозелёным.
# НЕ ПРОВЕРЯЕТ: содержание строк (что именно хранит таблица — приёмка);
#   таблицы вне `Ctx` (локальные для прохода — не реестры файла);
#   порядок полей.
#
# $1 — корень репозитория.
# $2 — override пути к sem.nv (шов самотеста).
# $3 — override пути к плану (шов самотеста).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
SEM="${2:-$ROOT/novac/src/sem/sem.nv}"
PLAN="${3:-$ROOT/docs/plans/274-novac-self-hosted-compiler.md}"
NAME=check-novac-ctx-tables

if [ ! -f "$SEM" ]; then
    echo "$NAME ok: судить нечего (нет $SEM)"
    exit 0
fi
[ -f "$PLAN" ] || { echo "$NAME: FAIL — нет плана $PLAN, состав таблиц не с чем сверить" >&2; exit 1; }

T="${TMPDIR:-/tmp}/novac-ctx-tables.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

# --- поля Ctx из исходника -------------------------------------------------
tr -d '\r' < "$SEM" | awk '
    /^export type Ctx \{/ { inb = 1; next }
    inb && /^\}/ { inb = 0 }
    inb && /^[[:space:]]+[a-z_][A-Za-z0-9_]*[[:space:]]/ {
        gsub(/^[[:space:]]+/, "", $0)
        split($0, p, /[[:space:]]/)
        print p[1]
    }
' | sort -u > "$T/src"

# --- имена из первой колонки таблицы §10.3б --------------------------------
# Диапазон: от заголовка 10.3б до следующего заголовка того же или высшего
# уровня. Берём только строки таблицы, первая ячейка которых — имя в
# обратных апострофах.
tr -d '\r' < "$PLAN" | awk '
    /^#+ .*10\.3б/ { inb = 1; next }
    inb && /^#+ / { inb = 0 }
    inb && /^\|[[:space:]]*`[a-z_][A-Za-z0-9_]*`[[:space:]]*\|/ {
        line = $0
        sub(/^\|[[:space:]]*`/, "", line)
        sub(/`.*$/, "", line)
        print line
    }
' | sort -u > "$T/plan"

NSRC=$(wc -l < "$T/src" | tr -d '[:space:]')
NPLAN=$(wc -l < "$T/plan" | tr -d '[:space:]')

if [ "$NSRC" -eq 0 ]; then
    echo "$NAME: FAIL — в $SEM не нашлось ни одного поля \`export type Ctx\`: страж потерял мишень (класс №519)" >&2
    exit 1
fi
if [ "$NPLAN" -eq 0 ]; then
    echo "$NAME: FAIL — таблица §10.3б плана пуста или переименована: сверять не с чем, а молчать нельзя (класс №519)" >&2
    exit 1
fi

MISSING=$(comm -23 "$T/src" "$T/plan")
STALE=$(comm -13 "$T/src" "$T/plan")

if [ -n "$MISSING" ]; then
    echo "$NAME: FAIL — таблица строк в Ctx заведена без решения (П17, план §10.3б):" >&2
    for m in $MISSING; do echo "  $m — нет строки в §10.3б" >&2; done
    echo "  Впиши строку в §10.3б и ответь там на вопрос «почему это ОТДЕЛЬНАЯ таблица»," >&2
    echo "  либо своди с существующей: метод есть функция с получателем (план 273 §2)." >&2
    exit 1
fi
if [ -n "$STALE" ]; then
    echo "$NAME: FAIL — строка §10.3б без поля в Ctx (протухшая запись, класс №519):" >&2
    for s in $STALE; do echo "  $s — такого поля в Ctx нет" >&2; done
    echo "  Убери строку той же волной, что и поле: реестр, отставший от кода, судит воздух." >&2
    exit 1
fi

echo "$NAME ok: таблиц строк в Ctx: $NSRC, все объявлены в §10.3б, протухших строк: 0"
exit 0
