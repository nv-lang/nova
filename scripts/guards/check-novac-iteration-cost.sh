#!/bin/sh
# scripts/guards/check-novac-iteration-cost.sh — храповик цены цикла novac.
#
# ПРАВИЛО (конвенция П14; план 274.2): цена одного витка итерации —
# зафиксированное число, а не «как получится». База
# scripts/guards/novac-iteration-cost.baseline держит на каждый ключ ДВЕ
# строки: бюджет «<ключ> <мс>» (потолок) и факт «<ключ>-last <мс>»
# (последний записанный замер). Судится В ОБЕ СТОРОНЫ: факт > бюджета —
# просадка; факт ВТРОЕ лучше ЗАПИСАННОГО ФАКТА — ускорение, база обязана
# быть поднята тем же коммитом. Пороги выбраны по наблюдению, а не на глаз
# (274.3/F10, оба ложных красных пойманы 2026-08-15): (1) считать от факта, а
# не от бюджета — «факт < бюджет/2» краснел бы на любой нормальной машине;
# (2) кратность 3, а не 2, и (3) замеры мельче 0.2 с на ускорение вообще не
# судятся — на них шум планировщика Windows и MSYS-форков даёт разы, и правило
# срабатывало на тишине машины, а не на изменении кода.
#
# ПРОВЕРЯЕТ: три ключа цикла — смоук (тёплый), один `novac check`, фаззер;
# замер — ЛУЧШИЙ из нескольких прогонов (мелкий и самый шумный check — из
# трёх, длинные смоук и фаззер — из двух: минимум N выборок и есть
# шумоустойчивая оценка цены, но каждая выборка стоит секунд гейта); для
# каждого ключа обязаны быть в базе и бюджет, и факт (нет факта — красный:
# половина храповика мертва), и факт не должен превышать бюджет
# (противоречивая база — красный).
# НЕ ПРОВЕРЯЕТ: цену дифф-раннера (68 с) — её меряет и судит по ключу
# diff-corpus-ms этой же базы check-novac-differential.sh; правдивость самих
# бюджетов (их поднимает человек тем же коммитом); шум машины сверх
# best-of-N — на занятой машине (замеры 2026-08-15 шли при 83% CPU от
# соседних окон) один и тот же `novac check` даёт 300–950мс против 160мс на
# тихой. Потому бюджет в базе — вдвое от ХУДШЕГО наблюдавшегося, а порог
# ускорения — вдвое ниже ЛУЧШЕГО: коридор ловит грубую просадку (x3 и хуже),
# а не 20%.
# NOVAC_COST=0 пропускает страж (локальная итерация); пропуск в гейте —
# сознательное решение интегратора.
#
# $1 — корень репозитория.
# Проверялся: Windows (Git Bash), 2026-08-15.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
NAME=check-novac-iteration-cost
. "$(dirname "$0")/lib/novac.sh"
BASE="$ROOT/scripts/guards/novac-iteration-cost.baseline"
NOVAC="$ROOT/novac/target/novac.exe"
[ "${NOVAC_COST:-1}" = "0" ] && { echo "$NAME: пропущен (NOVAC_COST=0 — локальная итерация)"; exit 0; }
novac_require_bin "$NAME" "$ROOT" "$NOVAC"
[ -f "$BASE" ] || { echo "$NAME: FAIL — нет $BASE" >&2; exit 1; }

base_num() { tr -d '\r' < "$BASE" | sed -n "s/^$1 \([0-9]*\)$/\1/p" | head -n 1; }
now_ms() { date +%s%N | cut -c1-13; }
best_of() {  # $1 = repeats, $2.. = command; prints best wall ms
    n="$1"; shift
    b=999999999; i=0
    while [ "$i" -lt "$n" ]; do
        i=$((i + 1))
        # rc ЗАМЕРЯЕМОЙ команды проверяется (274.3/F10, адверсарная проверка):
        # раннер, падающий сразу, «быстрее» любого бюджета — цена, измеренная у
        # сломанного механизма, зелёная и бессмысленная.
        s=$(now_ms); "$@" >/dev/null 2>&1; _rc=$?; e=$(( $(now_ms) - s ))
        if [ "$_rc" -ne 0 ]; then
            echo "  ЗАМЕР НЕВАЛИДЕН: команда «$*» вернула $_rc — цена сломанного механизма не считается" >&2
            printf 'BROKEN\n'
            return 1
        fi
        [ "$e" -lt "$b" ] && b=$e
    done
    echo "$b"
}
judge() {  # $1 key, $2 fact (ms) | BROKEN
    key="$1"; fact="$2"
    if [ "$fact" = "BROKEN" ]; then
        echo "  $key: замеряемый механизм упал — цена не судится, чинить механизм (274.3/F10)" >> "$T/bad"
        return
    fi
    bud=$(base_num "$key")
    last=$(base_num "$key-last")
    if [ -z "$bud" ]; then
        echo "  $key: нет бюджета в базе — добавь строку «$key <мс>»" >> "$T/bad"
        return
    fi
    if [ -z "$last" ]; then
        echo "  $key: нет факта в базе — добавь строку «$key-last $fact»: без факта храповик ускорения мёртв (П14)" >> "$T/bad"
        return
    fi
    if [ "$last" -gt "$bud" ]; then
        echo "  $key: БАЗА ПРОТИВОРЕЧИВА — факт ${last}мс больше бюджета ${bud}мс" >> "$T/bad"
    fi
    ebud=$(( bud * SCALE / 100 ))
    if [ "$fact" -gt "$ebud" ]; then
        echo "  $key: ПРОСАДКА — факт ${fact}мс > бюджет ${bud}мс (с поправкой на загрузку машины ${ebud}мс, калибровка x${SCALE}/100)" >> "$T/bad"
    elif [ "$fact" -lt 200 ] && [ "$last" -lt 400 ]; then
        # Порог измеримости (274.3/F10, поймано ложным красным 2026-08-15 в
        # полном прогоне): на замерах меньше ~0.2 с шум планировщика Windows
        # и MSYS-форки дают разброс в разы, и правило «ускорение вдвое»
        # срабатывает на тишине машины, а не на изменении кода. Ниже порога
        # ускорение не судится (просадка судится всегда — она про бюджет).
        :
    elif [ $((fact * 3)) -lt "$last" ]; then
        echo "  $key: УСКОРЕНИЕ — факт ${fact}мс втрое лучше факта базы (${last}мс): подними базу ТЕМ ЖЕ коммитом, иначе просадку потом не увидеть (П14)" >> "$T/bad"
    fi
    echo "$key ${fact}/${ebud}мс (бюджет ${bud}, факт базы ${last})" >> "$T/ok"
}
T="${TMPDIR:-/tmp}/novac-cost.$$"; mkdir -p "$T"; trap 'rm -rf "$T"' 0
cd "$ROOT" || exit 2

# КАЛИБРОВКА (274.3/F10, второй ложный красный 2026-08-15): wall-clock судить
# в абсолюте нельзя — тот же `novac check` даёт 150мс на тихой машине и 3300мс
# под полным прогоном гейта, и «просадка» оказывается свойством соседнего
# процесса, а не кода. Меряем в ТОМ ЖЕ прогоне эталонный fork оболочки
# (главный источник шума под MSYS) и масштабируем бюджеты на отношение
# «сейчас / записано в базе». Машина втрое медленнее — бюджеты втрое шире;
# код медленнее при спокойной машине — красный, как и задумано.
SCALE=$(novac_load_scale "$ROOT")   # общая дверь калибровки (lib/novac.sh)

# warm the smoke cache once (cold run is the oracle's price, not the loop's)
sh scripts/tools/novac-e1-smoke.sh examples/basics/hello.nv >/dev/null 2>&1
judge smoke-warm-ms "$(best_of 2 sh scripts/tools/novac-e1-smoke.sh examples/basics/hello.nv)"
judge check-one-ms "$(best_of 3 "$NOVAC" check examples/basics/hello.nv)"
judge fuzz-ms "$(best_of 2 sh scripts/tools/novac-fuzz-mutations.sh 40)"

MEASURED=$(tr '\n' ';' < "$T/ok" 2>/dev/null | sed -e 's/;/, /g' -e 's/, $//')
if [ -f "$T/bad" ]; then
    echo "$NAME: FAIL — цена цикла разошлась с базой (П14, $BASE):" >&2
    cat "$T/bad" >&2
    [ -n "$MEASURED" ] && echo "  замеры: $MEASURED" >&2
    exit 1
fi
echo "$NAME ok: цена цикла в бюджете (калибровка машины x${SCALE}/100) — $MEASURED"
exit 0
