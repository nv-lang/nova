#!/usr/bin/env bash
# scripts/guards/check-agent-definitions-wired.sh
# Определение субагента обязано быть НАЗВАНО командой, а команда — указывать на
# существующее определение. Связь в обе стороны.
#
# ДОМ И ОСНОВАНИЕ: план 276 шаг 2; вопрос владельца 2026-08-29 — «как агенты
# узнают о существовании `spec-reader` и какие механизмы принуждения есть?».
#
# ЗАЧЕМ. Честный ответ на тот вопрос: ПРИНУДИТЬ взять нужного агента машиной
# нельзя — гейт судит дерево, а вызов агента в дереве не остаётся. Значит
# машине достаётся не намерение, а СВЯЗНОСТЬ: чтобы окно могло узнать про
# агента, определение должно быть названо там, куда окно смотрит (скилл или
# команда), а они не должны звать агента, которого нет. Обе половины ломаются
# молча: определение, о котором нигде не сказано, не будет найдено никогда;
# ссылка на несуществующий тип отказывает в момент вызова, посреди работы.
#
# ПРОВЕРЯЕТ ДВЕ ВЕЩИ:
#   1. каждый файл `.claude/agents/X.md` упомянут хотя бы в одном файле
#      `.claude/commands/*.md` ИЛИ `.claude/skills/**` (по имени `X`);
#   2. каждый `subagent_type: "X"` или `subagent_type: X`, встреченный в
#      командах или скилах, имеет файл `.claude/agents/X.md`.
#
# ПОЧЕМУ ОБА КАТАЛОГА (владелец, 2026-08-29): команду надо вызвать слэшем, и
# слэш-меню принадлежит ВЛАДЕЛЬЦУ; инструкция, адресованная агенту, живёт в
# скилле — он всплывает сам. Судить только команды значило бы не видеть
# главный дом осведомления.
#
# ИМЯ АГЕНТА ОБЯЗАНО ОТЛИЧАТЬСЯ ОТ ИМЕНИ СКИЛЛА, И ЭТО НЕ ВКУС (вопрос
# владельца 2026-08-29: «скилл и команда `read-spec`, а агент `spec-reader` —
# насколько это оправдано?»). Две причины. Первая родовая: скилл есть
# ДЕЙСТВИЕ («вычитай спеку»), агент есть ИСПОЛНИТЕЛЬ («тот, кто читает
# спеки»); назвав их одинаково, перестаёшь видеть, кто кого звал. Вторая —
# про ЭТОГО стража: он ищет ИМЯ агента внутри скилов и команд. Совпади
# имена — грепу хватило бы того, что файл скилла упоминает сам себя, и
# проверка стала бы зелёной ни от чего. Этот класс случился в тот же день:
# шапка `flag-caller-scan.py` перечисляла флаги и тем удовлетворяла своего
# же стража. Значит переименование «для единообразия» тихо выключает
# проверку — и потому запрещено здесь, а не только в чьей-то памяти.
#
# ЧЕГО НЕ ПРОВЕРЯЕТ (сказано прямо, чтобы не создавать ложного чувства
# защищённости): что агента ДЕЙСТВИТЕЛЬНО берут вместо самодельного чтения.
# Это не проверяемо из дерева ни этим стражем, ни любым другим. Осведомление
# держится на скилле `/read-spec` и разделе «Агент-читатель» в `/delegate`;
# доказуемая же часть — только артефакты доклада (см. `guard-stop.py`, условие
# про строку «Модели агентов:»).
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-agent-definitions-wired.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-agent-definitions-wired.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
cd "$ROOT" || { echo "check-agent-definitions-wired: нет каталога $ROOT" >&2; exit 1; }

AG=".claude/agents"
CMD=".claude/commands"
# Скилы — второй дом инструкций, адресованных агенту (и главный: они
# всплывают САМИ, а команду надо вызвать слэшем). Упоминание агента в
# скилле осведомляет ровно так же, поэтому оба каталога судятся вместе.
SKILLS=".claude/skills"

if [ ! -d "$AG" ] && [ ! -d "$CMD" ] && [ ! -d "$SKILLS" ]; then
    echo "check-agent-definitions-wired ok: судить нечего — ни $AG, ни $CMD, ни $SKILLS нет"
    exit 0
fi

ORPHAN=""
NDEF=0
if [ -d "$AG" ]; then
    for a in "$AG"/*.md; do
        [ -f "$a" ] || continue
        name=$(basename "$a" .md)
        NDEF=$((NDEF + 1))
        seen=0
        for d in "$CMD" "$SKILLS"; do
            [ -d "$d" ] || continue
            grep -rql -- "$name" "$d" 2>/dev/null && { seen=1; break; }
        done
        if [ "$seen" -eq 1 ]; then
            :
        else
            ORPHAN="$ORPHAN $name"
        fi
    done
fi

DANGLING=""
NREF=0
if [ -d "$CMD" ] || [ -d "$SKILLS" ]; then
    refs=$(grep -rhoE 'subagent_type: *"?[A-Za-z0-9_-]+"?' "$CMD" "$SKILLS" 2>/dev/null \
           | sed -E 's/.*subagent_type: *"?([A-Za-z0-9_-]+)"?.*/\1/' | sort -u)
    for r in $refs; do
        NREF=$((NREF + 1))
        [ -f "$AG/$r.md" ] || DANGLING="$DANGLING $r"
    done
fi

norph=0; for m in $ORPHAN; do norph=$((norph + 1)); done
ndang=0; for m in $DANGLING; do ndang=$((ndang + 1)); done

echo "check-agent-definitions-wired: определений $NDEF, ссылок из команд и скилов $NREF, безымянных $norph, висячих $ndang"

if [ "$norph" -ne 0 ] || [ "$ndang" -ne 0 ]; then
    if [ "$norph" -ne 0 ]; then
        echo "check-agent-definitions-wired: НАРУШЕНИЕ — определение, о котором не говорит ни один скилл и ни одна команда:" >&2
        for m in $ORPHAN; do echo "    $AG/$m.md" >&2; done
        echo "    Окно смотрит в команды и скилы, а не в каталог определений: про" >&2
        echo "    такого агента оно не узнает никогда и напишет своё чтение заново." >&2
    fi
    if [ "$ndang" -ne 0 ]; then
        echo "check-agent-definitions-wired: НАРУШЕНИЕ — скилл или команда зовёт агента без определения:" >&2
        for m in $DANGLING; do echo "    subagent_type: $m (нет $AG/$m.md)" >&2; done
        echo "    Такой вызов отказывает В МОМЕНТ работы, а не на гейте." >&2
    fi
    echo "check-agent-definitions-wired: FAIL" >&2
    exit 1
fi

echo "check-agent-definitions-wired ok: каждое определение названо скиллом или командой, каждая ссылка ведёт в существующий файл"
exit 0
