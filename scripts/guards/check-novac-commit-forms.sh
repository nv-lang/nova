#!/bin/sh
# scripts/guards/check-novac-commit-forms.sh — коммит, учащий ПАРСЕР novac новой
# форме синтаксиса, обязан назвать ВСЕ формы этого синтаксиса и источник, по
# которому они перечислены (агент `.claude/agents/spec-reader.md`).
#
# ЗАЧЕМ, И ЭТО ЗАМЕР, А НЕ ПОЖЕЛАНИЕ. 2026-09-18 окно Карины учило курсор читать
# аргумент атрибута `#impl(P)` и проверило ЧЕТЫРЕ клетки: `#impl(Display)`,
# `#impl(Serialize)`, `#impl(coerce)`, `#realtime nogc`. Все четыре сошлись — и
# все четыре были об ОДНОМ атрибуте против другого. Формы `#impl(A + B + C)`,
# которую D186 даёт прямо, в сетке не было вовсе, и правило «есть ли Display
# СРЕДИ аргументов» приняло `#impl(Display + Serialize)`: автор объявил тип
# сериализуемым, ему поверили, а компилятор этот опт-ин молча проигнорировал.
# Поймал владелец, не страж и не самотест. Полуисполненный опт-ин хуже
# отвергнутого: при отказе автор видит, что форма не поддержана.
#
# ПОЧЕМУ ИМЕННО АГЕНТ, а не «прочитай спеку сам»: перечисление форм — работа
# читательская и механическая, её дом `/delegate`, и у агента есть ОБЯЗАТЕЛЬНАЯ
# ФОРМА ВЫДАЧИ (применимые правила · чего в документах нет · противоречия). Без
# третьего раздела окно и читает-то обычно то, что подтверждает задуманное.
#
# ЧТО ПРОВЕРЯЕТ (только когда в индексе есть novac/src/parse/*.nv):
#   * строку `Forms:` с ТРЕМЯ частями — источник (D-блок либо файл spec/),
#     слово `spec-reader` (утверждение, что формы перечислял агент) и САМ
#     ПЕРЕЧЕНЬ через запятую, не меньше ДВУХ форм; либо
#   * `Forms: none — <причина, минимум пять слов>` для правки, не трогающей
#     множество читаемых форм (починка, перенос, переименование).
#
# ПОЧЕМУ НЕ МЕНЬШЕ ДВУХ ФОРМ. Одна форма — это ровно то, что пишут, НЕ спросив:
# та, ради которой села работа. Порог в две заставляет назвать хотя бы одну,
# которой в голове не было. Он не доказывает полноту (страж не читает спеку) —
# он делает видимым, что перечисление вообще было.
#
# ЧЕГО НЕ ПРОВЕРЯЕТ, названо вслух: правдивость перечня и то, что агента правда
# звали (страж заставляет НАЗВАТЬ, а не доказывает); коммиты в `novac/src/check`
# и `novac/src/sem` — там форма СУДИТСЯ, а не читается, и требовать перечень у
# каждой правки отказа значило бы превратить строку в ритуал; чужие деревья.
#
# $1 — файл с сообщением коммита; $2 — корень репозитория;
# $3 — override списка проиндексированных файлов (шов самотеста, по строке).
export LC_ALL=C
MSG="${1:-}"
if [ -z "$MSG" ]; then
    echo "check-novac-commit-forms ok: судить нечего (нет файла сообщения — страж хука commit-msg)"
    exit 0
fi
ROOT="${2:-$(cd "$(dirname "$0")/../.." && pwd)}"
NAME=check-novac-commit-forms

if [ -n "$3" ]; then
    STAGED=$(printf '%s\n' "$3")
else
    STAGED=$(git -C "$ROOT" diff --cached --name-only 2>/dev/null)
fi
TOUCHES=$(printf '%s\n' "$STAGED" | grep -E '^novac/src/parse/.*\.nv$' | grep -vE '_test\.nv$' | head -n 1)
if [ -z "$TOUCHES" ]; then
    echo "$NAME ok: судить нечего (novac/src/parse не в индексе)"
    exit 0
fi

LINE=$(tr -d '\r' < "$MSG" | grep -E '^Forms:' | head -n 1)
if [ -z "$LINE" ]; then
    echo "$NAME: FAIL — коммит трогает парсер novac, а строки 'Forms:' в сообщении нет." >&2
    echo "  Перечисли ВСЕ формы синтаксиса, спросив агента .claude/agents/spec-reader.md:" >&2
    echo "  'Forms: D186 spec-reader — #impl(P), #impl(P1 + P2 + ...), #impl() empty'." >&2
    echo "  Или честно: 'Forms: none — <почему множество форм не меняется, пять слов>'." >&2
    exit 1
fi
BODY=$(printf '%s' "$LINE" | sed 's/^Forms:[[:space:]]*//')

# форма «none — причина»
if printf '%s' "$BODY" | grep -qiE '^none[[:space:]]*(—|-|--)'; then
    REASON=$(printf '%s' "$BODY" | sed -E 's/^none[[:space:]]*(—|-|--)[[:space:]]*//')
    NW=$(printf '%s' "$REASON" | wc -w | tr -d '[:space:]')
    if [ "$NW" -lt 5 ]; then
        echo "$NAME: FAIL — 'Forms: none' без причины (минимум пять слов после тире): «$LINE»" >&2
        exit 1
    fi
    echo "$NAME ok: множество форм не менялось — причина названа ($NW слов)"
    exit 0
fi

# источник: D-блок или файл спеки
if ! printf '%s' "$BODY" | grep -qE '(D[0-9]{1,4})|spec/'; then
    echo "$NAME: FAIL — 'Forms:' не называет ИСТОЧНИК перечня: «$LINE»." >&2
    echo "  Нужен D-блок (D186) либо путь в spec/ — иначе перечень не с чем сверить." >&2
    exit 1
fi

# утверждение, что перечислял агент
if ! printf '%s' "$BODY" | grep -qE 'spec-reader'; then
    echo "$NAME: FAIL — 'Forms:' не называет spec-reader: «$LINE»." >&2
    echo "  Формы перечисляет агент .claude/agents/spec-reader.md — у него обязательная" >&2
    echo "  форма выдачи с разделом «противоречия», и без неё читают то, что ищут." >&2
    exit 1
fi

# сам перечень: не меньше двух форм через запятую, после тире
LIST=$(printf '%s' "$BODY" | sed -E 's/^.*(—|--)[[:space:]]*//')
NF=$(printf '%s' "$LIST" | awk -F',' '{n=0; for (i=1;i<=NF;i++) if ($i ~ /[^[:space:]]/) n++; print n}')
if [ "${NF:-0}" -lt 2 ]; then
    echo "$NAME: FAIL — 'Forms:' перечисляет меньше двух форм: «$LIST»." >&2
    echo "  Одна форма — это та, ради которой села работа; порог в две заставляет назвать" >&2
    echo "  хотя бы одну, которой не было в голове. Замер 2026-09-18: четыре зелёные" >&2
    echo '  клетки и ни одной на `#impl(A + B)` — форму принял владелец, не страж.' >&2
    exit 1
fi
echo "$NAME ok: формы перечислены ($NF) с источником и через spec-reader"
exit 0
