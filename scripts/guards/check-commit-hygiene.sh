#!/usr/bin/env bash
# scripts/guards/check-commit-hygiene.sh
# Реестр 221.1 (класс «правило держится памятью»), план 254 —
# docs/plans/254-process-rules-without-mechanism.md, П1: четыре правила,
# которые интегратор выполнял РУКАМИ в каждом коммите.
# Вопрос владельца 2026-08-08: «какие есть ещё такие правила [живущие в голове и
# потому требующие повторения]?». Замер: 74 правила в памяти интегратора, у 57 не
# было механизма вовсе. Этот страж закрывает четыре самых дешёвых и самых
# проверяемых — те, что интегратор выполнял РУКАМИ в каждом коммите.
#
# ЧТО ПРОВЕРЯЕТСЯ (всё — перед коммитом, по индексу и по сообщению):
#   1. МАРКЕРЫ КОНФЛИКТА в том, что коммитится. Правило требовало грепать их
#      «одной командой вместе с commit» — то есть человек обязан был не забыть.
#      Забыть можно всегда; здесь забыть нечего.
#   2. НЕТ `Co-Authored-By` в сообщении. Правило владельца; проверяется строкой.
#   3. АВТОРСТВО — `user.email` обязан совпадать с эталоном репозитория.
#      Окна уже ошибались авторством, и правка после коммита стоит переписывания
#      истории.
#   4. `git config` НЕ ТРОНУТ агентом: общий `.git` делится между worktree, и
#      правка конфига травит авторство всей репы разом. Проверяется тем, что
#      эталонные значения на месте.
#
# ПОЧЕМУ ХУК, А НЕ ГЕЙТ. Гейт идёт 40 минут и запускается редко; к моменту его
# падения испорченный коммит уже в истории. Точка приложения — сам коммит.
#
# ЧЕГО НЕ ЛОВИТ: сообщение проверяется только на запрещённую строку, не на
# смысл; авторство сверяется с эталоном, а не с намерением. Это осознанный
# предел — страж закрывает забывчивость, а не подмену.
#
# ИСПОЛЬЗОВАНИЕ (вызывается хуком `commit-msg`; можно и вручную):
#   bash scripts/guards/check-commit-hygiene.sh [ФАЙЛ-СООБЩЕНИЯ] [КОРЕНЬ]

set -u
export LC_ALL=C

MSGFILE="${1:-}"
ROOT="${2:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
cd "$ROOT" || exit 1

EXPECT_EMAIL="${NOVA_COMMIT_EMAIL:-unitcraft@nv-lang.org}"
VIOL=0

say() { echo "check-commit-hygiene: $1" >&2; VIOL=$((VIOL + 1)); }

# ── 1. Маркеры конфликта в индексе ────────────────────────────────────────
# Смотрим ТОЛЬКО добавляемые строки: существующий файл может законно содержать
# такую строку как данные (селфтесты стражей — ровно этот случай).
CONF=$(git diff --cached --unified=0 2>/dev/null \
       | grep -nE '^\+(<<<<<<<|=======$|>>>>>>>)' | head -5)
if [ -n "$CONF" ]; then
    say "МАРКЕРЫ КОНФЛИКТА в коммитимом:"
    printf '%s\n' "$CONF" | sed 's/^/    /' >&2
fi

# ── 2. Co-Authored-By в сообщении ─────────────────────────────────────────
if [ -n "$MSGFILE" ] && [ -f "$MSGFILE" ]; then
    if grep -qiE '^[[:space:]]*Co-Authored-By:' "$MSGFILE"; then
        say "в сообщении есть Co-Authored-By — правило владельца запрещает"
    fi
fi

# ── 3. Авторство ──────────────────────────────────────────────────────────
EMAIL=$(git config user.email 2>/dev/null)
if [ -n "$EXPECT_EMAIL" ] && [ "${EMAIL:-}" != "$EXPECT_EMAIL" ]; then
    say "user.email = '${EMAIL:-<пусто>}', ожидалось '$EXPECT_EMAIL'"
    echo "    Коммит с чужим авторством правится только переписыванием истории." >&2
fi

# ── 4. Имя автора на месте ────────────────────────────────────────────────
NAME=$(git config user.name 2>/dev/null)
if [ -z "${NAME:-}" ]; then
    say "user.name пуст — общий .git делится между worktree, правка конфига травит всю репу"
fi

# ── 5. Язык сообщения: только ASCII ───────────────────────────────────────
# ПОЧЕМУ ЭТО ЗДЕСЬ, А НЕ ТОЛЬКО В ГЕЙТЕ (реестр 221.1 №649). Норма «сообщения
# по-английски» (владелец, 2026-08-09) механизм имела — `check-commit-language`,
# — но включённый ТОЛЬКО в гейт. Гейт судит историю: к моменту его отказа
# коммит уже сделан, и правка стоит переписывания. 2026-08-14 так и вышло:
# отказ гейта на чужом коммите, из-за ОДНОГО токена `Ф.0`, и он держит отправку
# 21 коммита. В шапке этого самого стража написано, почему точка приложения —
# сам коммит; правило языка при этом жило в гейте. Теперь и здесь.
#
# Проверяется НЕ «кириллица», а любой не-ASCII: `§`, прошедший перекодировку,
# уже уезжал на три зеркала нечитаемым (№590). Кавычка чужого текста (строка с
# `>`) и комментарии git (строка с `#`) исключены.
#
# Байтами, а не `grep -P`: класс `[^\x00-\x7F]` есть только у PCRE, и страж,
# молча пропускающий проверку при grep без `-P`, — это ровно №645.
if [ -n "$MSGFILE" ] && [ -f "$MSGFILE" ]; then
    NA=$(grep -vE '^[[:space:]]*[>#]' "$MSGFILE" | tr -d '\000-\177' | wc -c | tr -d ' ')
    if [ "${NA:-0}" -gt 0 ]; then
        say "в сообщении $NA не-ASCII байт(ов) — норма 2026-08-09: сообщения по-английски"
        grep -nE "[$(printf '\200')-$(printf '\377')]" "$MSGFILE" \
            | grep -vE '^[0-9]+:[[:space:]]*[>#]' | head -3 | sed 's/^/    /' >&2
        echo "    Фаза пишется Ph.N, а не кириллицей: история читается снаружи," >&2
        echo "    и не-ASCII в сообщении уже уезжал в зеркала перекодированным (№590)." >&2
        echo "    Цитату чужого текста ставь строкой с '>' — она не проверяется." >&2
    fi
fi

if [ "$VIOL" -gt 0 ]; then
    echo "check-commit-hygiene: FAIL — $VIOL нарушени(й)" >&2
    exit 1
fi
# Строка с `ok:` и указанием ЧТО именно проверено — требование
# check-gate-steps-assert.sh: «ok» без двоеточия и без предмета не отличается
# от молчания (реестр 221.1 №645, №647).
# П27 (novac): коммит, трогающий novac/src, называет донора решения или честно
# говорит, что донора нет. Отдельный страж — правило novac-овское, общий свод
# его не несёт; зовётся отсюда, потому что хук commit-msg один на репозиторий.
if [ -f "$ROOT/scripts/guards/check-novac-commit-donor.sh" ] && [ -n "${MSGFILE:-}" ]; then
    sh "$ROOT/scripts/guards/check-novac-commit-donor.sh" "$MSGFILE" "$ROOT" || exit 1
fi
echo "check-commit-hygiene ok: маркеры, авторство, запрет Co-Authored-By и язык сообщения проверены"
exit 0
