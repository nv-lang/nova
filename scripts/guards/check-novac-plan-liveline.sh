#!/bin/sh
# scripts/guards/check-novac-plan-liveline.sh — живая строка плана не отстаёт
# от кода, который она описывает.
#
# ПРАВИЛО, КОТОРОЕ ЗДЕСЬ МЕХАНИЗИРУЕТСЯ, придумано не этим стражем: оно
# написано в самом плане 274, в скобках у каждой живой строки — «обновляется
# ТЕМ ЖЕ СЛИЯНИЕМ, что и код». До 2026-08-18 это было обещание, и обещание не
# сдержалось: строка стояла с датой 2026-08-14, пока четыре дня шла работа
# следующего этапа. Владелец спросил «докажи, что статус соответствует плану» —
# и доказать было нечем: гейт судил КОД тридцатью двумя правилами, а строку,
# по которой читают состояние, не судил никто.
#
# ПОЧЕМУ ЭТО НЕ МЕЛОЧЬ. Живая строка — единственное место, откуда человек (и
# следующий агент) узнаёт, где работа стоит. Устаревшая строка не молчит, она
# ГОВОРИТ НЕВЕРНОЕ: «Э1 идёт» читается как «Э2 не начат». Цена — не косметика,
# а решения, принятые по неверной карте.
#
# ПРАВИЛО: дата в маркере живой строки (`на ГГГГ-ММ-ДД`) отстаёт от даты
# последнего коммита, тронувшего novac/src, не более чем на LAG дней.
# LAG = 2: строка обязана ехать со слиянием, но один прогон гейта, ночь и
# утренний пуш — это не отставание, а нормальный ритм работы. Ноль дней сделал
# бы красным любой коммит кода до правки текста и научил бы обходить страж.
#
# ПРОВЕРЯЕТ: `git log -1` по novac/src против всех дат в маркерах живых строк
# плана 274. Маркеров нет вовсе — красный: правило исчезло из документа.
# Репозиторий без истории (архив, tarball) — честное «судить нечего».
#
# НЕ ПРОВЕРЯЕТ: ПРАВДУ живой строки — что в ней написано именно то, что
# сделано. Это не машинный вопрос, и страж его не изображает: он держит только
# то, что дата свежая, а значит текст кто-то перечитал.
#
# $1 — корень репозитория (default: вычислить от себя);
# $2 — override даты последнего коммита кода (шов самотеста, ГГГГ-ММ-ДД).

set -u

NAME="check-novac-plan-liveline"
ROOT="${1:-$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)}"
PLAN="$ROOT/docs/plans/274-novac-self-hosted-compiler.md"
LAG=2

if [ ! -f "$PLAN" ]; then
    echo "$NAME ok: судить нечего (нет $PLAN)"
    exit 0
fi

if [ -n "${2:-}" ]; then
    CODE_DATE="$2"
else
    CODE_DATE=$(git -C "$ROOT" log -1 --format=%ad --date=short -- novac/src 2>/dev/null)
fi
if [ -z "$CODE_DATE" ]; then
    echo "$NAME ok: судить нечего (нет истории git по novac/src)"
    exit 0
fi

# ТОЛЬКО строки, которые сами называют себя живыми. Первая редакция стража
# брала любую дату документа и зазеленела на дате из соседнего раздела, пока
# живая строка стояла четырёхдневной давности: страж не промолчал, он сказал
# «свежо». Дата ищется в той же строке, где стоит слово — иначе судится не то.
LIVE=$(grep -n 'живая строка' "$PLAN" || true)
if [ -z "$LIVE" ]; then
    echo "$NAME: FAIL — в плане нет ни одной живой строки" >&2
    echo "  Правило «обновляется тем же слиянием, что и код» живёт в этих строках;" >&2
    echo "  без них состояние работ читать неоткуда." >&2
    exit 1
fi

DATES=$(printf '%s\n' "$LIVE" | grep -oE 'на [0-9]{4}-[0-9]{2}-[0-9]{2}' | sed 's/^на //' | sort -u)
if [ -z "$DATES" ]; then
    echo "$NAME: FAIL — у живой строки нет маркера даты (\`на ГГГГ-ММ-ДД\`)" >&2
    printf '%s\n' "$LIVE" | head -n 3 >&2
    echo "  Без даты «живая» — это слово, а не свойство: проверить нечем." >&2
    exit 1
fi

# Судятся ВСЕ живые строки: каждая описывает свой этап, и отставшая врёт про
# свой. Этап закрыт — строка перестаёт называться живой, тогда и не судится.
STALEST=$(printf '%s\n' "$DATES" | sort | head -n 1)
NEWEST="$STALEST"

d2e() { printf '%s\n' "$1" | tr -d '-'; }
DIFF_DAYS=$(python -c "
import datetime, sys
a = datetime.date.fromisoformat(sys.argv[1])
b = datetime.date.fromisoformat(sys.argv[2])
print((a - b).days)
" "$CODE_DATE" "$NEWEST" 2>/dev/null)

case "${DIFF_DAYS:-}" in
    ''|*[!0-9-]*) echo "$NAME: FAIL — не удалось сравнить даты ($CODE_DATE vs $NEWEST)" >&2; exit 1 ;;
esac

if [ "$DIFF_DAYS" -gt "$LAG" ]; then
    echo "$NAME: FAIL — живая строка плана отстала от кода на $DIFF_DAYS дней (предел $LAG)" >&2
    echo "  последний коммит в novac/src: $CODE_DATE" >&2
    echo "  самый свежий маркер в плане:  $NEWEST" >&2
    echo "  План 274 требует от этой строки обновления ТЕМ ЖЕ слиянием, что и код." >&2
    echo "  Устаревшая строка не молчит — она говорит неверное, и по ней принимают" >&2
    echo "  решения. Обновить текст и дату маркера в этом же слиянии." >&2
    exit 1
fi

echo "$NAME ok: живая строка плана свежа (маркер $NEWEST, код $CODE_DATE, отставание $DIFF_DAYS дн. при пределе $LAG)"
exit 0
