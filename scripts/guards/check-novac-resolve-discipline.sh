#!/bin/sh
# scripts/guards/check-novac-resolve-discipline.sh — два антипаттерна
# резолва, оба — правила владельца 2026-08-14.
#
# ПРАВИЛО 1 (скорость компиляции — верхний приоритет; число типов
# неограничено): резолв «имя → id» НЕ линейным перебором. Все str→id карты
# живут в одной двери names.NameTable (O(1)); цикл с сравнением `== name`
# вне names/ — красный.
#
# ПРАВИЛО 2 (класс №652 — тихий int-дефолт породил семью багов текущего
# компилятора): промах резолва не имеет права молча становиться int.
# Неизвестное — это ice() (инвариант сломан ПОСЛЕ чистого check) либо
# честная диагностика В check; «return T_INT» за проверкой `< 0` и
# хвост-выражения `T_INT`/`"nova_int"` — красные.
#
# ПРОВЕРЯЕТ грепом по novac/src/**/*.nv:
#   * вне names/: '== name' / '== fname' (канонические имена параметра
#     резолва; конвенция закреплена этим стражем);
#   * везде: '< 0' и 'return T_INT' на одной строке; голые хвосты
#     '^T_INT$' / '^"nova_int"$'.
# НЕ ПРОВЕРЯЕТ: доказанные int-ветки (`return T_INT` после проверки
# IntLit — легитимен и не матчится), переименованный параметр (ревью),
# семантику ice-веток. Эвристика расширяется по прецедентам — как все
# novac-стражи.
#
# Реестр правил: план 274 §10.3/§10.3а (каждое правило — против своего
# стража); подплан 274.3 — классы находок ревью и защита от них.
# $1 — корень репозитория; $2 — override сканируемой директории (самотест).
# Проверялся: Windows (Git Bash), 2026-08-14.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-resolve-discipline

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

# ОДИН проход awk (2026-08-19): прежняя редакция поднимала до шести
# процессов на файл -- около двухсот на дерево, 15.6 секунды стены. Правила
# ниже те же, слово в слово, и по тем же причинам, что записаны выше.
BAD=$(find "$SRC" -type f -name '*.nv' | sort | xargs awk -v SRC="$SRC" '
    FNR == 1 {
        rel = FILENAME; sub("^" SRC "/", "", rel)
        in_names = (rel ~ /^names\// || rel ~ /\/names\//)
    }
    {
        line = $0; sub(/\r$/, "", line)
        # Комментарии не судятся: доккомментарий, ЦИТИРУЮЩИЙ запрещённую
        # форму, краснел (правка 2026-08-17).
        is_comment = (line ~ /^[[:space:]]*\/\//)
        if (!in_names && !is_comment && line ~ /[=!]= (name|fname)([^A-Za-z0-9_]|$)/)
            printf "  %s:%d:%s — линейный резолв сравнением имён (дверь — names.NameTable)\n", rel, FNR, line
        if (line ~ /< 0.*return T_INT/ || line ~ /< 0.*return 0 }/)
            printf "  %s:%d:%s — промах резолва становится тихим дефолтом (класс №652)\n", rel, FNR, line
        if (line ~ /^[[:space:]]*(T_INT|"nova_int")[[:space:]]*$/)
            printf "  %s:%d:%s — хвост-дефолт вместо честного отказа\n", rel, FNR, line
        if (line ~ /^[[:space:]]*return (T_INT|T_STR|T_BOOL|T_F64)[[:space:]]*$/)
            printf "  %s:%d:%s — остаточная ветка решает тип (хвост обязан быть ice)\n", rel, FNR, line
    }
')

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — дисциплина резолва нарушена:" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Резолв имя→id — только через names.NameTable (O(1));" >&2
    echo "  промах резолва — ice()/диагностика в check, НИКОГДА не тихий int." >&2
    exit 1
fi
N=$(find "$SRC" -type f -name '*.nv' | wc -l | tr -d '[:space:]')
echo "$NAME ok: файлов .nv: $N, линейных сканов и тихих int-дефолтов: 0"
exit 0
