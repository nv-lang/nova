# -*- coding: utf-8 -*-
"""Ядро check-registry-single-verdict: одна строка реестра — ОДИН действующий
вердикт и ОДИН действующий статус.

ЗАЧЕМ. Строки реестра дописываются в хвост: расследование продолжилось, вердикт
изменился, приписка легла в конец. Человек читает ПОСЛЕДНЕЕ и видит правду.
Сканеры (`registry-routes-scan.py` и любой будущий) читают ПЕРВОЕ вхождение —
и видят вердикт месячной давности. Строка при этом выглядит безупречно.

ЧТО ЭТО СТОИЛО, замер 2026-08-18: СЕМЬ строк несли по два-три вердикта
«БЛОКИРУЕТ ТЕГ», пять из них ПРОТИВОРЕЧИВЫЕ (ДА против НЕТ), и ТРИДЦАТЬ СЕМЬ
строк — по два `Статус:`. Следствия обе стороны:
  * счёт блокеров тега был ЗАВЫШЕН на пять (67 против настоящих 62) — три
    строки со снятым вердиктом продолжали числиться блокерами;
  * #611, #660, #662 числились «K1 без маршрута», хотя ЗАКРЫТЫ: машина читала
    их первый, давно устаревший статус;
  * и наоборот — четыре ПЕРЕОТКРЫТЫЕ строки (446, 447, 452, 465) машина
    считала закрытыми и не показывала вовсе.
То есть заглавные числа релиза врали в ОБЕ стороны одновременно.

КАК ПИСАТЬ ПРАВИЛЬНО. Вердикт меняется НА МЕСТЕ, а прежний остаётся летописью
без маркера: `ТЕГ БЛОКИРОВАЛ (историческая запись): …` и `Статус был: …`.
История сохраняется дословно, притязание на действующий ответ — только у
одного вхождения.

НОЛЬ, БЕЗ ХРАПОВИКА: после уборки 2026-08-18 дублей ноль, и второй такой
попасть в реестр не должен — цена ошибки не в опрятности, а в том, что по этим
числам судят о готовности тега.
"""
import io
import os
import re
import sys

TARGET = os.path.join("docs", "plans", "221.1-bug-sweep.md")

MARK_BLOCK = u"БЛОКИРУЕТ ТЕГ:"
MARK_STATUS = u"Статус:"
ROW = re.compile(r"^\|\s*(\d+)\s*\|")
# Код-вставка markdown: цитата маркера, а не сам маркер.
INLINE_CODE = re.compile(r"`[^`]*`")


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="backslashreplace")
    except Exception:
        pass

    root = sys.argv[1] if len(sys.argv) > 1 else "."
    path = os.path.join(root, TARGET)
    w = sys.stdout.write

    if not os.path.isfile(path):
        w("MISSING %s\n" % TARGET.replace(os.sep, "/"))
        w("dup_verdict=-1\ndup_status=-1\n")
        return 1

    dup_v = 0
    dup_s = 0
    for line in io.open(path, encoding="utf-8", errors="replace"):
        m = ROW.match(line)
        if not m:
            continue
        num = m.group(1)
        # ЦИТАТА — НЕ ВЕРДИКТ. Строка, объясняющая само это правило, неизбежно
        # называет маркеры по имени: «строк с двумя `Статус:`». Счётчик,
        # принимающий цитату за утверждение, соврал бы ровно в ту сторону,
        # против которой заведён (тот же урок, что с комментарием в
        # `bare-type-lookup-scan`). Код-вставки в обратных апострофах
        # вырезаются до подсчёта.
        bare = INLINE_CODE.sub(u" ", line)
        nv = bare.count(MARK_BLOCK)
        ns = bare.count(MARK_STATUS)
        if nv > 1:
            dup_v += 1
            w("row %s: %d verdicts 'BLOCKS TAG'\n" % (num, nv))
        if ns > 1:
            dup_s += 1
            w("row %s: %d markers 'Status'\n" % (num, ns))
    w("dup_verdict=%d\n" % dup_v)
    w("dup_status=%d\n" % dup_s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
