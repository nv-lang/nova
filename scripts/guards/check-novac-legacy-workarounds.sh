#!/bin/sh
# scripts/guards/check-novac-legacy-workarounds.sh — форма обхода багов
# оракула (легаси-компилятора) в novac/** нормирована (план 274 §1.5,
# развилка владельца 2026-08-14: «фиксить в текущем ИЛИ переписать на nv с
# пометкой»). Имя маркера — LEGACY, в словаре проекта («легаси» = текущий
# компилятор, корзина bug-legacy реестра расхождений); переименован из
# ORACLE решением владельца (ассоциации с БД).
#
# ПРАВИЛО (что нормирует и откуда: план 274 §1.4/§1.5)
#   A (фоссилизация): каждый номерной маркер [LEGACY-#NNN] в novac обязан
#     ссылаться на баг, чья строка есть в реестре №221.1 и НЕ закрыта.
#     Маркер закрытого бага — красный: фикс-волна оракула снимает обходы той
#     же волной (греп на ноль входит в её приёмку).
#   B (атрибуция): самоистекающий маркер EXPECT_CC_ERROR в novac — это обход
#     бага оракула; файл-носитель обязан нести маркер [LEGACY-#…], иначе
#     счётчик носителей (вход в веху недели §1.4) слеп к этому обходу.
#   C (номер не бывает вечным «TBD»): носитель заводится формой
#     [LEGACY-#TBD-<slug>], когда номера ещё нет — номер выдаёт интегратор
#     (конвенция «номера маркеров не брать самому»). Такой носитель старше
#     TBD_MAX_DAYS суток — красный: это не «пока нет номера», а зависшая
#     заявка.
#
# ПРОВЕРЯЕТ
#   * обе живые формы маркера: [LEGACY-#123] и [LEGACY-#TBD-<slug>];
#   * номерные — против строки реестра «| N |»: строка есть и в ней нет
#     слова ЗАКРЫТ в ЛЮБОЙ форме («Статус: ЗАКРЫТ», «✅ ЗАКРЫТ 2026-08-14»,
#     «✅ ЗАКРЫТО …» — реестр несёт все три);
#   * возраст каждого #TBD-носителя по дате его строки (git blame -L,
#     поле author-time) против порога TBD_MAX_DAYS;
#   * каждый файл с EXPECT_CC_ERROR несёт маркер (любой из двух форм);
#   * ПЕЧАТАЕТ ВСЕГДА строку-счётчик носителей (и сколько из них #TBD) —
#     это машинное число «налога оракула» для вехи недели §1.4; печатается
#     и на зелёном, и на красном прогоне.
#
# НЕ ПРОВЕРЯЕТ
#   * обходы без маркеров и вне самоистекающей формы (словесный обход машине
#     не виден — на то ревью);
#   * честность самих маркеров EXPECT_* (их держит раннер: маркер истекает
#     сам);
#   * СМЫСЛ слова ЗАКРЫТ в строке реестра: детектор грубый — упоминание
#     ЗАКРЫТ где угодно в строке записи считается закрытием. Выбор
#     сознательный: ложный красный тут дешевле слепоты (до 2026-08-15
#     детектор искал точную фразу «Статус: ЗАКРЫТ» и не видел 70% реестра);
#   * возраст #TBD в файле, которого git не знает (новый/незакоммиченный,
#     а также прогон вне репозитория): blame даты не даёт — такой носитель
#     считается свежим и стареть начнёт с первого коммита;
#   * соответствие <slug> чему бы то ни было — slug свободный.
#
# $1 — корень репозитория (default: вычислить от себя).
# env NOVA_LEGACY_TBD_TIME — для самотеста: подменяет определение даты
#     строки (git blame) на эту метку unix-времени в секундах для ВСЕХ
#     #TBD-носителей; так самотест строит красный случай «протухший TBD»
#     на подложке, где никакого git нет.
#
# Проверялся: Windows (Git Bash), 2026-08-15.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
NAME=check-novac-legacy-workarounds

SRC="$ROOT/novac"
REG="$ROOT/docs/plans/221.1-bug-sweep.md"
# Обе живые формы носителя: номерная и заявка на номер.
MARK_RE='\[LEGACY-#(TBD-[A-Za-z0-9._-]+|[0-9]+)\]'
TBD_MAX_DAYS=3

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (novac ещё нет)"
    exit 0
fi
if [ ! -f "$REG" ]; then
    echo "$NAME: FAIL — реестра $REG нет, маркеры не сверить" >&2
    exit 1
fi

TMPD=$(mktemp -d 2>/dev/null) || TMPD="${TMPDIR:-/tmp}/$NAME.$$"
mkdir -p "$TMPD" || exit 1
trap 'rm -rf "$TMPD"' EXIT HUP INT TERM

HITS="$TMPD/hits"
grep -rnoE "$MARK_RE" "$SRC" 2>/dev/null | sort > "$HITS" || true

# Дата строки-носителя. Путь может содержать двоеточие (d:/…), поэтому
# разбор идёт справа параметрическими подстановками, а не cut -d:.
marker_time() {
    if [ -n "${NOVA_LEGACY_TBD_TIME:-}" ]; then
        # Самотестовая дверь — ГРОМКАЯ (274.3/F7): подмена времени должна быть
        # видна в логе гейта, иначе правило C глушится молча.
        echo "$NAME: ВНИМАНИЕ — возраст #TBD ПОДМЕНЁН через NOVA_LEGACY_TBD_TIME (самотест)" >&2
        printf '%s\n' "$NOVA_LEGACY_TBD_TIME"
        return 0
    fi
    # Возраст маркера — от ПЕРВОГО появления слага в истории, а не от даты
    # строки (адверсарная проверка 274.3/F7: git blame обнулял часы при любой
    # правке строки — переформатировал комментарий, и трёхдневный счётчик
    # начинался заново). `git log -S<слаг>` находит коммит, добавивший слаг;
    # последний в списке (--reverse не нужен: берём хвост) — первое появление.
    _slug="$3"
    if [ -n "$_slug" ]; then
        _t=$(git -C "$ROOT" log -S"$_slug" --format=%at -- "$SRC" 2>/dev/null | tail -1)
        [ -n "$_t" ] && { printf '%s\n' "$_t"; return 0; }
    fi
    git -C "$ROOT" blame -L "$2,$2" --porcelain -- "$1" 2>/dev/null \
        | sed -n 's/^author-time \([0-9][0-9]*\)$/\1/p' | head -1
}

BAD=0
NOW=$(date +%s)

# --- Счётчик «налог оракула» --------------------------------------------------
MARKS=$(wc -l < "$HITS" | tr -d ' ')
TBD_N=$(grep -c '\[LEGACY-#TBD-' "$HITS")
NUM_N=$((MARKS - TBD_N))
FILES=$(sed 's/:[0-9][0-9]*:\[LEGACY-#[^]]*\]$//' "$HITS" | sort -u | grep -c . )

# --- Правило C: возраст заявок на номер ---------------------------------------
OLDEST=-1
while IFS= read -r hit; do
    [ -n "$hit" ] || continue
    case "$hit" in
        *'[LEGACY-#TBD-'*) ;;
        *) continue ;;
    esac
    MARKER=${hit##*:}
    REST=${hit%:*}
    LN=${REST##*:}
    F=${REST%:*}
    T=$(marker_time "$F" "$LN" "$MARKER")
    [ -n "$T" ] || continue
    AGE=$(( (NOW - T) / 86400 ))
    [ "$AGE" -ge 0 ] || AGE=0
    [ "$AGE" -le "$OLDEST" ] || OLDEST=$AGE
    if [ "$AGE" -gt "$TBD_MAX_DAYS" ]; then
        echo "$NAME: FAIL — $MARKER живёт без номера $AGE сут (порог $TBD_MAX_DAYS): $F:$LN" >&2
        echo "  номер обязан прийти от интегратора: эскалируй." >&2
        BAD=1
    fi
done < "$HITS"

# --- Правило A: номерные маркеры против реестра -------------------------------
NUMS=$(sed -n 's/.*\[LEGACY-#\([0-9][0-9]*\)\].*/\1/p' "$HITS" | sort -u)
NUMC=$(printf '%s\n' "$NUMS" | grep -c . )
for n in $NUMS; do
    ROW=$(grep "^| $n |" "$REG" || true)
    if [ -z "$ROW" ]; then
        echo "$NAME: FAIL — [LEGACY-#$n] есть в novac, а строки | $n | в реестре нет" >&2
        BAD=1
        continue
    fi
    # Формы закрытия в реестре 221.1 (адверсарная проверка 274.3/F8): «Статус:
    # ЗАКРЫТ», «✅ ЗАКРЫТ 2026-08-14», «✅ ЗАКРЫТО …», «✅ **CLOSED 2026-07-24**»
    # (№55), «✅ закрыт 2026-08-02» строчными (№284). Детектор привязан к
    # МАРКЕРУ СТАТУСА (галочка или «Статус:»), а не к слову где угодно в строке:
    # голое `grep 'ЗАКРЫТ'` красило №371 («…по багу, ЗАКРЫТОМУ 2026-07-21» —
    # проза о ЧУЖОМ баге), а регистронезависимое без якоря покрасило бы ещё 18
    # строк со словами «не закрыт». Отрицание снимает срабатывание явно.
    # ЛОВУШКА (стоила трёх красных самотестов 2026-08-15): под `export LC_ALL=C`
    # у `grep -i` НЕТ свёртки регистра для кириллицы — «ЗАКРЫТ» не совпадает с
    # шаблоном «закрыт». Поэтому формы перечислены явно, а не через -i.
    if printf '%s\n' "$ROW" | grep -qE '(Статус:[[:space:]]*(ЗАКРЫТ|Закрыт|закрыт)|✅[^|]{0,40}(ЗАКРЫТ|ЗАКРЫТО|ЗАКРЫТА|Закрыт|закрыт|CLOSED|Closed|closed|DONE|Done|done))' \
       && ! printf '%s\n' "$ROW" | grep -qE '(не закрыт|НЕ ЗАКРЫТ|Не закрыт)'; then
        echo "$NAME: FAIL — [LEGACY-#$n] жив в novac, а баг №$n в реестре ЗАКРЫТ:" >&2
        grep -rn "\[LEGACY-#$n\]" "$SRC" | head -5 | sed 's/^/    /' >&2
        echo "  Фикс-волна оракула снимает обходы той же волной (§1.5):" >&2
        echo "  греп [LEGACY-#$n] по novac на ноль — часть её приёмки." >&2
        BAD=1
    fi
done

# --- Правило B: самоистекающая форма обязана нести атрибуцию ------------------
grep -rl 'EXPECT_CC_ERROR' "$SRC" 2>/dev/null | sort > "$TMPD/expect" || true
while IFS= read -r f; do
    [ -n "$f" ] || continue
    if ! grep -Eq "$MARK_RE" "$f"; then
        echo "$NAME: FAIL — $f несёт EXPECT_CC_ERROR без маркера [LEGACY-#NNN] / [LEGACY-#TBD-<slug>]" >&2
        echo "  Самоистекающий обход — тоже обход: без атрибуции счётчик" >&2
        echo "  носителей (веха недели, §1.4/§1.5) его не видит." >&2
        BAD=1
    fi
done < "$TMPD/expect"

# --- Итог: счётчик печатается всегда ------------------------------------------
if [ "$TBD_N" -eq 0 ]; then
    AGE_TXT="нет"
elif [ "$OLDEST" -ge 0 ]; then
    AGE_TXT="$TBD_N, старейший $OLDEST сут при пороге $TBD_MAX_DAYS"
else
    AGE_TXT="$TBD_N, возраст н/д (git даты не дал)"
fi
COUNTER="налог оракула — носителей $MARKS в $FILES файлах; из них #TBD: $AGE_TXT; номерных $NUM_N на $NUMC багов реестра"

if [ "$BAD" -eq 0 ]; then
    echo "$NAME ok: $COUNTER"
    exit 0
fi
echo "$NAME: $COUNTER"
exit 1
