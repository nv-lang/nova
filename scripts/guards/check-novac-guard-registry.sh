#!/bin/sh
# scripts/guards/check-novac-guard-registry.sh — МЕТА-СТРАЖ реестра стражей
# novac: таблица аудита «каждое правило — под своим стражем» обязана сходиться
# с каталогом стражей, с гейтом и с каталогом самотестов. За два дня работы
# 274.3 эти четыре списка разошлись молча. Карта стражей, разошедшаяся с
# реальностью, — тот же класс дефекта, что мёртвый страж (реестр 221.1 №519),
# только этажом выше: врёт не механизм, а список механизмов, и приёмка по нему
# считает закрытым то, чего нет.
#
# ПРАВИЛО (что нормирует и откуда). План docs/plans/274-novac-self-hosted-
# compiler.md §10.3 («каждому пункту конвенций — свой страж; каждому стражу —
# самотест») и §10.3а («сводный аудит: каждое правило — против своего стража»),
# плюс общая норма трёх свойств постоянного механизма (план 231 §4в:
# документирован / подключён / проверен) и правило «правило рождается вместе со
# стражем» (реестр 221.1 №636). Отсюда три машинных требования:
#   1) страж, существующий файлом, ОБЯЗАН быть вызван в scripts/gate.sh И иметь
#      самотест scripts/guards/selftest/test-<имя>.sh;
#   2) имя, названное таблицами §10.3/§10.3а, ОБЯЗАНО либо существовать файлом,
#      либо нести в своей строке маркер часов — по «правилу чтения таблицы»
#      §10.3а это законная запись «заводится на названном этапе»;
#   3) страж, существующий файлом, ОБЯЗАН иметь строку в §10.3/§10.3а —
#      правило без записи в аудите невидимо приёмке.
#
# ПРОВЕРЯЕТ: четыре множества имён вида check-novac-*.sh — (A) строки таблиц
# разделов §10.3 и §10.3а плана 274, (B) файлы scripts/guards/, (C) НЕ
# закомментированные строки scripts/gate.sh, (D) файлы scripts/guards/selftest/
# — и три требования выше. Отдельно ассертит, что оба раздела плана найдены и
# таблицы непусты: переименованный раздел иначе сделал бы стража слепым и вечно
# зелёным (тот самый класс №519).
# НЕ ПРОВЕРЯЕТ: содержание самих стражей (это их собственные самотесты);
# двунаправленность самотеста (её держат check-guard-wiring.sh и норма 254);
# упоминания стражей ВНЕ §10.3/§10.3а (реестр — только таблицы аудита, прозу
# плана судить нечем); самотест без своего стража (D без B) — печатается
# числом, но не красный: это законная форма группового самотеста на несколько
# стражей (test-check-novac-binary-guards.sh на бинарь-четвёрку).
#
# $1 — корень репозитория.
# Проверялся: Windows (Git Bash), 2026-08-15.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
NAME=check-novac-guard-registry
PLAN="$ROOT/docs/plans/274-novac-self-hosted-compiler.md"
GATE="$ROOT/scripts/gate.sh"
GUARDS="$ROOT/scripts/guards"
SELF="$GUARDS/selftest"

[ -f "$PLAN" ] || { echo "$NAME: FAIL — нет плана $PLAN" >&2; exit 1; }
[ -f "$GATE" ] || { echo "$NAME: FAIL — нет гейта $GATE" >&2; exit 1; }

T="${TMPDIR:-/tmp}/novac-guard-registry.$$"
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' 0

# --- (A) имена из таблиц §10.3 и §10.3а -------------------------------------
# Диапазон — от заголовка §10.3 до заголовка §10.4; внутри берутся только
# строки таблиц (первый символ вертикальной черты), чтобы проза раздела не
# попадала в реестр.
HEADS=$(grep -c '^### 10\.3' "$PLAN")
if [ "$HEADS" -lt 2 ]; then
    echo "$NAME: FAIL — в плане найдено $HEADS заголовков '### 10.3*', нужно 2 (§10.3 и §10.3а)" >&2
    echo "  Разделы переименованы или удалены — реестр стражей сверять не с чем. Без этого ассерта страж молча ослеп бы и вечно зеленел (класс №519)." >&2
    exit 1
fi
# Замыкающий якорь обязан существовать: без '### 10.4' sed отдаёт хвост файла
# ЦЕЛИКОМ, реестр раздувается чужими строками и правило 3 слепнет
# (адверсарная проверка 274.3/F12: ассерт был только на открывающие заголовки).
if ! grep -q '^### 10\.4\.' "$PLAN"; then
    echo "$NAME: FAIL — в плане нет заголовка '### 10.4.' — диапазон §10.3/§10.3а не замкнут, реестр разобран не будет" >&2
    exit 1
fi
# Строки таблиц раздела; кодовые заборы ``` пропускаются — иллюстрация в
# заборе не реестр (та же проверка F12).
sed -n '/^### 10\.3\./,/^### 10\.4\./p' "$PLAN" \
    | awk '/^```/ { fence = !fence; next } fence { next } /^\|/ { print }' > "$T/rows"
if [ ! -s "$T/rows" ]; then
    echo "$NAME: FAIL — таблицы §10.3/§10.3а пусты или не разобраны" >&2
    echo "  Проверь разметку: строки таблиц обязаны начинаться с вертикальной черты." >&2
    exit 1
fi

CLOCK=$(printf '\360\237\225\220')
: > "$T/a_raw"
: > "$T/a_clock_raw"
while IFS= read -r row; do
    names=$(printf '%s\n' "$row" | grep -oE 'check-novac-[a-z0-9-]+\.sh')
    [ -n "$names" ] || continue
    printf '%s\n' "$names" >> "$T/a_raw"
    case "$row" in
        *"$CLOCK"*) printf '%s\n' "$names" >> "$T/a_clock_raw" ;;
    esac
done < "$T/rows"
sort -u "$T/a_raw" > "$T/a"
sort -u "$T/a_clock_raw" > "$T/a_clock"

# --- (B) файлы стражей ------------------------------------------------------
: > "$T/b_raw"
for f in "$GUARDS"/check-novac-*.sh; do
    [ -f "$f" ] || continue
    basename "$f" >> "$T/b_raw"
done
sort -u "$T/b_raw" > "$T/b"

# --- (C) ВЫЗОВЫ в гейте ------------------------------------------------------
# Не любое упоминание имени, а строка, где страж действительно ЗАПУСКАЕТСЯ:
# `guard [--deadline N] <путь>/check-novac-X.sh` (адверсарная проверка
# 274.3/F12: упоминание в тексте fail-сообщения или в комментарии считалось
# вызовом, и страж, вынутый из гейта, оставался зелёным).
grep -v '^[[:space:]]*#' "$GATE" \
    | grep -E '^[[:space:]]*guard[[:space:]]' \
    | sed 's/||.*$//' \
    | grep -oE 'check-novac-[a-z0-9-]+\.sh' \
    | sort -u > "$T/c"

# --- (D) самотесты ----------------------------------------------------------
: > "$T/d_raw"
for f in "$SELF"/test-check-novac-*.sh; do
    [ -f "$f" ] || continue
    b=$(basename "$f")
    printf '%s\n' "${b#test-}" >> "$T/d_raw"
done
sort -u "$T/d_raw" > "$T/d"

# --- расхождения ------------------------------------------------------------
comm -23 "$T/b" "$T/c" > "$T/v_gate"                   # файл есть, вызова нет
comm -23 "$T/b" "$T/d" > "$T/v_self"                   # файл есть, самотеста нет
comm -23 "$T/a" "$T/b" > "$T/a_nofile"                 # план назвал, файла нет
comm -12 "$T/a_nofile" "$T/a_clock" > "$T/a_pending"   # ...и это законно (часы)
comm -23 "$T/a_nofile" "$T/a_clock" > "$T/v_plan"      # ...и это НЕ законно
comm -13 "$T/a" "$T/b" > "$T/v_audit"                  # файл есть, в аудите нет
comm -13 "$T/b" "$T/d" > "$T/d_orphan"                 # самотест без стража

n() { wc -l < "$1" | tr -d ' '; }
NA=$(n "$T/a"); NB=$(n "$T/b"); NC=$(n "$T/c"); ND=$(n "$T/d")
NP=$(n "$T/a_pending"); NO=$(n "$T/d_orphan")
BAD=$(( $(n "$T/v_gate") + $(n "$T/v_self") + $(n "$T/v_plan") + $(n "$T/v_audit") ))

if [ "$BAD" -ne 0 ]; then
    echo "$NAME: FAIL — реестр стражей novac разошёлся с планом/гейтом/самотестами, расхождений: $BAD" >&2
    echo "  множества: имён в плане $NA, файлов $NB, вызовов в гейте $NC, самотестов $ND" >&2
    if [ -s "$T/v_gate" ]; then
        echo "" >&2
        echo "1) СТРАЖ ЕСТЬ, НО НЕ ВЫЗВАН В scripts/gate.sh:" >&2
        sed 's|^|     |' "$T/v_gate" >&2
        echo "   Как чинить: добавить в scripts/gate.sh шаг вида" >&2
        echo '     guard "$ROOT/scripts/guards/<имя>.sh" "$ROOT" || fail "<что нарушено>"' >&2
        echo "   Незапускаемый страж хуже отсутствия: даёт ложное чувство защиты (правило владельца 2026-07-27)." >&2
    fi
    if [ -s "$T/v_self" ]; then
        echo "" >&2
        echo "2) СТРАЖ ЕСТЬ, НО НЕТ САМОТЕСТА:" >&2
        sed 's|^|     |' "$T/v_self" >&2
        echo "   Как чинить: завести scripts/guards/selftest/test-<имя>.sh на ОБА направления" >&2
        echo "   (зелёный случай И красный на подложке во временном каталоге)." >&2
        echo "   Образец — scripts/guards/selftest/test-check-novac-arch-invariants.sh." >&2
    fi
    if [ -s "$T/v_plan" ]; then
        echo "" >&2
        echo "3) ИМЯ НАЗВАНО ПЛАНОМ, ФАЙЛА НЕТ, МАРКЕРА ЭТАПА НЕТ:" >&2
        sed 's|^|     |' "$T/v_plan" >&2
        echo "   Как чинить: либо завести страж файлом, либо поставить в его строку §10.3/§10.3а" >&2
        echo "   маркер часов ('заводится на названном этапе'), либо убрать имя из таблицы," >&2
        echo "   если правило переехало к другому стражу." >&2
    fi
    if [ -s "$T/v_audit" ]; then
        echo "" >&2
        echo "4) СТРАЖ ЕСТЬ, НО ЕГО НЕТ В АУДИТЕ §10.3/§10.3а:" >&2
        sed 's|^|     |' "$T/v_audit" >&2
        echo "   Как чинить: внести строку в таблицу §10.3а плана 274 (правило | страж | статус)." >&2
        echo "   Правило без записи в аудите невидимо приёмке — аудит перестаёт быть аудитом." >&2
    fi
    echo "" >&2
    echo "План: docs/plans/274-novac-self-hosted-compiler.md §10.3, §10.3а." >&2
    exit 1
fi

echo "$NAME ok: имён в плане §10.3/§10.3а $NA (ждут этапа под маркером $NP), файлов стражей $NB, вызовов в gate.sh $NC, самотестов $ND (без своего стража $NO), расхождений 0"
exit 0
