#!/usr/bin/env bash
# scripts/guards/check-binary-not-busy.sh — общий бинарь ЭТОГО дерева не занят
# чужим прогоном.
#
# План: docs/plans/221.1-bug-sweep.md, строка №1098 (реестр 221.1), первая
# работа маршрута.
#
# ЧТО ЛОВИТ. На Windows работающий `.exe` нельзя перезаписать. Поэтому чужой
# запуск бинаря ЭТОГО дерева — даже двухсекундный `nova check` — роняет шаг
# `cargo build --release` идущего гейта.
#
# ЦЕНА БЕЗДЕЙСТВИЯ ИЗМЕРЕНА: ТРИ прогона яруса push (25-35 минут каждый)
# потеряны за сутки. Каждый раз отказ приходил ЧЕРЕЗ МИНУТУ сборки и назывался
# `os error 5` — то есть ПРАВАМИ ДОСТУПА, которых никто не менял. Причина не
# измерялась, а подразумевалась, и разбирающий шёл не туда.
#
# ИЩЕТСЯ АБСОЛЮТНЫЙ ПУТЬ, И ЭТО НЕ ПЕДАНТИЗМ. Первая редакция искала
# относительный хвост `nova-cli/target/release/nova` — и на первом же живом
# применении покраснела на СОСЕДНЕМ worktree (`nova-p274/nova-cli/...`), чей
# бинарь этой сборке не мешает вовсе: хвост у всех деревьев одинаков. То есть
# страж мерил НАПИСАНИЕ пути вместо предмета — «держат ли МОЙ файл». Ровно тот
# класс, ради которого заведены №1088 и №1098.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ СТРАЖЕМ, А НЕ СТРОКАМИ В ГЕЙТЕ. Проба в обе стороны на
# встроенной логике невозможна: за 300 секунд ярус push до шага сборки НЕ
# ДОХОДИТ (замер 2026-09-14). Логика внутри гейта проверяема только полным
# прогоном (followup `[M-mega-known-red-inline]`); у стража есть предмет, и
# самотест натравливает его на живой процесс за секунду.
#
# `$1` — корень дерева. `$2` — override АБСОЛЮТНОГО пути к бинарю (шов
# самотеста).
#
# НЕ WINDOWS — НЕ ПРЕДМЕТ, и это сказано ВСЛУХ: на Linux запись в работающий
# файл законна, ронять там нечего. Молчаливый пропуск читался бы как
# «проверено и чисто».
set -u
export LC_ALL=C
NAME=check-binary-not-busy
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
EXE="${2:-$ROOT/nova-cli/target/release/nova}"

# `ps -W` печатает пути в msys-форме (`/d/...`), а корень мог прийти в
# windows-форме (`D:/...`). Ищем ОБЕ, иначе страж молчал бы всегда — то есть
# был бы украшением, и заметить это было бы нечем.
EXE_MSYS=$(printf '%s' "$EXE" | sed -e 's#^\([A-Za-z]\):#/\L\1#' -e 's#\\#/#g')

if ! command -v ps >/dev/null 2>&1 || ! ps -W >/dev/null 2>&1; then
    echo "$NAME ok: судить нечего (ps -W недоступен — не Windows, работающий файл перезаписывается законно)"
    exit 0
fi

BUSY=$(ps -W 2>/dev/null | grep -F -e "$EXE" -e "$EXE_MSYS" | grep -v grep || true)

if [ -z "$BUSY" ]; then
    echo "$NAME ok: бинарь этого дерева свободен, держателей 0 (искал: $EXE_MSYS)"
    exit 0
fi

N=$(printf '%s\n' "$BUSY" | grep -c .)
echo "$NAME: FAIL — бинарь ЭТОГО дерева занят чужим прогоном: держателей $N (№1098)" >&2
printf '%s\n' "$BUSY" | sed 's/^/    /' >&2
echo "    искал: $EXE_MSYS" >&2
echo "    Это НЕ права доступа и НЕ регресс сборки: перезаписать работающий" >&2
echo "    .exe на Windows нельзя, поэтому \`cargo build\` упал бы через минуту" >&2
echo "    с \`os error 5\` — отказом, называющим не свою причину." >&2
echo "    Договорись о слоте и повтори. Правило (№1098): пока идёт чужой гейт," >&2
echo "    бинарь ЭТОГО дерева не ЗАПУСКАЕТСЯ вообще — запрет на ВЛАДЕНИЕ файлом," >&2
echo "    а не на нагрузку; двухсекундный check роняет сборку так же, как долгий." >&2
echo "    Бинарь СОСЕДНЕГО worktree предметом НЕ является и здесь не считается." >&2
exit 1
