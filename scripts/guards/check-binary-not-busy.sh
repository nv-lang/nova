#!/usr/bin/env bash
# scripts/guards/check-binary-not-busy.sh — общий бинарь не занят чужим прогоном.
#
# План: docs/plans/221.1-bug-sweep.md, строка №1098 (реестр 221.1), первая
# работа маршрута.
#
# ЧТО ЛОВИТ. На Windows работающий `.exe` нельзя перезаписать. Поэтому ЛЮБОЙ
# чужой запуск общего бинаря — даже двухсекундный `nova check` — роняет шаг
# `cargo build --release` чужого гейта.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ СТРАЖЕМ, А НЕ СТРОКАМИ В ГЕЙТЕ. Первая редакция стояла
# внутри `gate.sh` перед сборкой, и проверить её было нечем: проба в обе
# стороны упёрлась в то, что за 300 секунд ярус push до шага сборки НЕ ДОХОДИТ
# (замер 2026-09-14). Логика, живущая внутри гейта, проверяема только полным
# прогоном — это уже записано followup'ом `[M-mega-known-red-inline]`, и второй
# раз наступать на него незачем. У стража есть ПРЕДМЕТ, и его можно натравить
# за секунду.
#
# ЦЕНА БЕЗДЕЙСТВИЯ ИЗМЕРЕНА: ТРИ прогона яруса push (25-35 минут каждый)
# потеряны за сутки. Каждый раз отказ приходил ЧЕРЕЗ МИНУТУ сборки и назывался
# `os error 5` — то есть ПРАВАМИ ДОСТУПА, которых никто не менял. Причина не
# измерялась, а подразумевалась, и разбирающий шёл не туда.
#
# ПРИЗНАК ПРЕДЛОЖЕН ОКНОМ 283 и стоит в приёмке строки №1098: спросить
# процессы с путём к exe ДО сборки и отказать за секунду словами о занятости.
#
# `$1` — корень. `$2` — override пути к бинарю (шов самотеста).
#
# НЕ WINDOWS — НЕ ПРЕДМЕТ, и это сказано ВСЛУХ, а не пропущено молча: на Linux
# запись в работающий файл законна, ронять там нечего. Пропуск печатается
# строкой, иначе он читался бы как «проверено и чисто».
set -u
export LC_ALL=C
NAME=check-binary-not-busy
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
EXE_REL="${2:-nova-cli/target/release/nova}"

if ! command -v ps >/dev/null 2>&1 || ! ps -W >/dev/null 2>&1; then
    echo "$NAME ok: судить нечего (ps -W недоступен — не Windows, работающий файл перезаписывается законно)"
    exit 0
fi

BUSY=$(ps -W 2>/dev/null | grep -F "$EXE_REL" | grep -v grep || true)

if [ -z "$BUSY" ]; then
    echo "$NAME ok: общий бинарь $EXE_REL свободен, держателей 0"
    exit 0
fi

N=$(printf '%s\n' "$BUSY" | grep -c .)
echo "$NAME: FAIL — общий бинарь занят чужим прогоном: держателей $N (№1098)" >&2
printf '%s\n' "$BUSY" | sed 's/^/    /' >&2
echo "    Это НЕ права доступа и НЕ регресс сборки: перезаписать работающий" >&2
echo "    .exe на Windows нельзя, поэтому \`cargo build\` упал бы через минуту" >&2
echo "    с \`os error 5\` — отказом, называющим не свою причину." >&2
echo "    Договорись о слоте и повтори. Правило (№1098): пока идёт чужой гейт," >&2
echo "    общий бинарь не ЗАПУСКАЕТСЯ вообще — запрет на ВЛАДЕНИЕ файлом, а не" >&2
echo "    на нагрузку; двухсекундный check роняет сборку так же, как долгий прогон." >&2
exit 1
