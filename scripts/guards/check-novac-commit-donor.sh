#!/bin/sh
# scripts/guards/check-novac-commit-donor.sh — коммит, меняющий РЕШЕНИЕ в
# novac, называет донора или честно говорит, что донора нет (конвенция П27;
# владелец 2026-08-16: «в каждом коммите должно быть доказательство, что мы
# не изобретаем велосипед, а взяли то, что коммитим, у донора»).
#
# ЧТО СЧИТАЕТСЯ ДОКАЗАТЕЛЬСТВОМ, а что нет. «Взяли у rustc» — утверждение,
# его нельзя проверить, и оно тихо становится ритуальной фразой (как было с
# «идентично оракулу» до §7.0). Доказательство — УКАЗАТЕЛЬ: донор + сущность,
# по которой читающий может сравнить сам (`rustc TyCtxt`, `Go types2.Info`,
# `Zig InternPool`, `Roslyn Binder`, «Dragon Book §6.3», ссылка на статью). И
# отдельно — «донора нет» с причиной: решение может быть нашим, и скрывать
# это за фальшивым донором хуже, чем сказать прямо. Замер при заведении: из
# четырёх коммитов волны Э2-б1 донор был назван в одном, и без указателя.
#
# ПРОВЕРЯЕТ (только когда в индексе есть novac/src/*.nv БЕЗ *_test.nv — иначе
# судить нечего): сообщение коммита обязано содержать ОДНО из двух —
#   * строку `Donor:` с указателем — минимум два слова после двоеточия, из
#     которых первое — известное имя (rustc, Go, Swift, Zig, Roslyn, clang,
#     LLVM, C#, .NET, Koka, Dragon, Appel, Cooper, TAPL, paper) или любое
#     имя с сущностью через пробел; либо
#   * строку `Donor: none —` с причиной (минимум пять слов после тире).
# НЕ ПРОВЕРЯЕТ: правдивость указателя (это приёмка: страж заставляет назвать,
#   а не доказывает); коммиты, не трогающие novac/src (стражи, доки, планы,
#   тесты); что взято/не взято — это проза раздела, а не машинная половина.
#
# ГРАНИЦА ПРАВИЛА — РЕШЕНИЯ, НЕ ПРАВКИ. Починка ложняка, переименование,
# перенос строки донора не имеют и не должны его выдумывать: для них законна
# форма `Donor: none — mechanical fix, no design decision` (пять слов есть).
#
# $1 — файл с сообщением коммита; $2 — корень репозитория;
# $3 — override списка проиндексированных файлов (шов самотеста, по строке).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Без файла сообщения судить нечего (так его зовёт общий свип стражей);
# гейт зовёт с /dev/null, хук — с настоящим файлом.
MSG="${1:-}"
if [ -z "$MSG" ]; then
    echo "check-novac-commit-donor ok: судить нечего (нет файла сообщения — страж хука commit-msg)"
    exit 0
fi
ROOT="${2:-$(cd "$(dirname "$0")/../.." && pwd)}"
NAME=check-novac-commit-donor

if [ -n "$3" ]; then
    STAGED=$(printf '%s\n' "$3")
else
    STAGED=$(git -C "$ROOT" diff --cached --name-only 2>/dev/null)
fi
TOUCHES=$(printf '%s\n' "$STAGED" | grep -E '^novac/src/.*\.nv$' | grep -vE '_test\.nv$' | head -n 1)
if [ -z "$TOUCHES" ]; then
    echo "$NAME ok: судить нечего (novac/src не в индексе)"
    exit 0
fi

# первая строка сообщения — заголовок; ищем строку Donor: где угодно ниже
LINE=$(tr -d '\r' < "$MSG" | grep -E '^Donor:' | head -n 1)
if [ -z "$LINE" ]; then
    echo "$NAME: FAIL — коммит меняет novac/src, а строки 'Donor:' в сообщении нет (конвенция П27)" >&2
    echo "  Назови донора УКАЗАТЕЛЕМ, по которому можно сравнить: 'Donor: rustc TyCtxt (rustc_middle::ty), interned Ty'." >&2
    echo "  Или честно: 'Donor: none — <почему это наше решение, минимум пять слов>'." >&2
    echo "  Для механической правки без решения: 'Donor: none — mechanical fix, no design decision'." >&2
    exit 1
fi
BODY=$(printf '%s' "$LINE" | sed 's/^Donor:[[:space:]]*//')

# форма «none — причина»
if printf '%s' "$BODY" | grep -qiE '^none[[:space:]]*(—|-|--)'; then
    REASON=$(printf '%s' "$BODY" | sed -E 's/^none[[:space:]]*(—|-|--)[[:space:]]*//')
    NW=$(printf '%s' "$REASON" | wc -w | tr -d '[:space:]')
    if [ "$NW" -lt 5 ]; then
        echo "$NAME: FAIL — 'Donor: none' без причины (нужно минимум пять слов после тире): «$LINE»" >&2
        exit 1
    fi
    echo "$NAME ok: донора нет — причина названа ($NW слов)"
    exit 0
fi

# П27 п.2а: оракул донором быть не может (П25)
if printf '%s' "$BODY" | grep -qiE "oracle|orakul|nova-cli|compiler-codegen|emit_c\.rs|current compiler"; then
    echo "$NAME: FAIL — 'Donor:' называет ОРАКУЛ донором: «$LINE». Оракул — неподвижная точка ПОВЕДЕНИЯ, не образец устройства (П25); доноры формы — rustc/Go/Swift/Zig/Roslyn/clang, либо честное 'none — причина'." >&2
    exit 1
fi
# форма «донор + сущность»
NW=$(printf '%s' "$BODY" | wc -w | tr -d '[:space:]')
if [ "$NW" -lt 2 ]; then
    echo "$NAME: FAIL — 'Donor:' без сущности: «$LINE». Одно имя языка — не указатель; назови, ЧТО именно взято (структура, функция, глава)." >&2
    exit 1
fi
echo "$NAME ok: донор назван указателем — «$BODY»"
exit 0
