#!/usr/bin/env bash
# Страж: `static` не объявляется ВНУТРИ generic-функции.
#
# ЗАЧЕМ. Rust инстанцирует такой статик НА КАЖДУЮ МОНОМОРФИЗАЦИЮ — у каждого
# набора типов-параметров он СВОЙ. Для счётчика это обычно безобидно; для
# МЬЮТЕКСА смертельно: заведённый «чтобы сериализовать», он у каждого вызова
# свой и не сериализует ничего. Механизм ВЫГЛЯДИТ работающим и не работает —
# худший вид дефекта, потому что его не видно ни в обзоре, ни в зелёном
# прогоне.
#
# ЧТО ЭТО СТОИЛО (реестр №736, 2026-08-19). `with_scc_env<F: FnOnce()>` держал
# `static GUARD: Mutex<()>` внутри себя. Параметр там — ТИП ЗАМЫКАНИЯ, а он у
# каждого вызова свой: у каждого из семи тестов SCC-кэша был СВОЙ мьютекс.
# Тесты шли параллельно и портили друг другу глобальные счётчики. На CI это
# дало `v74_write_and_read_caches_isolated`: left (0, 3) против right (0, 1) —
# то есть чужие два промаха. Локально гонка выигрывалась.
#
# ТРЕТИЙ ЗА ОДИН ДЕНЬ ДЕФЕКТ ЭТОЙ СЕМЬИ: №733 (переменная среды на два теста),
# №734 (временный файл на три теста), этот (мьютекс, которого нет). Общее у
# всех — процесс один, ресурс один, тестов несколько; и все три вскрыл CI, а
# не локальный прогон, потому что там другое число ядер.
#
# НОЛЬ, БЕЗ ХРАПОВИКА: замер в день заведения дал РОВНО ОДИН случай на всё
# дерево, и он починен. Послаблять нечего — правка стоит одной строки
# (вынести статик из функции).
#
# $1 — корень. Самотест — selftest/test-check-generic-static.sh
#
# План docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения).

set -u
export LC_ALL=C

NAME="check-generic-static"
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CORE="$(dirname "$0")/generic-static-scan.py"

[ -f "$CORE" ] || { echo "$NAME: FAIL — нет ядра $CORE" >&2; exit 1; }

OUT=$(python "$CORE" "$ROOT" 2>&1)
if [ $? -ne 0 ]; then
    echo "$NAME: FAIL — ядро не отработало:" >&2
    printf '%s\n' "$OUT" | tail -5 >&2
    exit 1
fi

N=$(printf '%s\n' "$OUT" | sed -n 's/^found=\(-\{0,1\}[0-9][0-9]*\)$/\1/p' | tail -1)
case "$N" in ''|*[!0-9-]*) echo "$NAME: FAIL — ядро не вернуло число" >&2; exit 1;; esac
if [ "$N" -lt 0 ]; then
    echo "$NAME: FAIL — ядро не нашло исходников крейтов (переехали?)" >&2
    exit 1
fi

if [ "$N" -ne 0 ]; then
    echo "$NAME: FAIL — статиков внутри generic-функций: $N" >&2
    printf '%s\n' "$OUT" | grep -v '^found=' | head -12 >&2
    echo "    Такой статик инстанцируется НА КАЖДУЮ мономорфизацию: у каждого" >&2
    echo "    набора типов-параметров он СВОЙ. Мьютекс, заведённый так «чтобы" >&2
    echo "    сериализовать», не сериализует НИЧЕГО (реестр №736)." >&2
    echo "    Вынеси статик на уровень модуля — одна строка." >&2
    exit 1
fi

echo "$NAME ok: ни одного статика внутри generic-функции"
exit 0
