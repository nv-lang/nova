#!/bin/sh
# scripts/guards/check-novac-time-ledger.sh — доля «274 против 221» дня 30
# считается из леджера, а не по памяти (план 274 §1.4, поправка 2026-08-14;
# №636: правило без механизма не действует).
#
# ПРАВИЛО (план 274 §1.4 — docs/plans/274-novac-self-hosted-compiler.md — и
# ревью 274.3/F4):
#   а) каждая дата коммита, коснувшегося novac/**, начиная с первой строки
#      леджера, обязана иметь строку в docs/dev/novac-time-ledger.md. Сессии
#      амнезийны (274 §1.2): день 30 без леджера — «решение по данным» по
#      загрязнённому замеру;
#   б) доля — часть ОДНОГО рабочего дня, поэтому сумма долей за одну дату
#      не больше 1.0. За 2026-08-14 сумма была 5.55, за 2026-08-15 — 2.60:
#      метрика §1.4 («доля времени 274 против 221») от таких чисел
#      арифметически недействительна — делить не на что.
#
# ПРОВЕРЯЕТ: (а) покрытие дат коммитов novac строками леджера; (б) для каждой
# даты в таблице «| дата | класс | доля | что |» — сумму долей третьей колонки
# (ведущая тильда «~0.4» = та же оценка, снимается) против потолка 1.0,
# арифметика в awk; (в) что доля вообще число — «0.4», «~0.4», «1».
#
# НЕ ПРОВЕРЯЕТ (честно): честность самих долей — 0.05 вместо 0.5 машине
# неотличимы (⚖ суждение владельца); сессии без коммитов в novac (фикс-окна
# оракула живут в Rust-дереве — леджер их просит, машине они не видны);
# классы в колонке 2 (свободный текст); перебор меньше 1e-9 — это шум
# двоичной дроби (0.05 не представима точно), а не нарушение.
#
# $1 — корень репозитория (default: вычислить от себя).
# env NOVA_TL_DATES — для самотеста: список дат вместо git log.
#
# Проверялся: Windows (Git Bash), 2026-08-15.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
NAME=check-novac-time-ledger

LEDGER="$ROOT/docs/dev/novac-time-ledger.md"
if [ ! -d "$ROOT/novac" ] && [ -z "${NOVA_TL_DATES:-}" ] && [ ! -f "$LEDGER" ]; then
    echo "$NAME ok: судить нечего (novac ещё нет)"
    exit 0
fi
if [ ! -f "$LEDGER" ]; then
    echo "$NAME: FAIL — леджера $LEDGER нет, а novac есть (274 §1.4)" >&2
    exit 1
fi

# Начало покрытия — МИНИМАЛЬНАЯ дата таблицы, а не первая строка файла
# (адверсарная проверка 274.3/F4: при пересортировке строк «head -1» отдавал
# позднюю дату, и все коммиты раньше неё переставали судиться молча).
START=$(grep -o '^| 20[0-9][0-9]-[0-9][0-9]-[0-9][0-9] |' "$LEDGER" \
        | grep -o '20[0-9][0-9]-[0-9][0-9]-[0-9][0-9]' | sort | head -1)
if [ -z "$START" ]; then
    echo "$NAME: FAIL — в леджере нет ни одной строки с датой" >&2
    exit 1
fi

if [ -n "${NOVA_TL_DATES:-}" ]; then
    # Самотестовая дверь. ГРОМКАЯ (274.3/F4): молчаливая подмена половины
    # правила неотличима от работающей проверки — если дверь окажется в
    # окружении гейта, строка ниже это покажет в логе.
    echo "$NAME: ВНИМАНИЕ — покрытие дат ПОДМЕНЕНО через NOVA_TL_DATES (самотест): $NOVA_TL_DATES"
    DATES="$NOVA_TL_DATES"
else
    # Неглубокий клон (CI с fetch-depth 1) не имеет истории файлов: `git log --
    # novac` приписывает ВСЁ граничному коммиту и даёт его дату — страж краснел
    # на коммите, который novac не трогал (2026-08-16, первый прогон
    # gate-novac в CI). Без истории судить нечего — и это красный, не зелёный:
    # «нет данных» отличимо от «всё покрыто» только явным отказом.
    if [ -f "$(git -C "$ROOT" rev-parse --git-dir 2>/dev/null)/shallow" ]; then
        echo "$NAME: FAIL — неглубокий клон (shallow): истории novac/** нет, даты коммитов не восстановить; нужен fetch-depth 0" >&2
        exit 1
    fi
    DATES=$(git -C "$ROOT" log --format=%as -- novac 2>/dev/null | sort -u)
fi

BAD=0

# (а) покрытие: дата коммита в novac/** без строки в леджере.
for d in $DATES; do
    [ "$d" \< "$START" ] && continue
    if ! grep -q "^| $d |" "$LEDGER"; then
        echo "$NAME: FAIL — коммит в novac/** от $d без строки в леджере" >&2
        echo "  Одна строка в конце сессии: дата · класс · доля · что (274 §1.4)." >&2
        BAD=1
    fi
done

# (б,в) арифметика: сумма долей за дату <= 1.0. Колонки таблицы режем по '|',
# третья колонка — доля; «~» снимается, порядок дат сохраняем для вывода.
REPORT=$(awk '
# Кодовые заборы ``` — иллюстрация формата не должна судиться как данные
# (адверсарная проверка 274.3/F4: пример таблицы в заборе красил гейт).
/^```/ { fence = !fence; next }
fence { next }
# Строка ПОХОЖА на запись (начинается с | и несёт дату), но не разбирается
# строгим форматом — это НЕ повод молчать: тихо пропущенная строка не входит
# в сумму, и переполнение дня прячется (274.3/F4, найдено адверсарной
# проверкой). Такой случай — красный с указанием строки.
/^\|/ && /20[0-9][0-9]-[0-9][0-9]-[0-9][0-9]/ && $0 !~ /^\| 20[0-9][0-9]-[0-9][0-9]-[0-9][0-9] \|/ {
    printf "UNPARSED %d %s\n", NR, substr($0, 1, 60)
    next
}
/^\| 20[0-9][0-9]-[0-9][0-9]-[0-9][0-9] \|/ {
    split($0, f, "|")
    date = f[2]; share = f[4]
    gsub(/[ \t]/, "", date)
    gsub(/[ \t]/, "", share)
    sub(/^~/, "", share)
    if (share !~ /^[0-9]+(\.[0-9]+)?$/) {
        printf "BADVAL %s %s\n", date, (share == "" ? "<пусто>" : share)
        next
    }
    if (!(date in cnt)) { order[++nd] = date }
    sum[date] += share + 0
    cnt[date] += 1
}
END {
    max = 0
    for (i = 1; i <= nd; i++) {
        d = order[i]
        if (sum[d] > max) max = sum[d]
        if (sum[d] > 1.0 + 1e-9) printf "OVER %s %.2f %d\n", d, sum[d], cnt[d]
    }
    printf "STAT %d %.2f\n", nd, max
}
' "$LEDGER")

BADVAL=$(printf '%s\n' "$REPORT" | grep '^BADVAL ' || true)
OVER=$(printf '%s\n' "$REPORT" | grep '^OVER ' || true)
UNPARSED=$(printf '%s\n' "$REPORT" | grep '^UNPARSED ' || true)

if [ -n "$UNPARSED" ]; then
    echo "$NAME: FAIL — строка с датой не разобрана (274.3/F4: тихо пропущенная строка не входит в сумму дня):" >&2
    printf '%s\n' "$UNPARSED" | while read -r _ n rest; do
        echo "  строка $n: $rest" >&2
    done
    echo "  Формат записи строгий: «| ГГГГ-ММ-ДД | класс | доля | что |» — по одному" >&2
    echo "  пробелу вокруг разделителей (иначе арифметика дня считается не по всем" >&2
    echo "  строкам, а метрика §1.4 остаётся недействительной незаметно)." >&2
    BAD=1
fi

if [ -n "$BADVAL" ]; then
    echo "$NAME: FAIL — доля не число (колонка 3 таблицы леджера):" >&2
    printf '%s\n' "$BADVAL" | while read -r _ d v; do
        echo "  $d: доля «$v»" >&2
    done
    echo "  Формат доли: 0.4 или ~0.4 — десятичная доля рабочего дня (274 §1.4)." >&2
    BAD=1
fi

if [ -n "$OVER" ]; then
    echo "$NAME: FAIL — сумма долей за дату больше 1.0 (274 §1.4, ревью 274.3/F4):" >&2
    printf '%s\n' "$OVER" | while read -r _ d s c; do
        echo "  $d: сумма $s при $c строках (потолок 1.00)" >&2
    done
    echo "  Как чинить: доля — часть ОДНОГО рабочего дня, а не длительность сессии" >&2
    echo "  и не «сколько сделано». Пересчитать строки этой даты пропорционально до" >&2
    echo "  суммы <= 1.00 (шаг 0.05, минимум 0.05 на строку — строк НЕ терять) и" >&2
    echo "  отметить пересчёт примечанием над таблицей, как это сделано 2026-08-15" >&2
    echo "  (274.3/F4). Метрика «274 против 221» дня 30 делится на день." >&2
    BAD=1
fi

[ "$BAD" -eq 0 ] || exit 1

N=$(grep -c '^| 20' "$LEDGER" || true)
ND=$(printf '%s\n' "$REPORT" | awk '/^STAT /{print $2}')
MAXS=$(printf '%s\n' "$REPORT" | awk '/^STAT /{print $3}')
echo "$NAME ok: даты коммитов novac покрыты; строк $N, дат $ND, максимум суммы долей за дату $MAXS (потолок 1.00)"
exit 0
