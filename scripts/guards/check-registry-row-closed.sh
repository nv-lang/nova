#!/usr/bin/env bash
# Страж: КАЖДАЯ строка реестра 221.1 заканчивается замыкающей трубой.
#
# ЗАЧЕМ. В markdown замыкающая труба необязательна: `| a | b |` и `| a | b`
# рисуются одинаково. Поэтому в файле незаметно выросли ДВА стиля — 703 строки
# с трубой и 33 без. Пока строки только читают, разницы нет. Но дописывают их
# скриптом, и приём во всех скриптах один: срезать замыкающую трубу, дописать
# хвост, вернуть трубу. На строке, у которой трубы не было, этот приём съедает
# ПОСЛЕДНИЙ СИМВОЛ строки.
#
# ЧТО ЭТО СТОИЛО (2026-08-27, интегратор, на себе): у строк №467 и №387 так
# пропало по точке в конце. Гейт этого НЕ ПОЙМАЛ — он в тот прогон покраснел на
# бюджете времени, случайно, и порча всплыла только потому, что я сверил число
# полей с деревом до правки. Ни один страж реестра не судит форму строки:
# entry-shape смотрит класс и приоритет, single-verdict — вердикты и статусы,
# routes — маршруты. Форму не смотрел никто.
#
# ПОЧЕМУ ИМЕННО ЭТО ПРАВИЛО, а не «считать колонки». Число труб у строк РАЗНОЕ
# и законно разное: в тексте встречаются литеральные `|` (у №467 их пять, у
# №387 шесть, у большинства четыре), так что «ровно четыре» было бы стражем,
# который учит обходить себя. А вот «строка закрыта» — инвариант без
# исключений, и он делает общий приём дописки безопасным на ЛЮБОЙ строке.
# Это не обнаружение порчи задним числом, а снятие условия, при котором она
# возникает.
#
# ИСПОЛЬЗОВАНИЕ: bash scripts/guards/check-registry-row-closed.sh [КОРЕНЬ]
# Самотест — scripts/guards/selftest/test-check-registry-row-closed.sh
set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
REG="${NOVA_REGISTRY_FILE:-$ROOT/docs/plans/221.1-bug-sweep.md}"

if [ ! -f "$REG" ]; then
    echo "check-registry-row-closed: НЕТ ФАЙЛА РЕЕСТРА $REG — судить нечего, и это подозрительно" >&2
    exit 1
fi

BAD=$(awk '
    /^\| [0-9]+ \|/ {
        line = $0
        sub(/[ \t\r]+$/, "", line)
        if (line !~ /\|$/) {
            n = $0
            sub(/^\| /, "", n); sub(/ .*$/, "", n)
            print "    строка " n ": нет замыкающей трубы — дописка скриптом съест последний символ"
        }
    }
' "$REG")

if [ -n "$BAD" ]; then
    COUNT=$(printf '%s\n' "$BAD" | grep -c .)
    echo "check-registry-row-closed: FAIL — строк без замыкающей трубы: $COUNT" >&2
    printf '%s\n' "$BAD" >&2
    echo "    Правило: строка реестра заканчивается ' |'. Не косметика — общий приём" >&2
    echo "    дописки (срезать трубу, дописать, вернуть) на незакрытой строке" >&2
    echo "    съедает её последний символ; так пропали точки у №467 и №387." >&2
    exit 1
fi

TOTAL=$(grep -cE '^\| [0-9]+ \|' "$REG")
echo "check-registry-row-closed ok: все $TOTAL строк реестра закрыты трубой"
exit 0
