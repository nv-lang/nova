#!/bin/sh
# scripts/guards/check-hunter-mark.sh — план 278 Ф.2 + Ф.6 (регламент владельца
# 2026-08-30: треки и барьер бумажной охоты).
#
# ЗАЧЕМ. Мера плана 278 — «доля находок охотника, дошедших до реестра» — обязана
# СЧИТАТЬСЯ, а не вспоминаться, и считаться ПО ТРЕКАМ: у оракула свои охоты, у
# novac свои (решение владельца 2026-08-30), сваленные в кучу они не читаются.
# Числитель трека — метки «НАЙДЕНО ОХОТНИКОМ <дата> (<трек>)» в СТРОКАХ реестра
# docs/plans/221.1-bug-sweep.md (реестр остаётся ОДНИМ — разделение про кучи
# охоты, не про реестр). Знаменатель трека — строки «НАХОДКА |» в открытых
# отчётах docs/dev/hunts/<трек>/*.md ПЛЮС числа «находок N» из свёрнутых строк
# LEDGER.md того же трека (свёртка — check-hunter-fold.sh, формат леджера живёт
# там; формат отчёта, имени и метки живёт ЗДЕСЬ, бриф охотника ссылается сюда).
#
# БАРЬЕР БУМАЖНОЙ ОХОТЫ. Отчёт, существование которого гасит долг
# (check-hunter-debt.sh), обязан привозить ПРОБЫ В ДЕРЕВЕ:
#   - имя отчёта — строго `YYYY-MM-DD-<slug>.md` (иначе часы долга его не видят
#     и честная охота не гасит долг — ложный красный, найден панелью);
#   - рядом лежит каталог probes/<stem>/;
#   - в нём не меньше ТРЁХ НЕПУСТЫХ и РАЗЛИЧНЫХ по содержимому файлов (считаем
#     рекурсивно; пустые и дубли не в счёт) — и для отчёта «НИЧЕГО НЕ НАШЁЛ»
#     тоже: пустая охота законна, но обязана показать, ЧТО пробовала;
#   - КАЖДАЯ находка называет свою пробу 4-м полем: поле обязано быть непустым,
#     быть простым именем (без `/`, `.`, `..`) и указывать на непустую пробу
#     ВНУТРИ probes/<stem>/.
# Все четыре условия — заплатки по дырам, пробитым ЗАПУСКОМ (панель критиков
# 2026-08-30): три `touch`-файла проходили барьер; находка без 4-го поля и
# находка с цитатой «.» либо «../<чужой-stem>/p» проходили тоже.
#
# ЧТО КРАСНИТ:
#   1. метка без разбираемой даты (YYYY-MM-DD) ИЛИ без трека «(novac)»/«(oracle)»/
#      «(guards)» сразу после даты — трек ПОСЛЕ даты, чтобы регэксп даты не
#      сломался (guards — третий трек, охота на самих стражей, 2026-09-04);
#   2. отчёт без находок И без явного «НИЧЕГО НЕ НАШЁЛ» — молчание не успех (№770);
#   3. любое нарушение барьера проб или имени отчёта — бумажная охота;
#   4. меток трека больше, чем находок трека (открытых + свёрнутых) — метка
#      без отчёта-источника.
#
# ПОЧЕМУ МЕТКИ СЧИТАЮТСЯ ПО СТРОКАМ «| N |», А НЕ ГРЕПОМ ПО ФАЙЛУ: реестр — 2.5 МБ
# прозы, и честная строка, ЦИТИРУЮЩАЯ метку соседа, удваивала числитель и
# краснила гейт (класс «стражи читают прозу как данные», проверен запуском).
# Считаем СТРОКИ-ЗАПИСИ, несущие метку: одна запись — максимум одна метка.
#
# ЦИТАТА МЕТКИ ПИШЕТСЯ В БЭКТИКАХ — `НАЙДЕНО ОХОТНИКОМ <дата> (<трек>)` — и
# тогда не считается. Иначе различить «своя метка» и «пересказ соседней» нельзя
# ничем: обе живут в одной записи и одинаковы посимвольно. Форма дешёвая (проза
# реестра и так цитирует машинные строки бэктиками) и ровно та, которой проект
# уже отвечает на класс «страж читает прозу как данные».
#
# ЧИСЛО НЕ СУДИТСЯ: ноль охот — законно (0/0 зелёный). Судится ЦЕЛОСТНОСТЬ.
#
# Самотест: scripts/guards/selftest/test-check-hunter-mark.sh.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
REG="$ROOT/docs/plans/221.1-bug-sweep.md"
HUNTS_BASE="${NOVA_HUNTS_DIR:-$ROOT/docs/dev/hunts}"

rc=0
# Временные файлы — в TMPDIR, а не в дереве: страж, роняющий мусор в рабочую
# копию, сам создаёт грязь, из-за которой не проходит пуш.
T="${TMPDIR:-/tmp}/hunter-mark.$$"
mkdir -p "$T"
trap 'rm -rf "$T"' 0 2 15

# ── форма меток: дата + трек, по строкам-записям ─────────────────────────
BADMARK=$(grep -nE "НАЙДЕНО ОХОТНИКОМ" "$REG" 2>/dev/null \
    | grep -vE "НАЙДЕНО ОХОТНИКОМ 20[0-9]{2}-[0-9]{2}-[0-9]{2} \((novac|oracle|guards)\)" \
    | head -3)
if [ -n "$BADMARK" ]; then
    echo "check-hunter-mark: FAIL — строка реестра с меткой без даты (YYYY-MM-DD) или без трека «(novac)»/«(oracle)»/«(guards)» после даты:" >&2
    printf '%s\n' "$BADMARK" | cut -c1-140 | sed 's/^/    /' >&2
    rc=1
fi

# хеш содержимого пробы: sha1sum есть в msys/coreutils, cksum — везде
hash_of() {
    if command -v sha1sum >/dev/null 2>&1; then sha1sum < "$1" | cut -d' ' -f1
    else cksum < "$1" | tr -d ' '; fi
}

SUMMARY=""
for TRACK in novac oracle guards; do
    DIR="$HUNTS_BASE/$TRACK"
    if [ ! -d "$DIR" ]; then
        echo "check-hunter-mark: FAIL — нет каталога трека $DIR (треки — решение владельца 2026-08-30; guards — его слово 2026-09-04)" >&2
        rc=1
        continue
    fi

    # числитель: СТРОКИ-ЗАПИСИ реестра «| N | … метка (трек)», где метка не
    # обёрнута в бэктики (обёрнутая — цитата соседней записи, не своя метка)
    N_MARKS=$(awk -v track="$TRACK" '
        /^\| *[0-9]+ \|/ {
            line = $0
            gsub("`НАЙДЕНО ОХОТНИКОМ [0-9-]+ \\(" track "\\)`", "", line)
            if (line ~ ("НАЙДЕНО ОХОТНИКОМ [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9] \\(" track "\\)")) n++
        }
        END { print n+0 }' "$REG" 2>/dev/null)
    N_MARKS=${N_MARKS:-0}

    N_FINDINGS=0
    N_REPORTS=0
    for f in "$DIR"/*.md; do
        [ -f "$f" ] || continue
        base=${f##*/}
        [ "$base" = "LEDGER.md" ] && continue
        N_REPORTS=$((N_REPORTS + 1))
        stem=${base%.md}

        # имя отчёта — датный стем, иначе часы долга его не увидят
        if ! printf '%s' "$stem" | grep -qE "^20[0-9]{2}-[0-9]{2}-[0-9]{2}-[A-Za-z0-9._-]+$"; then
            echo "check-hunter-mark: FAIL — имя отчёта $TRACK/$base не по форме YYYY-MM-DD-<slug>.md: часы долга (Ф.5) такой файл не видят, и честная охота не погасит долг" >&2
            rc=1
        fi

        n=$(grep -cE "^НАХОДКА \|" "$f" || true)
        N_FINDINGS=$((N_FINDINGS + n))
        if [ "$n" -eq 0 ] && ! grep -qE "НИЧЕГО НЕ НАШЁЛ" "$f"; then
            echo "check-hunter-mark: FAIL — отчёт без находок И без явного «НИЧЕГО НЕ НАШЁЛ»: $TRACK/$base (молчание — не успех, №770)" >&2
            rc=1
        fi

        # барьер бумажной охоты: непустые различные пробы в дереве
        pd="$DIR/probes/$stem"
        if [ ! -d "$pd" ]; then
            echo "check-hunter-mark: FAIL — отчёт $TRACK/$base без каталога проб probes/$stem/ — отчёт без проб не свидетельство охоты" >&2
            rc=1
        else
            : > "$T/hashes"
            find "$pd" -type f -size +0c 2>/dev/null | sort | while IFS= read -r pf; do
                hash_of "$pf" >> "$T/hashes"
            done
            NP=$(sort -u "$T/hashes" | grep -c . || true)
            NP=${NP:-0}
            if [ "$NP" -lt 3 ]; then
                echo "check-hunter-mark: FAIL — в probes/$stem/ только $NP непустых РАЗЛИЧНЫХ проб(ы), нужно не меньше трёх — и пустой охоте тоже: покажи, что пробовал (пустые файлы и дубли не в счёт)" >&2
                rc=1
            fi
            # каждая находка называет свою пробу
            : > "$T/bad"
            grep -nE "^НАХОДКА \|" "$f" | while IFS= read -r hit; do
                ln=${hit%%:*}
                cited=$(printf '%s\n' "${hit#*:}" | awk -F'|' '{if (NF < 5) {print "<НЕТ-ПОЛЯ>"; exit} v=$4; gsub(/^[ \t]+|[ \t]+$/, "", v); if (v == "") v = "<ПУСТО>"; print v}')
                case "$cited" in
                    "<НЕТ-ПОЛЯ>"|"<ПУСТО>")
                        echo "check-hunter-mark: FAIL — находка $TRACK/$base:$ln не называет пробу 4-м полем ($cited): находка без пробы не находка" >&2
                        echo x >> "$T/bad" ;;
                    *[/\\]*|.|..)
                        echo "check-hunter-mark: FAIL — находка $TRACK/$base:$ln цитирует «$cited»: проба называется простым именем внутри probes/$stem/, не путём" >&2
                        echo x >> "$T/bad" ;;
                    *)
                        if [ -z "$(find "$pd/$cited" -type f -size +0c 2>/dev/null | head -1)" ]; then
                            echo "check-hunter-mark: FAIL — находка $TRACK/$base:$ln цитирует пробу «$cited», которой нет в probes/$stem/ или она пуста" >&2
                            echo x >> "$T/bad"
                        fi ;;
                esac
            done
            [ -s "$T/bad" ] && rc=1
        fi
    done

    # свёрнутые находки трека (формат леджера — дом check-hunter-fold.sh)
    N_FOLDED=0
    if [ -f "$DIR/LEDGER.md" ]; then
        N_FOLDED=$(awk -F'|' '/^СВЁРНУТО \|/ {v=$5; gsub(/[^0-9]/, "", v); s+=v} END {print s+0}' "$DIR/LEDGER.md")
    fi

    DEN=$((N_FINDINGS + N_FOLDED))
    if [ "$N_MARKS" -gt "$DEN" ]; then
        echo "check-hunter-mark: FAIL — меток трека $TRACK в реестре ($N_MARKS) больше, чем находок в его отчётах и леджере ($DEN): метка без отчёта-источника" >&2
        rc=1
    fi
    SUMMARY="$SUMMARY $TRACK: отчётов $N_REPORTS, находок $N_FINDINGS+$N_FOLDED свёрнутых, меток $N_MARKS;"
done

if [ "$rc" -eq 0 ]; then
    echo "check-hunter-mark ok:$SUMMARY мера считается грепом по строкам, пробы в дереве непусты и различны"
fi
exit "$rc"
