#!/bin/sh
# scripts/guards/check-hunter-mark.sh — план 278 Ф.2, §14.1 исследования охотника.
#
# ЗАЧЕМ. Мера плана 278 — «доля находок охотника, дошедших до реестра» — обязана
# СЧИТАТЬСЯ, а не вспоминаться: строка реестра сама не помнит, кто её принёс.
# Числитель — метки «НАЙДЕНО ОХОТНИКОМ <дата>» в docs/plans/221.1-bug-sweep.md.
# Знаменатель — строки-находки в отчётах охоты docs/dev/hunts/*.md (строка
# начинается с «НАХОДКА |»; формат задаётся брифом Ф.4 и этим стражем ВМЕСТЕ —
# два дома одного формата запрещены, поэтому бриф ссылается сюда).
#
# ЧТО КРАСНИТ (обе стороны меры должны быть исправны, иначе она врёт молча):
#   1. метка без даты или с датой, которую нельзя разобрать (YYYY-MM-DD);
#   2. отчёт охоты, в котором нет ни одной строки «НАХОДКА |» И ни строки
#      «НИЧЕГО НЕ НАШЁЛ» — молчание не успех (класс №770): отчёт обязан явно
#      сказать одно из двух;
#   3. числитель больше знаменателя — метка в реестре без отчёта-источника
#      значит, что кто-то поставил метку руками ради красивого числа.
#
# ЧИСЛО НЕ СУДИТСЯ: ноль охот — законное состояние (страж печатает 0/0 и
# зелёный). Судится ЦЕЛОСТНОСТЬ учёта. Решение «оставляем/снимаем охотника»
# принимает окно по Ф.4, глядя на эти числа.
#
# Самотест: scripts/guards/selftest/test-check-hunter-mark.sh — три подделки.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
REG="$ROOT/docs/plans/221.1-bug-sweep.md"
HUNTS_DIR="${NOVA_HUNTS_DIR:-$ROOT/docs/dev/hunts}"

rc=0

# ── числитель: метки в реестре ───────────────────────────────────────────
MARKS=$(grep -oE "НАЙДЕНО ОХОТНИКОМ[^|]*" "$REG" 2>/dev/null || true)
N_MARKS=0
if [ -n "$MARKS" ]; then
    N_MARKS=$(printf '%s\n' "$MARKS" | wc -l | tr -d ' ')
    BAD=$(printf '%s\n' "$MARKS" | grep -vcE "НАЙДЕНО ОХОТНИКОМ 20[0-9]{2}-[0-9]{2}-[0-9]{2}" || true)
    if [ "${BAD:-0}" -gt 0 ]; then
        echo "check-hunter-mark: FAIL — меток без разбираемой даты (YYYY-MM-DD): $BAD" >&2
        printf '%s\n' "$MARKS" | grep -vE "НАЙДЕНО ОХОТНИКОМ 20[0-9]{2}-[0-9]{2}-[0-9]{2}" | head -3 | sed 's/^/    /' >&2
        rc=1
    fi
fi

# ── знаменатель: строки-находки в отчётах охот ──────────────────────────
N_FINDINGS=0
N_REPORTS=0
if [ -d "$HUNTS_DIR" ]; then
    for f in "$HUNTS_DIR"/*.md; do
        [ -f "$f" ] || continue
        N_REPORTS=$((N_REPORTS + 1))
        n=$(grep -cE "^НАХОДКА \|" "$f" || true)
        N_FINDINGS=$((N_FINDINGS + n))
        if [ "$n" -eq 0 ] && ! grep -qE "НИЧЕГО НЕ НАШЁЛ" "$f"; then
            echo "check-hunter-mark: FAIL — отчёт без находок И без явного «НИЧЕГО НЕ НАШЁЛ»: ${f##*/} (молчание — не успех, №770)" >&2
            rc=1
        fi
    done
fi

# ── целостность: метка не живёт без источника ───────────────────────────
if [ "$N_MARKS" -gt "$N_FINDINGS" ]; then
    echo "check-hunter-mark: FAIL — меток в реестре ($N_MARKS) больше, чем находок в отчётах ($N_FINDINGS): метка без отчёта-источника" >&2
    rc=1
fi

if [ "$rc" -eq 0 ]; then
    echo "check-hunter-mark ok: отчётов охот $N_REPORTS, находок в них $N_FINDINGS, дошло до реестра $N_MARKS — обе половины меры считаются грепом"
fi
exit "$rc"
