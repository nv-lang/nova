#!/usr/bin/env bash
# check-runtime-cxx-clean.sh — заголовки рантайма обязаны разбираться КАК C++.
#
# ПОЧЕМУ (реестр 221.1 №1061, замер 2026-09-09). D471 ввёл в манифест пакета
# флаг `cxx = true`: с ним драйвер сборки — `clang++`/`g++`, и пакет может
# линковать C++-библиотеку. Приёмка того блока проверила, что при ОТСУТСТВИИ
# C++-драйвера отказ громкий, — она верна и зелена. Положительный путь
# «драйвер есть, флаг включён, настоящий пакет собирается» не проходил ни один
# реальный пакет, и первая же проба на `nova-duckdb` дала `CC-FAIL`. Радиус,
# измеренный компилятором, а не оценённый: 93 ошибки в ПЯТИ заголовках.
#
# Корень был один и назывался в комментарии над типом: `nova_str` объявлен
# `{ const uint8_t* ptr; int64_t len; }`, а совместимость с прежним
# `{ const char*; size_t }` обещана ПО РАЗМЕТКЕ. C с этим согласен — он сам
# приводит `char*` к `const uint8_t*` и `size_t` к `int64_t`. C++ судит ТИП, и
# обоих преобразований у него нет. Плюс сам составной литерал `(T){...}` — это
# C99, в C++ его нет вовсе.
#
# ЧТО ПРОВЕРЯЕТ. Одну трансляционную единицу, включающую `nova_rt/nova_rt.h`,
# разбирает `clang++ -std=c++17 -fsyntax-only`. Ноль ошибок — зелено.
#
# ПОЧЕМУ СТРАЖ, А НЕ ОДНОРАЗОВАЯ ПОЧИНКА. Расставить приведения значило бы
# починить сегодняшние 93 места и оставить механизм, который заведёт
# девяносто четвёртое: следующая правка рантайма сломает C++ МОЛЧА — C-корпус
# останется зелёным, а узнает об этом тот, кто через месяц соберёт пакет с
# `cxx = true`. Здесь то же правило, что и всюду: чинится класс, а держит его
# машина.
#
# ЕСЛИ C++-ДРАЙВЕРА НЕТ. Страж НЕ пропускает молча: он печатает, что не судил
# и почему, и это видно в выводе гейта. Тихий пропуск дал бы зелёную строку,
# означающую «проверено», при непроверенном — ровно тот класс, за которым
# охотятся все стражи честности в этом каталоге.
#
# ИСПОЛЬЗОВАНИЕ:
#   scripts/guards/check-runtime-cxx-clean.sh [корень-репы]
# #
# ПРОБА В ОБЕ СТОРОНЫ живёт ОДНИМ домом — в самотесте
# `scripts/guards/selftest/test-check-runtime-cxx-clean.sh`, на подложке через
# шов корня, а не на живом дереве: иначе красный самотест означал бы сразу
# и «проверка сломана», и «рантайм сломан» — два события под одним цветом.
# Внутрь стража она не встроена намеренно: самотест, живущий ВНУТРИ стража,
# не виден обходу `check-selftest-honest-count` (его область — каталог
# `selftest/`), то есть был бы честен ровно до первой правки.
#
# Выход: 0 — чисто (или честно объявленный пропуск), 1 — C++ не согласен.

set -euo pipefail

ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
CG="$ROOT/compiler-codegen"
RT="$CG/nova_rt"

if [ ! -f "$RT/nova_rt.h" ]; then
    echo "check-runtime-cxx-clean: нет $RT/nova_rt.h — судить нечего"
    exit 0
fi

# Драйвер ищется НЕ ТОЛЬКО В PATH. Замер 2026-09-09: на машине разработки
# `clang++` лежит в `C:/Program Files/LLVM/bin`, а в PATH оболочки его нет —
# страж, смотревший один PATH, объявлял бы «ПРОПУЩЕНО» КАЖДЫЙ раз и был бы
# честным по форме и бесполезным по делу. Проверка, которая всегда пропускает,
# хуже отсутствующей: она занимает место, где ожидается суждение.
#
# `NOVA_CXX` — прямое имя драйвера (и шов для пробы: имя, которого нет,
# заставляет страж дойти до ветки «драйвера нет» без порчи PATH).
# Имя названо в выводе: у компиляторов разная строгость, и вердикт без имени
# судьи не воспроизвести.
CXX_CANDIDATES="${NOVA_CXX:-clang++ g++}"
# Разделитель — двоеточие, а НЕ пробел: у «Program Files» пробел внутри имени,
# и разбиение по пробелу давало два несуществующих каталога, то есть вечный
# «драйвера нет». Поймано собственным самотестом при первом же прогоне.
CXX_DIRS="/c/Program Files/LLVM/bin:/usr/bin:/usr/local/bin:${NOVA_CXX_DIRS:-}"

CXX=""
for cand in $CXX_CANDIDATES; do
    if command -v "$cand" >/dev/null 2>&1; then
        CXX="$cand"
        break
    fi
    _oldifs="$IFS"; IFS=":"
    for d in $CXX_DIRS; do
        IFS="$_oldifs"
        [ -n "$d" ] || continue
        if [ -x "$d/$cand" ]; then
            CXX="$d/$cand"
            break
        fi
        if [ -x "$d/$cand.exe" ]; then
            CXX="$d/$cand.exe"
            break
        fi
        IFS=":"
    done
    IFS="$_oldifs"
    [ -n "$CXX" ] && break
done

if [ -z "$CXX" ]; then
    echo "check-runtime-cxx-clean: ПРОПУЩЕНО — C++-драйвер не найден (искал: $CXX_CANDIDATES)."
    echo "  Это НЕ зелёный вердикт: заголовки не судились. Поставьте C++-драйвер"
    echo "  или назовите его в NOVA_CXX, иначе флаг D471 \`cxx = true\` остаётся"
    echo "  непроверяемым на этой машине."
    exit 0
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Те же определения, что ставит настоящая сборка (test_runner.rs): без
# -DNOVA_USE_LIBUV=1 заголовки сами останавливают компиляцию своим #error,
# и страж судил бы отсутствие флага, а не совместимость с C++.
INCS=(-DNOVA_USE_LIBUV=1 -I "$CG")
VCPKG="$CG/vcpkg_installed/x64-windows-static/include"
[ -d "$VCPKG" ] && INCS+=(-I "$VCPKG")
UV="$RT/libuv/include"
[ -d "$UV" ] && INCS+=(-I "$UV")

cat > "$TMP/tu.cpp" <<'EOF'
/* Одна трансляционная единица: включить заголовки рантайма как C++ и ничего
 * больше. Ошибка здесь означает, что пакет с `cxx = true` не соберётся. */
#include "nova_rt/nova_rt.h"
int nova_cxx_probe(void) { return 0; }
EOF

OUT="$("$CXX" -std=c++17 -fsyntax-only -ferror-limit=500 "${INCS[@]}" "$TMP/tu.cpp" 2>&1)" && RC=0 || RC=$?
ERRS="$(printf '%s\n' "$OUT" | grep -c 'error:' || true)"

if [ "$RC" = "0" ]; then
    echo "check-runtime-cxx-clean ok ($CXX -std=c++17): заголовки рантайма разбираются как C++, ошибок 0"
    exit 0
fi

echo "check-runtime-cxx-clean FAIL ($CXX -std=c++17): ошибок $ERRS" >&2
printf '%s\n' "$OUT" | grep 'error:' | head -20 >&2
echo "" >&2
echo "ЧТО ЭТО ЗНАЧИТ: пакет с \`cxx = true\` (D471) не соберётся — заголовки" >&2
echo "рантайма одни на все платформы, значит это не про Windows и не про clang." >&2
echo "КАК ЧИНИТЬ: не приведением в каждом месте, а вводящей функцией —" >&2
echo "\`nova_str_of(p, n)\` вместо \`(nova_str){ p, n }\` (реестр 221.1 №1061)." >&2
exit 1
