#!/bin/sh
# scripts/guards/check-novac-no-alloc-in-lookup.sh — дверь поиска не
# аллоцирует (конвенция П18; требование владельца 2026-08-16 после разбора
# синтезированного ключа).
#
# КЛАСС, А НЕ ЗАПИСЬ. Живой случай: `FnTable`/`FieldTable` строили составной
# ключ интерполяцией — `ro key = "${owner}.${name}"` — и отдавали его двери.
# Это аллокация и форматирование на КАЖДЫЙ поиск, в самом горячем цикле
# компилятора (П14: скорость — приоритет №1). Страж строковых ключей молчал
# законно: он судит ТИПЫ таблиц (`Map[str`), а дверь `names` легальна.
# Правило поэтому шире ключа: внутри функции, которая ИЩЕТ, ничего не
# строится — ни строк, ни векторов. Составной ключ выражается цепочкой
# одноимённых строк и сравнением целых (образцы: `FnTable.row_of`,
# `FieldTable.field_type`).
#
# ПРОВЕРЯЕТ по novac/src/**/*.nv (тесты *_test.nv исключены), по функциям:
#   * функция считается ДВЕРЬЮ, если она МЕТОД ТАБЛИЦЫ (имя типа-приёмника
#     кончается на `Table`) — такие существуют ради поиска, — либо если её
#     тело содержит `.find(`/`.lookup(` и при этом она НИЧЕГО НЕ ПИШЕТ.
#     Различение по делу: дверь только СПРАШИВАЕТ, эмиттер СТРОИТ текст, и
#     строить — его работа. Признак эмиттера: `StringBuilder` в сигнатуре
#     или `@body.append(` в теле — то есть буфер ДАЛИ снаружи; локальный
#     `StringBuilder` внутри двери ролью эмиттера не считается (проверено на
#     живом ложняке: `emit_fn`/`emit_arm`
#     зовут `defs.find(name)` и законно собирают C-текст интерполяцией);
#   * внутри двери запрещены формы аллокации: интерполяция `${`, `.concat(`,
#     `StringBuilder`;
#   * дверь ОБЯЗАНА нести `#realtime nogc` — тогда запрет на аллокацию держит
#     сам компилятор (`E_REALTIME_NOGC_ALLOC`, D172 §nogc), а страж лишь
#     стережёт, чтобы пометку не сняли молча. Две сети дополняют друг друга:
#     компилятор ловит конструкторы контейнеров (`[]T.new()`), которых греп не
#     знает, а страж — сборку строк, которой нет в блэклисте (проверено пробой
#     2026-08-16: интерполяция проходит `#realtime nogc` молча).
#   * строка внутри вызова `ice(` не судится: сообщение инварианта строится
#     один раз, по дороге к падению, и это не горячий путь.
# НЕ ПРОВЕРЯЕТ: функции, которые НЕ ищут; эмиттеры (пишут текст — см. выше);
#   дверь, которая И спрашивает, И пишет (такой формы в novac нет; появится —
#   правило уточняется вместе с ней); мэнглинг (`sem/mangle.nv` по природе делает имена, и зовётся раз
#   на сущность, а не на поиск) — исключён поимённо; транзитивную горячесть
#   (функция, зовущая дверь, не судится: правило про саму дверь).
#   КОММЕНТАРИИ НЕ СУДЯТСЯ: доки нарочно цитируют снятую форму как историю.
#
# $1 — корень репозитория; $2 — override сканируемой директории (самотест).
# Проверялся: Windows (Git Bash), 2026-08-16.
export LC_ALL=C
# Корень приводится к АБСОЛЮТНОМУ пути: относительный `.` уводил поиск
# бинаря мимо цели, и страж писал «сломан раннер» о здоровом дереве
# (2026-08-18). Ложная краснота стоит дороже отсутствующей проверки:
# по ней идут искать поломку, которой нет, и в стража перестают верить.
# Если cd не удался — значение СОХРАНЯЕТСЯ как было: пустой ROOT судил бы
# корень файловой системы, а это хуже исходной болезни.
ROOT="${1:-$(dirname "$0")/../..}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd || printf '%s' "$ROOT")"
SRC="${2:-$ROOT/novac/src}"
NAME=check-novac-no-alloc-in-lookup

if [ ! -d "$SRC" ]; then
    echo "$NAME ok: судить нечего (нет $SRC)"
    exit 0
fi

NFILES=$(find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | wc -l | tr -d '[:space:]')
if [ "$NFILES" -eq 0 ]; then
    echo "$NAME ok: судить нечего (в $SRC файлов .nv: 0)"
    exit 0
fi

BAD=$(find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' ! -name 'mangle.nv' | sort | while IFS= read -r f; do
    rel=${f#"$SRC"/}
    tr -d '\r' < "$f" | awk -v rel="$rel" '
        function flush_fn() {
            if (fname == "") return
            # дверь: метод таблицы всегда; иначе — спрашивает и не пишет
            if (is_table || (asks && !writes)) is_door = 1
            if (is_door) {
                for (i = 1; i <= n; i++) {
                    printf "  %s:%d: дверь %s — %s: %s\n", rel, ln[i], fname, why[i], txt[i]
                }
                if (!has_rt && !is_mut) {
                    printf "  %s:%d: дверь %s — без пометки #realtime nogc: компилятор не проверяет её на аллокацию\n", rel, fnline, fname
                }
            }
            fname = ""; is_door = 0; is_table = 0; asks = 0; writes = 0; has_rt = 0; is_mut = 0; n = 0
        }
        # начало новой функции верхнего уровня закрывает предыдущую
        /^#realtime[[:space:]]+nogc/ { attr = 1; next }
        /^(export )?fn / {
            flush_fn()
            has_rt = attr; attr = 0
            fname = $0
            sub(/\(.*$/, "", fname)
            sub(/^(export )?fn /, "", fname)
            gsub(/[[:space:]]+$/, "", fname)
            # метод таблицы — дверь по определению, что бы ни было в теле
            fnline = NR
            # мутирующая форма (`mut @add`) регистрирует, а не ищет: пометку с
            # неё не требуем — она законно растит вектор строк
            is_mut = ($0 ~ /[[:space:]]mut[[:space:]]+@/)
            is_table = (fname ~ /^[A-Za-z0-9_]*Table[[:space:]]/ || fname ~ /^[A-Za-z0-9_]*Table$/)
            if (is_table) is_door = 1
            # эмиттер: StringBuilder в сигнатуре
            if ($0 ~ /StringBuilder/) writes = 1
        }
        /^(export )?type / { flush_fn() }
        {
            line = $0
            # снять комментарии: и целые строки, и хвост после кода
            sub(/\/\/.*$/, "", line)
            if (line ~ /^[[:space:]]*$/) next
            if (fname == "") next
            if (line ~ /\.find\(/ || line ~ /\.lookup\(/) asks = 1
            # Дверь по НАЗНАЧЕНИЮ, не только по вызову .find: функция, помеченная
            # #realtime nogc, ОБЪЯВЛЕНА дверью — и судится как дверь, что бы она ни
            # делала внутри (владелец 2026-08-16: builtin_types() строил вектор на
            # каждый вызов prim_c_name — тот индексировал массив, .find в нём не было,
            # и страж молчал). Отдельно: вызов функции-конструктора вектора
            # (`.of(`, `.new()`) внутри двери — аллокация, красный.
            if (has_rt) asks = 1
            if (line ~ /\.of\(/ || line ~ /\]\.new\(\)/) alloc_call = 1
            attr = 0
            # «пишет» = буфер ДАЛИ снаружи (поле приёмника). Локальный
            # StringBuilder внутри двери — это аллокация, а не роль эмиттера:
            # иначе дверь пряталась бы за собственным билдером (поймано
            # случаем 5 самотеста).
            if (line ~ /@body\.append\(/) writes = 1
            if (line ~ /ice\(/) next
            why_s = ""
            if (line ~ /\.of\(/ || line ~ /\]\.new\(\)/) why_s = "конструируется вектор (аллокация на каждый вызов)"
            else if (line ~ /\$\{/)             why_s = "строка собирается интерполяцией"
            else if (line ~ /\.concat\(/)  why_s = "строка склеивается concat"
            else if (line ~ /StringBuilder/) why_s = "заводится StringBuilder"
            if (why_s != "") {
                n++
                ln[n] = NR
                why[n] = why_s
                t = line
                gsub(/^[[:space:]]+/, "", t)
                txt[n] = substr(t, 1, 60)
            }
        }
        END { flush_fn() }
    '
done)

if [ -n "$BAD" ]; then
    echo "$NAME: FAIL — дверь поиска аллоцирует (конвенция П18, П14 «скорость — приоритет №1»):" >&2
    printf '%s\n' "$BAD" >&2
    echo "  Функция, которая сама спрашивает таблицу (.find/.lookup), не строит ничего." >&2
    echo "  Составной ключ — не текст: свяжи одноимённые строки полем next и сравнивай" >&2
    echo "  второй ключ целым числом при обходе цепочки (FnTable.row_of, FieldTable.field_type)." >&2
    exit 1
fi

DOORS=$(find "$SRC" -type f -name '*.nv' ! -name '*_test.nv' | xargs grep -l '\.find(\|\.lookup(' 2>/dev/null | wc -l | tr -d '[:space:]')
echo "$NAME ok: файлов .nv: $NFILES (из них с дверями поиска: $DOORS), аллокаций в дверях: 0"
exit 0
