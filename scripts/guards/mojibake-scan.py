# -*- coding: utf-8 -*-
"""Ядро check-no-mojibake.sh: печатает строки с подписью порчи текста.

Подписей ДВЕ, и они про разные происшествия. Флаг выбирает одну:

* без флага — «UTF-8 прочитан как CP1251»: текст цел, но прочитан не тем
  кодированием, и кириллица превратилась в сербско-македонский ряд. Такой
  текст ВОССТАНОВИМ обратным преобразованием (`scripts/tools/demojibake.py`);
* `--fffd` — символ-замена U+FFFD: байты УТЕРЯНЫ при перекодировке, и обратного
  преобразования нет. Восстановить можно только из истории git.

Вторая подпись добавлена 2026-09-05 (реестр 221.1 №972). До неё страж по имени
`check-no-mojibake` знал ровно одну форму порчи из двух — и вторая молча жила в
дереве: 6552 символа в восьми файлах, из них 6204 в `docs/history/
simplifications-closed.md`, куда AGENTS.md посылает агентов за закрытыми
упрощениями. Ремонтный проход `e504932dd` («восстановление cp1251-порчи»,
2026-07-19) прошёл по дереву и НЕ изменил их числа: инструмент и страж делили
одну слепую зону, поэтому починка выглядела полной.

Разбор на питоне, а не грепом, НАМЕРЕННО: образец состоит из кириллических
символов, а `grep` под `LC_ALL=C` работает побайтово и на не-ASCII образцах
ведёт себя непредсказуемо — этот класс уже стоил проекту ложных «ноль находок»
(см. шапку check-no-handwritten-plan-index.sh про классы [а-я] под LC_ALL=C).
Питон читает файл ЯВНЫМ UTF-8 и сравнивает кодовые точки.

Вывод: по строке на находку, формата `путь:номер`. Пусто — находок нет.
"""
import io
import os
import re
import sys

# Буквы сербско-македонского ряда и одиночная нижняя кавычка перед кириллицей:
# в правильном русском тексте не встречаются, а при порче появляются всегда.
SIG = re.compile(u"[ЂЃђѓћќљњїѕ]"
                 u"|‚[Ѐ-ӿ]")

# Символ-замена. Отдельным образцом, а не добавкой к SIG, чтобы число прежней
# метрики осталось СРАВНИМЫМ со своей летописью: храповик, у которого молча
# сменился предмет счёта, перестаёт мерить то, что обещал.
# Записан ЭКРАНИРОВАНИЕМ, а не литералом: литерал символа-замены сам является
# порчей, и любой инструмент, тронувший этот файл не тем кодированием, тихо
# заменил бы образец на что-то другое — страж перестал бы искать и не сказал бы
# об этом. Тот же приём, что в самотесте, где образцы задаются через python.
SIG_FFFD = re.compile(u"\ufffd")

EXTS = (".md", ".sh", ".py", ".awk", ".baseline", ".yml", ".yaml", ".toml", ".nv", ".rs")

# Ремонтный инструмент ХРАНИТ образцы порчи как данные — краснеть на нём
# значит учить обходить стража целиком.
# Файлы, которые ХРАНЯТ образцы порчи как данные. `mojibake.baseline` попал
# сюда не сразу: его летопись перечисляет буквы-подпись, и первый же прогон
# насчитал на два больше — страж нашёл сам себя. Ровно тот случай, когда
# описание проверки неотличимо от нарушения.
SKIP_FILES = ("demojibake.py", "mojibake-scan.py",
              "test-check-no-mojibake.sh", "mojibake.baseline",
              "check-no-mojibake.sh",
              # 2026-08-17: перехватчик, НЕ ДАЮЩИЙ порче случиться
              # (guard-shell-nonascii.py, PreToolUse на Bash/PowerShell).
              # В его объяснении стоит образец того, во что превращается
              # русский текст, прошедший через оболочку в cp1251 —
              # без образца объяснение не объясняет. Тот же случай, что
              # с mojibake.baseline выше.
              "guard-shell-nonascii.py")
SKIP_DIRS = ("target", ".git", "node_modules", "vcpkg_installed", ".claude")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = [a for a in sys.argv[1:] if a.startswith("--")]
    root = args[0] if args else "."
    sig = SIG_FFFD if "--fffd" in flags else SIG
    hits = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            if not f.endswith(EXTS) or f in SKIP_FILES:
                continue
            p = os.path.join(base, f)
            try:
                text = io.open(p, encoding="utf-8").read()
            except Exception:
                continue
            for i, line in enumerate(text.split(u"\n"), 1):
                if sig.search(line):
                    hits.append(u"%s:%d" % (os.path.relpath(p, root).replace("\\", "/"), i))
    out = io.open(sys.stdout.fileno(), "w", encoding="utf-8", newline="\n", closefd=False)
    for h in hits:
        out.write(h + u"\n")
    out.flush()


if __name__ == "__main__":
    main()
