#!/usr/bin/env bash
# scripts/guards/check-merge-discipline.sh
# Реестр 221.1, план 254 — docs/plans/254-process-rules-without-mechanism.md,
# П1: «в main вливается только проверенное гейтом». Повод — 75 коммитов без
# зелёного гейта (вопрос владельца 2026-08-08).
# Реестр 221.1 (класс «непроверенное копится в main»), вопрос владельца
# 2026-08-08: «почему допускаешь семьдесят пять коммитов без зелёного гейта? как
# избежать?»
#
# ЧТО СЛУЧИЛОСЬ. Интегратор вливал ветки окон в `main` по мере готовности, а
# пушил только после зелёного гейта. Гейт был красным много часов подряд (№472,
# фикстура №456, страж инвариантов, храповик роста) — и всё это время красный
# гейт закрывал ОТТОК, но не ПРИТОК. Накопилось 75 коммитов, половина из них
# трогает компилятор и рантайм: любой регресс пришлось бы искать в общей куче.
#
# ТОЧКА ПРИЛОЖЕНИЯ — СЛИЯНИЕ, А НЕ ПУШ. Ограничивать «сколько ждёт отправки»
# бессмысленно: это следствие. Ограничивать надо «сколько непроверенного влито».
# Правило: в `main` вливается только то, что прошло гейт; пока гейт красный,
# приток закрыт. Тогда большая непроверенная куча невозможна ПО ПОСТРОЕНИЮ, а не
# по памяти интегратора.
#
# КАК ЭТО ПРОВЕРЯЕТСЯ. Вердикт гейта лежит в `/tmp/gate_full.done` (пишется
# `scripts/tools/gate-bg.sh`) в виде `RC=<код> SEC=<секунды>`. Слияние в `main`
# законно, только если вердикт есть, он нулевой, и он НЕ СТАРШЕ текущего `HEAD` —
# иначе он относится к другому дереву и ничего не доказывает.
#
# ЗАЧЕМ ПРОВЕРКА СВЕЖЕСТИ. Без неё правило обходится само собой: один зелёный
# гейт недельной давности разрешал бы любые слияния вечно. Ровно тот класс
# «проверка есть, но ничего не проверяет», что №473.
#
# ИСПОЛЬЗОВАНИЕ (вызывается хуком `pre-merge-commit`, можно и вручную):
#   bash scripts/guards/check-merge-discipline.sh [КОРЕНЬ]
# ПЕРЕМЕННЫЕ:
#   NOVA_GATE_VERDICT      — путь к вердикту, по умолчанию /tmp/gate_full.done
#   NOVA_MERGE_ALLOW_RED=1 — осознанный обход (например, вливается САМ фикс
#                            красноты). Требует, чтобы причина была названа в
#                            сообщении слияния; хук её печатает в журнал.

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
VERDICT="${NOVA_GATE_VERDICT:-/tmp/gate_full.done}"
cd "$ROOT" || exit 1

BR=$(git rev-parse --abbrev-ref HEAD 2>/dev/null)
if [ "$BR" != "main" ] && [ "$BR" != "master" ]; then
    echo "check-merge-discipline: ветка '$BR' — правило касается только главной, пропуск"
    exit 0
fi

if [ "${NOVA_MERGE_ALLOW_RED:-0}" = "1" ]; then
    echo "check-merge-discipline: ОБХОД по NOVA_MERGE_ALLOW_RED=1 — причина обязана быть в сообщении слияния" >&2
    exit 0
fi

fail() {
    echo "check-merge-discipline: ОТКАЗ — $1" >&2
    echo "    В main вливается только то, что прошло гейт. Пока гейт красный," >&2
    echo "    приток закрыт: иначе непроверенное копится, и регресс придётся" >&2
    echo "    искать в общей куче (случай 2026-08-08: 75 коммитов)." >&2
    echo "    Что делать: прогнать 'bash scripts/tools/gate-bg.sh', дождаться" >&2
    echo "    зелёного, влить. Если вливается САМ фикс красноты — назови причину" >&2
    echo "    в сообщении и повтори с NOVA_MERGE_ALLOW_RED=1." >&2
    exit 1
}

[ -f "$VERDICT" ] || fail "вердикта гейта нет ($VERDICT) — дерево не проверено"

RC=$(sed -n 's/^RC=\([0-9][0-9]*\).*/\1/p' "$VERDICT" | head -1)
[ -n "${RC:-}" ] || fail "вердикт нечитаем ($VERDICT)"
[ "$RC" -eq 0 ] || fail "последний гейт КРАСНЫЙ (RC=$RC)"

# Свежесть: вердикт обязан быть НЕ СТАРШЕ последнего коммита в главной ветке.
V_TS=$(stat -c %Y "$VERDICT" 2>/dev/null)
H_TS=$(git log -1 --format=%ct HEAD 2>/dev/null)
if [ -n "${V_TS:-}" ] && [ -n "${H_TS:-}" ] && [ "$V_TS" -lt "$H_TS" ]; then
    fail "вердикт СТАРШЕ HEAD — он относится к другому дереву и ничего не доказывает"
fi

echo "check-merge-discipline ok: гейт зелёный и свежее HEAD — слияние законно"
exit 0
