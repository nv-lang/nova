#!/usr/bin/env bash
# scripts/guards/check-merge-discipline.sh
# Реестр 221.1, план 254 — docs/plans/254-process-rules-without-mechanism.md,
# П1: «в main вливается только проверенное гейтом». Повод — 75 коммитов без
# зелёного гейта (вопрос владельца 2026-08-08).
# Реестр 221.1 (класс «непроверенное копится в main»), вопрос владельца
# 2026-08-08: «почему допускаешь семьдесят пять коммитов без зелёного гейта? как
# избежать?»
#
# ЧТО СЛУЧИЛОСЬ. Интегратор вливал ветки окон в `main` по мере готовности, а
# пушил только после зелёного гейта. Гейт был красным много часов подряд (№472,
# фикстура №456, страж инвариантов, храповик роста) — и всё это время красный
# гейт закрывал ОТТОК, но не ПРИТОК. Накопилось 75 коммитов, половина из них
# трогает компилятор и рантайм: любой регресс пришлось бы искать в общей куче.
#
# ТОЧКА ПРИЛОЖЕНИЯ — СЛИЯНИЕ, А НЕ ПУШ. Ограничивать «сколько ждёт отправки»
# бессмысленно: это следствие. Ограничивать надо «сколько непроверенного влито».
# Правило: в `main` вливается только то, что прошло гейт; пока гейт красный,
# приток закрыт. Тогда большая непроверенная куча невозможна ПО ПОСТРОЕНИЮ, а не
# по памяти интегратора.
#
# КАК ЭТО ПРОВЕРЯЕТСЯ. Вердикт гейта лежит в `/tmp/gate_full.done` (пишется
# `scripts/tools/gate-bg.sh`) в виде
#   `RC=<код> SEC=<секунды> TIER=main HASH=<хеш> BRANCH=<ветка>`
# Слияние в `main` законно, только если вердикт есть, он нулевой, он НЕ СТАРШЕ
# текущего `HEAD`, он называет СВОЙ ЯРУС (и это `main`), а названный им ХЕШ
# совпадает с `HEAD` — иначе он относится к другому дереву и ничего не
# доказывает. Если слияние приносит пути яруса novac, дополнительно требуется
# зелёный и свежий вердикт `/tmp/gate_novac.done` с `TIER=novac`.
#
# ЗАЧЕМ ПРОВЕРКА СВЕЖЕСТИ. Без неё правило обходится само собой: один зелёный
# гейт недельной давности разрешал бы любые слияния вечно. Ровно тот класс
# «проверка есть, но ничего не проверяет», что №473.
#
# ЯРУС — ДОБАВЛЕНО 2026-09-06 ПО РЕЕСТРУ 221.1 №988, НА СОБСТВЕННОМ НАРУШЕНИИ.
# Свежести МАЛО. Вердикт говорил только «RC=0», и по нему нельзя было узнать
# ни КАКОЙ ярус его выдал, ни КАКОЕ дерево он судил. А ярусов два, и они судят
# РАЗНОЕ: `scripts/gate-novac.sh` зовёт 87 уникальных стражей `check-novac-*`,
# `scripts/gate.sh` — НИ ОДНОГО (два таких имени в нём есть, но оба в
# комментариях). Значит зелёный основной гейт открывал слияние ветки `novac/**`,
# которого ни один из этих 87 стражей не видел. Не гипотеза: интегратор влил так
# 7994d75ce и 7e6e6ad82, и страж не возразил, потому что возражать ему было
# нечем. Теперь вердикт обязан назвать ЯРУС и ХЕШ, а слияние, приносящее
# novac-пути, требует вердикта ОБОИХ ярусов.
#
# ПОЧЕМУ ПО `MERGE_HEAD`, А НЕ ПО ИМЕНИ ВЕТКИ. Хук `pre-merge-commit` работает
# ДО коммита слияния, когда `MERGE_HEAD` уже существует, — значит можно спросить
# у git, какие файлы слияние реально приносит, вместо догадки по имени ветки.
# Имя врёт в обе стороны: ветка `novac/x` может не трогать `novac/`, а ветка
# `fix-tests` — трогать.
#
# ПРАВИЛО «КАКИЕ ПУТИ ПРИНАДЛЕЖАТ ЯРУСУ NOVAC» СЮДА НЕ КОПИРУЕТСЯ: оно живёт в
# `scripts/tools/gate-tier-paths.sh`, откуда его берут и `push-after-gate.sh`, и
# `git-readiness.sh`. Третья копия разошлась бы с первыми двумя.
#
# ИСПОЛЬЗОВАНИЕ (вызывается хуком `pre-merge-commit`, можно и вручную):
#   bash scripts/guards/check-merge-discipline.sh [КОРЕНЬ]
# ПЕРЕМЕННЫЕ:
#   NOVA_GATE_VERDICT      — путь к вердикту ОСНОВНОГО яруса, по умолчанию
#                            /tmp/gate_full.done
#   NOVA_NOVAC_VERDICT     — путь к вердикту яруса novac, по умолчанию
#                            /tmp/gate_novac.done
#   NOVA_MERGE_ALLOW_RED=1 — осознанный обход (например, вливается САМ фикс
#                            красноты). Требует, чтобы причина была названа в
#                            сообщении слияния; хук её печатает в журнал.

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
VERDICT="${NOVA_GATE_VERDICT:-/tmp/gate_full.done}"
NOVAC_VERDICT="${NOVA_NOVAC_VERDICT:-/tmp/gate_novac.done}"
# shellcheck source=../tools/gate-tier-paths.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/../tools" && pwd)/gate-tier-paths.sh"
cd "$ROOT" || exit 1

BR=$(git rev-parse --abbrev-ref HEAD 2>/dev/null)
if [ "$BR" != "main" ] && [ "$BR" != "master" ]; then
    echo "check-merge-discipline: ветка '$BR' — правило касается только главной, пропуск"
    exit 0
fi

if [ "${NOVA_MERGE_ALLOW_RED:-0}" = "1" ]; then
    echo "check-merge-discipline: ОБХОД по NOVA_MERGE_ALLOW_RED=1 — причина обязана быть в сообщении слияния" >&2
    exit 0
fi

fail() {
    echo "check-merge-discipline: ОТКАЗ — $1" >&2
    echo "    В main вливается только то, что прошло гейт. Пока гейт красный," >&2
    echo "    приток закрыт: иначе непроверенное копится, и регресс придётся" >&2
    echo "    искать в общей куче (случай 2026-08-08: 75 коммитов)." >&2
    echo "    Что делать: прогнать 'bash scripts/tools/gate-bg.sh', дождаться" >&2
    echo "    зелёного, влить. Если вливается САМ фикс красноты — назови причину" >&2
    echo "    в сообщении и повтори с NOVA_MERGE_ALLOW_RED=1." >&2
    exit 1
}

[ -f "$VERDICT" ] || fail "вердикта гейта нет ($VERDICT) — дерево не проверено"

RC=$(sed -n 's/^RC=\([0-9][0-9]*\).*/\1/p' "$VERDICT" | head -1)
[ -n "${RC:-}" ] || fail "вердикт нечитаем ($VERDICT)"
[ "$RC" -eq 0 ] || fail "последний гейт КРАСНЫЙ (RC=$RC)"

# Свежесть: вердикт обязан быть НЕ СТАРШЕ последнего коммита в главной ветке.
V_TS=$(stat -c %Y "$VERDICT" 2>/dev/null)
H_TS=$(git log -1 --format=%ct HEAD 2>/dev/null)
if [ -n "${V_TS:-}" ] && [ -n "${H_TS:-}" ] && [ "$V_TS" -lt "$H_TS" ]; then
    fail "вердикт СТАРШЕ HEAD — он относится к другому дереву и ничего не доказывает"
fi

# ── Ярус: вердикт обязан назвать себя (№988) ──────────────────────────────
# Форма метки — `TIER=<ярус>[:<уровень>]`. Ярус и уровень разбираются отдельно.
V_TIER=$(sed -n 's/.*TIER=\([a-z][a-z-]*\).*/\1/p' "$VERDICT" | head -1)
V_LEVEL=$(sed -n 's/.*TIER=[a-z][a-z-]*:\([a-z][a-z]*\).*/\1/p' "$VERDICT" | head -1)
if [ -z "${V_TIER:-}" ]; then
    fail "вердикт не называет ЯРУС ($VERDICT) — по нему нельзя узнать, ЧТО он проверял.
    Перезапусти гейт: свежий gate-bg.sh штампует TIER/HASH/BRANCH (№988)"
fi
[ "$V_TIER" = "main" ] || fail "вердикт яруса '$V_TIER' подан как основной ($VERDICT) — ярусы судят РАЗНОЕ и не заменяют друг друга"

# УРОВЕНЬ ОСНОВНОГО ЯРУСА ОБЯЗАТЕЛЕН (№995). `loop` не судит корпус
# вовсе — ни линта, ни мега-CU, ни прогона, — а выглядел так же, как push.
case "${V_LEVEL:-}" in
    push|full) : ;;
    loop) fail "вердикт уровня 'loop' — этот уровень НЕ судит корпус (ни линта, ни мега-CU, ни прогона), слияние им не открывается" ;;
    "") fail "вердикт не называет УРОВЕНЬ прогона ($VERDICT) — ждётся TIER=main:<loop|push|full>. Перезапусти гейт: свежий gate-bg.sh штампует уровень (№995)" ;;
    *) fail "вердикт называет неизвестный уровень '$V_LEVEL' ($VERDICT)" ;;
esac

V_HASH=$(sed -n 's/.*HASH=\([0-9a-f][0-9a-f]*\).*/\1/p' "$VERDICT" | head -1)
H_HASH=$(git rev-parse HEAD 2>/dev/null)
if [ -n "${V_HASH:-}" ] && [ -n "${H_HASH:-}" ] && [ "$V_HASH" != "$H_HASH" ]; then
    fail "вердикт судил дерево $V_HASH, а HEAD сейчас $H_HASH — это ДРУГОЕ дерево"
fi

# ── Ярус novac: нужен, если слияние приносит его пути (№988) ───────────────
if git rev-parse -q --verify MERGE_HEAD >/dev/null 2>&1; then
    # НЕ ТРЁХТОЧЕЧНАЯ ФОРМА, И ЭТО НЕ СТИЛЬ. `A...B` берёт ОДНУ базу
    # слияния, а при нескольких git выбирает произвольную и говорит об этом
    # в stderr, который никто не читает (реестр 221.1 №629). У нас НЕСКОЛЬКО
    # баз бывает штатно: окно 274 вливает `main` в свою ветку, а интегратор
    # вливает ветку в `main` — крест-накрест. Произвольная база здесь
    # значит НЕДОСЧЁТ novac-путей, то есть МОЛЧАЛИВО ПРОПУЩЕННОЕ
    # ТРЕБОВАНИЕ ВЕРДИКТА — ровно та дыра, от которой заведён №988.
    # Поэтому берётся ОБЪЕДИНЕНИЕ по ВСЕМ базам: оно не может недосчитать
    # относительно любой из них, а лишний файл в списке стоит лишь одного
    # лишнего требования вердикта — ошибка в безопасную сторону.
    INCOMING=""
    for _b in $(git merge-base --all HEAD MERGE_HEAD 2>/dev/null); do
        INCOMING="$INCOMING
$(git diff --name-only "$_b" MERGE_HEAD 2>/dev/null)"
    done
    N_NOVAC=$(printf '%s\n' "$INCOMING" | novac_paths_count)
    if [ "${N_NOVAC:-0}" -gt 0 ]; then
        [ -f "$NOVAC_VERDICT" ] || fail "слияние приносит $N_NOVAC файл(ов) яруса novac, а его вердикта нет ($NOVAC_VERDICT).
    Основной гейт этих файлов НЕ судит: 87 стражей check-novac-* живут только в scripts/gate-novac.sh.
    Прогони: NOVAC_TIER=push bash scripts/gate-novac.sh"
        N_RC=$(sed -n 's/^RC=\([0-9][0-9]*\).*/\1/p' "$NOVAC_VERDICT" | head -1)
        [ -n "${N_RC:-}" ] || fail "вердикт яруса novac нечитаем ($NOVAC_VERDICT)"
        [ "$N_RC" -eq 0 ] || fail "гейт novac КРАСНЫЙ (RC=$N_RC) — слияние его путей закрыто"
        N_TIER=$(sed -n 's/.*TIER=\([a-z][a-z-]*\).*/\1/p' "$NOVAC_VERDICT" | head -1)
        # У ЯРУСА NOVAC УРОВЕНЬ ПОКА ЛИШЬ ПРЕДУПРЕЖДЕНИЕ, И ЭТО НАЗВАНО (№995).
        # Его производитель — `gate-novac.sh`, и правит его окно 274. Жёсткое
        # требование сейчас обесценило бы чужой прогон, идущий в эту минуту со
        # старым форматом, — двадцать пять минут машины ради формы. Послабление
        # снимается, как только тот производитель начнёт писать уровень.
        N_LEVEL=$(sed -n 's/.*TIER=[a-z][a-z-]*:\([a-z][a-z]*\).*/\1/p' "$NOVAC_VERDICT" | head -1)
        case "${N_LEVEL:-}" in
            push|full) : ;;
            loop) fail "вердикт яруса novac уровня 'loop' — слияние им не открывается" ;;
            "") echo "check-merge-discipline: ПРЕДУПРЕЖДЕНИЕ — вердикт яруса novac не называет УРОВНЯ (№995); принят как есть до правки gate-novac.sh окном 274" >&2 ;;
            *) fail "вердикт яруса novac называет неизвестный уровень '$N_LEVEL'" ;;
        esac
        # Ровно `novac`: `novac-sample` — это прогон со швом, НЕ полный.
        [ "${N_TIER:-}" = "novac" ] || fail "в $NOVAC_VERDICT лежит вердикт яруса '${N_TIER:-без имени}', а нужен novac (выборка со швом не годится)"
        # СВЕЖЕСТЬ ЯРУСА NOVAC МЕРЯЕТСЯ ПО `MERGE_HEAD`, А НЕ ПО `HEAD`.
        # Этот ярус гоняется на ВХОДЯЩЕЙ ветке, а не на моём дереве, и его
        # вердикт законно СТАРШЕ моего `HEAD` — сравнение со временем `HEAD`
        # давало бы ложный отказ на честно проверенной ветке. Сверка ПО ХЕШУ
        # строга и точна: вердикт обязан называть ИМЕННО тот коммит, который
        # вливается. Если хеша нет (старый формат) — падаем на время файла.
        N_HASH=$(sed -n 's/.*HASH=\([0-9a-f][0-9a-f]*\).*/\1/p' "$NOVAC_VERDICT" | head -1)
        M_HASH=$(git rev-parse MERGE_HEAD 2>/dev/null)
        if [ -n "${N_HASH:-}" ] && [ -n "${M_HASH:-}" ]; then
            case "$M_HASH" in
                "$N_HASH"*) : ;;
                *) fail "вердикт яруса novac судил $N_HASH, а сливается $M_HASH — это ДРУГОЕ содержимое" ;;
            esac
        else
            NV_TS=$(stat -c %Y "$NOVAC_VERDICT" 2>/dev/null)
            if [ -n "${NV_TS:-}" ] && [ -n "${H_TS:-}" ] && [ "$NV_TS" -lt "$H_TS" ]; then
                fail "вердикт яруса novac СТАРШЕ HEAD и не называет хеша — судить нечем"
            fi
        fi
        echo "check-merge-discipline: слияние приносит $N_NOVAC файл(ов) яруса novac — его вердикт есть, зелёный и свежий"
    fi
else
    echo "check-merge-discipline: MERGE_HEAD нет (ручной вызов) — принадлежность к ярусу novac НЕ проверялась"
fi

echo "check-merge-discipline ok: гейт зелёный, свежее HEAD, ярус назван — слияние законно"
exit 0
