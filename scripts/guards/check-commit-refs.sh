#!/usr/bin/env bash
# scripts/guards/check-commit-refs.sh
# Ссылка на коммит в доке обязана вести туда, где что-то есть.
#
# ДОМ И ОСНОВАНИЕ: `docs/dev/doc-conventions.md`, раздел «Ссылки наружу»
# (`{#external-links}`, решение владельца 2026-08-14); реестр 221.1 №646.
#
# ЗАЧЕМ. Правило про ссылки написано после вычистки истории 2026-08-13, и
# первая же его редакция ушла в дерево БЕЗ механизма — владелец на это и
# указал: «есть правило, должен быть страж». Цена не предполагается, а
# измерена этим самым стражем при заведении: **828 из 2769 хешей, названных в
# доке, недостижимы из `main`** — тридцать процентов ссылок на коммиты уже
# ведут в пустоту. Вычистка сменила хеши всего, что было после первого
# затронутого коммита; страховочная метка держит объекты в МОЁМ клоне, но не в
# чужом.
#
# ТРИ ПРАВИЛА И РАЗНОЕ ОТНОШЕНИЕ К НИМ:
#   R1 (ссылка на коммит в вебе без темы и даты) — база 0, растить нечему;
#   R2 (голый хеш недостижим из main) — ХРАПОВИК: 828 уже есть, чинить их
#      поштучно бессмысленно, но новых прибавиться не должно;
#   R3 (ссылка на код через зеркало) — база 0.
#
# ЧТО ЭТОТ СТРАЖ ЛОВИТ НА САМОМ ДЕЛЕ, кроме опечаток: **следующее
# переписывание истории.** Оно поднимет R2 разом на сотни — и гейт скажет об
# этом до отправки в зеркала, а не после.
#
# ЧЕГО НЕ ЛОВИТ (честно): хеши соседних реп (`nova-tls@7a44776`) он проверить
# не может — их истории здесь нет; конвенция поэтому и требует для них форму
# `репозиторий@хеш`, по которой видно, что хеш не наш. Наличие такой формы
# страж не требует: отличить её от нашего хеша без похода в соседнюю репу
# нельзя, а страж, ходящий по сети, в гейте недопустим.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-commit-refs.sh [КОРЕНЬ] [КОРЕНЬ-СКАНА]
# Самотест — scripts/guards/selftest/test-check-commit-refs.sh

set -u
export LC_ALL=C

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
SCAN="${2:-$ROOT}"
BASELINE="${NOVA_COMMITREFS_BASELINE:-$ROOT/scripts/guards/commit-refs.baseline}"
CORE="$(dirname "${BASH_SOURCE[0]}")/commit-refs-scan.py"

[ -f "$CORE" ] || { echo "check-commit-refs: нет ядра $CORE" >&2; exit 1; }

OUT=$(python "$CORE" "$ROOT" "$SCAN")
RC=$?
if [ "$RC" -ne 0 ]; then
    # Ядро вернуло не ноль — это НЕ «нарушений нет» (урок №645).
    echo "check-commit-refs: ядро упало (код $RC) — считать нечем" >&2
    echo "check-commit-refs: FAIL" >&2
    exit 1
fi

count() { printf '%s\n' "$OUT" | grep -c "^$1|" || true; }
R1=$(count R1); R2=$(count R2); R3=$(count R3)
R1=${R1:-0}; R2=${R2:-0}; R3=${R3:-0}

base_of() {
    local v=0
    [ -f "$BASELINE" ] && v=$(sed -n "s/^$1=\([0-9][0-9]*\).*/\1/p" "$BASELINE" | head -1)
    printf '%s' "${v:-0}"
}
B1=$(base_of commit_url_no_context)
B2=$(base_of dead_hash_refs)
B3=$(base_of mirror_links)

echo "check-commit-refs: ссылок на коммит без темы/даты $R1 (база $B1), мёртвых хешей $R2 (база $B2), ссылок через зеркало $R3 (база $B3)"

FAILED=0
report() { # правило текущее база подсказка
    local rule="$1" cur="$2" base="$3" hint="$4"
    if [ "$cur" -gt "$base" ]; then
        echo "check-commit-refs: $rule ВЫРОСЛО — $cur > базы $base" >&2
        printf '%s\n' "$OUT" | grep "^$rule|" | head -10 | sed 's/^/    /' >&2
        echo "    $hint" >&2
        FAILED=1
    elif [ "$cur" -lt "$base" ]; then
        echo "check-commit-refs: $rule долг СНИЗИЛСЯ ($cur < базы $base) — опусти базу в $BASELINE"
        if [ "$rule" = "R2" ]; then
            echo "check-commit-refs:   СНАЧАЛА ПРОВЕРЬ СРЕДУ. Достижимость считается по ВСЕМ"
            echo "check-commit-refs:   веткам (rev-list --all), и локально сюда попадают ветки"
            echo "check-commit-refs:   СОСЕДНИХ ОКОН, которых на CI-чекауте НЕТ. База хранит ЧИСЛО CI."
            echo "check-commit-refs:   Опустишь по локальному — уронишь авторитетный гейт: замер"
            echo "check-commit-refs:   2026-09-05 — локально 803, на CI 828, и я уронил его именно так."
        fi
    fi
}
report R1 "$R1" "$B1" "Ссылка на коммит обязана нести рядом тему в кавычках и дату: после переписывания истории читатель найдёт коммит по теме, по хешу — ничего."
report R2 "$R2" "$B2" "Хеша нет в main. Три причины, по частоте: (1) это коммит СОСЕДНЕЙ репы — тогда форма другая, 'репа@хеш' (nova-tls@7a44776), и правило её не трогает (doc-conventions, «Ссылки наружу»); (2) ветка не влита; (3) историю переписали — это тревога, а не опечатка: проверь, что отправляешь."
report R3 "$R3" "$B3" "Ссылка на код идёт на github.com/nv-lang — зеркала в ссылках не чередуются."

if [ "$FAILED" -ne 0 ]; then
    echo "    Правило: docs/dev/doc-conventions.md, раздел «Ссылки наружу»." >&2
    echo "check-commit-refs: FAIL" >&2
    exit 1
fi

echo "check-commit-refs ok: новых мёртвых ссылок на коммиты нет"
exit 0
