#!/usr/bin/env bash
# check-ci-status.sh — страж внешнего авторитетного гейта (GitHub Actions).
#
# ЗАЧЕМ (реестр 221.1 №395/№401/№402; правило владельца 2026-08-07:
# «проверка и слежение должны запускаться автоматически, а не потому что
# кто-то помнит»).
#
# Прецедент, ради которого страж заведён — сутки 2026-08-05/06:
#   * CI на github был красным по ЧЕТЫРЁМ воркфлоу, и за 24 слияния подряд
#     никто в него не заглянул: локальный `gate.sh` был зелёным, и этого
#     казалось достаточно. Обнаружено только прямым вопросом владельца.
#   * Хуже: на пуш `7ed38407d` не стартовало НИ ОДНОГО прогона при включённых
#     Actions и корректных триггерах. Не запустившийся гейт опаснее красного —
#     красный виден, молчащий выглядит как «всё хорошо».
#   * Первопричина расхождения структурная: локальный гейт гоняет
#     `nova check std/src`, а CI — `nova test std`. То есть CI видит то, чего
#     локальный гейт не видит ПО ПОСТРОЕНИЮ (№402: `retry_test` не собирается
#     при зелёном `check`). Пока это так, «локально зелено» — более слабое
#     утверждение, чем звучит, и об этом обязана напоминать машина.
#
# ПЕРЕД ТЕМ КАК КОПАТЬ ПО ВЕРДИКТУ `STALE` — ПОСМОТРИ НАРУЖУ:
#   https://www.githubstatus.com/api/v2/summary.json
# Именно так закончился первый случай, ради которого написан этот страж: 2026-08-06
# прогоны перестали запускаться по push, было перебрано полдюжины внутренних
# гипотез (настройки организации, состояние воркфлоу, skip-маркеры, права,
# биллинг), а причиной оказался ГЛОБАЛЬНЫЙ СБОЙ GitHub Actions — Major Outage с
# 15:22 UTC, инцидент дословно: «многие события push и pull request не запускают
# новые workflow runs». Признак внешнего сбоя: то же самое видно в ДРУГИХ репах
# семьи, а ручной `workflow_dispatch` при этом проходит.
#
# ЧТО ДЕЛАЕТ: спрашивает GitHub про прогоны на текущем `origin/main` (или на
# хеше из аргумента) и печатает вердикт рядом с локальным. Три исхода:
#   OK    — на хеше есть прогоны и все завершившиеся зелёные;
#   RED   — есть хотя бы один `failure`/`timed_out`/`startup_failure`,
#           либо `cancelled` БЕЗ более нового прогона того же задания;
#           отмена по ВЫТЕСНЕНИЮ (пришёл пуш новее, группа параллелизма
#           сняла очередь) отказом не считается — 2026-08-19 она
#           случалась на каждом втором пуше подряд;
#   STALE — прогонов на хеше НЕТ вовсе, а с момента коммита прошло больше
#           NOVA_CI_STALE_MIN минут (по умолчанию 20). Это и есть случай
#           «пуш прошёл, CI не отреагировал».
#
# РЕЖИМ ПО УМОЛЧАНИЮ — НЕ БЛОКИРУЮЩИЙ (exit 0 при любом вердикте): страж
# сообщает, а не останавливает работу, потому что внешний сервис бывает
# недоступен, и падение сети не должно ронять локальный гейт. Блокирующий
# режим включается флагом `--strict` (используется в pre-push хуке): там
# красный внешний гейт ОБЯЗАН остановить отправку.
#
# `gh` отсутствует / не авторизован / сеть недоступна → вердикт SKIP, exit 0,
# с явной строкой о причине. Молчания быть не должно ни в одном случае: страж,
# который ничего не напечатал, неотличим от стража, который всё проверил.
#
# ИСПОЛЬЗОВАНИЕ:
#   check-ci-status.sh [--strict] [хеш]
#
# LC_ALL=C — байтовый grep независимо от локали хоста (msys2-grep в
# ru_RU.UTF-8 на не-ASCII молча даёт ноль хитов; см. reference по стражам).
export LC_ALL=C

set -u

STRICT=0

# Наружный факт рядом с внутренним (см. шапку). Печатает строку про инцидент
# GitHub, если он есть; молчит, если всё в порядке или спросить не вышло.
# Короткий таймаут обязателен: страж не имеет права виснуть из-за того, что
# сама страница статуса недоступна.
github_incident_note() {
    command -v curl >/dev/null 2>&1 || return 0
    _st=$(timeout 10 curl -s https://www.githubstatus.com/api/v2/status.json 2>/dev/null \
          | grep -o '"indicator":"[a-z]*"' | head -1 | cut -d'"' -f4)
    case "$_st" in
        ''|none) return 0 ;;
    esac
    _desc=$(timeout 10 curl -s https://www.githubstatus.com/api/v2/status.json 2>/dev/null \
            | grep -o '"description":"[^"]*"' | head -1 | cut -d'"' -f4)
    say "ВНИМАНИЕ: у GitHub СЕЙЧАС инцидент — indicator=$_st ($_desc)."
    say "  Прежде чем искать причину у себя: молчащие прогоны и висящие пуши"
    say "  выглядят точно так же, как поломка своего дерева, и отличаются"
    say "  только этой строкой. https://www.githubstatus.com"
}

SHA_ARG=""
for arg in "$@"; do
    case "$arg" in
        --strict) STRICT=1 ;;
        *)        SHA_ARG="$arg" ;;
    esac
done

STALE_MIN="${NOVA_CI_STALE_MIN:-20}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/../.." && pwd)"
cd "$REPO_ROOT" || exit 0

say()  { echo "check-ci-status: $*"; }
skip() { say "SKIP — $*"; exit 0; }

command -v gh >/dev/null 2>&1 || skip "gh не установлен (внешний гейт не проверен)"
gh auth status >/dev/null 2>&1 || skip "gh не авторизован (внешний гейт не проверен)"

if [ -n "$SHA_ARG" ]; then
    SHA="$SHA_ARG"
else
    git fetch github main --quiet 2>/dev/null || git fetch origin main --quiet 2>/dev/null || true
    # `--verify --quiet`, а НЕ `2>/dev/null`: при неудаче обычный `rev-parse`
    # печатает НЕРАЗРЕШЁННЫЙ АРГУМЕНТ В STDOUT и лишь потом падает. Здесь это
    # давало SHA вида "github/main" + настоящий хеш, склеенные вместе, и
    # `git show` дальше валился на бессмысленной ревизии — ровно тот отказ,
    # который весь день выглядел как «коммиту 56 лет» (реестр №585).
    # Удалённого `github` в этом дереве нет вовсе: зеркала зовутся origin,
    # gitverse, sourcecraft.
    SHA="$(git rev-parse --verify --quiet github/main || git rev-parse --verify --quiet origin/main || true)"
fi
[ -n "$SHA" ] || skip "не удалось определить хеш удалённого main"

SHORT="$(echo "$SHA" | cut -c1-9)"

RUNS="$(gh run list --limit 40 \
        --json name,status,conclusion,headSha,createdAt,event,databaseId 2>/dev/null || true)"
[ -n "$RUNS" ] || skip "gh не вернул список прогонов (сеть/лимит?)"

# Интерпретатор: в Ubuntu (и на CI) `python` ОТСУТСТВУЕТ — есть только
# `python3`. Без этого фолбэка страж на Linux молча уходил в SKIP и не
# проверял ничего (найдено прогоном самотестов в WSL 2026-08-07, тот же
# класс, что №404: инструмент писался и проверялся только на Windows).
# Выбираем по ФАКТУ ИСПОЛНЕНИЯ, а не по наличию в PATH: в Windows
# `python3` часто резолвится в заглушку Microsoft Store, которая существует,
# запускается и не делает НИЧЕГО — проверка `command -v` её пропускает, и
# страж молча уходил бы в SKIP на машине, где python есть.
PY_BIN=""
for _cand in python3 python; do
    if command -v "$_cand" >/dev/null 2>&1 && [ "$("$_cand" -c 'print(42)' 2>/dev/null)" = "42" ]; then
        PY_BIN="$_cand"; break
    fi
done
[ -n "$PY_BIN" ] || skip "не найден рабочий python/python3 (разбор ответа gh невозможен)"
VERDICT="$(printf '%s' "$RUNS" | "$PY_BIN" -c "
import json,sys
sha=sys.argv[1]
try:
    runs=json.load(sys.stdin)
except Exception:
    print('SKIP|не разобрать ответ gh'); raise SystemExit
mine=[r for r in runs if r.get('headSha','').startswith(sha[:9])]
if not mine:
    print('NONE|'); raise SystemExit
# ОТМЕНА ПО ВЫТЕСНЕНИЮ — НЕ ОТКАЗ. У 'nova-gate' задана группа
# параллелизма, и при частых пушах GitHub отменяет СТОЯЩИЙ В ОЧЕРЕДИ
# прогон, когда приходит более новый. Считать это красным значит ронять
# отправки по причине, которой нет, — а ложный красный останавливает
# всех (довод №703). Отмена красна ТОЛЬКО если более нового прогона
# ТОГО ЖЕ задания не появилось: тогда её кто-то снял намеренно.
def _newer_exists(r):
    nm, ts = r.get('name'), r.get('createdAt', '')
    return any(o.get('name') == nm and o.get('createdAt', '') > ts
               for o in runs)
hard=[r for r in mine if r.get('conclusion') in ('failure','timed_out','startup_failure')]
canc=[r for r in mine if r.get('conclusion') == 'cancelled']
# Снятый прогон НЕ отказ и НЕ зелёное — это ОТСУТСТВИЕ вердикта, и
# называется оно теперь своим именем (второй носитель №735): три
# подряд отмены crate-tests 2026-08-19 были сняты из ОЧЕРЕДИ, не
# начав ни одного шага, а страж объявлял их красными.
red=hard
noverdict=[r for r in canc if not _newer_exists(r)]
superseded=[r for r in canc if _newer_exists(r)]
run=[r for r in mine if r.get('status') != 'completed']
if red:
    # ИМЯ ОДНО НЕ ГОВОРИТ, ЧЕЙ ЭТО КРАСНЫЙ (реестр 221.1 №785, 2026-08-27).
    # Ночной прогон (event=schedule) идёт ярусом full и доходит до
    # самотестов стражей, куда ярус push не доходит вовсе, — то есть
    # его краснота обычно СТАРШЕ твоей отправки и не про неё.
    def _tag(r):
        return '%s(%s #%s)' % (r['name'], r.get('event') or '?',
                               r.get('databaseId') or '?')
    print('RED|' + ', '.join(sorted(_tag(r) for r in red)))
elif noverdict:
    print('NOVERDICT|' + ', '.join(sorted({r['name'] for r in noverdict})))
elif run:
    print('RUNNING|' + ', '.join(sorted({r['name'] for r in run})))
else:
    tail = ''
    if superseded:
        tail = ' (+%d superseded)' % len(superseded)
    print('OK|' + str(len(mine)) + tail)
" "$SHA" 2>/dev/null)"

KIND="${VERDICT%%|*}"
DETAIL="${VERDICT#*|}"

case "$KIND" in
    OK)
        say "OK — внешний гейт зелёный на $SHORT ($DETAIL прогонов)"
        exit 0
        ;;
    RUNNING)
        say "идёт — на $SHORT ещё выполняются: $DETAIL"
        exit 0
        ;;
    NOVERDICT)
        say "НЕТ ВЕРДИКТА на $SHORT: прогон СНЯТ, не дав результата — $DETAIL"
        say "  снятый прогон — это ОТСУТСТВИЕ вердикта, а не отказ. Назвать"
        say "  его красным значило бы утверждать причину, которой никто не"
        say "  устанавливал (№735, родня №727: диагностика обязана называть"
        say "  ту причину, которую установила)."
        say "  ЗАМЕР 2026-08-19: три подряд отмены crate-tests, у всех"
        say "  startedAt == createdAt и снятие через 45-48 минут после"
        say "  постановки, при том что зелёный прогон того же задания идёт"
        say "  7 минут — их сняли ИЗ ОЧЕРЕДИ, не начав."
        say "  Отправка всё равно остановлена: отсутствие вердикта — не"
        say "  разрешение. Получить настоящий: gh run rerun <id>"
        [ "$STRICT" -eq 1 ] && exit 1
        exit 0
        ;;
    RED)
        say "RED — ВНЕШНИЙ ГЕЙТ КРАСНЫЙ на $SHORT: $DETAIL"
        say "  локальный зелёный вердикт этого НЕ отменяет: gate.sh гоняет"
        say "  \`nova check std\`, CI — \`nova test std\` (реестр №402)."
        case "$DETAIL" in
            *"(schedule "*)
                say "  СРЕДИ КРАСНЫХ ЕСТЬ НОЧНОЙ ПРОГОН (event=schedule)."
                say "  Он идёт ярусом full и доходит до самотестов стражей, куда"
                say "  ярус push не доходит вовсе. Значит его краснота, скорее"
                say "  всего, СТАРШЕ этой отправки и не про твой коммит — открой"
                say "  прогон по номеру выше, прежде чем чинить своё. 2026-08-27"
                say "  на выяснении этого ушёл целый заход: страж знал событие и"
                say "  не называл его (реестр 221.1 №785)."
                ;;
        esac
        [ "$STRICT" -eq 1 ] && exit 1
        exit 0
        ;;
    NONE)
        # №585: раньше `CT="$(git show ... || echo 0)"` глотал ЛЮБОЙ отказ git show
        # молча — CT=0 давал AGE_MIN в десятки миллионов минут, а условие ниже
        # (`$CT -gt 0`) на нуле не срабатывало, и шаг печатал «прогонов пока
        # нет» — то есть отказ ВХОДНЫХ ДАННЫХ (объект недоступен) выглядел как
        # «проверено, CI молчит». Разбор: `git show` не отдаёт дату, когда SHA
        # синтаксически резолвится (`git rev-parse` не проверяет наличие
        # объекта — только читает ref/packed-refs), а самого коммита нет в
        # локальном хранилище. Пробой (см. отчёт окна): `git show -s --format=%ct
        # <несуществующий SHA>` → `fatal: bad object <sha>`, rc=128, stdout
        # пуст. ГИПОТЕЗА (не подтверждена независимо, разбирающему проверить,
        # а не додумать): `.git` общий у ~70 worktree на машине (docs/plans/
        # 260-gate-speed-optimizations.md:198-201 уже отмечает `check-ci-status.sh`
        # как единственный страж, пишущий в общее — `git fetch`), и при
        # одновременном запуске гейта в нескольких worktree возможна гонка:
        # `git fetch` в ОДНОМ worktree обновляет ref до нового SHA раньше, чем
        # объект этого коммита полностью распакован/дописан в разделяемом
        # object store, и параллельный `check-ci-status.sh` в ДРУГОМ worktree
        # читает уже обновлённый ref, но ещё недописанный объект. Короткий/
        # неоднозначный SHA как причина ИСКЛЮЧЕНА: SHA либо приходит из
        # `git rev-parse origin/main` (полный хеш), либо явным аргументом —
        # ни один путь не режет SHA до короткой формы.
        CT_RAW="$(git show -s --format=%ct "$SHA" 2>&1)"
        CT_RC=$?
        case "$CT_RAW" in
            ''|*[!0-9]*) CT_RC=1 ;;
        esac
        if [ "$CT_RC" -ne 0 ]; then
            say "ОШИБКА — не удалось прочитать дату коммита $SHORT: git show вернул «${CT_RAW:-пусто}»"
            say "  проверка STALE ОТКАЗАНА, а не «прогонов пока нет» — без даты коммита нельзя"
            say "  установить его возраст. Причина обычно локальная: объект недоступен в"
            say "  этом дереве (гонка общего .git между worktree при параллельном fetch,"
            say "  либо fetch не завершился) — повтори страж отдельно; если повторяется,"
            say "  это дефект, не разовый сбой сети."
            exit 1
        fi
        CT="$CT_RAW"
        NOW="$(date +%s)"
        AGE_MIN=$(( (NOW - CT) / 60 ))
        # `-ge`, а не `-gt`: с порогом 0 («считать молчащим сразу») строгое сравнение
        # никогда не срабатывает на свежем коммите — самотест на Linux падал именно
        # так (клон --depth 1, возраст HEAD = 0 мин, порог 0 → 0 > 0 = false).
        if [ "$AGE_MIN" -ge "$STALE_MIN" ] && [ "$STALE_MIN" -ge 0 ]; then
            github_incident_note
            say "STALE — на $SHORT НЕТ НИ ОДНОГО ПРОГОНА, коммиту $AGE_MIN мин"
            say "  пуш прошёл, CI не отреагировал — молчащий гейт опаснее красного"
            [ "$STRICT" -eq 1 ] && exit 1
            exit 0
        fi
        github_incident_note
        say "прогонов на $SHORT пока нет (коммиту $AGE_MIN мин, порог $STALE_MIN)"
        exit 0
        ;;
    SKIP)
        skip "$DETAIL"
        ;;
    *)
        skip "неожиданный вердикт разбора"
        ;;
esac
