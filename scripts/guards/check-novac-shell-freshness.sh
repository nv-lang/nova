#!/bin/sh
# scripts/guards/check-novac-shell-freshness.sh — свежесть СГЕНЕРИРОВАННОЙ
# оболочки эмиттера novac.
#
# ПРАВИЛО (план 274 Э2 §9 + разбор 274.3/F6, класс К4 «два места правды
# разойдутся молча»): novac/src/emit_c/shell.tpl.c — не рукопись, а эмиссия
# оракула по зонтичному probe novac/probe/shell_probe.nv, вырезанная
# генератором scripts/tools/novac-regen-shell.sh. Лежит в репозитории (novac
# встраивает её при сборке) и служит ЭТАЛОНОМ ABI стражу
# check-novac-mangle-fixed-point.sh — то есть novac сверяется с этим снимком.
# Значит снимок обязан быть равен тому, что оракул эмитит СЕЙЧАС: иначе
# мэнгл-страж судит по устаревшему эталону, а probe/оракул уехали вперёд
# молча.
#
# ПРОВЕРЯЕТ: зовёт генератор в режиме `--check` (регенерация во временный
# файл + cmp с репозиторным шаблоном; сам шаблон не трогается). Совпало —
# зелёный; разошлось — красный с первыми строками diff и подсказкой.
# Оракула нет (не собран / не Windows) — честное «судить нечего», выход 0;
# машинное условие, при котором это перестаёт быть законным (П15): как
# только оракул есть, зелёное молчание невозможно — судится байт-в-байт.
# Шаблона нет, а probe есть — красный: сгенерированный артефакт пропал.
#
# НЕ ПРОВЕРЯЕТ: что probe покрывает всё подмножество эмиттера (это линковка
# смоуков и check-novac-mangle-fixed-point.sh); что сам шаблон осмыслен
# (форму слотов сверяет самопроверка генератора); совпадение оракула с
# `oracle-pin:` из novac/nova.toml (пин двигают сознательно — страж лишь
# требует, чтобы шаблон был перегенерирован ТЕМ ЖЕ слиянием, что и сдвиг).
#
# $1 — корень репозитория (default: вычислить от себя);
# $2 — override пути к генератору (шов самотеста).
# Цена: одна сборка probe оракулом, ~5–40 с.
# Проверялся: Windows (Git Bash), 2026-08-15.
export LC_ALL=C
ROOT="${1:-$(cd "$(dirname "$0")/../.." && pwd)}"
GEN="${2:-$(cd "$(dirname "$0")/../tools" && pwd)/novac-regen-shell.sh}"
NAME=check-novac-shell-freshness
TPL="$ROOT/novac/src/emit_c/shell.tpl.c"
PROBE="$ROOT/novac/probe/shell_probe.nv"

if [ ! -f "$GEN" ]; then
    echo "$NAME: FAIL — нет генератора $GEN: сверять шаблон нечем (274.3/F6)" >&2
    exit 1
fi
if [ ! -f "$TPL" ]; then
    if [ -f "$PROBE" ]; then
        echo "$NAME: FAIL — probe $PROBE есть, а сгенерированной оболочки $TPL нет" >&2
        echo "  Чинить: sh scripts/tools/novac-regen-shell.sh и закоммить шаблон тем же слиянием." >&2
        exit 1
    fi
    echo "$NAME ok: судить нечего (оболочки novac ещё нет — ни шаблона, ни probe)"
    exit 0
fi

out=$(sh "$GEN" --check "$TPL" 2>&1)
rc=$?
case "$rc" in
    0)
        echo "$NAME ok: шаблон == эмиссия оракула по probe ($(wc -l < "$TPL" | tr -d ' ') строк, $(wc -c < "$TPL" | tr -d ' ') байт)"
        exit 0
        ;;
    3)
        echo "$NAME ok: судить нечего (оракул не собран)"
        exit 0
        ;;
esac

echo "$NAME: FAIL — оболочка novac разошлась с эмиссией оракула (генератор вернул $rc):" >&2
printf '%s\n' "$out" | sed 's/^/  /' >&2
echo "  Чинить: прогони sh scripts/tools/novac-regen-shell.sh и закоммить" >&2
echo "  novac/src/emit_c/shell.tpl.c ТЕМ ЖЕ слиянием (плюс пересборка novac и" >&2
echo "  смоуки подмножества: шаблон меняет каждый эмитируемый файл). Если" >&2
echo "  разошёлся оракул, а не probe — сдвиг oracle-pin в novac/nova.toml идёт" >&2
echo "  тем же слиянием, что и перегенерация (274 §9, 274.3/F6)." >&2
exit 1
