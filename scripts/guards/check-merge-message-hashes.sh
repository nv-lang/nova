#!/usr/bin/env bash
# scripts/guards/check-merge-message-hashes.sh
# Хеш, названный в сообщении КОММИТА СЛИЯНИЯ, обязан быть достижим из этого
# коммита.
#
# ДОМ ПРАВИЛА — `docs/dev/doc-conventions.md`, раздел «Ссылки наружу»
# (то же правило «названный хеш ведёт туда, где что-то есть»). Реестр 221.1
# №994.
#
# ЧЕМ ЭТОТ СТРАЖ ОТЛИЧАЕТСЯ ОТ `check-commit-refs.sh`, И ПОЧЕМУ ОН ОТДЕЛЬНЫЙ.
# Тот судит хеши в ДОКЕ (`.md` в docs/plans, docs/dev, spec, корневые файлы) и
# держит храповик `dead_hash_refs=828` — наследство вычистки истории. Здесь
# другой КОРПУС (сообщения коммитов) и другой момент применения (слияние, а не
# правка доки), поэтому и правило другое по строгости: для НОВЫХ слияний это
# не храповик, а ноль. Свести их в один файл значило бы получить один страж на
# две разные вещи — ровно класс №992, заведённый в тот же день.
#
# ЗАЧЕМ, И ЦЕНА ИЗМЕРЕНА НА СЕБЕ. 2026-09-06 интегратор влил `origin/p274-novac`
# (отставший от локальной ветки окна 274) и написал сообщение РУКОЙ по тому,
# что СЧИТАЛ влитым: `950d52cb4` несёт заголовок «merge p274-novac
# (7994d75ce)», а `git merge-base --is-ancestor 7994d75ce 950d52cb4` говорит
# НЕТ — второй родитель `290b7ab0f`. Ложь прожила бы в истории тихо, если бы не
# одно: строка реестра №988 процитировала это сообщение КАК УЛИКУ («я сам влил
# два коммита без вердикта яруса novac»), и неверный факт из истории стал
# доказательством в реестре на сутки. Нашло его чужое окно, а не механизм.
#
# ЧТО СУДИТСЯ. Только коммиты слияния (два родителя и более) в диапазоне
# `<база>..HEAD`, по умолчанию `origin/main..HEAD` — то есть ровно то, что
# готовится к отправке. Историю страж не трогает: она не переписывается, а
# краснеть на всём, что было до его заведения, значит быть отключённым в
# первый же день.
#
# ЧЕГО НЕ ЛОВИТ, ЧЕСТНО: хеши соседних реп (`nova-tls@7a44776`) — их истории
# здесь нет; форма `репозиторий@хеш` пропускается по той же причине, что и в
# `check-commit-refs.sh`. И не ловит хеш, который ДОСТИЖИМ, но назван не тем,
# чем является: достижимость — не тождественность.
#
# ИСКЛЮЧЕНИЯ: `scripts/guards/merge-message-hashes.allow`, по строке на хеш
# коммита слияния, с причиной. Историю не переписываем, поэтому уже
# случившееся заносится туда ЯВНО, а не прощается молча.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/guards/check-merge-message-hashes.sh [КОРЕНЬ] [БАЗА]
# Самотест — scripts/guards/selftest/test-check-merge-message-hashes.sh

set -u
export LC_ALL=C

NAME="check-merge-message-hashes"
ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
BASE_REF="${2:-${NOVA_MERGE_MSG_BASE:-origin/main}}"
ALLOW="${NOVA_MERGE_MSG_ALLOW:-$ROOT/scripts/guards/merge-message-hashes.allow}"

cd "$ROOT" || exit 1

if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "$NAME ok: не репозиторий — судить нечего"
    exit 0
fi
if ! git rev-parse --verify --quiet "$BASE_REF" >/dev/null 2>&1; then
    # База недоступна (свежий клон без origin) — молчать нельзя, но и красить
    # не за что: судить физически нечем. Класс №645 требует СКАЗАТЬ.
    echo "$NAME ok: базы '$BASE_REF' нет — диапазон не определён, судить нечего"
    exit 0
fi

MERGES=$(git rev-list --merges "$BASE_REF..HEAD" 2>/dev/null)
if [ -z "$MERGES" ]; then
    echo "$NAME ok: слияний в диапазоне $BASE_REF..HEAD нет"
    exit 0
fi

BAD=0
CHECKED=0
for m in $MERGES; do
    if [ -f "$ALLOW" ] && grep -q "^$m" "$ALLOW" 2>/dev/null; then
        echo "$NAME: $m — в списке исключений, пропуск"
        continue
    fi
    MSG=$(git log -1 --format=%B "$m" 2>/dev/null)
    # Кандидаты: голые хеши 7-40 hex. Форму `репо@хеш` отсекаем, вырезая её
    # целиком ДО поиска: иначе её хвост попадёт в кандидаты как голый хеш.
    HASHES=$(printf '%s\n' "$MSG" \
        | sed 's/[A-Za-z0-9_.-]*@[0-9a-f]\{7,40\}//g' \
        | grep -oE '\b[0-9a-f]{7,40}\b' | sort -u)
    for h in $HASHES; do
        CHECKED=$((CHECKED + 1))
        if ! git cat-file -e "$h^{commit}" 2>/dev/null; then
            echo "$NAME: НАРУШЕНИЕ — $m называет $h, а такого коммита нет вовсе" >&2
            BAD=$((BAD + 1))
            continue
        fi
        if ! git merge-base --is-ancestor "$h" "$m" 2>/dev/null; then
            echo "$NAME: НАРУШЕНИЕ — $m называет $h, НЕДОСТИЖИМЫЙ из него" >&2
            echo "    родители: $(git log -1 --format=%P "$m")" >&2
            BAD=$((BAD + 1))
        fi
    done
done

if [ "$BAD" -gt 0 ]; then
    echo "$NAME: FAIL — сообщений слияния, называющих чужой хеш: $BAD" >&2
    echo "    Сообщение слияния пишется по тому, что вернул git, а не по тому," >&2
    echo "    что ты считал влитым. Проверить до коммита:" >&2
    echo "      git log -1 --format=%P <коммит-слияния>" >&2
    echo "    Уже случившееся заносится в $ALLOW с причиной: историю не" >&2
    echo "    переписываем (реестр 221.1 №994)." >&2
    exit 1
fi

echo "$NAME ok: хешей в сообщениях слияния проверено $CHECKED, все достижимы"
exit 0
