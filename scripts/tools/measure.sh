#!/usr/bin/env bash
# scripts/tools/measure.sh — ЕДИНСТВЕННЫЙ законный способ снять замер времени.
#
# ЗАЧЕМ ЭТОТ СКРИПТ СУЩЕСТВУЕТ (реестр 221.1 №449, требование владельца 2026-08-08
# «заметки не помогают, используй надёжные механизмы автопроверки»):
# интегратор ТРИЖДЫ за одни сутки объявил регресс/улучшение по цифре, снятой при
# живом гейте или работающем окне. Каждый раз чистый повтор опровергал вывод:
#   * №429 «+84.5% задержки» -> чистый перемер дал ПАРИТЕТ;
#   * №437 «мега-CU 4 мин -> 18 мин» -> база 270с была поставлена ПО ПАМЯТИ;
#   * MapLitCtx «106с, стало медленнее» -> чистый повтор дал 42-53с.
# Проблема не в дисциплине, а в отсутствии механизма. Механизм — здесь:
# скрипт ОТКАЗЫВАЕТСЯ мерить на занятой машине и сам считает разброс.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/tools/measure.sh [-n ПРОГОНОВ] [-l ЯРЛЫК] -- <команда...>
# ПРИМЕР:
#   bash scripts/tools/measure.sh -n 3 -l "check-10" -- \
#       ./nova-cli/target/release/nova.exe check $(cat /tmp/f10.txt | tr '\n' ' ')
#
# КОДЫ ВОЗВРАТА: 0 — замер валиден; 1 — машина занята (замер НЕ снят);
#                2 — разброс слишком велик, цифре верить нельзя.

set -u
export LC_ALL=C

RUNS=3
LABEL="measure"
SPREAD_MAX_PCT=25   # разброс выше — цифра не доверенная

while [ $# -gt 0 ]; do
    case "$1" in
        -n) RUNS="$2"; shift 2 ;;
        -l) LABEL="$2"; shift 2 ;;
        --) shift; break ;;
        *)  echo "measure: неизвестный аргумент '$1'" >&2; exit 1 ;;
    esac
done
[ $# -gt 0 ] || { echo "measure: не задана команда (после --)" >&2; exit 1; }

# ── ВОРОТА 1: машина обязана быть свободна ────────────────────────────────
# ТРИ независимых признака. Проверка по ИМЕНИ ИСПОЛНЯЕМОГО ФАЙЛА (basename),
# а НЕ по подстроке пути: первая редакция считала занятым любой процесс, чей
# путь содержит «nova» — то есть себя же, и одновременно НЕ ловила гейт.
# Поймано собственным селфтестом (страж без селфтеста не работает).
BUSY=""

# Переключатель ТОЛЬКО для селфтеста: снимает ВСЕ ворота занятости разом.
# Нужен потому, что селфтест запускается ИЗНУТРИ гейта, где живы cargo/clang/
# nova.exe, — и случаи, проверяющие ДРУГИЕ свойства (разброс, отсутствие
# ложных срабатываний), падали не по своей теме. Гасить ворота по одному
# оказалось недостаточно: трижды подряд вылезало то, что не заглушили.
# В рабочем пути НЕ ставить — цифра, снятая с этим флагом, недействительна.
if [ "${NOVA_MEASURE_SELFTEST_NO_GATES:-0}" = "1" ]; then
    BUSY=""
else

# (1) идущий гейт: лог есть, вердикта ещё нет
if [ -f /tmp/gate_full.log ] && [ ! -f /tmp/gate_full.done ]; then
    BUSY="$BUSY гейт-идёт"
fi

# (2) конкурирующие сборки/прогоны — по ИМЕНИ бинаря
for exe in cargo.exe clang.exe cl.exe link.exe rustc.exe nova.exe; do
    n=$(ps -W 2>/dev/null | awk '{print $NF}' | sed 's#.*[\\/]##' | grep -icx "$exe" || true)
    [ "${n:-0}" -gt 0 ] && BUSY="$BUSY $exe($n)"
done

# (3) фоновая загрузка ЦП: даже без опознанных имён машина может быть занята
# ДВА ИСТОЧНИКА, ПОТОМУ ЧТО `wmic` ЕСТЬ ТОЛЬКО НА WINDOWS (№765, 2026-08-26).
# На Linux он не находится, `CPU` оставался пуст, и вся защита «не мерить
# на занятой машине» там просто НЕ РАБОТАЛА — проверка, зелёная оттого, что
# никогда не исполнялась. `/proc/loadavg` даёт среднюю за минуту очередь;
# нормируем на число ядер и переводим в проценты — тот же смысл, что у wmic.
CPU=$(wmic cpu get loadpercentage //value 2>/dev/null \
      | tr -d '\r' | sed -n 's/^LoadPercentage=//p' | head -1)
if [ -z "${CPU:-}" ] && [ -r /proc/loadavg ]; then
    CPU=$(awk -v n="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 1)" \
              '{ p = ($1 / (n > 0 ? n : 1)) * 100; printf "%d", (p < 0 ? 0 : p) }' \
              /proc/loadavg 2>/dev/null)
fi
CPU_MAX=${NOVA_MEASURE_CPU_MAX:-35}
if [ -n "${CPU:-}" ] && [ "$CPU" -gt "$CPU_MAX" ]; then
    BUSY="$BUSY загрузка-ЦП(${CPU}%>${CPU_MAX}%)"
fi

fi

if [ -n "$BUSY" ]; then
    echo "measure: ОТКАЗ — машина занята:$BUSY" >&2
    echo "measure: замер на занятой машине НЕ ЗАСЧИТЫВАЕТСЯ (см. шапку скрипта)." >&2
    echo "measure: дождись завершения гейта/сборок/окон и повтори." >&2
    exit 1
fi

# ── Прогоны ───────────────────────────────────────────────────────────────
TIMES=""
for i in $(seq 1 "$RUNS"); do
    S=$SECONDS
    "$@" >/dev/null 2>&1
    rc=$?
    T=$((SECONDS - S))
    TIMES="$TIMES $T"
    echo "measure[$LABEL] прогон $i: ${T}с (код $rc)"
done

# ── ВОРОТА 2: разброс ─────────────────────────────────────────────────────
MIN=$(echo $TIMES | tr ' ' '\n' | sort -n | head -1)
MAX=$(echo $TIMES | tr ' ' '\n' | sort -n | tail -1)
MED=$(echo $TIMES | tr ' ' '\n' | sort -n | awk '{a[NR]=$1} END{print a[int((NR+1)/2)]}')

DELTA=$(( MAX - MIN ))
if [ "${MED:-0}" -gt 0 ]; then
    SPREAD=$(( DELTA * 100 / MED ))
elif [ "$DELTA" -gt 0 ]; then
    # Медиана 0 при ненулевой разнице — относительный разброс БЕСКОНЕЧЕН.
    # Поймано селфтестом: прежняя редакция выдавала здесь «разброс 0%» и
    # объявляла замер валидным при мин=0с / макс=3с.
    SPREAD=999
else
    SPREAD=0
fi

echo "measure[$LABEL] МЕДИАНА=${MED}с  мин=${MIN}с  макс=${MAX}с  разброс=${SPREAD}%"

# Абсолютный порог — страховка от «мал процент, но велика разница» и наоборот.
DELTA_MAX=${NOVA_MEASURE_DELTA_MAX:-2}
if [ "$DELTA" -gt "$DELTA_MAX" ] && [ "$SPREAD" -gt "$SPREAD_MAX_PCT" ]; then
    echo "measure: РАЗБРОС ${SPREAD}% (${DELTA}с) — цифре верить НЕЛЬЗЯ." >&2
    echo "measure: увеличь число прогонов (-n) либо освободи машину." >&2
    exit 2
fi

if [ "$SPREAD" -gt "$SPREAD_MAX_PCT" ] && [ "$DELTA" -gt "$DELTA_MAX" ]; then
    echo "measure: РАЗБРОС ${SPREAD}% > ${SPREAD_MAX_PCT}% — цифре верить НЕЛЬЗЯ." >&2
    echo "measure: увеличь число прогонов (-n) либо освободи машину." >&2
    exit 2
fi

echo "measure[$LABEL] замер ВАЛИДЕН: ${MED}с"
exit 0
