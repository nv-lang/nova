#!/usr/bin/env bash
# scripts/tools/run-guard-selftest.sh — ОДИН самотест стража, для параллельного запуска.
#
# ЗАЧЕМ. Профиль гейта 2026-08-12 (`scripts/tools/gate-profile.sh` по
# gate-run8.log): самотесты стражей — 1125 секунд из ~3400, то есть ТРЕТЬ всего
# прогона и первый потребитель с большим отрывом. Шли они строго
# последовательно, хотя каждый самотест по построению изолирован: свой
# `mktemp -d` либо `$$`-суффикс, ни один не пишет в настоящее дерево (проверено
# грепом по всем 43 перед введением параллельности — единственный кандидат,
# `test-check-worktree-location.sh`, заводит worktree внутри СВОЕГО временного
# репозитория, не в рабочем).
#
# Последовательность здесь ничего не охраняла — она была просто формой цикла.
#
# ЧТО ДЕЛАЕТ. Гоняет один самотест под тем же сроком, что стоял в гейте, и:
#   * копит вывод и печатает его ОДНИМ куском — иначе при параллельном запуске
#     строки разных самотестов перемешиваются и лог становится нечитаемым;
#   * при провале кладёт файл с именем самотеста в каталог провалов, чтобы
#     вызывающий собрал их после `xargs` и назвал каждый поимённо (код возврата
#     самого `xargs` сказал бы только «что-то упало»).
#
# ПОЧЕМУ НЕ ПРОСТО `xargs ... || fail`. Гейт обязан НАЗЫВАТЬ упавшего: правило
# «не рапортовать счёт, которого не видел» (реестр 221.1 №475 и родня). Файл в
# каталоге провалов — самый дешёвый способ передать имя через границу процесса.
#
# ИСПОЛЬЗОВАНИЕ (вызывается гейтом, руками обычно не нужен):
#   bash scripts/tools/run-guard-selftest.sh <путь-к-самотесту> <каталог-провалов> <корень>

set -u
export LC_ALL=C

ST="${1:?нет пути к самотесту}"
FAILDIR="${2:?нет каталога провалов}"
ROOT="${3:?нет корня дерева}"

NAME="$(basename "$ST")"

# БЮДЖЕТ (секунды на СВОБОДНОЙ машине) × КАЛИБРОВОЧНЫЙ МНОЖИТЕЛЬ.
#
# Было: жёсткий предел 300с и ИМЕННЫЕ исключения на 900с, каждое со своим
# ручным замером. Оно не масштабировалось: прогон гейта 18 покраснел на
# `test-check-doc-conventions.sh`, который идёт 46с в одиночку — то есть с
# запасом в шесть раз — и всё равно был убит под параллельной нагрузкой.
# Добавить третье исключение значило бы продолжить способ, которым проблема
# и накопилась.
#
# Стало: число описывает САМ САМОТЕСТ («сколько ему надо на свободной
# машине»), а поправку на занятость машины даёт `cal-factor.sh`, который
# измеряет её пробой из N параллельных процессов. Замер 2026-08-17: тот же
# набор самотестов под `-P 8` завершил 37 штук за 120с на свободной машине и
# 22 за те же 120с при работающем рядом воркфлоу.
#
# Множитель ограничен восьмёркой: без потолка «машина занята» и «самотест
# завис» стали бы неразличимы, а это ровно тот дефект (№475), ради которого
# сроки заведены.
case "$NAME" in
    # Компилирует примеры — 224с на свободной машине (замер 2026-08-13).
    test-check-doc-examples.sh) BUDGET=300; FLOOR=900 ;;
    # Гоняет страж doc-truth несколько раз — ~210с (замер 2026-08-14).
    test-check-doc-truth.sh)    BUDGET=300; FLOOR=900 ;;
    # Остальным приёмка №558 отводит минуту; берём вдвое с запасом на то,
    # что часть из них зовёт nova-бинарь.
    *)                          BUDGET=120; FLOOR=300 ;;
esac

# Множитель считает ГЕЙТ один раз на весь цикл и передаёт сюда: проба сама
# поднимает 8 процессов, и звать её на каждый самотест значило бы 45×8
# лишних запусков плюс добавленную нагрузку в тот самый замер. Если
# переменной нет (самотест запущен руками) — считаем на месте.
CAL="${NOVA_CAL_FACTOR:-}"
[ -n "$CAL" ] || CAL=$(bash "$ROOT/scripts/tools/cal-factor.sh" "$ROOT" 2>/dev/null)
case "$CAL" in ''|*[!0-9]*) CAL=1 ;; esac
[ "$CAL" -ge 1 ] || CAL=1
DEADLINE=$(( BUDGET * CAL ))

# ПОЛ — ПОИМЁННЫЙ, и он в точности равен прежнему пределу каждого самотеста
# (900 у двух тяжёлых, 300 у остальных). Общий пол в 300 урезал бы тяжёлым
# втрое — правка против ложных отказов породила бы их сама.
#
# Пол страхует случай, когда калибровка почему-либо вернула 1 (нет питона,
# испорчена база): тогда бюджеты 120/300 дали бы пределы УЖЕ прежних, и
# ложных отказов стало бы больше, а не меньше. Снять его можно будет тогда,
# когда калибровка станет обязательной, а не запасной — то есть когда её
# отказ будет считаться отказом гейта.
[ "$DEADLINE" -ge "$FLOOR" ] || DEADLINE="$FLOOR"

OUT="$(bash "$ROOT/scripts/tools/with-deadline.sh" "$DEADLINE" bash "$ST" 2>&1)"
RC=$?

# Один write вместо построчного — при -P N строки иначе чередуются.
printf '%s\n' "$OUT"

if [ "$RC" -ne 0 ]; then
    printf '%s\n' "$OUT" > "$FAILDIR/$NAME"
fi

# Всегда 0: провал передаётся ФАЙЛОМ, а не кодом возврата. Иначе `xargs`
# оборвал бы очередь на первом упавшем, и мы бы не узнали про остальные —
# ровно та слепота, из-за которой гейт вообще копит отказы, а не выходит на
# первом (см. шапку gate.sh).
exit 0
