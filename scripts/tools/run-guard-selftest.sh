#!/usr/bin/env bash
# scripts/tools/run-guard-selftest.sh — ОДИН самотест стража, для параллельного запуска.
#
# ЗАЧЕМ. Профиль гейта 2026-08-12 (`scripts/tools/gate-profile.sh` по
# gate-run8.log): самотесты стражей — 1125 секунд из ~3400, то есть ТРЕТЬ всего
# прогона и первый потребитель с большим отрывом. Шли они строго
# последовательно, хотя каждый самотест по построению изолирован: свой
# `mktemp -d` либо `$$`-суффикс, ни один не пишет в настоящее дерево (проверено
# грепом по всем 43 перед введением параллельности — единственный кандидат,
# `test-check-worktree-location.sh`, заводит worktree внутри СВОЕГО временного
# репозитория, не в рабочем).
#
# Последовательность здесь ничего не охраняла — она была просто формой цикла.
#
# ЧТО ДЕЛАЕТ. Гоняет один самотест под тем же сроком, что стоял в гейте, и:
#   * копит вывод и печатает его ОДНИМ куском — иначе при параллельном запуске
#     строки разных самотестов перемешиваются и лог становится нечитаемым;
#   * при провале кладёт файл с именем самотеста в каталог провалов, чтобы
#     вызывающий собрал их после `xargs` и назвал каждый поимённо (код возврата
#     самого `xargs` сказал бы только «что-то упало»).
#
# ПОЧЕМУ НЕ ПРОСТО `xargs ... || fail`. Гейт обязан НАЗЫВАТЬ упавшего: правило
# «не рапортовать счёт, которого не видел» (реестр 221.1 №475 и родня). Файл в
# каталоге провалов — самый дешёвый способ передать имя через границу процесса.
#
# ИСПОЛЬЗОВАНИЕ (вызывается гейтом, руками обычно не нужен):
#   bash scripts/tools/run-guard-selftest.sh <путь-к-самотесту> <каталог-провалов> <корень>

set -u
export LC_ALL=C

ST="${1:?нет пути к самотесту}"
FAILDIR="${2:?нет каталога провалов}"
ROOT="${3:?нет корня дерева}"

NAME="$(basename "$ST")"

# Срок тот же, что стоял в последовательной версии (300с, реестр №558 — мера
# ВРЕМЕННАЯ: приёмка №558 — ни один самотест не требует больше минуты, и тогда
# срок вернётся вниз). Не уложился — он не медленный, он сломан (№475).
OUT="$(bash "$ROOT/scripts/tools/with-deadline.sh" 300 bash "$ST" 2>&1)"
RC=$?

# Один write вместо построчного — при -P N строки иначе чередуются.
printf '%s\n' "$OUT"

if [ "$RC" -ne 0 ]; then
    printf '%s\n' "$OUT" > "$FAILDIR/$NAME"
fi

# Всегда 0: провал передаётся ФАЙЛОМ, а не кодом возврата. Иначе `xargs`
# оборвал бы очередь на первом упавшем, и мы бы не узнали про остальные —
# ровно та слепота, из-за которой гейт вообще копит отказы, а не выходит на
# первом (см. шапку gate.sh).
exit 0
