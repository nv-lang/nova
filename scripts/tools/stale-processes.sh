#!/usr/bin/env bash
# scripts/tools/stale-processes.sh — ПЕРЕЧЕНЬ забытых фоновых процессов. Ничего не
# убивает, и это свойство построения, а не обещание: в файле нет ни `kill`, ни
# `taskkill`, и самотест держит это грепом.
#
# ЗАЧЕМ (поручение владельца 2026-09-23, пункт 5 из восьми). В тот день из
# машины вычищено пятнадцать забытых `tail -f`: их оставляли окна, следившие за
# логом гейта, и ни одно не сняло своё. Узнали об этом случайно. Процесс, который
# никто не видит, живёт до перезагрузки и держит файл, дескриптор и строку в
# `ps`, по которой следующее окно гадает, чей это прогон.
#
# ПОЧЕМУ ТОЛЬКО ПЕРЕЧЕНЬ. На машине работают несколько окон и несколько учёток:
# «старый процесс» бывает чужим живым сервером (замер того же вечера: `npx nuxt
# --port 1306` с 15-го числа и оболочка сессии другой учётки с 19-го). Убивать по
# возрасту значит однажды убить чужую работу. Решает окно, которое процесс
# узнаёт, — это видно по команде.
#
# ЧТО СЧИТАЕТСЯ ЗАБЫТЫМ (по выводу `ps -ef` в msys/Git Bash):
#   * начат НЕ СЕГОДНЯ — у msys `ps` столбец STIME тогда несёт дату, а не время;
#   * «вечный» процесс слежения (`tail -f`, `sleep N`, `while true`, `watch`),
#     начатый сегодня, но больше часа назад.
# Родитель PID 1 признаком НЕ служит: так выглядит и оболочка текущей команды
# Claude Code (замер 2026-09-23).
#
# ИСПОЛЬЗОВАНИЕ: bash scripts/tools/stale-processes.sh
#   Код выхода всегда 0: это сведения, а не вердикт.
#   Шов самотеста: STALE_PS_FILE — готовый вывод `ps -ef` вместо живого,
#   STALE_NOW — «сейчас» в формате ЧЧ:ММ:СС.
set -u
export LC_ALL=C

if [ -n "${STALE_PS_FILE:-}" ]; then
    PS_OUT=$(cat "$STALE_PS_FILE")
else
    PS_OUT=$(ps -ef 2>/dev/null)
fi
NOW="${STALE_NOW:-$(date +%H:%M:%S)}"

printf '%s\n' "$PS_OUT" | awk -v now="$NOW" '
    function secs(t,   a) { split(t, a, ":"); return a[1] * 3600 + a[2] * 60 + a[3] }
    NR == 1 { next }
    {
        # Столбцы msys ps -ef: UID PID PPID TTY STIME COMMAND...; у STIME-даты
        # два поля («Sep 19»), у STIME-времени одно («23:03:31»).
        # Строка ПРОЦЕССА, а не продолжение многострочной команды: `ps -ef`
        # печатает тело `bash -c "<скрипт>"` как есть, и без этой проверки каждая
        # строка чужого скрипта читалась процессом (первый прогон на машине дал
        # 57 «процессов», из них настоящих — четыре).
        if ($2 !~ /^[0-9]+$/ || $3 !~ /^[0-9]+$/) next
        pid = $2
        if ($5 ~ /^[0-9][0-9]?:[0-9][0-9]:[0-9][0-9]$/) {
            start = $5; cmd_from = 6; today = 1
        } else if ($5 ~ /^[A-Z][a-z][a-z]$/ && $6 ~ /^[0-9][0-9]?$/) {
            start = $5 " " $6; cmd_from = 7; today = 0
        } else next
        cmd = ""
        for (i = cmd_from; i <= NF; i++) cmd = cmd (i > cmd_from ? " " : "") $i
        why = ""
        if (!today) {
            why = "начат не сегодня"
        } else if (cmd ~ /(^|[ \/])tail -f|(^|[ \/])sleep [0-9]|while true|(^|[ \/])watch / && secs(now) - secs(start) > 3600) {
            why = "слежение старше часа"
        }
        if (why != "") {
            n++
            printf "   PID %s · с %s · %s · %s\n", pid, start, why, substr(cmd, 1, 140)
        }
    }
    END {
        if (n == 0) print "stale-processes ok: забытых фоновых процессов не видно (ps -ef)"
        else printf "stale-processes: перечислено %d, не снят НИ ОДИН — снимает только окно, которое узнаёт свой процесс по команде\n", n
    }
'
exit 0
