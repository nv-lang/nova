#!/bin/sh
# scripts/tools/wait-for-verdict.sh — синхронное ожидание вердикта долгой команды
# с печатью прогресса.
#
# ЗАЧЕМ. Два правила окна тянут в разные стороны, и без этого приёма они
# несовместимы:
#   * `flow.md`: окно, закончившее ход ожиданием фоновой задачи, мертво —
#     долгое положено делать синхронно;
#   * сторож снимает окно за ДЕСЯТЬ МИНУТ без вывода, а ярус гейта идёт
#     восемь-двенадцать.
# Прямой `bash gate.sh` в переднем плане упирается и в потолок таймаута
# инструмента (600с), и в молчание. Этот цикл смотрит в лог, печатает строку
# состояния раз в интервал и выходит, как только вердикт появился, — окно
# остаётся живым и видно, на какой стадии прогон.
#
# Замерено окном 274 за смену 2026-08-30: приём применён четырежды (ярусы novac
# и main, CI-прогон, тихий замер), и каждый раз заменял собой либо мёртвое
# ожидание, либо серию слепых опросов.
#
# ПОЧЕМУ АРГУМЕНТАМИ, А НЕ КОПИЕЙ: первая версия жила в scratchpad с зашитыми
# путями, и её пришлось править `sed`'ом под каждый новый лог. Копия под задачу
# расходится с оригиналом на первой же правке — то же правило, по которому в
# этом проекте не заводят вторых копий чего бы то ни было.
#
# Использование:
#   sh scripts/tools/wait-for-verdict.sh <лог> <шаблон-вердикта> [предел_сек] [интервал_сек]
#
# Примеры:
#   sh scripts/tools/wait-for-verdict.sh target/gate.log 'GATE (OK|FAIL)'
#   sh scripts/tools/wait-for-verdict.sh target/push.log 'unpushed:|rc=1' 900 60
#
# Код возврата: 0 — вердикт найден; 1 — вышел предел (вердикта нет).
set -u
export LC_ALL=C

LOG=${1:-}
PAT=${2:-}
LIMIT=${3:-540}
STEP=${4:-30}

if [ -z "$LOG" ] || [ -z "$PAT" ]; then
    echo "usage: $0 <logfile> <verdict-regex> [limit_sec] [step_sec]" >&2
    exit 2
fi

n=0
while [ "$n" -lt "$LIMIT" ]; do
    # Вердикт ищется в ЦЕЛОМ логе, а не в хвосте: длинный прогон печатает после
    # вердикта ещё несколько строк, и `tail -1` их бы и показал.
    v=$(grep -aE "$PAT" "$LOG" 2>/dev/null | tail -1 | cut -c1-96)
    # Хвост — чтобы видеть, ЧТО идёт сейчас; без него строка прогресса
    # неотличима от зависания.
    s=$(tail -n 1 "$LOG" 2>/dev/null | cut -c1-64)
    if [ -n "$v" ]; then
        echo "[${n}s] VERDICT: $v"
        exit 0
    fi
    echo "[${n}s] ... :: $s"
    sleep "$STEP"
    n=$((n + STEP))
done

echo "[${n}s] LIMIT REACHED, no verdict matching /$PAT/ in $LOG" >&2
tail -n 3 "$LOG" 2>/dev/null >&2
exit 1
