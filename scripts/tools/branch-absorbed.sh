#!/usr/bin/env bash
# scripts/tools/branch-absorbed.sh
# Вошла ли работа ветки в базу — ОДНА дверь для этого вопроса.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №629 (доработка 2026-08-13), план 231 трек Д.
#
# ЗАЧЕМ. Вопрос «можно ли удалить эту ветку» задаётся в проекте постоянно —
# суточной уборкой, храповиком накопления, стражем принятых веток, интегратором
# перед релизом. И ровно на нём 2026-08-13 я ошибся ДВАЖДЫ подряд, обоими
# способами сразу: сверял поглощение трёхточечным диффом `main...ветка`.
#
# ПОЧЕМУ ТРЁХТОЧЕЧНЫЙ ДИФФ ЗДЕСЬ ЛЖЁТ. `A...B` — это «изменения B от ОБЩЕГО
# ПРЕДКА», и общий предок берётся ОДИН. Когда баз слияния несколько (ветка
# ловила main несколько раз), git выбирает произвольную и говорит об этом одной
# строкой в stderr, которую никто не читает:
#     warning: multiple merge bases, using db6dd4f71
# С древней базы давно влитый код выглядит ОТСУТСТВУЮЩИМ. Так `p-fix-n38-
# workertls` дважды пережила разбор с вердиктом «настоящая работа, удалять на
# догадке нельзя», хотя её фикс лежал в main с июля.
#
# ЧЕМ СВЕРЯТЬ ВМЕСТО ЭТОГО — тремя вопросами, ни один из которых не про дифф:
#   1. ПРЕДОК ли ветка базе (`merge-base --is-ancestor`) — влита как есть.
#   2. `git cherry` — есть ли у коммитов ветки эквивалент в базе ПО PATCH-ID.
#      Ровно это отвечает «работа вошла другим путём» (rebase, cherry-pick,
#      переписанная история, перенос в соседнюю репу нашей рукой).
#   3. Сравнение ВЕРШИН (`git diff база ветка`) — что в действительности
#      различается сейчас. Двухточечная форма не знает слова «предок» и потому
#      не умеет соврать про него.
# И четвёртым — СКОЛЬКО баз слияния: если больше одной, всякий вывод, взятый
# трёхточечной формой, обязан быть перепроверен.
#
# ЧЕГО НЕ ОТВЕЧАЕТ (сказано честно): «поглощена ли работа СМЫСЛОВО» — когда
# она переписана заново, переехала в другой репозиторий или вошла под другими
# именами. Тут не поможет никакой git: patch-id считает байты, а не замысел.
# Инструмент прямо говорит «решай глазами» и называет, куда смотреть.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/tools/branch-absorbed.sh <ветка> [база]      # база = main
# Код возврата: 0 — ветку можно удалять (влита либо все патчи есть в базе);
#               2 — есть коммиты без эквивалента, нужен человек;
#               1 — ошибка употребления.

set -u
export LC_ALL=C

BRANCH="${1:-}"
BASE="${2:-main}"

if [ -z "$BRANCH" ]; then
    echo "использование: branch-absorbed.sh <ветка> [база]" >&2
    exit 1
fi

git rev-parse --verify --quiet "$BRANCH" >/dev/null 2>&1 \
    || { echo "нет такой ветки: $BRANCH" >&2; exit 1; }
git rev-parse --verify --quiet "$BASE" >/dev/null 2>&1 \
    || { echo "нет такой базы: $BASE" >&2; exit 1; }

echo "=== $BRANCH  ->  $BASE ==="
echo "вершина ветки: $(git rev-parse --short "$BRANCH")   (запиши её, прежде чем удалять)"

# --- 0. Сколько баз слияния -------------------------------------------------
NBASES=$(git merge-base --all "$BASE" "$BRANCH" 2>/dev/null | grep -c .)
if [ "${NBASES:-0}" -gt 1 ]; then
    echo
    echo "!!! баз слияния: $NBASES — трёхточечная форма ($BASE...$BRANCH) здесь НЕДОСТОВЕРНА."
    echo "!!! git возьмёт одну базу произвольно и покажет влитое как отсутствующее."
fi

# --- 1. Предок ли ------------------------------------------------------------
if git merge-base --is-ancestor "$BRANCH" "$BASE" 2>/dev/null; then
    echo
    echo "ВЛИТА: ветка — предок $BASE, в ней нет ничего своего. Удалять безопасно."
    exit 0
fi

# --- 2. Patch-id: вошло ли другим путём -------------------------------------
# `git cherry база ветка` печатает по строке на коммит ветки:
#   `+ <sha>` — эквивалента в базе НЕТ;  `- <sha>` — эквивалент уже есть.
CHERRY=$(git cherry "$BASE" "$BRANCH" 2>/dev/null)
PLUS=$(printf '%s\n' "$CHERRY" | grep -c '^+' || true)
MINUS=$(printf '%s\n' "$CHERRY" | grep -c '^-' || true)

echo
echo "коммитов ветки:  $((PLUS + MINUS))"
echo "  уже в базе по patch-id: $MINUS"
echo "  без эквивалента:        $PLUS"

# --- 3. Чем различаются ВЕРШИНЫ (двухточечная форма) ------------------------
echo
echo "--- сравнение вершин ($BASE vs $BRANCH), двухточечная форма ---"
git diff --shortstat "$BASE" "$BRANCH" 2>/dev/null | sed 's/^/    /'
BEHIND=$(git rev-list --count "$BRANCH".."$BASE" 2>/dev/null)
echo "    ветка отстаёт от $BASE на $BEHIND коммит(ов)"

if [ "${PLUS:-0}" -eq 0 ]; then
    echo
    echo "ПОГЛОЩЕНА: своих коммитов нет — все имеют эквивалент в $BASE по patch-id."
    echo "Удалять безопасно; вершину выше запиши в сообщение коммита."
    exit 0
fi

echo
echo "НУЖЕН ЧЕЛОВЕК: $PLUS коммит(ов) без эквивалента в $BASE."
echo "  Прежде чем звать их работой, проверь ДВЕ вещи, на которых я ошибся:"
echo "    * не уехала ли работа в другой репозиторий — прочти статус её плана;"
echo "    * присутствует ли КЛЮЧЕВОЙ СИМВОЛ правки в $BASE (grep по имени"
echo "      функции), а не «показывает ли что-то дифф ветки»."
echo "  Свои коммиты:"
printf '%s\n' "$CHERRY" | grep '^+' | head -20 | sed 's/^/    /'
exit 2
