#!/usr/bin/env bash
# scripts/tools/registry-add.sh — положить реестр в индекс, назвав СВОИ номера.
#
# ДОМ И ОСНОВАНИЕ: реестр 221.1 №642, план 231 трек Д.
#
# ЗАЧЕМ. Правило проекта «`git add` только по именам файлов» защищает от чужих
# ФАЙЛОВ и бессильно против чужих СТРОК в общем файле. Реестр 221.1 —
# единственный файл, который правят одновременно из разных сессий, и 2026-08-13
# это выстрелило дважды подряд: коммит `guard(#639)` унёс запись параллельной
# сессии (№640, замер цены сборки), а следующую свою запись я завёл ТЕМ ЖЕ
# номером — дубль, который всякий поиск по номеру разрешил бы в пользу первой
# строки, молча.
#
# ЧТО ДЕЛАЕТ. Спрашивает у тебя, какие номера ты собирался завести или тронуть,
# и сверяет с тем, что РЕАЛЬНО изменилось в файле относительно HEAD. Расхождение
# в любую сторону — отказ:
#   * добавлена строка с номером, которого ты не называл — это чужая работа
#     либо твоя ошибка нумерации;
#   * ты назвал номер, а строки нет — правка не легла (мохибейк, не тот якорь).
# Дубли номеров проверяются отдельно и всегда.
#
# ЧЕГО НЕ ДЕЛАЕТ (сказано честно): не отличает твою правку ТЕЛА чужой записи от
# законной — если ты дописал строку, которую сам же и назвал, инструмент
# промолчит. Он ловит забывчивость и столкновение, а не умысел.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/tools/registry-add.sh 641 642        # завожу/правлю эти
#   bash scripts/tools/registry-add.sh --check 641    # только проверить
# После успеха файл лежит в индексе; коммить как обычно.

set -u
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
REG="docs/plans/221.1-bug-sweep.md"
CHECK_ONLY=0

ARGS=()
for a in "$@"; do
    case "$a" in
        --check) CHECK_ONLY=1 ;;
        *) ARGS+=("$a") ;;
    esac
done

if [ "${#ARGS[@]}" -eq 0 ]; then
    echo "использование: registry-add.sh [--check] НОМЕР [НОМЕР…]" >&2
    echo "  назови номера записей, которые ты завёл или тронул в этой правке" >&2
    exit 1
fi

cd "$ROOT" || exit 1

TMP="${TMPDIR:-/tmp}/regadd_$$"
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

git show "HEAD:$REG" > "$TMP/head.md" 2>/dev/null || : > "$TMP/head.md"

# Номера строк реестра в обеих версиях. Якорь — НАЧАЛО строки: тот же номер
# встречается значением колонки в сводных таблицах (урок №488).
nums() { grep -aoE '^\| [0-9]+ \|' "$1" | grep -oE '[0-9]+' | sort -n; }

nums "$TMP/head.md" > "$TMP/before.txt"
nums "$REG"         > "$TMP/after.txt"

# 1. Дубли — всегда и независимо от заявленного.
DUP=$(uniq -d < "$TMP/after.txt")
if [ -n "$DUP" ]; then
    echo "registry-add: ДУБЛИ НОМЕРОВ — поиск по номеру найдёт только первую строку:" >&2
    printf '%s\n' "$DUP" | sed 's/^/    №/' >&2
    exit 1
fi

# 2. Что появилось на самом деле.
ADDED=$(comm -13 "$TMP/before.txt" "$TMP/after.txt")

# 3. Что заявлено.
printf '%s\n' "${ARGS[@]}" | sort -n > "$TMP/claimed.txt"

UNCLAIMED=$(comm -23 <(printf '%s\n' "$ADDED" | sed '/^$/d') "$TMP/claimed.txt")
if [ -n "$UNCLAIMED" ]; then
    echo "registry-add: В ФАЙЛЕ ЕСТЬ ЗАПИСИ, КОТОРЫХ ТЫ НЕ НАЗЫВАЛ:" >&2
    printf '%s\n' "$UNCLAIMED" | sed 's/^/    №/' >&2
    echo "" >&2
    echo "    Это либо работа параллельной сессии (тогда НЕ клади её в свой" >&2
    echo "    коммит — дождись её автора), либо ты ошибся номером." >&2
    echo "    Реестр 221.1 №642." >&2
    exit 1
fi

MISSING=$(comm -13 <(printf '%s\n' "$ADDED" | sed '/^$/d') "$TMP/claimed.txt")
if [ -n "$MISSING" ]; then
    echo "registry-add: ЗАЯВЛЕНЫ, НО В ФАЙЛЕ НЕ ПОЯВИЛИСЬ:" >&2
    printf '%s\n' "$MISSING" | sed 's/^/    №/' >&2
    echo "    (правка не легла: мохибейк, не тот якорь, забытая запись файла)" >&2
    echo "    Если ты ПРАВИЛ существующую запись, а не заводил — это нормально." >&2
fi

if [ "$CHECK_ONLY" -eq 1 ]; then
    echo "registry-add ok: добавлено ровно заявленное ($(printf '%s\n' "$ADDED" | sed '/^$/d' | tr '\n' ' '))"
    exit 0
fi

git add "$REG"
echo "registry-add ok: $REG в индексе; добавлено: $(printf '%s\n' "$ADDED" | sed '/^$/d' | tr '\n' ' ')"
