#!/usr/bin/env bash
# scripts/tools/cal-factor.sh — во сколько раз ЭТА машина СЕЙЧАС медленнее эталона.
#
# ЗАЧЕМ. Пределы времени в гейте стояли константами (300с на самотест), а
# пропускная способность машины меняется в разы от посторонней нагрузки.
# Замер 2026-08-17: один и тот же набор самотестов под `-P 8` завершил 37 штук
# за 120с на свободной машине и 22 штуки за те же 120с, когда параллельно шёл
# фоновой воркфлоу — падение на 40% без единой правки кода. Прогон гейта 18
# покраснел именно так: `test-check-doc-conventions.sh`, идущий 46с в одиночку,
# был убит пределом 300с. Ложный отказ дороже пропущенного: он стоит
# сорокаминутного перезапуска и учит не верить гейту.
#
# Прежнее лекарство — ИМЕННЫЕ исключения с ручным замером
# (`doc-examples` → 900, `doc-truth` → 900). Оно не масштабируется: каждый
# новый выброс требует своего прогона, своего замера и своей строки, а список
# растёт при любом изменении нагрузки. Здесь исключения заменяются на ОДНО
# число, которое машина измеряет о себе сама.
#
# арифметику в один поток и оказалась слепой: под той же нагрузкой она дала
# 55 мс против 55 мс на свободной машине. Убивает самотесты не скорость одного
# процессов. Поэтому проба запускает N процессов разом и меряет wall-time
# ВМЕСТЕ со стартом: на этой же машине один поток дал 55 мс, восемь
# параллельно — 1240 мс. Старт процесса под нагрузкой дорожает тоже, и это
# часть измеряемого, а не помеха ему.
#
# ПОЧЕМУ ОТКАЗ = 1. Нет питона, нет базы, база испорчена — печатаем 1, и
# вызывающий получает ровно сегодняшнее поведение. Калибровка не имеет права
# сделать гейт ХУЖЕ, чем он был без неё.
#
# ПОТОЛОК 8. Калибровка не должна превращать ЗАВИСШИЙ самотест в получасовое
# ожидание: без потолка «машина занята» и «самотест сломан» становятся
# неразличимы, а это ровно тот дефект (№475), ради которого сроки и заведены.
#
# План: docs/plans/231-bug-cycle-exit.md (дисциплина механизмов принуждения),
# страж ничего не доказал).
#
# ИСПОЛЬЗОВАНИЕ:
#   FACTOR=$(bash scripts/tools/cal-factor.sh "$ROOT")   # печатает целое 1..8
set -u
export LC_ALL=C

ROOT="${1:-.}"
BASE_FILE="$ROOT/scripts/tools/cal-factor.baseline"

fallback() { echo 1; exit 0; }

command -v python >/dev/null 2>&1 || fallback
[ -f "$BASE_FILE" ] || fallback

REF=$(grep -m1 '^ms=' "$BASE_FILE" 2>/dev/null | cut -d= -f2)
PAR=$(grep -m1 '^parallel=' "$BASE_FILE" 2>/dev/null | cut -d= -f2)
case "$REF" in ''|*[!0-9]*) fallback ;; esac
case "$PAR" in ''|*[!0-9]*) PAR=8 ;; esac
[ "$REF" -gt 0 ] || fallback
[ "$PAR" -gt 0 ] || PAR=8

PROBE="${TMPDIR:-/tmp}/cal-probe-$$.py"
cat > "$PROBE" <<'PY'
s = 0
for i in range(400000):
    s += (i * i) % 7
PY
trap 'rm -f "$PROBE"' EXIT

# Wall-time N параллельных процессов — вместе со стартом, см. шапку.
#
# ТРИ РАУНДА, БЕРЁМ МИНИМУМ. Один замер шумит заметно: на свободной машине
# пять прогонов дали 393/349/563/438/394 мс — разброс в 1.6 раза, и одиночная
# выборка выдавала бы то множитель 1, то 2 без всякой смены нагрузки. Минимум
# из трёх стоит ~1.5 секунды на весь гейт (считается один раз) и убирает шум:
# нагрузка время добавляет, но никогда не отнимает.
NOW=""
_r=0
while [ "$_r" -lt 3 ]; do
    T0=$(date +%s%N 2>/dev/null) || fallback
    case "$T0" in ''|*[!0-9]*) fallback ;; esac
    _i=0
    while [ "$_i" -lt "$PAR" ]; do
        python "$PROBE" >/dev/null 2>&1 &
        _i=$((_i + 1))
    done
    wait
    T1=$(date +%s%N 2>/dev/null)
    case "$T1" in ''|*[!0-9]*) fallback ;; esac
    _ms=$(( (T1 - T0) / 1000000 ))
    if [ -z "$NOW" ] || [ "$_ms" -lt "$NOW" ]; then NOW=$_ms; fi
    _r=$((_r + 1))
done
case "$NOW" in ''|*[!0-9]*) fallback ;; esac
[ "$NOW" -gt 0 ] || fallback

# Округление вверх: половинчатый запас — не запас.
FACTOR=$(( (NOW + REF - 1) / REF ))
[ "$FACTOR" -ge 1 ] || FACTOR=1
[ "$FACTOR" -le 8 ] || FACTOR=8

echo "$FACTOR"
