#!/usr/bin/env bash
# scripts/tools/gate-bg.sh — ЕДИНСТВЕННЫЙ законный способ запустить авторитетный гейт.
#
# ЗАЧЕМ (требование владельца 2026-08-08: «правила не работают постоянно, сделай
# автоматическое правило»): интегратор трижды за сессию залипал в циклах
# `sleep`-ожидания гейта — один раз потерял ~3 часа: гейт закончил в 07:23, а
# обнаружено это было в 10:34. Гейт идёт 25-45 минут, и всё это время машина
# занята, а интегратор — свободен. Дисциплина «не жди» не работает, потому что
# ожидание выглядит как работа.
#
# МЕХАНИЗМ: этот скрипт ФИЗИЧЕСКИ не умеет ждать. Он запускает гейт откреплённым,
# печатает, чем заняться, и выходит немедленно. Ожидания здесь нет — значит и
# залипнуть не на чем. Проверка результата — отдельной командой `-c`, она тоже
# мгновенная и НЕ содержит sleep.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/tools/gate-bg.sh          # запустить и СРАЗУ вернуться
#   bash scripts/tools/gate-bg.sh -c       # одна строка статуса, без ожидания
#
# ДЛЯ АГЕНТА-ИНТЕГРАТОРА: запускать через Bash-инструмент с run_in_background,
# тогда уведомление о завершении придёт САМО — опрашивать не нужно вообще.

set -u
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LOG=/tmp/gate_full.log
DONE=/tmp/gate_full.done
STAMP=/tmp/gate_full.started

# ── Режим проверки: мгновенный, без ожидания ──────────────────────────────
if [ "${1:-}" = "-c" ]; then
    if [ -f "$DONE" ]; then
        verdict=$(cat "$DONE")
        rc=$(echo "$verdict" | sed -n 's/.*RC=\([0-9]*\).*/\1/p')
        mega=$(grep -a 'mega-CU exit' "$LOG" 2>/dev/null | tail -1 | cut -c1-70)
        if [ "${rc:-1}" = "0" ]; then
            echo "ГЕЙТ ЗЕЛЁНЫЙ ($verdict) :: $mega"
        else
            echo "ГЕЙТ КРАСНЫЙ ($verdict) :: $mega"
            grep -aE 'GATE FAIL' "$LOG" 2>/dev/null | tail -2
        fi
        exit 0
    fi
    if [ -f "$LOG" ]; then
        started=$(cat "$STAMP" 2>/dev/null || echo 0)
        now=$(date +%s)
        echo "ГЕЙТ ИДЁТ: $(wc -l < "$LOG") строк, $(( (now - started) / 60 )) мин — НЕ ЖДИ, займись другим"
        exit 0
    fi
    echo "ГЕЙТ НЕ ЗАПУСКАЛСЯ"
    exit 0
fi

# ── Режим запуска ─────────────────────────────────────────────────────────
if [ -f "$LOG" ] && [ ! -f "$DONE" ]; then
    echo "gate-bg: гейт УЖЕ идёт ($(wc -l < "$LOG") строк) — второй запуск отклонён." >&2
    echo "gate-bg: параллельные гейты дерутся за nova.exe и дают фантомные падения." >&2
    exit 1
fi

rm -f "$LOG" "$DONE"
date +%s > "$STAMP"

nohup bash -c "cd '$ROOT' && bash scripts/gate.sh > '$LOG' 2>&1; echo \"RC=\$? SEC=\$SECONDS\" > '$DONE'" \
    > /dev/null 2>&1 &

cat <<'EOF'
gate-bg: гейт запущен ОТКРЕПЛЁННО. Ожидания здесь нет — и не будет.

ЧТО ДЕЛАТЬ ПРЯМО СЕЙЧАС (не ждать!):
  * взять следующий пункт очереди К1 из docs/plans/221.1-bug-sweep.md;
  * раздать/принять окна;
  * разобрать красное на внешнем гейте;
  * дописать реестр/конвенции по уже закрытому.

ПРОВЕРИТЬ РЕЗУЛЬТАТ (мгновенно, без ожидания):
  bash scripts/tools/gate-bg.sh -c

ЗАПРЕЩЕНО: циклы `sleep`/`while` вокруг этого гейта. Ожидание выглядит как
работа, но ею не является — за одну сессию так потеряно ~3 часа.
EOF
exit 0
