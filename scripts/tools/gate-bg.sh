#!/usr/bin/env bash
# scripts/tools/gate-bg.sh — ЕДИНСТВЕННЫЙ законный способ запустить авторитетный гейт.
#
# ЗАЧЕМ (требование владельца 2026-08-08: «правила не работают постоянно, сделай
# автоматическое правило»): интегратор трижды за сессию залипал в циклах
# `sleep`-ожидания гейта — один раз потерял ~3 часа: гейт закончил в 07:23, а
# обнаружено это было в 10:34. Гейт идёт 25-45 минут, и всё это время машина
# занята, а интегратор — свободен. Дисциплина «не жди» не работает, потому что
# ожидание выглядит как работа.
#
# МЕХАНИЗМ: этот скрипт ФИЗИЧЕСКИ не умеет ждать. Он запускает гейт откреплённым,
# печатает, чем заняться, и выходит немедленно. Ожидания здесь нет — значит и
# залипнуть не на чем. Проверка результата — отдельной командой `-c`, она тоже
# мгновенная и НЕ содержит sleep.
#
# ИСПОЛЬЗОВАНИЕ:
#   bash scripts/tools/gate-bg.sh          # запустить и СРАЗУ вернуться
#   bash scripts/tools/gate-bg.sh -c       # одна строка статуса, без ожидания
#
# ДЛЯ АГЕНТА-ИНТЕГРАТОРА: запускать через Bash-инструмент с run_in_background,
# тогда уведомление о завершении придёт САМО — опрашивать не нужно вообще.

set -u
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# Пути переопределяемы ТОЛЬКО ради самотеста (шов). При незаданных переменных
# поведение прежнее — иначе шов сам был бы правкой поведения.
LOG=${GATE_BG_LOG:-/tmp/gate_full.log}
DONE=${GATE_BG_DONE:-/tmp/gate_full.done}
STAMP=${GATE_BG_STAMP:-/tmp/gate_full.started}
# Шов для проверки живого яруса novac: самотест подставляет своё имя процесса.
NOVAC_PROC_PAT=${GATE_BG_NOVAC_PAT:-gate-novac\.sh}

# «Лог есть, .done нет» — признак идущего гейта, но НЕ ЕДИНСТВЕННЫЙ. Замер
# 2026-09-06: интегратор снял .done рукой перед запуском, лаунчер увидел «идёт»
# по ВЧЕРАШНЕМУ логу и отклонил запуск, а сторож 9,5 минут читал финальную
# строку того лога. Финальная строка — второй признак: `GATE OK (final)`
# gate.sh печатает ТОЛЬКО на выходе зелёного прогона (gate.sh:1707-1709); у
# идущего прогона последняя строка — шаг, а не вердикт. Красный прогон
# второго признака НЕ имеет (`GATE FAIL:` бывает и не последней строкой) —
# там лаунчер отказывает, как раньше: ошибка в безопасную сторону.
_gate_log_finished() {
    tail -1 "$LOG" 2>/dev/null | grep -aqE 'GATE OK \(final\)'
}

# ── Режим проверки: мгновенный, без ожидания ──────────────────────────────
# ЯРУС NOVAC ИДЁТ СИНХРОННО и не виден ни по `.done`, ни по логу ОСНОВНОГО
# яруса: у него свой скрипт и свой файл вердикта. Единственный надёжный признак —
# живой процесс. Замер 2026-09-07: `ps -ef` показывал `bash scripts/gate-novac.sh`
# (старт 19:55:11) двадцать пятую минуту, а `tasklist` в ту же секунду давал НОЛЬ
# компиляторных процессов — стадия перемежает сборки и проверки. Без этой проверки
# `-c` печатал СТАРЫЙ вердикт, то есть утверждал состояние, которого не
# устанавливал (правило Г9 конвенции гейтов).
# Поле STIME берётся ПО ВИДУ (`HH:MM:SS`), а не по номеру: первой в выдаче
# `ps -ef | grep` идёт строка запуска, где на пятом месте стоит цель
# перенаправления, а не время. Замер 2026-09-07: первая версия печатала
# «процесс жив с /tmp/gate_novac_run.log». Берётся САМОЕ РАННЕЕ время — у стадии
# есть дочерние процессы, и интересует начало прогона, а не последнего шага.
_novac_stime() {
    ps -ef 2>/dev/null | grep -a "$NOVAC_PROC_PAT" | grep -v grep \
        | awk '{ for (i = 1; i <= NF; i++) if ($i ~ /^[0-9][0-9]:[0-9][0-9]:[0-9][0-9]$/) { print $i; break } }' \
        | sort | head -1
}

# Минуты с начала прогона. Через полночь разница отрицательна — тогда возвращается
# пусто, и печатается время старта: соврать про «N мин» хуже, чем не назвать их.
_novac_minutes() {
    _st="$1"
    [ -z "$_st" ] && return 0
    _h=${_st%%:*}; _rest=${_st#*:}; _m=${_rest%%:*}; _s=${_rest#*:}
    _start=$(( 10#$_h * 3600 + 10#$_m * 60 + 10#$_s ))
    _nowh=$(date +%H); _nowm=$(date +%M); _nows=$(date +%S)
    _now=$(( 10#$_nowh * 3600 + 10#$_nowm * 60 + 10#$_nows ))
    _d=$(( (_now - _start) / 60 ))
    [ "$_d" -ge 0 ] && echo "$_d"
}

# Возраст вердикта и о КАКОМ дереве он: сохранённый вердикт без этих двух чисел
# читается как свежий и про текущий HEAD. Замер 2026-09-07: файлу 68 минут, дерево
# ушло на 24 коммита вперёд, а в выводе не было ни того, ни другого.
# КОРОТКАЯ МЕТКА ДЛЯ ЗАГОЛОВКА. Замер 2026-09-08: подробная строка ниже печаталась
# ПОСЛЕДНЕЙ, а вывод этой команды читают через `head -2` — и её срезало четыре раза
# подряд у того же окна, которое её и завело. Вердикт девятичасовой давности, судивший
# дерево на 13 коммитов позади, был прочитан как состояние машины. Факт, который важен
# только если прочитан, не должен стоять там, где привычное усечение его убирает.
_verdict_tag() {
    _vf="$1"; _vh="$2"
    _mt=$(date -r "$_vf" +%s 2>/dev/null || echo 0)
    _age=$(( ($(date +%s) - _mt) / 60 ))
    [ "$_mt" = "0" ] && _age="?"
    _bh="?"
    if [ -n "$_vh" ] && git -C "$ROOT" cat-file -e "$_vh^{commit}" 2>/dev/null; then
        _bh=$(git -C "$ROOT" rev-list --count "$_vh..HEAD" 2>/dev/null || echo "?")
    fi
    if [ "$_bh" = "0" ] && [ "$_age" != "?" ] && [ "$_age" -lt 60 ]; then
        printf '[СВЕЖИЙ: %s мин, ТЕКУЩИЙ HEAD]' "$_age"
    else
        printf '[ПРОТУХШИЙ: %s мин, дерево ушло на %s коммит(ов)]' "$_age" "$_bh"
    fi
}

_verdict_context() {
    _vf="$1"; _vh="$2"
    _mt=$(date -r "$_vf" +%s 2>/dev/null || echo 0)
    _now=$(date +%s)
    _age=$(( (_now - _mt) / 60 ))
    [ "$_mt" = "0" ] && _age="?"
    if [ -n "$_vh" ] && git -C "$ROOT" cat-file -e "$_vh^{commit}" 2>/dev/null; then
        _behind=$(git -C "$ROOT" rev-list --count "$_vh..HEAD" 2>/dev/null || echo "?")
        if [ "$_behind" = "0" ]; then
            echo "    вердикту $_age мин; судил ТЕКУЩИЙ HEAD"
        else
            echo "    вердикту $_age мин; судил дерево на $_behind коммит(ов) ПОЗАДИ HEAD"
        fi
    else
        echo "    вердикту $_age мин; хэш вердикта в этом дереве НЕ НАЙДЕН"
    fi
}

if [ "${1:-}" = "-c" ]; then
    _nst=$(_novac_stime)
    if [ -n "$_nst" ]; then
        _nmin=$(_novac_minutes "$_nst")
        if [ -n "$_nmin" ]; then
            echo "ИДЁТ ЯРУС NOVAC: $_nmin мин (старт $_nst) — НЕ ЖДИ, займись другим"
        else
            echo "ИДЁТ ЯРУС NOVAC (старт $_nst) — НЕ ЖДИ, займись другим"
        fi
        echo "    вердикт ниже, если он есть, относится к ПРОШЛОМУ прогону:"
    fi
    if [ -f "$DONE" ]; then
        verdict=$(cat "$DONE")
        rc=$(echo "$verdict" | sed -n 's/.*RC=\([0-9]*\).*/\1/p')
        vhash=$(echo "$verdict" | sed -n 's/.*HASH=\([0-9a-f]*\).*/\1/p')
        mega=$(grep -a 'mega-CU exit' "$LOG" 2>/dev/null | tail -1 | cut -c1-70)
        _tag=$(_verdict_tag "$DONE" "$vhash")
        if [ "${rc:-1}" = "0" ]; then
            echo "ГЕЙТ ЗЕЛЁНЫЙ $_tag ($verdict) :: $mega"
        else
            echo "ГЕЙТ КРАСНЫЙ $_tag ($verdict) :: $mega"
            grep -aE 'GATE FAIL' "$LOG" 2>/dev/null | tail -2
        fi
        _verdict_context "$DONE" "$vhash"
        exit 0
    fi
    if [ -f "$LOG" ]; then
        started=$(cat "$STAMP" 2>/dev/null || echo 0)
        now=$(date +%s)
        if _gate_log_finished; then
            echo "ГЕЙТ ЗАВЕРШЁН, но .done снят рукой — вердикт только в логе: $(tail -1 "$LOG" | cut -c1-110)"
            exit 0
        fi
        echo "ГЕЙТ ИДЁТ: $(wc -l < "$LOG") строк, $(( (now - started) / 60 )) мин — НЕ ЖДИ, займись другим"
        exit 0
    fi
    echo "ГЕЙТ НЕ ЗАПУСКАЛСЯ"
    exit 0
fi

# ── Режим запуска ─────────────────────────────────────────────────────────
if [ -f "$LOG" ] && [ ! -f "$DONE" ]; then
    if _gate_log_finished; then
        echo "gate-bg: .done нет, но лог кончается вердиктом — прошлый прогон ЗАВЕРШЁН (его .done снят рукой); запускаю" >&2
    else
        echo "gate-bg: гейт УЖЕ идёт ($(wc -l < "$LOG") строк) — второй запуск отклонён." >&2
        echo "gate-bg: параллельные гейты дерутся за nova.exe и дают фантомные падения." >&2
        exit 1
    fi
fi

rm -f "$LOG" "$DONE"
date +%s > "$STAMP"

# Каждая строка лога получает отметку «секунд от старта». Профилировать гейт
# иначе было НЕЧЕМ: на вопрос владельца «что сколько занимает» ответа не
# существовало — лог не нёс времени вовсе, и любое рассуждение о том, что
# ускорять, было бы догадкой. Отметка ставится ЗДЕСЬ, а не правкой `gate.sh`:
# так профиль появляется у всех шагов разом, включая будущие, и никому не надо
# помнить про вызов таймера. `fflush` обязателен — без него awk буферизует, и
# лог перестаёт обновляться в реальном времени, ломая режим `-c`.
# ВЕРДИКТ НАЗЫВАЕТ СЕБЯ (реестр 221.1 №988). До 2026-09-06 он был строкой
# `RC=<код> SEC=<секунды>` — без яруса, без хеша судимого дерева, без ветки.
# `check-merge-discipline.sh` читает именно этот файл, поэтому зелёный ОСНОВНОЙ
# гейт открывал слияние ветки, чьи файлы судит ярус novac (87 стражей
# `check-novac-*`, которых `gate.sh` не зовёт ни разу), и страж говорил
# «слияние законно», потому что возражать ему было НЕЧЕМ. Замерено на себе:
# 7994d75ce и 7e6e6ad82 влиты в main без вердикта яруса novac.
# Хеш снимается ЗДЕСЬ, до запуска, — это дерево, которое гейт и будет судить.
# УРОВЕНЬ В МЕТКЕ (реестр 221.1 №995). Добавление яруса в №988 закрыло вопрос
# «кто проверял», но не вопрос «НАСКОЛЬКО». Ярусы самого гейта судят РАЗНОЕ:
# `loop` вообще не трогает корпус (ни линта, ни мега-CU, ни прогона) — он
# текстовый. Значит вердикт loop выглядел для стража слияния так же, как push,
# и открывал слияние с той же лёгкостью. Форма метки: `TIER=<ярус>:<уровень>`.
GATE_LEVEL="${NOVA_GATE_TIER:-full}"
GATE_HASH=$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)
GATE_BRANCH=$(git -C "$ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)
nohup bash -c "cd '$ROOT' && bash scripts/gate.sh 2>&1 \
    | awk -v t0=\$(date +%s) '{ printf \"[%5ds] %s\n\", systime()-t0, \$0; fflush() }' > '$LOG'; \
    echo \"RC=\${PIPESTATUS[0]} SEC=\$SECONDS TIER=main:$GATE_LEVEL HASH=$GATE_HASH BRANCH=$GATE_BRANCH\" > '$DONE'" \
    > /dev/null 2>&1 &

cat <<'EOF'
gate-bg: гейт запущен ОТКРЕПЛЁННО. Ожидания здесь нет — и не будет.

ЧТО ДЕЛАТЬ ПРЯМО СЕЙЧАС (не ждать!):
  * взять следующий пункт очереди К1 из docs/plans/221.1-bug-sweep.md;
  * раздать/принять окна;
  * разобрать красное на внешнем гейте;
  * дописать реестр/конвенции по уже закрытому.

ПРОВЕРИТЬ РЕЗУЛЬТАТ (мгновенно, без ожидания):
  bash scripts/tools/gate-bg.sh -c

ЗАПРЕЩЕНО: циклы `sleep`/`while` вокруг этого гейта. Ожидание выглядит как
работа, но ею не является — за одну сессию так потеряно ~3 часа.
EOF
exit 0
