#!/usr/bin/env bash
# scripts/tools/gate-profile.sh — профиль последнего прогона гейта.
#
# ЗАЧЕМ. Вопрос владельца 2026-08-08: «гейт идёт 40 минут — покажи профиль, что
# сколько занимает, надо проверить, что можно убыстрить оперативно». Ответа не
# существовало: лог не нёс времени, и любое суждение о том, что ускорять, было
# бы догадкой. Отметки времени ставит gate-bg.sh, этот скрипт их читает.
#
# ЧИТАЕТ строки вида `[  123s] == gate: <шаг> ==` и печатает, сколько занял
# КАЖДЫЙ шаг — то есть разницу до следующего. Последний шаг считается до конца
# лога. Сортировка по убыванию длительности: сверху то, что стоит ускорять.
set -u
export LC_ALL=C
LOG="${1:-/tmp/gate_full.log}"
[ -f "$LOG" ] || { echo "gate-profile: нет лога $LOG" >&2; exit 1; }

grep -aE '^\[ *[0-9]+s\] == gate: ' "$LOG" \
| sed -E 's/^\[ *([0-9]+)s\] == gate: (.*) ==.*/\1|\2/' \
| awk -F'|' '
    { t[NR]=$1; n[NR]=$2 }
    END {
        last = 0
        cmd = "grep -acE \"^\\[ *[0-9]+s\\]\" \"" ARGV[1] "\""
        for (i = 1; i <= NR; i++) {
            dur = (i < NR) ? t[i+1] - t[i] : -1
            printf "%s|%s|%s\n", dur, t[i], n[i]
        }
    }' ARGV1="$LOG" \
| sort -t'|' -k1,1nr \
| awk -F'|' '{ if ($1 < 0) printf "%6s  %-52.52s (последний шаг, до конца лога)\n", "?", $3; else printf "%5dс  %-52.52s (старт +%dс)\n", $1, $3, $2 }'

echo "--- всего ---"
tail -1 "$LOG" | grep -aoE '^\[ *[0-9]+s\]' || true
[ -f /tmp/gate_full.done ] && cat /tmp/gate_full.done
