#!/usr/bin/env bash
# scripts/tools/run-antirot-one.sh — ОДНА цель anti-rot, для параллельного запуска.
#
# ЗАЧЕМ. Профиль гейта 2026-08-12: `examples anti-rot` — 848 секунд из ~3400,
# ВТОРОЙ потребитель после самотестов (те уже параллелены, 1125 -> 258с).
# 32 цели (29 BUILD + 3 CHECK) шли строго последовательно, хотя каждая — своя
# независимая сборка примера: они не читают и не пишут общих файлов.
#
# ДВА ДЕФЕКТА ПОСЛЕДОВАТЕЛЬНОЙ ВЕРСИИ, найденные при переводе на параллель и
# починенные здесь — оба были невидимы, пока цикл шёл по одной цели за раз:
#
#   1. ОБЩИЙ ФАЙЛ ЛОГА. Все итерации писали в один
#      `${TMPDIR}/gate_antirot_$$.log` и удаляли его в конце шага. Пока цели
#      шли подряд, это работало «случайно»: лог перезаписывался, и до `grep`
#      доживал именно нужный. В параллели это гонка — цель читала бы чужой
#      вывод и печатала чужую ошибку.
#
#   2. СТОЛКНОВЕНИЕ ВЫХОДНЫХ ИМЁН. Выход собирался как
#      `${TMPDIR}/ex_$(basename путь .nv).exe`, а в списке ДВА разных примера
#      дают `hello` (проверено `uniq -d`). Последовательно они просто
#      затирали друг друга — второй перекрывал первый, и «собралось» означало
#      «собрался последний». В параллели это была бы порча на лету.
#
# Здесь и лог, и выход именуются от ПОЛНОГО пути цели, а не от basename.
#
# ЧТО ДЕЛАЕТ. Гоняет одну цель, копит вывод, печатает одним куском (иначе при
# -P N строки разных целей перемешиваются), и при провале кладёт файл с
# описанием в каталог провалов — чтобы вызывающий назвал упавшие ПОИМЁННО:
# код возврата `xargs` сказал бы только «что-то упало» (правило «не
# рапортовать счёт, которого не видел», реестр 221.1 №475).
#
# ИСПОЛЬЗОВАНИЕ (вызывается гейтом):
#   bash scripts/tools/run-antirot-one.sh <KIND> <путь> <каталог-провалов> <корень> <nova>

set -u
export LC_ALL=C

KIND="${1:?нет вида цели (BUILD|CHECK)}"
TARGET="${2:?нет пути цели}"
FAILDIR="${3:?нет каталога провалов}"
ROOT="${4:?нет корня дерева}"
NOVA="${5:?нет пути к nova}"

# Ключ от ПОЛНОГО пути: basename недостаточен (два разных примера дают `hello`).
SAFE="$(printf '%s' "$TARGET" | tr '/\\ .' '____')"
LOG="${TMPDIR:-/tmp}/gate_antirot_${SAFE}_$$.log"
OUTEXE="${TMPDIR:-/tmp}/ex_${SAFE}_$$.exe"

if [ "$KIND" = "BUILD" ]; then
    "$NOVA" build "$ROOT/$TARGET" --strict-effects -o "$OUTEXE" >"$LOG" 2>&1
    RC=$?
else
    "$NOVA" check "$ROOT/$TARGET" --strict-effects >"$LOG" 2>&1
    RC=$?
fi

if [ "$RC" -ne 0 ]; then
    {
        echo "anti-rot FAIL :: $KIND $TARGET"
        grep -m2 "error:" "$LOG" 2>/dev/null | sed 's/^/    /'
    } | tee "$FAILDIR/$SAFE"
fi

rm -f "$LOG" "$OUTEXE"

# Всегда 0 — провал передаётся ФАЙЛОМ: иначе `xargs` оборвал бы очередь на
# первой упавшей цели, и про остальные мы бы не узнали.
exit 0
