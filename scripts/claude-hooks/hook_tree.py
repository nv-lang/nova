# -*- coding: utf-8 -*-
"""Один дом ответа на вопрос «в каком дереве работает ЭТО окно».

Заведено 2026-09-18 (реестр 221.1 №1156). Дефект нашло окно Карины: хук
напоминания о записке мерил возраст файла в ГЛАВНОМ дереве, потому что
`CLAUDE_PROJECT_DIR` указывает именно туда, — а по `AGENTS.md` всякое окно,
кроме интегратора, работает в СВОЁМ worktree. Для целого класса адресатов
напоминание становилось невыполнимым.

**Почему отдельным файлом, а не копией в каждом хуке.** Ответ нужен трём хукам
сразу, и один из них уже показал, как такая копия ломается: путь от git читается
БАЙТАМИ, потому что `text=True` декодирует его кодировкой консоли, а домашний
каталог владельца кириллический (`C:/Users/Евгений/…`). Копия, написанная
второй раз по памяти, этой тонкости не унаследует — и замолчит ровно там, где
должна была заговорить. Две копии расходятся на первой правке; здесь это
измерено, а не предположено.
"""
import os
import subprocess


def session_root():
    """Дерево ЭТОЙ сессии (git-toplevel рабочего каталога), иначе — прежний корень.

    Промах намеренно возвращает `CLAUDE_PROJECT_DIR`: хук, который онемел, хуже
    хука, который иногда указывает на главное дерево. Молчание неотличимо от
    «всё в порядке».
    """
    fallback = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    try:
        out = subprocess.run(
            ["git", "-C", os.getcwd(), "rev-parse", "--show-toplevel"],
            capture_output=True, timeout=10)
        # БАЙТЫ, А НЕ `text=True` — см. шапку файла: путь с кириллицей приезжает
        # мусором, `isdir` отвечает «нет», и хук тихо уходит в чужое дерево.
        top = (out.stdout or b"").decode("utf-8", "replace").strip()
        if top and os.path.isdir(top):
            return os.path.normpath(top)
    except Exception:
        pass
    return fallback
