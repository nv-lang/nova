#!/usr/bin/env python3
"""guard-shell-nonascii.py — PreToolUse-хук Claude Code (Bash + PowerShell):
блокирует команды, несущие НЕ-ASCII текст, ДО их исполнения.

ПОЧЕМУ. Консоль этой машины работает в cp1251, и любой не-ASCII символ,
проходящий через командную строку, приезжает в файл искажённым: «Консоль»
превращается в «РљРѕРЅСЃРѕР»СЊ». Порча МОЛЧАЛИВАЯ — команда завершается
успешно, файл выглядит записанным, и узнаёт о ней страж `check-no-mojibake`
через десятки минут, на гейте.

Измеренная цена за одну смену 2026-08-17: ТРИ случая. Первый — комментарий в
`retracted-try-scan.py`; второй и третий — блоки в `run-guard-selftest.sh` и
`cal-factor.sh`, 14 испорченных строк, красный гейт (158 против базы 144) и
разбор «почему покраснело» вместо работы. Правило «не гонять русский текст
через оболочку» было записано в памяти ЗАДОЛГО до этого дня и все три раза не
сработало: соблюдение зависело от того, вспомнит ли агент его в моменте.
Это тот же класс, что и остальные правила-без-механизма (реестр 221.1 №718),
только здесь пострадавший — сам репозиторий.

ЧТО ДЕЛАТЬ ВМЕСТО. Писать файл инструментом Write (он передаёт текст мимо
оболочки), а из оболочки — только запускать. Для разовой правки — короткий
python-скрипт, записанный тем же Write.

ЧТО ПРОВЕРЯЕТ. Любой символ вне ASCII в тексте команды → exit 2 с указанием
первого такого символа и его позиции.

ЛОЖНЫЕ СРАБАТЫВАНИЯ И ПОЧЕМУ ИХ НЕТ. Проверка нарочно ГРУБАЯ — «никакого
не-ASCII в командной строке вообще»,— потому что тонкая («только в heredoc»,
«только при записи в файл») ошибается в обе стороны: порча случается и в
`sed -i`, и в `python -c`, и в `echo >>`, а безопасные случаи (грепнуть
русское слово, напечатать сообщение) решаются тем же способом — скриптом
через Write. Единственное исключение — сам ремонтный инструмент: команда,
которая ЧИНИТ порчу, обязана иметь право содержать её образцы, иначе страж
учит себя обходить. Признак ремонта — переменная окружения
`NOVA_ALLOW_NONASCII_CMD=1`, выставляемая явно и осознанно.

План: docs/plans/231-bug-cycle-exit.md, трек Д п.6 («правила из памяти
переезжают в перехватчик»), исполнительный дом docs/plans/231.2-enforcement-infra.md §1.
Родня: scripts/claude-hooks/guard-git.py, scripts/guards/check-no-mojibake.sh
(он ловит уже СЛУЧИВШУЮСЯ порчу — этот хук не даёт ей случиться).
"""
import json
import os
import sys

LIMIT = 60  # сколько символов контекста показать вокруг находки


def main() -> int:
    if os.environ.get("NOVA_ALLOW_NONASCII_CMD") == "1":
        return 0
    try:
        data = json.loads(sys.stdin.read() or "{}")
        cmd = (data.get("tool_input") or {}).get("command") or ""
    except Exception:
        return 0

    for i, ch in enumerate(cmd):
        if ord(ch) < 128:
            continue
        lo = max(0, i - LIMIT // 2)
        hi = min(len(cmd), i + LIMIT // 2)
        ctx = cmd[lo:hi].replace("\n", " ")
        sys.stderr.write(
            "ЗАПРЕЩЕНО: не-ASCII символ в командной строке "
            "(%r, U+%04X, позиция %d).\n" % (ch, ord(ch), i)
            + "  ...%s...\n" % ctx
            + "  ПОЧЕМУ: консоль в cp1251 портит такой текст МОЛЧА — команда\n"
            + "  завершится успехом, а в файле окажется «РљРѕРЅСЃРѕР»СЊ».\n"
            + "  За смену 2026-08-17 это случилось трижды и один раз уронило гейт.\n"
            + "  КАК НАДО: записать файл инструментом Write (он идёт мимо оболочки),\n"
            + "  а из оболочки только запускать. Разовая правка — короткий\n"
            + "  python-скрипт, записанный тем же Write.\n"
            + "  Если это РЕМОНТ порчи и образцы нужны в самой команде —\n"
            + "  NOVA_ALLOW_NONASCII_CMD=1, осознанно.\n"
        )
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
