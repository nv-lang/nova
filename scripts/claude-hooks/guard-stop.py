# -*- coding: utf-8 -*-
u"""Stop-хук: не давать закончить ход, если очередь НЕ пуста.

ЗАЧЕМ. Владелец повторил трижды за одну сессию: «Строй свой ход как
"сделал → доложил → сделал"; ждать после "доложил" надо ровно в трёх случаях —
нужен мой выбор, действие необратимо и не авторизовано, или очередь пуста. Во
всех прочих — отчёт и сразу следующий шаг в том же ходе». И трижды же
интегратор написал «делаю дальше: …» — и остановился.

Правило, которое приходится повторять, — не правило, а симптом. Лечится тем же,
чем лечились дрейф рабочего каталога (реестр №574) и конвенция `ffi.nv` (№569):
машиной вместо памяти.

ЧТО ДЕЛАЕТ. Смотрит на ПОСЛЕДНЕЕ сообщение ассистента в стенограмме. Если оно
объявляет следующий шаг («делаю дальше», «беру следующим», «продолжаю», «затем
гейт», …) — значит очередь по собственному признанию НЕ пуста, и заканчивать ход
рано. Хук возвращает `decision: block` с причиной, и модель продолжает работу.

ЧЕГО НЕ ДЕЛАЕТ (и почему так). Не пытается угадать, есть ли работа, когда о ней
не объявлено: три законные причины остановки — вопрос владельцу, неавторизованное
необратимое действие и пустая очередь — по тексту не отличимы машиной без риска
запереть ход в цикле. Поэтому ловится ровно один случай, зато без ложняков: «я
сам сказал, что делаю дальше, и не сделал».

ЗАЩИТА ОТ ЗАЦИКЛИВАНИЯ. `stop_hook_active` в полезной нагрузке означает, что ход
уже продолжен этим хуком, — тогда пропускаем. Иначе пара «хук блокирует → модель
пишет то же самое → хук блокирует» крутилась бы вечно.
"""
from __future__ import annotations

import io
import json
import os
import re
import sys

# Обороты, которыми объявляется следующий шаг. Список намеренно узкий: ловим
# ЯВНОЕ обещание, а не всякое упоминание будущего.
PROMISES = [
    u"делаю дальше",
    u"беру следующим",
    u"беру следующей",
    u"продолжаю",
    u"следующий шаг",
    u"дальше по очереди",
    u"дальше беру",
    u"иду дальше",
    u"в этом же ходе",
]

# Обороты, означающие законную остановку: ход ждёт решения владельца.
WAITS = [
    u"скажете",
    u"ваш выбор",
    u"какой путь",
    u"жду вашего",
    u"нужно ваше решение",
    u"подтвердите",
    u"?",
]

# ── ВТОРОЕ УСЛОВИЕ: доклад, в котором была работа агентов, обязан называть
# МОДЕЛИ (план 276 шаг 3, критерий «в»). Требование владельца стоячее: «в отчёте
# пиши, с какими моделями ты пускал агентов» — иначе экономию лимитов нельзя ни
# проверить, ни повторить.
#
# ГРАНИЦА ВЗЯТА УЗКО, И ЭТО РЕШЕНИЕ, А НЕ НЕДОДЕЛКА. Дословное «каждый доклад
# обязан нести строку» машиной неисполнимо: отличить доклад от любого другого
# сообщения нельзя, а блокировать КАЖДЫЙ конец хода — значит получить хук,
# который первое же окно отключит (тот же довод план приводит сам в шаге 4,
# критерий «в»: страж, краснеющий на всей истории, будет снят). Поэтому ловится
# доказуемое нарушение: сообщение САМО говорит, что агенты были, — и не называет
# моделей. Случай «агентов не пускал» хук не судит: его нечем отличить от
# обычного текста, и он остаётся на совести нормы.
MODELS_LINE = u"модели агентов"

# Признаки того, что агенты в этом ходе БЫЛИ. Узко: «запустил/пустил агента»,
# «делегировал», «агент вернул». Простое упоминание слова «агент» не в счёт —
# им полны обсуждения самих правил, и на нём хук ложнил бы постоянно.
AGENT_WORK = [
    u"запустил агент",
    u"пустил агент",
    u"пущен агент",
    u"делегировал",
    u"делегирую",
    u"отдаю агент",
    u"отдал агент",
    u"агент вернул",
    u"агент отчитал",
]


def last_assistant_text(path: str) -> str:
    if not path or not os.path.exists(path):
        return ""
    text = ""
    with io.open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except Exception:
                continue
            if rec.get("type") != "assistant":
                continue
            msg = rec.get("message") or {}
            parts = msg.get("content") or []
            if isinstance(parts, str):
                text = parts
                continue
            buf = []
            for p in parts:
                if isinstance(p, dict) and p.get("type") == "text":
                    buf.append(p.get("text") or "")
            if buf:
                text = "\n".join(buf)
    return text


def main() -> int:
    try:
        data = json.loads(sys.stdin.read() or "{}")
    except Exception:
        return 0

    if data.get("stop_hook_active"):
        return 0

    text = last_assistant_text(data.get("transcript_path") or "")
    if not text:
        return 0

    tail = text[-1200:].lower()

    # Условие 2 — независимо от условия 1: работа агентов названа, модели нет.
    # Ищем по ВСЕМУ сообщению, а не по хвосту: строка «Модели агентов:» может
    # стоять в начале доклада, а признак работы — в конце.
    whole = text.lower()
    if any(w in whole for w in AGENT_WORK) and MODELS_LINE not in whole:
        print(json.dumps({
            "decision": "block",
            "reason": (
                u"В докладе есть работа агентов, но нет строки «Модели агентов: …». "
                u"Требование владельца стоячее: без неё экономию лимитов нельзя ни "
                u"проверить, ни повторить. Допиши строку с моделями каждого "
                u"запущенного агента — и, если модель выбрана дороже haiku, одной "
                u"фразой почему."
            ),
        }, ensure_ascii=False))
        return 0

    promised = [p for p in PROMISES if p in tail]
    if not promised:
        return 0

    # Последний абзац с вопросом владельцу — законная остановка.
    if any(w in tail for w in WAITS):
        return 0

    print(json.dumps({
        "decision": "block",
        "reason": (
            u"Ход не окончен: в отчёте объявлен следующий шаг («%s»), "
            u"а он не сделан. Норма владельца — «сделал → доложил → "
            u"сделал»; ждать можно только когда нужен его выбор, действие "
            u"необратимо и не авторизовано, либо очередь пуста. Выполняй "
            u"объявленное сейчас, в этом же ходе." % promised[0]
        ),
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
