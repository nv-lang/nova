//! Тест-поддержка: компиляция на нити с ГАРАНТИРОВАННЫМ стеком.
//!
//! ДОМ И ОСНОВАНИЕ: реестр 221.1 №655. Глубина рекурсии парсера/чекера
//! рассчитана на нити компилятора с явным 64 МБ стеком — паттерн стоит в
//! трёх продакшен-местах (`src/main.rs`, `test_runner.rs`,
//! `nova-cli/src/main.rs`) и в doc-раннере (№655). Интеграционные тесты,
//! зовущие `parser::parse`/`types::check_module` НАПРЯМУЮ, компилируют на
//! нити cargo-test — на Linux она мала, и дорожка nova-doc падала stack
//! overflow'ом ДВАЖДЫ: три дня на `cargo test doc::`, а после починки
//! первого шага вскрылся второй, `doc_golden`, три дня прятавшийся за
//! красным первым (за первым красным не видно второго — свойство
//! последовательных шагов воркфлоу).
//!
//! Одна дверь для всех тест-харнессов: оборачивай ВЕСЬ компилирующий блок,
//! а не только `check_module` — где именно рекурсия глубже всего, вопрос
//! исследования на каждом фикстуре, а стек дешевле ответа.
//!
//! Замер 2026-08-14: прямых вызовов `check_module` в `tests/*.rs` — 24 в
//! 21 файле; в CI из них ходят два (doc_golden, doc_perf) — обёрнуты; 19
//! латентных перечислены в №655 и переезжают на эту дверь по мере касания.

use std::thread;

/// Выполняет `f` на нити с 64 МБ стека, возвращает результат. Паника
/// пробрасывается через `resume_unwind` — сообщения ассертов и
/// `#[should_panic]` ведут себя как без обёртки. `thread::scope` разрешает
/// заимствования из окружения — обёртка не заставляет владеть данными.
pub fn on_compiler_stack<'env, T, F>(f: F) -> T
where
    T: Send + 'env,
    F: FnOnce() -> T + Send + 'env,
{
    thread::scope(|s| {
        thread::Builder::new()
            .name("nova-test-compile".into())
            .stack_size(64 * 1024 * 1024)
            .spawn_scoped(s, f)
            .expect("spawn nova-test-compile thread")
            .join()
            .unwrap_or_else(|e| std::panic::resume_unwind(e))
    })
}
