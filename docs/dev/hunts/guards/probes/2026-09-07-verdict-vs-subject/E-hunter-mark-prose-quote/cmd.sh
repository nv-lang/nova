#!/bin/sh
# ПРОБА E — check-hunter-mark.sh
#
# ОБЕЩАНИЕ ШАПКИ (scripts/guards/check-hunter-mark.sh, дословно):
#   "ПОЧЕМУ МЕТКИ СЧИТАЮТСЯ ПО СТРОКАМ «| N |», А НЕ ГРЕПОМ ПО ФАЙЛУ: реестр —
#    2.5 МБ прозы, и честная строка, ЦИТИРУЮЩАЯ метку соседа, удваивала
#    числитель и краснила гейт (класс «стражи читают прозу как данные»,
#    проверен запуском). Считаем СТРОКИ-ЗАПИСИ, несущие метку."
#   "ЦИТАТА МЕТКИ ПИШЕТСЯ В БЭКТИКАХ — `НАЙДЕНО ОХОТНИКОМ <дата> (<трек>)` — и
#    тогда не считается."
#   "ЧТО КРАСНИТ: 1. метка без разбираемой даты (YYYY-MM-DD) ИЛИ без трека ..."
#
# ЧТО ПРОВЕРЯЕТ НА ДЕЛЕ. Правило 1 (форма метки) — единственная проверка,
# которая НЕ считает по строкам-записям и НЕ уважает бэктики:
#   BADMARK=$(grep -nE "НАЙДЕНО ОХОТНИКОМ" "$REG" \
#       | grep -vE "НАЙДЕНО ОХОТНИКОМ 20[0-9]{2}-[0-9]{2}-[0-9]{2} \((novac|oracle|guards)\)" \
#       | head -3)
# Это греп ПО ФАЙЛУ. Бэктики он не снимает и на «| N |» не смотрит — то есть
# ровно та форма цитаты, которую шапка ПРЕДПИСЫВАЕТ (шаблон с «<дата>»),
# делает стража красным, а сообщение при этом называет прозу
# «строкой реестра».
#
# Носителя в живом реестре сегодня нет (замер: 72 строки с меткой, 0 мимо
# фильтра, 0 не-записей). Это заряженное ружьё, а не текущий отказ.
#
# ЗАПУСК:  sh cmd.sh [КОРЕНЬ-РЕПОЗИТОРИЯ]
set -u
PYTHONIOENCODING=utf-8; export PYTHONIOENCODING
HERE=$(cd "$(dirname "$0")" && pwd)
REPO="${1:-}"
if [ -z "$REPO" ]; then
    d="$HERE"
    while [ "$d" != "/" ] && [ ! -f "$d/scripts/guards/check-hunter-mark.sh" ]; do
        d=$(dirname "$d")
    done
    REPO="$d"
fi
G="$REPO/scripts/guards/check-hunter-mark.sh"
[ -f "$G" ] || { echo "cmd.sh: не нашёл корень репозитория; передай его аргументом" >&2; exit 2; }

T="${TMPDIR:-/tmp}/probeE.$$"
rm -rf "$T"; mkdir -p "$T/docs/plans" "$T/hunts/novac" "$T/hunts/oracle" "$T/hunts/guards"
REG="$T/docs/plans/221.1-bug-sweep.md"

mkreg() {
    python - "$REG" "$1" <<'PYEOF'
import io, sys
out, case = sys.argv[1], sys.argv[2]
L = [u"# Реестр 221.1\n",
     u"\n",
     u"| N | prio | class | text |\n",
     u"|---|---|---|---|\n",
     u"| 1 | P2 | K3 | обычная запись без метки |\n"]
if case == "prose-template":
    L.append(u"\nПояснение к форме: метка пишется как "
             u"`НАЙДЕНО ОХОТНИКОМ <дата> (<трек>)` и в бэктиках не считается.\n")
elif case == "prose-real":
    L.append(u"\nПояснение к форме: метка пишется как "
             u"`НАЙДЕНО ОХОТНИКОМ 2026-09-04 (guards)` и в бэктиках не считается.\n")
elif case == "row-broken":
    L.append(u"| 2 | P2 | K3 | НАЙДЕНО ОХОТНИКОМ вчера |\n")
io.open(out, "w", encoding="utf-8", newline="\n").writelines(L)
PYEOF
}

run() {
    printf '%s\n' "--- $1 ---"
    NOVA_HUNTS_DIR="$T/hunts" sh "$G" "$T" 2>&1
    printf 'rc=%s\n\n' "$?"
}

mkreg clean
run "КОНТРОЛЬ 0: реестр без единой метки -> ожидается зелёный"

mkreg prose-template
echo "строка прозы, добавленная в реестр (ровно форма из шапки стража):"
sed -n '6,7p' "$REG"
run "ДЕФЕКТ: проза с ПРЕДПИСАННОЙ шапкой цитатой-шаблоном в бэктиках"

mkreg prose-real
run "КОНТРОЛЬ 1: та же проза, но в бэктиках стоит НАСТОЯЩАЯ дата+трек -> зелёный (значит краснит именно шаблон, а не проза как таковая)"

mkreg row-broken
run "КОНТРОЛЬ 2: настоящая СТРОКА-ЗАПИСЬ с испорченной меткой -> КРАСНЫЙ, страж делает своё дело"

rm -rf "$T"
