#!/usr/bin/env bash
# docs/plans/repro/p848/run.sh — ловля зависания реестровой строки №848
# (`presume_446_stress` идёт то 6 секунд, то не заканчивается вовсе).
#
# ЗАЧЕМ ЭТОТ КАТАЛОГ. До 2026-09-01 строка №848 говорила, что локально
# фикстура ЗЕЛЁНАЯ (5.3с; WSL2 ×20 подряд PASS) — то есть носителя для
# отладки не существовало, и класс наблюдался только через чужой CI, раз
# в десяток прогонов. Здесь он ловится на своей машине.
#
# ЧТО ОКАЗАЛОСЬ РУЧКОЙ. Число воркеров. Замер 2026-09-01, 49 прогонов на
# 16-ядерной машине, ОДИН бинарь и ОДИН способ запуска в обеих группах:
#
#   NOVA_MAXPROCS ∈ {1,2,4}  →  4 зависания из 25
#   NOVA_MAXPROCS = 8        →  0 зависаний из 24
#
# Здоровый прогон — 5-10с; зависший упирается в ЛЮБОЙ выставленный предел
# (95-96с при --timeout 90, 49с при --timeout 45). Поведение двоичное:
# промежуточных времён нет, значит это зависание, а не медленность.
#
# Это ГИПОТЕЗА, а не вывод: 4/25 против 0/24 — разница заметная, но чтобы
# отделить «мало воркеров» от «просто реже», нужно больше прогонов на
# каждом значении. Скрипт для того и написан.
#
# ИСПОЛЬЗОВАНИЕ (из корня репозитория):
#   bash docs/plans/repro/p848/run.sh [ЧИСЛО_ПРОГОНОВ] [MAXPROCS] [ТАЙМАУТ]
# по умолчанию: 8 прогонов, MAXPROCS=2, таймаут 45с.
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
NOVA="$ROOT/nova-cli/target/release/nova.exe"
[ -x "$NOVA" ] || NOVA="$ROOT/nova-cli/target/release/nova"
SRC="$(dirname "${BASH_SOURCE[0]}")/oversub_stress.nv"

RUNS="${1:-8}"
MP="${2:-2}"
TMO="${3:-45}"

[ -x "$NOVA" ] || { echo "нет собранного nova: $NOVA" >&2; exit 1; }

# Правим ENV-шапку копии на месте и ПЕЧАТАЕМ результат: первая попытка
# этого замера молча не меняла значение, и девять прогонов померили одно
# и то же. Проверяемая правка стоит одной строки вывода.
tmp="$(mktemp)"
sed "s|^// ENV NOVA_MAXPROCS=.*|// ENV NOVA_MAXPROCS=${MP}|" "$SRC" > "$tmp"
grep -m1 '^// ENV NOVA_MAXPROCS=' "$tmp" || { echo "ENV-строка не найдена" >&2; exit 1; }
mv "$tmp" "$SRC"

hangs=0
for i in $(seq 1 "$RUNS"); do
    s=$(date +%s)
    out="$("$NOVA" test "$SRC" --timeout "$TMO" 2>&1 | grep -aE 'PASS:|TIMEOUT' | tail -1)"
    e=$(date +%s)
    case "$out" in
        *"FAIL: 1"*|*TIMEOUT*) hangs=$((hangs + 1)); verdict="ЗАВИСЛО";;
        *)                     verdict="ok";;
    esac
    echo "  MAXPROCS=${MP} прогон ${i}: $((e - s))с — ${verdict}"
done
echo "ИТОГ: зависаний ${hangs} из ${RUNS} при MAXPROCS=${MP}"
